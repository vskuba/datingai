-- Перенос ручных миграций в `migrations/`: записи в журнале yoyo (выпуск 2026-08-30)
--
-- ЗАЧЕМ. Пять файлов из `data/migration_manual/` переехали в `migrations/` под
-- именами с меткой времени: вся история схемы теперь в одном месте и
-- накатывается сама. Но yoyo помнит применённое ПО ИМЕНИ файла
-- (`_yoyo_migration.migration_id`), а этих имён он никогда не видел — для него
-- все пять новые, и ближайший старт панели выполнил бы их заново.
--
-- Второй прогон не сломал бы ничего: каждый файл идемпотентен по сверке с
-- `information_schema`, и на живой базе все они прошли бы вхолостую. Но «не
-- сломает» — не повод выполнять: журнал должен говорить правду о том, что
-- применялось, иначе следующий человек не отличит применённое от пропущенного.
--
-- ЧТО ПРОВЕРЕНО НА ПРОДЕ 30.08.2026 — что переносить есть что и что оно уже стоит:
--
--   * пять колонок автовхода в `dating_profile` (`keep_online`, `logged_in_at`,
--     `relogin_since`, `relogin_tries`, `relogin_next_at`);
--   * индекс `idx_dating_message_dialog` (`profile_id`, `sender_uid`, `id`);
--   * колонка `user.role`, у первой учётки — `admin`;
--   * 655 собеседниц, все с хостом в `photo`, ни одной без;
--   * обе записи начальной схемы в журнале — `0001` и `20260101000000_initial_schema`.
--
-- ХЕШ — sha256 от ИМЕНИ миграции, а не от содержимого файла
-- (`yoyo/migrations.py: get_migration_hash`). Значения ниже не вычислены на
-- бумаге: чистая база поднята этими же семью файлами, и хеши сняты с журнала,
-- который yoyo написал сам. Они совпали с `sha256(имя)` до знака.
--
-- ВРЕМЯ приблизительное — дата выпуска файла, а не отметка ручного прогона: её
-- никто не записывал. На поведение это не влияет, yoyo смотрит только на наличие
-- строки; время нужно, чтобы журнал читался по порядку.
--
-- ТАБЛИЦЫ И СТРОКИ: `_yoyo_migration`, пять строк. Данные не трогаются вовсе.
--
-- ПОРЯДОК. Гнать ДО выкладки кода с перенесёнными файлами. Наоборот — значит дать
-- панели стартовать с новыми именами и без записей в журнале, то есть ровно то,
-- ради чего файл и написан.
--
-- Идемпотентность: первичный ключ таблицы — `migration_hash`, повтор гасится
-- `ON DUPLICATE KEY`. Файл можно гонять сколько угодно раз.
--
-- ПРОГОН (пароль переменной окружения, не аргументом):
--
--   docker exec -e MYSQL_PWD="$MYSQL_PASSWORD" -i dating_mysql \
--     mysql -u"$MYSQL_USER" --default-character-set=utf8mb4 -t "$MYSQL_DATABASE" \
--     < data/migration_manual/2026-08-30_yoyo_move_manual.sql

