// Два действия над пулом: убрать карточку и очистить пул целиком.
//
// Пулов на «Профилях» четыре — инвайты, рассылка, письма избранным, инициатива
// в чате, — и пятый рядом, ответы на письма. Устроены они по-разному и
// намеренно: у рассылки загрузка идёт двумя запросами разом, инициатива рисует
// список внутри загрузки, у инвайтов в ответе едет своя скорость. Общей
// выкройки «пул» здесь нет и не предполагается.
//
// А вот два действия у них одни и те же, и лежали они четырьмя и тремя копиями.
//
// ## ⚠⚠ Что копии стоили: «уже убрали» показывалось как поломка
//
// Пул живёт своей жизнью: карточку уносит отправка или чистка пулов, когда у
// анкеты кончается смена. Человек в этот момент смотрит на список, набранный
// минуту назад, и жмёт «×» по тому, чего уже нет. Цель его при этом
// **достигнута** — карточки в пуле нет, — и правильный ответ здесь «список
// обновлён», а не красная ошибка про несуществующий номер.
//
// Это знал **один** обработчик из четырёх — у инициативы. Трое остальных
// пугали человека отказом там, где всё хорошо.
//
// ## ⚠⚠ И второе: необратимое делалось молча
//
// Очистка пула восстановлению не подлежит — черновики сочиняются заново и
// стоят вызовов модели. Подтверждение спрашивал **один** из трёх (рассылка);
// инвайты и письма избранным очищались по одному нажатию, без вопроса.
//
// Теперь оба правила живут здесь, и новый пул получает их, ничего о них не
// зная.
//
// ⚠ Что делать **после** — дело вызывающего: один правит счётчик рядом с
// кнопкой, другой перечитывает список с сервера, третий закрывает окно. Сюда
// это не переносится: у каждого пула своё состояние, и общая «перерисовка»
// означала бы, что модуль знает про все четыре.

import {deleteData} from '../api.js';
import {showNotification} from '/static/js/notification.js';

// Чем кончилось удаление карточки.
//
// ⚠ Три исхода, а не два: «убрали» и «её уже не было» для человека одно и то же
// (карточки в пуле нет), но вызывающему они нужны порознь — после `gone` список
// перечитывают с сервера, потому что разъехался не только этот ряд.
export const POOL_DROP_DONE = 'done';
export const POOL_DROP_GONE = 'gone';
export const POOL_DROP_FAILED = 'failed';

/**
 * Убрать одну карточку пула.
 *
 * @param {string} url адрес ручки с номером строки.
 * @param {string} ask о чём спросить перед удалением; пусто — не спрашивать.
 * @returns {Promise<string>} `POOL_DROP_DONE`, `POOL_DROP_GONE` либо
 *   `POOL_DROP_FAILED`. Отказ человека на вопрос — тоже `POOL_DROP_FAILED`:
 *   для вызывающего это «ничего не менялось».
 *
 * ⚠⚠ **404 — не отказ, а рассинхрон**, и отвечаем на него мягко: цель человека
 * достигнута, карточки в пуле нет. Список после этого перечитывают —
 * разъехаться мог не только этот ряд.
 *
 * ⚠ Узнаём его **по коду**, а не по тексту: формулировку в роутере однажды
 * поправят, и примета по словам замолчит. Текст оставлен запасным — вкладка
 * могла не перечитать `api.js`.
 */
export async function poolDrop(url, ask = '') {
    if (ask && !confirm(ask)) return POOL_DROP_FAILED;

    try {
        await deleteData(url);
    } catch (e) {
        const gone = e.status === 404
            || /#\d+ нет|инвайта нет|ответа #\d+ нет/.test(String(e.message || ''));

        showNotification(
            gone ? 'Карточка уже ушла из пула — список обновлён' : e.message,
            gone ? 'info' : 'error');

        return gone ? POOL_DROP_GONE : POOL_DROP_FAILED;
    }

    return POOL_DROP_DONE;
}

/**
 * Очистить пул сайта целиком.
 *
 * @param {string} url адрес ручки с `site_id`.
 * @param {string} ask о чём спросить; пусто — не спрашивать.
 * @returns {Promise<number|null>} сколько убрано, либо `null` — не вышло или
 *   человек передумал.
 *
 * ⚠ **Спрашивать нужно всегда, когда есть что убирать.** Восстановить нечего:
 * черновики сочиняются заново и стоят вызовов модели. Довод `ask` оставлен
 * строкой, а не флагом, потому что вопрос у каждого пула свой — со своим счётом
 * и склонением.
 */
export async function poolClear(url, ask = '') {
    if (ask && !confirm(ask)) return null;

    try {
        const got = (await deleteData(url)).result || {};
        const dropped = Number(got.dropped || 0);
        showNotification(`Убрано из пула: ${dropped}`, 'success');

        return dropped;
    } catch (e) {
        showNotification('Пул не очистился: ' + e.message, 'error');

        return null;
    }
}
