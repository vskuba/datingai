// Расписание сменами: лента суток, на которой смены — интервалы.
//
// Общий модуль, потому что расписаний в панели **два, и они про разное**:
//
// * расписание анкеты («Анкеты», `dating_profile.schedule`) — когда ей быть в
//   сети; это про присутствие конкретной учётки;
// * расписание рассылки («Профили» → «Письма рассылка», `dating_site`) — когда с
//   сайта уходят письма; это про сайт, и анкета для него не нужна вовсе.
//
// Вопросы разные, а вид и правила ввода одни и те же: смена, ползунок, шаг в
// четверть часа, запрет пересечений. Две копии этого разошлись бы в первую же
// правку — и разошлись бы молча, потому что обе продолжали бы работать.
//
// ⚠ **Здесь только вид и правила.** Где хранится расписание, какой ручкой
// сохраняется и что стоит в шапке с подвалом блока — знает страница: у анкеты в
// подвале кнопка «Войти», у рассылки её нет и быть не может.

import {esc} from './view.js';
import {timeNowMinutes} from './time.js';

// Сутки в минутах — мера всей шкалы: ползунок ходит от 0 до 1440.
export const DAY_MINUTES = 24 * 60;

// Шаг ползунка. Четверть часа, а не минута: на ширине колонки минутный шаг даёт
// меньше пикселя на деление, и попасть в «10:00» мышью нельзя. Круглые времена,
// которыми расписание и задают, кратны пятнадцати все до одного.
export const STEP_MINUTES = 15;

// Сколько смен разрешено. ⚠ **То же число, что на сервере**
// (`DATING_SCHEDULE_MAX` в `dating_schedule.py`), и предел там смысловой, а не
// технический: смены с перерывами укладываются в сутки, а больше означало бы
// «включено почти всегда» — то самое круглосуточное присутствие, от которого
// расписание и уводит.
//
// Здесь оно затем, чтобы кнопка гасла **до** запроса: иначе пятая смена
// заводилась бы, ползунок работал, а сервер молча отказывал бы в сохранении.
export const SCHEDULE_MAX = 4;

// Насколько далеко должны стоять две ручки, чтобы не налезать друг на друга.
//
// ⚠ **Это про вид, а не про смысл**, и потому мера здесь — ширина ручки, а не
// «сколько длится осмысленная смена». Ручка круглая, 13 пикселей (`--thumb` в
// `dating_page.css`), лента — 520; тринадцать пикселей это 36 минут суток, а
// ближайший кратный шагу отрезок — 45.
//
// Меньше — и кружки перекрываются: две ручки в одной точке выглядят как одна, и
// взять нужную нельзя ни мышью, ни глазом. Поэтому расписание ползунком задаётся
// с зазором: смена не короче 45 минут, и между сменами не меньше 45 минут.
//
// ⚠ **Сервер при этом принимает и более тесное** — смены вплотную остаются
// законными (`dating_schedule.py`). Здесь ограничение того, что можно
// **набрать руками**, а не того, что бывает: расписание из миграции или чужой
// правки покажется как есть, ползунок его просто не улучшит.
//
// Поменяется ширина ленты или размер ручки — пересчитать так:
// `ceil(ручка_px / лента_px * 1440 / 15) * 15`.
export const SCHEDULE_GAP_MINUTES = 45;

// Насколько узкой должна быть смена, чтобы подпись над ней не помещалась.
//
// Считаем долей суток, а не пикселями: ширина ленты задана блоком (520 минус
// поля ≈ 496), и доля переводится в пиксели однозначно. «07:00 → 11:00» —
// тринадцать знаков моноширинного шрифта в 10 пикселей, около 78; 16% от ленты
// это 79. Смена короче четырёх часов подписи не получает — её время остаётся в
// подсказке заливки и появляется, пока тянут ручку.
const LABEL_MIN_SHARE = 0.16;

// ⚠ **Часы не сворачиваем по модулю суток**, хотя соблазн велик: конец суток —
// это `24:00`, а `24 % 24` дало бы `00:00`, то есть их начало.
//
// Так и было, и человек это видел: ползунок доводили до правого края, смена
// становилась «19:00 → 00:00», сортировка ставила её первой, а заливка схлопывалась
// в ноль длины. Со стороны — «ползунок доходит до конца, исчезает и появляется в
// начале».
//
// Больше 1440 сюда не приходит: значение зажато `Math.min`, а у ползунка стоит
// `max`. Так что «25:00» получиться неоткуда, и модуль здесь защищал от того, чего
// не бывает, ломая то, что бывает каждый день.
export const timeText = (minutes) => {
    const m = Math.max(0, Math.min(Number(minutes) || 0, DAY_MINUTES));

    return `${String(Math.floor(m / 60)).padStart(2, '0')}:`
         + `${String(m % 60).padStart(2, '0')}`;
};

export const timeMinutes = (text) => {
    const [h, m] = String(text || '0:0').split(':').map(Number);

    return (Number.isFinite(h) ? h : 0) * 60 + (Number.isFinite(m) ? m : 0);
};

// Смены по времени входа. Сортируем при каждой отрисовке: время правят ползунком,
// и смена, заведённая последней, может оказаться первой по времени.
export function scheduleSort(rows) {
    return [...(rows || [])].sort((a, b) => (a.from || '').localeCompare(b.from || ''));
}

// Номер смены, внутрь которой попадает минута суток. `-1` — ни одна.
//
// ⚠ **Границы — те же, что у сервера**: вход включительно, выход нет
// (`dating_schedule_now` в `dating_schedule.py`, `from <= minutes < to`). Разойдись
// они на минуту — лента красила бы зелёным смену, которая для воркера уже кончилась,
// и человек видел бы «идёт сейчас» там, где ничего не происходит. Ради этого
// правило и вынесено отдельной функцией: одно место, которое можно сверить с
// сервером глазами и проверить тестом.
//
// Смены не перекрываются (`scheduleCheck`), так что попасть можно только в одну.
// Негодное расписание из чужой правки покажется как есть — берём первую подошедшую,
// а на пересечение и без того ругается строка под лентой.
export function scheduleNowIndex(rows, minutes) {
    const now = Number(minutes);
    if (!Number.isFinite(now)) return -1;

    return (rows || []).findIndex(
        item => timeMinutes(item.from) <= now && now < timeMinutes(item.to));
}

// Номер смены, которая начинается раньше, чем кончилась предыдущая. `-1` —
// пересечений нет. Отдельной функцией: ответ нужен и словами под лентой, и
// подсветкой самой смены.
export function scheduleOverlap(rows) {
    for (let i = 1; i < rows.length; i++) {
        if (rows[i].from < rows[i - 1].to) return i;
    }

    return -1;
}

// Расписание годно, когда у каждой смены выход позже входа и смены не налезают
// друг на друга. Пустая строка — годно, иначе причина словами.
//
// Args:
//   empty: что сказать про пустое расписание. У анкеты и у рассылки это разные
//     вещи («входит вручную» против «письма шлём вручную»), а правило одно.
export function scheduleCheck(rows, empty = 'Расписания нет — ведём вручную') {
    if (!rows.length) return empty;

    if (rows.find(row => !row.from || !row.to)) {
        return 'У каждой смены должны быть начало и конец';
    }

    // Конец строго позже начала. Равенство тоже не годится: смена нулевой длины —
    // это начало, за которым сразу конец, то есть ничего.
    const backwards = rows.find(row => row.to <= row.from);
    if (backwards) return `Смена ${backwards.from}–${backwards.to}: конец не позже начала`;

    // **Смены не перекрываются.** Проверяем по соседям в отсортированном списке —
    // этого достаточно, чтобы поймать любое пересечение.
    const overlap = scheduleOverlap(rows);
    if (overlap >= 0) {
        return `Смены ${rows[overlap - 1].from}–${rows[overlap - 1].to} и `
             + `${rows[overlap].from}–${rows[overlap].to} налезают друг на друга`;
    }

    return '';
}

// Куда встанет новая смена: первый промежуток, свободный от уже заведённых.
// `null` — свободного места нет.
//
// Ищем сами, а не ставим «в конец»: смены не перекрываются, и запись, севшая
// поверх соседки, была бы негодной с первой же секунды. Пусть человек двигает
// готовую смену, а не чинит только что созданную.
export function scheduleRoom(rows) {
    // ⚠ Смене нужен не только свой зазор, но и зазоры до соседей: сядь она
    // впритык — её ручка тут же налезла бы на соседскую, и человек получил бы
    // новую смену, которую нечем взять.
    const need = SCHEDULE_GAP_MINUTES;
    let cursor = 0;

    for (const item of rows) {
        const start = timeMinutes(item.from);
        // Свободного места нужно на зазор больше с каждой стороны, где есть сосед.
        const pad = cursor ? need : 0;
        if (start - cursor >= need * 2 + pad) {
            return {from: cursor + pad, to: cursor + pad + need};
        }

        cursor = Math.max(cursor, timeMinutes(item.to));
    }

    const pad = cursor ? need : 0;
    if (DAY_MINUTES - cursor >= need + pad) {
        return {from: cursor + pad,
                to: Math.min(cursor + pad + need, DAY_MINUTES)};
    }

    return null;
}

// Подпись к смене: «10:00 → 15:00». Стрелка, а не тире: это не диапазон значений,
// а начало и конец — у них есть направление.
function timeLabel(item) {
    return `${esc(item.from)} → ${esc(item.to)}`;
}

// Докуда ходит ручка: до соседней и ни шагом дальше.
//
// ⚠ **Упор вместо обмена местами.** Прежде ручки могли пройти друг сквозь друга:
// значения пары сортировались, и меньшее становилось началом. Перетащив начало за
// конец, человек получал смену, вывернутую наизнанку, — и на ленте она прыгала.
// Соседние смены при этом налезали одна на другую, и расписание переставало
// сохраняться, о чём сообщала строка под лентой.
//
// Теперь это невозможно по построению: расписание, набранное ползунками, всегда
// годное, и строке под лентой жаловаться не на что.
//
// Границы:
//
//   начало — от конца предыдущей смены плюс зазор до конца своей минус зазор;
//   конец  — от начала своей плюс зазор до начала следующей минус зазор
//            (или до конца суток).
//
// ⚠ **Расстояние между любыми двумя ручками — не меньше `SCHEDULE_GAP_MINUTES`**,
// и это про вид: ближе кружки налезают друг на друга, и взять нужный нельзя. Своя
// пара и соседняя смена меряются одинаково — ручке всё равно, чья соседка рядом.
//
// ⚠ Вынесена наружу ради проверки (`tests/test_schedule_band.js`): правило «ручки
// упираются» словами не проверить, а через страницу — значило бы поднимать браузер
// ради арифметики над четырьмя числами.
//
// Args:
//   rows: смены **в том же порядке**, в каком они нарисованы, — по времени входа.
export function edgeRange(rows, index, edge) {
    const before = rows[index - 1];
    const after = rows[index + 1];
    const own = rows[index];

    if (edge === 'from') {
        return {min: before ? timeMinutes(before.to) + SCHEDULE_GAP_MINUTES : 0,
                max: timeMinutes(own.to) - SCHEDULE_GAP_MINUTES};
    }

    return {min: timeMinutes(own.from) + SCHEDULE_GAP_MINUTES,
            max: after ? timeMinutes(after.from) - SCHEDULE_GAP_MINUTES
                       : DAY_MINUTES};
}

// Где встанет подпись смены с серединой в `center` процентах ленты.
//
// ⚠ Подпись крайней смены прижимается к краю, а не центрируется. Обычная стоит
// серединой над своей сменой (`translateX(-50%)`), и у смены с полуночи левая
// половина подписи уехала бы за край блока — а лишние пиксели справа однажды уже
// дали этой странице горизонтальную прокрутку. Порог — половина подписи в долях
// ленты: около 78 пикселей на 496, то есть 8%.
//
// Возвращает и `left`, и класс: они всегда ставятся парой, и разведи мы их по
// двум местам — прижатая подпись однажды осталась бы с центрирующим `transform`,
// то есть уехала бы ровно туда, откуда её убирали.
function labelPlace(center) {
    if (center < 8) return {left: 0, cls: 'at-start'};
    if (center > 92) return {left: 100, cls: 'at-end'};

    return {left: center, cls: ''};
}

// Лента суток: шкала от полуночи до полуночи, смены — интервалы на ней.
//
// ⚠ **Это и ползунок, и лента разом.** Прежде их было два: список строк, где у
// каждой смены своя шкала в полные сутки, и лента «только смотреть» под ними.
// Сутки рисовались столько раз, сколько смен, а сравнить смены между собой можно
// было только в уме — одно и то же «14:00» стояло в каждой строке на своём месте.
//
// Ползунков поэтому 2×N: пара на смену, все на одной дорожке. Держится это на
// правиле «указатель ловит только сама ручка» — см. `dating_page.css`.
export function scheduleBandHtml(rows, live = true, edit = true) {
    const percent = (time) => (timeMinutes(time) / DAY_MINUTES) * 100;
    const overlap = scheduleOverlap(rows);
    const now = timeNowMinutes();
    const current = scheduleNowIndex(rows, now);

    // ⚠ Часы заводим отсюда, а не из `scheduleBandBind`: не-админу ленту рисуют, но
    // не привязывают (ползунки ему заперты), и привяжи мы ход часов к обработчикам
    // — зелёное у него застыло бы навсегда. Смотрят на ленту как раз чаще, чем
    // правят.
    nowTickStart();

    const labels = rows.map((item, index) => {
        const left = percent(item.from);
        const width = percent(item.to) - left;
        // Узкой смене подписи не даём: она налезла бы на соседнюю и обе стали бы
        // нечитаемыми. Узел всё равно рисуем — пока тянут ручку, подпись
        // показывается (`live`), и без узла её негде было бы показать.
        const hidden = width < LABEL_MIN_SHARE * 100;
        const place = labelPlace(left + width / 2);

        return `<span class="sched-label${index === overlap ? ' clash' : ''}`
             + `${place.cls ? ' ' + place.cls : ''}"`
             + ` data-index="${index}" style="left:${place.left}%`
             + `${hidden ? ';display:none' : ''}">${timeLabel(item)}</span>`;
    }).join('');

    // Заливка смены. Минимальная ширина — чтобы получасовая смена не схлопнулась
    // в невидимую полоску: взять её тогда было бы не за что.
    const fills = rows.map((item, index) => {
        const left = percent(item.from);
        const width = Math.max(percent(item.to) - left, 0.6);

        return `<div class="sched-fill${index === overlap ? ' clash' : ''}`
             + `${nowClass(index === current, live)}"`
             + ` data-index="${index}" data-from="${esc(item.from)}"`
             + ` data-to="${esc(item.to)}" style="left:${left}%;width:${width}%"`
             + ` title="${nowTitle(index, item, index === current, live)}">`
             + (edit
                ? `<button type="button" class="sched-drop" data-index="${index}"`
                  + ` title="Убрать смену ${esc(item.from)} → ${esc(item.to)}"`
                  + ` aria-label="Убрать смену ${esc(item.from)} → ${esc(item.to)}">×</button>`
                : '')
             + '</div>';
    }).join('');

    // Ручки. ⚠ Подпись у каждой своя и со временем смены: восемь ползунков на
    // одной дорожке различимы мышью, но не голосом и не по Tab — «начало» восемь
    // раз подряд не сказало бы, чьё это начало.
    //
    // ⚠ **Шкала у всех ползунков одна — целые сутки**, и сузить её по соседям
    // нельзя, как ни соблазнительно: `min`/`max` у `input[type=range]` задают не
    // только предел значения, но и то, как оно ложится на ширину. Ползунок с
    // `max="10:45"` растянет эти часы на всю ленту, и ручка уедет от своей заливки
    // — ровно то расхождение, от которого лента и лечилась.
    //
    // Поэтому упор сделан зажимом значения в `scheduleBandBind`, а шкала осталась
    // общей: только так положение ручки означает время, а не долю чьего-то
    // диапазона.
    // ⚠ **Только показ — без ползунков и крестиков.** Лента расписания стоит и
    // там, где править нечего: в шапке «Входящих» она отвечает на вопрос «когда
    // эта анкета готовит ответы», а правят смены на «Анкетах». Оставь мы ручки,
    // человек подвинул бы их здесь — и правка ушла бы в базу мимо того места, где
    // расписание ведут.
    const sliders = !edit ? '' : rows.map((item, index) => ['from', 'to'].map(edge =>
        `<input type="range" min="0" max="${DAY_MINUTES}" step="${STEP_MINUTES}"`
        + ` value="${timeMinutes(item[edge])}" data-edge="${edge}"`
        + ` data-index="${index}" class="${index === overlap ? 'clash' : ''}"`
        + ` aria-label="Смена ${index + 1}, ${edge === 'from' ? 'начало' : 'конец'}">`
    ).join('')).join('');

    // ⚠ Метка «сейчас» — тонкая черта поверх дорожки, и она не украшение.
    //
    // Зелёная смена отвечает «идёт», но её **отсутствие** двусмысленно: то ли
    // сейчас перерыв между сменами, то ли подсветка не работает вовсе. Черта
    // снимает вопрос — видно, где мы на сутках, даже когда зелёного нет.
    //
    // Стоит **под** ползунками в разметке, чтобы ручку можно было взять сквозь неё:
    // указатель она не ловит (`pointer-events` в `dating_page.css`), но порядок
    // узлов задаёт и то, кто рисуется поверх.
    const mark = `<div class="sched-now" style="left:${(now / DAY_MINUTES) * 100}%"`
               + ` title="Сейчас ${timeText(now)}"></div>`;

    return `<div class="sched-band${edit ? '' : ' sched-band-view'}"`
         + ` data-on="${live ? '1' : '0'}">`
         + `<div class="sched-labels">${labels}</div>`
         + '<div class="sched-range">'
         + '<div class="sched-track"></div>'
         + fills + mark + sliders
         + '</div>'
         + '<div class="sched-hours"><span>00</span><span>06</span><span>12</span>'
         + '<span>18</span><span>24</span></div>'
         + '</div>';
}

// ── «Сейчас» ─────────────────────────────────────────────────────────────────
//
// ⚠ Идущая смена красится зелёным, и у зелёного **два оттенка**, потому что вопрос
// «попадает ли минута в смену» и вопрос «происходит ли что-нибудь» — разные.
//
// Расписание исполняется, только когда включён выключатель над лентой (а у анкеты
// ещё и сама анкета включена). Крась мы одинаково — панель говорила бы «идёт
// сейчас» о смене, по которой никто не входит и никому не пишет. На «Профилях» это
// был бы первый же вид: отправка и расписание выключены по умолчанию.
//
// Отсюда `live`: **страница знает, действует ли расписание**, а модуль — нет. У
// анкеты это `schedule_on && !schedule_idle`, у рассылки `mailing_schedule_on`;
// сводить два разных условия внутрь модуля значило бы тащить в него обе страницы.

// Как часто пересчитываем «сейчас». Полминуты: смены кратны четверти часа, но
// граница переходится в любую минуту, и минутное опоздание зелёного человек
// заметит — он на часы и смотрит.
export const SCHEDULE_NOW_TICK_MS = 30000;

// Ход часов один на страницу. Лент на ней бывает много (у каждой анкеты своя), а
// вопрос у них общий — который час.
let nowTimer = null;

function nowTickStart() {
    // ⚠ Вне браузера часов не заводим: модуль гоняется в `node`
    // (`tests/test_schedule_band.js`), и вечный таймер там не дал бы процессу
    // завершиться — сюита висела бы до таймаута.
    if (nowTimer || typeof window === 'undefined') return;

    nowTimer = setInterval(() => scheduleNowMark(), SCHEDULE_NOW_TICK_MS);
}

function nowClass(current, live) {
    if (!current) return '';

    return live ? ' now' : ' now off';
}

function nowTitle(index, item, current, live) {
    const base = `Смена ${index + 1}: ${esc(item.from)} → ${esc(item.to)}`;
    if (!current) return base;

    return base + (live
        ? ' · идёт сейчас'
        : ' · время подошло, но расписание выключено');
}

// Перекрашивает уже нарисованные ленты, не трогая разметку.
//
// ⚠ **Перекраска, а не перерисовка**, и это не оптимизация: пересобери мы ленту
// раз в полминуты — под пальцем менялись бы узлы, и ползунок, который в этот миг
// тянут, отпустил бы ручку. Меняются только классы, подсказка и положение черты.
//
// Смены берутся **из самой разметки** (`data-from`, `data-to`), а не из списка,
// который был при отрисовке: список к этому времени мог уехать (человек правит
// соседнюю ленту, страница перечитала сайт), а разметка — это ровно то, что человек
// видит. Правило попадания при этом одно на оба случая — `scheduleNowIndex`.
export function scheduleNowMark(scope = null) {
    const root = scope || (typeof document === 'undefined' ? null : document);
    if (!root) return;

    const now = timeNowMinutes();

    root.querySelectorAll('.sched-band').forEach(band => {
        const live = band.dataset.on !== '0';
        const fills = [...band.querySelectorAll('.sched-fill')];
        const rows = fills.map(fill => ({from: fill.dataset.from, to: fill.dataset.to}));
        const current = scheduleNowIndex(rows, now);

        fills.forEach((fill, index) => {
            fill.classList.toggle('now', index === current);
            fill.classList.toggle('off', index === current && !live);
            fill.title = nowTitle(index, rows[index], index === current, live);
        });

        const mark = band.querySelector('.sched-now');
        if (mark) {
            mark.style.left = `${(now / DAY_MINUTES) * 100}%`;
            mark.title = `Сейчас ${timeText(now)}`;
        }
    });
}

// Лента вместе с кнопкой «+ Смена» и счётчиком — всё тело блока расписания.
//
// Шапку и подвал собирает страница: у анкеты в подвале стоит кнопка «Войти», у
// рассылки её нет, а у чекбокса в шапке подпись своя.
//
// Args:
//   live: действует ли расписание прямо сейчас — от этого зависит оттенок зелёного
//     у идущей смены. По умолчанию «да»: расписание, о котором страница ничего не
//     сказала, разумнее считать рабочим — иначе лента приглушала бы то, что честно
//     исполняется.
//   extra: разметка, которую страница добавляет в строку под лентой, справа от
//     счётчика. Так корзинка «удалить все шаблоны» встала рядом с «Смена: 1 из 4»,
//     не заводя копии всей ленты на странице: у ленты узлы пересобираются на
//     каждую отрисовку, и своя кнопка вне неё отрывалась бы от неё при первом
//     же движении ползунка.
export function scheduleBodyHtml(rows, live = true, extra = '') {
    // Кнопка одна: смена и есть единица расписания.
    //
    // Гаснет по двум причинам, и подсказка их различает: сутки заняты целиком либо
    // смен уже столько, сколько разрешено. Одна подсказка на оба случая отправила
    // бы человека расчищать сутки там, где чистить нечего.
    const full = rows.length >= SCHEDULE_MAX;
    const room = full ? null : scheduleRoom(rows);

    // ⚠ Лента рисуется **и у пустого расписания**: шкала суток без единой смены и
    // есть ответ «не бывает никогда», а на её месте человек ищет, куда добавлять.
    return scheduleBandHtml(rows, live)
         + '<div class="sched-add">'
         + `<button type="button" class="dating-btn sched-add-btn"${room ? '' : ' disabled'}`
         + ` title="${room ? 'Добавить смену в свободное время'
                           : (full ? `Смен уже ${SCHEDULE_MAX} — больше не заводим`
                                   : 'Свободного времени в сутках не осталось')}">`
         + '+ Смена</button>'
         // Счётчик смен — рядом с кнопкой, а не над лентой: интервалов на шкале
         // бывает четыре, и пересчитывать их глазами не должно быть нужно, чтобы
         // понять, упёрлись ли в предел.
         + `<span class="sched-count">Смен: ${rows.length} из ${SCHEDULE_MAX}</span>`
         + extra
         + '</div>';
}

// Вешает обработчики на уже нарисованное тело блока.
//
// Args:
//   root: узел, внутри которого лежит лента (форма блока).
//   rows: те же смены и **в том же порядке**, в каком их нарисовали, — иначе
//     `data-index` указывал бы не на ту смену.
//   edit: `edit(change)` — страница применяет `change(rows)` к своему черновику,
//     перерисовывает блок и сохраняет. Одна точка, а не вызов из каждого
//     обработчика: правок три (добавить, убрать, двинуть ручку), и забытый вызов
//     означал бы «эта правка не сохраняется», причём молча.
export function scheduleBandBind(root, rows, edit) {
    const add = root.querySelector('.sched-add-btn');
    if (add) {
        // Новая смена встаёт в **первый свободный промежуток**, а не в конец.
        add.addEventListener('click', () => {
            if (rows.length >= SCHEDULE_MAX) return;

            const room = scheduleRoom(rows);
            if (!room) return;

            edit(list => list.push({from: timeText(room.from), to: timeText(room.to)}));
        });
    }

    // ⚠ Обходим **смены, а не узлы**: узлов у смены три и лежат они в разных
    // местах ленты — подпись в своей строке, заливка с крестиком и пара ручек в
    // шкале. Собирает их обратно `data-index`, общий у всех трёх.
    rows.forEach((item, index) => {
        const at = (selector) => root.querySelector(`${selector}[data-index="${index}"]`);

        const fill = at('.sched-fill');
        const label = at('.sched-label');
        const drop = at('.sched-drop');
        if (!fill || !drop) return;

        // ⚠ **Смену ищем в списке и уходим, если не нашли.** `indexOf` возвращает
        // `-1`, а `splice(-1, 1)` считает от конца — то есть убрал бы последнюю
        // смену вместо той, на которой нажали. Не найтись же она может: страница
        // вправе пересобрать черновик (сменился сайт, пришло чужое сохранение), и
        // тогда объекты в нём другие, а обработчик держит прежние.
        drop.addEventListener('click', () => edit(list => {
            const at = list.indexOf(item);
            if (at >= 0) list.splice(at, 1);
        }));

        // Ползунок шлёт `input` на каждое движение ручки. Перерисовывать по нему
        // весь блок нельзя: новый узел не получит захвата указателя, и ручка
        // выскользнет из-под пальца на первом же шаге. Поэтому пока тянут — правим
        // смену и подкрашиваем её на месте, а перерисовку откладываем до `change`,
        // то есть до отпускания.
        const sliders = [...root.querySelectorAll(
            `input[type=range][data-index="${index}"]`)];

        // ⚠ **Каждая ручка читается своей**, без сортировки пары. Прежде значения
        // сортировались — меньшее становилось началом, — и ручки проходили друг
        // сквозь друга, меняясь ролями под пальцем. Теперь они упираются, и
        // перепутаться им негде: начало всегда левее конца.
        const readEdges = () => {
            const value = (edge) => Number(
                sliders.find(s => s.dataset.edge === edge).value);

            return {from: timeText(value('from')), to: timeText(value('to'))};
        };

        // Держит ручку в её пределах: своя пара и соседние смены.
        //
        // ⚠ **Значение возвращаем ползунку**, а не только запоминаем: иначе ручка
        // уехала бы дальше упора, показывая одно, пока смена стоит на другом. И
        // возвращаем **до** чтения — `readEdges` должен видеть уже зажатое.
        //
        // Так упор работает и мышью, и стрелками: оба способа проходят через
        // `input`, а нативные `min`/`max` для этого не годятся — они сжали бы шкалу
        // ползунка, оторвав ручку от заливки (см. `scheduleBandHtml`).
        const clamp = (slider) => {
            const {min, max} = edgeRange(rows, index, slider.dataset.edge);

            // ⚠ Места нет вовсе — не трогаем. Так бывает у расписания, пришедшего
            // **не отсюда**: миграция или чужая правка вправе завести смены
            // теснее, чем позволяет ползунок, и выдавливать их прыжком ручки
            // значило бы менять чужое решение молча.
            if (min > max) return;

            const value = Math.min(Math.max(Number(slider.value), min), max);

            if (Number(slider.value) !== value) slider.value = String(value);
        };

        sliders.forEach(slider => {
            slider.addEventListener('input', () => {
                clamp(slider);
                const edges = readEdges();
                // ⚠ Правим **сам объект смены**, а не копию: он же лежит в
                // черновике страницы, и отпустив ручку, она сохранит именно его.
                item.from = edges.from;
                item.to = edges.to;

                const left = (timeMinutes(edges.from) / DAY_MINUTES) * 100;
                const width = ((timeMinutes(edges.to) - timeMinutes(edges.from))
                               / DAY_MINUTES) * 100;
                fill.style.left = `${left}%`;
                fill.style.width = `${width}%`;
                fill.title = `Смена ${index + 1}: ${edges.from} → ${edges.to}`;

                if (!label) return;

                // ⚠ Подпись едет за серединой смены и **показывается, даже если
                // она узкая и в покое скрыта**: пока тянут ручку, человеку нужно
                // видеть, что он ставит, — иначе шаг в четверть часа приходится
                // угадывать по пикселям.
                const place = labelPlace(left + width / 2);
                label.style.left = `${place.left}%`;
                label.classList.toggle('at-start', place.cls === 'at-start');
                label.classList.toggle('at-end', place.cls === 'at-end');
                label.style.display = '';
                label.classList.add('live');
                label.innerHTML = timeLabel(edges);
            });

            // Отпустили — можно и пересортировать смены, и перерисовать ленту:
            // захватывать больше нечего.
            slider.addEventListener('change', () => edit(list => {
                const at = list.indexOf(item);
                if (at < 0) return;

                const edges = readEdges();
                list[at].from = edges.from;
                list[at].to = edges.to;
            }));
        });
    });
}
