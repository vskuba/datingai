// Селект сайта в шапке страниц раздела Dating.
//
// Список ведёт сосед (RhapsodyAi), но приходит он из **нашего снимка**
// (`GET /api/site`): сервер отдаёт то, что знает, и сверяет с соседом в фоне.
// Каждая страница раздела начинается с одного и того же — спросить список,
// нарисовать `<option>`, вернуть человеку тот сайт, который он выбирал в прошлый
// раз.
//
// ⚠ **Селект не бывает пустым из-за лежащего соседа.** Раньше бывал: список брали
// у него при каждом открытии, и его недоступность гасила всю панель — без
// выбранного сайта нет ни анкет, ни профилей, ни журналов. Теперь пусто здесь
// значит ровно одно: снимка ещё нет, то есть панель открыли впервые.
//
// Ключ выбора общий на весь раздел намеренно: человек ходит между страницами, и
// разный выбранный сайт на соседних читается как «я же выбрал ladadate», а
// показана оказывается чужая учётка. Поэтому копия этой загрузки на каждой
// странице и опасна: разъехавшись в мелочах, они продолжают писать в один ключ.
//
// Отдельным файлом, а не в `dating_view.js`: тот про отрисовку учётки — значки,
// бейджи, время, — и запроса к серверу в нём нет ни одного.

import {getData} from '../api.js';
import {esc} from './view.js';

// Где лежит выбранный сайт. Одно имя на весь раздел — см. выше.
export const DATING_SITE_KEY = 'dating_site';

// Ссылка на админ-панель агентства и её состояние.
//
// Панель агентства — это **её** страница, не наша: там видны все анкеты сайта,
// переписка и письма разом. Панель входит в неё сценарием у соседа и дальше
// держит сессию живой HTTP-ударом (`dating_panel.py`), а шапка отвечает на два
// вопроса разом: куда идти и жива ли она сейчас.
//
// ⚠ **Состояние берём из своей базы, а не ходим на панель.** Ручка `/panel`
// только читает последний ответ круга: переключение сайта вкладкой иначе
// означало бы запрос к чужому серверу на каждый щелчок.
//
// ⚠ **Точек три, и серая не равна красной.** Серая значит «ещё не спрашивали» —
// панель настроили минуту назад, круг до неё не дошёл; красная — «спросили, и
// панель нас не признала»; жёлтая — «до панели не достучались». Сведи их в две,
// и свежая настройка выглядела бы поломкой.
export async function datingPanelPaint(el, base, siteId) {
    if (!el) return null;

    if (!siteId) {
        el.hidden = true;

        return null;
    }

    let panel = {};
    try {
        panel = (await getData(`${base}/api/dating/site/${Number(siteId)}/panel`)).result || {};
    } catch (e) {
        // Отказ нашей ручки — не повод рисовать «панель лежит»: это разные
        // вещи, а перепутав их, человек пойдёт чинить чужой сервер.
        el.hidden = true;

        return null;
    }

    // Адреса нет — панели у сайта нет вовсе. Пустая ссылка в шапке обещала бы
    // то, чего некому исполнить.
    if (!panel.on) {
        el.hidden = true;

        return panel;
    }

    const status = String(panel.status || '');
    const word = {online: 'на связи', offline: 'вход потерян', error: 'не отвечает'}[status]
        || 'ещё не проверяли';

    el.hidden = false;
    el.className = `panel-link ${status}`;
    el.href = panel.url;
    el.target = '_blank';
    el.rel = 'noopener';
    el.title = [`Админ-панель: ${word}`,
                panel.checked_at ? `проверено ${panel.checked_at} UTC` : '',
                panel.login_at ? `вход ${panel.login_at} UTC` : '',
                panel.error || ''].filter(Boolean).join('\n');
    // ⚠ Слово «панель» в подписи, а не только хост: хост сайта знакомств и так
    // стоит рядом во вкладках, и голое `ladadate.com` в углу читалось бы как
    // повтор выбранного сайта, а не как ссылка на его кабинет агентства.
    el.innerHTML = `<span class="panel-dot"></span>`
        + `<span class="panel-name">панель ${esc(panel.name)}</span>`;

    return panel;
}

// ── Вкладки сайтов ─────────────────────────────────────────────────────────
//
// Селект отвечал на один вопрос — «какой сайт открыт», — и отвечал молча: чтобы
// узнать, где сейчас идёт жизнь, человек перебирал сайты по очереди. Вкладка
// отвечает сразу на три: сколько анкет в сети, сколько реплик в чате и сколько
// писем за полсуток.
//
// ⚠⚠ **Счётчики приезжают своей ручкой** (`/api/site/live`), а не вместе со
// списком. Список меняется раз в недели, счётчики — каждые несколько секунд;
// сведи их в одну, страница возила бы имена и адреса на каждый тик.
//
// ⚠ **Список рисуется без счётчиков, если те не пришли.** Вкладки — главное,
// числа на них — украшение: отказ счётчиков гасит числа, а не шапку.

// Сколько ждать между обновлениями счётчиков. ⚠ Не чаще страницы: числа читают
// глазами, и мельтешение раз в секунду мешало бы, а не помогало.
const DATING_SITE_LIVE_MS = 15000;

// Сколько пастельных цветов в палитре сайтов.
//
// ⚠⚠ Число обязано совпадать с числом блоков `[data-hue="N"]` в
// `dating_page.css`: скажи здесь больше — сайт с лишним номером останется без
// переменных и нарисуется запасным цветом, **молча**. За совпадением следит
// сторож `TestThePaletteAgrees`.
const DATING_SITE_HUES = 8;

// Отрисовать вкладки сайтов. Возвращает пришедший список.
//
// Args:
//   el: контейнер вкладок.
//   base: корень API.
//   onPick: зовётся при выборе сайта — доводом номер сайта строкой.
//
// ⚠ Выбор возвращается из `localStorage` одним ключом на весь раздел: человек
// ходит между страницами раздела, и разный сайт на соседних читался бы как
// «я же выбрал ladadate», а показана чужая учётка.
export async function datingSiteTabs(el, base, onPick) {
    const sites = await datingSiteList(base);

    // ⚠⚠ **Контейнер прикидывается селектом, и это не хитрость, а цена.**
    // Выбранный сайт страницы читают как `siteEl.value` и слушают событием
    // `change` — сорок пять мест в шести файлах. Переписать их значило бы
    // тронуть всю работу раздела ради вёрстки шапки; вместо этого вкладки
    // отвечают теми же двумя именами, и страницам правка не нужна вовсе.
    //
    // ⚠ Свойство заводится **один раз**: `datingSiteTabs` зовут и при первой
    // загрузке, и при обновлении списка, а второе `defineProperty` на том же
    // узле — отказ `TypeError`.
    if (!Object.getOwnPropertyDescriptor(el, 'value')) {
        Object.defineProperty(el, 'value', {
            get: () => String(el.dataset.pick || ''),
            set: (id) => _datingTabsPick(el, String(id)),
        });
    }

    el.dataset.pick = _datingSitePicked(sites);
    // ⚠⚠ Список помним на контейнере, и это нужно именно палитре: цвет сайта
    // считается по его **месту в списке**, а выбор приходит ещё и через
    // `el.value = …` — там списка нет вовсе. Без этого смена сайта кодом
    // перекрашивала бы вкладки, но не подвкладки: страница осталась бы в цвете
    // прежнего сайта, то есть соврала бы ровно о том, ради чего цвет и введён.
    el._datingSites = sites;
    // ⚠⚠ Обработчик выбора помним на контейнере: вкладки переписываются
    // целиком на каждом обновлении счётчиков, и вешать его надо заново. Без
    // этого щелчок работал бы ровно до первого тика, а потом переставал —
    // молча, и выглядело бы это «панель подвисла».
    el._datingOnPick = onPick;
    _datingTabsPaint(el, sites, {});
    _datingTabsWire(el, sites, onPick);
    // ⚠ Цвет тела ставится и при загрузке, а не только на щелчке: сайт
    // возвращается из `localStorage`, щелчка может не быть вовсе за всю жизнь
    // страницы — и подвкладки остались бы в запасном индиго.
    _datingTabsTint(el);

    // ⚠ Счётчики спрашиваются **после** отрисовки: вкладки должны появиться
    // сразу, а числа приехать следом. Иначе шапка пустует, пока считается
    // чужая арифметика.
    _datingLiveLoop(el, base, sites);

    return sites;
}

// Список сайтов без разметки: его читают страницы, которым нужны имена сайтов,
// а шапки с вкладками нет.
//
// ⚠ Первую сверку **ждём**: снимка ещё нет, а сверка уже пошла — единственный
// случай, когда ждать правильно, потому что показывать нечего, и «сайтов нет»
// здесь было бы неправдой.
export async function datingSiteList(base) {
    let answer = await getData(base + '/api/site');
    let sites = answer.result || [];

    for (let left = 6; !sites.length && (answer.sync || {}).refreshing && left > 0; left--) {
        await new Promise(done => setTimeout(done, 700));
        answer = await getData(base + '/api/site');
        sites = answer.result || [];
    }

    return sites;
}

// Какой сайт показывать: сохранённый, если он ещё в списке, иначе первый.
//
// ⚠ Проверка «ещё в списке» обязательна: закладку у соседа могли убрать, и
// выбор «как в прошлый раз» оставил бы страницу без единой открытой вкладки.
function _datingSitePicked(sites) {
    const saved = localStorage.getItem(DATING_SITE_KEY);

    if (saved && sites.some(row => String(row.id) === saved)) return saved;

    return sites.length ? String(sites[0].id) : '';
}

// Разметка вкладок: колонка на сайт, в колонке два ряда — имя и счётчики.
//
// Счётчики — отдельными значками, теми же классами, что у работы на карточке
// анкеты (`workPills`): одно состояние на панели обязано выглядеть одинаково
// везде, иначе два значка про одно читаются как про разное.
//
// ⚠⚠ Значки рисуются **всегда**, в том числе нулями. Прежде пустой счёт значок
// убирал — и ширина колонки менялась на каждом тике: числа приезжают отдельной
// ручкой через секунду после имён, и шапка дёргалась у человека под курсором.
// Серый ноль отвечает «тихо», а отсутствие значка не отвечает ничего.
function _datingTabsPaint(el, sites, live) {
    if (!sites.length) {
        el.innerHTML = '<span class="site-tabs-empty">сайтов нет — '
            + 'заведите закладку в RhapsodyAi</span>';

        return;
    }

    const picked = String(el.dataset.pick || '');

    el.innerHTML = sites.map(row => {
        const id = Number(row.id);
        const own = live[String(id)] || {};
        const online = Number(own.online || 0);
        const working = Number(own.profiles || 0);
        const whole = Number(own.whole || 0);

        // ⚠⚠ Знаменатель — **все анкеты сайта**, то же число, что в заголовке
        // списка слева («ПРОФИЛИ 19»). Прежде здесь стояли включённые, и у
        // Ladadate вкладка писала `0/0` рядом со списком из девятнадцати
        // строк: два числа про одно и то же спорили на одном экране, а список
        // рядом — та самая мера, с которой человек сверяет вкладку.
        //
        // ⚠ Сколько из них включено, говорит подсказка: на вкладке два числа
        // вместо одного отвечали бы на один вопрос дважды.
        const title = [`${esc(row.name)}`,
                       `в сети ${online} из ${whole} анкет`,
                       `включено ${working}`,
                       // ⚠ «От собеседников» сказано словами: значок считает
                       // **входящее**, и без этого число читалось бы как вся
                       // работа сайта, включая нашу собственную рассылку.
                       `за 12 часов от собеседников:`
                       + ` реплик ${Number(own.chat || 0)},`
                       + ` писем ${Number(own.mail || 0)}`].filter(Boolean).join('\n');

        // ⚠⚠ Колонка — **не одна кнопка**, и это вынужденно: у неё три
        // назначения. Имя выбирает сайт, значок реплик ведёт на «Чат →
        // Диалоги», значок писем — на «Фавориты → Диалоги». Вложить ссылку в
        // кнопку нельзя — разметка запрещает интерактивное в интерактивном, и
        // браузеры разбирают такое по-своему.
        return `<div class="site-tab${String(id) === picked ? ' on' : ''}"`
            + ` data-site="${id}" data-hue="${_datingSiteHue(sites, id)}"`
            + ` title="${esc(title)}">`
            + `<button type="button" class="site-tab-name"`
            + ` data-site="${id}">${esc(row.name)}</button>`
            + '<span class="site-tab-counts">'
            + `<span class="site-tab-live${online ? ' on' : ''}"`
            + ` >${online}/${whole}</span>`
            + _datingCount('chat', Number(own.chat || 0), id)
            + _datingCount('mail', Number(own.mail || 0), id)
            + '</span></div>';
    }).join('');
}

// Куда ведёт значок счёта: вид работы → страница и её вкладки.
//
// ⚠⚠ Адресом, а не записью в хранилище: ссылку видно в строке состояния до
// нажатия, её можно открыть в новой вкладке, и она не зависит от того, что
// страница запомнила в прошлый раз. Разбирает её сама страница «Профили».
//
// ⚠ Сайт едет доводом: значок зовёт к работе **этого** сайта, а открыт мог
// быть другой — человек смотрит на четыре колонки сразу.
// ⚠⚠ `feed` — это **вид события ленты** (`FEED_WHERE` на «Профилях»), а не
// второе написание той же пары. Страница, уже открытая на «Профилях», ловит
// щелчок и зовёт `feedGo(feed)` — тем самым одна карта «куда вести» остаётся
// одна на оба входа: ленту и значок. Разойдись они, щелчок по строке ленты и
// щелчок по значку уводили бы в разные места.
const DATING_COUNT_GOES = {
    chat: {tab: 'chat', sub: 'talk', feed: 'talk'},
    mail: {tab: 'fav', sub: 'talks', feed: 'favtalk'},
};

function _datingCountHref(kind, siteId) {
    const go = DATING_COUNT_GOES[kind];

    return `/admin/dating/profile?site=${Number(siteId)}`
        + `&tab=${go.tab}&sub=${go.sub}`;
}

// Один значок счёта: цветной и мигающий, пока есть о чём говорить, иначе серый.
//
// ⚠⚠ Ноль рисуется **тем же значком**, а не пустотой: исчезни он, ширина
// колонки менялась бы при каждом обновлении счётчиков. Серый с нулём отвечает
// «за полсуток тихо» — это ответ, а отсутствие значка ответом не является.
//
// ⚠ Мигание почты приезжает модификатором `beat`, а чата — своим правилом
// `.pill.chat`: на карточке анкеты тот же значок почты отвечает на другой
// вопрос («у неё N писем») и мигать там не должен.
//
// Рисунки значков: конверт и реплика. Обводка у обоих одной толщины — на этом
// держится их одинаковый вес в ряду.
//
// ## ⚠⚠ Почему рисунком, а не эмодзи
//
// Эмодзи `color` не слушаются: они цветные сами по себе, и покрасить их можно
// только фильтром. На тихом значке это и подвело. Замер с живой панели: самый
// тёмный пиксель у `💬` — 42, у `✉️` — 127, то есть вдвое бледнее. Конверт Noto
// почти целиком **белый** с тонким контуром, и обесцвеченный он сливается со
// светло-серой подложкой пилюли, пока пузырь чата рядом отлично виден.
//
// Затемнением это не чинится: `brightness` жмёт и белую заливку конверта, то
// есть знак превращается в серое пятно вместо рисунка. Нужен не фильтр, а
// управляемый цвет — его даёт `currentColor` в рисунке.
//
// ⚠ Отсюда же одинаковый вес: обводку обоих задаём мы, а не то, как шрифт
// нарисовал свой знак. Прежде конверт был тоньше пузыря, и ряд выглядел
// небрежно независимо от цвета.
const DATING_COUNT_SIGNS = {
    mail: '<rect x="1" y="3.5" width="14" height="9" rx="1.6"/>'
        + '<path d="M1.9 4.7 8 8.9l6.1-4.2"/>',
    chat: '<path d="M2.6 2.6h10.8a1.6 1.6 0 0 1 1.6 1.6v5.6a1.6 1.6 0 0 1-1.6'
        + ' 1.6H7.2l-3.6 2.9v-2.9H2.6A1.6 1.6 0 0 1 1 9.8V4.2a1.6 1.6 0'
        + ' 0 1 1.6-1.6Z"/>',
};

// Один значок счёта: цветной и мигающий, пока есть о чём говорить, иначе серый.
//
// ⚠⚠ Ноль рисуется **тем же значком**, а не пустотой: исчезни он, ширина
// колонки менялась бы при каждом обновлении счётчиков. Серый с нулём отвечает
// «за полсуток тихо» — это ответ, а отсутствие значка ответом не является.
//
// ⚠ Мигание почты приезжает модификатором `beat`, а чата — своим правилом
// `.pill.chat`: на карточке анкеты тот же значок почты отвечает на другой
// вопрос («у неё N писем») и мигать там не должен.
// ⚠⚠ Значок — **ссылка, и серый тоже**: «писем нет» это ответ, за которым
// человек идёт в тот же список, чтобы убедиться. Веди туда только мигающий —
// и значок переставал бы работать ровно тогда, когда на него смотрят спокойно.
function _datingCount(kind, count, siteId) {
    const cls = count ? `pill ${kind}${kind === 'mail' ? ' beat' : ''}`
                      : 'pill off';
    const go = DATING_COUNT_GOES[kind];

    return `<a class="${cls}" href="${_datingCountHref(kind, siteId)}"`
        + ` data-go="${go.feed}" data-site="${siteId}"`
        + ` title="${count} за 12 часов — открыть список">`
        + '<svg class="pill-sign" viewBox="0 0 16 16"'
        + ' fill="none" stroke="currentColor" stroke-width="1.6"'
        + ` stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">`
        + `${DATING_COUNT_SIGNS[kind]}</svg>${count}</a>`;
}

// Щелчок по вкладке: запомнить выбор, перерисовать, сказать странице.
//
// ⚠ Обработчик вешается после отрисовки: вкладки переписываются целиком на
// каждое обновление счётчиков, и повешенный до неё не пережил бы первого.
// ⚠⚠ Слушаем **колонку**, а не только имя: мимо значков в ней есть пустое
// место — ряд счётчиков шире своих пилюль, — и щелчок туда обязан выбрать
// сайт.
//
// ⚠⚠ Щелчок по значку колонка **пропускает мимо себя**, но всплытие не рвёт.
// Глушить его здесь нельзя: страница «Профили» ловит тот же щелчок выше по
// дереву, чтобы открыть место без перезагрузки, — и `stopPropagation` отнимал
// бы у неё событие. Это уже было: перехват молча не срабатывал, а ссылка
// уводила браузер на ту же страницу заново.
function _datingTabsWire(el, sites, onPick) {
    el.querySelectorAll('.site-tab').forEach(tab =>
        tab.addEventListener('click', event => {
            if (event.target.closest('[data-go]')) return;

            const id = String(tab.dataset.site || '');
            if (!id || id === String(el.dataset.pick || '')) return;

            _datingTabsPick(el, id);

            if (typeof onPick === 'function') onPick(id);
        }));
}

// Выбрать сайт: запомнить, подсветить, сказать странице событием.
//
// ⚠ Событие `change` — то же, что бросал прежний селект: три страницы слушают
// именно его (`siteEl.addEventListener('change', …)`). Бросаем **после**
// записи в `dataset`, иначе обработчик прочитал бы прежний сайт.
function _datingTabsPick(el, id) {
    if (!id || id === String(el.dataset.pick || '')) return;

    el.dataset.pick = id;
    localStorage.setItem(DATING_SITE_KEY, id);
    el.querySelectorAll('.site-tab').forEach(one =>
        one.classList.toggle('on', one.dataset.site === id));
    _datingTabsTint(el);

    el.dispatchEvent(new Event('change', {bubbles: true}));
}

// Цвет сайта — по его **месту в списке**, а не по номеру в базе.
//
// ⚠⚠ Место, а не `id % N`: смысл палитры в том, чтобы сайты отличались **друг
// от друга**, а два номера, разошедшихся на восемь, дали бы один цвет — и
// дали бы его молча, на живых данных. Цена размена: заведённый в середине
// списка сайт перекрашивает идущие за ним. Она разовая и видна сразу, а
// неразличимые вкладки были бы постоянными.
//
// ⚠ Список приходит с сервера в одном порядке на все шесть страниц раздела,
// поэтому цвет сайта одинаков везде — на этом держится весь приём.
function _datingSiteHue(sites, id) {
    const at = (sites || []).findIndex(row => String(row.id) === String(id));

    return at < 0 ? '' : String(at % DATING_SITE_HUES);
}

// Выкрасить страницу в цвет открытого сайта.
//
// ⚠⚠ Номер ставится **и на вкладку, и на `<body>`**, и это не дубль: на вкладке
// он красит её саму (чтобы цвет был виден у всех сразу, а не только у
// открытой), на теле — подвкладки открытого сайта, которые про список сайтов
// не знают ничего. Палитра при этом одна, в `dating_page.css`.
//
// ⚠ Неизвестный сайт снимает номер, а не ставит нулевой: запасной цвет в CSS —
// это прежний вид панели, а нулевой соврал бы «открыт первый сайт».
function _datingTabsTint(el) {
    if (!document.body) return;

    const hue = _datingSiteHue(el._datingSites, el.dataset.pick || '');

    if (hue) document.body.dataset.hue = hue;
    else delete document.body.dataset.hue;
}

// Счётчики: первый заход сразу, дальше по сроку.
//
// ⚠⚠ Таймер один на страницу, и прежний снимается: `datingSiteTabs` зовут и
// при первой загрузке, и при обновлении списка. Два таймера на одном контейнере
// удвоили бы запросы и стали бы перерисовывать вкладки друг под другом.
function _datingLiveLoop(el, base, sites) {
    if (el._datingLiveTimer) clearInterval(el._datingLiveTimer);

    const tick = async () => {
        // Контейнер мог уехать со страницы — например, сменился шаблон работы.
        if (!el.isConnected) {
            clearInterval(el._datingLiveTimer);

            return;
        }

        let live = {};
        try {
            live = (await getData(base + '/api/site/live')).result || {};
        } catch (e) {
            // ⚠ Молча: числа это украшение вкладки. Красная полоса на всю
            // панель из-за непришедшего счётчика пугала бы сильнее, чем стоит.
            return;
        }

        _datingTabsPaint(el, sites, live);
        _datingTabsWire(el, sites, el._datingOnPick);
    };

    el._datingLiveTimer = setInterval(tick, DATING_SITE_LIVE_MS);
    tick();
}
