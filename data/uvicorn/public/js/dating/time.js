// Времена панели: сдвиг из UTC в часовой пояс настройки.
//
// ⚠ **Всё, что приходит с сервера, — UTC.** И база, и контейнер приложения живут
// по UTC (`TZ` в compose не задан), поэтому `created_at`, `last_seen_at` и прочие
// метки приезжают в UTC. Показывать их как есть — значит показывать человеку
// время на несколько часов назад: он сверяет метку с часами на стене.
//
// Пояс берётся из настройки `timezone` («+3», «UTC-2») и приезжает **в разметке**,
// готовым числом часов (`window.DATING_TZ`, кладёт `base.html`). Не запросом:
// первые кадры страницы успели бы нарисоваться со старым значением, и человек
// видел бы, как время прыгает у него на глазах. Второй довод — ручка настроек
// закрыта админом, а правильное время нужно и оператору.
//
// Часы браузера здесь ни при чём намеренно. Оператор может сидеть в другом поясе,
// чем анкеты, а времена анкеты живут по одному общему поясу — тому, что в
// настройке. `toLocaleString` дал бы у двух людей разные времена одного события.

// Сколько часов прибавить к UTC. Ноль — «показываем как есть», то есть поведение
// до появления настройки.
//
// ⚠ Отсутствие `window` — законный случай, а не «такого не бывает»: модуль
// импортируется и вне браузера (сюита ленты расписания гоняет соседний модуль в
// `node`, `tests/test_schedule_band.js`). Падать там нечему: пояса нет — значит
// сдвига нет.
function tzHours() {
    if (typeof window === 'undefined') return 0;

    return Number(window.DATING_TZ) || 0;
}

// Метка времени сервера, сдвинутая в пояс настройки.
//
// Возвращает строку `YYYY-MM-DD HH:MM:SS` — тот же вид, в каком метка пришла,
// чтобы всё, что резало её по индексам, продолжало работать.
//
// Разбираем сами, а не через `new Date`: FastAPI отдаёт `2026-09-01T07:42:28` без
// часового пояса, и браузер такую строку **считает местной** — то есть прибавил
// бы к ней ещё и свой сдвиг поверх нашего. Приписать «Z» можно, но тогда результат
// придётся доставать методами `getUTC*`, а это тот же ручной разбор, только
// длиннее.
export function timeShift(value) {
    const raw = String(value || '').replace('T', ' ');
    if (raw.length < 19) return raw;

    const hours = tzHours();
    if (!hours) return raw;

    // Собираем дату как UTC и двигаем миллисекундами: сложение часов «в уме»
    // ошибается на границе суток, месяца и года — 31 декабря 23:00 плюс два часа
    // это не «31 декабря 25:00».
    const at = Date.UTC(+raw.slice(0, 4), +raw.slice(5, 7) - 1, +raw.slice(8, 10),
                        +raw.slice(11, 13), +raw.slice(14, 16), +raw.slice(17, 19));
    if (Number.isNaN(at)) return raw;

    const moved = new Date(at + hours * 3600000);
    const pad = (n) => String(n).padStart(2, '0');

    return `${moved.getUTCFullYear()}-${pad(moved.getUTCMonth() + 1)}-${pad(moved.getUTCDate())}`
        + ` ${pad(moved.getUTCHours())}:${pad(moved.getUTCMinutes())}:${pad(moved.getUTCSeconds())}`;
}

// «Сегодня» по часам панели, а не браузера: сравнивать сдвинутую метку с датой
// браузера значило бы называть вчерашним то, что для панели сегодняшнее.
export function timeToday() {
    return timeShift(new Date().toISOString().slice(0, 19).replace('T', ' ')).slice(0, 10);
}

// Сколько минут прошло с начала **местных** суток панели: 0–1439.
//
// ⚠ Мера здесь та же, в какой расписание задано и в какой его читает воркер
// (`dating_schedule_now(rows, minutes)`, `dating_mailing_round_run(offset_hours)`).
// Возьми страница часы браузера — оператор из другого пояса видел бы зелёной не ту
// смену, которую сервер считает идущей, и лента спорила бы с делом.
export function timeNowMinutes() {
    const local = timeShift(new Date().toISOString().slice(0, 19).replace('T', ' '));

    return Number(local.slice(11, 13)) * 60 + Number(local.slice(14, 16));
}

// Возраст метки словами: «только что», «17 ч назад», «3 дн назад».
//
// ⚠⚠ **Зачем понадобилось.** Снимок ленты показывался часами снятия — «кеш 06:28»,
// — и в одиннадцать вечера это читалось как «недавно», хотя прошли сутки работы.
// Ловушка была двойной: часы 24-часовые, и утро от вечера человек различал только
// зная это. Спросили прямо: «06:28 — это шесть утра или шесть вечера?»
//
// Возраст такого вопроса не задаёт вовсе. Час снятия при этом не теряется — он
// остаётся в подсказке, там его читают те, кому нужна точность.
//
// ⚠ **Пояс здесь ни при чём, и это не оплошность.** Возраст — разница двух
// моментов, а разность от пояса не зависит: 03:28 UTC семнадцать часов назад и в
// Киеве, и в Токио. Отсюда и приём: метку разбираем как UTC (сервер только такие и
// шлёт) и вычитаем из часов браузера, не трогая `timeShift`.
//
// ⚠ **Считаем от метки, а не берём `age_sec` из ответа.** Ответ мог прийти час
// назад и с тех пор лежать в памяти страницы: «2 мин назад» застыло бы на месте,
// пока человек смотрит. Разница же пересчитывается на каждой отрисовке сама.
export function timeAgo(value) {
    const raw = String(value || '').replace('T', ' ');
    if (raw.length < 19) return '';

    const at = Date.UTC(+raw.slice(0, 4), +raw.slice(5, 7) - 1, +raw.slice(8, 10),
                        +raw.slice(11, 13), +raw.slice(14, 16), +raw.slice(17, 19));
    if (Number.isNaN(at)) return '';

    return timeAgoSec((Date.now() - at) / 1000);
}

// То же из готового числа секунд — для тех, кому возраст уже посчитал сервер.
//
// ⚠ **Часы переходят в дни, а не растут без предела.** Снимок живёт неделю, и
// «168 ч назад» — число, которое человек делит в уме, чтобы понять, много это или
// мало.
//
// ⚠ Отрицательное — «только что»: часы браузера и сервера расходятся на секунды, и
// «-3 с назад» выглядело бы поломкой там, где всё в порядке.
export function timeAgoSec(sec) {
    const left = Math.floor(Number(sec) || 0);

    if (left < 10) return 'только что';
    if (left < 60) return `${left} с назад`;
    if (left < 3600) return `${Math.floor(left / 60)} мин назад`;
    if (left < 86400) return `${Math.floor(left / 3600)} ч назад`;

    return `${Math.floor(left / 86400)} дн назад`;
}
