// Как показывают учётку: значки, бейджи, подсказки, время.
//
// Общее для «Анкет» и «Профилей». Обе страницы рисуют одни и те же строки одной
// и той же ручки (`GET /api/dating/profile`), и две копии этой логики разошлись
// бы в мелочах — а мелочи здесь и есть смысл: пульсирующая точка отличает живую
// анкету от замершего экрана, мигающий ⚠ отличает «ещё пробуем» от «сдались».
//
// Разметка тут же, а не в шаблонах, по той же причине: классы (`dot`, `pill`,
// `profile-warn`) живут в `dating_page.css`, общем для обеих страниц, и менять
// их надо в одном месте.

import {timeShift, timeToday} from './time.js';

export function esc(value) {
    const el = document.createElement('div');
    el.textContent = value == null ? '' : value;
    return el.innerHTML.replace(/"/g, '&quot;').replace(/'/g, '&#39;');
}

export function face(photo, cls = 'profile-face') {
    // Лицо анкеты одной строкой. ⚠⚠ **Имена у девушек повторяются** — на сайте
    // две Дианы, — и в журнале они различались только памятью читающего: строки
    // одинаковые, понять, чья работа, можно было лишь открыв «Анкеты».
    //
    // ⚠ `referrerpolicy="no-referrer"` обязателен, и это не про приватность.
    // Сайты знакомств защищаются от хотлинка: LadaDate отдаёт фото по прямому
    // запросу (200), но с чужим `Referer` отвечает **403**. Браузер шлёт его
    // сам, и без этого атрибута аватарки пусты при верных адресах в базе.
    //
    // ⚠ Пустое фото рисуется **пустой клеткой того же размера**, а не
    // пропускается: иначе имена ездят влево-вправо и столбец перестаёт читаться
    // сверху вниз. Анкета без фото — обычное дело: её просто ещё не читали.
    if (!photo) {
        return `<span class="${cls}"></span>`;
    }

    return `<img class="${cls}" src="${esc(photo)}" alt="" loading="lazy"`
        + ' referrerpolicy="no-referrer">';
}

// Классы лиц, которым положена заглушка. ⚠ Список закрытый, и `work-who-face`
// в него не входит намеренно: лицо в шапке — **один переиспользуемый узел** с
// `id`, его адрес меняют на каждую выбранную анкету. Подмени его на `span`, и
// следующей анкете менять было бы нечего. Здесь только те лица, что строятся
// заново на каждую отрисовку списка.
const FACE_STUB_CLASSES = ['profile-face', 'mail-face'];

export function faceFallback(root = document) {
    // Фотографию отдаёт **сам сайт знакомств**, у нас лежит только адрес; между
    // браузером оператора и его Cloudflare случается всё — VPN, проверка,
    // залежавшийся неудачный ответ (`max-age` там год). Прежде такой промах
    // прятал картинку (`onerror` → `visibility: hidden`), и строка выходила
    // безликой: «фотографии нет» и «фотография не доехала» выглядели одинаково.
    //
    // ⚠ Слушаем **на перехвате** (`true`): `error` у картинки не всплывает, и
    // обычный слушатель на документе не сработал бы вовсе.
    root.addEventListener('error', (event) => {
        const el = event.target;
        if (!(el instanceof HTMLImageElement)) return;
        if (!FACE_STUB_CLASSES.some(cls => el.classList.contains(cls))) return;

        faceStub(el);
    }, true);
}

function faceStub(el) {
    // Имя берём из `alt`: там ему и место — это подпись к картинке, а не наша
    // выдумка ради заглушки. Нет имени — остаётся пустая клетка прежнего
    // размера, то есть ровно прежнее поведение.
    const name = String(el.getAttribute('alt') || '').trim();
    const stub = document.createElement('span');

    stub.className = `${el.className} face-stub`;
    stub.textContent = name ? name[0].toUpperCase() : '';
    // ⚠ Подсказка обязательна: буква сама по себе читается как «фотографии
    // нет», а это другое состояние — и лечится оно другим.
    stub.title = name ? `${name}: фотография не загрузилась`
        : 'фотография не загрузилась';

    el.replaceWith(stub);
}

export function statusTitle(row) {
    if (row.status === 'online') {
        return 'вход подтверждён ' + String(row.last_seen_at || '').slice(0, 19).replace('T', ' ')
            + proxyHint(row);
    }
    if (row.status === 'error') return row.last_error || 'опрос не прошёл';
    return row.has_state ? 'вход протух — залогиньтесь заново' : 'входа ещё не было';
}

// Каким адресом сайт видит анкету — хвостом к подсказке «в сети».
//
// ⚠ **Только у той, что в сети.** Выход назначается сам, при первом походе к
// сайту, и у спящей анкеты в кэше может лежать адрес, которого она в следующий
// раз не получит: реестр изменился, предел не сошёлся. Показывать его значит
// обещать то, чего не будет, — а по такому обещанию потом ищут причину
// блокировки.
//
// ⚠ Пусто — законный случай: `proxy_required` выключен, и анкета ходит общим
// адресом сервера. Молчание здесь честнее выдуманного «нет прокси»: подсказка
// отвечает на вопрос «когда подтверждён вход», а не «есть ли выход».
export function proxyHint(row) {
    const ip = String(row.proxy_ip || '');

    return ip ? `\nвыход: ${ip}` : '';
}

// Точка «в сети или нет» — **два** состояния, а не три: зелёная пульсирует,
// красная нет. Отдельно от `statusDot`, где состояний три (серое «не входили»,
// зелёное, красное «опрос не прошёл»).
//
// Разница по смыслу вопроса. `statusDot` отвечает «что с учёткой» — и «входа ещё
// не было» там честно серое, потому что это не поломка. Здесь вопрос другой:
// «работает ли анкета прямо сейчас». Ответа на него ровно два, и серый в колонке
// с двумя состояниями читался бы как третье, которого нет.
export function onlineDot(row) {
    const on = row.status === 'online';

    return `<span class="dot ${on ? 'online' : 'off'}" title="${esc(statusTitle(row))}"></span>`;
}

export function statusDot(row) {
    return `<span class="dot ${esc(row.status)}" title="${esc(statusTitle(row))}"></span>`;
}

// Значок «не входит». Текст подсказки собираем здесь, а состояние считает
// сервер: арифметика суток в двух местах разошлась бы.
export function warnBadge(row) {
    if (!row.revive_state || row.revive_state === 'ok') return '';

    const when = row.relogin_next_at ? timeShift(row.relogin_next_at).slice(11, 16) : '';
    const title = row.revive_state === 'given_up'
        ? `не удаётся войти: ${row.last_error || 'причина неизвестна'} — попытки прекращены, нужен вход вручную`
        : `не удаётся войти: ${row.last_error || 'причина неизвестна'}`
          + (when ? `; следующая попытка в ${when}` : '');

    return `<span class="profile-warn ${esc(row.revive_state)}" title="${esc(title)}">⚠</span>`;
}

// Работа, которая на учётке висит: непрочитанные в чате, собеседники, письма.
// Ноли не показываются вовсе — бейдж «0» занимает место и ничего не сообщает.
export function workPills(row) {
    return (row.unread_chat ? `<span class="pill chat" title="новых сообщений в чате">💬 ${row.unread_chat}</span>` : '')
        + (row.contacts ? `<span class="pill" title="собеседников в чате">Собеседников: ${row.contacts}</span>` : '')
        + (row.unread > 0 ? `<span class="pill mail" title="непрочитанных писем в почте">✉ ${row.unread}</span>` : '');
}

// Время — абсолютное, `26/08 13:59`, и это не лень.
//
// «Вчера» и «2 часа назад» пришлось бы считать по часам браузера, а времена
// анкеты живут по одному общему поясу — тому, что стоит в настройке `timezone`.
// Оператор может сидеть в другом; «вчера» тогда показывалось бы у записи,
// сделанной час назад. День и месяц перед временем нужны по той же причине, по
// какой они стоят в журнале: записи лежат за много дней, и голое время не
// отличает вчерашнюю попытку входа от сегодняшней. Год опущен — смотрят
// последние дни, а строка повторяется у каждой записи.
//
// Сдвиг из UTC делает `timeShift` (`dating_time.js`): с сервера метка приходит в
// UTC, а человек сверяет её с часами на стене.
export function seenText(value) {
    const text = timeShift(value);
    if (text.length < 16) return '';

    return `${text.slice(8, 10)}/${text.slice(5, 7)} ${text.slice(11, 16)}`;
}

// Отметка времени в журнале: «19/08 11:39:23» — день и месяц перед временем.
//
// Дата нужна потому, что журнал хранит записи за много дней, а одно голое время
// не отличает вчерашнюю попытку входа от сегодняшней — при разборе «почему анкета
// не входит» это первое, что нужно знать.
//
// Год не показываем: строка стоит перед каждой записью, а разбирают журнал за
// последние дни. Резать по индексам можно, потому что формат фиксирован
// (`YYYY-MM-DDTHH:MM:SS.ffffff` от FastAPI); разъедется он — здесь и будет видно,
// а не в тихо неверной дате.
//
// Секунды здесь есть, а в `seenText` их нет, и это не расхождение: в журнале
// подряд идущие шаги укладываются в одну минуту, и без секунд не видно, что за
// чем шло; в колонке «Вход» секунда события месячной давности не значит ничего.
// Короткая метка для тесных мест: сегодняшнее — часами, старше — датой.
//
// ⚠ **Одними часами показывать нельзя.** «16:25» у сообщения недельной давности
// читается как сегодняшнее, и человек отвечает на письмо, которое считает свежим.
// Место при этом тесное — строка диалога и шапка колонки, — поэтому дата вместо
// часов, а не вместе с ними.
//
// «Сегодня» считается по часам панели, а не браузера: оператор может сидеть в
// другом поясе, и его полночь не должна объявлять вчерашним то, что для панели
// сегодняшнее.
export function timeShort(value) {
    const stamp = timeShift(value);
    if (stamp.length < 16) return '';

    return timeToday() === stamp.slice(0, 10)
        ? stamp.slice(11, 16)
        : `${stamp.slice(8, 10)}/${stamp.slice(5, 7)}`;
}

// Полная метка для окна переписки: `10:35 26/12/2026`.
//
// ⚠ **Год обязателен, и не сокращённый.** В окне разговор читают целиком, и в нём
// рядом лежат реплики из живого сокета и привезённые из панели агентства — то есть
// сегодняшние и прошлогодние. «26/12» у прошлогодней читается как позавчерашняя, а
// две последние цифры года («26/12/26») путаются с числом и месяцем.
//
// Время впереди даты: в разговоре сперва смотрят на час, а дату уточняют лишь у тех
// реплик, где усомнились.
export function timeFull(value) {
    const stamp = timeShift(value);
    if (stamp.length < 16) return '';

    return `${stamp.slice(11, 16)} ${stamp.slice(8, 10)}/${stamp.slice(5, 7)}`
         + `/${stamp.slice(0, 4)}`;
}

export function logStamp(value) {
    const raw = timeShift(value);
    if (raw.length < 19) return raw;

    return `${raw.slice(8, 10)}/${raw.slice(5, 7)} ${raw.slice(11, 19)}`;
}

// Журнал учётки в панель. Общий для «Анкет» и «Профилей»: строки одной и той же
// ручки, и две копии разошлись бы в цвете уровня — а по нему в ленте и ищут.
//
// Прокрутку сохраняем сами: журнал перерисовывается своим таймером, и без этого
// он прыгал бы наверх у человека, который отлистал к нужной строке.
export function logRender(el, rows, emptyText) {
    const scroll = el.scrollTop;

    el.innerHTML = rows.length
        ? rows.map(row => `<div class="log-row ${esc(row.level)}">`
            + `<span class="log-time">${esc(logStamp(row.created_at))}</span>`
            + `<span class="log-text">${esc(row.text)}</span></div>`).join('')
        : `<div class="log-empty">${esc(emptyText)}</div>`;

    el.scrollTop = scroll;
}

// Кнопки страниц. Одна функция на все списки панели — анкеты, собеседницы,
// профили: разъехавшись, они дали бы разные пейджеры на соседних страницах.
//
// `current` — номер с нуля, как индекс среза, которым режут список.
//
// `count` — счёт строк словами и без номера страницы: «40 анкет», «7 из 40
// анкет». Номер приписывает пейджер сам: «страница 2 из 3» — его знание, и
// собирать эту строку у каждого списка значило бы три места, которые разойдутся.
// Имя предмета при этом остаётся за списком: у одного анкеты, у другого
// собеседницы.
//
// ⚠ **Счёт заодно решает, показывать ли подвал при одной странице.** Без счёта
// пейджер из одной кнопки только занимает место — подвал прячется. Со счётом
// прятать нельзя: под списком пусто, и пропавший подвал читается как «пагинации
// нет вообще» — человек не понимает, показали ему всё или только начало. Строка
// «всё на одной странице» отвечает на это прямо.
export function pagerRender(el, pages, current, pick, count = '') {
    const show = pages > 1 || !!count;
    el.classList.toggle('open', show);
    if (!show) {
        el.innerHTML = '';
        return;
    }

    // ⚠ Одна страница — счёт **по центру**, а не слева. Кнопок рядом нет, и
    // прижатая к краю строка выглядит забытой; классом, а не стилем в разметке:
    // раскладку подвала держит `dating_page.css`, и делить её на два места
    // значило бы искать причину сдвига в двух местах сразу.
    el.classList.toggle('lone', pages <= 1);

    if (pages <= 1) {
        el.innerHTML = '';
        el.append(pagerCount(`${count} — всё на одной странице`));
        return;
    }

    const button = (label, page, disabled, active) =>
        `<button type="button" class="page-btn${active ? ' active' : ''}" data-page="${page}"`
        + `${disabled ? ' disabled' : ''}>${label}</button>`;

    // ⚠ Кнопки — **в своей обёртке**, а не прямыми детьми подвала: подвал разложен
    // сеткой в три колонки, и только так счёт слева не сдвигает кнопки с середины.
    // Прежде счёт съедал свободное место `margin-right: auto`, и центр уезжал тем
    // сильнее, чем длиннее строка счёта.
    let html = button('‹', current - 1, current === 0, false);
    for (const page of pagerPages(pages, current)) {
        html += page === PAGER_GAP
            // Разрыв — не кнопка: нажимать в нём нечего, и `<button disabled>`
            // обещал бы обратное. Заодно он не ловит Tab.
            ? '<span class="page-gap">…</span>'
            : button(page + 1, page, false, page === current);
    }
    html += button('›', current + 1, current === pages - 1, false);

    const pagesEl = document.createElement('span');
    pagesEl.className = 'pane-pages';
    pagesEl.innerHTML = html;

    el.innerHTML = '';
    // Счёт — первым, до кнопок: порядок в разметке совпадает с порядком на экране,
    // и читалка идёт по нему так же, как глаз.
    if (count) el.append(pagerCount(`${count} · страница ${current + 1} из ${pages}`));
    el.append(pagesEl);

    pagesEl.querySelectorAll('.page-btn').forEach(btn => {
        btn.addEventListener('click', () => pick(Number(btn.dataset.page)));
    });
}

// Метка разрыва в ряду страниц. Не число и не строка «…»: сравнивать с числом
// проще, а вид разрыва решает тот, кто рисует.
export const PAGER_GAP = -1;

// Сколько страниц показываем по каждую сторону от текущей.
//
// Одна: ряд выходит «1 … 4 5 6 … 20» — семь мест, и он не растёт с числом
// страниц. Две дали бы девять и на узкой колонке уже переносились бы.
export const PAGER_AROUND = 1;

// Самый длинный ряд, какой вообще может получиться: два края, окно вокруг текущей
// и два разрыва между ними.
//
// ⚠ Из него же следует, **когда разрывы не нужны вовсе**: пока страниц не больше,
// чем мест в ряду, они все в него помещаются, и «…» ничего не сокращает — только
// прячет. Так и вышло на пяти страницах: ряд «1 2 … 5» той же ширины, что «1 2 3 4
// 5», но две страницы из него исчезли.
export const PAGER_MAX_ROW = 2 * PAGER_AROUND + 5;

// Какие страницы показать: первая, последняя, соседи текущей, между ними разрывы.
//
// ⚠ Заведено потому, что **страниц бывает много**. Ряд из всех подряд у сорока
// страниц не помещается в колонку и переносится на вторую строку, отодвигая список;
// а нужны из них ровно три — где мы, начало и конец.
//
// ⚠ **Разрыв в одну страницу закрываем самой страницей.** «…» вместо «3» ничего не
// сокращает (ширина та же), а прячет то, до чего один щелчок.
//
// Вынесена наружу ради проверки (`tests/test_pager.js`): правило словами не
// проверить, а через браузер — значило бы поднимать Chromium ради арифметики.
export function pagerPages(pages, current, around = PAGER_AROUND) {
    const total = Math.max(0, Number(pages) || 0);
    if (total <= 1) return total ? [0] : [];

    // Все помещаются — показываем все: разрыв здесь не сокращает ряд, а только
    // прячет страницы (см. `PAGER_MAX_ROW`).
    if (total <= 2 * around + 5) return [...Array(total).keys()];

    const now = Math.min(Math.max(Number(current) || 0, 0), total - 1);

    // Что показываем непременно: края и окно вокруг текущей.
    const want = new Set([0, total - 1]);
    for (let i = now - around; i <= now + around; i++) {
        if (i >= 0 && i < total) want.add(i);
    }

    const list = [...want].sort((a, b) => a - b);
    const out = [];

    list.forEach((page, index) => {
        const prev = list[index - 1];
        if (index && page - prev > 1) {
            out.push(page - prev === 2 ? prev + 1 : PAGER_GAP);
        }
        out.push(page);
    });

    return out;
}

// Счёт строк в подвале. Узлом с `textContent`, а не разметкой: строку собирает
// вызывающий из имени предмета, и вставлять её как HTML значило бы без нужды
// доверять ей разметку.
function pagerCount(text) {
    const el = document.createElement('span');
    el.className = 'pane-count';
    el.textContent = text;

    return el;
}
