// Селект сайта в шапке страниц раздела Dating.
//
// Своих сайтов у проекта нет: закладки живут у соседа (RhapsodyAi) и приходят
// сюда ручкой `GET /api/site`. Каждая страница раздела начинается с одного и
// того же — спросить список, нарисовать `<option>`, вернуть человеку тот сайт,
// который он выбирал в прошлый раз.
//
// Ключ выбора общий на весь раздел намеренно: человек ходит между страницами, и
// разный выбранный сайт на соседних читается как «я же выбрал ladadate», а
// показана оказывается чужая учётка. Поэтому копия этой загрузки на каждой
// странице и опасна: разъехавшись в мелочах, они продолжают писать в один ключ.
//
// Отдельным файлом, а не в `dating_view.js`: тот про отрисовку учётки — значки,
// бейджи, время, — и запроса к серверу в нём нет ни одного.

import {getData} from './api.js';
import {esc} from './dating_view.js';

// Где лежит выбранный сайт. Одно имя на весь раздел — см. выше.
export const DATING_SITE_KEY = 'dating_site';

// Заполняет селект сайтами и возвращает пришедший список.
//
// **Отказ не глотается.** Сказать о нём страница обязана по-своему: «Анкеты» пишут
// в подсказку шапки, остальные показывают уведомление. Селект при этом остаётся
// каким был — страница сама решает, писать ли в него «сайты не пришли».
export async function datingSiteFill(el, base) {
    const sites = (await getData(base + '/api/site')).result || [];

    // Имя — через `esc`, id — через `Number`: и то и другое пришло от соседа, а
    // подставляется в разметку. Название сайта заводит человек, и кавычка в нём
    // без экранирования разорвала бы атрибут.
    el.innerHTML = sites.length
        ? sites.map(row => `<option value="${Number(row.id)}">${esc(row.name)}</option>`).join('')
        : '<option value="">сайтов нет</option>';

    // Сохранённый сайт ставим, только если он ещё в списке: закладку у соседа
    // могли убрать, и выбор «как в прошлый раз» показал бы пустой селект.
    const saved = localStorage.getItem(DATING_SITE_KEY);
    if (saved && sites.some(row => String(row.id) === saved)) el.value = saved;

    return sites;
}
