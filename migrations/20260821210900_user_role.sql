-- Роль пользователя панели: user.role (выпуск 2026-08-21)
--
-- ПЕРЕНЕСЕНО из `data/migration_manual/` 30.08.2026. Гоняли руками потому, что
-- схема тогда жила одним замороженным `0001.sql`: на живой базе новой колонки от
-- правки файла не появилось бы, а без неё падает вход — `auth_required` читает роль.
--
-- ВТОРОЙ РАЗ НЕ ВЫПОЛНИТСЯ: колонка уже стоит и на проде, и локально (админ там
-- с ролью `admin`), а запись о файле внесена в `_yoyo_migration` вручную
-- (`.claude/docs/migration.md`, §2.1). Сверка с `information_schema` ниже —
-- второй рубеж: на установке с нуля колонка приходит из начальной схемы, а
-- таблица `user` на момент миграций ещё пуста, и повышать некого.
--
-- ЧТО МЕНЯЕТСЯ: одна колонка в `user`. Данные не переписываются.
--
-- ОДНО ИСКЛЮЧЕНИЕ — существующие учётки. По умолчанию колонка ставит `dating`
-- (новая учётка не должна получать доступ к бэкапам от того, что о роли забыли
-- подумать), но те, кто работал в панели до этой правки, работали с полными
-- правами. Понизить их молча значит отобрать доступ у того, кто им пользовался,
-- поэтому учётка из `ADMIN_USERNAME` получает `admin` явно. Остальные — если они
-- есть — остаются `dating`; поднять роль вручную дешевле, чем разбираться, кому
-- бэкапы достались по недосмотру.
--
-- Идемпотентность: колонка добавляется по сверке с `information_schema`, роль
-- админа проставляется только там, где она ещё пустая. Файл можно гонять сколько
-- угодно раз.
--
-- ПЕРЕД ПРОГОНОМ: дамп базы («Настройки → Backup» в панели либо
-- `.claude/docs/migration.md`, раздел 3).

-- ---------------------------------------------------------------- До
SELECT 'ДО' AS этап,
       (SELECT COUNT(*) FROM information_schema.COLUMNS
         WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'user'
           AND COLUMN_NAME = 'role') AS колонка_есть,
       (SELECT COUNT(*) FROM `user`) AS всего_учёток;

-- ------------------------------------------- 1. Колонка
SET @sql := IF(
    (SELECT COUNT(*) FROM information_schema.COLUMNS
      WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'user'
        AND COLUMN_NAME = 'role') = 0,
    'ALTER TABLE `user` ADD COLUMN `role` VARCHAR(20) NOT NULL DEFAULT ''dating''
       COMMENT ''dating — анкеты; admin — плюс установка'' AFTER `password_hash`',
    'SELECT ''role уже на месте'' AS шаг');
PREPARE это FROM @sql; EXECUTE это; DEALLOCATE PREPARE это;

-- ------------------------------------------- 2. Прежний хозяин панели — админ
--
-- Имя берётся не из окружения (SQL его не видит), а по самой ранней учётке: это
-- та, которую завёл `auth_seed_first_user` при первом запуске. На установке, где
-- учётка одна, это она и есть.
UPDATE `user`
   SET `role` = 'admin'
 WHERE `id` = (SELECT * FROM (SELECT MIN(`id`) FROM `user`) AS первая)
   AND `role` <> 'admin';

-- ---------------------------------------------------------------- После
SELECT 'ПОСЛЕ' AS этап, `id`, `username`, `role` FROM `user` ORDER BY `id`;
