-- Фиксация переименованной начальной схемы в журнале yoyo (выпуск 2026-08-26)
--
-- ПЕРЕНЕСЕНО из `data/migration_manual/` 30.08.2026 — вместе с остальными, чтобы
-- вся история схемы лежала в одном месте. Файл особый: он правит не схему и не
-- данные, а **журнал самого yoyo**, и на установке с нуля не делает ничего —
-- `SELECT` ниже ищет запись `0001`, которой там нет. Проверено на чистой базе:
-- вставки не произошло, все семь миграций прошли без ошибок.
--
-- ВТОРОЙ РАЗ НЕ ВЫПОЛНИТСЯ: на проде и локально он отработал руками 26.08.2026
-- (в журнале лежат обе записи), а запись о нём самом внесена в `_yoyo_migration`
-- вручную, как и об остальных перенесённых (§2.1).
--
-- ЗАЧЕМ ОН БЫЛ НУЖЕН. `migrations/0001.sql` переименован в
-- `20260101000000_initial_schema.sql`: дальше миграции нумеруются меткой времени и
-- сами встают в правильный порядок при слиянии веток. Но yoyo помнит применённое
-- по ИМЕНИ файла (`_yoyo_migration.migration_id`), и для него переименованный файл
-- — новый. Не зафиксировав его как применённый, ближайший старт панели выполнит
-- начальную схему заново, а в ней `DROP TABLE` по всем таблицам. То есть база
-- теряет всё: учётки анкет, переписку, журнал, собеседниц и пользователей.
--
-- ЧТО ПРОВЕРЕНО. Хеш в журнале yoyo — это sha256 от ИМЕНИ миграции, а не от
-- содержимого файла (`yoyo/migrations.py: get_migration_hash`). Значит запись
-- считается детерминированно и подделкой не является: она ровно та, что yoyo
-- записал бы сам.
--
-- Проверено не по документации, а по живому журналу этой базы: там лежит запись
-- `0001` с хешем `888b19a43b15…`, и это в точности sha256('0001'). Отсюда:
--
--   sha256('20260101000000_initial_schema')
--     = f8d6516fa90f6235e7dbf15d69bdaf83a28debf5372e250d50be66c0096cae49
--
-- ТАБЛИЦЫ И СТРОКИ: `_yoyo_migration`, одна строка. Данные не трогаются вовсе.
-- Старую запись `0001` НЕ удаляем — она след того, что схема применялась, и
-- никому не мешает.
--
-- ЕСЛИ ЗАПИСИ `0001` НЕТ (база поднималась с нуля уже после переименования) —
-- `SELECT` вернёт ноль строк, вставки не будет, и это верно: там уже стоит новое
-- имя.
--
-- ПОРЯДОК (когда файл гнали руками). На проде он шёл ДО выкладки кода с
-- переименованным файлом. Наоборот — значит дать панели стартовать с новым именем
-- и без записи в журнале, то есть ровно то, ради чего файл и написан. Это же
-- правило действует для любой ручной записи в `_yoyo_migration`: сначала запись,
-- потом выкладка кода с файлом.

INSERT INTO `_yoyo_migration` (`migration_hash`, `migration_id`, `applied_at_utc`)
SELECT 'f8d6516fa90f6235e7dbf15d69bdaf83a28debf5372e250d50be66c0096cae49',
       '20260101000000_initial_schema',
       COALESCE(MAX(`applied_at_utc`), UTC_TIMESTAMP())
  FROM `_yoyo_migration`
 WHERE `migration_id` = '0001'
ON DUPLICATE KEY UPDATE `applied_at_utc` = VALUES(`applied_at_utc`);

-- Проверка: должны быть обе записи.
SELECT `migration_id`, LEFT(`migration_hash`, 12) AS `hash`, `applied_at_utc`
  FROM `_yoyo_migration` ORDER BY `applied_at_utc`, `migration_id`;
