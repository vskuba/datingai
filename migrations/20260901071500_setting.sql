-- Таблица настроек панели: ключ → значение (выпуск 2026-09-01)
--
-- ЗАЧЕМ: до сих пор всё, что настраивается, жило в окружении — а окружение
-- меняется правкой `.env` и перезапуском контейнера. Для того, что настраивают
-- редко и один раз (адреса, токены), это нормально; для того, что подкручивают
-- на ходу, — нет. Страница «Настройки → Значения» даёт второй способ: строка в
-- базе, которую видно и можно поменять не заходя на сервер.
--
-- ФОРМА ВЗЯТА У СОСЕДА не ради единообразия, а ради общей библиотеки:
-- `py_modules/setting_/setting_.py` — один файл на оба проекта, и он ожидает
-- именно эти колонки. Разойдись схема — общий модуль пришлось бы ветвить по
-- проекту, а это ровно то, чего общая библиотека и должна избегать.
--
-- ⚠ `node_id` ЗДЕСЬ ЛИШНЯЯ, И ЭТО НАМЕРЕННО. Узлов (`node`) в этом проекте нет
-- и не планируется: узлы — хозяйство RhapsodyAi, где одна настройка бывает разной
-- на разных машинах. Колонку держим потому, что её читает и пишет общий модуль:
-- убери её — сломается `setting_get` на первом же вызове. Внешнего ключа при этом
-- нет, ссылаться не на что; значение всегда NULL.
--
-- Идемпотентность: `CREATE TABLE IF NOT EXISTS`. Файл можно гонять сколько угодно
-- раз.

-- ---------------------------------------------------------------- До
SELECT 'ДО' AS этап,
       (SELECT COUNT(*) FROM information_schema.TABLES
         WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'setting') AS таблица_есть;

-- ------------------------------------------- Таблица
--
-- `key` — CHAR(50): столько же, сколько у соседа. Ключ читает человек, и длинные
-- имена в нём заводить незачем.
--
-- `value` — LONGTEXT: в настройке бывает и число, и JSON-простыня. Тип один на
-- все значения, разбор — на стороне того, кто настройку читает.
--
-- `user_id` — настройка одного человека (у соседа так хранят личные предпочтения).
-- Страница такие не показывает: она про общие. Внешний ключ с каскадом — удалили
-- учётку, унесли и её настройки; висячая строка не пригодится никому.
--
-- `dynamic` — признак «поставлено кодом, а не человеком». Такие строки страница
-- тоже прячет: они не настройки, а состояние, и править их руками нечего.
CREATE TABLE IF NOT EXISTS `setting` (
    `id` INT NOT NULL AUTO_INCREMENT,
    `key` CHAR(50) NOT NULL,
    `user_id` INT DEFAULT NULL COMMENT 'настройка одного человека; NULL — общая',
    `node_id` INT DEFAULT NULL COMMENT 'узлов здесь нет: колонка ради общего py_modules/setting_',
    `value` LONGTEXT NOT NULL,
    `dynamic` TINYINT NOT NULL DEFAULT 0 COMMENT '1 — поставлено кодом; страница такие не показывает',
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_setting_key_scope` (`key`, `user_id`, `node_id`),
    CONSTRAINT `fk_setting_user` FOREIGN KEY (`user_id`) REFERENCES `user` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ---------------------------------------------------------------- После
SELECT 'ПОСЛЕ' AS этап,
       (SELECT COUNT(*) FROM information_schema.TABLES
         WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'setting') AS таблица_есть,
       (SELECT COUNT(*) FROM `setting`) AS строк;
