-- Журнал прогонов сценариев: что просили у соседа и чем это кончилось (2026-09-01)
--
-- ЗАЧЕМ: прогон сценария — самое дорогое, что делает панель. Это вкладка Chromium,
-- вход на сайт под анкетой и десятки секунд ожидания; идут они очередью, по одному.
-- До сих пор след от них оставался разрозненный: вход и импорт писали строку в
-- журнал анкеты, выгрузка и списки собеседников не писали ничего, а сколько прогон
-- занял и на каком шаге встал — не записывалось нигде.
--
-- ⚠ ОТДЕЛЬНАЯ ТАБЛИЦА, А НЕ `dating_log`. Две причины, и обе непреодолимые:
--
--   1. `dating_log.profile_id` — NOT NULL с внешним ключом. Импорт и выгрузка
--      гоняются **до** того, как анкета заведена, и приписать их некому.
--   2. У прогона своя форма: сценарий, длительность, номер шага, на котором он
--      встал. Втискивать это в одно текстовое поле значит терять то, ради чего
--      журнал и заводят, — возможность спросить «какие сценарии падают чаще».
--
-- Журнал анкеты при этом остаётся: где `profile_id` известен, строка пишется и
-- туда. Человек, разбирающий одну анкету, не должен ходить на другую страницу.
--
-- ЧИСТКА: своей нет и не планируется. Прогонов единицы в минуту (очередь их и не
-- пустит быстрее), а разбирают журнал за последние дни. Появится нужда — заведётся
-- отдельной миграцией, а не `DELETE` внутри вставки.
--
-- Идемпотентность: `CREATE TABLE IF NOT EXISTS`. Файл можно гонять сколько угодно раз.

-- ---------------------------------------------------------------- До
SELECT 'ДО' AS этап,
       (SELECT COUNT(*) FROM information_schema.TABLES
         WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'dating_scenario_run') AS таблица_есть;

-- ------------------------------------------- Таблица
--
-- `site_id` — без внешнего ключа: сайты живут у соседа, и проверить его движком
-- базы невозможно (то же правило, что у `dating_profile.site_id`).
--
-- `profile_id` — NULL там, где анкеты нет: импорт и выгрузка идут по сайту целиком.
-- Внешний ключ с `SET NULL`, а не `CASCADE`: удалили анкету — прогон остаётся.
-- Он про то, что делали с сайтом, и вопрос «почему импорт тогда развалился»
-- переживает саму анкету.
--
-- `scenario_name` хранится строкой рядом с номером: у соседа сценарий могут
-- переименовать или удалить, и тогда номер перестанет что-либо значить. Имя —
-- то, по чему прогон узнают через месяц.
--
-- `ms` — сколько занял прогон. Ради него журнал наполовину и заводится: «вход
-- стал идти вдвое дольше» видно только рядом лежащими замерами.
CREATE TABLE IF NOT EXISTS `dating_scenario_run` (
    `id` INT NOT NULL AUTO_INCREMENT,
    `site_id` INT NOT NULL COMMENT 'сайт у соседа; внешнего ключа нет — таблица чужая',
    `profile_id` INT NULL COMMENT 'анкета, если прогон о ней; импорт и выгрузка идут без неё',
    `scenario_id` INT NOT NULL DEFAULT 0 COMMENT 'номер у соседа; 0 — сценарий не нашёлся',
    `scenario_name` VARCHAR(200) NOT NULL COMMENT 'имя: номер могут переименовать',
    `status` ENUM('ok','error') NOT NULL DEFAULT 'ok',
    `step_no` INT NOT NULL DEFAULT 0 COMMENT 'шаг, на котором встал; 0 — дошёл до конца',
    `error` TEXT NULL COMMENT 'причина отказа целиком — её читают человеком',
    `ms` INT NOT NULL DEFAULT 0 COMMENT 'сколько занял прогон',
    `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    PRIMARY KEY (`id`),
    -- Лента страницы «Журналы»: отбор по сайту, порядок по свежести. Составной
    -- именно в этом порядке — сначала равенство, потом сортировка.
    INDEX `idx_dsr_site` (`site_id`, `id`),
    -- Журнал одной анкеты — по нему же собирается её лента прогонов.
    INDEX `idx_dsr_profile` (`profile_id`, `id`),
    CONSTRAINT `fk_dsr_profile` FOREIGN KEY (`profile_id`)
        REFERENCES `dating_profile` (`id`) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ---------------------------------------------------------------- После
SELECT 'ПОСЛЕ' AS этап,
       (SELECT COUNT(*) FROM information_schema.TABLES
         WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'dating_scenario_run') AS таблица_есть,
       (SELECT COUNT(*) FROM `dating_scenario_run`) AS строк;
