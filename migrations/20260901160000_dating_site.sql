-- Настройки сайта на нашей стороне (2026-09-01)
--
-- ЗАЧЕМ: сайты-закладки живут у RhapsodyAi — там их адрес, метки и `presence`.
-- Но появились настройки, которые про **нашу** работу с сайтом, а не про сам сайт:
-- их у соседа хранить негде и незачем. Таблица привязывает их к его номеру.
--
-- ⚠ ЭТО НЕ КОПИЯ СПИСКА САЙТОВ. Правило проекта («своей копии сайтов, сценариев и
-- агентов здесь не заводится», `CLAUDE.md`) остаётся в силе: имени и адреса здесь
-- нет и быть не должно — они у соседа, и вторая копия разошлась бы с первой в тот
-- день, когда сайт переименуют. Здесь только `site_id` как ключ и наши значения.
--
-- Строка появляется, когда настройку **сохранили**, а не когда сайт завели у
-- соседа. Пустая строка на каждый сайт означала бы, что таблица делает вид, будто
-- знает про сайты больше, чем знает.
--
-- ⚠ ВНЕШНЕГО КЛЮЧА НЕТ, и это осознанно: `site_id` указывает в чужую базу, движком
-- его не проверить. То же правило, что у `dating_profile.site_id` (`database.md`,
-- §3). Проверяет API-клиент: несуществующий сайт получает 422 от соседа.
--
-- ФОРМА ЗНАЧЕНИЙ — JSON, а не колонка на настройку. Настройки сайта только
-- заводятся, и какие именно понадобятся, сейчас не знает никто; колонка под каждую
-- означала бы миграцию на каждую. Когда список устоится, частые переедут в свои
-- колонки — тогда будет что переносить.
--
-- Идемпотентность: `CREATE TABLE IF NOT EXISTS`. Файл можно гонять сколько угодно раз.

-- ---------------------------------------------------------------- До
SELECT 'ДО' AS этап,
       (SELECT COUNT(*) FROM information_schema.TABLES
         WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'dating_site') AS таблица_есть;

-- ------------------------------------------- Таблица
CREATE TABLE IF NOT EXISTS `dating_site` (
    `site_id` INT NOT NULL COMMENT 'Сайт-закладка в RhapsodyAi: своей таблицы сайтов здесь нет',
    `settings` JSON NULL COMMENT 'Наши настройки этого сайта: ключ → значение',
    `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `updated_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (`site_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ---------------------------------------------------------------- После
SELECT 'ПОСЛЕ' AS этап,
       (SELECT COUNT(*) FROM information_schema.TABLES
         WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'dating_site') AS таблица_есть,
       (SELECT COUNT(*) FROM `dating_site`) AS строк;
