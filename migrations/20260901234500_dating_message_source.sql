-- Откуда сообщение: сокет или панель агентства (2026-09-01)
--
-- ЗАЧЕМ: у панели агентства есть страница `userchatmessages` — журнал сообщений
-- анкет за диапазон дат. Это **тот же вид данных**, что ловит вебсокет, поэтому
-- отдельной таблицы под него не заводим: сообщения живут в `dating_message`, и
-- страница показывает их той же карточкой чата, не зная, откуда они взялись.
--
-- Но два различия сохранить обязательно, и ради них эта колонка.
--
-- ⚠ РАЗНЫЕ ПРОСТРАНСТВА НОМЕРОВ. У сокета `message_uid` — ULID кадра, у панели
-- свой числовой номер (`36594474`). Колонка одна, и без пометки источника
-- разобрать, чей это номер, потом будет нечем. Номера панели пишутся с приставкой
-- (`panel:36594474`), а колонка говорит то же самое явно — приставку в запросе не
-- напишешь, а `source = 'panel'` напишешь.
--
-- ⚠ ИМПОРТ НЕ ДОЛЖЕН ЗАПУСКАТЬ АВТООТВЕТ. Автоответчик берёт последнее
-- неотвеченное входящее по каждому собеседнику (`dating_answer.py`), и привезённая
-- за неделю история выглядит для него ровно как свежая почта: агент начал бы
-- отвечать на недельные сообщения пачкой — деньги на LLM и настоящие письма
-- настоящим людям. Пометки «уже пробовали» (`answer_tried_at`) для этого мало:
-- она держит пять минут, а потом попытка повторяется.
--
-- Поэтому отбор автоответа исключает `source = 'panel'`. Это **временно и
-- намеренно**: ответы на привезённые сообщения — отдельная задача, и включать их
-- надо осознанно, а не побочным следствием импорта.
--
-- ПОЧЕМУ УМОЛЧАНИЕ `socket`: строк в таблице уже 25 тысяч, и все они от сокета.
-- Умолчание `panel` соврало бы про каждую из них, а `NULL` заставил бы каждый
-- запрос помнить про третье состояние, которого не бывает.
--
-- Идемпотентность: колонка добавляется проверкой на существование. Файл можно
-- гонять сколько угодно раз.

-- ---------------------------------------------------------------- До
SELECT 'ДО' AS этап,
       (SELECT COUNT(*) FROM information_schema.COLUMNS
         WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'dating_message'
           AND COLUMN_NAME = 'source') AS колонка_есть,
       (SELECT COUNT(*) FROM `dating_message`) AS строк;

-- ------------------------------------------- Колонка
SET @sql := IF(
    (SELECT COUNT(*) FROM information_schema.COLUMNS
      WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'dating_message'
        AND COLUMN_NAME = 'source') = 0,
    'ALTER TABLE `dating_message`
       ADD COLUMN `source` ENUM(''socket'',''panel'') NOT NULL DEFAULT ''socket''
           COMMENT ''Откуда сообщение: живой сокет или журнал панели агентства''',
    'SELECT ''колонка source уже есть'' AS пропуск');
PREPARE stmt FROM @sql; EXECUTE stmt; DEALLOCATE PREPARE stmt;

-- ---------------------------------------------------------------- После
SELECT 'ПОСЛЕ' AS этап,
       (SELECT COUNT(*) FROM information_schema.COLUMNS
         WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'dating_message'
           AND COLUMN_NAME = 'source') AS колонка_есть,
       (SELECT COUNT(*) FROM `dating_message` WHERE `source` = 'panel') AS из_панели;
