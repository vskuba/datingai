-- Индекс диалога по времени: «последняя реплика» перестала совпадать с `MAX(id)` (2026-09-02)
--
-- ЗАЧЕМ: карточка чата раскладывает собеседников по свежести последней реплики, а
-- свежесть считала по `MAX(id)` — автоинкремент, который для сокета совпадал с
-- порядком событий: сообщение пришло, сообщение легло.
--
-- ⚠ С импортом переписки из панели агентства это перестало быть правдой. Импорт
-- приносит **историю за неделю** и кладёт её сегодня, то есть **после** всего, что
-- сокет успел поймать. В диалоге, где есть оба источника, наибольший `id` — у
-- недельной давности реплики, и карточка показывала её как последнюю: диалоги
-- сортировались наоборот, а красный значок «нужен ответ» загорался по старому
-- сообщению.
--
-- Сортировать пачку при вставке недостаточно, и это главное: внутри пачки порядок
-- поправить можно, но сама пачка ложится позже свежих сообщений сокета.
--
-- ЦЕНА ИЗМЕРЕНА, и поэтому индекс, а не оконная функция. На 21 762 репликах и 400
-- диалогах:
--
--   * `MAX(id)`, как было              —   9 мс, но ответ неверный;
--   * `ROW_NUMBER()` по времени        — 121 мс (и 118 мс даже с этим индексом:
--                                        MySQL всё равно сортирует);
--   * `MAX(created_at)` + этот индекс  —  29 мс, ответ верный.
--
-- Двадцать миллисекунд на перерисовку карточки (раз в 15 секунд на открытую
-- анкету) — приемлемо; сто двадцать были бы нет.
--
-- ПОРЯДОК ПОЛЕЙ: `profile_id` и `sender_uid` берутся равенством, `created_at`
-- остаётся отсортированным — по нему и свежесть диалога, и десяток последних
-- реплик без сортировки. `id` в хвосте разнимает реплики, пришедшиеся на одну
-- секунду: у панели время с точностью до секунды, и без него «последняя» из двух
-- выбиралась бы случайно.
--
-- ⚠ СТАРЫЙ ИНДЕКС НЕ УБИРАЕМ. `idx_dating_message_dialog` (по `id`) по-прежнему
-- покрывает счёт реплик и выборку по `id`, и он дешевле этого на чтение.
--
-- Идемпотентность: индекс добавляется проверкой на существование. Файл можно
-- гонять сколько угодно раз.

-- ---------------------------------------------------------------- До
SELECT 'ДО' AS этап,
       (SELECT COUNT(*) FROM information_schema.STATISTICS
         WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'dating_message'
           AND INDEX_NAME = 'idx_dating_message_time') AS индекс_есть,
       (SELECT COUNT(*) FROM `dating_message`) AS строк;

-- ------------------------------------------- Индекс
SET @sql := IF(
    (SELECT COUNT(*) FROM information_schema.STATISTICS
      WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'dating_message'
        AND INDEX_NAME = 'idx_dating_message_time') = 0,
    'CREATE INDEX `idx_dating_message_time` ON `dating_message`
        (`profile_id`, `sender_uid`, `created_at`, `id`)',
    'SELECT ''индекс уже есть'' AS пропуск');
PREPARE stmt FROM @sql; EXECUTE stmt; DEALLOCATE PREPARE stmt;

-- ---------------------------------------------------------------- После
SELECT 'ПОСЛЕ' AS этап,
       (SELECT COUNT(*) FROM information_schema.STATISTICS
         WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'dating_message'
           AND INDEX_NAME = 'idx_dating_message_time') AS колонок_в_индексе;
