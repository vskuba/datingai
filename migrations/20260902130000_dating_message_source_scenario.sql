-- Третий источник сообщения: сценарий у соседа (2026-09-02)
--
-- ЗАЧЕМ: колонка `source` завелась с двумя значениями — `socket` (поймал живой
-- вебсокет) и `panel` (привезли из журнала панели агентства). Появился третий путь:
-- отправка **сценарием у соседа**, живым браузером, там где у сайта нет своей ручки
-- отправки (`dating.md`, §5.9).
--
-- Записи такой отправки ложились со `socket` — умолчанием колонки, — и это враньё:
-- сокета в этот момент нет вовсе, у Ladadate он и не настроен. Разбираясь потом,
-- почему сообщение ушло без сокета, человек искал бы поломку там, где её нет.
--
-- ⚠ ЗНАЧЕНИЕ ДОБАВЛЯЕТСЯ, А НЕ ПЕРЕИМЕНОВЫВАЕТСЯ. Прежние 12 432 исходящих —
-- настоящий сокет, и трогать их нельзя: они и правда оттуда.
--
-- ЧТО ЭТО МЕНЯЕТ ДЛЯ АВТООТВЕТА: ничего. Он отбирает входящие (`direction = 'in'`)
-- и исключает `panel`; исходящие в отбор не попадают ни при каком источнике.
--
-- Идемпотентность: `MODIFY` с полным набором значений — повторный прогон приводит
-- колонку к тому же виду. Файл можно гонять сколько угодно раз.

-- ---------------------------------------------------------------- До
SELECT 'ДО' AS этап,
       (SELECT COLUMN_TYPE FROM information_schema.COLUMNS
         WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'dating_message'
           AND COLUMN_NAME = 'source') AS тип,
       (SELECT COUNT(*) FROM `dating_message` WHERE `source` = 'socket') AS из_сокета;

-- ------------------------------------------- Колонка
ALTER TABLE `dating_message`
    MODIFY COLUMN `source` ENUM('socket','panel','scenario') NOT NULL DEFAULT 'socket'
        COMMENT 'Откуда сообщение: живой сокет, журнал панели или сценарий у соседа';

-- ---------------------------------------------------------------- После
SELECT 'ПОСЛЕ' AS этап,
       (SELECT COLUMN_TYPE FROM information_schema.COLUMNS
         WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'dating_message'
           AND COLUMN_NAME = 'source') AS тип,
       (SELECT COUNT(*) FROM `dating_message` WHERE `source` = 'scenario') AS сценарием;
