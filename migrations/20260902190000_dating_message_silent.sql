-- Молчание агента — законный исход, и его надо помнить (2026-09-02)
--
-- ЗАЧЕМ: пустой ответ LLM — это решение агента «сейчас отвечать не надо», а не
-- сбой. Но помнить его было негде: ставилась только отметка попытки
-- (`answer_tried_at`), а `is_answered` оставался нулём. Отсюда два следствия, и
-- второе дороже первого:
--
--   * значок «нужен ответ» в диалоге мигал вечно — он считается как «последняя
--     реплика входящая И не отвечена»;
--   * ⚠ круг автоответа спрашивал агента снова каждые пять минут
--     (`DATING_ANSWER_RETRY_SEC`), тот снова молчал, и так без конца. Молчание
--     стоило денег на LLM в цикле.
--
-- ⚠ ПОЧЕМУ НЕ `is_answered = 1`: это поле означает «мы отправили ответ». Пометь им
-- молчание — и диалог в панели выглядел бы закрытым, хотя в нём нет ни слова от
-- нас. Врать в данных ради того, чтобы погас значок, — плохая цена.
--
-- ⚠ ПОЧЕМУ НЕ ПУСТАЯ РЕПЛИКА В ПЕРЕПИСКЕ: переписка — это то, что действительно
-- сказано. Выдуманная пустая строка попала бы в счётчик реплик, в выгрузку, в
-- сверку при импорте и в запрет повтора (он сравнивал бы новый текст с пустым), а
-- фильтровать её пришлось бы в пяти-шести местах чтения. Забытое место показало бы
-- человеку пустой пузырь.
--
-- ПОЧЕМУ DATETIME, А НЕ ФЛАГ: одна колонка отвечает на оба вопроса — было ли
-- молчание (`IS NOT NULL`) и когда. Флаг потребовал бы второй колонки со временем:
-- окно переписки показывает «агент решил не отвечать» с отметкой времени, иначе
-- человек не поймёт, почему тихо, и полезет искать поломку.
--
-- ⚠ НОВОЕ СООБЩЕНИЕ МОЛЧАНИЕ НЕ НАСЛЕДУЕТ: метка ставится на те строки, что были
-- на момент решения. Написал собеседник снова — у новой строки метка пуста, и
-- агента спросят опять. Так и надо: молчание относится к сказанному, а не к
-- собеседнику навсегда.
--
-- Идемпотентность: колонка добавляется только если её нет.

-- ---------------------------------------------------------------- До
SELECT 'ДО' AS этап,
       (SELECT COUNT(*) FROM information_schema.COLUMNS
         WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'dating_message'
           AND COLUMN_NAME = 'answer_silent_at') AS колонка_есть,
       (SELECT COUNT(*) FROM `dating_message`
         WHERE `direction` = 'in' AND `is_answered` = 0) AS ждут_ответа;

-- ------------------------------------------- Колонка
SET @sql = IF(
    (SELECT COUNT(*) FROM information_schema.COLUMNS
      WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'dating_message'
        AND COLUMN_NAME = 'answer_silent_at') = 0,
    'ALTER TABLE `dating_message`
        ADD COLUMN `answer_silent_at` DATETIME NULL DEFAULT NULL
            COMMENT ''Когда агент решил не отвечать; NULL — такого решения не было''
            AFTER `answer_tried_at`',
    'SELECT ''колонка answer_silent_at уже есть'' AS пропуск');
PREPARE stmt FROM @sql;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;

-- ---------------------------------------------------------------- После
SELECT 'ПОСЛЕ' AS этап,
       (SELECT COUNT(*) FROM information_schema.COLUMNS
         WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'dating_message'
           AND COLUMN_NAME = 'answer_silent_at') AS колонка_есть,
       (SELECT COUNT(*) FROM `dating_message`
         WHERE `answer_silent_at` IS NOT NULL) AS промолчали;
