-- Откуда у анкеты пароль: свой или общий агентский (2026-09-03)
--
-- ЗАЧЕМ: пароль брался «свой, если задан, иначе общий из настройки сайта». Правило
-- удобное, но у него нет состояния: по анкете не видно, под каким паролем она
-- работает. Человек стирает своё поле, чтобы «вернуться к общему», — и получает
-- анкету, которая молча ходит под чужим паролем, если общий кто-то поменял.
--
-- Теперь источник задаётся явно: `site` — общий агентский, `own` — свой.
--
-- ⚠ ПОЧЕМУ УМОЛЧАНИЕ `site`, А НЕ `own`. Живых анкет 64, и своего пароля нет ни у
-- одной: их заводили импортом, а работают они общим агентским. Умолчание `own`
-- означало бы, что после этой миграции все 64 «остались без пароля» — и вход, и
-- отправка, и списки перестали бы работать разом.
--
-- ⚠ АНКЕТАМ СО СВОИМ ПАРОЛЕМ СТАВИМ `own`. Иначе правило сменилось бы у них молча:
-- был свой пароль, стал общий — при том что в поле лежит своё значение, и по
-- странице это выглядело бы как «пароль есть, но работает не он».
--
-- ЧТО ЭТО МЕНЯЕТ В КОДЕ: правило «свой сильнее общего» уступает место явному
-- выбору. Прежнее поведение сохраняется у всех, у кого выбор совпал с тем, что
-- давало правило, — то есть у всех.
--
-- Идемпотентность: колонка добавляется, если её нет; заполнение — только там, где
-- значение ещё умолчательное и есть свой пароль.

-- ---------------------------------------------------------------- До
SELECT 'ДО' AS этап,
       (SELECT COUNT(*) FROM information_schema.COLUMNS
         WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'dating_profile'
           AND COLUMN_NAME = 'password_source') AS колонка_есть,
       (SELECT COUNT(*) FROM `dating_profile` WHERE `password` <> '') AS со_своим_паролем,
       (SELECT COUNT(*) FROM `dating_profile`) AS всего;

-- ------------------------------------------- Колонка
SET @sql = IF(
    (SELECT COUNT(*) FROM information_schema.COLUMNS
      WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'dating_profile'
        AND COLUMN_NAME = 'password_source') = 0,
    'ALTER TABLE `dating_profile`
        ADD COLUMN `password_source` ENUM(''site'', ''own'') NOT NULL DEFAULT ''site''
            COMMENT ''Откуда пароль: общий агентский из настроек сайта или свой''
            AFTER `password`',
    'SELECT ''колонка password_source уже есть'' AS пропуск');
PREPARE stmt FROM @sql;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;

-- ------------------------------------------- У кого свой пароль — тому `own`
--
-- ⚠ Только там, где значение ещё умолчательное: повторный прогон не должен
-- переписывать выбор, который человек к тому времени сделал руками. Отличить
-- «умолчание» от «выбрано site» нечем, поэтому условие по паролю: своё поле
-- заполнено, а источник ещё общий — значит выбор не делали.
UPDATE `dating_profile`
   SET `password_source` = 'own'
 WHERE `password` <> '' AND `password_source` = 'site';

-- ---------------------------------------------------------------- После
SELECT 'ПОСЛЕ' AS этап,
       (SELECT COUNT(*) FROM `dating_profile` WHERE `password_source` = 'own') AS свой,
       (SELECT COUNT(*) FROM `dating_profile` WHERE `password_source` = 'site') AS общий,
       (SELECT COUNT(*) FROM `dating_profile`
         WHERE `password_source` = 'own' AND `password` = '') AS свой_но_пусто;
