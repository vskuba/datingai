-- Расписание массовой рассылки — общее на сайт (2026-09-06)
--
-- ЗАЧЕМ: у вкладки «Письма рассылка» появилось расписание — когда с сайта уходит
-- массовая рассылка тем, кто сейчас в сети. Хранить его было негде.
--
-- ⚠ ПОЧЕМУ НА САЙТЕ, А НЕ НА АНКЕТЕ. Расписание анкеты (`dating_profile.schedule`)
-- отвечает на вопрос «когда ей быть в сети» — оно про присутствие конкретной
-- учётки. Здесь вопрос другой: «когда уходит рассылка», и ответ на него один на
-- весь сайт. Рассылку шлют всем, кто онлайн, и у каждой анкеты своего времени
-- рассылки нет — раскладывать общее решение по двадцати учёткам значило бы
-- двадцать мест, где его правят, и двадцать способов разойтись.
--
-- ⚠ ПОЧЕМУ СВОИ КОЛОНКИ, А НЕ КЛЮЧ В `settings`. Настройки сайта переписываются
-- **целиком** (`PUT /api/dating/site/{id}`): страница «Сайты» держит весь набор
-- перед глазами и шлёт то, что на ней. Ключа `mailing_schedule` она не знает — и
-- первое же сохранение любой соседней настройки стёрло бы расписание молча.
-- Своя колонка от этого свободна.
--
-- Заодно расписание — не «ключ → значение из набора», ради которых `settings` и
-- заведены, а структура: список смен, который правят ползунком.
--
-- ⚠ ПОЧЕМУ `mailing_schedule_on` УМОЛЧАНИЕМ 0. Тот же довод, что у расписания
-- анкеты: смены правят ползунком, и промежуточные состояния законны. Исполняй мы
-- «по факту наличия», рассылка уходила бы на каждое движение ручки. Плюс своё:
-- рассылка — действие наружу, и включать её у всех сайтов разом никто не просил.
--
-- ⚠ ЭТО НЕ ТО ЖЕ, ЧТО `dating_profile.mailing_on`. Тот флаг про анкету — участвует
-- ли она в рассылке вовсе (он же отбор вкладки). Здесь — про сайт: гнать ли
-- рассылку по расписанию. Выключенное расписание при включённых анкетах значит
-- «рассылку шлют руками», ровно как пустое расписание у анкеты.
--
-- Идемпотентность: колонки добавляются только если их нет.

-- ---------------------------------------------------------------- До
SELECT 'ДО' AS этап,
       (SELECT COUNT(*) FROM information_schema.COLUMNS
         WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'dating_site'
           AND COLUMN_NAME = 'mailing_schedule') AS колонка_есть,
       (SELECT COUNT(*) FROM `dating_site`) AS сайтов;

-- ------------------------------------------- Само расписание
SET @sql = IF(
    (SELECT COUNT(*) FROM information_schema.COLUMNS
      WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'dating_site'
        AND COLUMN_NAME = 'mailing_schedule') = 0,
    'ALTER TABLE `dating_site`
        ADD COLUMN `mailing_schedule` JSON NULL DEFAULT NULL
            COMMENT ''Смены массовой рассылки: когда с сайта уходят письма''
            AFTER `settings`',
    'SELECT ''колонка mailing_schedule уже есть'' AS пропуск');
PREPARE stmt FROM @sql;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;

-- ------------------------------------------- Выключатель
SET @sql = IF(
    (SELECT COUNT(*) FROM information_schema.COLUMNS
      WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'dating_site'
        AND COLUMN_NAME = 'mailing_schedule_on') = 0,
    'ALTER TABLE `dating_site`
        ADD COLUMN `mailing_schedule_on` TINYINT(1) NOT NULL DEFAULT 0
            COMMENT ''Гнать рассылку по расписанию, а не руками''
            AFTER `mailing_schedule`',
    'SELECT ''колонка mailing_schedule_on уже есть'' AS пропуск');
PREPARE stmt FROM @sql;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;

-- ---------------------------------------------------------------- После
--
-- ⚠ Умолчания не проставляем: пустое расписание рассылки — законное состояние
-- («шлют руками»), и разница с расписанием анкеты здесь намеренная. Там умолчание
-- ставится при заведении учётки, потому что анкету заводят чтобы она работала;
-- сайт же заводят у соседа, и рассылка с него может не идти вовсе.
SELECT 'ПОСЛЕ' AS этап,
       (SELECT COUNT(*) FROM `dating_site`
         WHERE `mailing_schedule` IS NOT NULL
           AND JSON_LENGTH(`mailing_schedule`) > 0) AS со_сменами,
       (SELECT COUNT(*) FROM `dating_site` WHERE `mailing_schedule_on` = 1) AS исполняется;
