-- Собеседники сайта: карточка человека, которому пишут (2026-09-06)
--
-- ЗАЧЕМ: рассылка уходит тем, кто **сейчас в сети**, и письмо должно спрашивать
-- про их интересы. Знать интересы неоткуда: списки «Все онлайн» дают имя,
-- возраст, страну и фото — и живут неделю в Redis, а в базу не ложатся вовсе.
--
-- `dating_contact` для этого не годится: там собеседницы **конкретной анкеты**, с
-- которыми уже есть переписка. Рассылка же пишет незнакомым — их в `dating_contact`
-- нет и быть не может, пока они не ответят.
--
-- ⚠ ПОЧЕМУ ПО САЙТУ, А НЕ ПО АНКЕТЕ. Человек на сайте один, и то, что о нём
-- известно, не зависит от того, какая анкета на него смотрит. Держи мы карточку у
-- анкеты — двадцать учёток собирали бы одни и те же сведения по двадцать раз, и
-- каждая своей ценой в браузере.
--
-- ⚠ ПОЧЕМУ ТАБЛИЦА НАПОЛНЯЕТСЯ ПО ТРЕБОВАНИЮ, А НЕ СПИСКОМ ЦЕЛИКОМ. Людей в сети
-- на живом сайте 168, всего на сайте — тысячи. Свалить их в базу разом значило бы
-- хранить тысячи карточек, из которых понадобятся единицы: письмо уходит тем, кого
-- выбрали. Поэтому строка заводится, когда о человеке **спросили** — открыли
-- карточку или дошла очередь рассылки.
--
-- Отсюда `about_state`: у строки два разных «пусто». «Не собирали» — значит
-- подробностей ещё не спрашивали; «собирали, не нашли» — значит сходили и там
-- ничего нет. Одним пустым полем их не различить, а решения они требуют разных:
-- в первом случае идти собирать, во втором — не ходить второй раз.
--
-- ⚠ ЧЕГО ЗДЕСЬ ПОКА НЕ БУДЕТ. `about` и `email` API сайта не отдаёт — проверено
-- живьём на LadaDate: и список, и попытки достать карточку одного человека дают
-- только `AccountId`, `Name`, `Age`, `Birthday`, `Country`, `City`, `ProfilePhoto`.
-- Подробности снимает браузер, и сценария «карточка мужчины» у соседа ещё нет.
-- Колонки заводятся сразу, потому что место для них известно; наполнит их сбор,
-- когда сценарий появится, а до тех пор их правят руками.

-- ---------------------------------------------------------------- До
SELECT 'ДО' AS этап,
       (SELECT COUNT(*) FROM information_schema.TABLES
         WHERE TABLE_SCHEMA = DATABASE()
           AND TABLE_NAME = 'dating_companion') AS таблица_есть;

-- ------------------------------------------- Карточка собеседника
CREATE TABLE IF NOT EXISTS `dating_companion` (
    `id` INT NOT NULL AUTO_INCREMENT,
    `site_id` INT NOT NULL COMMENT 'Сайт-закладка: человек принадлежит сайту, а не анкете',
    `uid` VARCHAR(32) NOT NULL COMMENT 'Номер человека на сайте (AccountId)',
    `name` VARCHAR(190) NOT NULL DEFAULT '',
    `photo` VARCHAR(500) NOT NULL DEFAULT '',
    `age` INT NOT NULL DEFAULT 0 COMMENT 'Ноль — «не знаем», а не нулевой возраст',
    `city` VARCHAR(190) NOT NULL DEFAULT '',
    `country` VARCHAR(190) NOT NULL DEFAULT '',
    `email` VARCHAR(190) NOT NULL DEFAULT ''
        COMMENT 'Почта. API сайта её не отдаёт — пока правится руками',
    `about` TEXT NULL DEFAULT NULL
        COMMENT 'Полезный текст из профиля: то, из чего письмо берёт интересы',
    -- ⚠ Два разных «пусто» у `about`, и различать их обязательно: «не собирали» —
    -- повод сходить, «собирали, не нашли» — повод не ходить второй раз.
    -- ⚠ Комментарий одной строкой: склейка соседних литералов ('a' 'b') — приём
    -- Python, а не SQL, и MySQL на ней падает с 1064. Поймано при накате.
    `about_state` ENUM('none', 'wait', 'done', 'empty', 'fail') NOT NULL DEFAULT 'none'
        COMMENT 'none — не собирали, wait — собираем, done — есть текст, empty — там пусто, fail — не вышло',
    `about_error` VARCHAR(500) NOT NULL DEFAULT ''
        COMMENT 'Почему не вышло: причина словами, для страницы',
    `about_at` DATETIME NULL DEFAULT NULL COMMENT 'Когда последний раз ходили за текстом',
    `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `updated_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (`id`),
    -- Человек на сайте один: повторный заход обновляет строку, а не заводит вторую.
    UNIQUE KEY `uq_dating_companion` (`site_id`, `uid`),
    -- Отбор страницы: сайт, потом свежесть. Список читают сверху вниз, свежие
    -- сверху — это те, о ком спрашивали последними.
    INDEX `idx_dating_companion_site` (`site_id`, `updated_at`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ---------------------------------------------------------------- После
--
-- ⚠ Пусто, и это правильно: таблица наполняется по требованию. Строки в ней
-- появятся, когда о ком-то спросят, — заливать сюда списки при накате значило бы
-- ровно то, чего эта таблица избегает.
SELECT 'ПОСЛЕ' AS этап,
       (SELECT COUNT(*) FROM `dating_companion`) AS карточек;
