-- Две переменные, с которых начинают: `girl_name` и `companion_name` (2026-09-07)
--
-- ЗАЧЕМ: реестр переменных заводит человек, и до сих пор он был пуст. Пустой
-- реестр означает, что письмо не может сослаться ни на что: любая переменная в
-- тексте — «неизвестная», и шаблон не сохраняется. То есть первый же шаг
-- упирается в отказ, а что заводить — приходится придумывать самому.
--
-- Эти две — минимум, с которого письмо становится письмом, а не листовкой:
-- обращение к получателю по имени и подпись отправительницы.
--
-- ⚠ ПОЧЕМУ ТОЛЬКО САЙТАМ С АНКЕТАМИ. Реестр по сайту, и сайтов у соседа десятки;
-- заводить переменные тем, с кем не работают, значило бы засорять их реестр
-- строками, которые никто не просил. Анкеты — признак работы: где их нет, там и
-- писем нет.
--
-- Прежняя миграция (`20260906210000_dating_mail_var_source`) заводила эти же две
-- по другому признаку — «где уже есть шаблоны или переменные». На момент наката
-- таких сайтов не было ни одного, и она не завела ничего: признак оказался
-- замкнут сам на себя (переменные заводятся там, где уже есть переменные).
-- Здесь признак внешний.
--
-- ⚠ РАЗНЫЙ `source`, И ЭТО ГЛАВНОЕ. `girl_name` — про анкету: значение одно на
-- всех адресатов, лежит у неё и заполняется руками или агентом. `companion_name`
-- — про адресата: у анкеты его нет и быть не может, оно подставляется при
-- отправке из карточки собеседника. Заведи мы обе одинаково — вторая висела бы у
-- каждой анкеты пустой строкой, которую нечем заполнить.
--
-- Умолчаний не ставим: пустое умолчание значит «письмо не уйдёт, пока не
-- заполнят», и это правильный исход. Умолчание вида «дорогой друг» ушло бы живым
-- людям вместо имени.
--
-- Идемпотентность: вставка по условию отсутствия.

-- ---------------------------------------------------------------- До
SELECT 'ДО' AS этап,
       (SELECT COUNT(DISTINCT site_id) FROM `dating_profile`) AS сайтов_с_анкетами,
       (SELECT COUNT(*) FROM `dating_mail_var`) AS переменных;

-- ------------------------------------------- Имя девушки: про анкету
INSERT INTO `dating_mail_var` (`site_id`, `name`, `source`, `title`, `default_value`)
SELECT s.site_id, 'girl_name', 'profile', 'Имя девушки, от которой письмо', ''
  FROM (SELECT DISTINCT site_id FROM `dating_profile`) s
 WHERE NOT EXISTS (SELECT 1 FROM `dating_mail_var` v
                    WHERE v.site_id = s.site_id AND v.name = 'girl_name');

-- ------------------------------------------- Имя собеседника: про адресата
INSERT INTO `dating_mail_var` (`site_id`, `name`, `source`, `title`, `default_value`)
SELECT s.site_id, 'companion_name', 'companion', 'Имя получателя письма', ''
  FROM (SELECT DISTINCT site_id FROM `dating_profile`) s
 WHERE NOT EXISTS (SELECT 1 FROM `dating_mail_var` v
                    WHERE v.site_id = s.site_id AND v.name = 'companion_name');

-- ---------------------------------------------------------------- После
SELECT 'ПОСЛЕ' AS этап,
       (SELECT COUNT(*) FROM `dating_mail_var` WHERE `name` = 'girl_name') AS girl_name,
       (SELECT COUNT(*) FROM `dating_mail_var` WHERE `name` = 'companion_name') AS companion_name;
