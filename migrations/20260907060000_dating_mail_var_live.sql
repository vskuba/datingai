-- Переменные, которые вычисляются при отправке (2026-09-07)
--
-- ЗАЧЕМ: письмо должно спрашивать про интересы получателя, но шаблон пишется
-- **до** того, как известно, кому он уйдёт. Выходило одно из двух: либо шаблон
-- под конкретного человека (годен ровно ему), либо общее письмо без вопроса —
-- а письмо без вопроса не получает ответа.
--
-- Развязка: вопрос становится переменной. Шаблон пишется общим и ссылается на
-- `[[question_to_companion]]`, а сам вопрос сочиняется агентом в момент
-- рассылки — по профилю того, кому письмо уходит.
--
-- ⚠ ТРЕТИЙ ИСТОЧНИК, И ОН ОТЛИЧАЕТСЯ ОТ ОБОИХ ПРЕЖНИХ.
--
--   `profile`   — лежит у анкеты, заполняется заранее (руками или агентом);
--   `companion` — лежит в карточке получателя, **читается** при отправке;
--   `live`      — не лежит нигде: **вычисляется** при отправке.
--
-- Разница между `companion` и `live` не формальная. Первое — поле, которое можно
-- посмотреть глазами и поправить; второе существует только в момент отправки и у
-- каждой пары своё. Свалив их в один источник, мы получили бы в карточке
-- получателя поле «вопрос», которое нечем заполнить и незачем хранить.
--
-- ⚠ ПОЧЕМУ НЕ ОТДЕЛЬНАЯ СУЩНОСТЬ. Для письма все три одинаковы: пишутся
-- `[[имя]]`, проверяются по реестру и одинаково ломают рассылку, когда их нечем
-- подставить. Разный только способ добыть значение — это поле, а не вторая
-- таблица со своей страницей и своими ручками.
--
-- ⚠ ЧЕГО ЗДЕСЬ ПОКА НЕТ. Круга рассылки не существует, и подставлять `live`
-- некому. Заведение переменной — это договор о том, как оно будет устроено:
-- шаблоны уже можно писать с вопросом, и агент письма уже знает, что такую
-- переменную надо оставить как есть, а не сочинять текст на её месте.
--
-- Идемпотентность: `MODIFY` повторяем без вреда, вставка — по условию.

-- ---------------------------------------------------------------- До
SELECT 'ДО' AS этап,
       (SELECT COLUMN_TYPE FROM information_schema.COLUMNS
         WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'dating_mail_var'
           AND COLUMN_NAME = 'source') AS источники,
       (SELECT COUNT(*) FROM `dating_mail_var`
         WHERE `name` = 'question_to_companion') AS вопрос_есть;

-- ------------------------------------------- Третий источник
--
-- ⚠ `MODIFY` без условия: он идемпотентен сам по себе (повторный накат приводит
-- колонку к тому же виду), а проверять текст `COLUMN_TYPE` строкой значило бы
-- завязаться на то, как MySQL его форматирует.
ALTER TABLE `dating_mail_var`
    MODIFY COLUMN `source` ENUM('profile', 'companion', 'live') NOT NULL DEFAULT 'profile'
        COMMENT 'Откуда значение: profile — у анкеты, companion — из карточки получателя, live — вычисляется при отправке';

-- ------------------------------------------- Сам вопрос
--
-- Заводим сайтам, у которых есть анкеты, — тем же признаком, что и базовые две
-- переменные (`20260907030000`): анкеты означают, что с сайтом работают.
INSERT INTO `dating_mail_var` (`site_id`, `name`, `source`, `title`, `default_value`)
SELECT s.site_id, 'question_to_companion', 'live',
       'Вопрос получателю про его интересы — сочиняется при отправке', ''
  FROM (SELECT DISTINCT site_id FROM `dating_profile`) s
 WHERE NOT EXISTS (SELECT 1 FROM `dating_mail_var` v
                    WHERE v.site_id = s.site_id AND v.name = 'question_to_companion');

-- ------------------------------------------- Уборка осиротевших значений
--
-- ⚠ Если у `live`-переменной успело завестись значение у анкеты (до этой
-- миграции все были `profile` или `companion`), его надо убрать: оно означало бы
-- «вопрос, один на всех получателей» — то есть ровно то, от чего эта переменная и
-- уводит.
DELETE v FROM `dating_profile_var` v
  JOIN `dating_profile` p ON p.id = v.profile_id
  JOIN `dating_mail_var` m ON m.site_id = p.site_id AND m.name = v.name
 WHERE m.source = 'live';

-- ---------------------------------------------------------------- После
SELECT 'ПОСЛЕ' AS этап,
       (SELECT COUNT(*) FROM `dating_mail_var` WHERE `source` = 'profile') AS у_анкеты,
       (SELECT COUNT(*) FROM `dating_mail_var` WHERE `source` = 'companion') AS у_получателя,
       (SELECT COUNT(*) FROM `dating_mail_var` WHERE `source` = 'live') AS на_лету;
