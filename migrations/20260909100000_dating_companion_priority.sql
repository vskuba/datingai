-- Приоритет собеседника в рассылке (2026-09-09)
--
-- ЗАЧЕМ. Адресаты для писем берутся из ленты «Все онлайн», и порядок в ней — тот,
-- в каком их отдал сайт. Для панели это случайность: сегодня человек первый, завтра
-- сотый, а пул набирается до потолка и обрывается на полпути по списку.
--
-- Между тем не все адресаты равны. Про одних известно многое (описание снято,
-- переписка была), про других — ничего; с одними работают прямо сейчас, другие
-- просто оказались онлайн. Отметка «приоритет» и есть способ сказать: этим пишем
-- в первую очередь.
--
-- ⚠ ЭТО ПОРЯДОК, А НЕ ОТБОР. Отмеченные идут первыми, остальные — следом, и вторые
-- никуда не деваются. Сделай мы из этого фильтр, включённая отметка у одного
-- человека молча выключила бы рассылку всем прочим — а человек отмечал одного, а не
-- отменял остальных.
--
-- ⚠ ВЫКЛЮЧЕН ПО УМОЛЧАНИЮ. Отметка у всех — это отсутствие отметки: порядок снова
-- становится тем, каким его отдал сайт, только теперь с видимостью решения.

ALTER TABLE `dating_companion`
    ADD COLUMN `priority` TINYINT(1) NOT NULL DEFAULT 0
        COMMENT 'Писать этому человеку в первую очередь при наборе пула'
        AFTER `email`;

-- Индекс по паре: отбор идёт всегда внутри сайта, и одного `priority` мало —
-- отмеченных со всех сайтов сразу не спрашивает никто.
ALTER TABLE `dating_companion`
    ADD INDEX `idx_dating_companion_priority` (`site_id`, `priority`);
