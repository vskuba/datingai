-- Расписание для написания шаблонов писем (2026-09-09)
--
-- ЗАЧЕМ. Шаблоны пишет агент (`dating_mail_write`), а зовут его руками, кнопкой.
-- Кнопку нажимают, когда вспомнят, — и через неделю у сайта те же пять текстов,
-- которыми он писал в понедельник. Письма при этом уходят сотням людей, и один и
-- тот же текст на всех читается как рассылка робота, чем он и является.
--
-- Расписание отвечает на это: сколько-то новых заготовок в сутки, сами собой, в те
-- часы, когда за ними присмотрят.
--
-- ⚠ ЭТО ТРЕТЬЕ РАСПИСАНИЕ, И ОНО ПРО ДРУГОЕ. У анкеты (`dating_profile.schedule`)
-- вопрос «когда ей быть в сети», у рассылки (`mailing_schedule`) — «когда готовим
-- письма», здесь — «когда пишем новые шаблоны». Смены и вид общие
-- (`dating_schedule.js`), вопросы разные, и хранить их одной колонкой значило бы
-- связать три независимых решения в одно.
--
-- ⚠ ВЫКЛЮЧЕНО ПО УМОЛЧАНИЮ, отдельным флагом. Причина та же, что у рассылки: смены
-- правят ползунком, промежуточные состояния законны, и «исполнять по факту наличия»
-- означало бы запускать агента на каждое движение ручки.

ALTER TABLE `dating_site`
    ADD COLUMN `template_schedule` JSON NULL
        COMMENT 'Смены суток, в которые агент пишет новые шаблоны'
        AFTER `mailing_send_on`,
    ADD COLUMN `template_schedule_on` TINYINT(1) NOT NULL DEFAULT 0
        COMMENT 'Исполнять ли расписание шаблонов'
        AFTER `template_schedule`;
