-- Выключатель ответов на входящие письма (2026-09-09)
--
-- Пул ответов копится сам, а уходят ответы только когда это разрешено. Флаг и есть
-- разрешение.
--
-- ⚠ ВЫКЛЮЧЕН ПО УМОЛЧАНИЮ, и причина та же, что у `mailing_send_on`: ответ уходит
-- живому человеку. Накат миграции, включивший ответы, был бы худшим из сюрпризов —
-- панель заговорила бы от имени сорока девушек, ни у кого не спросив.
--
-- ⚠ ФЛАГ У САЙТА, А НЕ У АНКЕТЫ. Пул ответов один на сайт: письма приходят разным
-- девушкам, а решение «отвечаем ли вообще» человек принимает один раз. Разложи мы
-- его по анкетам — включать пришлось бы сорок раз, а забыть одну достаточно, чтобы
-- потом гадать, почему её собеседники молчат.
--
-- Расписание при этом остаётся у анкеты (`dating_profile.schedule`): «когда она в
-- сети» — вопрос про учётку, и второго источника у него быть не должно.

ALTER TABLE `dating_site`
    ADD COLUMN `reply_send_on` TINYINT(1) NOT NULL DEFAULT 0
        COMMENT 'Отвечать ли на входящие письма: ответы уходят живым людям'
        AFTER `template_schedule_on`;
