-- Генерация ответов на входящие письма (2026-09-09)
--
-- ЗАЧЕМ ОТДЕЛЬНЫЙ ФЛАГ. На вкладке «Ответы» стоит расписание анкеты и галочка рядом
-- с ним. Сперва галочка писала в `schedule_on` — тот самый выключатель, что на
-- «Анкетах»: он включает **вход по сменам**, то есть воркер начинает логинить
-- девушку на сайт.
--
-- Это не то, чего от неё ждут в этом месте. Человек, включающий галочку у пула
-- ответов, разрешает **готовить ответы**, а не отправлять анкету в сеть; вход —
-- действие наружу, самое заметное из всех, и делать его побочным следствием чужого
-- решения нельзя. Отсюда своя колонка.
--
-- ⚠ ПАРА К `mailing_on`, И УСТРОЕНА ТАК ЖЕ. У анкеты уже есть «участвует ли она в
-- рассылке»; это — «готовим ли ответы от её имени». Оба про то, что панель делает
-- от лица девушки, и оба выключены по умолчанию.
--
-- ⚠ РАСПИСАНИЕ ПРИ ЭТОМ ОБЩЕЕ. `schedule` остаётся одно на анкету: «когда она в
-- сети» — вопрос про учётку, и второго источника у него быть не должно. Флаги
-- разные, часы одни.

ALTER TABLE `dating_profile`
    ADD COLUMN `reply_on` TINYINT(1) NOT NULL DEFAULT 0
        COMMENT 'Готовить ли ответы на входящие письма этой анкеты'
        AFTER `mailing_on`;
