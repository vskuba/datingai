-- Генерация ответов: решение переезжает с анкеты на сайт (2026-09-10)
--
-- ЧТО БЫЛО. Флаг «готовим ли ответы» жил у анкеты (`dating_profile.reply_on`), и
-- круг брал письма только тех девушек, у кого он включён. Выглядело это разумно:
-- решение про конкретную анкету.
--
-- ПОЧЕМУ МЕНЯЕМ. На странице выключатель стоит в полосе подвкладок «Писем», рядом
-- с «отправкой ответов» — и та **уже про сайт** (`reply_send_on`). Два соседних
-- флажка, живущих по разным правилам, объяснить нельзя: один заперт, пока не
-- выбрана анкета, второй нажимается всегда. Человек читает это как поломку.
--
-- Вторая причина — цена включения. Пул ответов один на сайт; разложенный по
-- анкетам флаг означает включить его сорок раз, а забытая анкета молчит, и
-- причину ищут в поломке. Ровно тот довод, по которому `reply_send_on` с самого
-- начала завели у сайта.
--
-- ⚠ ЧТО ИЗМЕНИТСЯ В ПОВЕДЕНИИ, и это осознанный размен. Сейчас генерация идёт
-- только у тех анкет, кому флаг проставили руками (на живом сайте — у одной из
-- тринадцати). После переезда она пойдёт **у всех включённых анкет сайта**, как
-- только выключатель поднимут. Отбор «эта анкета отвечает, а эта нет» пропадает;
-- если он понадобится снова, вернуть его следует **вторым** уровнем — флаг сайта
-- плюс флаг анкеты, как у рассылки (расписание сайта + «Письма рассылка» у
-- анкеты), а не заменой одного другим.
--
-- ⚠ СТОЛБЕЦ АНКЕТЫ НЕ УДАЛЯЕМ. `dating_profile.reply_on` остаётся с прежними
-- значениями: удалить его — потерять сведения о том, кому генерацию уже
-- включали, а восстановить их будет неоткуда, если размен окажется неудачным.
-- Читать его после этой миграции никто не должен.

ALTER TABLE `dating_site`
    ADD COLUMN `reply_make_on` TINYINT(1) NOT NULL DEFAULT 0
        COMMENT 'Готовим ли ответы на входящие письма этого сайта'
        AFTER `reply_send_on`;

-- ⚠ Переносим прежнее решение, а не начинаем с нуля. Сайт, где генерацию хоть
-- одной анкете уже включали, работал — и выключить его молча этой миграцией
-- значило бы остановить работу без единого следа в панели.
UPDATE `dating_site` s
   SET s.`reply_make_on` = 1
 WHERE EXISTS (SELECT 1 FROM (SELECT DISTINCT `site_id` FROM `dating_profile`
                               WHERE `reply_on` = 1) AS p
                WHERE p.`site_id` = s.`site_id`);

SELECT 'ПОСЛЕ' AS этап,
       (SELECT COUNT(*) FROM `dating_site` WHERE `reply_make_on` = 1) AS сайтов_с_генерацией,
       (SELECT COUNT(*) FROM `dating_profile` WHERE `reply_on` = 1) AS анкет_с_прежним_флагом;
