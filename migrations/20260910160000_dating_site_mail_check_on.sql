-- Забор входящих писем: выключатель у сайта (2026-09-10)
--
-- ЧТО БЫЛО. Письма с сайта забирала **только кнопка** «Забрать письма» на
-- подвкладке «Входящие», и забирала их у **одной** анкеты — той, что выбрана
-- слева. Автоматики не было никакой: `dating_mail_in_fetch` звала одна ручка
-- `POST /api/dating/mail-in/fetch`, и та — по нажатию.
--
-- ПОЧЕМУ ЭТО ХУЖЕ, ЧЕМ КАЖЕТСЯ. Забор стоит первым в цепочке, и вся остальная
-- автоматика опиралась на него: круг ответов пишет ответы на то, что лежит в
-- `dating_mail_in`, круг отправки шлёт написанное. Оба научились работать сами —
-- и оба молча простаивали, если человек не нажал кнопку. Панель при этом
-- выглядела работающей: выключатели подняты, кругов двенадцать, ошибок нет.
-- Просто писем не было, потому что за ними никто не сходил.
--
-- ⚠ ПО УМОЛЧАНИЮ ВКЛЮЧЕНО, и это расходится с остальными выключателями почты
-- (`mailing_send_on`, `reply_send_on`, `reply_make_on` — все по нулям). Разница
-- не в смелости, а в том, куда направлено действие: те трое **пишут наружу**, а
-- этот только читает. Забор ничего не отправляет, ничего не показывает
-- собеседнику и не делает анкету онлайн — он приносит в панель то, что человеку
-- и так адресовано. Выключенный по умолчанию, он означал бы панель, которая по
-- умолчанию не показывает почту.
--
-- Признак пересмотреть: если у сайта появится плата за запрос или счётчик
-- обращений, «по умолчанию читаем всем» перестанет быть бесплатным.

ALTER TABLE `dating_site`
    ADD COLUMN `mail_check_on` TINYINT(1) NOT NULL DEFAULT 1
        COMMENT 'Забираем ли входящие письма этого сайта кругом'
        AFTER `reply_make_on`;

SELECT 'ПОСЛЕ' AS этап,
       (SELECT COUNT(*) FROM `dating_site` WHERE `mail_check_on` = 1) AS сайтов_с_забором,
       (SELECT COUNT(*) FROM `dating_site`) AS всего_сайтов;
