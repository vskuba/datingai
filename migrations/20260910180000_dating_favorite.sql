-- Избранные: кого мы добавили девушке в звёздочки (2026-09-10)
--
-- ЗАЧЕМ. Ответивший на письмо мужчина должен оказаться у девушки в избранных: на
-- сайте это звёздочка на его анкете. Добавляет её сценарий у соседа
-- («анкета мужчины: в избранные») — ручки у сайта нет, только кнопка на странице,
-- и каждое добавление стоит ~40 секунд живого браузера.
--
-- Отсюда таблица: без неё круг ходил бы по одним и тем же людям каждые пять минут,
-- платя сорок секунд за то, что уже сделано.
--
-- ⚠ ПОЧЕМУ ПО АНКЕТЕ, А НЕ ПО САЙТУ — в отличие от `dating_companion`. Избранные
-- **у каждой девушки свои**: один и тот же мужчина у Дианы в звёздочках, а у Елены
-- нет, и это не расхождение сведений, а два разных факта. Держи мы признак в
-- карточке собеседника (одна на сайт), добавление под одной анкетой означало бы
-- «добавлено» для всех тринадцати.
--
-- ⚠ ПОЧЕМУ ВООБЩЕ ХРАНИМ, ЕСЛИ ЕСТЬ СПИСОК САЙТА. Список избранных сайт отдаёт и
-- дёшево (`GET /users/my-favorites`, 70 мс) — и он остаётся источником истины: круг
-- сверяется с ним, а не с этой таблицей. Таблица отвечает на другой вопрос —
-- **что мы уже пробовали и чем это кончилось**. Список говорит «его там нет», но не
-- говорит, ходили ли мы за ним трижды и падали ли на входе.
--
-- ⚠ ДВА РАЗНЫХ «ОН ТАМ ЕСТЬ». `done` — мы нажали звёздочку; `already` — он был там
-- до нас (добавил человек руками или анкета пришла с избранными). Для круга разницы
-- нет — оба означают «больше не ходить», — а для человека есть: по `done` видно, что
-- сделала панель, а по `already` — что было и так.
--
-- ⚠ ОТКАЗ ПОВТОРЯЕМ, но не бесконечно: `tries`. Здесь это уместнее, чем у сбора
-- описаний (`dating_companion.about_state`, где `fail` не повторяется вовсе), потому
-- что причина обычно временная — занятая вкладка у соседа (409), оборванная сеть,
-- медленный сайт, — а цель никуда не девается: он всё ещё должен оказаться в
-- избранных. Потолок держит эту разницу в рамках: три захода, дальше строка молчит и
-- ждёт человека.

-- ---------------------------------------------------------------- До
SELECT 'ДО' AS этап,
       (SELECT COUNT(*) FROM information_schema.TABLES
         WHERE TABLE_SCHEMA = DATABASE()
           AND TABLE_NAME = 'dating_favorite') AS таблица_есть;

-- ------------------------------------------------- Избранные анкеты
CREATE TABLE IF NOT EXISTS `dating_favorite` (
    `id` INT NOT NULL AUTO_INCREMENT,
    `site_id` INT NOT NULL COMMENT 'Сайт-закладка: по нему отбирает круг',
    `profile_id` INT NOT NULL COMMENT 'Анкета девушки: избранные у каждой свои',
    `uid` VARCHAR(32) NOT NULL COMMENT 'Номер мужчины на сайте (AccountId)',
    `state` ENUM('done', 'already', 'fail') NOT NULL DEFAULT 'fail'
        COMMENT 'done — мы нажали звёздочку, already — был там до нас, fail — не вышло',
    `error` VARCHAR(500) NOT NULL DEFAULT ''
        COMMENT 'Почему не вышло: причина словами, для журнала анкеты',
    `tries` INT NOT NULL DEFAULT 0
        COMMENT 'Сколько раз ходили. Потолок держит круг: отказ повторяем, но не вечно',
    `reason` VARCHAR(32) NOT NULL DEFAULT 'mail_in'
        COMMENT 'Почему добавляли: mail_in — пришло письмо, hand — нажал человек',
    `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `updated_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (`id`),
    -- Пара «эта девушка — этот мужчина» одна: повторный заход правит строку, а не
    -- заводит вторую. На этом же ключе держится отбор «кого ещё не пробовали».
    UNIQUE KEY `uq_dating_favorite` (`profile_id`, `uid`),
    -- Отбор круга: сайт, потом состояние. Ему нужны неудачи с недобранным
    -- потолком — по всему сайту разом, а не по анкете.
    INDEX `idx_dating_favorite_site` (`site_id`, `state`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ---------------------------------------------------------------- После
--
-- ⚠ Пусто, и это правильно: строку заводит круг, когда сходит на сайт. Заливать
-- сюда при накате нечего — что у кого в избранных, знает сайт, а не мы.
SELECT 'ПОСЛЕ' AS этап,
       (SELECT COUNT(*) FROM `dating_favorite`) AS строк;
