-- Автоответ в чате: решение переезжает с анкеты на сайт (2026-09-11)
--
-- ЧТО БЫЛО. Флаг «отвечает ли за неё агент» жил у анкеты
-- (`dating_profile.auto_answer`), галочкой «Чат автоответ» в её настройках. Круг
-- автоответа брал только тех девушек, у кого он поднят.
--
-- ПОЧЕМУ МЕНЯЕМ. Это третий такой переезд, и довод у всех троих один: **решение
-- про занятие, а не про учётку**. Разложенный по анкетам флаг означает включить
-- его сорок раз, забытая анкета молчит, и причину ищут в поломке. Так уже было с
-- генерацией ответов на письма (`reply_on` → `reply_make_on`) и с отправкой.
--
-- Вторая причина — место. Выключатель стоял в карточке анкеты на «Анкетах», а
-- смотрят на чат в «Профилях», на подвкладке «Диалоги». Чтобы включить автоответ,
-- человек уходил на другую страницу, находил там анкету и щёлкал галочку, не
-- видя ни одного диалога.
--
-- ⚠ ЧТО ИЗМЕНИТСЯ В ПОВЕДЕНИИ, и это осознанный размен. Автоответ пойдёт **у всех
-- включённых анкет сайта**, как только выключатель поднимут; отбор «эта отвечает,
-- а эта нет» пропадает. Понадобится снова — возвращать его надо **вторым**
-- уровнем (флаг сайта плюс флаг анкеты), как у рассылки, а не заменой одного
-- другим.
--
-- ⚠ СТОЛБЕЦ АНКЕТЫ НЕ УДАЛЯЕМ. `dating_profile.auto_answer` остаётся с прежними
-- значениями: удалить его — потерять сведения о том, кому автоответ уже включали,
-- а восстановить их будет неоткуда, если размен окажется неудачным. Читать его
-- после этой миграции никто не должен.
--
-- ⚠ `auto_answer_only` ТОЖЕ ОСТАЁТСЯ И ТОЖЕ НЕ ЧИТАЕТСЯ. Он отвечал на другой
-- вопрос — «только автоответ, без ручной отправки», — и переносить его вместе с
-- первым значило бы решить за человека то, чего он не просил.
--
-- Идемпотентность: колонка заводится по условию отсутствия.

-- ---------------------------------------------------------------- До
SELECT 'ДО' AS этап,
       (SELECT COUNT(*) FROM information_schema.COLUMNS
         WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'dating_site'
           AND COLUMN_NAME = 'chat_answer_on') AS колонка_есть,
       (SELECT COUNT(*) FROM `dating_profile` WHERE `auto_answer` = 1) AS анкет_с_флагом;

-- ------------------------------------------- Выключатель сайта
SET @sql = IF(
    (SELECT COUNT(*) FROM information_schema.COLUMNS
      WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'dating_site'
        AND COLUMN_NAME = 'chat_answer_on') = 0,
    'ALTER TABLE `dating_site`
        ADD COLUMN `chat_answer_on` TINYINT(1) NOT NULL DEFAULT 0
            COMMENT ''Отвечает ли агент в чате за анкеты этого сайта''
            AFTER `favorite_mail_send_on`',
    'SELECT ''колонка chat_answer_on уже есть'' AS пропуск');
PREPARE s FROM @sql; EXECUTE s; DEALLOCATE PREPARE s;

-- ------------------------------------------- Переносим прежнее решение
--
-- ⚠ Переносим, а не начинаем с нуля. Сайт, где автоответ хоть одной анкете уже
-- включали, **работал** — и выключить его молча этой миграцией значило бы
-- остановить работу без единого следа в панели: девушки просто перестали бы
-- отвечать, а причину никто бы не связал с накатом.
UPDATE `dating_site` s
   SET s.`chat_answer_on` = 1
 WHERE EXISTS (SELECT 1 FROM (SELECT DISTINCT `site_id` FROM `dating_profile`
                               WHERE `auto_answer` = 1) AS p
                WHERE p.`site_id` = s.`site_id`);

-- ---------------------------------------------------------------- После
SELECT 'ПОСЛЕ' AS этап,
       (SELECT COUNT(*) FROM `dating_site` WHERE `chat_answer_on` = 1) AS сайтов_с_автоответом,
       (SELECT COUNT(*) FROM `dating_profile` WHERE `auto_answer` = 1) AS анкет_с_прежним_флагом;
