-- Где переменная участвует: занятия, из которых её можно выключить.
--
-- Появилось из живого случая. Шаблон «Curious and warm» требовал
-- `companion_last_name`, а тот по своему определению пуст у любого, чьё имя в
-- одно слово — на проде это 44 собеседника из 99. Письмо с незаполненной
-- переменной не уходит, и рассылка молча пропускала пары: пул стоял пустым при
-- включённом расписании, живой девушке и полутора сотнях людей в сети.
--
-- Починить это правкой шаблона можно один раз; писать шаблоны продолжает агент
-- (круг `template_per_day`), и он получает **весь реестр как обязательный** —
-- то есть вернул бы ту же переменную в следующий же черновик.
--
-- ⚠ **JSON, а не колонка на занятие.** Занятие сейчас одно, но список их —
-- код (`DATING_MAIL_VAR_USES`), а не схема: второе и третье добавятся правкой
-- реестра, без миграции на каждое. Тот же довод, что у `dating_site.settings`.
--
-- ⚠ **Хранится только снятое.** Пусто — участвует везде, и это сохраняет
-- сегодняшнее поведение для всех существующих строк: занятие, добавленное
-- завтра, включено у всех, кто о нём не знал.
ALTER TABLE dating_mail_var
    ADD COLUMN uses JSON NULL COMMENT 'Снятые занятия: {"mail_write": false}. Пусто — участвует везде'
    AFTER default_value;
