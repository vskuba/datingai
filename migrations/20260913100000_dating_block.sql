-- ответ на инвайт от Nadezhda748852 к DDominic909801:
--
--     200 {"IsSuccess":false,"Reason":"ERROR_MESSAGE_USER_DENY",
--          "Message":"User ignore messages from you"}
--
-- Собеседник закрылся от этой анкеты. Для нас это был обычный отказ: реплика
-- оставалась в пуле с причиной, а круг набора через сутки готовил ему следующую —
-- каждая ценой вызова LLM. Столько же стоила бы и рассылка: канал другой, а
-- закрылся он от девушки, а не от способа доставки.
--
-- ЧТО ЗАВОДИМ. Пару «анкета — собеседник» с причиной и датой. Пара, а не человек:
-- он закрылся от **этой** девушки, и остальные для него — незнакомки, которых он
-- не отвергал. Ровно так же устроено «с кем уже говорили» у инвайтов.
--
-- ⚠ ПОЧЕМУ ОТДЕЛЬНАЯ ТАБЛИЦА, а не флаг у `dating_companion`. Карточка собеседника
-- заводится **по требованию** и живёт на сайт, а не на пару: флаг в ней означал бы
-- «он закрылся от всех наших девушек», чего сайт не говорил. Плюс карточки может
-- не быть вовсе — а запрет нужен и тогда.
--
-- ⚠ ЗАПИСЬ НЕ ИСТЕКАЕТ. Сайт не сообщает, когда человек передумал, и срок жизни
-- был бы выдумкой: «через месяц попробуем снова» — это решение написать тому, кто
-- просил не писать. Снять запись может человек, руками.
--
-- Идемпотентность: таблица заводится по условию отсутствия.

-- ---------------------------------------------------------------- До
SELECT 'ДО' AS этап,
       (SELECT COUNT(*) FROM information_schema.TABLES
         WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'dating_block') AS таблица_есть;

-- ------------------------------------------- Сам чёрный список
CREATE TABLE IF NOT EXISTS `dating_block` (
    `id` INT NOT NULL AUTO_INCREMENT,
    `site_id` INT NOT NULL COMMENT 'Сайт-закладка: по нему отбирают круги и страница',
    `profile_id` INT NOT NULL COMMENT 'Девушка, от которой закрылись',
    `uid` VARCHAR(32) NOT NULL COMMENT 'Номер собеседника на сайте',
    `name` VARCHAR(190) NOT NULL DEFAULT ''
        COMMENT 'Как его зовут. ⚠ Хранится: карточки собеседника может не быть, а список читает человек',
    `reason` VARCHAR(500) NOT NULL DEFAULT ''
        COMMENT 'Что ответил сайт — целиком, вместе с его кодом отказа',
    `source` ENUM('chat', 'mail', 'hand') NOT NULL DEFAULT 'chat'
        COMMENT 'Откуда узнали: отказ чата, отказ почты или рука человека',
    `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (`id`),
    -- ⚠ Пара уникальна: второй отказ тому же человеку от той же девушки — не
    -- вторая запись, а та же самая. Пишем `INSERT IGNORE`, и ключ решает это за
    -- нас — без чтения перед записью, то есть без гонки двух кругов.
    UNIQUE KEY `uq_dating_block` (`profile_id`, `uid`),
    -- Отбор кругов: «кого не трогать на этом сайте» спрашивается каждым набором
    -- пула, и спрашивается по сайту целиком.
    INDEX `idx_dating_block_site` (`site_id`, `created_at`),
    -- Удалили анкету — её запреты уходят с ней: запрет без автора не отвечает на
    -- вопрос «кто кому не пишет».
    CONSTRAINT `fk_dating_block_profile` FOREIGN KEY (`profile_id`)
        REFERENCES `dating_profile` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci
  COMMENT='Кому эта анкета больше не пишет: собеседник закрылся от неё';

