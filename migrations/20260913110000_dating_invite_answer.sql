-- «Доставка» показывает ответ сайта, а не только наш вывод из него (2026-09-13)
--
-- ПОЧЕМУ. Панель писала об инвайте два слова: «ушло» либо причина отказа. Слова
-- эти — **наш пересказ** ответа сайта, и когда пересказ расходится с тем, что
-- видит человек, разобраться нечем.
--
-- Так и вышло: у анкет числятся ушедшие реплики, а зайдя под собеседником,
-- человек не нашёл в чате ни одной. Ответ сайта ответил бы на это сразу — он у
-- нас был и не сохранялся.
--
-- ⚠ ЭТО НЕ ПРИДИРКА К ФОРМУЛИРОВКЕ. «Ушло» у нас означает ровно «сайт принял
-- кадр», и в `dating_send.py` записано, почему принятое может не дойти: женской
-- анкете сайт показывает её сообщение в её же переписке, а мужчина не получает
-- его, пока не пригласит первым (`needInvite`). Отличить этот случай от настоящей
-- доставки можно только по ответу сайта.
--
-- ⚠ ХРАНИМ У ОБОИХ ИСХОДОВ, а не только у неудач. Причина неудачи и так лежит в
-- `error`; ценен как раз ответ на **удачную** отправку — там и живёт разница
-- между «принял» и «доставил».
--
-- ⚠ 500 СИМВОЛОВ, как у `error`. Ответ бывает страницей целиком, а вопрос к нему
-- один: что сказал сайт. Начало ответа на него отвечает, хвост — это вес таблицы
-- на каждую реплику.
--
-- Идемпотентность: колонка заводится по условию отсутствия.

-- ---------------------------------------------------------------- До
SELECT 'ДО' AS этап,
       (SELECT COUNT(*) FROM information_schema.COLUMNS
         WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'dating_invite'
           AND COLUMN_NAME = 'answer') AS колонка_есть;

-- ------------------------------------------- Ответ сайта
SET @sql = IF(
    (SELECT COUNT(*) FROM information_schema.COLUMNS
      WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'dating_invite'
        AND COLUMN_NAME = 'answer') = 0,
    'ALTER TABLE `dating_invite`
        ADD COLUMN `answer` VARCHAR(500) NOT NULL DEFAULT ''''
            COMMENT ''Что ответил сайт — как есть. ⚠ «Принял» ≠ «доставил»: см. needInvite''
            AFTER `error`',
    'SELECT ''колонка answer уже есть'' AS пропуск');
PREPARE s FROM @sql; EXECUTE s; DEALLOCATE PREPARE s;

-- ---------------------------------------------------------------- После
SELECT 'ПОСЛЕ' AS этап,
       (SELECT COUNT(*) FROM information_schema.COLUMNS
         WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'dating_invite'
           AND COLUMN_NAME = 'answer') AS колонка_есть;
