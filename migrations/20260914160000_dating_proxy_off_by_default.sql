-- Выходы по умолчанию выключены: снимаем их у сайтов, где галочки нет (2026-09-14)
--
-- ЗАЧЕМ. У выходов появился главный выключатель — настройка сайта `proxy_enabled`,
-- галочка в шапке вкладки «Прокси». Снята — прокси не используются нигде: ни при
-- входе, ни в чате, ни в присутствии, ни кругом проверки. По умолчанию она снята,
-- потому что каналы покупают не в первый день, а включённый механизм в этот момент
-- означает поход к соседу на каждой двери и строку «своего выхода нет» в журнале
-- каждой анкеты.
--
-- ⚠ ПОЧЕМУ ЭТОГО НЕ ХВАТАЕТ БЕЗ МИГРАЦИИ. Раздача спрашивает выключатель и после
-- него отдаёт пусто, но **кэш в анкете переживает выключение**, а читают его не
-- только через раздачу:
--
--   * удары присутствия берут адрес прямо из `dating_profile.proxy_url`;
--   * прогоны сценариев у соседа получают `proxy_id` из той же строки.
--
-- То есть анкета, которой выход достался до появления выключателя, продолжала бы
-- ходить каналом, которого для сайта уже нет. Выключатель, выключающий половину,
-- хуже отсутствующего: он обещает то, чего не делает.
--
-- ЧТО ДЕЛАЕМ. Снимаем выход у анкет тех сайтов, где `proxy_enabled` не равен `1`.
-- Сегодня это все сайты — настройка новая, и поставить её никто ещё не мог.
-- Условие всё равно пишем по настройке, а не «у всех»: миграцию применяют и на
-- проде, и на стенде, и порядок применения не обязан совпадать с порядком правок
-- в панели.
--
-- ⚠ ЭТО НЕ ПОТЕРЯ ДАННЫХ. Выход не принадлежит анкете: он лежит в реестре у
-- соседа, а здесь только кэш «кому какой достался». Включив галочку обратно,
-- человек получит раздачу заново — первая же дверь возьмёт свободный адрес.
-- Единственное, что не переживает снятие, — привязка «эта девушка входила с этого
-- IP», и она же — причина, по которой выключение стоит делать осознанно.
--
-- Идемпотентность: `UPDATE` по условию; повторный прогон не найдёт строк.

-- ---------------------------------------------------------------- До
SELECT 'ДО' AS этап,
       (SELECT COUNT(*) FROM `dating_profile`
         WHERE `proxy_id` <> 0 OR `proxy_url` <> '') AS анкет_с_выходом,
       (SELECT COUNT(*) FROM `dating_site`
         WHERE JSON_UNQUOTE(JSON_EXTRACT(`settings`, '$.proxy_enabled')) = '1')
           AS сайтов_с_галочкой;

-- ------------------------------------------- Снимаем выходы там, где галочки нет
UPDATE `dating_profile` `g`
   SET `g`.`proxy_id` = 0, `g`.`proxy_url` = '', `g`.`proxy_ip` = '',
       `g`.`proxy_at` = NULL
 WHERE (`g`.`proxy_id` <> 0 OR `g`.`proxy_url` <> '')
   AND COALESCE((SELECT JSON_UNQUOTE(JSON_EXTRACT(`s`.`settings`, '$.proxy_enabled'))
                   FROM `dating_site` `s` WHERE `s`.`site_id` = `g`.`site_id`), '0') <> '1';

-- ---------------------------------------------------------------- После
SELECT 'ПОСЛЕ' AS этап,
       (SELECT COUNT(*) FROM `dating_profile`
         WHERE `proxy_id` <> 0 OR `proxy_url` <> '') AS анкет_с_выходом;
