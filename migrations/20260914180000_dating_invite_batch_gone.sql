-- Настройка `invite_batch` больше не нужна: шаблон один на пул (2026-09-14)
--
-- ЗАЧЕМ. Инвайты перешли на общий шаблон: агент вызывается **один раз на заход** и
-- присылает текст с метками, а карточки собирает подстановка имён. Прежде реплика
-- сочинялась каждой паре, и `invite_batch` отвечала на единственный вопрос —
-- сколько вызовов LLM мы готовы ждать у нажатой кнопки. Вопроса больше нет.
--
-- ⚠ ХУЖЕ ТОГО, ТЕПЕРЬ ОНА ВРЕДНА. Круг набирает пул **целиком и только пустой**:
-- шаблон один, и доложенные к прежним сорока десять карточек лежали бы в пуле
-- вторым текстом вперемешку с первым. Порция меньше пула означала бы именно это.
--
-- ЧТО ДЕЛАЕМ. Убираем ключ из настроек сайтов. Из реестра (`DATING_SITE_KNOWN`) он
-- уже убран; оставь мы значение в базе — страница показала бы его в «Своих
-- настройках», среди заведённого руками, и человек искал бы, на что оно влияет.
--
-- ⚠ УДАЛЯЕТСЯ ТОЛЬКО ЭТОТ КЛЮЧ. `JSON_REMOVE` по одному пути не трогает соседние:
-- в этой колонке живут пароли API и настройка присутствия, и переписывать её
-- целиком ради одного ключа нельзя.
--
-- Идемпотентность: `JSON_REMOVE` по отсутствующему пути ничего не меняет; условие
-- в `WHERE` не даёт трогать строки, где ключа нет.

-- ---------------------------------------------------------------- До
SELECT 'ДО' AS этап,
       COUNT(*) AS сайтов_с_ключом
  FROM `dating_site`
 WHERE JSON_EXTRACT(`settings`, '$.invite_batch') IS NOT NULL;

-- ------------------------------------------- Убираем ключ
UPDATE `dating_site`
   SET `settings` = JSON_REMOVE(`settings`, '$.invite_batch')
 WHERE JSON_EXTRACT(`settings`, '$.invite_batch') IS NOT NULL;

-- ---------------------------------------------------------------- После
SELECT 'ПОСЛЕ' AS этап,
       COUNT(*) AS сайтов_с_ключом
  FROM `dating_site`
 WHERE JSON_EXTRACT(`settings`, '$.invite_batch') IS NOT NULL;
