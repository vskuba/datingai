-- Журнал внешних запросов: каждый поход наружу отдельной строкой (2026-09-15)
--
-- ЗАЧЕМ. Панель ходит наружу непрерывно — вход на сайт, забор писем, списки
-- собеседников, удары присутствия, отправка, страницы кабинета и панели
-- агентства, — и до сих пор **ни один из этих походов не был виден человеку**. В
-- ленте «Журналы» сходятся ровно две таблицы: `dating_log` (ход работы по анкете)
-- и `dating_scenario_run` (прогоны сценариев у соседа). HTTP к самому сайту не
-- попадал никуда, кроме `docker logs`.
--
-- Цена этой слепоты выяснилась в сентябре. Круг ленты «Все онлайн» стучался в
-- `POST /auth/login` каждые две минуты, вход не проходил, и за сутки набралось 484
-- неудачи — после чего сайт закрыл наш IP целиком, всем анкетам разом. В панели
-- это выглядело как «списки не обновляются»: ни одной строки про то, что мы
-- ломимся на сайт каждые две минуты, нигде не было.
--
-- ⚠ ПОЧЕМУ ОТДЕЛЬНАЯ ТАБЛИЦА, А НЕ `dating_log`. Считано по настройкам прода на
-- тринадцати анкетах: присутствие 37 440 походов в сутки, забор писем 9 360,
-- избранные 3 744, ленты и панель ещё тысяча — **около 52 000 строк в сутки**. В
-- `dating_log` сейчас 2 490 строк за 27 дней, то есть 92 в сутки. Ссыпав одно в
-- другое, мы получили бы пятисоткратный рост, а правая колонка на «Профилях» —
-- та, что человек читает глазами, — превратилась бы в поток ударов присутствия.
--
-- Разные вопросы — разные таблицы: `dating_log` отвечает «что происходило с
-- анкетой», а этот журнал — «куда и зачем мы ходили и что нам ответили».
--
-- ⚠ СРОК ХРАНЕНИЯ ОБЯЗАТЕЛЕН И ЗАДАН ЗДЕСЬ ЖЕ. 52 тысячи строк в сутки — это
-- полтора миллиона в месяц; без чистки таблица переросла бы всю остальную базу за
-- недели. Чистит круг (`dating_request_round`), срок — настройка панели
-- `request_keep_days`, по умолчанию трое суток. Трое, а не сутки: разбирают такое
-- задним числом, и «вчера вечером» должно быть на месте в понедельник утром.
--
-- ЧТО В СТРОКЕ:
--
--   `profile_id` — чьей учёткой ходили. **Ноль — поход по сайту**, а не по анкете
--                  (лента «Все онлайн», сессия панели агентства, проверка выходов):
--                  внешнего ключа поэтому нет, он запретил бы ноль;
--   `site_id`    — сайт: по нему отбирает страница, селект сайта общий на раздел;
--   `door`       — какая дверь: `login`, `mail`, `people`, `heartbeat`, `send`,
--                  `panel`, `cabinet`, `socket`, `proxy`. Не путь, а **занятие**:
--                  по пути человек не поймёт, а по занятию поймёт сразу;
--   `method`,`path` — что именно спросили. Путь без адреса сайта: он один на сайт
--                  и в каждой строке был бы шумом;
--   `status`     — код ответа. Ноль — ответа не было вовсе (обрыв, таймаут);
--   `ok`         — удачей ли кончилось. Отдельно от кода: у сайта `200` с телом
--                  `{"IsSuccess": false}` — это отказ, и по коду его не отличить;
--   `error`      — чем кончилось, если не удачей. Словами, для человека;
--   `ms`         — сколько заняло. По нему видно медленный прокси и висящий сайт;
--   `proxy_ip`   — каким адресом нас видели. Пусто — шли общим адресом сервера.
--
-- ⚠ ПАРОЛЕЙ И ТЕЛ ЗДЕСЬ НЕТ. Ни строки подключения к прокси (только увиденный
-- IP), ни тела запроса, ни тела ответа: в них пароли, cookie и переписка живых
-- людей. Журнал читают в консоли и копируют в переписку — см. правило в
-- `py_modules/docs/observability_rules.md`, §10.
--
-- Идемпотентность: таблица заводится по условию отсутствия.

-- ---------------------------------------------------------------- До
SELECT 'ДО' AS этап,
       (SELECT COUNT(*) FROM information_schema.TABLES
         WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'dating_request') AS таблица_есть;

-- ------------------------------------------- Таблица
CREATE TABLE IF NOT EXISTS `dating_request` (
    `id`         BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    `profile_id` INT NOT NULL DEFAULT 0
                 COMMENT 'Чьей учёткой ходили. 0 — поход по сайту, а не по анкете',
    `site_id`    INT NOT NULL DEFAULT 0 COMMENT 'Сайт-закладка: по нему отбирает страница',
    `door`       VARCHAR(16) NOT NULL DEFAULT ''
                 COMMENT 'Занятие: login, mail, people, heartbeat, send, panel, cabinet, socket, proxy',
    `method`     VARCHAR(8) NOT NULL DEFAULT '' COMMENT 'GET, POST, WS',
    `path`       VARCHAR(255) NOT NULL DEFAULT '' COMMENT 'Путь без адреса сайта',
    `status`     SMALLINT NOT NULL DEFAULT 0 COMMENT 'Код ответа. 0 — ответа не было вовсе',
    `ok`         TINYINT(1) NOT NULL DEFAULT 0
                 COMMENT 'Удачей ли кончилось. ⚠ Не то же, что код: 200 с IsSuccess=false — отказ',
    `error`      VARCHAR(500) NOT NULL DEFAULT '' COMMENT 'Чем кончилось, если не удачей',
    `ms`         INT NOT NULL DEFAULT 0 COMMENT 'Сколько заняло, миллисекунды',
    `proxy_ip`   VARCHAR(45) NOT NULL DEFAULT ''
                 COMMENT 'Каким адресом нас видели. Пусто — общий адрес сервера',
    `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    PRIMARY KEY (`id`),
    -- Отбор страницы: сайт плюс свежие сверху. Первым `site_id`, потому что
    -- селект сайта стоит в шапке и снимается с каждого запроса.
    KEY `idx_dating_request_site` (`site_id`, `created_at`),
    -- Журнал одной анкеты: та же лента, но по ней.
    KEY `idx_dating_request_profile` (`profile_id`, `created_at`),
    -- Чистка по сроку ходит только по времени, без сайта.
    KEY `idx_dating_request_when` (`created_at`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci
  COMMENT='Внешние запросы: куда ходили, что ответили, сколько заняло';

-- ---------------------------------------------------------------- После
SELECT 'ПОСЛЕ' AS этап,
       (SELECT COUNT(*) FROM information_schema.TABLES
         WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'dating_request') AS таблица_есть,
       (SELECT COUNT(*) FROM information_schema.STATISTICS
         WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'dating_request') AS столбцов_в_ключах;
