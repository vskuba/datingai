-- Черновик ответа в чате: пишется заранее, ждёт собеседника (2026-09-19)
--
-- ЗАЧЕМ. Ответ в чате сочинялся и отправлялся одним движением, и пока собеседника
-- нет в сети, не существовало вовсе: круг видел «нет в сети», уходил и не тратил
-- вызов LLM. Правильно по деньгам, но у этого две цены.
--
-- Первая: человек не видит работы. В окне разговора пусто, и «ответ готовится»
-- ничем не отличается от «ничего не происходит» — ровно тот вопрос, с которого
-- начался этот заход.
--
-- Вторая: ответ приходит с опозданием. Собеседник появился — и ждёт ещё круг плюс
-- десяток секунд на LLM. С черновиком он уходит сразу: текст уже лежит.
--
-- ⚠⚠ УСТРОЕНО КАК У ПИСЕМ (`mail_reply`), И НАРОЧНО. Там это работает давно:
-- черновик лежит строкой со `status = 'draft'`, показывается последней репликой
-- разговора с пометкой «ответ в пуле» и уносится кругом отправки. Второй способ
-- хранить то же самое разошёлся бы с первым на первой же правке — а объяснять,
-- почему у писем и у чата «ждущий ответ» ведёт себя по-разному, нечем.
--
-- ⚠ КЛЮЧ — НА `message_id`, И ЭТО НЕ УКРАШЕНИЕ. Черновик отвечает **конкретной
-- реплике**, а не человеку вообще. Отсюда бесплатно получаются две вещи:
--
--   • протухание. Написал он снова — у пары новая последняя реплика, новый
--     `message_id` и новый черновик; старый остаётся при своей строке и в
--     разговор больше не идёт. Ключ на паре («анкета + собеседник») такого не
--     даёт: пришлось бы сверять времена руками и однажды ошибиться в сторону
--     «отправили ответ на позавчерашнее».
--
--   • отсутствие дублей. Круг ходит раз в минуту и запросто зайдёт дважды на ту
--     же реплику; ключ превращает вторую попытку в отказ вставки, а не во второй
--     ответ тому же человеку.
--
-- ⚠ ПОВОДОМ БЫВАЕТ И НАША СОБСТВЕННАЯ РЕПЛИКА. У ведущей разговор анкеты второй
-- повод написать — **тишина**: последнее слово осталось за нами и давно. Тогда
-- `message_id` указывает на исходящую строку, и это законно: «ответ на молчание
-- после вот этих наших слов» — такая же единица работы.
--
-- ⚠ КАСКАД ОТ `message`. Ушла реплика — ушёл и черновик ответа на неё: ответ, у
-- которого не осталось повода, прочесть нельзя — не с чем сверить. То же
-- соображение, что у `mail_reply.mail_in_id`.
--
-- ⚠ `site_id` ДЕРЖИМ СВОЙ, хотя он выводится из анкеты. Отбор пула идёт по сайту,
-- и join к `profile` на каждой выборке — лишняя работа ради поля, которое у
-- строки не меняется. Так же сделано у всех трёх соседних пулов.
--
-- Идемпотентность: `CREATE TABLE IF NOT EXISTS`.

CREATE TABLE IF NOT EXISTS `chat_reply` (
    `id`         INT NOT NULL AUTO_INCREMENT,
    `site_id`    INT NOT NULL COMMENT 'Сайт: пул отбирается по нему',
    `profile_id` INT NOT NULL COMMENT 'От чьего имени отвечаем',
    `message_id` INT NOT NULL COMMENT 'Повод написать: реплика, на которую отвечаем',

    `uid`  VARCHAR(32)  NOT NULL DEFAULT '' COMMENT 'Кому: номер собеседника на сайте',
    `name` VARCHAR(190) NOT NULL DEFAULT '' COMMENT 'Его имя на момент ответа',

    `body` TEXT NOT NULL COMMENT 'Текст ответа — то, что уйдёт',

    -- ⚠ Те же три состояния, что у писем, и то же правило: неудача оставляет
    -- черновик в пуле (`draft` с причиной в `error`), чтобы круг повторил.
    -- `failed` похоронил бы ответ на живую реплику.
    `status` ENUM('draft', 'sent', 'failed') NOT NULL DEFAULT 'draft'
        COMMENT 'draft — ждёт собеседника, sent — ушло, failed — не ушло',
    `error`   VARCHAR(500) NOT NULL DEFAULT '' COMMENT 'Почему не ушло: словами',
    `sent_at` DATETIME NULL COMMENT 'Когда ушло. NULL — ещё ждёт',

    `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,

    PRIMARY KEY (`id`),
    UNIQUE KEY `uq_chat_reply` (`message_id`),
    -- Под выборку пула: по сайту, свежие сверху.
    KEY `idx_chat_reply_site` (`site_id`, `status`, `id`),
    -- Под «есть ли черновик у этой пары» — самый частый вопрос круга.
    KEY `idx_chat_reply_pair` (`profile_id`, `uid`, `status`),
    CONSTRAINT `fk_chat_reply_message` FOREIGN KEY (`message_id`)
        REFERENCES `message` (`id`) ON DELETE CASCADE,
    CONSTRAINT `fk_chat_reply_profile` FOREIGN KEY (`profile_id`)
        REFERENCES `profile` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci
  COMMENT='Черновики ответов в чате: написаны агентом, ждут собеседника в сети';
