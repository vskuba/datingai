-- Пул инициативы: чем возвращаться к затихшему разговору (2026-09-19)
--
-- ЗАЧЕМ. Разговор затихает не потому, что кончился, а потому, что последнее слово
-- осталось за нами и человек не ответил. Сейчас такая пара лежит мёртвой: круг
-- отвечает только на входящее, а сам не пишет.
--
-- Пул собирает, **чем** заговорить снова: вопрос, повод, короткий текст под
-- конкретную пару. Человек его читает и правит до того, как оно уйдёт, — ровно
-- как в трёх соседних пулах (рассылка, инвайты, приставания).
--
-- ⚠⚠ УСТРОЕНО КАК ОСТАЛЬНЫЕ ПУЛЫ, И НАРОЧНО. Те же три состояния, та же неудача,
-- оставляющая строку в пуле с причиной. Четвёртый способ хранить «текст, ждущий
-- отправки» разошёлся бы с тремя первыми на первой же правке, а объяснять, почему
-- у инициативы всё иначе, нечем.
--
-- ⚠ КЛЮЧ — НА ПАРУ, А НЕ НА РЕПЛИКУ, и этим пул отличается от `chat_reply`. Там
-- повод — конкретная его реплика, и ключ стоит на ней. Здесь повода-реплики нет
-- вовсе: поводом служит **тишина**, а у тишины номера нет. Пара «анкета +
-- собеседник» — единственное, что эту работу опознаёт, и ключ не даёт завести ей
-- вторую карточку, пока первая не ушла.
--
-- ⚠ `try_no` — КОТОРЫЙ ЭТО ЗАХОД. Настройка сайта `chat_initiative_repeat`
-- говорит, сколько раз подряд возвращаться к молчащему; без счётчика в строке
-- считать пришлось бы по журналу, а он живёт трое суток и чистится.
--
-- Счёт сбрасывает **его ответ**: заговорил — разговор жив, и следующая тишина
-- начинается с нуля. Решает это код набора, а не база: здесь лишь место под число.
--
-- ⚠ РАБОТЫ ЗА ПУЛОМ ПОКА НЕТ. Таблица, ручка и колонка на странице заведены, а
-- набирать карточки некому: круга инициативы не существует. Пул будет пустым, и
-- это ожидаемо — см. подсказки настроек `chat_initiative_*`.
--
-- Идемпотентность: `CREATE TABLE IF NOT EXISTS`.

CREATE TABLE IF NOT EXISTS `chat_initiative` (
    `id`         INT NOT NULL AUTO_INCREMENT,
    `site_id`    INT NOT NULL COMMENT 'Сайт: пул отбирается по нему',
    `profile_id` INT NOT NULL COMMENT 'От чьего имени пишем',

    `uid`  VARCHAR(32)  NOT NULL DEFAULT '' COMMENT 'Кому: номер собеседника на сайте',
    `name` VARCHAR(190) NOT NULL DEFAULT '' COMMENT 'Его имя на момент набора',

    `body` TEXT NOT NULL COMMENT 'Чем заговорить: вопрос или короткий текст',

    -- ⚠ Который это заход к молчащему. Предел задаёт настройка сайта
    -- `chat_initiative_repeat`; его ответ счёт обнуляет.
    `try_no` INT NOT NULL DEFAULT 1 COMMENT 'Который заход подряд: 1, 2, …',

    `status` ENUM('draft', 'sent', 'failed') NOT NULL DEFAULT 'draft'
        COMMENT 'draft — ждёт отправки, sent — ушло, failed — не ушло',
    `error`   VARCHAR(500) NOT NULL DEFAULT '' COMMENT 'Почему не ушло: словами',
    `sent_at` DATETIME NULL COMMENT 'Когда ушло. NULL — ещё в пуле',

    `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,

    -- ⚠ Одна ждущая карточка на пару. Ушедшие ключ не держат: у них столбец пуст,
    -- а `NULL` в MySQL уникальности не нарушает. Простой ключ по `(profile_id,
    -- uid)` запретил бы **историю** — вторую инициативу тому же человеку когда бы
    -- то ни было.
    --
    -- ⚠⚠ ЗАВИСИТ ОТ `status` И `uid`, НО НЕ ОТ `profile_id`, и это не стиль.
    -- MySQL запрещает `ON DELETE CASCADE` у внешнего ключа, если от его столбца
    -- зависит генерируемый (`Cannot add foreign key constraint`, 1215). Впиши мы
    -- сюда `profile_id` — таблица не создалась бы вовсе; номер анкеты поэтому
    -- входит в **ключ**, а не в вычисление. Тем же приёмом живёт `invite`.
    `draft_uid` VARCHAR(32) GENERATED ALWAYS AS
        (IF(`status` = 'draft', `uid`, NULL)) STORED
        COMMENT 'Номер собеседника, пока карточка в пуле. NULL у ушедших',

    PRIMARY KEY (`id`),
    UNIQUE KEY `uq_chat_initiative_draft` (`profile_id`, `draft_uid`),
    -- Под выборку пула: по сайту, свежие сверху.
    KEY `idx_chat_initiative_site` (`site_id`, `status`, `id`),
    KEY `fk_chat_initiative_profile` (`profile_id`),
    CONSTRAINT `fk_chat_initiative_profile` FOREIGN KEY (`profile_id`)
        REFERENCES `profile` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci
  COMMENT='Пул инициативы: чем вернуться к затихшему разговору';
