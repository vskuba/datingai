-- Счётчик событий, не зависящий от рабочих таблиц (2026-09-20)
--
-- ЗАЧЕМ. Статистика считала «сколько инвайтов ушло» прямо по таблице `invite`:
-- `SUM(status = 'sent')`. Пока таблица хранила всё, это работало. Как только у неё
-- появилась чистка по сроку (шесть часов), счёт обвалился: страница показывала
-- 38 889 ушедших там, где за трое суток ушло 280 тысяч.
--
-- ⚠⚠ ЭТО ОБЩЕЕ ПРАВИЛО, А НЕ СЛУЧАЙ С ИНВАЙТАМИ. Рабочая таблица отвечает на
-- вопрос «что сейчас в работе» и вправе забывать старое — иначе она растёт без
-- предела. Статистика отвечает на вопрос «сколько сделано» и забывать не вправе.
-- Считать второе по первой — значит привязать историю к сроку уборки, и первая же
-- ротация стирает её молча.
--
-- ⚠ АГРЕГАТ ПО СУТКАМ, А НЕ СТРОКА НА СОБЫТИЕ. Событий девяносто тысяч в сутки;
-- строка на каждое дала бы таблицу, которую пришлось бы чистить — и мы вернулись
-- бы туда, откуда ушли. Строка на «сайт + анкета + вид + сутки» это тринадцать
-- анкет на пять видов: два десятка строк в сутки, семь тысяч в год.
--
-- ⚠⚠ `profile_id = 0` — «по сайту целиком», и это НЕ NULL. Два довода, и второй
-- решающий. MySQL не допускает NULL в первичном ключе вовсе. А в UNIQUE он его
-- допускает, но там NULL не равен NULL — значит `ON DUPLICATE KEY UPDATE` не
-- сработал бы для строк «по сайту», и счётчик молча плодил бы по строке на
-- каждое событие вместо того, чтобы складывать.
--
-- Внешнего ключа нет **нарочно**: удалили анкету — её работа остаётся в истории,
-- иначе счёт «сколько сделано» менялся бы задним числом.
--
-- Идемпотентность: `CREATE TABLE IF NOT EXISTS`, заполнение — `INSERT IGNORE`.

CREATE TABLE IF NOT EXISTS `stat_day` (
    `site_id`    INT NOT NULL COMMENT 'Сайт-закладка',
    `profile_id` INT NOT NULL DEFAULT 0 COMMENT 'Анкета; 0 — событие сайта целиком',
    `kind`       VARCHAR(32) NOT NULL COMMENT 'Вид события: invite_sent, chat_out, …',
    `day`        DATE NOT NULL COMMENT 'Сутки по времени базы (UTC)',

    `n` INT NOT NULL DEFAULT 0 COMMENT 'Сколько раз случилось',

    `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `updated_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
        ON UPDATE CURRENT_TIMESTAMP,

    -- ⚠ Ключ по «сайт + вид + сутки + анкета»: он же и защита от дублей, на нём
    -- держится `ON DUPLICATE KEY UPDATE n = n + …`.
    PRIMARY KEY (`site_id`, `kind`, `day`, `profile_id`),
    -- Под выборку окна: «что было за последние сутки/неделю» по сайту.
    KEY `idx_stat_day_window` (`site_id`, `kind`, `day`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci
  COMMENT='Счётчик событий по суткам: история, не зависящая от чистки рабочих таблиц';

-- ── Что успеем восстановить ─────────────────────────────────────────────────
--
-- ⚠ Журнал анкет помнит трое суток, и в нём есть строки «Инвайт ушёл: …». Это
-- единственный след ушедших инвайтов, переживший чистку таблицы, — переносим его
-- в счётчик, чтобы страница не начинала историю с нуля.
--
-- ⚠⚠ Дальше трёх суток восстанавливать нечего, и это честнее, чем выдумать. Те
-- тридцать восемь тысяч, что лежат в `invite` сейчас, — не история, а окно
-- последних часов: сложи мы их сверху, счёт получился бы двойным.

INSERT IGNORE INTO `stat_day` (`site_id`, `profile_id`, `kind`, `day`, `n`)
SELECT p.`site_id`, l.`profile_id`, 'invite_sent', DATE(l.`created_at`), COUNT(*)
  FROM `log` l
  JOIN `profile` p ON p.`id` = l.`profile_id`
 WHERE l.`text` LIKE 'Инвайт ушёл%'
 GROUP BY p.`site_id`, l.`profile_id`, DATE(l.`created_at`);

SELECT 'ПОСЛЕ' AS этап,
       (SELECT COUNT(*) FROM `stat_day`) AS строк,
       (SELECT COALESCE(SUM(`n`), 0) FROM `stat_day` WHERE `kind` = 'invite_sent')
       AS восстановлено_инвайтов,
       (SELECT COUNT(DISTINCT `day`) FROM `stat_day`) AS суток;
