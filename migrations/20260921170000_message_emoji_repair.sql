-- Починка эмодзи, разобранных панелью неверно (2026-09-21)
--
-- ЗАЧЕМ. Панель агентства отдаёт эмодзи номером в ПЯТЬ шестнадцатеричных цифр
-- (ὠ9 — это 😉), а её разборщик читает ровно четыре. Пятая цифра остаётся
-- в тексте буквой, и выходит пара «знак греческого расширенного плюс цифра»:
--
--     😉  U+1F609   →   ὠ9   (U+1F60 + цифра 9)
--
-- ⚠⚠ ДВЕ БЕДЫ СРАЗУ. Человек видит в переписке греческую букву — это заметно.
-- Но хуже незаметное: наша же реплика, вернувшаяся из журнала сайта, перестаёт
-- совпадать с той, что мы отправили, и отсев близнецов (`message_twin.py`) её
-- не узнаёт. Так у пары Diana → Henry остались видимые дубли после того, как
-- все прочие исчезли.
--
-- ⚠ ЭТО РАЗОВАЯ УБОРКА. Новые искажения не появятся: текст чинится **на входе**
-- (`text_emoji_same` в общем слое, зовут четыре воронки — чат, панель, имена,
-- письма). Здесь чинится только то, что успело накопиться.
--
-- ⚠⚠ ЗНАКИ ПИШУТСЯ ЛИТЕРАЛАМИ, А НЕ ЧЕРЕЗ `CHAR()`. Первая проба этой миграции
-- делала `CHAR(0x1F60 USING utf8mb4)` и не чинила ничего: MySQL понимает число
-- как последовательность БАЙТОВ (`1F 60`), а вовсе не как номер знака. Файл в
-- UTF-8, клиент зовётся с `--default-character-set=utf8mb4` — литерал доезжает
-- как есть.
--
-- ⚠ ПОЧЕМУ ЗАМЕНА ТОЧЕЧНАЯ, А НЕ ОБЩЕЕ ПРАВИЛО. Развернуть пару обратно — это
-- «голова × 16 + цифра», и в SQL такое выражается только перечислением. На всей
-- базе (42 261 строка) искажены ровно две, обе одним знаком. Перечисляем его;
-- проверка в конце покажет, если найдётся что-то ещё.
--
-- Идемпотентность: `REPLACE` не найдёт строку на второй заход и ничего не тронет.

SELECT 'ДО' AS этап,
       (SELECT COUNT(*) FROM `message` WHERE `text` LIKE '%ὠ9%') AS искажённых;

-- 😉 U+1F609 — единственный, что встретился.
UPDATE `message`
   SET `text` = REPLACE(`text`, 'ὠ9', '😉')
 WHERE `text` LIKE '%ὠ9%';

SELECT 'ПОСЛЕ' AS этап, ROW_COUNT() AS починено,
       (SELECT COUNT(*) FROM `message` WHERE `text` LIKE '%ὠ9%') AS осталось;

-- ⚠ Что ещё искажено и этой заменой не покрыто: знак греческого расширенного,
-- за которым идёт шестнадцатеричная цифра. Не пусто — значит встретился другой
-- эмодзи, и его пару надо дописать новой миграцией.
SELECT 'ОСТАЛЬНОЕ' AS этап, `id`, `source`, RIGHT(`text`, 24) AS хвост
  FROM `message`
 WHERE `text` COLLATE utf8mb4_bin REGEXP '[ἀ-ᾯ][0-9a-fA-F]'
 LIMIT 10;
