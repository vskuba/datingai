-- Пауза между письмами избранным: секунды → минуты (2026-09-23)
--
-- ## ⚠⚠ ЗАЧЕМ: число читает человек, а не машина
--
-- Настройка `favorite_mail_gap` была набором из четырёх сроков в секундах:
-- `3600` — «1 час», `14400` — «4 часа» и так далее. Два изъяна:
--
-- * **набор запрещал нужное.** Он отвечает на вопрос «какие значения
--   осмысленны», и для многих сроков это верно — но здесь осмысленна любая
--   пауза: сайты разные, и подбирают её опытом. Выбор из четырёх заставлял
--   брать ближайший вариант, а не свой;
-- * **секунды не читаются.** «240» человек складывает в четыре часа сходу,
--   «14400» — ни во что.
--
-- Теперь это числовое поле, значение в минутах, единица названа прямо в
-- заголовке: «Пауза между письмами, мин».
--
-- ## ⚠⚠⚠ Значение ОБЯЗАНО быть переведено, иначе пауза вырастет в 60 раз
--
-- В базе лежат секунды, выставленные человеком. Смени мы только смысл — те же
-- `14400` стали бы **14400 минутами, то есть десятью сутками** молчания: письма
-- избранным перестали бы уходить вовсе, и причину искали бы в круге отправки.
--
-- Поэтому миграция делит на 60 то, что уже лежит.
--
-- ⚠ **Делим только похожее на секунды.** Признак — значение больше 720: минуты
-- столько не бывают у паузы между письмами (это полсуток), а секунды — сплошь и
-- рядом (3600 это всего час). Меньшее не трогаем: либо его уже перевели, либо
-- человек вписал минуты руками после выкладки кода.
--
-- ⚠ Ключ настройки **не переименован**, как и при прошлой правке смысла: в нём
-- лежит выставленное человеком значение, и смена ключа молча вернула бы сайт к
-- умолчанию.
--
-- Идемпотентность: второй заход не найдёт значений больше 720 и ничего не
-- тронет.

SELECT 'ДО' AS этап, site_id,
       JSON_UNQUOTE(JSON_EXTRACT(`settings`, '$.favorite_mail_gap')) AS пауза
  FROM `site`
 WHERE JSON_EXTRACT(`settings`, '$.favorite_mail_gap') IS NOT NULL;

UPDATE `site`
   SET `settings` = JSON_SET(
         `settings`, '$.favorite_mail_gap',
         CAST(FLOOR(JSON_UNQUOTE(JSON_EXTRACT(`settings`, '$.favorite_mail_gap')) / 60)
              AS CHAR))
 WHERE JSON_EXTRACT(`settings`, '$.favorite_mail_gap') IS NOT NULL
   AND JSON_UNQUOTE(JSON_EXTRACT(`settings`, '$.favorite_mail_gap')) REGEXP '^[0-9]+$'
   AND CAST(JSON_UNQUOTE(JSON_EXTRACT(`settings`, '$.favorite_mail_gap')) AS UNSIGNED) > 720;

SELECT 'ПОСЛЕ' AS этап, site_id,
       JSON_UNQUOTE(JSON_EXTRACT(`settings`, '$.favorite_mail_gap')) AS пауза_минут,
       CONCAT(ROUND(JSON_UNQUOTE(JSON_EXTRACT(`settings`, '$.favorite_mail_gap')) / 60, 1),
              ' ч') AS читается_как
  FROM `site`
 WHERE JSON_EXTRACT(`settings`, '$.favorite_mail_gap') IS NOT NULL;
