-- Роль `dating` → `operator`: имя второй роли приводится к общему скелету панели.
--
-- ЗАЧЕМ. Вход, роли и управление людьми переехали в общий слой
-- (`py_modules/panel_/`, страница `.claude/docs-common/panel.md`). Там имя второй
-- роли — `operator`, и это не косметика: роль лежит **в этом столбце**, её кладёт
-- в куку вход и сравнивает `PanelUser`. Проект, оставшийся на своём имени, из
-- общего скелета выпадает.
--
-- ЧТО МЕНЯЕТСЯ: значения `user.role` и умолчание столбца. Ничего, кроме этой
-- таблицы, роль не хранит — ни одна предметная таблица на неё не ссылается.
--
-- ⚠⚠ ПОРЯДОК С ВЫКЛАДКОЙ НЕ ВАЖЕН, и это проверено по коду, а не на удачу.
-- `PanelUser` трактует **любое незнакомое значение роли как наименьшие права**, а
-- наименьшие права это и есть оператор. Значит:
--
--   миграция раньше кода — новый `operator` старый код читает как незнакомое и
--                          даёт права оператора. Верно;
--   код раньше миграции — старый `dating` новый код читает как незнакомое и
--                          даёт права оператора. Тоже верно.
--
-- Админ в обоих случаях остаётся админом: сравнение идёт со строкой `admin`,
-- которая не меняется. Единственный видимый след рассинхрона — подпись роли на
-- странице «Пользователи» на время между двумя шагами.
--
-- ⚠ ПЕРЕМЕННЫЕ ОКРУЖЕНИЯ СМЕНИЛИСЬ ТОЖЕ: `DATING_USERNAME`/`DATING_PASSWORD` →
-- `OPERATOR_USERNAME`/`OPERATOR_PASSWORD`. Забыть их в `.env` прода не опасно:
-- посев только **заводит** оператора, когда такого логина нет, и на установке,
-- где он уже есть, не делает ничего.
--
-- ПОВТОРНЫЙ ПРОГОН БЕЗВРЕДЕН: `UPDATE` по значению `dating` во второй раз не
-- находит ни одной строки, а умолчание ставится в то же самое значение.
--
-- ⚠ СТРАХОВКИ ЧЕРЕЗ `information_schema` ЗДЕСЬ НЕТ НАМЕРЕННО, хотя ниже DDL.
-- Страховка нужна там, где команда **падает** на повторе: `ADD COLUMN` на
-- существующем столбце, `DROP` на отсутствующем. `MODIFY COLUMN` не из таких —
-- он ставит столбец в описанное состояние, сколько его ни гоняй. А сам столбец
-- `role` есть на любой установке: он приходит из начальной схемы.

-- ДО: кто с какой ролью. На этой строке видно, сколько учёток поедет.
SELECT 'ДО' AS mark, `role`, COUNT(*) AS n FROM `user` GROUP BY `role` ORDER BY `role`;

ALTER TABLE `user`
    MODIFY COLUMN `role` VARCHAR(20) NOT NULL DEFAULT 'operator'
    COMMENT 'operator — предметная работа; admin — плюс устройство установки';

UPDATE `user` SET `role` = 'operator' WHERE `role` = 'dating';

-- ПОСЛЕ: сколько кого осталось. Строк с `dating` быть не должно ни одной.
SELECT 'ПОСЛЕ' AS mark, `role`, COUNT(*) AS n FROM `user` GROUP BY `role` ORDER BY `role`;
