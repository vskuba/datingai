-- Разрешение отправлять фотографии в письмах (2026-10-06)
--
-- ЗАЧЕМ: в блоке «Настройки анкеты» на вкладке «Общая информация» появляется
-- галочка «Отправка фотографий», и её состоянию негде храниться.
--
-- ⚠ ИСПОЛНИТЕЛЯ У ФЛАГА ПОКА НЕТ, И ЭТО НЕ НЕДОДЕЛКА. Вложений в письмах проект
-- сейчас не шлёт вовсе: всё, что зовётся `photo` в почтовом коде, — аватарка
-- собеседника из списка сайта, а не снимок в письме. Колонка хранит решение
-- человека, чтобы оно не пропадало до того дня, когда отправку напишут. Тот же
-- порядок, которым заводился `mailing_on`.
--
-- ⚠ ПОЧЕМУ У АНКЕТЫ, А НЕ У САЙТА. Снимки лежат в галерее **анкеты** (её папка
-- на Google Диске), и решение «этой девушке можно слать фото» — про неё: у одной
-- папка собрана и проверена, у другой пуста. Понадобится ещё и общий запрет по
-- сайту — он встанет настройкой сайта **поверх** этого флага, а не заменой: так
-- же разведены `reply_on` у анкеты и `reply_send_on` у сайта.
--
-- ⚠ ПОЧЕМУ УМОЛЧАНИЕ 0. Включённая галочка у функции, которой нет, — это ложь:
-- человек решит, что фотографии уходят, и не поймёт, почему их никто не видел.
-- И даже когда отправку напишут, разрешение слать снимки должно быть выбором
-- человека по каждой анкете, а не доставаться сорока учёткам молча.
--
-- ⚠ ПОЧЕМУ БЕЗ ИНДЕКСА. Отбирать по колонке некому — круга нет. Индекс, который
-- никто не читает, платится на каждой записи. Заведёт его та задача, которая
-- напишет отправку.
--
-- Идемпотентность: `yoyo` её не требует (`.claude/docs/migration.md`, §2), но
-- соседние файлы её держат, и цена нулевая — зато файл можно прогнать руками по
-- прод-туннелю, не боясь второго накатывания.

-- ---------------------------------------------------------------- До
SELECT 'ДО' AS этап,
       (SELECT COUNT(*) FROM information_schema.COLUMNS
         WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'profile'
           AND COLUMN_NAME = 'mail_photo_on') AS колонка_есть,
       (SELECT COUNT(*) FROM `profile`) AS анкет;

-- ------------------------------------------- Колонка
--
-- ⚠ `AFTER reply_on`: почтовые флаги анкеты стоят подряд (`mailing_on`,
-- `reply_on`), и четвёртый читается рядом с ними, а не между `enabled` и
-- расписанием.
SET @sql = IF(
    (SELECT COUNT(*) FROM information_schema.COLUMNS
      WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'profile'
        AND COLUMN_NAME = 'mail_photo_on') = 0,
    'ALTER TABLE `profile`
        ADD COLUMN `mail_photo_on` TINYINT(1) NOT NULL DEFAULT 0
            COMMENT ''Разрешена ли отправка фотографий в письмах от этой анкеты''
            AFTER `reply_on`',
    'SELECT ''колонка mail_photo_on уже есть'' AS пропуск');
PREPARE stmt FROM @sql;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;

-- ---------------------------------------------------------------- После
SELECT 'ПОСЛЕ' AS этап,
       (SELECT COUNT(*) FROM `profile` WHERE `mail_photo_on` = 1) AS шлют_фото,
       (SELECT COUNT(*) FROM `profile` WHERE `mail_photo_on` = 0) AS не_шлют;
