-- E2E-проверки интерфейса: результаты прогонов и выключатель случая (2026-10-10)
--
-- ЗАЧЕМ. Вёрстку правят, не видя её, и типовой дефект в исходнике не виден
-- вовсе: колонка уехала на 3 px, текст обрезан на полуслове, блок вылез за
-- вьюпорт. Ошибки при этом нет ни одной — журнал чист, консоль пуста. Находил
-- такое человек, открыв страницу.
--
-- Прогон открывает страницу панели, снимает кадр, меряет названные области
-- числами из DOM и кладёт сюда строку. Страница «Тесты → E2E» это читает.
--
-- ⚠⚠ Схема живёт в проекте, а не в общем каркасе: таблицы у каждой установки
-- свои, и общий модуль в чужую схему не лезет. Сам код страницы — в submodule
-- `dashboard` (`src/page/e2e/`), он только требует эти две таблицы.
--
-- ⚠ Строка — на ТЕСТ × ШИРИНУ, а не на тест. Сетка, собранная на широкой, на
-- мобильной даёт горизонтальный скролл, и это разные вердикты одного случая.
-- Свести их в строку значило бы потерять, какая именно ширина красная.

CREATE TABLE IF NOT EXISTS `test_e2e`
(
    `id`              BIGINT UNSIGNED   NOT NULL AUTO_INCREMENT,

    -- Один прогон = одна метка на всех своих строках. UUID, а не номер: строки
    -- пишутся по мере готовности случаев, и номер пришлось бы выдавать заранее
    -- отдельной таблицей ради единственного поля.
    `run_uuid`        CHAR(36)          NOT NULL,

    -- Имя и описание случая КОПИЕЙ из YAML. Вчерашний прогон обязан читаться
    -- вчерашними словами, даже если случай с тех пор переписали или удалили.
    `name`            VARCHAR(190)      NOT NULL,
    `description`     TEXT                       DEFAULT NULL,

    `page`            VARCHAR(190)      NOT NULL,

    -- Ширина вьюпорта этой строки. Не ENUM: набор ширин задаёт случай, и новая
    -- ширина не должна требовать миграции.
    `width`           SMALLINT UNSIGNED NOT NULL,

    -- ⚠ `error` отдельно от `fail` намеренно: «тест не смог проверить» и «тест
    -- проверил и нашёл дефект» требуют разных действий, а одним красным они
    -- неразличимы.
    `status`          ENUM ('ok', 'fail', 'error') NOT NULL,

    `areas_total`     SMALLINT UNSIGNED NOT NULL DEFAULT 0,
    `areas_failed`    SMALLINT UNSIGNED NOT NULL DEFAULT 0,

    -- Строка на область: имя, селектор, rect, правила, вердикт, замеренное
    -- число. ⚠ JSON, а не своя таблица: области читают всегда целиком вместе со
    -- своей строкой и никогда не ищут по ним.
    `area_json`       JSON              NOT NULL,

    -- Пути относительно каталога кадров, а не сами файлы: картинки в базе
    -- раздувают дамп и бэкап, а читаются по одной — ручкой раздачи.
    `shot_path`       VARCHAR(255)      NOT NULL DEFAULT '',
    `shot_plain_path` VARCHAR(255)      NOT NULL DEFAULT '',

    -- Что страница сказала в консоль: красная ошибка при внешне целом кадре
    -- означает, что часть обработчиков не навесилась, — кадр этого не покажет.
    `console_json`    JSON                       DEFAULT NULL,

    `error`           TEXT                       DEFAULT NULL,
    `duration_ms`     INT UNSIGNED      NOT NULL DEFAULT 0,

    -- UTC, как всё время здесь: в пояс настройки `timezone` переводит страница.
    `created_at`      DATETIME          NOT NULL DEFAULT CURRENT_TIMESTAMP,

    PRIMARY KEY (`id`),
    KEY `idx_test_e2e_run` (`run_uuid`),
    KEY `idx_test_e2e_name_created` (`name`, `created_at`),
    KEY `idx_test_e2e_created` (`created_at`)
) ENGINE = InnoDB
  DEFAULT CHARSET = utf8mb4
  COLLATE = utf8mb4_general_ci;


-- Выключатель отдельного случая: что гонять, а что пока не трогать.
--
-- ЗАЧЕМ. Случай может шуметь: страница перестроилась, селектор ещё не поправлен,
-- а прогон каждую ночь красит отчёт красным. Красный тест, который никто не
-- чинит, вреднее отсутствующего — на него перестают смотреть, и вместе с ним
-- перестают смотреть на соседние.
--
-- ⚠⚠ Признак в БАЗЕ, а не в самом YAML. Файлы случаев одни на все установки:
-- выключив случай в файле, выключаешь его и на проде, и у разработчика разом, —
-- а гасят их как раз порознь. Плюс правка файла требует выкладки, то есть
-- погасить ночной шум в три часа ночи нечем.
--
-- ⚠ Ключ — ИМЯ ФАЙЛА случая, а не его название: название правят ради
-- формулировки, и привязка выключателя терялась бы молча.
--
-- ⚠ Строки нет — случай ВКЛЮЧЁН. Заводится она только переключателем, поэтому
-- новый случай работает сразу, без строки и без миграции.

CREATE TABLE IF NOT EXISTS `test_e2e_case`
(
    `case_file`  VARCHAR(190) NOT NULL,
    `enabled`    TINYINT(1)   NOT NULL DEFAULT 1,

    -- Название на момент переключения — копией: показать в отчёте, что именно
    -- выключено, если файл случая тем временем переименовали или унесли.
    `name`       VARCHAR(190) NOT NULL DEFAULT '',

    `updated_at` DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP
                              ON UPDATE CURRENT_TIMESTAMP,

    PRIMARY KEY (`case_file`)
) ENGINE = InnoDB
  DEFAULT CHARSET = utf8mb4
  COLLATE = utf8mb4_general_ci;
