-- Описание собеседника: русские подписи прежних снимков → английские (2026-10-13)
--
-- ЗАЧЕМ. `companion.about` хранит строки «Подпись: значение», и подписи ставил
-- `companion_about_text` по-русски: «О себе», «Увлечения», «Занятие». Читателей у
-- этого текста двое, и обоим нужен английский:
--
--   * агент — текст уезжает переменной `companion_bio` в английский промпт (узел
--     Dating у соседа объявляет `en`), и русский абзац внутри модель читает как
--     чужой кусок, подстраивая под него язык ответа;
--   * человек — поле «Описание» на вкладке «Информация» стоит ровно напротив
--     собранного Bio, и две подписи у одной строки («О себе» слева, «About
--     Myself» справа) заставляют переводить глазами туда и обратно.
--
-- Код уже исправлен: новые снимки ложатся сразу английскими. Эта миграция про
-- накопленное — переснимается карточка раз в две недели
-- (`companion_about_every`), и без неё «починено» значило бы «починено у новых».
--
-- ⚠⚠ ЗАМЕНА ПРИВЯЗАНА К НАЧАЛУ СТРОКИ, а не идёт по всему тексту. Голый
-- `REPLACE(about, 'Дети: ', 'Children: ')` сработал бы и внутри рассказа
-- человека — «пишет про Дети: …» в чужих словах не редкость. Приём: приписываем
-- перевод строки спереди, меняем только `\n<подпись>: `, потом приписанное
-- снимаем. Подпись в середине строки при этом не совпадает никогда.
--
-- ⚠ Семь подписей — ровно `COMPANION_ABOUT_FIELDS` в коде. Разойдись списки, и
-- непереведённую подпись подхватит `companion_about_english` на лету: карта
-- перевода остаётся жить как раз на этот случай и на вписанное руками.
--
-- ⚠ Идемпотентна: английская подпись ни одному из `\n<рус>: ` не равна, второй
-- прогон не делает ничего.
--
-- ⚠ `about` правили и руками. Правка человека — свободный текст, и её подписи
-- (если они есть) под замену не попадут: совпадение требуется точное, вместе с
-- двоеточием и пробелом. Это намеренно — выдуманный перевод чужих слов хуже
-- оставленного как есть.

UPDATE companion
SET about = TRIM(LEADING '\n' FROM
    REPLACE(
      REPLACE(
        REPLACE(
          REPLACE(
            REPLACE(
              REPLACE(
                REPLACE(CONCAT('\n', about),
                  '\nО себе: ',             '\nAbout Myself: '),
                '\nУвлечения: ',            '\nHobby: '),
              '\nЗанятие: ',                '\nOccupation: '),
            '\nОбразование: ',              '\nEducation: '),
          '\nСемейное положение: ',         '\nMarital Status: '),
        '\nДети: ',                         '\nChildren: '),
      '\nРелигия: ',                        '\nReligion: '))
WHERE about LIKE '%О себе: %'
   OR about LIKE '%Увлечения: %'
   OR about LIKE '%Занятие: %'
   OR about LIKE '%Образование: %'
   OR about LIKE '%Семейное положение: %'
   OR about LIKE '%Дети: %'
   OR about LIKE '%Религия: %';
