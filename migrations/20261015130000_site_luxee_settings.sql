-- Сайт Luxee: описание для чтения панели (2026-10-15)
--
-- ЗАЧЕМ. Luxee пришёл в список сайтов снимком с соседской закладки, но имени
-- и адреса для чтения панели мало: панель читается драйвером, а драйвер
-- выбирается по ключу `driver` в описании (`site_registry.py`), и без него
-- кнопка «Обновить с сайта» отвечает «панель этого сайта читать нечем». Это
-- ровно та грабля, которую уже пережил Ladadate (миграция 20261012230000 —
-- тогда достаточно было дописать ключ в готовое описание; здесь описания нет
-- вовсе, заводим его целиком).
--
-- Три ключа — три двери, и все три нужны анкете Luxee:
--   presence  — что за сайт и каким драйвером его читать (база для всех четырёх
--               реестров: панель, чат, анкета, собеседник);
--   admin_url — страница анкеты в кабинете после входа (кнопка ходит в неё по
--               сессии, api.md §3.11);
--   admin_mark — примета кабинета: по ней форма входа считается кабинетом.
--
-- ⚠ Отбор по адресу сайта, а не по номеру: `site_id` — номер закладки у соседа,
-- и на другой установке за ним стоит другой сайт. Адрес же принадлежит самому
-- сайту.
--
-- ⚠ `presence` — строка JSON внутри JSON-колонки, а не вложенный объект
-- (читалка `json_column_load` ждёт строку; объект стал бы словарём там, где
-- ждут строку). Отсюда CAST(... AS CHAR).
--
-- ⚠ Строка может прийти от синка и без описания вовсе (закладка соседа пуста) —
-- отсюда COALESCE: JSON_SET по NULL вернул бы NULL.
--
-- Идемпотентность: пишем только туда, где ключей ещё нет.

-- ---------------------------------------------------------------- До
SELECT 'ДО' AS этап, site_id, name, IFNULL(CAST(settings AS CHAR), '(без описания)') AS описание
  FROM site
 WHERE is_gone = 0 AND url LIKE '%luxee%'
 ORDER BY site_id;

UPDATE site
   SET settings = JSON_SET(COALESCE(settings, JSON_OBJECT()),
        '$.presence', CAST('{"base": "https://luxee.io", "driver": "luxee"}' AS CHAR),
        '$.admin_url', 'https://luxee.io/profiles',
        '$.admin_mark', 'StarAgency')
 WHERE is_gone = 0
   AND url LIKE '%luxee.io%'
   AND NOT JSON_CONTAINS_PATH(COALESCE(settings, '{}'),
        'one', '$.presence', '$.admin_url', '$.admin_mark');

-- ---------------------------------------------------------------- После
SELECT 'ПОСЛЕ' AS этап, site_id, name, CAST(settings AS CHAR) AS описание
  FROM site
 WHERE is_gone = 0 AND url LIKE '%luxee%'
 ORDER BY site_id;
