-- Переменные для сайта, рождённого после переменных (Luxee, 2026-10-16)
--
-- ЗАЧЕМ. Реестр переменных собирается по сайтам одним приёмом: каждая прежняя
-- миграция вставляла свою переменную всем сайтам, у которых на момент прогона
-- были анкеты (`SELECT DISTINCT site_id FROM profile` — «анкеты означают, что с
-- сайтом работают»). Luxee пришёл в список позже всех пяти заходов и под этот
-- приём не попал ни в один: вкладка «Переменные» в его анкетах читает реестр по
-- номеру сайта, реестра нет — и человек видит «на этом сайте переменных не
-- заведено», хотя письмо собирается у всех сайтов одинаково.
--
-- ⚠ МНОЖЕСТВО ОДНО НА ВСЕХ. Пять строк — ровно тот канон, что лежит у прежних
-- сайтов, подписи слово в слово взяты из тех четырёх миграций
-- (`20260907030000` базовые две, `20260907060000` вопрос, `20260911160000`
-- части имени, `20260912140000` переезд имён на нижнее подчёркивание). Укладка
-- в один запрос, а не четыре, — только потому, что здесь это один разговор:
-- набор переезжает целиком, по одному краю не докачаешь.
--
-- ⚠ ОТБОР ПО АНКЕТАМ, А НЕ ПО НОМЕРУ САЙТА. Номер закладки — чужая и чужая: на
-- другой установке за ним стоит другой сайт (здесь Luxee под `.com` вообще не
-- значится). Анкеты — признак тот же, что у четырёх прежних миграций.
--
-- У анкеты на вкладке видно только `profile` (`girl_name`), остальные четыре —
-- companion и live — едут в письмо при отправке и в карточке не живут
-- (`mail_var.py`); заводятся молча и молча же участвуют, `uses` пустой.
--
-- Идемпотентность: вставка по условию отсутствия — строки прежних сайтов не
-- трогаются вовсе, дописывается только недостающее.

-- ---------------------------------------------------------------- До
SELECT 'ДО' AS этап, s.site_id,
       (SELECT COUNT(*) FROM `mail_var` v WHERE v.site_id = s.site_id) AS переменных
  FROM (SELECT DISTINCT site_id FROM `profile`) s
 ORDER BY s.site_id;

-- ------------------------------------------- Канон для сайтов без реестра
INSERT INTO `mail_var` (`site_id`, `name`, `source`, `title`, `default_value`)
SELECT s.site_id, v.name, v.source, v.title, ''
  FROM (SELECT DISTINCT site_id FROM `profile`) s
  JOIN (                               -- тот же порядок, что у прежних четырёх
          SELECT 'girl_name' AS name, 'profile' AS source,
                 'Имя девушки, от которой письмо' AS title
          UNION ALL
          SELECT 'companion_name', 'companion', 'Имя получателя письма'
          UNION ALL
          SELECT 'question_to_companion', 'live',
                 'Вопрос получателю про его интересы — сочиняется при отправке'
          UNION ALL
          SELECT 'companion_first_name', 'companion',
                 'Имя собеседника без фамилии — первое слово. Пусто, если делить нечего'
          UNION ALL
          SELECT 'companion_last_name', 'companion',
                 'Фамилия собеседника — всё после первого пробела. Пусто, если пробела нет'
       ) v
 WHERE NOT EXISTS (SELECT 1 FROM `mail_var` w
                    WHERE w.site_id = s.site_id AND w.name = v.name);

-- ---------------------------------------------------------------- После
SELECT 'ПОСЛЕ' AS этап, s.site_id,
       (SELECT COUNT(*) FROM `mail_var` v WHERE v.site_id = s.site_id) AS переменных
  FROM (SELECT DISTINCT site_id FROM `profile`) s
 ORDER BY s.site_id;
