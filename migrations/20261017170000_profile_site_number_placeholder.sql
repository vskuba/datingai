-- Номер на сайте и почта, записанные статусом «WAIT:» (2026-10-17)
--
-- ЗАЧЕМ. Анкету STELA за 2026-10-16 завёл импорт: карточка девушки на странице
-- `userprofiles` висела с плашкой статуса «WAIT:» (ждём фото), и шаг `номер`
-- прогона снял текст плашки вместо номера анкеты. Так «WAIT:» легло и в логин
-- учётки, и в `id` карточки:
--
--   колонка login   = «WAIT:»   (на сайте у неё storojnicencostela@gmail.com)
--   ключ id в JSON  = «WAIT:»   (номер на сайте — 458262)
--
-- Кнопка «Обновить с сайта» на этом спотыкается молча: `profile_panel_read`
-- берёт uid из карточки, GET `…/userprofile/edit/WAIT:` — и панель отвечает 400
-- с пустым телом. Человек видит «С сайта не снялось: панель ответила 400» и не
-- может узнать, что номеру анкеты просто нечем было быть числом.
--
-- ⚠ Правятся ОБА места номера разом («номер на сайте — в двух сразу»: колонка
-- `profile_id` — первый источник читателей, ключ `id` карточки — второй; см.
-- `agent.py`, `agent_site_uid`). Колонка до правки была NULL, как и у пяти
-- соседних анкет того импорта — номер жил только в JSON.
--
-- ⚠ Логин — половина ключа, которым агент помнит анкету. Здесь это не разъезд:
-- ключом анкету держит `girl_id` — номер сайта (см. ⚠⚠⚠ в докстринге
-- `agent_vars`), а разговором анкета на нём пока не висит.
--
-- Идемпотентность: UPDATE целится только в строки, где `id` карточки всё ещё
-- «WAIT:»; второй прогон не находит ни одной и не делает ничего.

-- ---------------------------------------------------------------- До
SELECT 'ДО' AS этап, id, site_id, login,
       JSON_UNQUOTE(JSON_EXTRACT(profile, '$.id')) AS `номер в карточке`
  FROM profile
 WHERE JSON_UNQUOTE(JSON_EXTRACT(profile, '$.id')) = 'WAIT:';

-- ------------------------------------------------------- анкета STELA
UPDATE profile
   SET profile    = JSON_SET(profile, '$.id', '458262'),
       profile_id = '458262',
       login      = 'storojnicencostela@gmail.com'
 WHERE JSON_UNQUOTE(JSON_EXTRACT(profile, '$.id')) = 'WAIT:';

-- ---------------------------------------------------------------- После
SELECT 'ПОСЛЕ' AS этап, id, site_id, login, profile_id,
       JSON_UNQUOTE(JSON_EXTRACT(profile, '$.id')) AS `номер в карточке`
  FROM profile
 WHERE id = 10315706;
