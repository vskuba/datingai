-- База текстов инвайтов: сочиняем один раз, раздаём по сроку (2026-10-23)
--
-- ЗАЧЕМ. Инвайты набираются каждые несколько минут, и каждый заход звал агента:
-- пул при пустом расходе жёг вызовы LLM впустую, а тексты всё равно кончаются —
-- модель повторяет любимые обороты, и через неделю новый шаблон не отличим от
-- старого глазами. Инвайт живёт у мужчины около пятнадцати минут, потом его не
-- читает никто. Значит текст — не расходник, а заготовка: сочинил один раз,
-- выдаёшь по кругу, выждал срок.
--
-- Таблица собирает коллекцию уникальных текстов сайта. Круг сначала роется здесь
-- и зовёт агента только на нехватку; когда коллекция дорастает до того, что
-- каждый текст отлежал срок, вызовы LLM сходят на нет — это и есть разгрузка
-- движка. Срок задаёт настройка `invite_reuse_hours` (0 — не переиспользовать,
-- сочинять каждый заход, как было до этой таблицы).
--
-- ⚠ ПОЧЕМУ СВОЯ ТАБЛИЦА, А НЕ КОЛОНКА В `invite`. У `invite` строка — это
-- **пара** «девушка — собеседник» с готовой репликой, именами внутри и судьбой
-- (черновик, ушло, отказ); строк тысячи, и одна и та же рамка лежит в них
-- полусотней копий с разными именами. Здесь строка — **сам текст**, один раз на
-- сайт. Смешать — значит считать уникальность по столбцу, который мутирует
-- подстановка. Раздельные таблицы читаются каждая по-своему; имя `invite_draft`
-- подчёркивает: это заготовки, а не карточки.
--
-- ⚠ `body_key` — MD5 НОРМАЛИЗОВАННОГО ТЕКСТА, а не UNIQUE по `body`. TEXT в
-- ключ MySQL не пускает (только префикс, а префикс путает тексты, различающиеся
-- в хвосте), а сравнение должно быть таким же, как в `invite_templates_check`:
-- регистр и пробелы человек не различит. Ключ считает код (`invite._text_key`);
-- дубль не долетает до вставки, его убирает `INSERT IGNORE` на месте.
--
-- ⚠ `used_at` — ВРЕМЯ ПОСЛЕДНЕЙ ВЫДАЧИ, а не сочинения. По нему круг и решает,
-- можно ли текст отдать снова; при выдаче он и обновляется. Для свежевставленного
-- текста это одно и то же: сочинили — значит тут же раздали.
--
-- ⚠ `lang` — ЯЗЫК ТЕКСТА. Смена `answer_language` у сайта вывела бы старый
-- текст в чужой язык — фильтр сайта такое отклоняет, а мы бы держали мертвечину
-- в обороте до истечения срока. Строки старой языковой ветки остаются в базе
-- (вернёшь язык — вернётся и коллекция), но не выдаются.
--
-- ⚠ ЧИСТКИ НЕТ, И ЭТО РЕШЕНИЕ. `invite_clean_hours` подчищает карточки пар —
-- здесь другой предмет: текст в этой таблице не мусор, а сырьё. Коллекция
-- растёт, пока агент не начнёт повторяться, и стоит.
--
-- Идемпотентность: таблица заводится по условию отсутствия.

-- ---------------------------------------------------------------- До
SELECT 'ДО' AS этап,
       (SELECT COUNT(*) FROM information_schema.TABLES
         WHERE TABLE_SCHEMA = DATABASE()
           AND TABLE_NAME = 'invite_draft') AS таблица_есть;

-- ------------------------------------------------- База текстов
CREATE TABLE IF NOT EXISTS `invite_draft` (
    `id` INT NOT NULL AUTO_INCREMENT,
    `site_id` INT NOT NULL COMMENT 'Сайт-закладка: тексты одного сайта не уходят другому',
    `lang` VARCHAR(10) NOT NULL DEFAULT ''
        COMMENT 'Язык, на котором текст сочинён: в чужой язык не выдаётся',
    `body` TEXT NOT NULL COMMENT 'Шаблон реплики с метками — ровно то, что вернул агент',
    `body_key` CHAR(32) NOT NULL
        COMMENT 'MD5 нормализованного текста; нормализация — та же, что у invite_templates_check',
    `used_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
        COMMENT 'Когда текст выдали последний раз; по нему решается повтор',
    `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
        COMMENT 'Когда текст сочинён. Для повтора не смотрим: у него есть used_at',
    PRIMARY KEY (`id`),
    -- ⚠ Один нормализованный текст — одна строка **на сайт и язык**. Язык в
    -- ключе не для порядка: без него тот же текст, законно рождённый в другом
    -- языке, не вставился бы вовсе, и этот язык не получил бы его никогда.
    -- Гонка между кругом и кнопкой решается здесь, а не проверкой в коде:
    -- `INSERT IGNORE` второй экземпляр не пустит, и дубль не зайдёт ни при
    -- каком раскладе.
    UNIQUE KEY `uq_invite_draft` (`site_id`, `lang`, `body_key`),
    -- Отбор захода: «самые давние годные тексты этого сайта и языка» — на
    -- каждое пополнение пула.
    INDEX `idx_invite_draft_take` (`site_id`, `lang`, `used_at`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ---------------------------------------------------------------- После
--
-- ⚠ Таблица пуста, и это правильно: наполняет её первый же набор — по старой
-- дороге, через агента. Заливать сюда при накате нечего.
SELECT 'ПОСЛЕ' AS этап,
       (SELECT COUNT(*) FROM `invite_draft`) AS текстов;
