-- Лента гостей: кто заходил к анкетам сайта (2026-10-27)
--
-- ЗАЧЕМ. Рассылку составляют, глядя на ленты собеседников, и одна из них —
-- «Гости»: люди, которые заходили на анкету. Это самый тёплый список из всех:
-- человек уже проявил интерес, в отличие от ленты «Все онлайн», где просто
-- кто-то в сети. Раньше на вкладке «Письма рассылка» ряд «Гости» был — пустым
-- словом из шаблона: наполнять его было нечем.
--
-- Таблица копит гостей **по всем анкетам сайта разом**: анкета заходит в свой
-- кабинет, снимает страницу гостей и оставляет строку на каждого. Лента сайта —
-- union этих строк: один и тот же человек мог заходить к трём анкетам, и в ленте
-- он стоит один раз, со свежей из дат. Так лента честно отвечает на вопрос «кто
-- вообще заходил к нашему агентству», а не «к выбранной анкете».
--
-- ⚠ ПОЧЕМУ СВОЯ ТАБЛИЦА, А НЕ КОЛОНКА В `companion`. Карточка `companion` —
-- про **человека** сайта: имя, фото, анкета. Гость — про **событие**: человек N
-- заходил к анкете M. У одного человека сотни событий по анкетам, и в карточку
-- их не сложить — карточка одна, а анкет, куда он заходил, много. Строка здесь
-- ровно одна на пару «анкета — человек»; дата — последняя из виденных.
--
-- ⚠ ПОЧЕМУ ЗДЕСЬ НЕТ ИМЕНИ И ФОТО. Их держит `companion`, и одна пара
-- «сайт + номер» лежит там один раз (ключ `uq_dating_companion`). Дублировать их
-- сюда значило бы иметь два ответа на «как его зовут», расходящихся с первой же
-- правки. Круг заводит карточку дверью `companion_save`, а здесь остаётся
-- только факт визита.
--
-- ⚠ ВЫКЛЮЧЕННЫЕ АНКЕТЫ. Строки гостят от анкеты, а лента — сайта: в неё попадают
-- строки **всех** анкет, включая выключенные. Витрина выключенной анкеты всё ещё
-- стоит на сайте, и гости у неё бывают; снял мы строки выключенных — лента
-- врала бы, что этих людей не было.
--
-- ⚠ ЧИСТКИ НЕТ, и это решение, а не недоделка: гость — факт, а не расходник,
-- факты не стирают по сроку. Растёт таблица медленно — по числу реальных визитов.
--
-- Идемпотентность: таблица заводится по условию отсутствия.

-- ---------------------------------------------------------------- До
SELECT 'ДО' AS этап,
       (SELECT COUNT(*) FROM information_schema.TABLES
         WHERE TABLE_SCHEMA = DATABASE()
           AND TABLE_NAME = 'companion_guest') AS таблица_есть;

-- ------------------------------------------------- Строка: визит к анкете
CREATE TABLE IF NOT EXISTS `companion_guest` (
    `id` INT NOT NULL AUTO_INCREMENT,
    `site_id` INT NOT NULL COMMENT 'Сайт-закладка: лента собирается по сайту, а не по анкете',
    `profile_id` INT NOT NULL COMMENT 'Анкете которой гость. Выключенные анкеты в ленте остаются',
    `uid` VARCHAR(32) NOT NULL COMMENT 'Номер человека на сайте; тот же, что у companion.uid',
    `visit_at` DATE DEFAULT NULL
        COMMENT 'Дата визита со страницы гостей; NULL — страница даты не показала',
    `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
        COMMENT 'Когда гость увиден впервые',
    PRIMARY KEY (`id`),
    -- Один человек у одной анкеты — одна строка. Повторный визит обновляет
    -- дату, а не заводит второго близнеца: гонку двух заходов ловит этот ключ,
    -- а не проверка в коде.
    UNIQUE KEY `uq_companion_guest` (`profile_id`, `uid`),
    -- Сбор ленты: «все гости сайта, свежие сверху». Дедупликация по человеку —
    -- уже в запросе ленты, здесь только порядок обхода.
    INDEX `idx_companion_guest_site` (`site_id`, `visit_at`),
    -- Отбор круга: «самые свежие гости анкеты» — по нему круг берёт анкету и
    -- режет список лимитом `mailing_guests_max`.
    INDEX `idx_companion_guest_profile` (`profile_id`, `visit_at`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ---------------------------------------------------------------- После
--
-- ⚠ Таблица пуста, и это правильно: наполняет её круг гостей — у сайтов, где в
-- «Активных лентах» стоит галочка «Гости» и у соседа заведён сценарий.
SELECT 'ПОСЛЕ' AS этап,
       (SELECT COUNT(*) FROM `companion_guest`) AS гостей;
