-- Поля анкеты собеседника целиком (2026-10-28)
--
-- ЗАЧЕМ. Карточка собеседника помнила о человеке шесть колонок — имя, возраст,
-- город, страну, почту и описание. Страница профиля на сайте говорит о нём
-- куда больше: дату рождения, цели знакомства, языки, внешность, финансовое
-- положение, «о себе», цели на будущее, любимую еду. Раньше из этого в карточку
-- шло только то, о чем можно спросить письмом (`companion.about`), а остальное
-- выбрасывалось на разборе — спросить про это было нечем, и агент выдумывал.
--
-- Колонка `params` — JSON «подпись → значение»: **всем снятым полем**, каким бы
-- они ни были. Подписи — английские, как на странице (тот же выбор, что у
-- `companion.about`: ключ поля переживёт перевод интерфейса и смену вёрстки).
-- Русские подписи для человека отдаёт реестр `companion_param.py` сервером, а не
-- копиями на странице.
--
-- ⚠ ПОЧЕМУ JSON, А НЕ КОЛОНКИ. Наборов полей у сайтов два, и они не совпадают
-- (у Ladadate «Hair Color», у Step2Love «Hair length» плюс анкетные вопросы), а
-- новых сайтов будет больше. Под каждую пару колонок — миграция; здесь одна
-- колонка на все подписи, а порядок показа и подпись по-русски задаёт реестр.
--
-- ⚠ ЗДЕСЬ НЕТ того, что уже лежит колонками: имени, возраста, города и страны
-- (у них своя жизнь в списках), номера и почты. Дубль означал бы два ответа на
-- один вопрос, расходящихся с первой же правки.
--
-- ⚠ ПОРЯДОК КЛЮЧЕЙ внутри JSON MySQL хранит по-своему (JSON — двоичное дерево);
-- показ всегда проходит через `companion_param_frame`, который задаёт порядок
-- реестром, — ровно как у параметров девушки (`profile_param.py`).

ALTER TABLE companion
    ADD COLUMN params JSON NULL COMMENT 'поля страницы анкеты: подпись сайта → значение' AFTER about;
