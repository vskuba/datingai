-- Step2Love: лента «Все онлайн» ходит раз в полчаса, а не в две минуты (2026-10-28)
--
-- ЗАЧЕМ. Лента Step2Love снимается **сценарием**, и каждый её заход начинается со
-- входа в панель агентства: сценарий не знает готовой сессии, он входит каждый
-- раз заново (шаги `login/` → `billing.php` → `my_profiles.php`). Панель считает
-- попытки входа и на лишней молча отвечает «You have exceeded the login attempt
-- limit» — форма входа остаётся пустой, кнопки автологина нет, и прогон спотыкается
-- на шаге с кнопкой. Темп в две минуты — 30 входов в час — уложил панель за полтора
-- часа: прод молчал с 10:55, локальная установка с 10:15 того же дня (одна учётка
-- на двоих — лимит общий), лист ленты показывал вчерашних 12 человек.
--
-- ЧАСЫ. Два входа в час — к двенадцати входам в час проверки входящих
-- (`chat_check_every` в пять минут; он исторически тянул панель без жалоб):
-- суммарно ~14 входов в час — меньше того, что панель терпела, пока ленты со
-- своим входом вовсе не было. Полчаса здесь — страховка, а не лень: «кому писать
-- сейчас» решается по ленте полчаса как снятой — это лучше, чем по ленте, которая
-- встала на ночь.
--
-- ⚠ Отбор по адресу сайта, а не по номеру: `site_id` — номер закладки у соседа,
-- и на другой установке за ним стоит другой сайт. Адрес принадлежит самому сайту.
--
-- ⚠ Пишем только туда, где ключа ещё нет: человек мог задать свой темп на
-- странице «Сайты», и миграция его право не перебивает.
--
-- Идемпотентность: второй заход не меняет ничего.

-- ---------------------------------------------------------------- До
SELECT 'ДО' AS этап, site_id, name,
       JSON_UNQUOTE(JSON_EXTRACT(settings, '$.online_check_every')) AS темп_ленты
  FROM site
 WHERE is_gone = 0 AND url LIKE '%mystep2love.com%';

UPDATE site
   SET settings = JSON_SET(COALESCE(settings, JSON_OBJECT()),
        '$.online_check_every', '1800')
 WHERE is_gone = 0 AND url LIKE '%mystep2love.com%'
   AND JSON_EXTRACT(settings, '$.online_check_every') IS NULL;

-- ---------------------------------------------------------------- После
SELECT 'ПОСЛЕ' AS этап, site_id, name,
       JSON_UNQUOTE(JSON_EXTRACT(settings, '$.online_check_every')) AS темп_ленты
  FROM site
 WHERE is_gone = 0 AND url LIKE '%mystep2love.com%';
