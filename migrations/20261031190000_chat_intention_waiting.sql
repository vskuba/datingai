-- Намерение ждёт доставки: обещание есть только у сказанного (2026-10-31)
--
-- ⚠⚠⚠ ЗАЧЕМ. Намерение заводилось **по ответу прогона**, то есть до отправки.
-- Размен был назван в коде прямо («лечится позже отметкой доставки») и лечения
-- не дождался. Цена вскрылась живьём: инициатива Olga → Benoit в 17:08 не
-- ушла — сайт ответил `IsSuccess:false`, — а намерение «пришлю фото письмом»
-- записалось и встало в пул.
--
-- Дальше было бы хуже самой потери: круг собрал бы письмо со снимком и
-- отправил человеку, который обещания **не слышал**. Для него это письмо из
-- ниоткуда.
--
-- Правило теперь одно: **карточка намерения — только для доставленного**.
--
-- ⚠⚠ НОВОЕ СОСТОЯНИЕ, А НЕ УДАЛЕНИЕ НЕДОСТАВЛЕННЫХ. Намерение, чья реплика
-- ещё не ушла, — это не ошибка: у писем между сочинением и отправкой проходят
-- часы, и всё это время строка законно ждёт. Удаляй мы её, повторная отправка
-- той же реплики осталась бы без обещания.
--
-- ⚠ `waiting` ключ `uq_chat_intention_open` НЕ занимает: он построен на
-- `IF(status = 'open', intention, NULL)`, и ждущие строки для него невидимы.
-- Это верно — два ожидания подряд законны, а одно открытое по-прежнему одно.
--
-- ⚠⚠ Но свой ключ ждущим нужен, и он ВКЛЮЧАЕТ НОМЕР ОБМЕНА
-- (`uq_chat_intention_wait`). Агент метит одно обещание на каждой реплике,
-- пока оно висит в истории; без ключа такие строки плодились бы пачками.
-- Включи мы в ключ только пару и метку — вторая реплика не завела бы строки
-- вовсе, и доставка **её** обмена не нашла бы, что открывать: у лежащей номер
-- от первой реплики, которая могла и не уйти.
--
-- ⚠⚠ `message_id` — номер обмена разговора у соседа, и он здесь ключ связи:
-- по нему намерение находит свою реплику, когда та уйдёт. Пара «анкета +
-- собеседник» для этого не годится — у неё может быть несколько обменов
-- подряд, и доставка одного открыла бы чужое обещание.
--
-- ⚠ Ноль законен и значит «обмена нет»: агент промолчал либо прогон ушёл в
-- «Тишину». Такое намерение не откроется никогда — и правильно, потому что
-- реплики, в которой оно дано, не существует.

SELECT 'ДО' AS этап,
       (SELECT COUNT(*) FROM `chat_intention`) AS намерений,
       (SELECT COUNT(*) FROM `chat_intention` WHERE `status` = 'open') AS открытых,
       (SELECT COUNT(*) FROM `information_schema`.`COLUMNS`
         WHERE `TABLE_SCHEMA` = DATABASE() AND `TABLE_NAME` = 'chat_intention'
           AND `COLUMN_NAME` = 'message_id') AS колонка_уже;

-- 1. Третье состояние. ⚠ `MODIFY` сохраняет накопленное: ни одна строка не
--    меняет значения, меняется только набор допустимых.
ALTER TABLE `chat_intention`
  MODIFY COLUMN `status` ENUM('waiting', 'open', 'done') NOT NULL DEFAULT 'open'
    COMMENT 'waiting — реплика ещё не ушла; open — ждёт исполнения; done — исполнено';

-- 2. Номер обмена, по которому намерение узнаёт свою реплику.
SET @есть = (SELECT COUNT(*) FROM `information_schema`.`COLUMNS`
              WHERE `TABLE_SCHEMA` = DATABASE()
                AND `TABLE_NAME` = 'chat_intention'
                AND `COLUMN_NAME` = 'message_id');

SET @sql = IF(@есть = 0,
  'ALTER TABLE `chat_intention`
     ADD COLUMN `message_id` INT NOT NULL DEFAULT 0
       COMMENT ''Номер обмена у соседа: по нему намерение открывается, когда реплика ушла''
       AFTER `intention`,
     ADD KEY `ix_chat_intention_message` (`message_id`, `status`),
     ADD UNIQUE KEY `uq_chat_intention_wait`
       (`profile_id`, `uid`, `intention`, `message_id`)',
  'SELECT ''колонка уже есть — пропуск'' AS пропуск');

PREPARE st FROM @sql;
EXECUTE st;
DEALLOCATE PREPARE st;

-- ⚠⚠ Накопленное НЕ переводим в `waiting`: эти намерения заведены по старому
-- правилу, их реплики давно ушли либо нет, и узнать это уже нечем. Оставляем
-- как есть — человек разберёт их корзинкой, а новые пойдут по новому правилу.

SELECT 'ПОСЛЕ' AS этап,
       (SELECT COUNT(*) FROM `information_schema`.`COLUMNS`
         WHERE `TABLE_SCHEMA` = DATABASE() AND `TABLE_NAME` = 'chat_intention'
           AND `COLUMN_NAME` = 'message_id') AS колонка_стала,
       (SELECT COUNT(*) FROM `chat_intention` WHERE `status` = 'open') AS открытых_осталось;
