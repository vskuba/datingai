-- Счётчик чата на вкладке сайта перестаёт перебирать всю переписку (2026-10-31)
--
-- ЗАЧЕМ. Вкладки сайтов в шапке раздела показывают четыре счётчика и
-- обновляются раз в пятнадцать секунд. Три из четырёх стоят меньше миллисекунды,
-- а четвёртый — реплики чата за полсуток (`site_live._chat`) — **56,8 мс**:
--
--     EXPLAIN … type: ALL, key: NULL, rows: 41931
--
-- То есть на каждый тик читалась **вся** таблица переписки целиком, ради того
-- чтобы найти в ней горстку свежих строк.
--
-- ⚠⚠ ВЕДУЩАЯ КОЛОНКА — `created_at`, А НЕ `direction`, и это решили измерения,
-- а не привычка ставить равенство первым:
--
--     всего строк      43 782
--     direction = 'in' 42 519   ← 97%, не отсекает ничего
--     за 12 часов          22   ← 0,05%, отсекает всё
--
-- Индекс, ведомый `direction`, уткнулся бы в те же сорок две тысячи строк: под
-- значением `in` лежит почти вся таблица. Работу делает именно срок.
--
-- ⚠ `direction` второй колонкой всё же нужен: он снимает лишние чтения строк
-- внутри найденного промежутка и пригодится, когда входящих станет не 97%.
--
-- ⚠⚠ Индекс **не уникальный** — на накопленных данных он не может отказать по
-- повторам. Это важно после сегодняшней аварии: уникальный ключ на колонке с
-- общим для всех значением уронил панель на девять минут
-- (`20261031190000_chat_intention_waiting.sql`). Здесь такой беды нет по
-- устройству, а не по удаче.
--
-- ⚠ Прежние четыре индекса не трогаем: все они ведомы `profile_id` и отвечают
-- на вопрос «переписка этой пары», то есть на другой вопрос. Этому запросу
-- анкета не задана вовсе — он считает по всем сразу.
--
-- ЦЕНА. Пятый индекс — это лишняя запись на каждую вставку реплики. Она
-- оплачена с запасом: читают таблицу раз в пятнадцать секунд при открытой
-- панели, а пишут в неё редко — на живом сайте три входящих за восемь часов.
--
-- ИЗМЕРЕНО на копии прода (43 572 реплики), до и после:
--
--     _chat         15,3 мс → 0,4 мс     (type=ALL, rows=42773 → type=range, rows=1)
--     весь заход    24,6 мс → 2,0 мс
--
-- ⚠ Ответ при этом тот же: счёт с `FORCE INDEX` и с `IGNORE INDEX` на широком
-- окне сошёлся до строки (42 110 и 389).

SELECT 'ДО' AS этап,
       (SELECT COUNT(*) FROM `message`) AS реплик,
       (SELECT COUNT(DISTINCT `INDEX_NAME`) FROM `information_schema`.`STATISTICS`
         WHERE `TABLE_SCHEMA` = DATABASE() AND `TABLE_NAME` = 'message'
           AND `INDEX_NAME` = 'idx_dating_message_live') AS индекс_уже;

SET @есть = (SELECT COUNT(DISTINCT `INDEX_NAME`) FROM `information_schema`.`STATISTICS`
              WHERE `TABLE_SCHEMA` = DATABASE()
                AND `TABLE_NAME` = 'message'
                AND `INDEX_NAME` = 'idx_dating_message_live');

SET @sql = IF(@есть = 0,
  'ALTER TABLE `message`
     ADD KEY `idx_dating_message_live` (`created_at`, `direction`)',
  'SELECT ''индекс уже есть — пропуск'' AS пропуск');

PREPARE st FROM @sql;
EXECUTE st;
DEALLOCATE PREPARE st;

SELECT 'ПОСЛЕ' AS этап,
       (SELECT COUNT(DISTINCT `INDEX_NAME`) FROM `information_schema`.`STATISTICS`
         WHERE `TABLE_SCHEMA` = DATABASE() AND `TABLE_NAME` = 'message'
           AND `INDEX_NAME` = 'idx_dating_message_live') AS индекс_стал,
       (SELECT COUNT(*) FROM `message`) AS реплик_осталось;
