-- Письма, написанные человеком на сайте: забор из панели агентства (2026-11-26)
--
-- ЗАЧЕМ. Иногда живой оператор отвечает мужчине прямо на сайте, минуя нас: зашёл,
-- напечатал, отправил — и письмо помечено отвеченным, а нас в нём нет. Сайт API
-- отправленных писем не показывает вовсе, и круг ответов видел бы его письмо
-- неотвеченным стал бы отвечать вторым: мужчина получил бы две реплики подряд,
-- одну живым стилем, другую агентом (решение владельца 26.11.2026).
--
-- ЧТО. `mail_human` — её письма, привезённые со страницы истории пары в
-- панели агентства (`usermessagehistory/{её номер}?id2={его номер}`), которых
-- нет в наших пулах отправки: их написал на сайте живой оператор от её имени.
-- Дорога — `src/dating/mail_human.py`.
--
-- ⚠ СВОЯ ТАБЛИЦА, а не `mail_reply`. `mail_reply` — наш пул: у него статусы,
-- время отправки, доставка и круг, который по нему ходит. Письмо человека у нас
-- не сочинялось и не отправлялось; положить его в пул значило бы протащить
-- `status` и круг отправки через строку, к которой они не имеют отношения.
--
-- ⚠ УНИКАЛЬНЫЙ КЛЮЧ (`profile_id`, `message_id`): забор приходит на одну
-- страницу истории не один раз — по новой его причине повторная копия письма
-- заведена быть не должна.
--
-- ⚠ `history_at` — отметка доклада соседу, тем же смыслом, что у `message`:
-- NULL — не доставлено, попробуется следующим кругом; ставится **только** по
-- успешному ответу соседа (ноль у него — отказ, а не «уже было»).
--
-- ⚠ `profile_id` с каскадом: удалили анкету — её переписка уходит с ней. То же
-- правило, что у входящих писем.
--
-- Идемпотентность: таблица по условию отсутствия.

-- ---------------------------------------------------------------- До
SELECT 'ДО' AS этап,
       (SELECT COUNT(*) FROM information_schema.TABLES
         WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'mail_human') AS таблица_есть;

-- ------------------------------------------- Письма человека на сайте
CREATE TABLE IF NOT EXISTS `mail_human` (
    `id`         INT  NOT NULL AUTO_INCREMENT,
    `site_id`    INT  NOT NULL COMMENT 'Сайт-закладка: по нему доклад соседу и отбор круга',
    `profile_id` INT  NOT NULL COMMENT 'Под чьей анкетой написано письмо: наша анкета',
    `uid`        VARCHAR(32)  NOT NULL DEFAULT '' COMMENT 'Кому: его номер на сайте',

    -- ⚠ Номер письма **на сайте**, а не наш: им забор сверяет повторные
    -- приходы той же страницы. Два наших номера одного письма задвоили бы и
    -- доклад соседу, и строку в разговоре.
    `message_id` BIGINT NOT NULL COMMENT 'Номер письма на сайте: ключ повтора забора',

    `body` TEXT NOT NULL COMMENT 'Текст письма, каким его отдаёт страница истории',

    -- ⌛ Часы страницы истории. Замер 26.11.2026 (письмо 853634242): время
    -- страницы совпадает с `mail_in.date_post`, то есть UTC; сверка с нашими
    -- письмами идёт с допуском на всякий размен часов.
    `date_post` DATETIME NULL COMMENT 'Когда написано — страница истории, по замеру UTC',

    `attachment` VARCHAR(500) NOT NULL DEFAULT '' COMMENT 'Ссылка на первый снимок из вложений письма; пусто — вложений нет',

    -- ⚠ Смысл тот же, что у `message.history_at`: отметка ставится по успеху
    -- доклада, NULL — сосед ждёт свою строку.
    `history_at` DATETIME NULL COMMENT 'Когда доклад уехал соседу; NULL — не уехал',

    `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,

    PRIMARY KEY (`id`),
    -- Повтор забора той же страницы: тот же номер письма — та же строка.
    UNIQUE KEY `uq_mail_human` (`profile_id`, `message_id`),
    -- Недокладанные строки: круг ищет их по сайту, свежие первыми.
    KEY `idx_mail_human_site` (`site_id`, `history_at`),
    KEY `fk_mail_human_profile` (`profile_id`),
    CONSTRAINT `fk_mail_human_profile` FOREIGN KEY (`profile_id`)
        REFERENCES `profile` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci
  COMMENT='Её письма, написанные живым человеком прямо на сайте: страница истории панели';

-- ---------------------------------------------------------------- После
SELECT 'ПОСЛЕ' AS этап,
       (SELECT COUNT(*) FROM information_schema.TABLES
         WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'mail_human') AS таблица_стала,
       (SELECT COUNT(*) FROM `mail_human`) AS писем;
