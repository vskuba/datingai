"""Каталог прав установки: какие права бывают и что входит в роль.

Механизм проверки живёт в общем скелете (`py_modules/panel_/`), а **имена прав**
— здесь и только здесь: `tool_rules.md`, §1 запрещает предметное знание в общем
слое, и «какие права бывают у панели знакомств» это ровно оно.

## ⚠⚠ Каталог нарочно мелкий, и это честно

Сегодня у панели один вопрос про доступ: пускать ли к устройству установки —
seed, бэкапы, люди, настройки. Всё остальное неделимо: кто видит переписку
анкеты, тот на неё и отвечает.

Поэтому прав ровно два, по числу настоящих различий. Расписать каталог на
`profile:view`, `profile:edit`, `mail:send` сейчас значило бы завести полсотни
имён, каждое из которых есть у обеих ролей, — список, который ничего не
разделяет, но выглядит как разделение. Это хуже отсутствия прав: по нему начнут
принимать решения.

**Признак дробить**: появилась роль, которой доступна *часть* предметных страниц.
С ней права заводятся по месту, а не заранее.

## ⚠ Роль `operator` отличается от `admin` ровно одним правом

На этом держится `is_admin`: полнота роли — совпадение набора прав с каталогом
(`docs-common/panel.md`, §1). Дай оператору оба права, и он станет полноправным
молча.
"""

from enum import Enum

from dashboard.src.panel.panel_access import PanelAccess

# Как зовутся роли. ⚠ Имена уезжают в столбец `user.role` и в куку сессии: это
# не ярлыки для страницы, а значения в базе.
AUTH_ACCESS_ROLE_ADMIN = 'admin'
AUTH_ACCESS_ROLE_OPERATOR = 'operator'


class AuthPermission(str, Enum):
    """Права установки. ⚠ Значение уезжает в проверки — менять его нельзя."""

    # Обычная работа панели: анкеты, переписка, письма, журналы. Неделима
    # намеренно — см. ⚠⚠ в заголовке.
    PANEL_WORK = 'panel:work'

    # Устройство установки: seed, бэкапы, люди, настройки, веб-морда к базе.
    # ⚠ Это не предметная операция, и названо оно соответственно: вопрос тут не
    # «что ты делаешь», а «отвечаешь ли ты за установку».
    INSTALL_MANAGE = 'install:manage'


# Что входит в роль. ⚠ Полноправие определяется совпадением с полным каталогом,
# поэтому `admin` здесь не перечисляется поимённо — он получает всё.
AUTH_ACCESS_ROLE_PERMISSIONS = {
    AUTH_ACCESS_ROLE_ADMIN: frozenset(AuthPermission),
    AUTH_ACCESS_ROLE_OPERATOR: frozenset({AuthPermission.PANEL_WORK}),
}


class AuthAccess(PanelAccess):
    """Договор доступа этой установки — отвечает скелету панели."""

    def permissions_all(self) -> frozenset:
        return frozenset(AuthPermission)

    def permissions_of(self, role: str) -> frozenset:
        """Права роли. ⚠ Незнакомая роль получает пустой набор, а не набор
        оператора: роль в базе может оказаться какой угодно, и трактовать
        «непонятно что» как работника значит пускать по опечатке."""
        return AUTH_ACCESS_ROLE_PERMISSIONS.get(str(role or ''), frozenset())

    def roles_all(self) -> frozenset:
        """Список закрытый: роли здесь не заводятся на ходу, и опечатка `admn`
        завела бы учётку, которая не может ничего, а выглядела бы рабочей."""
        return frozenset(AUTH_ACCESS_ROLE_PERMISSIONS)

    def role_admin(self) -> str:
        return AUTH_ACCESS_ROLE_ADMIN

    def role_operator(self) -> str:
        return AUTH_ACCESS_ROLE_OPERATOR
