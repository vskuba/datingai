"""Задание-страховка: смена держателя чатов ставится, если её нет.

Смену ставит себе сама предыдущая, а при старте — uvicorn
(`chat_worker_recover`). Оба способа отказывают в одном и том же случае:
**лёг сам uvicorn**. Тогда поставить новую смену некому, и панель выглядит
живой, пока никто не замечает, что сообщений нет.

Это задание и есть та страховка. Звать его часто — нормально: ключ
single-flight делает повторный вызов бездействием, а не вторым держателем на
те же сокеты (`chat_worker_enqueue`). Два держателя одной учётки — это два
соединения, и сайт вышибает оба.

## ⚠⚠ Пять месяцев оно не работало

В расписании Cronicle задание стояло и запускалось каждые пять минут — но
било в ручку **соседа**, прося исполнить файл из нашего репозитория. У соседа
такого файла нет: каждый прогон отвечал `400 Файл src/cronjob/dating_chat.py
не найден`. Страховка, о которой написано в `worker.md`, не сработала ни разу.

Чинится это вместе: своя дверь `POST /cronjob` у панели и этот файл рядом с
ней (`src/cronjob/cronjob.py`).

## Запуск

    POST /cronjob {"job": "dating_chat"}

Разумный срок — те же пять минут. Чаще незачем: смена живёт своей жизнью, а
задание лишь проверяет, что она есть.
"""

import asyncio
import sys
from pathlib import Path

# Задание запускается отдельным процессом по пути к файлу, и корня проекта в
# `sys.path` у него нет — чинит это он сам, первыми строками.
sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from logging_.logging_ import logger_exception  # noqa: E402 — после починки пути
from src.dating.error import error_catch_install  # noqa: E402
from mysql_.mysql_ import mysql_pool_close  # noqa: E402

from src.worker.dating.chat_worker import chat_worker_enqueue  # noqa: E402


async def main() -> None:
    """Поставить смену, если её нет; сказать словом, что вышло.

    ⚠ Молчит, когда смена уже идёт: это **обычный** исход, а не новость.
    Печатай мы «смена уже идёт» каждые пять минут, журнал Cronicle перестали
    бы читать — и пропустили бы ту единственную строку, ради которой он нужен.
    """
    # ⚠ Застава журнала: падение задания прежде видел только `app.log`.
    error_catch_install('cronjob')

    try:
        job = chat_worker_enqueue()
        if job:
            print(f'смена держателя поставлена заново: {job}')
    except Exception as err:  # noqa: BLE001 — заданию нельзя падать молча
        logger_exception(f'[cronjob] страховка смены не сработала: {err}')
        raise
    finally:
        # Пул закрываем сами: процесс живёт один прогон, и оставленные
        # соединения копились бы по одному на каждые пять минут.
        await mysql_pool_close()


if __name__ == '__main__':
    asyncio.run(main())
