"""Задание E2E: снять страницы панели и записать вердикты.

## Запуск

Через Cronicle — он живёт у соседа и стучится в нашу дверь `/cronjob`:

    POST /cronjob {"job": "e2e_run", "timeout": 900}

Раз в сутки, в ночное окно. Чаще незачем: случаи стерегут вёрстку и содержимое
страниц, а те меняются выкладками, а не минутами.

## ⚠⚠ Зачем вообще расписание, если есть кнопка

Кнопка отвечает на вопрос «сломал ли я это сейчас», и на него отвечает тот, кто
помнит, что менял. Расписание отвечает на другой: «сломалось ли что-нибудь,
пока никто не смотрел». Пока прогон шёл только по кнопке, красное на проде не
видел никто — а оно там было: страница E2E не работала вовсе, и нашлось это
случайно.

## ⚠⚠ Сроки матрёшкой, и порядок обязателен

Задание (900) < HTTP-запрос Cronicle (950) < само событие (1000). Разойдись они
в другую сторону — Cronicle оборвал бы связь на живой работе и посчитал её
провалившейся: в ленте красное, в базе честные вердикты, и разбираться придётся
с несуществующей бедой.

⚠ Срок щедрый не зря: на случай × ширину приходится запуск Chrome, а сквозной
случай снимает **две** панели — нашу и соседа.

⚠ Контейнер-браузер этому прогону не нужен: Chromium есть в самом контейнере
приложения (ставится при сборке образа). Общий пул вкладок соседа не занимается.

Устройство — `.claude/docs/e2e.md`, каркас — `py_modules/tests_e2e/`.
"""

import asyncio

from logging_.logging_ import logger_exception, logger_info
from mysql_.mysql_ import mysql_pool_close

from dashboard.src.page.e2e.e2e_run import e2e_run_all
from src.dating.error import error_catch_install


async def main() -> None:
    """Точка входа задания: прогон и строка в журнал с его итогом."""
    # ⚠ Застава журнала: падение задания прежде видел только `app.log`.
    error_catch_install('cronjob')

    try:
        got = await e2e_run_all()
        # ⚠ Говорим ВСЕГДА, в отличие от галереи рядом, которая молчит на
        # пустом заходе. Там новость — что нашлось; здесь новость — что
        # проверка состоялась. Молчание прогона неотличимо от «не запускался»,
        # а это ровно тот вопрос, ради которого он заведён.
        logger_info(f"🧪 E2E: тестов {got['tests']}, провалов {got['failed']}, "
                    f"сорвалось {got['errored']}"
                    + (f", выключено {got['skipped']}" if got.get('skipped') else ''))
    except Exception as err:  # noqa: BLE001 — заданию нельзя падать молча
        logger_exception(f'E2E: прогон по расписанию сорвался: {err}')
    finally:
        # Пул закрываем сами: задание живёт один прогон, и оставленные
        # соединения копились бы по одному на каждую ночь.
        await mysql_pool_close()


if __name__ == '__main__':
    asyncio.run(main())
