# Сколько диалогов отвечаем за раз. Каждый — прогон workflow, и полсотни разом
# превратили бы кнопку в получасовое ожидание.
ANSWER_LIMIT = 5

# Через сколько тишины инициатор пишет снова. Три минуты: раньше — похоже на
# нетерпеливого робота, позже — разговор рвётся. Считается от последней реплики
# в диалоге, чья бы она ни была.
ANSWER_NUDGE_SEC = 180

# Роль, которая ведёт разговор: пишет первой и возвращается после тишины.
ANSWER_ROLE_LEAD = 'man'

# Через сколько повторно спрашивать агента про то же сообщение, если он промолчал.
# Меньше — трата LLM на одно и то же, больше — собеседник ждёт слишком долго.
ANSWER_RETRY_SEC = 300

# Сколько первых реплик пары обязаны получить ответ — настройка сайта и её
# умолчание. ⚠ Судья у соседа вправе промолчать, и обычно это верно; но в
# начале разговора молчание обрывает то, что мы сами и начали инвайтом.
ANSWER_ANYWAY_FIRST_SETTING = 'chat_answer_anyway_first'
ANSWER_ANYWAY_FIRST_DEFAULT = 5

# Язык ответа. Не вкусовщина: фильтр сайта отклоняет кириллицу — «Message not
# delivered. Unacceptable words: …», — поэтому русский ответ агента до собеседника
# просто не дойдёт. Язык задаётся сайтом (`presence.answer_language`), а здесь
# лишь разумное умолчание.
ANSWER_LANGUAGE = 'en'


async def answer_run(profile: dict, presence: dict, agent_id: int,
                            limit: int = ANSWER_LIMIT) -> dict:
    """Отвечает тем, чьё сообщение осталось без ответа.

    Args:
        profile: строка `profile`.
        presence: настройка сайта — из неё берётся отправка.
        agent_id: агент анкеты, который сочиняет ответ.
        limit: сколько диалогов обработать за раз.

    Returns:
        dict: `asked` — сколько раз спросили агента, `sent` — сколько ответов
        ушло, `silent` — сколько раз агент промолчал, `offline` — сколько
        собеседников вышли из чата, `drafted` — сколько ответов написано
        впрок, `errors` — что не вышло.

    ⚠ `asked` и `sent` больше не равны даже в удачном заходе: ответ пишется
    одним кругом, а уходит другим — тем, что застал собеседника в сети.
    """
    profile_id = int(profile['id'])
    # Имя анкеты для журнала: строки всех анкет там вперемешку, и «→ Semen» без
    # отправителя не говорит, кто ответил.
    me = _me_name(profile)
    language = str(presence.get('answer_language') or ANSWER_LANGUAGE)
    only = _only_parse(profile.get('auto_answer_only'))
    lead = str(profile.get('role') or '') == ANSWER_ROLE_LEAD
    # ⚠ Порог обязательности спрашиваем **до** отбора: он в нём и участвует —
    # «отвечать всегда» не должно упираться в порог свежести.
    anyway_first = await _anyway_first(int(profile.get('site_id') or 0))
    waiting = await _waiting_find(profile_id, limit, only, lead)
    if not waiting:
        await log_write(profile_id, 'info',
                               'Продолжать разговор пока не нужно' if lead
                               else 'Неотвеченных сообщений нет')
        return {'asked': 0, 'sent': 0, 'silent': 0, 'offline': 0,
                'drafted': 0, 'errors': []}

    await log_write(profile_id, 'info', f'Поводов написать: {len(waiting)}')

    asked = sent = silent = offline = drafted = 0
    errors = []

    for row in waiting:
        uid = str(row['sender_uid'])
        # Имя **с номером**: имена собеседников повторяются десятками («три Natalia
        # в списке — обычное дело»), и по одному имени в журнале не понять, с кем
        # разговор.
        name = str(row['sender_name'] or '').strip()
        who = f'{name} {uid}' if name else f'#{uid}'

        # ⚠⚠ **Черновик уже есть — значит текст написан, и платить снова не за
        # что.** В этом вся затея: собеседник появился, а ответ ему уже лежит.
        # Прежде он ждал ещё круг и десяток секунд на LLM.
        #
        # Спрашиваем **по поводу** (`row['id']`), а не по паре: написал он снова —
        # повод другой, черновика по нему нет, и мы сочиним свежий ответ, а не
        # отправим заготовленный на позавчерашнее.
        ready = await chat_reply_waiting(profile_id, int(row['id']))

        if not ready:
            # ⚠⚠ **Вопрос — это слова собеседника, и только они.** Промпт у
            # соседа так и объявляет: «=== %companion_title% пишет ===
            # %prompt_user%». Клади мы туда задание («Продолжи разговор…»),
            # модель прочла бы нашу инструкцию как сказанное человеком, а шаг
            # записи положил бы её в переписку от его имени.
            #
            # Пусто — законный исход: последним говорили мы, он молчит.
            question = str(row['text']) if row.get('direction') == 'in' else ''

            # ⚠ Молчит — значит заговариваем первыми, и сказать об этом надо
            # **флагом**, а не текстом вопроса. Флаг уводит заход веткой
            # «Инициатива», у которой задание «заговори» написано в промпте;
            # прежде ветку выбирал текст, и потому он был обязателен.
            first = not question

            # Попытку отмечаем до вопроса, а не после: прогон длится минуты, и
            # круг успел бы начаться заново, спросив агента о том же во второй раз.
            await _tried_mark(profile_id, uid)

            # ⚠⚠ «Здесь молчать нельзя» — решаем мы, а не агент. У соседа это
            # переменная `answer_anyway`: она не отменяет проверку ответа, а
            # закрывает судье путь молчания (`wf_dating_talk_answer_anyway`).
            #
            # ⚠ Историю разговора спрашивать тут не нужно: обе — чат и письма —
            # берёт сам `_agent_ask`. Прежде её добывали три места перед вызовом,
            # и с появлением второго канала они разошлись бы.
            anyway = await _anyway_here(profile_id, uid, anyway_first)
            answer, error = await _agent_ask(agent_id, question, language, profile,
                                             uid=uid, anyway=anyway, name=name,
                                             initiative=first)
            asked += 1
            if error:
                errors.append(f'{who}: {error}')
                await log_write(profile_id, 'fail',
                                f'Агент не ответил для {who}: {error}')
                continue

            if not answer:
                # ⚠ **Молчание — решение, и его надо запомнить.**
                #
                # Прежде ставилась только отметка попытки, а `is_answered`
                # оставался нулём: значок «нужен ответ» мигал вечно, а круг
                # спрашивал агента снова каждые пять минут — тот снова молчал, и
                # молчание стоило денег на LLM в цикле.
                #
                # `is_answered` для этого не годится: он означает «мы отправили
                # ответ», и диалог выглядел бы закрытым без единого нашего слова.
                # Поэтому своя метка — она же и время, для показа в переписке.
                silent += 1
                await _silent_mark(profile_id, uid)
                await log_write(profile_id, 'info',
                                f'{me} → {who}: агент решил не отвечать')
                continue

            # ⚠⚠ **Сторож чужого имени, и стоит он до укладки в пул.**
            #
            # Беда, ради которой он заведён, была тихой: ответ грамотный, к месту,
            # по-английски — и с обращением «ok vadim» к человеку по имени Gerard.
            # Ни код ответа, ни журнал о ней не сказали; заметил её человек,
            # прочитав текст. Имя приходило из справочника соседа, потому что
            # своего мы не передавали.
            #
            # Передача имени дыру закрыла, но следующая правка промптов или
            # справочника на той стороне откроет её снова — и узнаем мы тем же
            # способом, случайно. Поэтому текст с чужим именем не уходит вовсе:
            # лучше промолчать, чем написать живому человеку не его именем.
            alien = companion_ref_foreign(answer, companion_title(name, uid))
            if alien:
                errors.append(f'{who}: в ответе чужое имя «{alien}»')
                await log_write(
                    profile_id, 'fail',
                    f'Не отправлено {me} → {who}: в ответе чужое имя «{alien}» — '
                    f'«{answer[:120]}»')
                continue

            reply_id = await chat_reply_put(int(profile.get('site_id') or 0),
                                            profile_id, int(row['id']), uid,
                                            name, answer)
            drafted += 1
            ready = {'id': reply_id, 'body': answer}

        # ⚠ **Отправляем только тому, кто в сети.** Сайт либо отклонит сообщение,
        # либо примет его в пустоту, а повод написать никуда не денется: черновик
        # лежит и уйдёт, как только человек вернётся.
        #
        # Проверка стоит **после** сочинения, а не до, и это перемена: прежде
        # офлайн означал «даже не спрашиваем агента». Текст теперь готовится
        # заранее — ради этого всё и делалось.
        if not online_check(int(profile.get('site_id') or 0), uid)['online']:
            # ⚠ В журнал — молча. Повод тот же, текст тот же, круг ходит раз в
            # минуту: за ночь это тысяча одинаковых строк, в которых утонуло бы
            # всё остальное. Ждущий черновик и так виден в разговоре.
            offline += 1
            continue

        answer = str(ready['body'])
        result = await send_message(profile, presence, uid, answer)
        if result['ok']:
            sent += 1
            await chat_reply_sent(int(ready['id']))
            await log_write(profile_id, 'out', f'{me} → {who}: «{answer[:300]}»')
        elif result.get('offline'):
            # Собеседник вышел из чата между проверкой и отправкой. Ошибкой это не
            # считаем: он вернётся, и черновик уйдёт — теперь уже без нового
            # вызова LLM.
            offline += 1
            await log_write(profile_id, 'info', f'{who}: нет в чате, отвечу когда вернётся')
        else:
            errors.append(f"{who}: {result['error']}")
            # ⚠ Черновик остаётся в пуле с причиной, а не хоронится: повод написать
            # жив, и следующий круг повторит попытку тем же текстом.
            await chat_reply_failed(int(ready['id']), result['error'])
            # ⚠ Текст и при отказе: без него не видно, что именно не ушло, и
            # нельзя решить — повторять или сообщение всё-таки дошло.
            await log_write(
                profile_id, 'fail',
                f"Не ушло: {me} → {who} «{answer[:120]}» — {result['error']}")

    await log_write(
        profile_id, 'ok',
        f'Ответы: спрошено {asked}, написано {drafted}, отправлено {sent}, '
        f'промолчал {silent}, нет в чате {offline}, ошибок {len(errors)}')

    return {'asked': asked, 'sent': sent, 'silent': silent, 'offline': offline,
            'drafted': drafted, 'errors': errors}


# Вид письма — он же имя ветки у соседа. ⚠ Значения знает развилка
# `transitions_before` шага «Ответ в чат»: разойдись они, письмо ушло бы веткой
# чата и вышло репликой в двадцать слов.
ANSWER_MAIL_WRITE = 'write'
ANSWER_MAIL_REPLY = 'reply'

# Длина письма: жребий на каждое. ⚠⚠ **Просить «пиши по-разному» бесполезно** —
# это записанный опытом закон проекта, а не осторожность. Пока длину задавала
# вилка в промпте («от одного абзаца до трёх»), из двенадцати писем прода девять
# вышли ровно в три абзаца: у вилки верх читается как цель.
#
# ⚠ Жребий здесь был и раньше — `FAVORITE_MAIL_LENGTHS` шаблонной эпохи, с той же
# оговоркой «однообразие длины видно так же, как однообразие слов». Переезд писем
# на `dating_talk` унёс шаблон вместе с ним; это возврат, а не новшество.
#
# ⚠ Слова, а не число: «два абзаца по 40–60 слов» модель исполняет точно, а «2»
# требует догадки, сколько это слов.
ANSWER_MAIL_LENGTHS = (
    'один абзац — 40–60 слов',
    'два абзаца — по 40–60 слов каждый',
    'три абзаца — по 40–60 слов каждый',
)


def answer_mail_length() -> str:
    """Длина очередного письма — одна из `ANSWER_MAIL_LENGTHS`.

    ⚠ Отдельной функцией, а не `random.choice` по месту: жребий один на оба
    письма (первое и ответ), и вторая копия разошлась бы с первой на первой же
    правке вилки.
    """
    return random.choice(ANSWER_MAIL_LENGTHS)


async def answer_mail_write(agent_id: int, profile: dict, uid: str,
                            language: str, name: str = '') -> tuple[str, str]:
    """Письмо избранному, который замолчал. Возвращает (текст, ошибка).

    Args:
        agent_id: агент **писем** этого сайта (`fav_mail_<сайт>`). ⚠ Не агент
            чата: workflow у них общий, а системный промпт разный — тот про
            реплики, этот про письма.
        profile: анкета девушки, от чьего имени письмо.
        uid: собеседник на сайте.
        language: язык письма — настройка сайта.
        name: его имя, как его видит панель.

    Returns:
        tuple: текст письма и ошибка. Пустой текст без ошибки — агент промолчал;
        для письма это негодный исход, и решает его вызывающий.

    ## ⚠⚠ Почему письмо пишет workflow чата, а не свой

    Избранный — человек, **с которым уже говорили**: звёздочку ставят тому, кто
    отвечал. Прежний `dating_favorite_mail_write` не знал о нём ничего — ни
    имени, ни разговора, ни фактов, — и промпт там прямо запрещал ссылаться на
    прошлое. Живому человеку это читалось ровно так, как есть: женщина, с
    которой он переписывался, пишет ему как незнакомому.

    `dating_talk` видит переписку, ищет факты о нём, о ней и о договорённостях —
    то есть пишет письмо тому, кого знает.

    ## ⚠⚠ Цена размена названа прямо

    Было: **один** вызов на заход, шаблон раскладывался по парам подстановкой
    имени. Стало: вызов **на каждое письмо**, и каждый дороже — `dating_talk`
    обращается к модели до четырёх раз плюс подпрогоны фактов.

    Десять писем за заход — сорок-шестьдесят вызовов вместо одного. Это и есть
    плата за письмо, которое не выглядит рассылкой; дешевле её не бывает:
    персональное письмо нельзя написать, не прочитав переписку.

    ⚠ **Отбор и пределы стоят до этого вызова** (`favorite_mail.py`): каждое
    письмо дорого, и платить за него ради того, чтобы выбросить, незачем.
    """
    return await _agent_ask(
        int(agent_id), '', str(language or ''), profile,
        uid=str(uid), name=str(name or ''),
        # ⚠⚠ **Письмо, а не инициатива.** У той свой смысл — «собеседник
        # молчит, пишем первыми **репликой в чат**», и попади письмо в её ветку,
        # оно получило бы «до 25 слов, как в мессенджере».
        mail=ANSWER_MAIL_WRITE,
        # ⚠ Молчать нельзя: заход набора пула стоил отбора и вызова модели, и
        # пустой ответ тратит его впустую.
        anyway=True)


async def answer_mail_reply(agent_id: int, profile: dict, uid: str,
                            language: str, name: str = '') -> tuple[str, str]:
    """Ответ на пришедшее письмо. Возвращает (текст, ошибка).

    Args:
        agent_id: агент **ответов** этого сайта (`mail_reply_<сайт>`). ⚠ Свой, а
            не тот, что пишет первым: workflow общий, промпты разные — там
            «заговори», здесь «ответь».
        profile: анкета девушки, от чьего имени ответ.
        uid: собеседник на сайте.
        language: язык ответа — настройка сайта.
        name: его имя, как его видит панель.

    Returns:
        tuple: текст ответа и ошибка. Пустой текст без ошибки — агент промолчал.

    ## ⚠⚠ Зачем переписан: письмо и чат были разными людьми

    Прежде ответы писал свой workflow (`dating_mail_reply`), и переписку он
    получал **своим** запросом — из трёх таблиц, не зная про письма избранным
    вовсе. Чата же он не видел ни строкой: человек, с которым девушка вчера
    переболтала весь вечер в чате, получал ответ от той, кто про этот вечер не
    помнит.

    Теперь ответ идёт общим `dating_talk`, и агенту доезжают **обе** истории —
    чат и письма, — но собирает их сам сосед из `companion_session`. Отличается
    только системный промпт агента: у `fav_mail_*` он про «напиши первой», у
    этого — про «ответь на письмо».

    ⚠ Само письмо в вопрос не кладём — и вопрос здесь **пуст** вовсе: письмо уже
    последней строкой в ленте писем, а `prompt_user` означает «что сказал
    собеседник».
    """
    return await _agent_ask(
        int(agent_id), '', str(language or ''), profile,
        uid=str(uid), name=str(name or ''),
        # ⚠ Своя ветка у соседа: «отвечай на то, что он написал», а не
        # «заговори первой».
        mail=ANSWER_MAIL_REPLY,
        # ⚠ Молчать нельзя: человек написал письмо и ждёт ответа. В чате
        # молчание законно, здесь оно читается как «его игнорируют».
        anyway=True)


# Доли, которыми жребий у соседа правит разнообразие письма: ключ настройки
# сайта → имя переменной вызова и умолчание долей (0..1).
#
# ⚠⚠ **Жребий бросает сосед, а настройки живут здесь** — и это не половинчатость,
# а разделение по смыслу. «Сколько писем с именем» — дело сайта: у одного
# агентства так принято, у другого иначе, и крутит это человек на странице сайта.
# А «какие бывают зачины» — дело промпта, и лежит оно рядом с промптом.
#
# ⚠ Ключи переменных с приставкой `dice_`: у соседа так зовётся всё, что ведёт
# жребий, и по имени в промпте видно, что значение бросили, а не прислали.
ANSWER_DICE_PERCENTS = (
    ('favorite_mail_name_percent', 'dice_mail_name_percent', 0.10),
    ('favorite_mail_question_percent', 'dice_mail_question_percent', 0.25),
    ('favorite_mail_story_percent', 'dice_mail_story_percent', 0.40),
)


async def _dice_percents(site_id) -> dict:
    """Доли настроек сайта — переменными вызова для шага «Жребий».

    ⚠ Шлём **всегда**, а не только для писем: лишняя переменная у соседа ничего
    не стоит, а «слать или не слать» — это ещё одно условие, которое однажды
    разойдётся с тем, какие ветки ими пользуются.

    ⚠⚠ Сбой чтения даёт **умолчание, а не ноль**: ноль значит «никогда», и
    принять такое решение молча из-за недоступной базы нельзя — письма пошли бы
    все на одно лицо, и причину искали бы в промпте.
    """
    return {name: await percent_value(int(site_id or 0), key, default)
            for key, name, default in ANSWER_DICE_PERCENTS}


async def _agent_ask(agent_id: int, question: str, language: str,
                     profile: dict,
                     uid: str = '', anyway: bool = False,
                     # ⚠ Флаг, а не приём. Прежде сюда клали текст приёма
                     # («пошути коротко») — жребий бросала панель; теперь его
                     # бросает шаг «Жребий» у соседа, и отсюда нужен один ответ:
                     # заговорить первой или отвечать на сказанное.
                     name: str = '', initiative: bool = False,
                     mail: str = '') -> tuple[str, str]:
    """Спрашивает агента в RhapsodyAi. Возвращает (ответ, ошибка).

    Пустой ответ ошибкой не считается — он значим сам по себе и разбирается выше:
    агент может намеренно промолчать.

    ⚠ **Историю берём здесь, а не у вызывающего.** Звали три места — чат,
    инициатива, письмо, — и каждое спрашивало её само перед вызовом. Каналов
    стало два, и три копии «спроси историю» разошлись бы на первой правке: одно
    место отдавало бы обе, другое по-прежнему чат. Вопрос «что агент знает о
    человеке» принадлежит этой точке.

    ⚠ **Кто говорит — задаётся переменными вызова, а не агентом.** Отвечает один
    универсальный агент на все анкеты (`agent.py`), и без `girl_name` он
    назовётся значением по умолчанию, а без `girl_id` сложит факты всех девушек в
    один документ. Наши переменные в сборке у соседа идут последними и перекрывают
    его собственные.

    Ходим служебным токеном, а не заголовками того, кто нажал кнопку: в RhapsodyAi
    пользователей этого проекта нет, и представляться там надо своей учёткой.
    """
    from src.dating.agent import agent_bio, agent_vars
    from src.dating.companion_bio import companion_bio_text

    card = profile.get('profile')
    if isinstance(card, str):
        try:
            card = json.loads(card or '{}')
        except ValueError:
            card = {}

    try:
        answer = await rhapsody_api_chat_ask(
            agent_id, question,
            variables={'user_language': language,
                       # ⚠⚠ **Историю разговора отсюда больше не шлём.** Обе
                       # ленты — чат и письма — собирает сам сосед двумя шагами
                       # workflow из `companion_session`
                       # (`…_wf_talk_companion_session`), и туда же он кладёт
                       # каждый обмен. Дом у разговора один.
                       #
                       # Прежде ленту считали здесь из пяти своих таблиц и
                       # присылали готовым текстом. Пока она жила у нас, у соседа
                       # разговор оседал слепками — в `variables_start` каждого
                       # прогона и внутри собранных промптов, — и выбрать его по
                       # паре, времени или каналу было нельзя.
                       #
                       # ⚠⚠ Своего кода истории у панели больше нет:
                       # `talk_history.py` был единственным её читателем и удалён.
                       # Заводить второй не надо — он считал бы ленту из наших
                       # пяти таблиц, то есть из второго дома.
                       #
                       # ⚠⚠ Троица `companion_*` едет **в `variables`**
                       # (`companion_ref.companion_vars`, ниже): с правкой
                       # `remove_companion` сосед перестал подставлять её из
                       # запроса — что не прислали, то стало пустым default.
                       # Номер нужен шагу «Переменные»: из
                       # `%companion_id%_%companion_name%` он клеит ключ фактов.
                       # ⚠⚠ **Анкета собеседника — на случай, когда фактов о нём
                       # ещё нет.** Факты извлекает из переписки отдельный
                       # workflow, и в начале разговора извлекать нечего: агент
                       # писал человеку, не зная о нём ничего, хотя карточка у
                       # нас лежит. Промпт подставляет её **вместо** фактов, а не
                       # вместе с ними (`wf_dating_talk_companion_bio`): два
                       # источника об одном человеке расходятся, и модель взяла бы
                       # тот, что удобнее фразе.
                       'companion_bio': await companion_bio_text(
                           profile.get('site_id'), uid),
                       # ⚠⚠ **И её собственная анкета — на тот же случай.**
                       # Факты о девушке придумывает `girl_fact_invent` и копит
                       # от разговора к разговору; у новой анкеты их нет вовсе, и
                       # она отвечала бы, не зная о себе ничего. Промпт берёт
                       # анкету, **только если** не нашлось ни одним из двух
                       # поисков (`wf_dating_talk_girl_bio`).
                       #
                       # ⚠ Тот же `agent_bio`, что кладёт биографию при заведении
                       # агента: один сборщик на оба случая — иначе агент знал бы
                       # о себе одно, а отвечал по другому.
                       'girl_bio': agent_bio(card or {}),
                       # ⚠⚠ Кто именно пишет. Что не прислано — то пустой
                       # default, и факты леглись бы в общий документ безымянно
                       # (`companion_ref.py`).
                       **companion_vars(profile.get('site_id'), uid, name),
                       # ⚠ Строкой '1'/'0': у соседа `%if%` считает ложными
                       # пустое, '0' и отсутствие (`ai_workflow_variable_truthy`),
                       # а `False` превратился бы в 'False' — то есть в истину.
                       'answer_anyway': '1' if anyway else '0',
                       # ⚠⚠ Инициатива: шаг сочинения меняет задачу с
                       # «ответь» на «заговори» (`wf_dating_talk_initiative`).
                       #
                       # ⚠ Шлём **только повод**, а не приём. Приём («пошути»,
                       # «подколи», «расскажи историю») бросает жребий у соседа,
                       # шаг «Жребий» (`…_wf_talk_dice_common.sql`): двенадцать
                       # приёмов с весами переехали туда слово в слово. Здесь
                       # они лежали лишней копией договора — и разошлись бы с
                       # промптом на первой же правке.
                       'make_initiative': '1' if initiative else '0',
                       # ⚠⚠ Письмо, а не реплика. Строкой '1'/'0' — по тому же
                       # доводу, что у соседних флагов.
                       'mail_mode': '1' if mail else '0',
                       # ⚠⚠ **Какое именно письмо.** У соседа три ветки сочинения
                       # разными шагами (`…_wf_talk_branches.sql`), и развилка
                       # смотрит сюда: `reply` уводит на ответ, иначе `mail_mode`
                       # уводит на письмо первым.
                       #
                       # ⚠ Ветку выбирает переход **до** вызова модели, а не
                       # `%if%` внутри промпта: три задания в одном шаге текли
                       # друг в друга — инициатива получала два блока формата
                       # ответа и три JSON-примера.
                       'mail_kind': str(mail or ''),
                       # ⚠⚠ Длина письма приходит **готовой**, как и приём
                       # инициативы: жребий бросаем мы, а не просим модель быть
                       # разной. Вилка в промпте давала девять писем из двенадцати
                       # ровно в три абзаца — верх вилки читается как цель.
                       #
                       # ⚠ Жребий здесь, а не у вызывающих: писем два вида —
                       # первое и ответ, — и оба идут одной веткой промпта. Две
                       # копии броска разошлись бы, а третий вид письма про
                       # жребий просто забыл бы.
                       'mail_length': answer_mail_length() if mail else '',
                       **(await _dice_percents(profile.get('site_id'))),
                       **agent_vars(profile, card or {})})
    except RhapsodyError as e:
        return '', str(e)

    return answer, ''


def _me_name(profile: dict) -> str:
    """Имя анкеты с сайта — то, под которым её видит собеседник.

    Из JSON-столбца `profile`: анкета приходит от сайта целиком, и вытаскивать
    поля в свои колонки значило бы держать вторую копию. Нет имени — остаётся
    логин, он есть всегда.
    """
    card = profile.get('profile')
    if isinstance(card, str):
        try:
            card = json.loads(card or '{}')
        except ValueError:
            card = {}

    card = card or {}
    name = str(card.get('name') or '').strip()
    uid = str(card.get('id') or '').strip()

    if name:
        return f'{name} {uid}'.strip()

    return uid or str(profile.get('login') or '')


def _only_parse(value) -> list:
    """Список тех, кому разрешено отвечать. Пусто — ограничения нет."""
    return [part.strip() for part in str(value or '').replace(';', ',').split(',') if part.strip()]


async def _anyway_first(site_id: int) -> int:
    """Сколько первых реплик пары обязаны получить ответ. Настройка сайта.

    Ноль — выключено. Сбой чтения даёт умолчание: обязательный ответ в начале
    разговора — то поведение, ради которого настройку и заводили, и тихо терять
    его из-за сбоя чтения хуже, чем лишний раз ответить.
    """
    from src.uvicorn.routers.dating.site_ import site_seconds

    try:
        return max(0, int(await site_seconds(int(site_id or 0),
                                             ANSWER_ANYWAY_FIRST_SETTING)))
    except Exception as e:
        logger_info(f'[dating] порог обязательного ответа не прочитался: {e}')

        return ANSWER_ANYWAY_FIRST_DEFAULT


async def _anyway_here(profile_id: int, uid: str, first: int) -> bool:
    """Обязателен ли ответ этому человеку прямо сейчас.

    ## ⚠⚠ Считаем **его** реплики, а не наши

    Вопрос настройки — «сколько первых реплик разговора держим обязательными», и
    мерить его надо тем, что делает он: наших сообщений в паре может быть сколько
    угодно (инвайт, потом ещё инвайт), а разговором это станет с первого его слова.

    ⚠ Считается **по паре**. Один и тот же мужчина, отвечающий двум нашим девушкам,
    начинает два разговора, и каждому свой счёт: у второй девушки его первая
    реплика — тоже первая.

    ⚠ Сбой чтения отвечает «не обязателен»: обязательность — усиление, и включать
    её вслепую значило бы слать ответ там, где судья счёл бы его лишним.
    """
    if int(first or 0) <= 0:
        return False

    try:
        async with mysql_get_db_async() as db:
            await db.execute(
                'SELECT COUNT(*) AS n FROM message'
                " WHERE profile_id = %s AND sender_uid = %s AND direction = 'in'",
                (int(profile_id), str(uid or '')))
            row = await db.fetchone()
    except Exception as e:
        logger_info(f'[dating] счёт первых реплик не сложился: {e}')

        return False

    return int((row or {}).get('n') or 0) <= int(first)


async def _waiting_find(profile_id: int, limit: int, only: list, lead: bool) -> list:
    """Поводы написать: по одному на диалог.

    Смотрим последнюю реплику диалога, а не каждое сообщение: ответ на неё
    закрывает переписку целиком, а не одну строку.

    Отвечающему повод один — входящее без ответа. Ведущему разговор их два: то же
    входящее и **тишина**, когда последнее слово осталось за нами дольше
    `ANSWER_NUDGE_SEC`. Иначе после намеренного молчания собеседницы
    разговор кончается сам.

    `only` — кому разрешено писать. Отбор в запросе, а не после: иначе выборка
    «последних N» съедалась бы теми, кому писать нельзя, и разрешённый собеседник
    ждал бы своей очереди неизвестно сколько.
    """
    # Ждёт ответа то входящее, на которое мы не отвечали и про которое давно не
    # спрашивали агента. Второе условие — защита от повторов при молчании.
    #
    # ⚠⚠ **Возраст реплики больше не проверяется, и это осознанный откат.**
    #
    # Здесь стоял порог свежести: на привезённое из панели старше суток агент не
    # отвечал. Довод был такой: импорт за 60 дней приносит переписку разом, и без
    # порога первый же прогон дал бы десятки поводов написать по старым письмам.
    #
    # Довод не выдержал проверки. **Это чат, а не письма**: реплика адресная, она
    # не рассылается пачкой. А замер на живом проде показал цену порога — он
    # закрывал **одну** пару из одной: «с порогом 0, без порога 1».
    #
    # Зато вреда он приносил вдвое больше, чем виделось. Первая реплика Брайана
    # осталась без ответа, хотя настройка «отвечать всегда на первые пять» прямо
    # его обещала: порог отсекал пару **до** того, как считалась обязательность.
    # А написанный и оплаченный черновик не мог уйти, потому что его повод
    # состарился, пока адресат отсутствовал.
    #
    # ⚠ Вместе с порогом ушли и **две подпорки**, заведённые, чтобы его обходить:
    # послабление готовому черновику и послабление обязательному ответу. Сущность
    # породила две сущности — верный признак, что лишняя была первая.
    # ⚠ `answer_silent_at IS NULL` — «про это сообщение решения молчать не было».
    # Без него круг переспрашивал агента про то же сообщение до конца времён.
    #
    # Метка стоит на конкретных строках, а не на собеседнике: напишет он снова — у
    # новой строки она пуста, и агента спросят опять. Молчание относится к
    # сказанному, а не к человеку навсегда.
    # ⚠⚠ **Ноль означает «без порога», а не «ничего не свежее».**
    #
    # Подставь мы ноль в `INTERVAL %s SECOND`, условие стало бы «создано в
    # будущем» — то есть панельное не отвечалось бы никогда, ровно наоборот
    # написанному в подсказке настройки. Поэтому при нуле кусок про возраст в
    # запрос не попадает вовсе.
    # ⚠⚠ **Готовый черновик снимает **оба** запрета: и выдержку повтора, и порог
    # свежести панельного.** Оба сторожат **вызовы LLM** — «не спрашивай агента
    # про то же» и «не отвечай на древнее». У пары с написанным текстом спрашивать
    # уже нечего: осталась одна отправка, и она бесплатна.
    #
    # Поймано на проде: Yulia ↔ Brian. Реплика пришла из панели, ей стало сорок
    # девять часов при пороге в сутки — круг перестал брать пару, и готовый ответ
    # пролежал двое суток при собеседнике в сети. Мы заплатили за текст и не
    # отправили его.
    #
    # ⚠ Срока жизни у черновика нет: он висит, пока адресат не появится, — тогда
    # и уходит. Возраст повода роли не играет, потому что **ответ на реплику
    # один**: `is_answered` закрывает пару, и второй раз она в работу не попадёт.
    #
    # ⚠ Цена размена: агент пишет с оглядкой на время суток («не здоровайся утром
    # вечером»), и черновик, пролежавший до вечера, может поздороваться невпопад.
    # Бьёт это только по тем, кто пропал надолго, и стоит дешевле, чем молчание в
    # ответ на прямой вопрос.
    draft_ready = (" OR EXISTS (SELECT 1 FROM chat_reply r"
                   "             WHERE r.message_id = m.id AND r.status = 'draft')")

    # ⚠⚠ **«Отвечать всегда» обязано значить всегда.**
    #
    # Настройка `chat_answer_anyway_first` обещает ответ на первые реплики пары —
    # затем, что позвали мы сами, и молчание в начале обрывает разговор. Но
    # считалась она **после** отбора, а порог свежести отсекает пару **до**: на
    # проде первая же реплика Брайана попала в эту щель и осталась без ответа,
    # хотя обязательной значилась.
    #
    # ⚠ Послабление даётся **только паре, начатой нашим инвайтом**, и это не
    # придирка. Без него массовый импорт (кнопка «забрать переписку за 60 дней»)
    # принёс бы сотни пар с одной-двумя репликами — все «первые», все
    # обязательные, — и панель ответила бы пачкой на трёхмесячную давность. Ровно
    # то, от чего порог и заведён. Чужая импортированная переписка инвайтом не
    # начиналась; наша — начиналась всегда.
    # ⚠ Выдержка повтора — тем же послаблением.
    #
    # Оставь мы её общей, вышло бы обидно: текст написан, собеседник в сети, а
    # круг не берёт пару ещё пять минут — ровно та задержка, ради устранения
    # которой черновики и заводились.
    fresh = ("m.direction = 'in' AND m.is_answered = 0 AND m.answer_silent_at IS NULL "
             " AND (m.answer_tried_at IS NULL "
             "      OR m.answer_tried_at < NOW() - INTERVAL %s SECOND"
             + draft_ready + ')')

    reason = f'({fresh})' if not lead else \
        f'({fresh} OR m.created_at < NOW() - INTERVAL %s SECOND)'

    # Номер анкеты дважды: во внешний подзапрос («последняя реплика пары») и во
    # внутренний («какая именно, если время совпало»).
    #
    # ⚠ Срок свежести кладём в список, **только когда он есть в запросе**: порядок
    # `%s` обязан совпадать с текстом, и лишний параметр сдвинул бы все остальные.
    params = [int(profile_id), int(profile_id)]

    params.append(int(ANSWER_RETRY_SEC))
    if lead:
        params.append(int(ANSWER_NUDGE_SEC))

    where = ''
    if only:
        where = ' AND m.sender_uid IN (' + ', '.join(['%s'] * len(only)) + ')'
        params.extend(only)
    params.append(int(limit))

    # ⚠ **«Последняя реплика» считается по времени, а не по `MAX(id)`.**
    #
    # Автоинкремент совпадал с порядком событий, пока писал один сокет. Импорт
    # переписки из панели приносит **историю за неделю** и кладёт её сегодня, то
    # есть с наибольшими `id`: «последней» в диалоге оказывалась реплика недельной
    # давности.
    #
    # Последствие было не косметическое: свежее неотвеченное сообщение оставалось
    # без ответа, потому что последней считалась привезённая старая реплика. Тот же
    # разбор, что у списка диалогов (`profile_view.py`) и у запрета повтора
    # (`send.py`) — три места, и во всех порядок один.
    #
    # Двойной подзапрос нужен для случая одинакового времени: панель отдаёт время с
    # точностью до минуты, и две реплики в одну минуту — обычное дело. Тогда
    # различаем по `id` — внутри одного времени он снова означает порядок.
    async with mysql_get_db_async() as db:
        await db.execute(
            # ⚠ `m.id` — **повод написать**, и он уезжает в черновик ответа
            # (`chat_reply.message_id`). Ключ черновика стоит на нём: написал
            # собеседник снова — повод новый, и прежний черновик в разговор уже не
            # идёт. Без номера протухание пришлось бы сверять по времени руками.
            'SELECT m.id, m.sender_uid, m.sender_name, m.text, m.direction FROM message m '
            '  JOIN (SELECT sender_uid, MAX(created_at) AS last_at FROM message '
            '         WHERE profile_id = %s GROUP BY sender_uid) t '
            '    ON t.sender_uid = m.sender_uid AND t.last_at = m.created_at '
            '   AND m.id = (SELECT MAX(x.id) FROM message x '
            '                WHERE x.profile_id = %s AND x.sender_uid = m.sender_uid '
            '                  AND x.created_at = t.last_at) '
            f' WHERE {reason}' + where +
            ' ORDER BY m.created_at DESC, m.id DESC LIMIT %s', tuple(params))
        rows = await db.fetchall()

    return [dict(row) for row in (rows or [])]


async def _silent_mark(profile_id: int, uid: str) -> None:
    """Отмечает, что про эти сообщения агент решил не отвечать.

    Ставится на все неотвеченные входящие этого собеседника — на то, что агент и
    видел, когда решал. Он читает разговор целиком, а не одну реплику, и решение
    относится ко всему, что накопилось.

    Не бросает: неудачная отметка вернёт круг к тому же сообщению через пять минут
    — неприятно, но терпимо, а сорванный круг лишил бы ответов всех остальных.
    """
    try:
        async with mysql_get_db_async() as db:
            await db.execute(
                'UPDATE message SET answer_silent_at = NOW() '
                " WHERE profile_id = %s AND sender_uid = %s AND direction = 'in' "
                '   AND is_answered = 0 AND answer_silent_at IS NULL',
                (int(profile_id), str(uid)))
            await db.connection.commit()
    except Exception as e:
        logger_info(f'[dating] молчание #{profile_id} не отметилось: {e}')


async def _tried_mark(profile_id: int, uid: str) -> None:
    """Отмечает, что про эти сообщения агента уже спрашивали.

    Не бросает: неудачная отметка приведёт к лишнему вопросу агенту через минуту,
    а сорванный из-за неё круг — к тому, что не ответят вообще никому.
    """
    try:
        async with mysql_get_db_async() as db:
            await db.execute(
                'UPDATE message SET answer_tried_at = NOW() '
                " WHERE profile_id = %s AND sender_uid = %s AND direction = 'in' AND is_answered = 0",
                (int(profile_id), str(uid)))
            await db.connection.commit()
    except Exception as e:
        logger_info(f'[dating] отметка попытки не проставилась: {e}')
