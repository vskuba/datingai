async def _required_trim(profile: dict, presence: dict, required: set) -> set:
    """Повторы по заданиям «напиши повторно»: сколько и как часто, остальное — Skip.

    Luxee заводит задание «напиши повторно» примерно через 15 минут его
    молчания и, пока оно висит, запирает все прочие диалоги учётки (485).
    Отвечая на каждое, агент писал молчащему раз в четверть часа: Kateryna →
    Specialted, 21.11.2026, двенадцать реплик подряд без единого ответа.

    Решение владельца: не больше `chat_catchup_followups` повторов подряд и не
    чаще `chat_catchup_followup_gap` минут; сверх этого задание **пропускается**
    кнопкой панели («Skip», причина «Non-active user»).

    ⚠⚠ Пропуск и тогда, когда пауза ещё не вышла: держать задание до срока
    значит держать замок на всю учётку — час без ответов всем остальным.

    ⚠ Пары, где последним говорил он, не трогаем: это задание «ответь».
    ⚠ Не снялось — пара остаётся обязательной: лучше лишний повтор, чем замок.
    """
    if not required:
        return required

    site_id = int(profile.get('site_id') or 0)
    cap, gap = await _followup_limits(site_id)
    girl = str(profile.get('profile_id') or profile.get('login') or '').strip()
    keep = set(required)

    for uid in sorted(required):
        state = await _followup_state(int(profile['id']), uid)
        # ⚠ Первые минуты после нашей реплики в очереди ещё висит **прежнее**
        # задание «ответь» — панель снимает его не мгновенно. Пропускать его
        # незачем: повтор в это время и так не пишется (`_waiting_find`).
        if not state['ours_last'] or state['quiet_sec'] < ANSWER_FOLLOWUP_AFTER_SEC:
            continue

        if state['followups'] < cap and state['quiet_sec'] >= gap:
            continue

        why = (f'повторов уже {state["followups"]} из {cap}'
               if state['followups'] >= cap
               else f'с нашей реплики {state["quiet_sec"] // 60} мин из {gap // 60}')
        error = await site_registry_chat(presence).required_skip(
            site_id, presence, girl, uid)
        if error:
            await log_write(int(profile['id']), 'fail',
                            f'Catch Up {uid}: пропуск не удался ({error}) — пишем повтор')
            continue

        keep.discard(uid)
        await log_write(int(profile['id']), 'info',
                        f'Catch Up {uid}: задание пропущено — он молчит, {why}')

    return keep


async def _followup_limits(site_id: int) -> tuple[int, int]:
    """Потолок повторов подряд и пауза между ними (в секундах)."""
    try:
        cap = max(0, int(await site_seconds(site_id, ANSWER_FOLLOWUPS_SETTING)))
        gap = max(0, int(await site_seconds(site_id, ANSWER_FOLLOWUP_GAP_SETTING))) * 60
    except Exception as e:
        logger_info(f'[dating] пределы повторов Catch Up не прочитались: {e}')
        cap, gap = ANSWER_FOLLOWUPS_DEFAULT, ANSWER_FOLLOWUP_GAP_DEFAULT * 60

    return cap, gap


async def _followup_state(profile_id: int, uid: str) -> dict:
    """Чья реплика последняя, сколько наших повторов после его слова, сколько тишины.

    ⚠ Повтором считается каждая наша реплика после его последней, **кроме
    первой** — первая и есть ответ ему. ⚠ Отражения из панели не считаются:
    наша реплика лежит дважды (`message_twin_skip`).
    """
    async with mysql_get_db_async() as db:
        await db.execute(
            'SELECT MAX(created_at) AS at FROM message m'
            " WHERE m.profile_id = %s AND m.sender_uid = %s AND m.direction = 'in'",
            (int(profile_id), str(uid)))
        his = ((await db.fetchone()) or {}).get('at')

        await db.execute(
            'SELECT COUNT(*) AS n, MAX(m.created_at) AS at,'
            '       TIMESTAMPDIFF(SECOND, MAX(m.created_at), NOW()) AS quiet'
            '  FROM message m'
            " WHERE m.profile_id = %s AND m.sender_uid = %s AND m.direction = 'out'"
            '   AND (%s IS NULL OR m.created_at > %s)'
            + message_twin_skip('m'),
            (int(profile_id), str(uid), his, his))
        ours = (await db.fetchone()) or {}

    n = int(ours.get('n') or 0)

    return {'ours_last': n > 0,
            'followups': max(0, n - 1),
            'quiet_sec': int(ours.get('quiet') or 0)}


async def _anyway_first(site_id: int) -> int:
    """Сколько первых ответов пары обязательны. Настройка сайта.

    Ноль — выключено. Сбой чтения даёт умолчание: обязательный ответ в начале
    разговора — то поведение, ради которого настройку и заводили, и тихо терять
    его из-за сбоя чтения хуже, чем лишний раз ответить.
    """
    try:
        return max(0, int(await site_seconds(int(site_id or 0),
                                             ANSWER_ANYWAY_FIRST_SETTING)))
    except Exception as e:
        logger_info(f'[dating] порог обязательного ответа не прочитался: {e}')

        return ANSWER_ANYWAY_FIRST_DEFAULT


async def _anyway_here(profile_id: int, uid: str, first: int) -> bool:
    """Обязателен ли ответ этому человеку прямо сейчас.

    ## ⚠⚠ Считаем **её ответы**, а не его реплики

    Настройка обещает «первые N реплик разговора получают ответ обязательно», и
    мерить это надо тем, что делаем **мы**. Считалось наоборот — его входящие, — и
    порог съедался разговорчивостью собеседника, а не нашей работой.

    Поймано на проде, пара Diana ↔ Bruce при пороге 25: его входящих 37, её
    ответов 21. Брюс пишет очередями по три-пять реплик, и его счёт перевалил за
    порог на полутора неделях разговора — судье снова открылся путь молчания, и он
    им воспользовался (`answer_silent_at = 2026-10-11 08:03:26`). Со стороны это
    выглядит ровно тем, от чего настройка заводилась: позвали сами, человек пишет,
    девушка замолчала.

    Счёт по нашим ответам читается однозначно: «25» значит двадцать пять
    обязательных ответов этой паре, сколько бы сообщений он ни прислал.

    ## ⚠ Инвайт не ответ, близнец не второй ответ

    Из счёта вычитаются два вида исходящих строк, и обе нашлись в той же паре:

    * `source = 'invite'` — приглашение, перенесённое в историю
      (`chat_invites_to_history`). Разговора оно не продолжает, а **открывает**;
      съедай оно квоту, настройка «отвечать на инвайты» тратилась бы на сам инвайт.
    * отражение из панели — `message_twin_skip`. Строка 107375 (`panel`) дословно
      повторяет наш инвайт 107378 той же секундой; без правила близнецов одна
      реплика считалась бы дважды, и порог выбирался бы тем быстрее, чем дольше
      пара живёт.

    ⚠ Правило близнеца берётся **общее**, а не переписывается здесь: разойдись оно
    с показом, человек видел бы в диалоге одно число ответов, а счётчик порога
    держал бы другое — и объяснить расхождение было бы нечем.

    ## ⚠ Граница строгая: `<`, а не `<=`

    Считаем **уже сказанное**: в момент вопроса её ответа ещё нет. Двадцать пять
    написанных ответов значат, что следующий — двадцать шестой, то есть за
    обещанием. При пороге 5 пятый ответ ещё обязателен, шестой уже нет.

    ⚠ Считается **по паре**. Один и тот же мужчина, отвечающий двум нашим девушкам,
    начинает два разговора, и каждому свой счёт: у второй девушки её первый ответ —
    тоже первый.

    ⚠ Сбой чтения отвечает «не обязателен»: обязательность — усиление, и включать
    её вслепую значило бы слать ответ там, где судья счёл бы его лишним.
    """
    if int(first or 0) <= 0:
        return False

    try:
        async with mysql_get_db_async() as db:
            await db.execute(
                'SELECT COUNT(*) AS n FROM message m'
                ' WHERE m.profile_id = %s AND m.sender_uid = %s'
                "   AND m.direction = 'out' AND m.source <> 'invite'"
                + message_twin_skip('m'),
                (int(profile_id), str(uid or '')))
            row = await db.fetchone()
    except Exception as e:
        logger_info(f'[dating] счёт первых ответов не сложился: {e}')

        return False

    return int((row or {}).get('n') or 0) < int(first)


async def _waiting_find(profile_id: int, limit: int, only: list, lead: bool,
                        required: set = frozenset()) -> list:
    """Поводы написать: по одному на диалог.

    `required` — собеседники, ответ которым **обязателен** (задания Catch Up у
    Luxee, `site_base.required_pairs`): они идут первыми, и прежнее решение
    молчать (`answer_silent_at`) их не прячет — висящее задание запирает
    панели отправку во все остальные диалоги.

    Смотрим последнюю реплику диалога, а не каждое сообщение: ответ на неё
    закрывает переписку целиком, а не одну строку.

    Отвечающему повод один — входящее без ответа. Ведущему разговор их два: то же
    входящее и **тишина**, когда последнее слово осталось за нами дольше
    `ANSWER_NUDGE_SEC`. Иначе после намеренного молчания собеседницы
    разговор кончается сам.

    `only` — кому разрешено писать. Отбор в запросе, а не после: иначе выборка
    «последних N» съедалась бы теми, кому писать нельзя, и разрешённый собеседник
    ждал бы своей очереди неизвестно сколько.
    """
    # Ждёт ответа то входящее, на которое мы не отвечали и про которое давно не
    # спрашивали агента. Второе условие — защита от повторов при молчании.
    #
    # ⚠⚠ **Возраст реплики больше не проверяется, и это осознанный откат.**
    #
    # Здесь стоял порог свежести: на привезённое из панели старше суток агент не
    # отвечал. Довод был такой: импорт за 60 дней приносит переписку разом, и без
    # порога первый же прогон дал бы десятки поводов написать по старым письмам.
    #
    # Довод не выдержал проверки. **Это чат, а не письма**: реплика адресная, она
    # не рассылается пачкой. А замер на живом проде показал цену порога — он
    # закрывал **одну** пару из одной: «с порогом 0, без порога 1».
    #
    # Зато вреда он приносил вдвое больше, чем виделось. Первая реплика Брайана
    # осталась без ответа, хотя настройка «отвечать всегда на первые пять» прямо
    # его обещала: порог отсекал пару **до** того, как считалась обязательность.
    # А написанный и оплаченный черновик не мог уйти, потому что его повод
    # состарился, пока адресат отсутствовал.
    #
    # ⚠ Вместе с порогом ушли и **две подпорки**, заведённые, чтобы его обходить:
    # послабление готовому черновику и послабление обязательному ответу. Сущность
    # породила две сущности — верный признак, что лишняя была первая.
    # ⚠ `answer_silent_at IS NULL` — «про это сообщение решения молчать не было».
    # Без него круг переспрашивал агента про то же сообщение до конца времён.
    #
    # Метка стоит на конкретных строках, а не на собеседнике: напишет он снова — у
    # новой строки она пуста, и агента спросят опять. Молчание относится к
    # сказанному, а не к человеку навсегда.
    # ⚠⚠ **Ноль означает «без порога», а не «ничего не свежее».**
    #
    # Подставь мы ноль в `INTERVAL %s SECOND`, условие стало бы «создано в
    # будущем» — то есть панельное не отвечалось бы никогда, ровно наоборот
    # написанному в подсказке настройки. Поэтому при нуле кусок про возраст в
    # запрос не попадает вовсе.
    # ⚠⚠ **Готовый черновик снимает **оба** запрета: и выдержку повтора, и порог
    # свежести панельного.** Оба сторожат **вызовы LLM** — «не спрашивай агента
    # про то же» и «не отвечай на древнее». У пары с написанным текстом спрашивать
    # уже нечего: осталась одна отправка, и она бесплатна.
    #
    # Поймано на проде: Yulia ↔ Brian. Реплика пришла из панели, ей стало сорок
    # девять часов при пороге в сутки — круг перестал брать пару, и готовый ответ
    # пролежал двое суток при собеседнике в сети. Мы заплатили за текст и не
    # отправили его.
    #
    # ⚠ Срока жизни у черновика нет: он висит, пока адресат не появится, — тогда
    # и уходит. Возраст повода роли не играет, потому что **ответ на реплику
    # один**: `is_answered` закрывает пару, и второй раз она в работу не попадёт.
    #
    # ⚠ Цена размена: агент пишет с оглядкой на время суток («не здоровайся утром
    # вечером»), и черновик, пролежавший до вечера, может поздороваться невпопад.
    # Бьёт это только по тем, кто пропал надолго, и стоит дешевле, чем молчание в
    # ответ на прямой вопрос.
    draft_ready = (" OR EXISTS (SELECT 1 FROM chat_reply r"
                   "             WHERE r.message_id = m.id AND r.status = 'draft')")

    # ⚠⚠ **«Отвечать всегда» обязано значить всегда.**
    #
    # Настройка `chat_answer_anyway_first` обещает обязательный ответ в начале
    # разговора — затем, что позвали мы сами, и молчание там его обрывает. Но
    # считалась она **после** отбора, а порог свежести отсекает пару **до**: на
    # проде первая же реплика Брайана попала в эту щель и осталась без ответа,
    # хотя обязательной значилась.
    #
    # ⚠ Послабление даётся **только паре, начатой нашим инвайтом**, и это не
    # придирка. Без него массовый импорт (кнопка «забрать переписку за 60 дней»)
    # принёс бы сотни пар с одной-двумя репликами — все «первые», все
    # обязательные, — и панель ответила бы пачкой на трёхмесячную давность. Ровно
    # то, от чего порог и заведён. Чужая импортированная переписка инвайтом не
    # начиналась; наша — начиналась всегда.
    # ⚠ Выдержка повтора — тем же послаблением.
    #
    # Оставь мы её общей, вышло бы обидно: текст написан, собеседник в сети, а
    # круг не берёт пару ещё пять минут — ровно та задержка, ради устранения
    # которой черновики и заводились.
    must = sorted(str(one) for one in (required or ()))
    # ⚠ Пустой случай — выражение, а не `0`: `ORDER BY 0` MySQL читает как
    # номер столбца и отвечает 1054.
    must_in = ('m.sender_uid IN (' + ', '.join(['%s'] * len(must)) + ')') if must \
        else '(1 = 0)'
    fresh = ("m.direction = 'in' AND m.is_answered = 0"
             f" AND (m.answer_silent_at IS NULL OR {must_in})"
             " AND (m.answer_tried_at IS NULL "
             "      OR m.answer_tried_at < NOW() - INTERVAL %s SECOND"
             + draft_ready + ')')

    # ⚠⚠ Задание очереди, где последней была **наша** реплика, — «напиши
    # повторно» (Catch Up Luxee, вид 7: 17.11 «whisper in my ear?», он молчит
    # двое суток, и панель держит замок). Входящего без ответа там нет, и без
    # этой ветки отбор такой диалог не видел бы никогда. Вопроса у такого
    # повода нет — заход уходит веткой «Инициатива», как молчание у ведущей.
    # Выдержка повтора — по отметке на самой нашей реплике (`_tried_row`).
    parts = [fresh]
    if must:
        parts.append(f"{must_in} AND m.direction = 'out'"
                     ' AND m.created_at < NOW() - INTERVAL %s SECOND'
                     " AND (m.answer_tried_at IS NULL"
                     "      OR m.answer_tried_at < NOW() - INTERVAL %s SECOND"
                     + draft_ready + ')')
    if lead:
        parts.append('m.created_at < NOW() - INTERVAL %s SECOND')
    reason = '(' + ' OR '.join(f'({one})' for one in parts) + ')'

    # Номер анкеты дважды: во внешний подзапрос («последняя реплика пары») и во
    # внутренний («какая именно, если время совпало»).
    #
    # ⚠ Срок свежести кладём в список, **только когда он есть в запросе**: порядок
    # `%s` обязан совпадать с текстом, и лишний параметр сдвинул бы все остальные.
    params = [int(profile_id), int(profile_id)]

    params.extend(must)
    params.append(int(ANSWER_RETRY_SEC))
    if must:
        params.extend(must)
        params.append(int(ANSWER_FOLLOWUP_AFTER_SEC))
        params.append(int(ANSWER_RETRY_SEC))
    if lead:
        params.append(int(ANSWER_NUDGE_SEC))

    where = ''
    if only:
        where = ' AND m.sender_uid IN (' + ', '.join(['%s'] * len(only)) + ')'
        params.extend(only)
    params.extend(must)
    params.append(int(limit))

    # ⚠ **«Последняя реплика» считается по времени, а не по `MAX(id)`.**
    #
    # Автоинкремент совпадал с порядком событий, пока писал один сокет. Импорт
    # переписки из панели приносит **историю за неделю** и кладёт её сегодня, то
    # есть с наибольшими `id`: «последней» в диалоге оказывалась реплика недельной
    # давности.
    #
    # Последствие было не косметическое: свежее неотвеченное сообщение оставалось
    # без ответа, потому что последней считалась привезённая старая реплика. Тот же
    # разбор, что у списка диалогов (`profile_view.py`) и у запрета повтора
    # (`send.py`) — три места, и во всех порядок один.
    #
    # Двойной подзапрос нужен для случая одинакового времени: панель отдаёт время с
    # точностью до минуты, и две реплики в одну минуту — обычное дело. Тогда
    # различаем по `id` — внутри одного времени он снова означает порядок.
    async with mysql_get_db_async() as db:
        await db.execute(
            # ⚠ `m.id` — **повод написать**, и он уезжает в черновик ответа
            # (`chat_reply.message_id`). Ключ черновика стоит на нём: написал
            # собеседник снова — повод новый, и прежний черновик в разговор уже не
            # идёт. Без номера протухание пришлось бы сверять по времени руками.
            # ⚠ `m.created_at` в выдаче — граница хвоста неотвеченного
            # (`_waiting_tail`): без него в вопрос попало бы и пришедшее, пока
            # шёл прогон, то есть то, на что ответит следующий круг.
            'SELECT m.id, m.sender_uid, m.sender_name, m.text, m.direction,'
            '       m.created_at FROM message m '
            '  JOIN (SELECT sender_uid, MAX(created_at) AS last_at FROM message '
            '         WHERE profile_id = %s GROUP BY sender_uid) t '
            '    ON t.sender_uid = m.sender_uid AND t.last_at = m.created_at '
            '   AND m.id = (SELECT MAX(x.id) FROM message x '
            '                WHERE x.profile_id = %s AND x.sender_uid = m.sender_uid '
            '                  AND x.created_at = t.last_at) '
            f' WHERE {reason}' + where +
            f' ORDER BY {must_in} DESC, m.created_at DESC, m.id DESC LIMIT %s',
            tuple(params))
        rows = await db.fetchall()

    return [dict(row) for row in (rows or [])]


async def _waiting_tail(profile_id: int, uid: str, row: dict) -> str:
    """Всё, что собеседник сказал и на что мы не ответили, — одним вопросом.

    Args:
        profile_id: наша анкета.
        uid: номер собеседника на сайте.
        row: повод написать из `_waiting_find` — последняя реплика диалога.

    Returns:
        str: реплики по возрастанию времени, через перевод строки. Пусто —
        последним говорили мы (повод был «тишина», а не входящее).

    ## ⚠⚠ Почему хвост, а не одна реплика

    `_answered_mark` после отправки закрывает **все** входящие собеседника
    (`WHERE … is_answered = 0`), а в вопрос уходила одна последняя. Остальные
    молча исчезали: ни модель их не видела, ни переписка у соседа.

    ## ⚠⚠⚠ Граница хвоста — НАША ПОСЛЕДНЯЯ РЕПЛИКА, а не `is_answered`

    Напрашивается `is_answered = 0` — ровно то, что закроет `_answered_mark`.
    **Так нельзя**, и это проверено на живых данных: пометка проставляется
    не всегда. Привезённое из панели ложится в таблицу **задним числом**, уже
    после нашего ответа, и остаётся с нулём навсегда.

    Diana ↔ Mike, 27.09: по `is_answered` в хвост попали бы **девять** реплик,
    включая «hi» в 05:50, на которое ответили двумя часами раньше. Агент
    получил бы вопросом половину дневной переписки и ответил бы на давно
    закрытое.

    По нашей последней реплике хвост — две: «you want to come???» и «oh». Это
    и есть то, что человек сказал после наших слов.

    ⚠ Нашей реплики нет вовсе (разговор начал он) — берём всё, что есть, но не
    больше `ANSWER_TAIL_LIMIT`.

    ## ⚠ Отбор идёт до повода по времени

    Иначе в вопрос попало бы и то, что пришло, пока прогон шёл, — а на него
    ответит следующий круг, и повторять его здесь значит отвечать дважды.

    ⚠ Реплики, на которые решили **промолчать** (`answer_silent_at`), входят
    тоже: молчание не повод забыть сказанное. Написал он после нашего молчания
    ещё раз — агент должен видеть обе реплики.

    ⚠ Своей ошибкой не роняем круг: не вышло прочесть хвост — отвечаем по
    одной реплике, как раньше. Ответ без двух строк лучше, чем молчание.
    """
    if row.get('direction') != 'in':
        return ''

    one = str(row.get('text') or '')

    # ⚠⚠ Его снимки — словами, до того как хвост уедет агенту: иначе агент видит
    # «[photo]» и отвечает на текст рядом (`message_vision.py`). Обычно описание
    # уже положил импорт; здесь страховка, и неудача ответа не держит.
    try:
        await message_vision_run(profile_id=int(profile_id), uid=str(uid))
    except Exception as e:
        logger_info(f'[dating] снимки хвоста не описались: {e}')

    try:
        async with mysql_get_db_async() as db:
            # Когда мы говорили в последний раз. Пусто — не говорили вовсе.
            await db.execute(
                'SELECT MAX(m.created_at) AS said_at FROM message m'
                " WHERE m.profile_id = %s AND m.sender_uid = %s"
                "   AND m.direction = 'out' AND m.created_at <= %s",
                (int(profile_id), str(uid)[:32], row.get('created_at')))
            said_at = ((await db.fetchone()) or {}).get('said_at')

            # ⚠ По времени и `id`, как и «последняя реплика» в
            # `_waiting_find`: импорт из панели кладёт историю с большими
            # `id`, и порядок у этих двух мест обязан быть один.
            after = ' AND m.created_at > %s' if said_at else ''
            params = [int(profile_id), str(uid)[:32]]

            if said_at:
                params.append(said_at)

            params.extend([row.get('created_at'), row.get('created_at'),
                           int(row.get('id') or 0), int(ANSWER_TAIL_LIMIT)])

            await db.execute(
                'SELECT m.text, m.media FROM message m'
                " WHERE m.profile_id = %s AND m.sender_uid = %s"
                "   AND m.direction = 'in'" + after +
                '   AND (m.created_at < %s OR (m.created_at = %s AND m.id <= %s))'
                ' ORDER BY m.created_at DESC, m.id DESC LIMIT %s',
                tuple(params))
            rows = await db.fetchall()
    except Exception as e:
        logger_info(f'[dating] хвост неотвеченного не прочитался: {e}')

        return one

    texts = [message_vision_line(r['text'], r.get('media')) for r in reversed(rows or [])]
    texts = [t for t in texts if t]

    return ANSWER_TAIL_GLUE.join(texts) if texts else one


async def _silent_mark(profile_id: int, uid: str) -> None:
    """Отмечает, что про эти сообщения агент решил не отвечать.

    Ставится на все неотвеченные входящие этого собеседника — на то, что агент и
    видел, когда решал. Он читает разговор целиком, а не одну реплику, и решение
    относится ко всему, что накопилось.

    Не бросает: неудачная отметка вернёт круг к тому же сообщению через пять минут
    — неприятно, но терпимо, а сорванный круг лишил бы ответов всех остальных.
    """
    try:
        async with mysql_get_db_async() as db:
            await db.execute(
                'UPDATE message SET answer_silent_at = NOW() '
                " WHERE profile_id = %s AND sender_uid = %s AND direction = 'in' "
                '   AND is_answered = 0 AND answer_silent_at IS NULL',
                (int(profile_id), str(uid)))
            await db.connection.commit()
    except Exception as e:
        logger_info(f'[dating] молчание #{profile_id} не отметилось: {e}')


async def _tried_row(message_id: int) -> None:
    """Отметка попытки на **нашей** реплике — поводе «напиши повторно».

    У такого повода нет его входящих, и `_tried_mark` метить нечего: без этой
    отметки агента спрашивали бы о нём каждую минуту. Не бросает.
    """
    try:
        async with mysql_get_db_async() as db:
            await db.execute('UPDATE message SET answer_tried_at = NOW() WHERE id = %s',
                             (int(message_id),))
            await db.connection.commit()
    except Exception as e:
        logger_info(f'[dating] отметка попытки #{message_id} не проставилась: {e}')


async def _tried_mark(profile_id: int, uid: str) -> None:
    """Отмечает, что про эти сообщения агента уже спрашивали.

    Не бросает: неудачная отметка приведёт к лишнему вопросу агенту через минуту,
    а сорванный из-за неё круг — к тому, что не ответят вообще никому.
    """
    try:
        async with mysql_get_db_async() as db:
            await db.execute(
                'UPDATE message SET answer_tried_at = NOW() '
                " WHERE profile_id = %s AND sender_uid = %s AND direction = 'in' AND is_answered = 0",
                (int(profile_id), str(uid)))
            await db.connection.commit()
    except Exception as e:
        logger_info(f'[dating] отметка попытки не проставилась: {e}')
