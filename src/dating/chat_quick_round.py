"""Круг быстрых ответов: «привет» в паузе, пока агент сочиняет.

## ⚠⚠⚠ Занятие молчит, пока ему нечего сказать, — и это не поломка

Правило целиком живёт в `chat_quick.py` (оно же отвечает, почему быстрый
ответ **не ставит** пометку «отвечено» и почему о нём не знает сосед). Круг —
только темп: посмотреть сайты, где настройка не ноль, и позвать правило.

## ⚠⚠ Тик — пять секунд, и это про цену паузы

Настройка `chat_quick_after` обещает человеку «ответ уйдёт через N секунд,
если агент не ответил». Отработай круг реже, чем раз в N, — и реплика
уходила бы через N **плюс сон круга**: при N=50 и тике в минуту половина
ответов уходила бы за полторы минуты, а половина — никогда не уходила бы
вовсе (следующая реплика успевала бы прийти раньше). Пять секунд — в десять
раз чаще самого короткого разумного срока; при нуле в настройке занятие не
работает вовсе, и тик ничего не стоит: проверка `site_seconds` — один кэш.

⚠ Цена названа: один SELECT по онлайн-анкетам сайта за тик, и тот уходит в
пусто у сайта с нулевой настройкой. Отправка — только когда пара вправила
условия, не чаще одной быстрой строки на входящее (Redis-метка в `chat_quick`).

## ⚠ Своего выключателя нет, и это решение

Выключатели у занятия уже три, и все на странице: ноль в интервале, пустой
список шаблонов и `enabled`/онлайн анкеты. Четвёртый переключатель рядом с
тремя означал бы, что человек выключит одно, а другое продолжит.
"""

from src.dating.chat_quick import chat_quick_run
from src.dating.round import round_sites, round_sites_run

# Как часто круг просыпается. Доводы — в заголовке файла.
CHAT_QUICK_ROUND_TICK_SEC = 5

# Ключ слота: один заход на сайт за раз. ⚠ Метка `{id}`, а не `{site_id}` —
# её подставляет слой, и чужая осталась бы в ключе текстом, то есть одним
# общим слотом на все сайты.
#
# ⚠⚠⚠ `key` без `every` слой **молча отвергает** (урок `chat_request_round`):
# срок здесь равен тику — смысл ровно тот же, держить заход от наложения.
CHAT_QUICK_ROUND_KEY = 'dating:chat_quick:round:{id}'


async def chat_quick_round_run() -> dict:
    """Один круг: быстрый ответ по всем сайтам, где он настроен.

    Returns:
        dict: `sites` — сколько сайтов обошли, `sent` — сколько быстрых строк
        ушло.

    ⚠ Заход **не бросает**: первый сломанный сайт не лишает ответа
    остальные. Отказ — строка в журнале (`round_sites_run`).
    """
    rows = await round_sites(what='быстрых ответов чата')
    if not rows:
        return {'sites': 0, 'sent': 0}

    done = await round_sites_run(rows, work=_work, every=_every,
                                 key=CHAT_QUICK_ROUND_KEY,
                                 what='быстрый ответ чата', keep_going=True)

    sent = sum(int((one[1] or {}).get('sent') or 0)
               for one in done if one and one[1])

    return {'sites': len(done), 'sent': sent}


# ── Приватное ────────────────────────────────────────────────────────────────


async def _work(row, minutes: int) -> dict:
    """Один сайт: правило из `chat_quick`, счётчик его — наружу."""
    site_id = int(row['site_id'] if isinstance(row, dict) else row)

    return await chat_quick_run(site_id)


async def _every(site_id: int) -> int:
    """Срок слота — он же тик круга.

    ⚠ Настройкой наружу не вынесен: выдержку отвечает `chat_quick_after` (ноль —
    занятия нет), а этот срок — внутреннее дело темпа.
    """
    return CHAT_QUICK_ROUND_TICK_SEC
