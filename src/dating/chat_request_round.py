"""Круг запросов чата: принимаем всех, кто постучался.

## ⚠⚠⚠ Без принятого запроса разговора не бывает вовсе

У Step2Love написать человеку нельзя, пока между вами нет открытого чата, а
открывается он только принятым запросом (`chat_request.py`). Пока запрос
висит, `chatObjectList` пуст, отправка отвечает `offline`, переписки в панели
не заводится — и со стороны это выглядит так, будто собеседник молчит.

Поэтому круг и заведён: решение «принимать» у нас всегда одинаковое, а
нажимать галочку некому.

## ⚠⚠ Тик — пятнадцать секунд, и это про цену ожидания

У запроса есть срок: `destroyTimeout` в живом кадре — **300 000 мс, пять
минут**. Просыпайся круг реже — запросы истекали бы, не дождавшись нас, и
разговор не начинался бы по нашей же вине.

Но дело не только в сроке. Запрос шлёт **живой человек**, который сидит в
чате и ждёт: минута до принятия — это минута, когда он смотрит на «ожидание»
и может уйти. Пятнадцать секунд — столько же, сколько у присутствия, и по
тому же доводу: занятие, за которым кто-то наблюдает, не терпит ожидания в
полсрока.

⚠ Цена названа: один POST к чат-серверу на анкету за тик. Десять анкет при
этом тике — сорок запросов в минуту, то есть ровно столько, сколько делает
одна открытая страница чата.

⚠ Своего выключателя у занятия **нет**, и это решение. Принимать запрос —
не рассылка и не приставание: он уже адресован нашей анкете, и отказ от него
означал бы «мы не хотим говорить», а не «мы бережём лимит». Гасится занятие
тем же, чем гасится всё остальное у анкеты, — `enabled` и расписанием.

⚠ Расписания круг **не спрашивает**: берёт тех, у кого есть вход
(`storage_state`), то есть кто и так в сети по расписанию. Второе условие
рядом с первым отвечало бы на тот же вопрос дважды.
"""

from logging_.logging_ import logger_info
from mysql_.mysql_ import mysql_get_db_async

from src.dating.chat_request import chat_request_accept_all
from src.dating.feed import feed_write
from src.dating.round import round_sites, round_sites_run
from src.dating.site_presence import site_presence

# Как часто круг просыпается. ⚠ Срок жизни запроса у сайта — пять минут
# (`destroyTimeout` живого кадра), но тик взят по другому доводу: человек
# ждёт принятия, глядя в экран. Подробности — в заголовке файла.
CHAT_REQUEST_ROUND_TICK_SEC = 15

# Ключ слота: один заход на сайт за раз. ⚠ Метка `{id}`, а не `{site_id}` —
# её подставляет слой, и чужая осталась бы в ключе текстом, то есть одним
# общим слотом на все сайты.
#
# ⚠⚠ Слот тут **не придерживает темп** — его срок равен тику, то есть «не
# чаще, чем круг и так просыпается». Нужен он от **наложения заходов**:
# тормозящий сайт держит заход дольше пятнадцати секунд, и без слота
# следующий тик начал бы второй обход поверх первого — то есть второй POST
# открытия под той же анкетой, что сайт считает подозрением.
#
# ⚠⚠⚠ Пустой `key` при этом **не вариант**: слой требует `every` при `key`, а
# `key` без `every` роняет заход целиком — и роняет **молча**, строкой только
# в логах воркера. Так круг и простоял первые десять минут после выкладки:
# снаружи он выглядел живым, панель ничего не показывала.
CHAT_REQUEST_ROUND_KEY = 'dating:chat_request:round:{id}'

# Сколько запросов принимаем за заход у одной анкеты — потолок самого
# `chat_request`. Здесь он не переопределяется: правило про «сколько
# разговоров открыть разом» одно, и второе число рядом разошлось бы с первым.


async def chat_request_round_run() -> dict:
    """Один круг: принять все ждущие запросы по всем сайтам.

    Returns:
        dict: `sites` — сколько сайтов обошли, `taken` — сколько запросов
        приняли.

    ⚠ Заход **не бросает**: круг обходит сайты подряд, и первый сломанный
    лишил бы приёма остальные. Отказ — строка в журнале.
    """
    rows = await round_sites(what='запросов чата')
    if not rows:
        return {'sites': 0, 'taken': 0}

    done = await round_sites_run(rows, work=_work, every=_every,
                                 key=CHAT_REQUEST_ROUND_KEY,
                                 what='запросы чата', keep_going=True)

    taken = sum(int((one[1] or {}).get('taken') or 0)
                for one in done if one and one[1])

    return {'sites': len(done), 'taken': taken}


# ── Приватное ────────────────────────────────────────────────────────────────


async def _work(row, minutes: int) -> dict:
    """Принимает запросы по всем анкетам сайта.

    ⚠ Отказ одной анкеты не уносит остальных: у каждой свой вход, и
    протухшая сессия соседки — не повод бросать тех, у кого она жива.
    """
    site_id = int(row['site_id'] if isinstance(row, dict) else row)

    presence = await site_presence(site_id)

    # ⚠ Сайт без адреса чат-сервера этого занятия не знает вовсе: запросы
    # живут в сокете, а он есть не у всех. Молчим — это не отказ.
    if not str((presence.get('send') or {}).get('base') or '').strip():
        return {'taken': 0}

    taken = 0
    for girl in await _girls(site_id):
        got = await chat_request_accept_all(girl, presence)

        if got['error']:
            logger_info(f"[dating] запросы чата, анкета #{girl['id']}: "
                        f"{got['error']}")

            continue

        taken += int(got['taken'] or 0)

        if got['taken']:
            # ⚠ В ленту пишем **только о принятом**: заход идёт каждые
            # пятнадцать секунд по всем анкетам, и строка «ничего не было»
            # вытеснила бы из кольца на тридцать записей всё остальное за
            # полминуты.
            feed_write(site_id, 'chat',
                       f"Принято приглашений в чат: {got['taken']}")

    return {'taken': taken}


async def _every(site_id: int) -> int:
    """Срок слота — он же тик круга.

    ⚠ Настройкой наружу **не вынесен**: придерживать тут нечего (заход это
    один POST на анкету), а число в реестре обещало бы человеку выбор, который
    ничего не меняет. Подробности — в шапке файла.
    """
    return CHAT_REQUEST_ROUND_TICK_SEC


async def _girls(site_id: int) -> list[dict]:
    """Анкеты сайта, которым есть чем открыть соединение.

    ⚠ Условий два, и оба обязательны: `enabled` — ведём ли анкету вовсе,
    `storage_state` — был ли вход. Без второго соединение не откроется, и
    заход стоил бы запроса в никуда по каждой спящей.
    """
    try:
        async with mysql_get_db_async() as db:
            await db.execute(
                'SELECT * FROM profile'
                ' WHERE site_id = %s AND enabled = 1'
                '   AND storage_state IS NOT NULL ORDER BY id',
                (int(site_id),))
            rows = await db.fetchall()
    except Exception as e:
        logger_info(f'[dating] анкеты для запросов чата не спросились: {e}')

        return []

    return [dict(row) for row in rows or []]
