"""Всё, что мы знаем о собеседнике, — одним текстом для агента.

Агент чата узнаёт о человеке из **фактов**: их собирает отдельный workflow
(`companion_fact_extract`) из того, что человек сам написал в переписке, и
ищет по ним поиск у соседа (`qdrant_fact_search_companion`).

Беда в начале разговора: фактов ещё нет. Переписки не было — извлекать нечего,
и агент пишет человеку, не зная о нём ничего, хотя **у нас его анкета есть**:
имя, возраст, город, страна и рассказ о себе с сайта (`companion.about`).

Здесь эта анкета собирается в текст. Дальше он уезжает переменной
`companion_bio`, и промпт подставляет его **только когда фактов не нашлось**
(`[<if qdrant_fact_search_38_result_str>] … [<else>] … [<endif>]`): факты точнее —
они из живого разговора, а анкета написана однажды и часто давно.

## ⚠ Почему не всегда, а только вместо фактов

Дать и то, и другое значило бы дать модели два источника об одном человеке, и в
них бывают разные ответы: в анкете «Семейное положение: Single», а в разговоре
он упомянул жену. Модель не знает, какой источник свежее, и выберет тот, что
удобнее фразе. Факты свежее по устройству — их кладёт разговор, идущий сейчас.

## ⚠⚠ Что сюда НЕ попадает

**Фото, почта и внутренние номера.** `email` в карточке есть, но человеку его
не показывают и агенту он не нужен: в реплику ему попасть нечем, а утечь —
есть куда. То же с `uid` и `id`.

**Пустые поля не называются вовсе.** «Город: —» модель читает как факт («город
неизвестен») и может об этом заговорить. Молчание честнее: чего нет, о том не
сказано.

## Как выглядит

    Имя: James
    Возраст: 67
    Живёт: christchurch, New Zealand
    О себе: single have 10 year old son…
    Увлечения: cars trucks buses…
    Занятие: engineer

Первые три строки собираются здесь, остальное приходит готовым из `about` — его
разбирает и подписывает `companion_about.py`, и переписывать те подписи тут
значило бы завести второй их набор.
"""

from logging_.logging_ import logger_info
from mysql_.mysql_ import mysql_get_db_async

# Сколько знаков анкеты отдаём. ⚠ Не ради экономии токенов, а ради внимания
# модели: полторы тысячи знаков это уже «простыня», в которой тонет сама реплика
# собеседника. Самое важное в `about` стоит первым — «О себе» идёт до увлечений и
# религии, — поэтому обрезаем хвост.
COMPANION_BIO_MAX = 1200


async def companion_bio_text(site_id: int, uid: str) -> str:
    """Анкета собеседника одним текстом. Пусто — нечего сказать.

    Args:
        site_id: сайт-закладка.
        uid: номер человека на сайте.

    Returns:
        str: строки «Поле: значение», по одной на строку. Пустая строка, если
        карточки нет или в ней нет ничего, кроме служебного.

    ⚠ **Не бросает.** Это подсказка поверх разговора: сорвись она, реплику всё
    равно надо написать — просто без анкеты, ровно как было до этой правки.
    """
    site_id, uid = int(site_id or 0), str(uid or '')
    if not site_id or not uid:
        return ''

    try:
        async with mysql_get_db_async() as db:
            await db.execute(
                'SELECT name, age, city, country, about FROM companion'
                ' WHERE site_id = %s AND uid = %s', (site_id, uid))
            row = await db.fetchone()
    except Exception as e:
        logger_info(f'[dating] анкета собеседника {uid} не спросилась: {e}')

        return ''

    return companion_bio_build(dict(row or {}))


def companion_bio_build(card: dict) -> str:
    """Собирает текст из готовой строки карточки. Отдельно — ради проверяемости.

    ⚠ **Чистая функция, без базы**: правила «что показываем и как подписываем»
    проверяются на словаре, а не на живой строке. Тот же приём, что у разбора
    анкеты (`companion_about_text`).
    """
    lines = []

    name = str(card.get('name') or '').strip()
    if name:
        lines.append(f'Имя: {name}')

    # ⚠ Ноль — это «не знаем», а не «ноль лет»: столбец `NOT NULL DEFAULT 0`.
    age = int(card.get('age') or 0)
    if age:
        lines.append(f'Возраст: {age}')

    # Город и страна — **одной строкой**: порознь они читаются как два разных
    # факта, а это один ответ на вопрос «откуда он».
    place = ', '.join(one for one in (str(card.get('city') or '').strip(),
                                      str(card.get('country') or '').strip())
                      if one)
    if place:
        lines.append(f'Живёт: {place}')

    # Рассказ с сайта приходит уже подписанным («О себе:», «Увлечения:»…) —
    # разбирает и подписывает его `companion_about.py`. Свой набор подписей здесь
    # разошёлся бы с тем при первой же правке.
    about = str(card.get('about') or '').strip()
    if about:
        lines.append(about)

    text = '\n'.join(lines).strip()

    # ⚠ Режем **по границе строки**, а не по знаку: оборванная на полуслове
    # анкета выглядит как сбой и провоцирует модель её «досочинить».
    if len(text) > COMPANION_BIO_MAX:
        kept = []
        left = COMPANION_BIO_MAX
        for line in text.split('\n'):
            if len(line) + 1 > left:
                break

            kept.append(line)
            left -= len(line) + 1

        text = '\n'.join(kept).strip()

    return text
