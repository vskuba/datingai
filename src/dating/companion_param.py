"""Поля анкеты собеседника: один реестр подписей для вкладки и для хранения.

Снятая страница человека (`companion_about`) разбирается по подписям сайта —
«Marital status», «Eye color» — и в таком виде поля ложатся в `companion.params`.
Названия эти английские: они переживают и перевод интерфейса, и правку вёрстки,
и по ним же сверяются с живой страницей.

Человек же видит карточку по-русски. Здесь — **реестр**: какие подписи вообще
бывают, как они подписаны по-русски и в каком порядке стоят на вкладке
«Информация» карточки.

## ⚠ Реестр один, а читателей двое

Ответ ручки карточки (порядок и подписи строк) и отбор того, что писать в
колонку `params` из разобранных полей. Своя копия списка в любом из них
разошлась бы с реестром молча — тот же приём, что у параметров девушки
(`profile_param.py`) и у словаря тегов галереи.

## ⚠ Чего здесь нет

**Значений.** Нормализацией и отбором занимается разбор (`companion_about`);
здесь только имена и порядок.

**Своих подписей для новых сайтов.** Новый сайт со своими подписями приводит их
к канону **своей картой** у драйвера (`site/site_about.py`): подпись сайта →
подпись из этого реестра. Реестр от этого не меняется.

## ⚠ Порядок

Порядок задаёт **только этот список**: MySQL хранит JSON двоичным деревом и
ключи объекта пересортировывает по-своему — из колонки они приезжают не в том
порядке, в каком легли. Ответ ручки карточки проходит через
`companion_param_shown`, а не отдаётся как прочитано.
"""

