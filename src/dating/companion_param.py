# Подписи, которые лежат **колонками** карточки, а не в `params`: имя, возраст,
# город и страну показывают поля слева, и вторая их копия в списке полей
# читалась бы правкой, которой нет. Номер — это ключ строки, почта — поле связи.
COMPANION_PARAM_COLUMNS = ('Id:', 'Name', 'Age', 'Location', 'Email')

# Поля, которым на вкладке нужна полная ширина: ответы на анкетные вопросы —
# абзацы, а не строки.
COMPANION_PARAM_WIDE = frozenset((
    'About Myself', 'Hobby', 'About Partner', 'Qualities', 'Goals', 'Travel',
    'Dream', 'Media', 'Food', 'Sports', 'Five things', 'Message me if',
    'Occupation',
))


def companion_param_values(fields: dict) -> dict:
    """Что из разобранных полей лежит в `params`.

    Args:
        fields: разбор `companion_about_parse` — «подпись сайта → значение».

    Returns:
        dict: те же пары, кроме тех, что уже колонки карточки
        (`COMPANION_PARAM_COLUMNS`). Пустой ввод — пустой ответ.
    """
    return {label: str(value or '').strip() for label, value in (fields or {}).items()
            if label not in COMPANION_PARAM_COLUMNS and str(value or '').strip()}


def companion_param_shown(params) -> list[dict]:
    """Строки для вкладки: [{'title','value','wide'}] в порядке реестра.

    Args:
        params: прочитанная колонка `params` — словарь или пустота.

    ## ⚠ Неизвестная подпись не прячется

    Реестр — про русский язык и порядок, а не про запрет: поле, которое реестр
    не знает (сайт добавил секцию), уезжает в **конец** списка со своей
    английской подписью как есть. Спрятать его значило бы молча потерять сведения,
    которые мы сняли, — а заметна такая потеря только когда её уже нечем восполнить.
    """
    got = params if isinstance(params, dict) else {}

    lines = [{'title': ru, 'value': str(got[one]).strip(), 'wide': one in COMPANION_PARAM_WIDE}
             for one, ru in COMPANION_PARAM_TITLES
             if str(got.get(one) or '').strip()]

    known = {one for one, _ru in COMPANION_PARAM_TITLES}
    lines += [{'title': one, 'value': str(value).strip(),
               'wide': one in COMPANION_PARAM_WIDE}
              for one, value in sorted(got.items())
              if one not in known and str(value or '').strip()]

    return lines
