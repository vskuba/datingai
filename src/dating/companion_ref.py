"""Как мы называем собеседника, когда зовём агента у соседа.

## ⚠⚠ Зачем понадобился отдельный модуль

`/chat/ask` собеседника в запросе больше не приносит, и троицу `companion_*`,
которую читают шаги workflow, зовущий кладёт **в `variables` сам**: с
`…remove_companion` сосед из запроса ничего не подставляет — молча лёг бы
пустой default. Прежде номер ехал полем запроса и считался «типом собеседника»;
единица оказалась конкретной персоной — «Vadim». Цена вышла в двух местах.

**Имя в тексте.** Промпты зовут собеседника `%companion_title%`, и агент писал
живым людям «ok vadim» — человеку по имени Gerard. Поймано на проде.

**Факты, и это хуже.** Шаг разбора кладёт факты в Qdrant по ключу
`document_id: '%companion_name%'`, а переписку — по `'%girl_id%_%companion_name%'`.
С одним именем на всех факты обо **всех** мужчинах сайта валились в один документ,
а разговоры девушки со всеми — в один «yulia_77_Vadim».

## ⚠⚠ Троица зеркальна девушкиной, и это не косметика

| Переменная | Что это | Пример | Чем собрана |
|------------|---------|--------|-------------|
| `companion_id` | его номер **на сайте** | `128282` | `companion_uid` |
| `companion_name` | то же имя техническим видом | `gerard` | `companion_name` → `agent_key` |
| `companion_title` | имя, которым агент зовёт его в тексте | `Gerard` | `companion_title` |

Склейка у соседа **одна и та же** на оба конца (шаг «Переменные», позиция 0):

    companion_unique_id = %companion_id%_%companion_name%
    girl_unique_id      = %girl_id%_%girl_name%

Значит и половины обязаны значить одно: слева номер, справа имя. У девушки
выходит `643694_diana` — это и есть самый большой документ фактов на проде.

## ⚠⚠⚠ Чем это было и почему было неверно

Здесь лежал **весь ключ целиком** в `companion_name` (`dating_343_128282`), а
`companion_id` был приколочен к константе `10` — номеру единственной общей записи
справочника `dating_person`. Ключ выходил `10_dating_343_128282`: константа,
приставка, сайт, номер — и **ни одного имени**.

Три беды, и все три тихие:

1. **Десятка мертва.** Сосед перестал резолвить собеседника из запроса
   (`remove_companion`, `agent_session_companion_drop`): `companion_id` больше
   никуда не ведёт внешним ключом, и единственный его читатель — та самая
   склейка. То есть константа просто дописывала `10_` ко всякому ключу.
2. **Имя переменной врало.** Это записано в миграции соседа
   (`…_wf_talk_companion_key`) его же словами: «в „имени собеседника“ лежал ключ
   `dating_343_128282`, и всякий, кто правил промпт, видел не то, что там на
   самом деле». У девушки это починили (`…_wf_talk_girl_title`), у мужчины — нет.
3. **Ключи двух сторон читались по-разному.** `643694_diana` против
   `10_dating_343_128282` в одном и том же индексе Qdrant, а читают их люди,
   разбирая, чьи факты в документе.

## ⚠⚠ Цена: сайт из ключа ушёл

Приставка `dating` и `site_id` были в ключе не зря — они разводили номера разных
сайтов: номер `128282` может встретиться и на Goldenbride, и на Ladadate. Теперь
их нет, и столкновение возможно: **тот же номер и то же имя на двух сайтах**.

Размен принят осознанно по двум доводам. Первый — склейка одна на обе стороны, и
у девушки сайта в ключе тоже нет (`girl_id` — это её номер на сайте): развести
половины по смыслу значило бы иметь два правила там, где у соседа одно правило.
Второй — имя в ключе делает столкновение куда менее вероятным, чем было бы у
голого номера.

⚠ **Признак, по которому решение стоит пересмотреть:** двое разных людей с одним
номером и одним именем на двух сайтах. Лечится это добавлением сайта **в обе**
половины разом — и нашу, и девушкину, — а не правкой одной здесь.

## ⚠ Имя для промптов — отдельное поле

`companion_name` — ключ (машинный), `companion_title` — имя, которым агент зовёт
человека в тексте. Слей их в одно, и агент либо обращается номером, либо ключует
факты именем, которое на сайте носят десятки людей.
"""

import re

# ⚠ Имена служебных персон справочника соседа. Появление любого из них в ответе
# агента означает, что имя собеседника снова не доехало и подставилось чужое, —
# ровно та беда, ради которой этот модуль и заведён.
COMPANION_REF_FOREIGN = ('vadim', 'olenka')


def companion_uid(uid) -> str:
    """Номер собеседника на сайте — левая половина ключа, как `girl_id` у девушки.

    Args:
        uid: номер собеседника на сайте.

    Returns:
        str: номер строкой. Пусто — если номера нет: тогда звать агента незачем,
        факты всё равно некуда положить.

    ⚠ Мусор вычищаем: половина уезжает в `document_id` Qdrant и в фильтры поиска,
    и знак препинания там однажды встретит разбор, который его не ждёт.
    """
    return re.sub(r'[^A-Za-z0-9_-]', '', str(uid or '').strip())


def companion_name(name, uid) -> str:
    """Имя собеседника техническим видом: латиница строчными — правая половина ключа.

    Args:
        name: имя, как его видит панель.
        uid: номер на сайте — на случай, когда от имени ничего не осталось.

    Returns:
        str: `Gerard` → `gerard`, `Jan Kowalski` → `jan_kowalski`.

    ## ⚠⚠ Собирает **та же** функция, что `girl_name` — `agent_key`

    Не «такая же», а буквально одна: склейка у соседа одна на обе стороны, и два
    правила транслита под одну склейку разошлись бы на первой правке — молча, потому
    что ключ по-прежнему выглядел бы ключом. Это тот же довод, по которому доля из
    настройки живёт одной функцией на весь проект (`percent.py`).

    ⚠ **Нет имени — отдаём номер**, ровно как `girl_name` скатывается на `girl_id`:
    ключ обязан быть, иначе факты лягут в документ с пустой половиной. Имя не
    сводится к латинице (`許萊納`) — тот же случай, что пустое.
    """
    from src.dating.agent import agent_key

    return agent_key(name) or companion_uid(uid)


def companion_title(name, uid) -> str:
    """Имя, которым агент зовёт человека в тексте.

    ⚠ Нет имени — отдаём **номер**, а не пустую строку: промпт построен на
    `%companion_title%` («=== %companion_title% пишет ==='), и пустая метка
    оставила бы агенту фразу без подлежащего. Номер некрасив, но честен.
    """
    name = ' '.join(str(name or '').split())

    return name or str(uid or '').strip() or 'собеседник'


def companion_vars(site_id, uid, name) -> dict:
    """Переменные вызова, описывающие собеседника.

    Args:
        site_id: сайт-закладка. ⚠ **Больше не участвует** — довод и цена в
            докстринге модуля, раздел «Цена: сайт из ключа ушёл». Оставлен в
            подписи: зовущих четыре, и снимать довод у всех ради ключа, который
            завтра может его вернуть, дороже, чем держать его здесь.
        uid: номер собеседника на сайте.
        name: его имя, как его видит панель.

    Returns:
        dict: троица `companion_id`, `companion_name`, `companion_title`.

    ⚠ **Троица едет здесь целиком, и это не избыточность.** Сосед перестал
    подставлять `companion_*` по умолчанию: что workflow не получил запросом,
    тот берёт пустой default (`chat.py`). Номер в ключе нужен не меньше имени:
    шаг «Переменные» склеивает `companion_unique_id` из `%companion_id%` и
    `%companion_name%`, и половина без второй половины ключом не станет.
    """
    return {'companion_id': companion_uid(uid),
            'companion_name': companion_name(name, uid),
            'companion_title': companion_title(name, uid)}


def companion_ref_foreign(text: str, title: str = '') -> str:
    """Чужое имя в ответе агента. Пусто — всё чисто.

    Args:
        text: то, что агент собирается отправить.
        title: имя настоящего адресата — оно законно, даже если совпало со
            служебным.

    Returns:
        str: найденное чужое имя, для причины отказа.

    ## ⚠⚠ Зачем сторож, если имя теперь передаётся

    Затем, что беда была тихой. Ответ грамотный, по-английски, к месту — и с чужим
    именем в обращении; ни код ответа, ни журнал о ней не говорят. Заметил её
    человек, прочитав текст.

    Передача имени эту дыру закрывает, но следующая правка промптов или справочника
    у соседа может открыть её снова, и узнаем мы об этом тем же способом — случайно.

    ⚠ **Ищем по границе слова и без учёта регистра.** «Vadim» и «vadim» — одно и то
    же; а вот подстрока внутри слова именем не является, иначе сторож ловил бы
    невинные слова.
    """
    text = str(text or '')

    if not text.strip():
        return ''

    # Имя адресата исключаем: собеседника вправду может звать Вадим, и запрещать
    # агенту обращаться к нему по имени было бы бессмысленно.
    own = str(title or '').strip().lower()

    for name in COMPANION_REF_FOREIGN:
        if name == own:
            continue

        if re.search(rf'\b{re.escape(name)}\b', text, re.IGNORECASE):
            return name

    return ''
