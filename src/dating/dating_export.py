"""Выгрузка анкет с сайта: сшивка того, что вернул сценарий, в таблицу.

Сценарий у RhapsodyAi отдаёт не таблицу, а `extract` — словарь «имя шага → текст»,
где несколько совпадений одного селектора склеены переводами строк
(`browser_scenario_run`, действие `extract`). То есть список профилей приходит
**столбцами**: отдельно все имена, отдельно все возрасты, отдельно все ссылки.

Сшивать их в строки приходится здесь: сосед про смысл шагов ничего не знает, для
него это просто текст со страницы. А раз здесь — то отдельным модулем, а не телом
ручки: сшивка это чистая функция над словарём, и проверять её незачем гонять
браузер.

Порядок столбцов — порядок шагов сценария: словарь его сохраняет, и он же
осмысленный порядок колонок в таблице. Новая колонка на странице заводится новым
шагом `extract` у соседа, а не правкой этого файла.
"""


def dating_export_rows(extract: dict) -> tuple[list, list]:
    """Разбирает `extract` сценария в колонки и строки.

    Args:
        extract: ответ сценария — `{имя шага: 'значение\\nзначение\\n…'}`.

    Returns:
        tuple: список имён колонок и список строк-словарей.
    """
    columns = [str(name) for name in (extract or {}) if str(name or '').strip()]
    if not columns:
        return [], []

    values = {name: _split(extract.get(name)) for name in columns}

    # Длину берём по самому длинному столбцу, а не по самому короткому. Столбцы
    # приходят независимыми выжимками, и сайт легко отдаёт по одному из них
    # меньше: у части анкет не заполнен город, селектор не нашёл ничего и строк
    # в этом столбце на десяток меньше. Режь мы по короткому — молча потеряли бы
    # хвост списка, причём ровно тех анкет, которые заполнены хуже прочих.
    height = max((len(rows) for rows in values.values()), default=0)

    return columns, [{name: _at(values[name], index) for name in columns}
                     for index in range(height)]


# ── Приватное ────────────────────────────────────────────────────────────────

def _split(value) -> list:
    """Текст шага — в список значений. Пустые строки выбрасываем.

    Пустые строки среди совпадений — обычное дело: селектор ловит и разделители
    разметки. Оставь мы их, строки таблицы разъехались бы по индексу, и имя одной
    анкеты встало бы напротив возраста другой.
    """
    if value is None:
        return []

    if isinstance(value, (list, tuple)):
        return [str(item).strip() for item in value if str(item).strip()]

    return [line.strip() for line in str(value).split('\n') if line.strip()]


def _at(rows: list, index: int) -> str:
    """Значение столбца по номеру строки; кончились — пусто."""
    return rows[index] if index < len(rows) else ''
