"""Лента событий: что панель сделала только что, строкой в две строки.

Круги воркера работают молча. Почта забирается, ответы пишутся, инвайты
набираются — и всё это видно только косвенно: по числу в пуле, по новой карточке в
диалогах, по строке в журнале анкеты. Вопроса «что сейчас происходит» страница не
знала вовсе, и человек отвечал на него, обновляя вкладки по очереди.

Лента отвечает на него прямо: две последние строки в полосе вкладок «Профилей».

## ⚠ Это не журнал и не «Ошибки»

Три разных вопроса, и сводить их нельзя:

| Где | Вопрос | Срок жизни |
|-----|--------|------------|
| **лента** (здесь) | что случилось **сейчас** | минуты, кольцо на 30 записей |
| журнал анкеты (`dating_log`) | что было **с этой девушкой** | до чистки, в базе |
| «Ошибки» (`dating_error`) | что сломано **прямо сейчас** | до устранения |

Лента не хранит историю и не заменяет журнал: она отвечает на вопрос, который
задают глазами, а не поиском.

## ⚠ Кольцо в Redis, а не таблица

Событий много (каждый забор почты, каждый набор пула), а живут они минуты: строка
в базе на каждое означала бы таблицу, растущую быстрее переписки, и чистку к ней.
Кольцо же само выбрасывает старое, а перезапуск смены — не потеря: события,
которых никто не увидел, никому и не нужны.

Тот же приём и та же причина, что у снимка держателей (`dating_socket.py`): между
воркером и панелью нет ничего, кроме базы и Redis.

## ⚠ Лента по сайту, а не одна на всех

Селект сайта стоит в шапке, и человек смотрит на **выбранный**. Общая лента
показывала бы ему забор писем на соседнем сайте вперемешку со своими — и на вопрос
«а это про кого?» пришлось бы отвечать на каждой строке.
"""

import json
import time

from logging_.logging_ import logger_info
from redis_.redis_ import redis_conn_get

# Где лежит лента сайта.
DATING_FEED_KEY = 'dating:feed:{site_id}'

# Сколько событий держим. Тридцати хватает: страница показывает две строки, а
# остальное — запас на случай, если человек отвернулся на минуту.
DATING_FEED_KEEP = 30

# Сколько лента живёт без новых событий. Полчаса: круги ходят чаще, и пустая лента
# после получаса тишины честнее, чем вчерашняя строка, выглядящая свежей.
DATING_FEED_TTL_SEC = 1800

# Длина строки события. Она рисуется в одну строку полосы вкладок, и длинная
# обрезалась бы там же — лучше обрезать осмысленно и при записи.
DATING_FEED_TEXT_MAX = 200

# Виды событий. ⚠ Закрытый список: по виду страница красит строку, и вид, о
# котором она не знает, приехал бы бесцветным.
DATING_FEED_KINDS = ('mail', 'chat', 'reply', 'invite', 'fav', 'panel', 'warn',
                     # ⚠ Начало разговора — свой вид, а не `chat` и не `fav`. По
                     # нему считается счётчик у слова «Диалоги», и слейся он с
                     # общим, у вкладки прыгала бы каждая привезённая реплика.
                     # Два вида, потому что и вкладки две: чат и письма избранным.
                     'talk', 'favtalk')


def dating_feed_write(site_id: int, kind: str, text: str, profile_id: int = 0) -> str:
    """Кладёт событие в ленту сайта.

    Args:
        site_id: сайт, к которому событие относится.
        kind: вид из `DATING_FEED_KINDS` — им страница красит строку.
        text: что случилось, человеческими словами.
        profile_id: анкета, если событие про неё. Ноль — про сайт целиком.

    Returns:
        str: сама запись строкой — её передают в `dating_feed_done`, чтобы
        заменить «идёт» на «вышло». Пусто — записать не вышло.

    ⚠ **Не бросает и ничего не ждёт.** Событие — сведение для показа; сбой Redis не
    повод ронять круг, который забирает почту. Страница переживёт пустую ленту,
    письма без круга — нет. Тот же довод, что у снимка держателей.
    """
    site_id = int(site_id or 0)
    if not site_id or not str(text or '').strip():
        return ''

    one = _row(kind, text, profile_id)
    key = DATING_FEED_KEY.format(site_id=site_id)
    try:
        conn = redis_conn_get()

        # ⚠ **Повтор не плодит строку, а обновляет прежнюю.** Круги ходят с разной
        # частотой — за письмами раз в две минуты, за перепиской раз в три, — и
        # «Писем не пришло» каждые две минуты выталкивало бы переписку из двух
        # видимых строк ещё до того, как человек её заметит. На это и пожаловались:
        # «в ленте одни письма, а что чат забирается — не вижу».
        #
        # Сравниваем вид и текст, но не время: одинаковый текст значит, что нового
        # сказать нечего, и честнее обновить метку, чем занять вторую строку тем же
        # самым.
        if _same(conn.lindex(key, 0), kind, text):
            conn.lset(key, 0, one)
            conn.expire(key, DATING_FEED_TTL_SEC)

            return one

        pipe = conn.pipeline()
        # Новое — в голову: страница читает сверху, и переворачивать список на
        # каждое чтение значило бы платить за порядок, который можно задать сразу.
        pipe.lpush(key, one)
        pipe.ltrim(key, 0, DATING_FEED_KEEP - 1)
        pipe.expire(key, DATING_FEED_TTL_SEC)
        pipe.execute()
    except Exception as e:
        logger_info(f'[dating] событие ленты не записалось: {e}')

        return ''

    return one


def dating_feed_done(site_id: int, started: str, kind: str, text: str,
                     profile_id: int = 0) -> None:
    """Заменяет строку «идёт» её же итогом. Строки уже нет — пишет новую.

    Args:
        started: что вернул `dating_feed_write` в начале работы.

    ⚠ **Замена, а не вторая строка**, и это не экономия места. Долгий заход надо
    показать, пока он идёт (обход тринадцати анкет — десятки секунд), но «Забираю
    письма: анкет 13» без итога читается как незаконченное: человек видит начало и
    не знает, чем кончилось. Две же строки на один заход забивали бы обе строки
    полосы одной только почтой.

    ⚠ **Итог пишется всегда, даже пустой.** «Писем не пришло» — тоже ответ, и
    молчание вместо него оставляло бы на экране вечное «забираю».

    ⚠ Заменяем **только если наша строка всё ещё в голове**: пока шёл заход, в
    ленту мог лечь чужой круг, и слепой `lset 0` затёр бы его событие.
    """
    site_id = int(site_id or 0)
    if not site_id:
        return

    key = DATING_FEED_KEY.format(site_id=site_id)
    try:
        conn = redis_conn_get()
        if started and conn.lindex(key, 0) == started:
            conn.lset(key, 0, _row(kind, text, profile_id))
            conn.expire(key, DATING_FEED_TTL_SEC)

            return
    except Exception as e:
        logger_info(f'[dating] итог события не записался: {e}')

    dating_feed_write(site_id, kind, text, profile_id)


def dating_feed_read(site_id: int, limit: int = DATING_FEED_KEEP) -> list[dict]:
    """События сайта, свежие первыми.

    Returns:
        list: `{at, kind, text, profile_id, age_sec}`. Пусто — событий не было или
        Redis молчит; для показа это одно и то же.
    """
    site_id = int(site_id or 0)
    if not site_id:
        return []

    try:
        raw = redis_conn_get().lrange(DATING_FEED_KEY.format(site_id=site_id),
                                      0, max(int(limit), 1) - 1)
    except Exception as e:
        logger_info(f'[dating] лента событий не прочиталась: {e}')

        return []

    now = time.time()
    rows = []
    for one in raw or []:
        try:
            row = json.loads(one)
        except ValueError:
            continue

        row['age_sec'] = int(max(0, now - float(row.get('at') or 0)))
        rows.append(row)

    return rows


# ── Приватное ────────────────────────────────────────────────────────────────

def _same(raw, kind: str, text: str) -> bool:
    """Та же ли это строка по смыслу: тот же вид и тот же текст.

    ⚠ Время не сравниваем — на нём и держится обновление: строка остаётся одна, а
    метка у неё свежая, и человек видит «Писем не пришло · только что» вместо
    десятка одинаковых рядов.
    """
    if not raw:
        return False

    try:
        last = json.loads(raw)
    except (TypeError, ValueError):
        return False

    return (str(last.get('kind') or '') == (str(kind) if kind in DATING_FEED_KINDS
                                            else 'warn')
            and str(last.get('text') or '') == str(text).strip()[:DATING_FEED_TEXT_MAX])


def _row(kind: str, text: str, profile_id: int = 0) -> str:
    """Запись события строкой JSON — в таком виде она и лежит в кольце."""
    return json.dumps({'at': time.time(),
                       'kind': str(kind) if kind in DATING_FEED_KINDS else 'warn',
                       'text': str(text).strip()[:DATING_FEED_TEXT_MAX],
                       'profile_id': int(profile_id or 0)}, ensure_ascii=False)
