        # ответа: это один и тот же разговор, и два его вида означали бы, что
        # агент ответа и агент возобновления видят разных людей.
        # ⚠ **Пустую историю отдаём пустой строкой, а не указанием.** Сперва
        # вместо неё уезжал текст «переписки нет, не выдумывай» — инструкция в
        # переменной данных. Работало плохо (модель всё равно сочиняла кофейню, о
        # которой «мы говорили») и было не на своём месте: у соседа промпт умеет
        # ветвиться сам — `%if mail_history% … %else% … %endif%`, и пустая строка
        # для него ложна. Инструкция теперь там, где ей и место, — в промпте
