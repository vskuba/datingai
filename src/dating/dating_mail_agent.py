"""Агенты у соседа, которые пишут текст: письма, вопросы, ответы, инвайты.

Разных занятий шесть, и потому шесть workflow — у агента соседа он один:

| Что | Workflow | Что отдаёт |
|-----|----------|------------|
| заполнить переменные анкеты | `dating_mail_vars` | JSON «имя → значение» |
| написать черновик письма | `dating_mail_write` | текст письма |
| сочинить вопрос получателю | `dating_mail_question` | один вопрос |
| ответить на входящее письмо | `dating_mail_reply` | текст ответа |
| позвать в чат незнакомого | `dating_invite_write` | одна реплика с именем |
| возобновить затихший разговор | `dating_favorite_mail_write` | текст письма |

Общее у них — сборка сведений об анкете и о собеседнике (`_card`,
`_companion_card`) и поиск агента по метке сайта (`_agent_id`); отсюда и один
модуль. Расходятся они требованиями к тексту, и каждое выражено своим промптом у
соседа — свести их в один нельзя: письму нужны абзацы, вопросу — знак вопроса и
отсутствие обращения, инвайту — обращение по имени и одна строка.

⚠ **Инвайт живёт здесь, хотя он не письмо.** Модуль про агентов, пишущих текст, а
не про почту: имя (`dating_mail_agent`) осталось от времён, когда занятий было
два. Разводить его сейчас значило бы вынести `_card`, `_companion_card` и
`_agent_id` в третье место ради одной функции.

## Агент, заполняющий переменные писем.

Человек заводит на сайте имена переменных (`girl_name`, `girl_city`, …), а
значения нужны у каждой анкеты — по десятку полей на сорок учёток. Заполнять их
руками это работа на день; заполняет агент у соседа.

## Как это устроено

1. собираем **сведения об анкете** — то, что о ней знает наша база;
2. собираем **список полей** — имена и подписи из реестра сайта;
3. спрашиваем агента (`POST /chat/ask`, workflow `dating_mail_vars`);
4. разбираем ответ и **берём только ожидаемые имена**.

⚠ **Агент один на сайт, а не на анкету.** Сведения об анкете идут в запросе, и
второй агент ничего бы не добавил — зато удвоил бы их число у соседа. Заводится
он сам при первом обращении, тем же приёмом, что агент анкеты
(`dating_agent.py`).

## ⚠ Разбор ответа — здесь, а не у соседа

Движок соседа умеет `llm_to_json`, но тот требует **заранее известных ключей**:
они перечислены в метаданных шага и проверяются при разборе. Здесь ключи знает
только вызывающий — их заводит человек, и у каждого сайта свои.

Поэтому workflow отдаёт ответ LLM как есть, а JSON вырезаем и сверяем мы: у нас
же лежит реестр, по которому видно, что просили. Выдуманное имя молча
отбрасывается — принять его значило бы завести переменную, которой нет ни в одном
списке.

## ⚠ Пустое значение лучше выдуманного

Письмо с незаполненной переменной не уйдёт — и это правильный исход. Письмо с
выдуманным именем уйдёт живому человеку и будет выглядеть ровно тем, чем
является. Поэтому промпт просит пропускать неизвестное, а разбор выбрасывает
пустые строки.
"""

