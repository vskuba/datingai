"""Круг рассылки: пул набирается сам, по расписанию сайта.

Раз в минуту смотрит, у каких сайтов идёт смена рассылки, и добирает им пул. То
же самое, что делает кнопка «Генерировать письма», только без человека у экрана.

## ⚠ Круг **готовит письма, а не отправляет их**

Отправка — отдельное решение и отдельный выключатель (`mailing_send_on`, выключен
по умолчанию). Письма уходят живым людям, и «расписание включено» не значит
«разрешаю рассылать»: человек включает смены, чтобы к утру был готов пул, который
он прочтёт.

Разведи мы это одним флагом — включение расписания означало бы согласие на
отправку, которого никто не давал.

## Два срока, и они про разное

| Что | Чем задан | На какой вопрос отвечает |
|-----|-----------|--------------------------|
| смены суток | `dating_site.mailing_schedule` | в какие часы вообще готовим |
| частота внутри смены | настройка `mailing_every` | как часто добираем пул за эти часы |

Одного расписания мало. Смена «09:00–18:00» — это девять часов, и без второго
срока круг набирал бы пул каждую минуту: пятьсот сорок заходов вместо восемнадцати
получасовых, и каждый стоит вызовов LLM за `question_to_companion`.

## ⚠ Пул — запас, а не поток

Круг добирает пул, **пока в нём не станет `mailing_pool_max` неотправленных**
(обычно 50), и на этом останавливается. Письма ждут отправки, и складывать их
тысячами незачем: устареют раньше, чем дойдёт очередь — адресаты уйдут с сайта, а
вопрос про их интересы останется.

За один заход при этом берётся не больше порции (`mailing_batch`): даже когда до
потолка далеко, заход не должен длиться часами — круг вернётся через свой срок.

⚠ **Когда набирали — помним в Redis, а не в памяти процесса.** Смена держателя
перезапускается (свой срок, деплой, падение), и память сбрасывалась бы вместе с
ней: после каждого перезапуска пул набирался бы заново, независимо от настройки.
Тот же приём и та же причина, что у импорта переписки.

## Сайты обходятся по одному

Набор пула — это вызовы LLM за живыми переменными, минуты работы. Два сайта разом
удвоили бы очередь к соседу, ничего не ускорив: очередь у него общая.
"""

