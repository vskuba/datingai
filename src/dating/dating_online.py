"""В сети ли собеседник — общая проверка перед отправкой.

Писать тому, кого нет на сайте, бессмысленно на обоих путях: сайт либо отклоняет
сообщение, либо принимает его в пустоту. Поэтому и ручная отправка, и автоответ
сперва спрашивают здесь.

## ⚠ Смотрим снимок, а не ходим на сайт

Список «кто в сети» и так снимается для ленты на странице (`dating_people.py`) и
лежит в Redis. Спрашивать сайт заново перед каждой отправкой значило бы платить
40 секундами сценария (или лишним запросом к API) за сведение, которое у нас уже
есть и которому от силы пять минут.

Отсюда главное свойство: **ответ приблизительный**. Собеседник мог выйти минуту
назад, и мы этого ещё не знаем. Это приемлемо — цена ошибки здесь мала: сообщение
уйдёт в пустоту, как уходило и раньше. Дорого другое — вовсе не отправить тому,
кто в сети, поэтому:

⚠ **Нет снимка — считаем, что в сети.** Снимка нет у сайта, где лента не заведена
вовсе (Goldenbride), и в первые минуты после перезапуска. Молчать в этих случаях
значило бы тихо выключить автоответ на весь сайт, и никто бы не понял почему.
Запрет должен срабатывать там, где мы **знаем**, что человека нет, а не там, где мы
ничего не знаем.
"""

import json
import time

from logging_.logging_ import logger_info
from redis_.redis_ import redis_conn_get

# Ключ снимка «кто в сети» по сайту. Тот же, что кладёт `dating_people.py`; вид
# ключа держим строкой здесь, чтобы не тянуть импортом весь модуль ручек — он
# ходит к соседу и в базу, а нам нужно только чтение Redis.
#
# ⚠ Разъехаться им нельзя: тест сверяет обе строки (`test_online.py`).
DATING_ONLINE_KEY = 'dating:people:site:{site_id}:online'

# Сколько снимок годится для этого решения. Пять минут — та же выдержка, с какой
# он и обновляется (`DATING_PEOPLE_FRESH_SEC`): более старому верить нельзя, состав
# сети меняется быстро.
#
# ⚠ Протухший снимок — это «не знаем», а не «никого нет»: см. правило выше.
DATING_ONLINE_FRESH_SEC = 300


def dating_online_check(site_id: int, uid: str) -> dict:
    """В сети ли собеседник по последнему снимку сайта.

    Args:
        site_id: сайт-закладка.
        uid: номер собеседника на сайте.

    Returns:
        dict: `online` — можно ли писать; `known` — было ли на чём основать ответ;
        `age_sec` — сколько снимку секунд (`-1`, если снимка нет).

        ⚠ **`online: True` при `known: False`** — это «не знаем, поэтому не мешаем».
        Разделение важно для страницы: «в сети» и «неизвестно» подписываются
        по-разному, а запрещать по незнанию нельзя.
    """
    snapshot = _snapshot(int(site_id or 0))
    if not snapshot:
        return {'online': True, 'known': False, 'age_sec': -1}

    age = int(time.time() - snapshot['at'])
    if age >= DATING_ONLINE_FRESH_SEC:
        # Снимок устарел: состав сети за пять минут меняется, и запрещать по нему
        # — угадывать. Пропускаем, отметив, что уверенности нет.
        return {'online': True, 'known': False, 'age_sec': age}

    people = snapshot.get('people') or []

    return {'online': any(str(p.get('uid')) == str(uid) for p in people),
            'known': True, 'age_sec': age}


# ── Приватное ────────────────────────────────────────────────────────────────

def _snapshot(site_id: int) -> dict | None:
    """Снимок «кто в сети» из Redis. Сбой Redis — не беда: вернём «не знаем».

    Ронять отправку из-за кэша нельзя: он здесь ускорение, а не источник правды.
    """
    if not site_id:
        return None

    try:
        raw = redis_conn_get().get(DATING_ONLINE_KEY.format(site_id=site_id))
    except Exception as e:
        logger_info(f'[dating] снимок онлайна не прочитался: {e}')

        return None

    if not raw:
        return None

    try:
        snapshot = json.loads(raw)
    except ValueError:
        return None

    return snapshot if isinstance(snapshot, dict) and 'people' in snapshot else None
