"""Круг ленты «Все онлайн»: снимок держится свежим сам.

Кто в сети — сведение, на котором стоит половина панели: по нему составляют
рассылку, по нему рисуется точка у собеседника, по нему решается, писать ли
сейчас. Живёт оно в Redis (`dating_people.py`), с выдержкой по настройке сайта
`online_check_every`.

## ⚠ Чего не хватало

Снимок обновлялся **только при обращении к ручке** — то есть пока человек держит
открытой страницу «Профили». Закрыл вкладку, ушёл на «Анкеты» — и лента стареет;
через пять минут она уже ни на что не годится.

Видно это было по мелочи: точка «сейчас на сайте» у собеседников не загоралась
никогда. Не потому, что никого нет, а потому, что снимку был час, и панель честно
отвечала «не знаем».

## Что делает круг

Раз в минуту смотрит, не пора ли обновить ленту каждого сайта, и заводит съём.
Дальше — как у страницы: тот же кэш, та же выдержка, тот же жёсткий пол. Круг не
приносит нового способа снимать список, он лишь **нажимает на кнопку вместо
человека**.

⚠ **Своей выдержки у него нет.** Частота — та же настройка `online_check_every`,
что и у страницы: два числа для одного вопроса разошлись бы, и объяснить, почему
лента обновляется то так, то этак, стало бы нечем.

## ⚠ Сайты обходятся по одному

Съём — это вход браузером под анкетой и ~40 секунд. Два сайта разом удвоили бы
очередь к соседу, ничего не ускорив: пул Chromium у него общий.

## ⚠ Ходим, только когда есть кому

Круг обходит сайты, но снимок берётся **от лица анкеты в сети**: если ни одна не
работает, поход отменяется молча (`_site_profile` вернёт пусто). Смысла в снимке
тогда нет — лента нужна тем, кто сейчас в чате, а их ноль.

Раньше бралась любая анкета, даже спящая, и круг стучался на сайт круглые сутки.
Когда общий пароль перестал подходить, это стоило нам блокировки IP: 484
неудачных входа за сутки, `ERROR_SING_IN_BY_IP_DAILY_FAILED_LIMIT`, и сайт закрыл
адрес для всех анкет разом.
"""

import time

from logging_.logging_ import logger_info
from mysql_.mysql_ import mysql_get_db_async

# Как часто круг просыпается. Минута — как у прочих кругов смены: выдержка ленты
# задана в секундах (обычно 120), и чаще смотреть нечего.
#
# ⚠ Тик — не частота съёма. Съём ограничен выдержкой сайта, и большинство тиков
# только читают время снимка.
DATING_ONLINE_ROUND_TICK_SEC = 60


async def dating_online_round_run() -> dict:
    """Один круг: обновить ленту тем сайтам, у кого снимок постарел.

    Returns:
        dict: `checked` — сколько сайтов посмотрели, `started` — скольким завели
        съём. Съём идёт в фоне: круг его заводит и не ждёт — ровно как страница.
    """
    from src.uvicorn.routers.dating.dating_people import (dating_people_snap_due,
                                                          dating_people_snap_start)

    started = 0
    sites = await _sites()

    for site_id in sites:
        try:
            if not await dating_people_snap_due(site_id):
                continue

            if await dating_people_snap_start(site_id):
                started += 1
        except Exception as e:
            # ⚠ Один сайт не должен ронять обход: у соседа бывает занят пул, у
            # сайта — смениться вёрстка. Прочим это не мешает.
            logger_info(f'[dating] лента сайта #{site_id}: {e}')

    if started:
        logger_info(f'[dating] круг ленты: обновляем {started} из {len(sites)}')

    return {'checked': len(sites), 'started': started}


# ── Приватное ────────────────────────────────────────────────────────────────

async def _sites() -> list[int]:
    """Сайты, у которых есть наши анкеты.

    ⚠ Отбор по анкетам, а не по списку сайтов: снимок `dating_site` держит и те,
    что завели «на будущее», и ушедшие. Гонять браузер по ним значило бы платить
    сорока секундами за пустой ответ. Тот же отбор, что у импорта переписки.

    ⚠ Анкета нужна и по существу: лента снимается **под её входом**, гостю сайт
    списка не покажет.
    """
    try:
        async with mysql_get_db_async() as db:
            await db.execute(
                'SELECT DISTINCT site_id FROM profile'
                ' WHERE site_id > 0 AND enabled = 1 ORDER BY site_id')
            rows = await db.fetchall()
    except Exception as e:
        logger_info(f'[dating] сайты для ленты не спросились: {e}')

        return []

    return [int(row['site_id']) for row in rows or []]
