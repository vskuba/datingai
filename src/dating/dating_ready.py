# Настройка сайта с общим паролем анкет — тем, которым войдёт сценарий, если у
# анкеты своего нет. Та же, что у списков собеседников и у отправки.
DATING_READY_PASSWORD_SETTING = 'api_password'

# Транспорты, которым нужен снятый вход. ⚠ Перечислением, а не «всё кроме
# сценария»: появится четвёртый — и молчаливое «кроме» решило бы за него, а
# ошибиться здесь значит либо запретить работу, либо разрешить невозможную.
DATING_READY_NEEDS_LOGIN = {'ws', 'http'}


def dating_password_pick(profile: dict, site_password: str = '') -> str:
    """Пароль анкеты по её настройке: свой или общий агентский.

    ⚠ **Источник задаёт анкета явно** (`password_source`), а не правило «свой, если
    задан». Прежнее правило было удобным, но у него нет состояния: по анкете не
    видно, под каким паролем она работает. Человек стирал своё поле, чтобы
    «вернуться к общему», и получал анкету, молча ходящую под чужим паролем, если
    общий кто-то поменял.

    ⚠ **Запасного пути нет.** Выбран `own`, а поле пусто — возвращаем пустоту, а не
    подставляем общий: подстановка вернула бы ту же неявность, от которой и уходим,
    только теперь вопреки явно сделанному выбору.

    Returns:
        str: пароль либо пустая строка — «войти нечем», и вызывающий скажет об этом
        человеку словами.
    """
    if str(profile.get('password_source') or 'site') == 'own':
        return str(profile.get('password') or '').strip()

    return str(site_password or '').strip()


def dating_ready_check(profile: dict, transport: str, site_password: str = '') -> dict:
    """Может ли панель сейчас работать с анкетой.

    Args:
        profile: строка `profile`.
        transport: чем сайт отправляет — `ws`, `http` или `scenario`.
        site_password: общий пароль анкет у сайта, если он задан.

    Returns:
        dict: `can` — можно ли; `why` — почему нельзя, словами для панели. При
        `can = True` причина пустая: «почему можно» человеку не нужно.

    ⚠ **Выключенная анкета готовой не считается.** Иначе панель показывала бы
    «готова» у той, с которой ничего не делают, и человек искал бы поломку в
    работе, а не в галочке.
    """
    if not int(profile.get('enabled', 1) or 0):
        return {'can': False, 'why': 'анкета выключена'}

    if str(transport) in DATING_READY_NEEDS_LOGIN:
        if not profile.get('storage_state'):
            return {'can': False, 'why': 'вход не снят: сначала «Залогиниться»'}

        # Сокету нужен ещё и адрес: он снимается вместе с входом, но живёт своей
        # колонкой и может оказаться пустым при частичном входе.
        if str(transport) == 'ws' and not str(profile.get('ws_url') or '').strip():
            return {'can': False, 'why': 'адрес чат-сокета не снят'}

        return {'can': True, 'why': ''}

    # Сценарий: вход он сделает сам, но пароль нужен.
    #
    # Откуда пароль — решает сама анкета (`password_source`), и правило одно на
    # всех: `dating_password_pick`.
    if dating_password_pick(profile, site_password):
        return {'can': True, 'why': ''}

    own = str(profile.get('password_source') or 'site') == 'own'

    return {'can': False,
            'why': ('выбран свой пароль, но он не задан' if own
                    else 'нет общего пароля сайта: впишите его в настройках сайта')}


async def dating_ready_online(profile_id: int) -> bool:
    """Всё ещё ли анкета в сети — **прямо сейчас**, а не когда её отбирали.

    ## ⚠⚠ Зачем спрашивать второй раз

    Круги отбирают анкеты запросом `status = 'online'`, а потом обходят их по
    одной с паузой: сайт считает частые заходы подозрением, и заходы разведены
    намеренно. За время обхода список успевает устареть.

    Поймано живьём на проде:

        20:00:41  анкета 43 ушла в офлайн — смена кончилась
        20:00:43  GET /messages под ней    ← через две секунды

    Обход начался, когда обе были в сети; смена кончилась на второй секунде, и
    круг доработал по снимку, снятому до неё. Вреда в тот раз не вышло — письма
    забирались по живому токену, входа не было, — но правило «под спящей анкетой
    наружу не ходим» держится не на везении.

    ⚠ **Запрос на анкету, а не один на список.** Список и есть то, что устарело;
    перечитывать его целиком значило бы получить снимок, который устареет так же.
    Запрос дешёвый и к **своей** базе — он не идёт наружу и не считается сайтом.

    ⚠ **Молчание базы читается как «в сети».** Ошибка чтения не повод отменять
    работу: круг и так обходит анкеты раз в две минуты, а лишний пропуск тише, но
    вреднее — письма не заберутся, и понять почему будет нечем.
    """
    from mysql_.mysql_ import mysql_get_db_async

    try:
        async with mysql_get_db_async() as db:
            await db.execute(
                "SELECT status = 'online' AND enabled = 1 AS живая"
                '  FROM profile WHERE id = %s', (int(profile_id),))
            row = await db.fetchone()
    except Exception as e:
        from logging_.logging_ import logger_info

        logger_info(f'[dating] статус анкеты #{profile_id} не спросился: {e}')

        return True

    return bool((row or {}).get('живая'))


async def dating_ready_write(profile_id: int, state: dict) -> None:
    """Кладёт признак в базу — по нему воркер и отбирает.

    Пишем только при изменении: колонка читается запросом воркера каждую минуту, а
    меняется редко, и лишний `UPDATE` на каждую проверку засорял бы бинлог.
    """
    try:
        async with mysql_get_db_async() as db:
            await db.execute('UPDATE profile '
                             '   SET can_work = %s, work_reason = %s '
                             ' WHERE id = %s AND (can_work <> %s OR work_reason <> %s)',
                             (1 if state['can'] else 0, str(state['why'])[:200],
                              int(profile_id),
                              1 if state['can'] else 0, str(state['why'])[:200]))
            await db.connection.commit()
    except Exception as e:
        logger_info(f'[dating] признак готовности #{profile_id} не записался: {e}')


def dating_ready_transport(presence, site_settings: dict) -> str:
    """Чем сайт отправляет: `ws`, `http` или `scenario`.

    ⚠ **Наша настройка старше `presence.send`** — то же правило, что в отправке
    (`dating_send.py`): `presence` описывает сайт, но правит его только сосед, а
    «чем отправлять» решает наша сторона.
    """
    chosen = str((site_settings or {}).get('send_transport') or '').strip()
    if chosen and chosen != 'presence':
        return chosen

    send = dating_json_load(presence).get('send') or {}

    return str(send.get('transport') or 'http').lower()
