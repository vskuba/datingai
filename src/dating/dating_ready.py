"""Готова ли анкета к работе — один признак на все сайты.

## Зачем понадобился

Воркер отбирал анкеты условием «снят вход» (`storage_state IS NOT NULL`). Для
сокетного сайта это верно: без входа нет адреса сокета, держать нечего. Но у
Ladadate сокета нет вовсе — там пишут **сценарием**, который входит на сайт сам,
каждый раз заново, и `storage_state` ему не нужен.

Итог: из 24 анкет Ladadate воркер видел **ноль**. Автоответ до них не доходил, и
понять это по панели было нельзя — анкета выглядела нормальной.

## Что такое «готова»

Не «включена» и не «в сети», а **«панель может сейчас с ней работать»**. Три разных
признака, и путать их дорого:

| Признак | Про что | Кто меняет |
|---------|---------|-----------|
| `enabled` | ведём ли анкету вовсе | человек, галочкой |
| `can_work` | **можно ли с ней работать** | код, по обстоятельствам |
| `status` | в сети ли прямо сейчас | опрос присутствия |

Условие готовности зависит от того, чем сайт отправляет:

* **сокет** (`transport: ws`) — нужен снятый вход: адрес сокета берётся из него;
* **сценарий** — нужен пароль (свой у анкеты или общий агентский у сайта): сценарий
  войдёт сам, а без пароля ему нечем;
* **HTTP-ручка сайта** — как у сокета, вход нужен: запрос идёт с его cookie.

## ⚠ Почему это столбец, а не вычисление на месте

Соблазн был посчитать в отборе воркера и не заводить колонку. Отказался по двум
причинам, и обе практические:

* **отбор идёт SQL-запросом.** Вычисляя в Python, пришлось бы тащить все анкеты и
  спрашивать настройку сайта по каждой — а воркер ходит этим путём раз в минуту;
* **человек не видит, почему анкета молчит.** Колонка с причиной (`work_reason`)
  отвечает на это прямо в панели: «нет пароля — сценарию нечем войти». Вычисление
  в отборе не отвечает никому.

Цена — согласованность: колонку надо обновлять, когда меняются обстоятельства.
Поэтому пересчёт живёт **здесь**, в одной функции, и зовётся из тех мест, где
обстоятельства и меняются: вход, выход, проверка, правка учётки, круг воркера.
"""

from logging_.logging_ import logger_info
from mysql_.mysql_ import mysql_get_db_async

from src.dating.dating_json import dating_json_load

# Настройка сайта с общим паролем анкет — тем, которым войдёт сценарий, если у
# анкеты своего нет. Та же, что у списков собеседников и у отправки.
DATING_READY_PASSWORD_SETTING = 'api_password'

# Транспорты, которым нужен снятый вход. ⚠ Перечислением, а не «всё кроме
# сценария»: появится четвёртый — и молчаливое «кроме» решило бы за него, а
# ошибиться здесь значит либо запретить работу, либо разрешить невозможную.
DATING_READY_NEEDS_LOGIN = {'ws', 'http'}


def dating_ready_check(profile: dict, transport: str, site_password: str = '') -> dict:
    """Может ли панель сейчас работать с анкетой.

    Args:
        profile: строка `dating_profile`.
        transport: чем сайт отправляет — `ws`, `http` или `scenario`.
        site_password: общий пароль анкет у сайта, если он задан.

    Returns:
        dict: `can` — можно ли; `why` — почему нельзя, словами для панели. При
        `can = True` причина пустая: «почему можно» человеку не нужно.

    ⚠ **Выключенная анкета готовой не считается.** Иначе панель показывала бы
    «готова» у той, с которой ничего не делают, и человек искал бы поломку в
    работе, а не в галочке.
    """
    if not int(profile.get('enabled', 1) or 0):
        return {'can': False, 'why': 'анкета выключена'}

    if str(transport) in DATING_READY_NEEDS_LOGIN:
        if not profile.get('storage_state'):
            return {'can': False, 'why': 'вход не снят: сначала «Залогиниться»'}

        # Сокету нужен ещё и адрес: он снимается вместе с входом, но живёт своей
        # колонкой и может оказаться пустым при частичном входе.
        if str(transport) == 'ws' and not str(profile.get('ws_url') or '').strip():
            return {'can': False, 'why': 'адрес чат-сокета не снят'}

        return {'can': True, 'why': ''}

    # Сценарий: вход он сделает сам, но пароль нужен.
    #
    # Свой пароль анкеты сильнее общего — тот же порядок, что у отправки и у
    # списков собеседников: общий заводят оптом, и окажись он сильнее, анкета со
    # своей парой молча ходила бы под чужим паролем.
    if str(profile.get('password') or '').strip() or str(site_password or '').strip():
        return {'can': True, 'why': ''}

    return {'can': False,
            'why': 'нет пароля: сценарию нечем войти на сайт'}


async def dating_ready_write(profile_id: int, state: dict) -> None:
    """Кладёт признак в базу — по нему воркер и отбирает.

    Пишем только при изменении: колонка читается запросом воркера каждую минуту, а
    меняется редко, и лишний `UPDATE` на каждую проверку засорял бы бинлог.
    """
    try:
        async with mysql_get_db_async() as db:
            await db.execute('UPDATE dating_profile '
                             '   SET can_work = %s, work_reason = %s '
                             ' WHERE id = %s AND (can_work <> %s OR work_reason <> %s)',
                             (1 if state['can'] else 0, str(state['why'])[:200],
                              int(profile_id),
                              1 if state['can'] else 0, str(state['why'])[:200]))
            await db.connection.commit()
    except Exception as e:
        logger_info(f'[dating] признак готовности #{profile_id} не записался: {e}')


def dating_ready_transport(presence, site_settings: dict) -> str:
    """Чем сайт отправляет: `ws`, `http` или `scenario`.

    ⚠ **Наша настройка старше `presence.send`** — то же правило, что в отправке
    (`dating_send.py`): `presence` описывает сайт, но правит его только сосед, а
    «чем отправлять» решает наша сторона.
    """
    chosen = str((site_settings or {}).get('send_transport') or '').strip()
    if chosen and chosen != 'presence':
        return chosen

    send = dating_json_load(presence).get('send') or {}

    return str(send.get('transport') or 'http').lower()
