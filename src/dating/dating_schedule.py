"""Расписание анкеты: когда ей быть в сети.

Смены суток — пары «с... до...», по местному времени панели (настройка `timezone`).
Анкета входит на сайт к началу смены и выходит в конце: ночью она спит, как спит
живой человек, и круглосуточное присутствие не выдаёт её механикой.

## ⚠ Раньше это был только вид

Расписание жило в памяти страницы до перезагрузки — ни таблицы, ни ручки. В коде
страницы так и стояло: «чтобы никто не решил, будто расписание уже работает».
Теперь оно хранится.

## Почему JSON-колонка, а не своя таблица

Смен две-четыре, читают их **только вместе с анкетой** и заменяют целиком — по
одной смене их никто не спрашивает и не правит. Отдельная таблица дала бы join на
каждый показ карточки и порядок вставки, который пришлось бы поддерживать; выигрыш
— нормализация, которой здесь нечего нормализовать.

Тот же приём и по той же причине, что у настроек сайта (`dating_site.settings`).

## ⚠ Умолчание не пустое

Пустое расписание означает «анкету ведут руками» — законное состояние, но не то,
которое нужно при заведении: анкету заводят, чтобы она работала. Поэтому у новых
анкет три смены — утро, день, вечер (`DATING_SCHEDULE_DEFAULT`).
"""

import json

from logging_.logging_ import logger_info

# Расписание по умолчанию: утро, день, вечер. Между сменами перерывы — они и делают
# присутствие похожим на живое. Ночь пустая: анкета спит.
#
# ⚠ Время местное, по настройке `timezone`, а не UTC. Расписание сверяют с часами на
# стене, и «войти в 7 утра» человек понимает буквально.
DATING_SCHEDULE_DEFAULT = [
    {'from': '07:00', 'to': '11:00'},
    {'from': '14:00', 'to': '18:00'},
    {'from': '19:00', 'to': '23:00'},
]

# Сколько смен разрешаем. Четыре — предел не технический, а смысловой: смены с
# перерывами укладываются в сутки, а больше означало бы «включено почти всегда», то
# есть то же круглосуточное присутствие, от которого расписание и уводит.
DATING_SCHEDULE_MAX = 4


def dating_schedule_load(value) -> list[dict]:
    """Расписание из столбца базы. Мусор и пустота — пустой список.

    ⚠ **Пустое — законное состояние**, а не повод подставлять умолчание: оно
    означает «анкету ведут руками». Умолчание ставится при заведении анкеты, и
    только там: подставь его здесь — и человек, снявший все смены, получал бы их
    обратно на каждом показе страницы.
    """
    if isinstance(value, str):
        try:
            value = json.loads(value or '[]')
        except ValueError:
            return []

    if not isinstance(value, list):
        return []

    rows = []
    for item in value:
        if not isinstance(item, dict):
            continue

        start, end = _hhmm(item.get('from')), _hhmm(item.get('to'))
        if start and end:
            rows.append({'from': start, 'to': end})

    # По времени: смены правят ползунком, и заведённая последней может оказаться
    # первой по часам. Порядок нужен и странице, и проверке пересечений.
    return sorted(rows, key=lambda row: row['from'])[:DATING_SCHEDULE_MAX]


def dating_schedule_check(rows: list) -> str:
    """Годно ли расписание. Пустая строка — годно, иначе причина словами.

    Причина уезжает человеку на страницу, поэтому говорит, что поправить, а не
    какое правило нарушено.
    """
    if not isinstance(rows, list):
        return 'расписание должно быть списком смен'

    if len(rows) > DATING_SCHEDULE_MAX:
        return f'смен не больше {DATING_SCHEDULE_MAX}'

    clean = []
    for item in rows:
        start, end = _hhmm((item or {}).get('from')), _hhmm((item or {}).get('to'))
        if not start or not end:
            return 'у смены должно быть время начала и конца в виде 07:00'

        if start >= end:
            return f'смена {start}–{end}: конец должен быть позже начала'

        clean.append({'from': start, 'to': end})

    clean.sort(key=lambda row: row['from'])
    for first, second in zip(clean, clean[1:]):
        # ⚠ Пересечение — не придирка: две смены внахлёст означают вход поверх
        # входа, и анкета получит вторую сессию, не закрыв первую.
        if second['from'] < first['to']:
            return (f"смены {first['from']}–{first['to']} и "
                    f"{second['from']}–{second['to']} налезают друг на друга")

    return ''


def dating_schedule_dump(rows: list) -> str:
    """Расписание в столбец базы — уже проверенным.

    Проверку здесь не повторяем: у неё своя функция, и вызывающий обязан позвать её
    первой. Двойная проверка означала бы два места, где правило может разойтись.
    """
    return json.dumps(dating_schedule_load(rows), ensure_ascii=False)


def dating_schedule_now(rows: list, minutes: int) -> bool:
    """Должна ли анкета быть в сети в эту минуту суток.

    Args:
        rows: расписание.
        minutes: минуты от начала местных суток (0–1439).

    Returns:
        bool: попадает ли минута в какую-нибудь смену. ⚠ **Пустое расписание — это
        `False`**, а не «всегда в сети»: «ведут руками» значит, что сама она не
        входит. Обратное толкование включило бы круглосуточное присутствие у всех,
        кто расписание не заводил.
    """
    for item in dating_schedule_load(rows):
        if _minutes(item['from']) <= int(minutes) < _minutes(item['to']):
            return True

    return False


def dating_schedule_profile_now(profile: dict, minutes: int) -> bool:
    """Должна ли **эта анкета** быть в сети в эту минуту.

    ⚠ **Расписание действует только у включённой анкеты.** Выключенную не ведут
    вовсе (`dating.md`, §5.10): она не отвечает и ничего не отправляет, и входить по
    расписанию ей тем более незачем — вход это действие наружу, самое заметное из
    всех.

    Отдельной функцией, а не параметром у `dating_schedule_now`: параметр легко не
    передать, и забывший вызывающий получил бы вход у выключенной анкеты молча.
    Здесь забыть нечего — на входе вся строка целиком.

    Args:
        profile: строка `dating_profile`; нужны `enabled` и `schedule`.
        minutes: минуты от начала местных суток (0–1439).
    """
    if not int(profile.get('enabled', 1) or 0):
        return False

    return dating_schedule_now(profile.get('schedule'), minutes)


def dating_schedule_why_idle(profile: dict) -> str:
    """Почему расписание сейчас не действует. Пустая строка — действует.

    Для страницы: блок расписания у выключенной анкеты выглядит рабочим, и без
    объяснения человек ждёт, что анкета войдёт в семь утра, — а она не войдёт.
    """
    if not int(profile.get('enabled', 1) or 0):
        return 'анкета выключена — расписание не действует'

    if not dating_schedule_load(profile.get('schedule')):
        return 'расписания нет — анкету ведут руками'

    return ''


# ── Приватное ────────────────────────────────────────────────────────────────

def _hhmm(value) -> str:
    """`7:0`, `07:00`, `7` → `07:00`. Мусор → пустая строка.

    Терпимость к виду нужна не для красоты: время приходит и со страницы, и из
    базы, и из миграции, и одна забытая ведущая ноль ломала бы сравнение строк, на
    котором держится весь порядок.

    ⚠ **`24:00` — законное время, и только оно одно за пределами суток.** Смена
    «с 19:00 до полуночи» — обычное желание, а выразить его иначе нечем: `00:00`
    означает начало тех же суток, и смена схлопывалась бы в ноль длины.

    Так и было: ползунок доводили до правого края (1440 минут), страница показывала
    «00:00», смена становилась «19:00 → 00:00» и уезжала в начало ленты — человек
    видел, как она исчезает и появляется слева.

    Началом `24:00` быть не может: конец обязан быть позже начала, а позже полуночи
    в сутках ничего нет. Отдельной проверки для этого не нужно — `_check` отклонит
    такую смену на общих основаниях.
    """
    text = str(value or '').strip()
    if not text:
        return ''

    parts = text.split(':')
    try:
        hour = int(parts[0])
        minute = int(parts[1]) if len(parts) > 1 else 0
    except ValueError:
        return ''

    if hour == 24 and minute == 0:
        return '24:00'

    if not (0 <= hour <= 23 and 0 <= minute <= 59):
        return ''

    return f'{hour:02d}:{minute:02d}'


def _minutes(hhmm: str) -> int:
    """`07:30` → 450. Вид уже проверен `_hhmm`."""
    try:
        hour, minute = hhmm.split(':')

        return int(hour) * 60 + int(minute)
    except (ValueError, AttributeError) as e:
        logger_info(f'[dating] непонятное время в расписании: {hhmm!r} ({e})')

        return 0
