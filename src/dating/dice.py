"""Жребий, устойчивый по ключу: число между границами, одно и то же у одной пары.

## ⚠⚠ Зачем он устойчив

Срок, выпадающий заново на каждом тике круга, разброса не даёт вовсе. Круг
просыпается раз в минуту и спрашивает одно и то же: «пора ли?». Свежий бросок
рано или поздно выпадет низким — и работать будет одна нижняя граница, а верхняя
не значит ничего.

Поэтому число **выводится из ключа**: пока ключ тот же, число то же. Ключ
собирает вызывающий, и собирает его так, чтобы тот менялся вместе с событием,
после которого срок отсчитывается: пара и время последней реплики у инициативы,
анкета и время её последнего письма у паузы между письмами.

## ⚠⚠ Не `hash()` и не `random`

Встроенный `hash()` солится на каждый процесс (`PYTHONHASHSEED`), а воркеров
несколько и перезапускаются они часто: один и тот же ключ давал бы разное число у
соседних процессов и после каждой выкладки — то есть ровно тот развал, от
которого жребий сюда и уводится.

## ⚠ Почему модуль, а не функция по месту

Копия жила в инициативе (`initiative._due_sec`), и второй потребитель — пауза
между письмами избранным (`favorite_mail`) — сделал бы её второй. Разойдись они,
разошлись бы молча: обе дают правдоподобное число, и сравнить их можно только
глазами.

⚠ Общий слой (`py_modules`) спрошен — готового нет: `tool_find` на «случайное
число по ключу, одинаковое при повторном вызове» не даёт ничего ближе
`journal_key` (отпечаток ошибки). Заводить там namespace ради шести строк не
стали: потребителей пока двое и оба здесь.
"""


import hashlib


def dice_steady(key: str, low: int, high: int) -> int:
    """Число между `low` и `high` включительно — одно и то же для одного ключа.

    Args:
        key: что задаёт бросок. Должен меняться вместе с событием, от которого
            идёт отсчёт, иначе срок застынет навсегда.
        low: нижняя граница.
        high: верхняя. Меньше нижней или равна ей — возвращается `low`, и это
            законное «без разброса», а не ошибка: человек, не желающий жребия,
            ставит ноль или повторяет нижнюю.

    Returns:
        int: `low <= число <= high`.

    ⚠ Доля берётся из восьми байт `blake2b`: быстрее и короче `sha256`, а
    требований криптостойкости здесь нет вовсе — ключ не секрет, и угадывать
    нечего.
    """
    low, high = int(low), int(high)
    if high <= low:
        return low

    digest = hashlib.blake2b(str(key).encode('utf-8'), digest_size=8).digest()
    share = int.from_bytes(digest, 'big') / float(1 << 64)

    return low + int(share * (high - low + 1))
