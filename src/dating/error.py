"""Отказы, которые не про анкету: связь с соседом, сверка списков, фоновые задачи.

Журнал анкеты (`log`) отвечает на вопрос «что происходило с этой учёткой».
Есть отказы, которые ни к какой учётке не привязаны: не обновился список сайтов,
не ответил сосед, встала фоновая сверка. Приписать их случайной анкете значило бы
соврать — работа не её; потерять совсем значило бы объяснять людям, почему панель
показывает недельной давности список и молчит об этом.

## ⚠ Строка одна на источник, а не на каждый отказ

Лежащий сосед отвечает отказом на **каждый** показ страницы. Строка на каждый — это
тысяча одинаковых записей за час и таблица, в которой ничего не найти. Поэтому
запись одна на пару «источник + сайт», а повторы считаются:

* `hits` — сколько раз подряд;
* `first_at` — когда сломалось впервые: по нему видно, идёт это час или неделю;
* `last_at` — когда в последний раз.

Отсюда и смысл страницы «Ошибки»: она отвечает на вопрос **«что сломано сейчас»**, а
не «что ломалось за неделю». История отказов, если понадобится, — отдельная работа.

## Удача стирает запись

Не «закрывает», не «помечает решённой», а стирает: строка здесь означает «сломано
прямо сейчас». Оставь мы её после починки — страница показывала бы отказ, которого
больше нет, и ей перестали бы верить.
"""

from logging_.logging_ import logger_info
from mysql_.mysql_ import mysql_get_db_async

# Известные источники отказов. Строкой в базе, но константами здесь: имя источника
# пишет один код, а читает другой (страница отбирает по нему), и опечатка развела
# бы их молча.
ERROR_SITES_SYNC = 'sites_sync'
ERROR_DRIVE = 'drive'

# Как источник зовётся на странице. Отдельно от ключа: `sites_sync` в столбце
# рядом с человеческой причиной выглядит чужим.
ERROR_TITLES = {ERROR_SITES_SYNC: 'Список сайтов',
                ERROR_DRIVE: 'Google Диск'}

# Сколько отказов показываем. Их единицы — по строке на источник, — но предел
# нужен: без него страница однажды попробует нарисовать всё, что накопилось.
ERROR_LIMIT = 200

# Длина причины. Обрезаем при записи, а не при показе: в базе незачем держать
# мегабайт чужой трассы, а человек читает первую строку.
ERROR_MESSAGE_MAX = 2000


async def error_write(source: str, message: str, site_id: int = 0) -> None:
    """Записывает отказ. Повтор того же источника — счётчик, а не новая строка.

    Args:
        source: что не вышло (`ERROR_SITES_SYNC` и подобные).
        message: причина словами — её и читает человек.
        site_id: к какому сайту относится; 0 — отказ не про сайт.

    Не бросает: запись отказа не должна ронять то, что этот отказ поймало. Иначе
    сбой базы превращал бы «список не обновился» в «страница не открылась».
    """
    try:
        async with mysql_get_db_async() as db:
            await db.execute(
                'INSERT INTO error (source, site_id, message)'
                ' VALUES (%s, %s, %s)'
                ' ON DUPLICATE KEY UPDATE message = VALUES(message), hits = hits + 1',
                (str(source)[:64], int(site_id), str(message)[:ERROR_MESSAGE_MAX]))
            await db.connection.commit()
    except Exception as e:
        logger_info(f'[dating] отказ «{source}» не записался: {e}')


async def error_clear(source: str, site_id: int = 0) -> None:
    """Убирает отказ — после того, как то же самое получилось.

    ⚠ **Стираем, а не помечаем решённым.** Строка здесь значит «сломано прямо
    сейчас»; оставь мы её после починки, страница показывала бы отказ, которого
    больше нет, и ей перестали бы верить.
    """
    try:
        async with mysql_get_db_async() as db:
            await db.execute('DELETE FROM error WHERE source = %s AND site_id = %s',
                             (str(source)[:64], int(site_id)))
            await db.connection.commit()
    except Exception as e:
        logger_info(f'[dating] отказ «{source}» не убрался: {e}')


async def error_rows(site_id: int = 0, limit: int = ERROR_LIMIT) -> list[dict]:
    """Что сломано сейчас — свежее сверху.

    Args:
        site_id: показать отказы этого сайта. Ноль — все, вместе с общими.

    ⚠ **Отбор по сайту не отсекает общие отказы** (`site_id = 0`). «Список сайтов
    не обновляется» не относится ни к какому сайту в отдельности, но касается
    любого из них: спрятав такую строку на странице выбранного сайта, мы оставили
    бы человека без единственного объяснения того, что он видит.
    """
    where, params = '', []
    if int(site_id or 0):
        where = ' WHERE site_id IN (%s, 0)'
        params = [int(site_id)]

    async with mysql_get_db_async() as db:
        await db.execute(
            'SELECT id, source, site_id, message, hits, first_at, last_at'
            f' FROM error{where} ORDER BY last_at DESC LIMIT {int(limit)}', params)
