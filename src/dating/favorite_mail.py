async def favorite_mail_why(site_id: int, offset_hours: int = 0) -> str:
    """Почему пул не наполняется прямо сейчас. Пусто — наполняется, повода нет.

    Returns:
        str: одна строка для шапки пула — та же, что круг пишет в `reasons`, но
        про **ближайшую** пару: ту, которой письмо появится раньше прочих.

    ⚠ **Отвечает не «когда придёт круг», а «почему сейчас пусто»**, и это разные
    вопросы. Круг может приходить каждые полчаса и каждый раз уходить ни с чем:
    ближайшей паре нельзя писать ещё три часа, и человек, видящий только срок
    круга, ждёт набора к этому сроку — а его не будет. Наблюдалось живьём: анкета
    в сети, её избранный в сети, генерация включена, пул пуст, и объяснения нет
    нигде, кроме журнала воркера.

    ⚠ **Считается по тем же правилам, что и набор** (`_quiet`, `favorite_mail_person_soon`,
    `favorite_mail_girl_soon`) — не второй их копией: разойдись они, шапка
    обещала бы письмо, которого набор не сделает, или молчала бы там, где он
    работает.
    """
    site_id = int(site_id or 0)
    if not site_id:
        return ''

    # ⚠ **Смена — первый вопрос, и раньше пар.** Вне смены круг не наберёт ничего,
    # сколько бы пар ни ждало; скажи мы про пары, человек чинил бы пределы, пока
    # дело в часах. Тот же порядок и та же формулировка, что у отправки
    # (`send_why`) и у отправки инвайтов.
    if not await favorite_mail_shift_site(site_id, offset_hours):
        return 'сейчас не смена: письма сочиняются по часам, заданным у сайта'

    try:
        pairs = await _quiet(site_id)
    except Exception as e:
        logger_info(f'[dating] повод пула избранных не спросился: {e}')

        return ''

    if not pairs:
        # ⚠ Не «ошибка», а обычное состояние, и причин у него три: избранных нет
        # вовсе, анкеты не в сети, либо последним везде говорил он — тогда пишет
        # круг ответов, а не этот. Человек должен читать это как ответ, а не как
        # поломку.
        #
        # ⚠ «Затихших разговоров» из строки убрано намеренно: переписка в нашей
        # базе больше не условие — звёздочка сама означает, что разговор был
        # (см. `_quiet`). Прежний текст отправлял бы человека искать письма,
        # которых отбор уже не спрашивает.
        return ('писать некому: у анкет в сети нет избранных, которым сейчас '
                'уместно письмо')

    per_day = await _seconds(site_id, FAVORITE_MAIL_PER_DAY_SETTING,
                             FAVORITE_MAIL_PER_DAY_DEFAULT)
    gap_low, gap_high = await favorite_mail_gap_range(site_id)

    # ⚠ Пауза спрашивается **по анкете**, и анкет в паре списков меньше, чем пар:
    # тринадцать девушек против сотни пар. Спроси мы её на каждую пару, вопрос
    # повторялся бы десятками, а ответ у него один на девушку.
    soon: dict[int, str] = {}

    reasons = []
    for pair in pairs:
        profile_id_ = int(pair['profile_id'])
        if profile_id_ not in soon:
            soon[profile_id_] = await favorite_mail_girl_soon(
                profile_id_, gap_low, gap_high, _girl_said(pair))

        why = (await favorite_mail_person_soon(site_id, str(pair['uid']), per_day)
               or soon[profile_id_])
        # Есть хоть одна пара, которой можно писать, — повода объясняться нет:
        # круг наберёт её на ближайшем заходе.
        if not why:
            return ''

        reasons.append(f"{_addressee(pair)}: {why}")

    # ⚠ Показываем **одну** причину, а не список: шапка пула — одна строка, и
    # десять причин в ней превратились бы в полосу, которую не читают. Первая —
    # про ближайшую пару: `_quiet` отдаёт их по свежести разговора.
    tail = f' (и ещё {len(reasons) - 1})' if len(reasons) > 1 else ''

    return reasons[0] + tail


async def favorite_mail_person_soon(site_id: int, uid: str, per_day: int) -> str:
    """Рано ли писать этому человеку. Пустая строка — можно.

    Считает **дневной предел** — сколько писем этот человек получил от нас за
    сутки. Пауза здесь больше не живёт: она про девушку, а не про получателя, и
    отвечает за неё `favorite_mail_girl_soon`.

    ⚠ **Пара к `favorite_mail_girl_soon`, и ключи у них разные намеренно**: тот
    считает отправительницу, этот — получателя. Имена обязаны читаться парой,
    иначе следующий читатель решит, что одна из двух лишняя.

    ⚠ Имя публичное, без подчёркивания: правило нужно не только набору пула, но
    и окну «почему этой паре не пишут» (`mail_explain.py`). Подчёркивание
    означало бы «внутреннее дело модуля», а оно уже не внутреннее.

    ⚠ **Считается ушедшее ему от любой нашей анкеты** по всему сайту:
    рассылка и приставание. Письма считает получатель, а не наши таблицы и не
    наши девушки. ⚠ Наш ответ на его письмо предел не тратит — см.
    `favorite_mail_person_sent`.

    ## ⚠⚠ Считалось по паре, и от этого предел не работал

    Здесь стояло `profile_id = %s AND uid = %s` — счёт вёлся по паре «анкета +
    человек». Каждая девушка честно выдерживала свои два письма в сутки, но про
    других не знала, а избранным один мужчина бывает у многих.

    Поймано на живых данных: собеседник получил **четыре письма от четырёх разных
    девушек за одиннадцать минут** — 18:28, 18:31, 18:34, 18:39. Ни одна пара
    предела не превысила: у каждой было по одному письму при разрешённых двух.

    Чинится сменой ключа на `site_id`: название настройки — «писем **избранному**
    в сутки» — говорит про человека, и теперь код говорит о том же.

    ⚠ **Цена размена честная.** При тринадцати анкетах в сети «два письма в сутки»
    означало до двадцати шести; теперь означает два. Это и есть смысл настройки, но
    писем станет заметно меньше — если их нужно больше, поднимают саму настройку, а
    не обходят её числом девушек.

    ## ⚠⚠ А пауза уехала отсюда целиком

    Вторая настройка (`favorite_mail_gap`) стояла в этой же функции и считалась
    так же — по получателю. Смысл был «одному человеку не чаще раза в четыре
    часа», и **про девушку он не говорил ничего**: круг отправки, уносящий по
    письму в минуту, выпускал от одной Елены четыре письма четверым за восемь
    минут, и каждая пара при этом была чиста.

    Теперь пауза значит «одна девушка — одно письмо за срок», живёт в
    `favorite_mail_girl_soon` и спрашивается **отдельно**: у неё другой ключ
    (анкета, а не получатель) и другой спрашивающий — кроме набора её проверяет
    круг отправки, которому предел получателя знать незачем.

    ⚠ **Сбой базы — не пишем.** Непрочитанный счёт означает неизвестный предел, а
    лишнее письмо живому человеку отменить нельзя. Та же сторона ошибки, что у
    дневного потолка отправки.

    ⚠ Сам счёт живёт в `favorite_mail_person_sent`, здесь только вердикт и
    слова: число нужно и окну «почему этой паре не пишут», а второй такой запрос
    разошёлся бы с этим на первой правке — окно показывало бы одно число, а
    предел считал по другому.
    """
    got = await favorite_mail_person_sent(site_id, uid)
    if got is None:
        return 'не удалось посчитать, сколько ему уже написали'

    day_sent = int(got['count'])
    when = got['last_at']
    since = await _since(when) if when is not None else None

    if day_sent < int(per_day):
        return ''

    # ⚠ **Дневной предел называет, когда он отпустит.** «Ушло два — предел два»
    # отвечает на «почему», но не на «и что теперь»: человек у экрана решает,
    # ждать ему или поднимать настройку, а для этого нужен срок. Сутки считаются
    # скользящим окном, поэтому освободится оно тогда, когда из окна выпадет самое
    # давнее письмо, — но проще и честнее сказать про ближайшее.
    count_word = f'{day_sent} {_letters_word(day_sent)}'

    # ⚠⚠ **Строка называет ту границу, по которой счёт и шёл.** Их две
    # (`favorite_mail_person_sent`), и после его ответа считается не «за сутки»,
    # а «с его письма». Скажи мы «за сутки» в обоих случаях — человек увидел бы
    # «ушло 1 за сутки» там, где за сутки ушло четыре, и пошёл бы искать
    # пропажу в журнале доставки.
    his_since = (await _since(got['his_last'])
                 if got.get('his_last') is not None else None)
    head = (f'с его письма {_ago_word(his_since)} ушло {count_word}'
            if his_since is not None and his_since < FAVORITE_MAIL_DAY_SEC
            else f'за сутки уже ушло {count_word}')

    return (f'{head} — предел {int(per_day)} в сутки'
            + (f', последнее {_ago_word(since)}' if since is not None else ''))


async def favorite_mail_person_sent(site_id: int, uid: str):
    """Сколько писем ушло этому человеку с его последнего ответа.

    Args:
        site_id: сайт-закладка.
        uid: собеседник на сайте.

    Returns:
        dict: `count` — писем после границы, `last_at` — время последнего
        (`None`, если писем не было), `his_last` — его последнее письмо
        (`None`, если он не писал). `None` целиком — спросить не удалось, и
        решает это вызывающий: предел отказывает в письме, окно молчит числом.

    ⚠⚠ **Единственное место, где письма получателю считаются.** Знание тут в
    четырёх частях — ключ (`site_id`, а не анкета: предел на человека), набор
    пулов (`MAIL_SEND_COLD_TABLES` — те, которыми пишем **первыми**: рассылка и
    приставание), окно в сутки и граница по его письму. Разъедься копии, и окно
    показывало бы одно число, а предел считал по другому — причём молча.

    ⚠ Цена прежней копии известна: пока ключом был `profile_id`, один человек
    получил четыре письма от четырёх девушек за одиннадцать минут при пределе
    два.

    ## ⚠⚠ Границы две, и берётся поздняя из них

    `GREATEST(сутки назад, его последнее письмо)` — то есть счёт идёт «с его
    ответа, но не дальше суток».

    Прежде нижний край был один, суточный, и письма, ушедшие **до** его ответа,
    держали пару до конца суток. Снято с прода 11.10.2026: Diana ↔ Bruce — два
    письма ушли, он ответил в 10:16, и приставание молчало с «за сутки уже ушло
    2 письма — предел 1 в сутки», хотя оба ушли раньше его ответа.

    Довод тот же, по которому неделей раньше чинили инициативу: его ответ —
    ровно то событие, ради которого занятие работает, и наказывать за прошлое
    живой разговор нельзя. Читается правило так: **N писем на каждый его
    ответ**, и не больше N в сутки.

    ⚠⚠ `COALESCE` обязателен: `GREATEST` с одним `NULL` отдаёт `NULL`, сравнение
    становится ложным, счёт — нулём, то есть предел снялся бы у **всех**, кто
    нам ни разу не писал, — а это большинство. Та же грабля записана у
    `initiative._since_sql`.

    ⚠ Суточное окно его письмо **поднимает, а не заменяет**: настройка зовётся
    «в сутки», и считай мы от начала времён, предел стал бы вечным.

    ⚠ Граница ключуется **человеком** (`site_id + uid`), как и сам счёт: его
    письмо любой нашей девушке снимает предел целиком. Иначе письмо Диане
    сбрасывало бы счёт только у Дианы, а Елена держала бы его до конца суток —
    при общем на двоих пределе.

    ⚠ В счёт идёт **и наш ответ** на его письмо: человеку всё приходит в одну
    почту. Отсюда при `per_day = 1` выходит «он написал → ответ ушёл → до
    следующего его письма тихо», и это не недоработка, а смысл единицы.

    ⚠ Чат границей не считается — только `mail_in`. Отклик в чате говорит о
    разговоре, но не о том, что читают **почту**; пиши мы письма активному в
    чате и глухому к письмам, предела у него не стало бы вовсе.
    """
    from src.dating.mail_send import MAIL_SEND_COLD_TABLES, mail_sent_union

    sql = ('SELECT COUNT(*) AS per_day_count, MAX(sent_at) AS last_at,'
           f'       {FAVORITE_MAIL_HIS_LAST_SQL} AS his_last'
           '  FROM ('
           + mail_sent_union("site_id = %s AND uid = %s AND status = 'sent'",
                             tables=MAIL_SEND_COLD_TABLES)
           + ') AS sent'
             ' WHERE sent_at IS NOT NULL'
             '   AND sent_at > GREATEST(NOW() - INTERVAL 1 DAY,'
             f'         COALESCE({FAVORITE_MAIL_HIS_LAST_SQL},'
             "                  '1000-01-01 00:00:00'))")

    # ⚠ По паре доводов на каждую подстановку, и порядок тут — порядок текста:
    # столбец «его последнее», затем по одной паре на ветку союза, затем
    # граница. Переставь их — запрос не падает, а отвечает неправду.
    args = (int(site_id), str(uid)) * (len(MAIL_SEND_COLD_TABLES) + 2)

    try:
        async with mysql_get_db_async() as db:
            await db.execute(sql, args)
            row = await db.fetchone()
    except Exception as e:
        logger_info(f'[dating] счёт писем {uid} на сайте #{site_id} '
                    f'не спросился: {e}')

        return None

    return {'count': int((row or {}).get('per_day_count') or 0),
            'last_at': (row or {}).get('last_at'),
            'his_last': (row or {}).get('his_last')}


