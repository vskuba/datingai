"""Переписка с избранными: письмо, возобновляющее затихший разговор.

Цепочка почты до сих пор замыкалась на ответах: мы разослали, он ответил, мы
ответили — и ждём. Он не пишет, разговор затихает, а повода написать у нас нет:
все наши поводы были реакцией на его письмо.

Здесь повод появляется. Письмо **пишем первыми** тем, кто уже отвечал, — то есть
избранным (`favorite`), и это не знакомство, а напоминание о себе тому, кто
замолчал.

## Кого берём в работу

| Условие | Почему |
|---------|--------|
| человек в избранных этой анкеты | звёздочку ставят тому, кто отвечал: разговор был |
| **анкета в сети** (`status = 'online'`) | письмо уходит от её имени, и уносит его отправка — а та тоже ждёт, пока девушка на сайте |
| **собеседник в сети** | письмо застаёт его на сайте; написанное в отсутствие уйдёт в груду непрочитанного, а предел в два письма будет потрачен |
| последним говорил **не он** | он молчит — это и есть повод; ответить ему должен круг ответов, а не этот |
| прошло не меньше `favorite_mail_gap` | два письма подряд за час выдают робота |
| за сутки ему ушло меньше `favorite_mail_per_day` | предел на человека, а не на сайт |
| в пуле нет его черновика | второй черновик тому же человеку — это два письма подряд, отложенных на потом |
| ему не пишет другая наша анкета этим заходом | шаблон общий: два одинаковых письма от двух женщин выдают агентство |

## ⚠⚠ Переписки в нашей базе быть не обязано

Условия «была переписка» в списке нет, и это исправление по живой жалобе: вкладка
отвечала «писать некому: у избранных нет затихших разговоров» при полутора десятках
избранных у каждой анкеты.

**Звёздочка сама по себе означает, что разговор был.** Её ставят тому, кто отвечал;
шёл разговор на сайте — возможно, задолго до панели, — и в `dating_message` мог не
приехать вовсе. Требуя своих записей, мы отказывались писать именно там, где повод
очевиднее всего.

Что при этом не изменилось: **частоту держат пределы** (`favorite_mail_per_day`,
`favorite_mail_gap`), считая всё ушедшее человеку. Переписка в базе защитой от
навязчивости никогда не была.

## ⚠⚠ Шаблон один на весь заход, и вызов LLM тоже один

Прежде письмо сочинял агент **на каждую пару**: пул в полсотни писем стоил
полусотни вызовов LLM и минут ожидания у нажатой кнопки. Теперь устроено как у
инвайтов:

1. бросаем жребий — с именем ли письмо (`favorite_mail_name_percent`), каким
   приёмом, какой длины, будет ли рассказ девушки о себе
   (`favorite_mail_story_percent`) и кончится ли вопросом
   (`favorite_mail_question_percent`);
2. **один** запрос агенту — он присылает шаблон с меткой `[[companion_name]]`;
3. раскладываем шаблон по парам: метка заменяется первым словом имени.

⚠⚠ **Цена размена здесь выше, чем у инвайтов, и названа прямо.** Инвайт уходит
незнакомому — терять нечего. Письмо уходит тому, кто **уже отвечал**: прежняя
версия видела переписку пары и отталкивалась от неё, шаблон же общий и не видит
ничего. Разговор возобновляется теперь не «с того места», а заново.

Держится это тем, что письмо и не притворяется продолжением: промпт прямо
запрещает ссылаться на прошлые слова — то самое правило, что раньше включалось
только на пустой истории. Живому человеку такое письмо читается как «вспомнила о
тебе», а не как ответ на реплику, которой он не помнит.

## ⚠⚠ Один человек — одно письмо за заход

Мужчина бывает избранным у двух наших девушек, и отбор возвращает обе пары. Прежде
это было законно: письма писались разные. С общим шаблоном он получил бы **два
одинаковых письма от двух разных женщин**, то есть увидел бы агентство. То же
правило и тот же довод, что у инвайтов.

⚠ **Порядок проверок — от дешёвого к дорогому.** Онлайн читается из снимка в
Redis, пределы — запросом к базе, и только потом зовётся агент. Шаблон к тому же
спрашивается **лениво** — на первой паре, которая прошла все проверки: заход, где
не прошла ни одна, не должен стоить вызова LLM.

⚠ **Оба предела — про человека, а не про сайт.** Письма считает получатель, а не
наши таблицы: сделай мы «два письма в сутки» на сайт, тринадцать анкет делили бы
их на всех, и занятие не работало бы вовсе.

⚠ **Считается всё ушедшее ему**, а не только этот пул: рассылка, ответ и
возобновление приходят человеку в одну почту. Тот же довод, по которому
`send_max_day` общий на рассылку и ответы.

## Чего здесь нет

**Отправки.** Письмо ложится в пул и ждёт. Уходит оно отдельным решением —
выключателем `favorite_mail_send_on`, снятым по умолчанию, — и уносит его общий
круг отправки, в часы `mailing_schedule`. Та же граница, что у рассылки и
ответов: необратимый шаг остаётся за человеком.

**Своего расписания.** Набор ничего не отправляет, а отправка идёт по часам всей
почты сайта. Второе расписание отвечало бы на тот же вопрос вторым голосом.
"""

