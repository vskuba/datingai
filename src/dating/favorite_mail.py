async def _sync_stars(site_id: int, profile_id: int = 0) -> None:
    """Переписывает списки избранных с сайта в нашу таблицу — по анкетам в сети.

    ⚠ **Только те, кто в сети**, и это не экономия: письмо всё равно пишут от
    анкеты на смене (`_quiet` берёт только их), а спрашивать сайт под спящей
    значило бы ходить туда ради строк, которые сегодня не понадобятся.

    ⚠ **Сбой одной анкеты не уносит остальных** и не роняет набор: список не
    пришёл — работаем по тому, что уже знаем. `favorite_sync` молчит сам.

    ⚠ **Без `api_base` не ходим вовсе**: у сайта без своего API списка избранных
    не спросить, и звёзды туда попадают только кругом звёздочек.
    """
    base = str(await site_setting(int(site_id), 'api_base') or '').strip()
    if not base:
        return

    password = str(await site_setting(int(site_id), 'api_password') or '')

    try:
        async with mysql_get_db_async() as db:
            await db.execute(
                'SELECT id, site_id, login, password, password_source'
                '  FROM profile'
                " WHERE site_id = %s AND enabled = 1 AND status = 'online'"
                '   AND (%s = 0 OR id = %s)',
                (int(site_id), int(profile_id or 0), int(profile_id or 0)))
            girls = [dict(row) for row in await db.fetchall() or []]
    except Exception as e:
        logger_info(f'[dating] анкеты для сверки избранных не спросились: {e}')

        return

    for girl in girls:
        await favorite_sync(girl, base, password_pick(girl, password))


def _sync_due(site_id: int) -> bool:
    """Пора ли сверять звёзды с сайтом. Первый заход после старта — да.

    В словаре лежит **момент, раньше которого нельзя**, а не момент прошлой
    сверки: так срок берётся из настройки один раз — при отметке, — и правка
    настройки не требует помнить, каким срок был в прошлый раз.
    """
    import time

    return time.monotonic() >= _sync_at.get(int(site_id), 0.0)


def _sync_mark(site_id: int, every: int) -> None:
    """Запоминает сверку: следующая не раньше чем через `every` секунд.

    ⚠ **Отметка ставится до похода, а не после.** Сверка идёт по анкете с
    запросом на каждую — восемь анкет это восемь запросов и почти секунда; не
    отметь мы сразу, следующий тик завёл бы вторую сверку поверх первой.
    """
    import time

    _sync_at[int(site_id)] = time.monotonic() + max(0, int(every))


def favorite_sync_forget(site_id: int = 0) -> None:
    """Забыть отметку сверки — для тестов и для правки настроек.

    Сменили срок на странице «Сайты» — следующий заход обязан его увидеть, а не
    досиживать прежний час.
    """
    if site_id:
        _sync_at.pop(int(site_id), None)

        return

    _sync_at.clear()


async def _quiet(site_id: int, profile_id: int = 0) -> list[dict]:
    """Пары «анкета — избранный», которым сейчас уместно написать.

    ⚠⚠ **Переписка в нашей базе больше не обязательна, и это исправление.**
    Прежде пара бралась только при наличии писем у нас — `JOIN` по сшивке всей
    почты, — и вкладка честно отвечала «писать некому: у избранных нет затихших
    разговоров» при полутора десятках избранных у каждой анкеты.

    Довод заказчика, и он верный: **звёздочка сама по себе означает, что разговор
    был**. Её ставят тому, кто отвечал; переписка могла идти на сайте задолго до
    панели либо приехать не полностью. Требуя своих записей, мы отказывались писать
    именно там, где повод очевиднее всего.

    Остаётся то, что и было смыслом отбора:

    ⚠ **Последним говорил не он.** Скажи последним он — письмо ему напишет круг
    ответов (`reply_round.py`), и наше возобновление пришло бы вторым
    подряд, не отвечая на заданный вопрос. Переписки нет вовсе — условие не мешает:
    последним не говорил никто.

    ⚠ **Кто уже ждёт в пуле — не берём.** Второй черновик тому же человеку это
    два письма подряд, просто отложенных: отправитель шлёт их по одному, но оба
    уйдут ему, и второе — не зная о первом.

    ⚠ **Частоту держат пределы, а не наличие истории** (`_too_soon`): два письма в
    сутки и четыре часа паузы, считая **всё** ушедшее ему. Это и есть защита от
    навязчивости; переписка в базе ею никогда не была.

    Порядок — по давности разговора, и пары без переписки идут первыми (`NULL`
    вперёд): у них повод старше всех — им не писали никогда.
    """
    from src.dating.mail_send import mail_sent_union

    # ⚠ «Последняя реплика» считается **по всей почте**, а не по одному источнику:
    # входящие письма (он), наши ответы и оба пула ушедшего (мы). Смотри мы только
    # входящие, затихшим выглядел бы всякий, кому мы писали последним, — включая
    # того, кому письмо ушло пять минут назад.
    sql = (
        'SELECT f.profile_id, f.uid,'
        '       COALESCE(c.name, comp.name, %s) AS name,'
        '       COALESCE(NULLIF(comp.photo, %s), c.photo, %s) AS photo,'
        # ⚠⚠ Анкета девушки уезжает агенту письма: из неё берутся её имя, ключ
        # фактов и биография (`agent_vars`, `agent_bio`). Прежде письмо писал
        # шаблон, не знавший ни её, ни его, — и полей этих не требовалось.
        '       p.id AS girl_id, p.site_id AS girl_site, p.login AS girl_login,'
        '       p.profile AS girl_card,'
        '       talk.last_at, talk.last_side'
        '  FROM favorite f'
        # ⚠ **Анкета обязана быть в сети**, а не просто включена. Письмо уходит
        # от её имени, и сайт показывает его от лица девушки, которой в этот
        # момент на сайте нет; а круг отправки такое письмо всё равно не возьмёт
        # (`send_round`), и пул набивался бы тем, что не уйдёт.
        "  JOIN profile p ON p.id = f.profile_id AND p.enabled = 1"
        "   AND p.status = 'online'"
        # ⚠ **`LEFT JOIN`, а не `JOIN`** — та самая правка: у избранного может не
        # быть ни одного письма в нашей базе, и это не повод его пропускать.
        '  LEFT JOIN ('
        '     SELECT profile_id, uid,'
        '            MAX(at) AS last_at,'
        '            SUBSTRING_INDEX(MAX(CONCAT(at, %s, side)), %s, -1) AS last_side'
        '       FROM ('
        # Его письма — отдельной веткой: `mail_in` не пул отправки, и в общем
        # списке ему места нет. Наши три — тем же перечислением, что у всех
        # прочих счётчиков почты.
        "          SELECT profile_id, uid, date_post AS at, 'him' AS side"
        '            FROM mail_in'
        '          UNION ALL '
        + mail_sent_union(
            "status = 'sent'",
            select="profile_id, uid, sent_at AS at, 'her' AS side") +
        '       ) AS all_mail'
        '      WHERE at IS NOT NULL'
        '      GROUP BY profile_id, uid) AS talk'
        '    ON talk.profile_id = f.profile_id AND talk.uid = f.uid'
        '  LEFT JOIN contact c'
        '    ON c.profile_id = f.profile_id AND c.uid = f.uid'
        '  LEFT JOIN companion comp'
        '    ON comp.site_id = f.site_id AND comp.uid = f.uid'
        ' WHERE f.site_id = %s AND (%s = 0 OR f.profile_id = %s)'
        # ⚠ Тот же набор, что делит разговоры между «Фаворитами» и «Входящими»
        # (`FAVORITE_STATES`): кого считаем избранным — один вопрос, и
        # ответ на него должен быть один.
        f'   AND f.state IN ({FAVORITE_STATES_SQL})'
        # ⚠ «Последним говорил не он»: либо мы, либо никто. `IS NULL` и есть
        # случай «переписки у нас нет» — он законный, см. докстринг.
        "   AND (talk.last_side IS NULL OR talk.last_side = 'her')"
        # ⚠⚠ **Черновик занимает ближайшую очередь девушки, поэтому условие по
        # анкете, а не по паре.** Прежде здесь стояло `d.uid = f.uid` — «второго
        # письма тому же человеку не пишем», — и этого было довольно, пока пауза
        # считалась по получателю. Теперь пауза считает отправительницу: лежащий
        # черновик уйдёт первым и займёт её срок целиком, а всё набранное сверх
        # него пролежит до вечера и протухнет — отбор берёт того, кто **сейчас** в
        # сети.
        #
        # Условие по анкете строже прежнего и его покрывает: нет черновика у
        # девушки — нет его и у пары.
        '   AND NOT EXISTS (SELECT 1 FROM favorite_mail d'
        '                    WHERE d.profile_id = f.profile_id'
        "                      AND d.status = 'draft')"
        # ⚠ И закрывшиеся от анкеты. «Ты замолчал» тому, кто просил не писать, —
        # худшее из наших писем, и сайт его всё равно не примет (`block.py`).
        # Условием в этом же запросе, а не отсевом после: список уходит в потолок
        # захода, и отсеки мы их позже — запрещённые пары съедали бы места живых.
        '   AND NOT EXISTS (SELECT 1 FROM block b'
        '                    WHERE b.profile_id = f.profile_id AND b.uid = f.uid)'
        ' ORDER BY talk.last_at')

    try:
        async with mysql_get_db_async() as db:
            await db.execute(sql, ('', '', '', ' ', ' ',
                                   int(site_id), int(profile_id), int(profile_id),
                                   *FAVORITE_STATES))
            rows = await db.fetchall()
    except Exception as e:
        logger_info(f'[dating] затихшие разговоры сайта #{site_id} '
                    f'не спросились: {e}')

        return []

    return [_pair_row(row) for row in rows or []]


def _pair_row(row) -> dict:
    """Строка пары с анкетой девушки, собранной под вызов агента.

    ⚠ **Анкета складывается здесь, а не у вызывающего.** Агенту она уходит в том
    же виде, что и в чате (`answer._agent_ask` ждёт строку `profile` с полями
    `id`, `site_id`, `login`, `profile`), и собирать её в цикле набора значило бы
    держать знание о её устройстве в двух местах.
    """
    pair = dict(row)

    pair['profile'] = {
        'id': int(pair.pop('girl_id', 0) or 0),
        'site_id': int(pair.pop('girl_site', 0) or 0),
        'login': str(pair.pop('girl_login', '') or ''),
        'profile': pair.pop('girl_card', None),
    }

    return pair


def _girl_sent_union(key: str) -> str:
    """Все ушедшие письма одной девушки — тремя пулами, одним списком.

    Args:
        key: чем подставляется её номер. `%s` — для отдельного запроса,
            `m.profile_id` — для связанного подзапроса внутри чужого `SELECT`.

    ⚠ **Тело у правила одно, а видов у него два**: круг набора спрашивает «рано
    ли ей писать» и получает словами, круг отправки отбирает письма запросом и
    получает условием. Разойдись они — пул набирал бы то, чего отправка не
    берёт, либо отправка уносила бы то, чего набор не считает готовым.

    ⚠ Перечисляет таблицы `mail_sent_union`, а не эта функция: список пулов один
    на проект.
    """
    from src.dating.mail_send import mail_sent_union

    return mail_sent_union(
        f"profile_id = {key} AND status = 'sent' AND sent_at IS NOT NULL")




def _minutes_now(offset_hours: int) -> int:
    """Минуты от начала местных суток."""
    return int((time.time() + int(offset_hours) * 3600) // 60 % (24 * 60))


async def _too_soon(site_id: int, uid: str, per_day: int) -> str:
    """Рано ли писать этому человеку. Пустая строка — можно.

    Считает **дневной предел** — сколько писем этот человек получил от нас за
    сутки. Пауза здесь больше не живёт: она про девушку, а не про получателя, и
    отвечает за неё `favorite_mail_girl_soon`.

    ⚠ **Считается всё ушедшее ему от любой нашей анкеты**: рассылка, ответ и
    возобновление, по всему сайту. Письма считает получатель, а не наши таблицы
    и не наши девушки.

    ## ⚠⚠ Считалось по паре, и от этого предел не работал

    Здесь стояло `profile_id = %s AND uid = %s` — счёт вёлся по паре «анкета +
    человек». Каждая девушка честно выдерживала свои два письма в сутки, но про
    других не знала, а избранным один мужчина бывает у многих.

    Поймано на живых данных: собеседник получил **четыре письма от четырёх разных
    девушек за одиннадцать минут** — 18:28, 18:31, 18:34, 18:39. Ни одна пара
    предела не превысила: у каждой было по одному письму при разрешённых двух.

    Чинится сменой ключа на `site_id`: название настройки — «писем **избранному**
    в сутки» — говорит про человека, и теперь код говорит о том же.

    ⚠ **Цена размена честная.** При тринадцати анкетах в сети «два письма в сутки»
    означало до двадцати шести; теперь означает два. Это и есть смысл настройки, но
    писем станет заметно меньше — если их нужно больше, поднимают саму настройку, а
    не обходят её числом девушек.

    ## ⚠⚠ А пауза уехала отсюда целиком

    Вторая настройка (`favorite_mail_gap`) стояла в этой же функции и считалась
    так же — по получателю. Смысл был «одному человеку не чаще раза в четыре
    часа», и **про девушку он не говорил ничего**: круг отправки, уносящий по
    письму в минуту, выпускал от одной Елены четыре письма четверым за восемь
    минут, и каждая пара при этом была чиста.

    Теперь пауза значит «одна девушка — одно письмо за срок», живёт в
    `favorite_mail_girl_soon` и спрашивается **отдельно**: у неё другой ключ
    (анкета, а не получатель) и другой спрашивающий — кроме набора её проверяет
    круг отправки, которому предел получателя знать незачем.

    ⚠ **Сбой базы — не пишем.** Непрочитанный счёт означает неизвестный предел, а
    лишнее письмо живому человеку отменить нельзя. Та же сторона ошибки, что у
    дневного потолка отправки.
    """
    # ⚠ `site_id`, а не `profile_id`: предел на человека, и неважно, которая из
    # наших девушек ему написала. Все три таблицы этот столбец несут.
    from src.dating.mail_send import MAIL_SEND_TABLES, mail_sent_union

    sql = ('SELECT COUNT(*) AS per_day_count, MAX(sent_at) AS last_at FROM ('
           + mail_sent_union("site_id = %s AND uid = %s AND status = 'sent'")
           + ') AS sent'
             ' WHERE sent_at IS NOT NULL AND sent_at > NOW() - INTERVAL 1 DAY')

    try:
        async with mysql_get_db_async() as db:
            await db.execute(sql, (int(site_id), str(uid)) * len(MAIL_SEND_TABLES))
            row = await db.fetchone()
    except Exception as e:
        logger_info(f'[dating] счёт писем {uid} на сайте #{site_id} '
                    f'не спросился: {e}')

        return 'не удалось посчитать, сколько ему уже написали'

    day_sent = int((row or {}).get('per_day_count') or 0)
    when = (row or {}).get('last_at')
    since = await _since(when) if when is not None else None

    # ⚠ **Дневной предел называет, когда он отпустит.** «Ушло два — предел два»
    # отвечает на «почему», но не на «и что теперь»: человек у экрана решает,
    # ждать ему или поднимать настройку, а для этого нужен срок. Сутки считаются
    # скользящим окном, поэтому освободится оно тогда, когда из окна выпадет самое
    # давнее письмо, — но проще и честнее сказать про ближайшее.
    if day_sent >= int(per_day):
        count_word = f'{day_sent} {_letters_word(day_sent)}'

        return (f'за сутки уже ушло {count_word} — предел {int(per_day)} в сутки'
                + (f', последнее {_ago_word(since)}' if since is not None else ''))

    return ''


def _letters_word(n: int) -> str:
    """Склонение: «1 письмо», «2 письма», «5 писем».

    ⚠ Не украшение: строка идёт человеку на экран, и «ушло 2 писем» читается как
    сбой подстановки — то есть заставляет усомниться в самом числе.
    """
    tail = abs(int(n)) % 100
    if 11 <= tail <= 14:
        return 'писем'

    return {1: 'письмо', 2: 'письма', 3: 'письма', 4: 'письма'}.get(tail % 10, 'писем')


def _hours_word(seconds: int) -> str:
    """Срок словами: «4 часа». Настройка в секундах, человек думает часами."""
    hours = max(1, round(int(seconds) / 3600))

    tail = hours % 100
    if 11 <= tail <= 14:
        word = 'часов'
    else:
        word = {1: 'час', 2: 'часа', 3: 'часа', 4: 'часа'}.get(hours % 10, 'часов')

    return f'{hours} {word}'


def _left_word(seconds: int) -> str:
    """Сколько ещё ждать: «2 ч 40 мин», «35 мин».

    ⚠ Минуты нужны: пауза бывает в час, и «через 1 ч» вместо «через 5 мин»
    отправило бы человека ждать впустую.
    """
    minutes = max(1, round(int(seconds) / 60))
    if minutes < 60:
        return f'{minutes} мин'

    hours, rest = divmod(minutes, 60)

    return f'{hours} ч' + (f' {rest} мин' if rest else '')


def _ago_word(seconds: int) -> str:
    """Когда это было: «40 мин назад», «6 ч назад»."""
    return f'{_left_word(seconds)} назад'


async def _since(when) -> int:
    """Сколько секунд прошло с метки. ⚠ Считает **база**, а не процесс.

    Метки в базе стоят по часам сервера MySQL, а процесс живёт по своим: разойдись
    они на час — и пауза в четыре часа превратилась бы то в три, то в пять. Спорить
    об этом незачем, когда ту же разницу умеет посчитать тот, кто хранит метку.
    """
    async with mysql_get_db_async() as db:
        await db.execute('SELECT TIMESTAMPDIFF(SECOND, %s, NOW()) AS sec', (when,))
        row = await db.fetchone()

    return int((row or {}).get('sec') or 0)


