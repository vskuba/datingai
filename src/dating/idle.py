"""Почему круг ничего не сделал — записью, а не молчанием.

Круг, решивший не идти, до сих пор молчал. «Пул полон», «расписание не идёт»,
«отправка выключена», «анкет в сети нет» не оставляли следа нигде, кроме лога
процесса, который никто не читает.

## ⚠⚠ Молчание неотличимо от поломки

Это не теория: пул инвайтов на проде **застыл на 21 черновике** и не набирался
неделю. Со стороны выглядело как «работает» — круг исправно ходил, чистил ушедших
собеседников и не добавлял ничего. Понять, почему, можно было только чтением
кода: правило «набираем лишь пустой пул» плюс снятый выключатель отправки давали
вечный простой, и сказать об этом было некому.

С тех пор круги научились отвечать на вопрос «почему стоит» для **страницы**
(`send_why`, `invite_send_why`), но ответ живёт ровно пока открыта
вкладка. Ночной простой по-прежнему не оставляет следа.

## Что пишем и чего не пишем

⚠ **Только смену причины.** Круг идёт раз в минуту; пиши он каждый заход, за ночь
набежало бы пятьсот одинаковых строк, и настоящая беда утонула бы в них. Пока
причина та же — молчим, а счётчик заходов растёт.

⚠ **Уход простоя — тоже событие.** Круг пошёл — пишем «пошёл, простаивал N
заходов». Без этого в журнале остаётся вопрос без ответа: непонятно, чинилось оно
само или всё ещё стоит.

⚠ **Причина — словами для человека**, а не кодом состояния. Её читают в панели, и
«пул полон: 50 из 50» полезнее, чем `POOL_FULL`.

## Где это видно

В ленте журнала (`log`) под номером анкеты, если причина про анкету, и в
объявлениях (`error`), если про сайт целиком. Разделение по тому, **кто
чинит**: анкету правят в её карточке, сайт — на странице «Сайты».
"""

from logging_.logging_ import logger_info

# Сколько заходов подряд молчать об одной причине. Ноль — пишем каждую смену
# причины и ничего больше; это и есть правило, число здесь для читаемости.
IDLE_SAME_QUIET = 0

# Что сейчас известно про каждый круг: `{ключ: (причина, заходов подряд)}`.
#
# ⚠ **В памяти процесса, а не в Redis**, и это осознанно. Смена держателя
# перезапускается раз в час; после перезапуска первая же причина запишется
# заново — одна лишняя строка в час против отдельного ключа на каждый круг в
# чужом хранилище. Данные эти живут минуты и ничего не решают.
_seen: dict[str, tuple[str, int]] = {}


async def idle_write(key: str, why: str, site_id: int = 0,
                            profile_id: int = 0) -> bool:
    """Записывает причину простоя, если она сменилась. Иначе молчит.

    Args:
        key: чей это круг — `invite_send`, `mailing`, `favorite_mail`. Ключ, а не
            название: по нему сравнивается прошлая причина.
        why: почему не пошли, словами для человека. Пусто — круг **пошёл**, и
            это тоже записывается, если до того он простаивал.
        site_id: сайт, если причина про него.
        profile_id: анкета, если причина про неё.

    Returns:
        bool: записали ли. `False` — причина та же, что и в прошлый заход.

    ⚠ **Не бросает.** Журнал простоя не имеет права уронить круг: он про то,
    почему работа не идёт, и падать из-за него значило бы остановить и ту работу,
    которая идёт.
    """
    key = str(key or '')
    why = str(why or '').strip()
    was, count = _seen.get(key, ('', 0))

    if why == was:
        _seen[key] = (was, count + 1)

        return False

    _seen[key] = (why, 1)

    try:
        await _note(key, why, was, count, site_id, profile_id)
    except Exception as e:
        logger_info(f'[dating] журнал простоя «{key}»: {e}')

        return False

    return True


def idle_forget(key: str = '') -> None:
    """Забыть, что круг простаивал. Без ключа — все круги.

    Для тестов и для правки настроек: сменили выключатель — следующий заход
    обязан сказать об этом, даже если причина словами та же.
    """
    if key:
        _seen.pop(str(key), None)

        return

    _seen.clear()


# ── Приватное ────────────────────────────────────────────────────────────────

async def _note(key: str, why: str, was: str, count: int, site_id: int,
                profile_id: int) -> None:
    """Куда легла запись: в журнал анкеты или в объявления по сайту.

    ⚠ **Разделение по тому, кто чинит.** Анкету правят в её карточке — там и
    журнал; сайт правят на странице «Сайты» — туда и объявление. Свали мы всё в
    одно место, человек искал бы причину не там, где она чинится.
    """
    from src.dating.error import error_clear, error_write
    from src.dating.log import log_write

    source = f'idle_{key}'

    # Круг пошёл: гасим прежнее объявление и говорим, сколько простояли.
    if not why:
        if profile_id:
            await log_write(int(profile_id), 'info',
                                   f'Работа пошла — простояли заходов: {count}')
        else:
            await error_clear(source, int(site_id or 0))

        return

    if profile_id:
        await log_write(int(profile_id), 'info', f'Работа стоит: {why}')

        return

    await error_write(source, f'работа стоит: {why}', int(site_id or 0))
