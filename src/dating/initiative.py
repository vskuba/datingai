"""Инициатива: девушка пишет первой, когда разговор затих.

## Зачем

Разговор кончается не словом «пока», а молчанием: мы ответили, он не ответил.
Автоответ такую пару не видит вовсе — он отвечает на входящее, а входящего нет.
Инициатива её поднимает: через настроенный срок девушка сама спрашивает что-то
новое.

## ⚠⚠ Чем это **не** является

Не инвайт: там первая реплика незнакомому человеку, здесь продолжение начатого
разговора. Не автоответ: тот отвечает на сказанное, а здесь отвечать не на что.

Ближе всего механизм к тому, что уже делает роль `man` (`ANSWER_NUDGE_PROMPT`):
она возвращается после тишины сама. Инициатива — то же самое для женской анкеты,
только со сроком и числом заходов, которые задаёт сайт.

## Четыре настройки, и каждая своё

| Настройка | Что задаёт |
|-----------|------------|
| `chat_initiative_after` | через сколько минут тишины пишем **впервые** — от |
| `chat_initiative_after_max` | тот же срок — **до**; между ними жребий |
| `chat_initiative_reset_after` | через сколько **часов** возвращаемся снова |
| `chat_initiative_repeat` | сколько раз **подряд** возвращаемся, пока он молчит |
| `chat_initiative_max_day` | предохранитель: сколько инициатив паре за сутки |

Пятая, `chat_initiative_send_every`, живёт у круга: она про отправку, не про
отбор (`initiative_round.py`).

## ⚠⚠ Пределов два, и они отвечают на разные вопросы

Это главное в отборе, и один предел здесь уже стоял — дневной, не обнулявшийся
его ответом. Он отвечал на вопрос «сколько раз в день мне напишут», и на него же
отвечал бы потолок; но живой разговор он глушил наглухо.

**`chat_initiative_repeat` — сколько раз подряд мы зовём молчащего.** Его ответ
счёт **обнуляет**: ответил — значит разговор жив, и прошлые заходы перестают
считаться. Это и есть защита, ради которой предел заводился: три подряд «ты
тут?» в пустоту выдают автомат надёжнее любого текста. Молчание — тоже ответ.

⚠⚠ **Обнуление само себя ограничивает, и в этом вся соль.** Новая инициатива
требует **его реплики**: не ответил — счёт не обнулился, и второй заход не
уйдёт. Прежний довод против обнуления («отвечающий через раз получит инициативу
хоть двадцать раз в сутки») верен буквально, но описывает не беду: двадцать раз
ответивший человек — это живой разговор, а не писание в пустоту.

**`chat_initiative_max_day` — потолок на пару за скользящие сутки**, и он стоит
поверх обнуления именно потому, что обнуление ничем не ограничено сверху.
Сторожит он не живого человека, а патологию: зацикленный автоответчик на той
стороне отвечает на всё, обнуляет счёт каждый раз — и без потолка пара получила
бы сорок реплик за сутки.

⚠ Мерка скользящая, как у инвайтов (`invite_repeat_max_day`): полночь ничего не
значит для того, кто читает сообщения.

⚠ Пределы считаются **в этом порядке** — сперва «подряд», потом дневной. Оба
дёшевы (один запрос на пару), но первый отсекает несравнимо чаще, и читать его
первым — то же, что читать условия от частого к редкому.

⚠⚠ **Срок бросается жребием, и жребий устойчив на один промежуток тишины.**
Одно число на сайт означало бы, что все затихшие пары оживают через одинаковое
время после последней реплики — ряд сообщений по линейке. Разброс даёт `_due_sec`,
и он выводит срок **из самой пары**, а не из случая: круг просыпается каждую
минуту, и свежий жребий на каждом тике рано или поздно выпал бы низким — работала
бы одна «от», а «до» не значила бы ничего.
"""


