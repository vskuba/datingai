"""Инициатива: девушка пишет первой, когда разговор затих.

## Зачем

Разговор кончается не словом «пока», а молчанием: мы ответили, он не ответил.
Автоответ такую пару не видит вовсе — он отвечает на входящее, а входящего нет.
Инициатива её поднимает: через настроенный срок девушка сама спрашивает что-то
новое.

## ⚠⚠ Чем это **не** является

Не инвайт: там первая реплика незнакомому человеку, здесь продолжение начатого
разговора. Не автоответ: тот отвечает на сказанное, а здесь отвечать не на что.

Ближе всего механизм к тому, что уже делает роль `man` (`ANSWER_NUDGE_PROMPT`):
она возвращается после тишины сама. Инициатива — то же самое для женской анкеты,
только со сроком и числом заходов, которые задаёт сайт.

## Пять настроек отбора, и каждая своё

| Настройка | Что задаёт |
|-----------|------------|
| `chat_initiative_after` | через сколько минут тишины пишем **впервые** — от |
| `chat_initiative_after_max` | тот же срок — **до**; между ними жребий |
| `chat_initiative_reset_after` | через сколько **часов** возвращаемся снова |
| `chat_initiative_repeat` | сколько раз **подряд** возвращаемся, пока он молчит |
| `chat_initiative_max_day` | сколько из этих заходов уместится в сутки |

Шестая, `chat_initiative_send_every`, живёт у круга: она про отправку, не про
отбор (`initiative_round.py`).

## ⚠⚠ Пределов два, и граница счёта у них **одна**

Считаются оба от **его последнего слова** (либо от ручного сброса, если он
позже) — одним выражением `_since_sql`. Ответил — счёт начинается
заново: разговор жив, и прошлые заходы перестают считаться. Молчание тоже
ответ, и ради него предел и заводился: три подряд «ты тут?» в пустоту выдают
автомат надёжнее любого текста.

**`chat_initiative_repeat` — сколько раз подряд зовём молчащего** за весь
промежуток тишины, какой бы длинный он ни был.

**`chat_initiative_max_day` — сколько из этих заходов уместится в сутки.** Он
не отнимает заходы, а **растягивает** их: при «подряд 7» и «в сутки 1»
молчащего зовут семь раз, но по разу в день.

⚠ Отсюда следует, что дневной предел **выше «подряд» не значит ничего**: счёт
за сутки — подмножество счёта «подряд», и при `max_day >= repeat` первым всегда
упирается второй. Так и устроено умолчание: предел берут в руки, когда хотят
растянуть заходы по дням, а не когда хотят ограничить их число.

⚠⚠ **Прежде дневной счёт его ответом не обнулялся, и это глушило живые пары.**
Он мерился просто от «сутки назад» и держал ту, что минуту как ответила: Diana ↔
Bruce — заход в 08:02, его ответ в 11:02, человек вдобавок сбросил счёт руками в
11:14, а окно всё равно отвечало «дневной потолок исчерпан: 1 из 1». Прежний
довод (предохранитель против зацикленного автоответчика на той стороне) верен
буквально, но цену назначал живому разговору: его ответ — ровно то событие, ради
которого занятие и работает. Патологию держит тот же предел, только теперь
числом за сутки **внутри одной тишины**: поставивший «в сутки 1» получает одну
инициативу в сутки при любом автоответчике.

⚠ Мерка скользящая, как у инвайтов (`invite_repeat_max_day`): полночь ничего не
значит для того, кто читает сообщения.

⚠ Пределы считаются **в этом порядке** — сперва «подряд», потом дневной. Оба
дёшевы (один запрос на пару), но первый отсекает несравнимо чаще, и читать его
первым — то же, что читать условия от частого к редкому.

⚠⚠ **Срок бросается жребием, и жребий устойчив на один промежуток тишины.**
Одно число на сайт означало бы, что все затихшие пары оживают через одинаковое
время после последней реплики — ряд сообщений по линейке. Разброс даёт `_due_sec`,
и он выводит срок **из самой пары**, а не из случая: круг просыпается каждую
минуту, и свежий жребий на каждом тике рано или поздно выпал бы низким — работала
бы одна «от», а «до» не значила бы ничего.
"""


