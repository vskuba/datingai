async def initiative_make(site_id: int, limit: int = 0) -> dict:
    """Набирает пул инициативы по сайту.

    Args:
        site_id: сайт-закладка.
        limit: сколько карточек завести за заход. Ноль — без предела.

    Returns:
        dict: `made` — сколько карточек завели, `skipped` — сколько пар пропущено,
        `errors` — что не вышло.

    ⚠⚠ **Словами про пустоту отвечает не эта функция, а `initiative_why`.** Здесь
    лежал ещё и ключ `why` с фразой «инициатива выключена настройками сайта» — его
    **не читал никто**: круг берёт из ответа `made`, ручка колонки зовёт
    `initiative_why`. То есть на один вопрос отвечали два места, и худшее из них
    молчало в пустоту: две разных причины (обнулён срок, обнулён потолок) оно
    сводило в одну фразу. Понадобится ответ здесь — звать `initiative_why`, а не
    заводить вторую формулировку.
    """
    after, after_max = await _after_range(site_id)
    repeat = await _repeat(site_id)
    max_day = await _max_day(site_id)
    reset_sec = await _reset_after(site_id)

    # ⚠ Выключает занятие **нижняя** граница: ноль в ней значит «не возвращаться
    # к затихшим вовсе». Ноль в верхней — всего лишь «без разброса».
    if after <= 0 or repeat <= 0:
        return {'made': 0, 'skipped': 0, 'errors': []}

    made = skipped = 0
    errors = []

    for profile in await _profiles(site_id):
        # ⚠ Агента спрашиваем **на анкету**, а не на пару: он один и тот же для
        # всех её разговоров, а поход к соседу за номером стоит запроса.
        agent = await _agent(profile)
        if not agent:
            continue

        for pair in await _quiet(int(profile['id']), after, after_max, repeat,
                                 max_day, reset_sec):
            if limit and made >= int(limit):
                return {'made': made, 'skipped': skipped, 'errors': errors}

            got = await _one(profile, agent, pair)
            if got == 'made':
                made += 1
            elif got.startswith('ошибка:'):
                errors.append(got[7:])
            else:
                skipped += 1

    return {'made': made, 'skipped': skipped, 'errors': errors}


async def initiative_why(site_id: int) -> str:
    """Почему пул инициативы пуст — словами. Пусто — сказать нечего.

    Args:
        site_id: сайт-закладка.

    Returns:
        str: одна строка для колонки пула, человеческими словами.

    ## ⚠⚠ Ради этого всё и написано: пустое место неотличимо от поломки

    Человек открывает колонку, видит пустоту и не знает, что перед ним: набор
    снят, настройка обнулена, девушки спят или сломалось. Раньше здесь стояла
    одна фраза на все случаи — «круга инициативы ещё не сделан», — и она пережила
    сам круг: тот работает с сентября, а колонка всё уверяла, что занятия нет.

    ## ⚠⚠ Почему здесь, а не у круга

    Лежала она в `initiative_round.py` и **тянула приватные соседа** отложенным
    импортом: `_after_range`, `_repeat`, `_profiles`. То есть круг знал про
    устройство отбора ровно столько же, сколько сам отбор, — и правка любого из
    трёх молча меняла смысл чужой подсказки.

    Спрашивает она о том, что знает этот модуль, и только о нём: выключатель
    сайта, сроки, потолок, анкеты в сети. Значит и отвечать ей отсюда — тогда
    приватное остаётся приватным, а подсказка не может разойтись с отбором,
    потому что зовёт те же функции, что и он.

    ⚠ Круг при этом ничего не потерял: пул он набирает `initiative_make`, а
    объяснять пустоту — не его работа. Своего `_sites()` подсказке тоже не нужно:
    выключатель одного сайта читает `_on`, и это один запрос вместо обхода всех.

    ⚠⚠ **Про погашенный сайт (`is_gone`) подсказка не знает, и это принято
    сознательно.** Круг обходит сайты `round_sites`, а тот гасшие отбрасывает
    всегда; `_on` же читает только колонку флага. Значит у сайта, погашенного
    соседом при поднятом флаге, последняя строка скажет «затихших разговоров
    сейчас нет» вместо правды «круг сюда не ходит».

    Цена мала, а плата за точность велика. Выбрать такой сайт в панели нельзя:
    селект берёт `site_rows`, а тот гасшие не отдаёт, — то есть дойти сюда можно
    только руками собранным адресом, и ответ будет не действием, а одной
    неточной фразой. Прежняя версия, спрашивавшая `_sites()`, врала на том же
    месте иначе и хуже: гасший сайт она объявляла «набор выключен», советуя
    поднять галочку, которая и так поднята.

    ⚠ Признак пересмотреть: гасшие сайты станут доступны выбору в панели — или
    появится вторая дверь, зовущая подсказку по номеру извне. Тогда `is_gone`
    спрашивается **здесь же, своей строкой**, а не добавляется в `_on`:
    «сайт погашен» и «набор снят» — разные ответы человеку.

    ⚠ **Порядок — от решённого к преходящему.** Снятый выключатель важнее
    обнулённой настройки, а та важнее того, что прямо сейчас никто не в сети:
    первое человек сделал сам, последнее пройдёт само.

    ⚠⚠ **Последняя строка — не пустота, а утверждение.** Дойдя до неё, мы знаем,
    что мешать некому: выключатель поднят, сроки заданы, девушки в сети. Значит
    затихших пар на прошлом тике не нашлось, и сказать об этом надо прямо —
    молчание здесь снова читалось бы как поломка.
    """
    site_id = int(site_id or 0)
    if not site_id:
        return ''

    try:
        if not await _on(site_id):
            return ('набор инициативы выключен: поднять — галочка «набор '
                    'инициативы» в карточке анкеты')

        after, _ = await _after_range(site_id)
        if after <= 0:
            return ('срок инициативы обнулён: настройка сайта «Инициатива, '
                    'проявить через минут (от)»')

        if await _repeat(site_id) <= 0:
            return ('заходов разрешено ноль: настройка сайта «Инициатива, '
                    'сколько раз подряд звать молчащего»')

        if not await _profiles(site_id):
            return ('ни одна анкета сайта не в сети: инициатива уходит в чат, '
                    'а это вход под анкетой')

        # ⚠ Про пределы говорим здесь же, одной оговоркой. Проверить их по
        # месту нельзя: они считаются **на пару**, а эта подсказка про сайт —
        # перебрать все пары значило бы запрос на каждую ради строки в шапке.
        # Умолчать хуже: «затихших нет» при полном журнале читается как поломка.
        return ('затихших разговоров сейчас нет: круг возвращается к паре, '
                f'когда она молчит дольше срока, и берёт по '
                f'{INITIATIVE_PER_PROFILE} на анкету за раз. Пары, которых уже '
                'позвали, не считаются затихшими, пока он не ответит — а если '
                'дневной предел ниже «подряд», то и пока не истекли сутки')
    except Exception as e:
        logger_info(f'[dating] повод пустоты инициативы не спросился: {e}')

        # Молчим: подсказка не обязана работать, когда не работает база. Пустая
        # строка означает «сказать нечего», а не «всё хорошо».
        return ''


async def initiative_blocked(site_id: int,
                             pairs: list[tuple[int, str]]) -> set:
    """Пары, чей счёт заходов упёрся в потолок сайта.

    Args:
        site_id: сайт-закладка — из него берётся потолок `chat_initiative_repeat`.
        pairs: пары `(номер анкеты, собеседник)`, о которых спрашивают.

    Returns:
        set: подмножество `pairs` — те, которым инициатива больше не уйдёт, пока
        он не ответит или человек не сбросит счёт руками.

    ## ⚠⚠ Это про потолок, а не про «почему пул пуст»

    Отбор круга спрашивает больше: срок тишины, дневной потолок, сторону
    последней реплики. Здесь ответ на один вопрос — тот, который задаёт иконка в
    шапке разговора: «к этой паре мы больше не вернёмся сами?»

    Смешивать их нельзя: иконка, краснеющая от «сейчас не вышел срок», горела бы
    почти всегда и ничего не значила.

    ⚠ **Одним запросом на всю страницу**, а не по строке: диалогов на странице
    до пятидесяти, и запрос на каждую стоил бы пятидесяти походов в базу ради
    одного значка.

    ⚠ Счёт берётся общим выражением (`_in_row_sql`) — тем же, которым
    отбирает круг.
    """
    pairs = [(int(one), str(two)) for one, two in (pairs or []) if int(one or 0)]
    if not pairs:
        return set()

    repeat = await _repeat(int(site_id or 0))
    # ⚠ Ноль в потолке — занятие выключено, и «упёрлась» бессмысленно: иконка
    # горела бы у всех пар сразу, объясняя не потолок, а снятое занятие.
    if repeat <= 0:
        return set()

    # ⚠ Спрошенные пары приезжают подзапросом `UNION ALL`, а не конструктором
    # `VALUES`: тот есть только с MySQL 8.0.19, и выигрыша от него здесь нет.
    asked = ' UNION ALL '.join(['SELECT %s AS profile_id, %s AS uid']
                               + ['SELECT %s, %s'] * (len(pairs) - 1))
    args = [value for pair in pairs for value in pair]

    async with mysql_get_db_async() as db:
        await db.execute(
            'SELECT d.profile_id, d.uid FROM (' + asked + ') d WHERE '
            + _in_row_sql('d.profile_id', 'd.uid') + ' >= %s',
            (*args, int(repeat)))
        rows = await db.fetchall() or []

    return {(int(row['profile_id']), str(row['uid'])) for row in rows}


async def initiative_explain(profile_id: int, uid: str) -> dict:
    """Всё об инициативе одной пары: счета, сроки, потолки и что мешает сейчас.

    Args:
        profile_id: анкета.
        uid: собеседник на сайте.

    Returns:
        dict: настройки сайта, счета пары, сроки и `blockers` — список помех
        словами, в том же порядке, в каком их проверяет круг. Пустой список
        значит «пара годна прямо сейчас».

    ## ⚠⚠ Зачем отдельная функция, а не «посчитать на странице»

    Правил у занятия восемь, и семь из них невидимы: человек видит пустую колонку
    либо красный значок и не знает, упёрлась пара в потолок, не вышел ли срок или
    она не годится вовсе. Это тот же урок, что у `initiative_why` для колонки
    пула, только про **пару**, а не про сайт.

    ⚠ **Считает сервер теми же выражениями, что и круг** — счёт «подряд» берётся
    `_in_row_sql`, срок пары `_due_sec`, пределы теми же `_repeat` и
    `_max_day`. Своя копия на странице разошлась бы с кругом на первой правке, и
    окно объясняло бы занятие, которого нет.

    ⚠⚠ **Условия годности здесь переписаны одной парой, и это цена.** Отбор круга
    (`_quiet`) идёт по всем парам анкеты разом и выражен иначе; свести их в один
    запрос не выходит. Поэтому за совпадением следит тест
    (`test_initiative_explain.py`): он гоняет обе дороги по одним данным и ловит
    расхождение, а не надеется на внимательность.

    ⚠ Чего здесь **нет намеренно** — предсказания «когда уйдёт следующая».
    Отправка идёт своим кругом со своей паузой (`chat_initiative_send_every`), и
    зависит она от всего сайта: назвать минуту значило бы соврать точностью.
    Окно отвечает «когда пара станет годной», а это честно считается.
    """
    profile_id, uid = int(profile_id or 0), str(uid or '')
    if not profile_id or not uid:
        return {}

    async with mysql_get_db_async() as db:
        await db.execute('SELECT site_id FROM profile WHERE id = %s', (profile_id,))
        site_id = int(((await db.fetchone()) or {}).get('site_id') or 0)

    on = await _on(site_id)
    after, after_max = await _after_range(site_id)
    repeat = await _repeat(site_id)
    max_day = await _max_day(site_id)
    reset_after = await _reset_after(site_id)

    state = await _pair_state(profile_id, uid)
    if not state:
        return {'site_id': site_id, 'known': False, 'on': on,
                'after_sec': after, 'after_max_sec': after_max,
                'repeat': repeat, 'max_day': max_day,
                'reset_after_sec': reset_after,
                'blockers': ['переписки с этим собеседником нет вовсе']}

    in_row = int(state.get('in_row') or 0)
    in_day = int(state.get('in_day') or 0)
    quiet = int(state.get('quiet_sec') or 0)
    # Срок **этой** пары: жребий между границами, тот же, что бросает круг.
    due = _due_sec(profile_id, uid, state.get('last_at'), after, after_max)

    # ⚠ Порядок — тот же, что у круга: от решённого человеком к преходящему.
    # Иначе окно называло бы главной помехой ту, что пройдёт сама через минуту.
    blockers = []
    if not on:
        blockers.append('набор инициативы выключен у сайта')
    if repeat <= 0:
        blockers.append('потолок заходов обнулён: занятие выключено')
    if not state.get('his_last'):
        blockers.append('он не написал ни разу — это неотвеченный инвайт, '
                        'и возвращаться к нему работа инвайтов')
    if state.get('last_side') != 'out' and not state.get('last_silent'):
        blockers.append('последним говорил он, и ответ ещё не решён — '
                        'реплику ждёт автоответ')
    if repeat > 0 and in_row >= repeat:
        blockers.append(f'потолок заходов подряд исчерпан: {in_row} из {repeat}')
    if in_day >= max_day:
        blockers.append(f'дневной потолок исчерпан: {in_day} из {max_day} за сутки')
    if quiet < due:
        blockers.append(f'срок тишины не вышел: молчит {quiet // 60} мин '
                        f'из нужных {due // 60}')
    # ⚠⚠ Срок возврата спрашивается **только у повторного захода** (`in_row > 0`)
    # и только когда он задан: ноль — «сброса нет», и условие тогда не участвует
    # вовсе. То же `(%s = 0 OR cnt.in_row = 0 OR ...)`, что и в отборе круга.
    if reset_after and in_row > 0 and quiet < reset_after:
        blockers.append(f'повторный заход ждёт свой срок: молчит {quiet // 3600} ч '
                        f'из нужных {reset_after // 3600}')

    return {
        'site_id': site_id, 'known': True, 'on': on,
        # Настройки сайта — их человек и правит, увидев окно.
        'after_sec': after, 'after_max_sec': after_max, 'repeat': repeat,
        'max_day': max_day, 'reset_after_sec': reset_after,
        # Счета пары.
        'in_row': in_row, 'in_day': in_day, 'left': max(0, repeat - in_row),
        'capped': bool(repeat > 0 and in_row >= repeat),
        'day_capped': bool(in_day >= max_day),
        # Время: что когда было и сколько ждать.
        'last_at': state.get('last_at'), 'last_side': state.get('last_side'),
        'his_last': state.get('his_last'), 'reset_at': state.get('reset_at'),
        'silent': bool(state.get('last_silent')),
        'quiet_sec': quiet, 'due_sec': due,
        # Сколько осталось ждать годности. ⚠ Ноль — «срок вышел», а не «сейчас
        # уйдёт»: мешать может и потолок, о нём говорит `blockers`.
        'wait_sec': max(0, max(due, reset_after if (reset_after and in_row) else 0)
                        - quiet),
        'sent': state.get('sent') or [],
        'blockers': blockers,
    }


async def _one(profile: dict, agent: int, pair: dict) -> str:
    """Одна пара: спросить агента и положить карточку. Исход — словами."""
    profile_id = int(profile['id'])
    uid = str(pair['uid'])
    name = str(pair.get('name') or '')
    who = f'{name} {uid}'.strip()

    # ⚠ Карточка у пары уже лежит — второй не заводим. Ключ базы это и так
    # запретит, но платить за вызов LLM перед отказом вставки незачем.
    if await chat_initiative_waiting(profile_id, uid):
        return 'есть'

    language = str(pair.get('language') or 'en')

    # ⚠⚠ `anyway=True` всегда. Инициатива, на которую агент промолчал, — заход,
    # потраченный впустую: пара останется затихшей, а счётчик повторов не
    # сдвинется. Судья при этом не перестаёт проверять текст, он лишь не вправе
    # выбрать молчание (`wf_dating_talk_answer_anyway`).
    # ⚠ Историю не спрашиваем: обе — чат и письма — берёт сам `_agent_ask`.
    # ⚠⚠ **Вопрос пуст, и это правильно.** `prompt_user` у соседа означает «что
    # сказал собеседник», а он ничего не говорил — потому мы и пишем. Задание
    # «заговори первой, приёмом из жребия» целиком лежит в промпте ветки
    # «Инициатива»; дублировать его вопросом значило бы спорить с промптом за
    # внимание модели, а шаг записи положил бы нашу инструкцию в переписку от
    # имени человека.
    #
    # ⚠ Ветку выбирает флаг `initiative`, а не текст вопроса.
    # ⚠ Решения прогона инициативе не нужны: снимок прикладывают к **письму**,
    # а реплика в чат вложений не носит вовсе — как и у чата (`answer_run`).
    text, error, message_id, _ = await _agent_ask(agent, '', language, profile,
                                                  uid=uid, name=name,
                                                  anyway=True, initiative=True)

    if error:
        await log_write(profile_id, 'fail',
                        f'Инициатива не сочинилась для {who}: {error}')

        return f'ошибка:{who}: {error}'

    if not text:
        # Агент промолчал — значит разговор и вправду кончен. Это законный исход,
        # и настаивать незачем: молчание тут решение, а не сбой.
        return 'молчит'

    # ⚠ Сторож чужого имени — тот же, что у ответов. Инициатива уходит живому
    # человеку так же, как ответ, и цена ошибки та же.
    alien = companion_ref_foreign(text, companion_title(name, uid))
    if alien:
        await log_write(profile_id, 'fail',
                        f'Инициатива не взята для {who}: чужое имя «{alien}»')

        return f'ошибка:{who}: в тексте чужое имя «{alien}»'

    # ⚠⚠ Номер обмена кладём в строку пула: карточку сочиняет этот круг, а
    # уносит отправкой другой (`initiative_round._send`), позже — когда
    # собеседник окажется в сети. Без своего места в строке номер до отправки
    # не дожил бы, и ушедшая инициатива осталась бы у соседа неотмеченной.
    await chat_initiative_put(int(profile.get('site_id') or 0), profile_id, uid,
                              name, text, int(pair.get('try_no') or 1),
                              message_id)
    await log_write(profile_id, 'info',
                    f'Инициатива готова: {_me_name(profile)} → {who} '
                    f'(заход {int(pair.get("try_no") or 1)})')

    return 'made'


async def _quiet(profile_id: int, after_sec: int, after_max_sec: int,
                 repeat_max: int,
                 max_day: int = INITIATIVE_MAX_DAY_DEFAULT,
                 reset_sec: int = 0) -> list[dict]:
    """Затихшие пары этой анкеты: кому пора написать самим.

    ## ⚠⚠ Что считается затихшим

    Два случая, и второй неочевиден.

    **Последняя реплика наша**, и ей больше срока пары. Он не ответил — тишина.

    **Последняя реплика его, но агент решил промолчать** (`answer_silent_at`). Со
    стороны это тоже тишина: мы намеренно не ответили, он больше не писал.

    ⚠⚠ **Второй случай пришлось дописывать по живой паре.** Без него разговор
    выпадал из обоих занятий сразу: автоответ такую реплику не берёт — решение
    молчать записано и держит его отбор (`answer_silent_at IS NULL`), — а
    инициатива не брала, потому что последним говорил он. Пара оставалась мёртвой
    навсегда. Поймано на проде: Nadezhda ↔ Semen, тридцать три часа тишины после
    намеренного молчания.

    ⚠ **Реплика, ждущая ответа, сюда не попадает.** Пока `answer_silent_at` пуст,
    автоответ ещё придёт, и лезть туда инициативе нельзя — вышли бы два наших
    сообщения подряд на одну реплику.

    ## ⚠⚠ Сколько заходов уже было: два счёта от одной границы

    Граница у обоих одна — **его последняя реплика** (либо ручной сброс, если он
    позже). Ответил — оба счёта обнулились: разговор жив, и прошлые заходы
    больше не считаются. Это и защищает от трёх «ты тут?» в пустоту.

    **Подряд** — все ушедшие карточки после границы (`repeat_max`), за весь
    промежуток тишины.

    **За сутки** — те же карточки, но за скользящие 24 часа (`max_day`): предел
    отвечает «сколько заходов одной тишины уместится в сутки», то есть
    растягивает их по дням, а не отнимает.

    ⚠ Оба счёта берутся **одним запросом** условными суммами: два запроса на пару
    означали бы два похода в базу там, где хватает одного, а разойтись они не
    могут — слагаемые считаются по одной и той же выборке.

    ⚠⚠ У счёта «подряд» **нет окна по времени**, и это не забывчивость: он мерит
    один промежуток тишины, а тот бывает и трёхдневным. Ограничь его сутками, и
    трёхдневное молчание обнуляло бы счёт само, без всякого его ответа.

    ⚠ Пары без единого его слова не берём вовсе: это ушедший инвайт, на который не
    ответили, и возвращаться к нему — работа инвайтов (`invite_repeat_after`), а
    не эта. Отсюда же следует, что `his_last` в счёте «подряд» всегда непуст.

    ## ⚠⚠ Сроков два, и они о разных заходах

    **Первый заход** меряется минутным сроком с жребием: разговор затих только
    что, и вернуться к нему стоит быстро.

    **Повторный** ждёт `chat_initiative_reset_after` (часы). Одним сроком на оба
    случая занятие и встало: при пределе «один подряд» пара получала одну реплику
    и замирала навсегда — счёт обнуляет только его ответ, а на 72 ушедшие
    инициативы 33 парам не ответил никто.

    ⚠ Ноль в сроке — «сброса нет»: повторы меряются минутным сроком, как прежде.

    ⚠ Потолком остаётся `chat_initiative_repeat`: срок отвечает «когда», потолок
    — «сколько». Второго счётчика нет намеренно.

    ## ⚠⚠ Срок у каждой пары свой

    В SQL уходит только **нижняя** граница — она отсекает дёшево и индексом. Выше
    неё срок у каждой пары свой, жребием (`_due_sec`), и проверяется он здесь же,
    строкой: `quiet_sec` — сколько пара молчит.

    ⚠⚠ **Отбор идёт целиком в запросе, и `LIMIT` применяется после него.** Прежде
    счёт заходов стоил отдельного запроса на пару и потому брался **после** окна:
    двадцать свежайших затихших пар набирались до отбора, а негодные —
    неотвеченные инвайты, реплики, ждущие ответа, — съедали окно целиком. Годная
    пара, молчащая дольше всех, в него не попадала вовсе.

    ⚠ Жребий остаётся в Python: он выводится из пары (`blake2b` от
    `profile_id:uid:last_at`), и повторить его в SQL значило бы завести второе
    правило о том же. Порядок проверок — от частого отсева к редкому.
    """
    async with mysql_get_db_async() as db:
        # «Последняя реплика» считается по времени, а не по `MAX(id)`: импорт из
        # панели кладёт недельную историю сегодняшними номерами. Та же мерка, что
        # у автоответа и у списка диалогов — три места, и во всех правило одно.
        await db.execute(
            'SELECT q.uid, q.name, q.last_at, q.quiet_sec, cnt.in_row'
            '  FROM (SELECT t.profile_id, t.sender_uid AS uid, t.last_at,'
            '               (SELECT c.name FROM companion c'
            '                 WHERE c.site_id = p.site_id'
            '                   AND c.uid = t.sender_uid) AS name,'
            # Его последнее слово. ⚠ Нужно дважды: им решается, говорил ли он
            # хоть раз (без единого слова это неотвеченный инвайт, а не затихший
            # разговор), и от него же считается счёт «подряд».
            '               ' + _his_last_sql('t.profile_id', 't.sender_uid')
            + ' AS his_last,'
            '               (SELECT m2.direction FROM message m2'
            '                 WHERE m2.profile_id = t.profile_id'
            '                   AND m2.sender_uid = t.sender_uid'
            '                 ORDER BY m2.created_at DESC, m2.id DESC'
            '                 LIMIT 1) AS last_side,'
            # ⚠ Решение молчать по **последней** реплике: оно и превращает
            # «неотвеченное» в «затихшее». Берём тем же порядком, что и сторону, —
            # иначе можно поймать метку от позапрошлой.
            '               (SELECT m3.answer_silent_at FROM message m3'
            '                 WHERE m3.profile_id = t.profile_id'
            '                   AND m3.sender_uid = t.sender_uid'
            '                 ORDER BY m3.created_at DESC, m3.id DESC'
            '                 LIMIT 1) AS last_silent,'
            # Сколько пара молчит — им и проверяется жребий срока. Считает база,
            # а не мы: её `NOW()` и отобрал строку ниже, и мерить одно и то же
            # двумя часами значило бы ловить расхождение в секундах.
            '               TIMESTAMPDIFF(SECOND, t.last_at, NOW()) AS quiet_sec'
            '          FROM (SELECT m.profile_id, m.sender_uid,'
            '                       MAX(m.created_at) AS last_at'
            '                  FROM message m WHERE m.profile_id = %s'
            '                 GROUP BY m.profile_id, m.sender_uid) t'
            '          JOIN profile p ON p.id = t.profile_id'
            '         WHERE t.last_at < NOW() - INTERVAL %s SECOND) q'
            # ⚠ `LATERAL`: счёту нужен `q.his_last`, посчитанный строкой выше.
            # MySQL 8.0.14+; на проде и локально 8.0.46.
            '  JOIN LATERAL (SELECT '
            + _in_row_sql('q.profile_id', 'q.uid', 'q.his_last')
            + ' AS in_row,'
            # ⚠ Тот же счёт, но в скользящих сутках, и от **той же** границы:
            # его ответ обнуляет оба. Мерка как у `invite_repeat_max_day` —
            # полночь ничего не значит для того, кто читает сообщения.
            '                       '
            + _in_day_sql('q.profile_id', 'q.uid', 'q.his_last')
            + ' AS in_day'
            '               ) cnt ON TRUE'
            # ⚠ Последним говорил он — берём, **только если решено молчать**.
            # Пока решения нет, реплику ждёт автоответ, и это его работа.
            "  WHERE (q.last_side = 'out' OR q.last_silent IS NOT NULL)"
            # ⚠ Он не сказал ни слова — это неотвеченный инвайт, не наша работа.
            '    AND q.his_last IS NOT NULL'
            # ⚠ «Подряд» — первым: он отсекает несравнимо чаще дневного.
            '    AND cnt.in_row < %s'
            # ⚠ Сколько заходов одной тишины уместится в сутки. Счёт — от той
            # же границы, что «подряд», и потому `in_day <= in_row` всегда:
            # предел выше «подряд» не участвует вовсе.
            '    AND cnt.in_day < %s'
            # ⚠⚠ Повторный заход ждёт **свой** срок, в часах. Первому он не указ:
            # его срок минутный, с жребием. Ноль в настройке — «сброса нет», и
            # условие тогда не участвует вовсе.
            '    AND (%s = 0 OR cnt.in_row = 0 OR q.quiet_sec >= %s)'
            # ⚠ Порядок «свежая тишина сверху»: разговор, затихший час назад, ещё
            # живой, и шансов на ответ у него больше. Окно теперь считает
            # **годные** строки, а не все подряд.
            '  ORDER BY q.last_at DESC LIMIT %s',
            (int(profile_id), int(after_sec), int(repeat_max), int(max_day),
             int(reset_sec), int(reset_sec),
             INITIATIVE_PER_PROFILE * 10))
        rows = await db.fetchall() or []

    got = []
    for row in rows:
        # Срок этой пары — жребием между границами. Нижнюю уже проверил SQL;
        # всё, что между границами, решается здесь.
        due = _due_sec(profile_id, str(row['uid']), row.get('last_at'),
                       int(after_sec), int(after_max_sec))
        if int(row.get('quiet_sec') or 0) < due:
            continue

        # ⚠ Номер захода — по счёту **подряд**, а не дневному: «заход 2»
        # значит «второй раз зову в эту тишину», и ровно это читает человек в
        # журнале анкеты. Дневной счёт к номеру отношения не имеет.
        got.append({'uid': str(row['uid']), 'name': row.get('name') or '',
                    'try_no': int(row.get('in_row') or 0) + 1})

        if len(got) >= INITIATIVE_PER_PROFILE:
            break

    return got


async def _profiles(site_id: int) -> list[dict]:
    """Анкеты сайта, от чьего имени пишем.

    ⚠ **Только те, что в сети.** Инициатива уходит в чат, а чат — это вход под
    анкетой; спящей девушке написать нечем. Тот же отбор, что у круга инвайтов и
    у избранных.
    """
    async with mysql_get_db_async() as db:
        await db.execute(
            'SELECT id, site_id, login, profile_id, profile, role, auto_answer_only'
            '  FROM profile'
            " WHERE site_id = %s AND enabled = 1 AND status = 'online'",
            (int(site_id),))
        rows = await db.fetchall()

    return [dict(row) for row in (rows or [])]


async def _agent(profile: dict) -> int:
    """Агент анкеты у соседа. Ноль — анкету ещё не проверяли, и мы молчим."""
    card = profile.get('profile')
    if isinstance(card, str):
        card = json_column_load(card) or {}

