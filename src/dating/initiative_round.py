# Как часто круг просыпается. Минута — как у автоответа: чаще незачем, сроки
# инициативы считаются десятками минут.
#
# ⚠⚠ **Тик — потолок частоты отправки, и об этом легко забыть.** Пауза
# (`chat_initiative_send_every`) задана в минутах, и ноль в ней значит не «без
# пауз вовсе», а «по карточке в минуту»: чаще круг не проснётся. Минута здесь
# предел достаточный — сроки самой инициативы считаются десятками минут.
INITIATIVE_ROUND_TICK_SEC = 60

# Сколько карточек заводим за тик на весь сайт. Каждая — вызов LLM; без предела
# первый же заход на затихшем сайте стоил бы сотен вызовов разом.
INITIATIVE_ROUND_MAKE = 5

# Пауза между отправками — настройка сайта, **в минутах**. ⚠ Умолчание три минуты:
# инициатива возвращается к **начатому** разговору, и спешить ей некуда — человек
# уже знаком с девушкой и зайдёт в чат ещё.
#
# ⚠ Срок свой, и ничьего чужого он не меняет: прочие занятия меряются своими
# настройками.
#
# ⚠⚠ Константы «сколько отправляем за тик» здесь больше нет, и это не потеря.
# Стояла тройка с доводом «всплеск из десятка реплик за минуту виден со стороны» —
# довод верный, а число неверное: три реплики в минуту это тот же всплеск, только
# втрое тише, и крутить его человек не мог. Теперь частоту задаёт он.
INITIATIVE_SEND_EVERY_SETTING = 'chat_initiative_send_every'
INITIATIVE_SEND_EVERY_DEFAULT = 3

# Когда сайту уходила последняя карточка инициативы: `{сайт: время}`. В памяти
# процесса: перезапуск смены — это лишняя пауза, а не лишняя реплика, и ошибаться
# сюда безопасно. ⚠ Словарь свой, только для этого круга: соседние занятия ведут
# свой темп сами.
_sent_at: dict[int, float] = {}


async def initiative_round_run() -> dict:
    """Один круг по всем сайтам, где занятие включено хоть наполовину."""
    sites = await _sites()

    if not sites:
        return {'sites': 0, 'made': 0, 'sent': 0, 'stale': 0}

    # ⚠ `keep_going`: сайты здесь независимы, и отказ у одного (сосед занят,
    # сайт сменил вёрстку) не повод не дойти до остальных. ⚠ Слота круг не
    # ставит (`key` пуст): его тик и есть его срок — сроки инициативы считает
    # сама пара, по времени своей последней реплики (`initiative.py`).
    counted = await round_sites_run(sites, work=_work, what='инициативы',
                                    keep_going=True)

    made = sum(int(one.get('made') or 0) for _, one in counted)
    sent = sum(int(one.get('sent') or 0) for _, one in counted)
    stale = sum(int(one.get('stale') or 0) for _, one in counted)

    if made or sent or stale:
        logger_info(f'[dating] инициатива: набрано {made}, отправлено {sent}, '
                    f'снято протухших {stale}')

    return {'sites': len(sites), 'made': made, 'sent': sent, 'stale': stale}


async def initiative_why(site_id: int) -> str:
    """Почему пул инициативы пуст — словами. Пусто — сказать нечего.

    Args:
        site_id: сайт-закладка.

    Returns:
        str: одна строка для колонки пула, человеческими словами.

    ## ⚠⚠ Ради этого всё и написано: пустое место неотличимо от поломки

    Человек открывает колонку, видит пустоту и не знает, что перед ним: набор
    снят, настройка обнулена, девушки спят или сломалось. Раньше здесь стояла
    одна фраза на все случаи — «круга инициативы ещё не сделан», — и она пережила
    сам круг: тот работает с сентября, а колонка всё уверяла, что занятия нет.

    ⚠ **Спрашивается теми же вопросами и в том же порядке, что и круг**
    (`initiative_round_run` и `initiative_make`), а не второй их копией:
    разойдись они, колонка объясняла бы простой, которого нет.

    ⚠ **Порядок — от решённого к преходящему.** Снятый выключатель важнее
    обнулённой настройки, а та важнее того, что прямо сейчас никто не в сети:
    первое человек сделал сам, последнее пройдёт само.

    ⚠⚠ **Последняя строка — не пустота, а утверждение.** Дойдя до неё, мы знаем,
    что мешать некому: выключатель поднят, сроки заданы, девушки в сети. Значит
    затихших пар на прошлом тике не нашлось, и сказать об этом надо прямо —
    молчание здесь снова читалось бы как поломка.
    """
    from src.dating.initiative import (INITIATIVE_PER_PROFILE, _after_range,
                                       _profiles, _repeat)

    site_id = int(site_id or 0)
    if not site_id:
        return ''

    try:
        make = {int(one['site_id']): one['chat_initiative_on']
                for one in await _sites()}.get(site_id)
        if not make:
            return ('набор инициативы выключен: поднять — галочка «набор '
                    'инициативы» в карточке анкеты')

        after, _ = await _after_range(site_id)
        if after <= 0:
            return ('срок инициативы обнулён: настройка сайта «Инициатива, '
                    'проявить через минут (от)»')

        if await _repeat(site_id) <= 0:
            return ('заходов разрешено ноль: настройка сайта «Инициатива, '
                    'сколько раз подряд звать молчащего»')

        if not await _profiles(site_id):
            return ('ни одна анкета сайта не в сети: инициатива уходит в чат, '
                    'а это вход под анкетой')

        # ⚠ Про пределы говорим здесь же, одной оговоркой. Проверить их по
        # месту нельзя: они считаются **на пару**, а эта подсказка про сайт —
        # перебрать все пары значило бы запрос на каждую ради строки в шапке.
        # Умолчать хуже: «затихших нет» при полном журнале читается как поломка.
        return ('затихших разговоров сейчас нет: круг возвращается к паре, '
                f'когда она молчит дольше срока, и берёт по '
                f'{INITIATIVE_PER_PROFILE} на анкету за раз. Пары, которых уже '
                'позвали, не считаются затихшими, пока он не ответит — и пока '
                'не истекли сутки, если выбран дневной потолок')
    except Exception as e:
        logger_info(f'[dating] повод пустоты инициативы не спросился: {e}')

        # Молчим: подсказка не обязана работать, когда не работает база. Пустая
        # строка означает «сказать нечего», а не «всё хорошо».
        return ''


async def _work(site: dict, minutes: int) -> dict:
    """Один сайт за заход: чистка, набор, отправка — в этом порядке.

    Args:
        site: строка `_sites` — номер и два флага.
        minutes: местные минуты суток. Инициатива расписания не спрашивает,
            довод приходит от захода слоя и здесь не нужен.

    Returns:
        dict: `made`, `sent`, `stale` — счётчики этого сайта. `sent` больше
        единицы не бывает: отправка идёт по одной карточке за паузу (`_send`).

    ⚠ **Порядок именно такой.** Чисти мы протухшее после набора, круг успел бы
    отправить карточку тому, кто ответил секунду назад, — а её текст сочинялся
    под тишину и прозвучал бы мимо разговора.
    """
    site_id = int(site['site_id'])

    # ⚠ Чистка идёт **всегда**, независимо от флагов: карточка, ставшая вредной,
    # вредна и при снятой отправке — человек прочитает её в пуле и не поймёт,
    # почему панель собралась писать тому, кто только что ответил сам.
    stale = await _stale_clean(site_id)

    # ⚠⚠ И карточки ушедших анкет — тем же общим сметальщиком, что у рассылки и
    # фаворитов (`pool.py`). Зовём его **здесь**, а не полагаемся на соседние
    # круги: те ходят по своим выключателям, и при снятой рассылке карточки
    # инициативы от спящих девушек лежали бы в пуле, пока их кто-нибудь не
    # увидит.
    #
    # ⚠ Тексты инициативы протухают быстрее прочих: приём жребия бывает
    # «расскажи про свой день» или «спроси про планы на вечер». Пролежав до
    # завтра, такая карточка врёт не тоном, а содержанием — и лучше сочинить
    # заново, когда девушка вернётся.
    stale += await pool_sweep(site_id)

    made = 0
    if site['chat_initiative_on']:
        got = await initiative_make(site_id, limit=INITIATIVE_ROUND_MAKE)
        made = int(got.get('made') or 0)

    return {'made': made,
            'sent': await _send(site_id) if site['chat_initiative_send_on'] else 0,
            'stale': stale}


async def _send(site_id: int) -> int:
    """Уносит **одну** готовую карточку тому, кто сейчас в чате.

    Args:
        site_id: сайт-закладка.

    Returns:
        int: `1` — реплика ушла, `0` — пауза не вышла, отправлять некому либо
        сайт отказал.

    ## ⚠⚠ Одна карточка за паузу, и пауза общая на сайт

    Прежде заход уносил три подряд, без пауз: пул набирается сразу всем анкетам
    сайта, и включённая инициатива выглядела залпом — десяток девушек пишет
    первыми в одну минуту, нередко одним и тем же людям в ленте.

    ⚠ **Пауза проверяется здесь, а не у вызывающего.** Решение «пора ли» и
    решение «кому именно» — одно решение: не нашлось адресата в сети, и пауза
    тратиться не должна.

    ⚠ **Очередь — от старых карточек к свежим** (`chat_initiative_ready`): текст
    сочинялся под тишину и тем бесполезнее, чем дольше лежит.
    """
    if not round_mem_due(_sent_at, int(site_id), await _send_every(site_id)):
        return 0

    for card in await chat_initiative_ready(site_id):
        uid = str(card['uid'])

        # ⚠ Нет в сети — не отправляем и **пометки не ставим**: он вернётся, и
        # карточка уйдёт. Ровно как черновик ответа. Берём следующего — того, кто
        # в ленте сейчас.
        if not online_check(int(site_id), uid)['online']:
            continue

        profile = await _profile(int(card['profile_id']))
        if not profile:
            continue

        # ⚠ Отметку о заходе ставим **до** отправки, а не после: тик минута, а
        # отправка идёт секунды — не отметь мы сразу, второй тик успел бы взять
        # ту же строку, пока первый ждёт ответа сайта.
        round_mem_mark(_sent_at, int(site_id))

        who = f"{card.get('name') or ''} {uid}".strip()
        result = await send_message(profile, await _presence(site_id), uid,
                                    str(card['body']))

        if result['ok']:
            await chat_initiative_sent(int(card['id']))
            # ⚠⚠ Доставку отмечаем только у ушедшего: сосед записал обмен внутри
            # прогона, то есть до того, как мы постучались к сайту знакомств.
            # Номер дожил до сюда в строке пула — карточку сочинял другой круг.
            await rhapsody_api_chat_delivered(int(card.get('talk_message_id') or 0))
            await log_write(int(card['profile_id']), 'out',
                            f"Инициатива → {who}: «{str(card['body'])[:300]}»")

            return 1

        if result.get('offline'):
            # Вышел между проверкой и отправкой — не ошибка, карточка ждёт дальше.
            # ⚠ И пауза с ним: ничего не ушло, а отметка уже стоит — ждать её
            # честнее, чем перебирать пул дальше, пока сайт отдаёт «его нет».
            return 0

        await chat_initiative_failed(int(card['id']), result['error'])
        await log_write(
            int(card['profile_id']), 'fail',
            f"Инициатива не ушла → {who}: {result['error']}")

        # ⚠ Отказ сайта **кончает заход**, а не ведёт к следующей карточке:
        # причина у него почти всегда общая — сессия протухла, сайт попросил
        # подождать, — и дослать вторую значило бы получить тот же отказ, кормя
        # счётчик сайта.
        return 0

    return 0


async def _send_every(site_id: int) -> int:
    """Пауза между отправками у этого сайта, в секундах.

    ⚠ Ноль — законное «без паузы»: человек выбрал «как можно чаще». Это не
    выключатель — за него отвечает `chat_initiative_send_on`, — и на деле ноль
    значит «по карточке в минуту»: чаще круг не просыпается
    (`INITIATIVE_ROUND_TICK_SEC`).

    ⚠ Настройка **в минутах**, как и соседние сроки инициативы: границы одного
    занятия обязаны мериться одним.
    """
    try:
        minutes = int(await site_seconds(int(site_id or 0),
                                         INITIATIVE_SEND_EVERY_SETTING))
    except Exception as e:
        logger_info(f'[dating] пауза отправки инициативы не прочиталась: {e}')

        minutes = INITIATIVE_SEND_EVERY_DEFAULT

    return max(0, minutes) * 60


async def _stale_clean(site_id: int) -> int:
    """Снимает карточки тех, кто успел ответить сам.

    ⚠⚠ **Текст сочинялся под тишину.** Уйдя после его реплики, «расскажи, как
    прошли выходные» прозвучит мимо разговора: он спросил о другом, а девушка
    будто не прочитала. Отвечать теперь будет автоответ — на сказанное.
    """
    async with mysql_get_db_async() as db:
        # Пара, у которой последняя реплика — входящая, а карточка всё ещё ждёт.
        await db.execute(
            'SELECT i.profile_id, i.uid FROM chat_initiative i'
            " WHERE i.site_id = %s AND i.status = 'draft'"
            '   AND EXISTS (SELECT 1 FROM message m'
            '                WHERE m.profile_id = i.profile_id'
            '                  AND m.sender_uid = i.uid'
            "                  AND m.direction = 'in'"
            # ⚠ `>=`, а не `>`: `created_at` здесь с точностью до секунды, и
            # реплика, пришедшая в ту же секунду, что легла карточка, при
            # строгом сравнении осталась бы незамеченной. Сторона ошибки
            # выбрана нарочно: снять лишнюю карточку дёшево — круг наберёт
            # новую, — а отправить мимо разговора нельзя.
            '                  AND m.created_at >= i.created_at)',
            (int(site_id),))
        rows = await db.fetchall() or []

    gone = 0
    for row in rows:
        gone += await chat_initiative_stale(int(row['profile_id']),
                                            str(row['uid']))

    return gone


async def _sites() -> list[dict]:
    """Сайты и их выключатели: набирать ли (`chat_initiative_on`) и
    отправлять ли (`chat_initiative_send_on`)."""
