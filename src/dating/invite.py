async def _avoid(site_id: int) -> list[str]:
    """Что уже писали этому сайту — чтобы не повторяться.

    ⚠ **Берём `DISTINCT body`, а не строки пула.** Пул набирается одним шаблоном
    на полсотни карточек: возьми мы строки как есть, список был бы полусотней
    копий одного текста, и модель увидела бы один пример вместо десяти.

    ⚠ **По сайту, а не по анкете.** Собеседники у сайта общие, и человек, которому
    вчера писала Диана, сегодня может получить реплику от Елены — повтор он
    заметит.

    Сбой базы отвечает пустым списком: без него шаблон выйдет чуть более похожим
    на прошлые, и это несравнимо лучше, чем пустой пул.
    """
    try:
        async with mysql_get_db_async() as db:
            await db.execute(
                # ⚠ Группировка, а не `DISTINCT`: нам нужен **свежий** десяток,
                # а порядок по `MAX(id)` требует группы. `DISTINCT` с `ORDER BY
                # MAX(id)` — синтаксическая ошибка, и она бы вылезла только на
                # живом запросе.
                'SELECT body FROM invite'
                ' WHERE site_id = %s AND body <> %s'
                ' GROUP BY body ORDER BY MAX(id) DESC LIMIT %s',
                (int(site_id), '', INVITE_AVOID_MAX))
            rows = await db.fetchall()
    except Exception as e:
        logger_info(f'[dating] прошлые шаблоны не спросились: {e}')

        return []

    return [str(row['body']) for row in rows or []]


def _fill(template: str, girl: dict, person: dict) -> str:
    """Подставляет имена в шаблон и вычищает то, что подставить не вышло.

    ⚠ **Имя — первое слово, а не полное.** В ленте лежит «Brian Ritter», а в чате
    обращаются «Brian»; фамилия в реплике звучит как обращение из документа. То же
    правило у девушки: в анкете «Diana K.», в реплике «Diana».

    ⚠⚠ **Одно слово — это тоже имя**, и здесь была живая беда. `people_name_parts`
    отвечает пустотой на имя без пробела («Paulo», «CLAY», «Tall_Good_Man»): так
    задумано для писем, где промпт сам решает через `%if%`, чем звать. Инвайт же
    берёт ответ буквально — и получал пустоту, а `mail_render` на пустое
    значение **оставляет метку в тексте**.

    Итог был виден в пуле прода: 23 карточки из 36 с «I'm curious,
    [[companion_name]], what's…» — при том, что имя у человека есть. Поэтому здесь
    падаем на первое слово полного имени, а не на пустоту.

    ⚠ **Подстановка не рекурсивная** (`mail_render`): имя, в котором
    случайно окажется `[[…]]`, второй раз не разбирается.
    """
    from src.dating.people import people_name_parts

    girl_name = str(json_column_load(girl.get('profile')).get('name') or '')
    person_name = str(person.get('name') or '')

    filled = mail_render(template, {
        INVITE_SLOT_GIRL: _first_word(girl_name),
        INVITE_SLOT_MAN: (str(person.get('firstname') or '').strip()
                                 or _first_word(person_name))})

    return invite_marks_strip(filled)


async def _time_chance(site_id: int) -> float:
    """Доля инвайтов, где агенту показывают текущее время. Настройка сайта.

    ⚠ Тот же перевод процентов в долю, что у имён (`_man_chance`), и та же
    причина завести: частоту модель не считает — её задаёт панель жребием.
    """
    return await _percent(site_id, INVITE_TIME_SETTING, INVITE_TIME_CHANCE)


async def _man_chance(site_id: int) -> float:
    """Доля инвайтов с именем собеседника — настройка сайта, долей от единицы."""
    return await _percent(site_id, INVITE_MAN_NAME_SETTING, INVITE_MAN_NAME_CHANCE)


async def _percent(site_id: int, key: str, fallback: float) -> float:
    """Настройка-процент долей от единицы. Одна на все доли инвайта.

    Args:
        site_id: сайт-закладка.
        key: ключ настройки в `SITE_KNOWN`.
        fallback: доля, если настройки нет или её не прочитать.

    ⚠ **В настройке проценты, здесь доля.** Человек в форме пишет «10», а жребий
    бросается по доле; перевод живёт в одном месте — иначе где-нибудь сравнят
    процент с `random.random()`, и выпадать будет всегда.

    ⚠⚠ **Ноль — законное значение, а не «настройки нет».** Человек выбрал в форме
    «никогда»; подмени мы его умолчанием, имя или время появлялись бы там, где их
    запретили. Отличаем по тому, задан ли ключ у сайта вообще.

    ⚠ Сбой чтения даёт умолчание, а не ноль: «этого не будет вовсе» — решение, и
    принимать его молча из-за недоступной базы нельзя.
    """
    from src.uvicorn.routers.dating.site_ import site_seconds, site_setting

    try:
        percent = int(await site_seconds(int(site_id), str(key)))
        if not percent:
            задано = str(await site_setting(int(site_id), str(key))).strip() != ''
            if not задано:
                return fallback
    except Exception as e:
        logger_info(f'[dating] доля «{key}» не спросилась: {e}')

        return fallback

    return max(0.0, min(1.0, percent / 100))


