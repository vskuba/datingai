async def _invited(site_id: int) -> set:
    """Пары, которым звать **пока рано**: инвайт лежит в пуле или ушёл недавно.

    ⚠⚠ **Это больше не «звали когда-либо».** Инвайт заканчивается не отправкой, а
    **ответом**: пока человек молчит, приглашение не состоялось, и звать его можно
    снова. Прежнее правило «один инвайт на человека навсегда» вычёркивало
    промолчавшего из работы насовсем — а таких большинство.

    Поймано живьём: человека позвали, он не ответил, его строка `sent` осталась
    в базе, и больше он не попадал в пул ничем — ни кругом, ни кнопкой, ни
    приоритетом. Очистка пула не помогала: она сносит черновики, а ушедшее
    остаётся.

    ⚠ **Держат человека три условия, и каждое своё.**

      **Черновик в пуле** — он ждёт отправки, и второй задвоил бы карточку;
      **ушёл недавно** — `invite_repeat_after`, «как часто»;
      **за сутки уже довольно** — `invite_repeat_max_day`, «сколько всего».

    ⚠ **Пауза и потолок порознь не работают.** Без паузы круг зовёт молчащего
    каждый заход, пока тот в ленте. Без потолка пятиминутная пауза даёт под сотню
    приглашений за день — навязчивость, которую человек видит первой.

    ⚠ **Сутки скользящие** (`NOW() - INTERVAL 1 DAY`), а не календарные: полночь
    ничего не значит для того, кто читает сообщения.

    ⚠⚠ **Пределы считаются по паре, а не по человеку.** Было `GROUP BY uid` —
    «сколько инвайтов получил он от агентства целиком», — и пять свободных девушек
    упирались в счёт, набранный тремя другими.

    Поймано на приоритетном собеседнике: ему ушло ровно десять реплик за сутки, от
    трёх анкет, потолок десять — и пять оставшихся девушек молчали, хотя ни одна из
    них ему не писала. Он при этом стоял первым в очереди набора.

    ⚠ **Цена размена, и она настоящая.** При пяти анкетах потолок «десять в сутки»
    теперь означает до пятидесяти реплик одному человеку, а пауза держит только
    свою пару: две девушки вправе написать ему в одну минуту. Прежнее правило
    защищало от того, что видно с его стороны, — «агентство, выдавшее себя», — и
    заказчик решил, что отбор дороже: перестаёт работать он, а не сайт.

    Что от прежнего осталось: **в один заход человек получает одну реплику**
    (`_pairs`) — две Дианы, написавшие разом, были настоящей бедой, и она не
    вернётся.
    """
    from src.uvicorn.routers.dating.site_ import site_seconds

    after = int(await site_seconds(int(site_id), INVITE_REPEAT_SETTING)
                or INVITE_REPEAT_DEFAULT)
    per_day = int(await site_seconds(int(site_id),
                                            INVITE_REPEAT_MAX_SETTING)
                  or INVITE_REPEAT_MAX_DEFAULT)

    try:
        async with mysql_get_db_async() as db:
            await db.execute(
                'SELECT profile_id, uid FROM invite WHERE site_id = %s'
                ' GROUP BY profile_id, uid'
                "  HAVING SUM(status <> 'sent') > 0"
                '      OR MAX(sent_at) > NOW() - INTERVAL %s SECOND'
                '      OR SUM(sent_at > NOW() - INTERVAL 1 DAY) >= %s',
                (int(site_id), after, per_day))
            rows = await db.fetchall()
    except Exception as e:
        logger_info(f'[dating] готовые инвайты сайта #{site_id} не спросились: {e}')

        # ⚠ Сбой решается **в сторону бездействия**, как и у переписки: не зная,
        # кого уже позвали, мы рискуем позвать второй раз, а пустой набор означал
        # бы «никого не звали» — худшую из догадок.
        raise DatingInviteError(f'не спросить, кого уже звали: {e}') from e

    return {(int(row['profile_id']), str(row['uid'])) for row in rows or []}


async def _talked(site_id: int) -> set:
    """Пары, у которых разговор **состоялся**: человек ответил.

    ⚠⚠ **Считаем только входящие, и это исправление настоящей беды.** Раньше сюда
    шли все реплики пары — включая **наш собственный инвайт**. Отправка кладёт его
    в `dating_message` исходящим, и пара тут же переставала быть свободной: позвали
    человека один раз, он не ответил, а второй раз позвать уже нельзя — «у них же
    переписка». Переписки при этом не было ни одной буквы с его стороны.

    Поймано живьём: у пары Соломия ↔ Semen Gorbunkov четыре строки, все `out`,
    входящих ноль — то есть монолог, который панель считала диалогом. Таких пар на
    проде оказалось семь.

    Отсюда правило, которое и просил заказчик: **инвайт не заканчивается отправкой,
    он заканчивается ответом**. Пока ответа нет, звать можно снова.

    ⚠ **По `dating_message`, а не по `dating_contact`.** Первое — сами реплики,
    второе — список собеседниц, каким его отдал сайт: он приходит не целиком и
    бывает пуст у анкеты, у которой переписка есть. Спрашивать «говорили ли» надо у
    того, что говорили.

    ⚠ **Пара, а не человек.** Разговор — свойство двоих: тот же мужчина может
    вовсю переписываться с одной нашей анкетой и не знать второй. Проверено на
    живом: Semen ответил Диане и молчит у Соломии — и для Соломии он законный
    адресат первой реплики.

    ⚠ **Одним запросом на сайт, а не по анкете.** Анкет тринадцать, и запрос на
    каждую превратил бы набор пула в тринадцать походов в базу до первой реплики.
    """
    try:
        async with mysql_get_db_async() as db:
            await db.execute(
                'SELECT DISTINCT m.profile_id, m.sender_uid AS uid'
                '  FROM message m'
                '  JOIN profile p ON p.id = m.profile_id'
                " WHERE p.site_id = %s AND m.sender_uid <> %s AND m.direction = 'in'",
                (int(site_id), ''))
            rows = await db.fetchall()
    except Exception as e:
        logger_info(f'[dating] переписки сайта #{site_id} не спросились: {e}')

        # ⚠ Сбой решается **в сторону бездействия**: не зная, с кем говорили, мы
        # рискуем написать «здравствуйте» тому, с кем переписываемся неделю. Пустой
        # набор означал бы «ни с кем не говорили», то есть худшую из догадок.
        raise DatingInviteError(f'не спросить, с кем уже говорили: {e}') from e

    return {(int(row['profile_id']), str(row['uid'])) for row in rows or []}


