async def invite_make(site_id: int, limit: int, profile_id: int = 0,
                             first_uid: str = '') -> dict:
    """Набирает пул инвайтов: **один шаблон** от агента и карточки по нему.

    Args:
        site_id: сайт-закладка.
        limit: сколько карточек делаем за заход. ⚠ Это больше не число вызовов
            LLM: вызов один на весь заход, а `limit` — размер пула.
        profile_id: звать только от этой анкеты. Ноль — от всех включённых.
            ⚠ Сужение, а не отбор заново: анкета всё равно должна быть с этого
            сайта, включённой и в сети, иначе инвайтов не будет вовсе.
        first_uid: кого позвать первым — карточка, выбранная в ленте «Все онлайн».

    Returns:
        dict: `made` — готово карточек, `skipped` — пар пропущено, `reasons` —
        чего не хватило, `left` — сколько кандидатов осталось, `stopped` — почему
        заход оборвался (пусто — дошёл до конца).

    ## Как это устроено

    1. бросаем жребий, каким быть шаблону: с именем девушки (5%), с именем
       мужчины (30%), с обоими или без имён вовсе;
    2. **один** запрос агенту — он присылает шаблон с метками;
    3. раскладываем шаблон по парам: девушки по очереди, каждой — случайный
       свободный собеседник, метки заменяются именами.

    ⚠⚠ **Собеседники в пуле уникальны, и это следствие общего шаблона.** Текст у
    всех карточек один; отправь его две наши девушки одному человеку — он получит
    два одинаковых сообщения от разных незнакомок, то есть увидит агентство. Один
    человек — одна карточка, и правило считается **по всему пулу**, а не по
    заходу: кнопку жмут поверх непустого пула.

    ⚠⚠ **У каждой девушки свой текст** (`_templates`), а карточки перемешиваются
    перед укладкой: иначе пул, обрывающийся на потолке, доставался бы первым
    двум-трём анкетам целиком. Собеседник выбирается случайно — ровное чередование
    читается как рассылка. Приоритетные (`companion.priority`) выбираются первыми:
    пока они есть, случай бросается среди них.

    ⚠ **Повторный заход продолжает с того же места.** Пары, у которых инвайт уже
    лежит или ушёл недавно, пропускаются (`_invited`), а занятые собеседники — по
    уникальности выше.
    """
    girls = await _girls(site_id)
    if profile_id:
        girls = [girl for girl in girls if girl['id'] == int(profile_id)]

    people = mailing_people_first(await _people(site_id), first_uid)
    if not girls or not people:
        return {'made': 0, 'skipped': 0, 'reasons': [], 'left': 0, 'stopped': ''}

    invited = await _invited(site_id)
    talked = await _talked(site_id)
    # ⚠ Закрывшиеся от анкеты — отдельным набором, а не внутри `talked`. Пары те
    # же по виду, но вопросы разные: там «уже знакомы», здесь «просил не писать», и
    # слей мы их, причина пропуска стала бы неразличима.
    # ⚠ Набор **чата**: почтовые запреты («не подходите по возрасту») к
    # инвайтам отношения не имеют — довод в `block.block_pairs`.
    blocked = await block_pairs(site_id, 'chat')
    # Занятые собеседники: у кого карточка в пуле уже лежит — от любой девушки.
    taken = await _pool_uids(site_id)
    # ⚠ Язык спрашиваем **один раз на заход**: он про сайт, и настройка живёт у
    # соседа — запрос на пару был бы запросом к соседу на каждую карточку.
    language = await _language(site_id)

    # ⚠⚠ **Шаблон каждой девушке свой — один вызов на всех.**
    #
    # Прежде шаблон был один на заход, и весь пул уходил от одного имени. Просить
    # же агента на каждую девушку отдельно значило бы дюжину вызовов LLM за заход
    # — ровно та цена, ради ухода от которой шаблон и заводили.
    #
    # Середина: **один вызов, а в нём просим столько текстов, сколько девушек в
    # сети**, и судья у соседа сверяет их между собой — не похожи ли.
    try:
        templates = await _templates(site_id, language, len(girls))
    except DatingMailAgentError as e:
        # Агент недоступен — это не «шаблон не годится», а «сейчас не выйдет
        # вовсе». Пул подождёт следующего захода.
        logger_info(f'[dating] инвайты остановлены: {e}')

        return {'made': 0, 'skipped': 0, 'reasons': [], 'left': 0, 'stopped': str(e)}

    if not templates:
        return {'made': 0, 'skipped': 0, 'reasons': [INVITE_SKIP_SILENT],
                'left': 0, 'stopped': ''}

    # ⚠⚠⚠ **Текст не раздаётся по кругу, и это предохранитель, а не экономия.**
    #
    # Было `templates[at % len(templates)]`: при нехватке текстов круг замыкался,
    # а на **одном** тексте — замыкался на нём же, и все двенадцать анкет писали
    # одно и то же. Так и ушло в прод, когда у соседа сломался счётчик цикла:
    # ошибки не было ни одной, панель докладывала «готово 93».
    #
    # Теперь при нехватке заход берёт **столько девушек, сколько есть текстов**.
    # Остальные ждут следующего захода — это дешевле, чем выдать агентство: один
    # мужчина своих двух реплик не увидит, а двое, сравнив, увидят сразу.
    #
    # ⚠ Девушек в этом случае выбираем **жребием, а не первых по списку**: иначе
    # при стойкой нехватке инвайты всегда уходили бы от одной и той же анкеты с
    # меньшим `id`, а остальные молчали бы неделями.
    short = max(0, len(girls) - len(templates))
    if short:
        girls = random.sample(girls, len(templates))

    # Кому какой текст. ⚠ По порядку, а не жребием: тексты уже разные, и второй
    # случай поверх первого ничего бы не добавил.
    by_girl = {int(girl['id']): templates[at]
               for at, girl in enumerate(girls)}

    made, skipped, reasons, left = 0, 0, [], 0
    # ⚠ Нехватку текстов говорим человеку **строкой причины**, а не только в
    # журнал: пул, набранный на треть анкет, со стороны выглядит поломкой набора.
    if short:
        reasons.append(INVITE_SKIP_SHORT.format(
            girls=len(templates), short=short))
    # ⚠ Настройку читаем **один раз на заход**, а не на карточку: пул набирается
    # десятками, и полсотни одинаковых чтений — работа впустую.

    # ⚠⚠ **Карточки перемешиваем, и это не косметика.**
    #
    # `_cards` выдаёт их очередью по девушкам — первая, вторая, третья, снова
    # первая. Пул при этом обрывается на потолке, и при дюжине девушек с двумя
    # десятками мест в него попадали бы первые две-три девушки целиком.
    #
    # После перемешивания места достаются всем поровну — и заодно журнал сайта
    # перестаёт читаться как рассылка: ровное чередование имён заметно само по
    # себе.
    cards = list(_cards(girls, people, invited, talked, blocked, taken))
    random.shuffle(cards)

    for girl, person in cards:
        if made >= max(int(limit), 0):
            left += 1
            continue

        template = by_girl.get(int(girl['id']), templates[0])

        # ⚠ Имя мужчины проверяем, **только если шаблон его просит**. Прежде пары
        # с нелатинским именем (`許萊納` из ленты Ladadate) отбрасывались всегда —
        # агент такое имя в реплику не вставлял. Теперь без метки имя не нужно
        # вовсе, и такие люди перестали выпадать из работы.
        #
        # ⚠ Проверяется **шаблон этой девушки**, а не общий: метки у текстов
        # разные, и один на всех ответ стал бы неправдой для остальных.
        if f'[[{INVITE_SLOT_MAN}]]' in template \
                and not people_name_usable(person.get('name')):
            skipped += 1
            if INVITE_SKIP_ALIEN not in reasons:
                reasons.append(INVITE_SKIP_ALIEN)
            continue

        text = _fill(template, girl, person)
        if not await _put(site_id, girl, person, text):
            # Ключ не пустил: черновик этой паре уже лежит. Не наша строка и не
            # ошибка — просто считать её сделанной нельзя.
            skipped += 1
            continue

        made += 1

    if made or skipped:
        logger_info(f'[dating] инвайты сайта #{site_id}: готово {made}'
                    + (f', пропущено {skipped}' if skipped else ''))

    return {'made': made, 'skipped': skipped, 'reasons': reasons, 'left': left,
            'stopped': ''}


async def invite_pool_left(site_id: int, ready_only: bool = False) -> int:
    """Сколько неотправленных инвайтов в пуле сайта.

    Args:
        ready_only: считать только те, что **уйдут сами** — без прежней ошибки.
            ⚠ Этим круг решает, пора ли набирать новый пул.

    ⚠⚠ **Два счёта, и путать их нельзя.** Страница показывает пул целиком: человек
    видит и то, что застряло с ошибкой, — это его работа, он дошлёт руками. Круг
    же ждёт, пока пул **опустеет**, чтобы взять новый шаблон; считай он строки с
    ошибкой, одна такая строка остановила бы инвайты навсегда — отправитель её не
    берёт (`invite_send_round`), а круг видел бы непустой пул.
    """
    where = " AND error = ''" if ready_only else ''

    try:
        async with mysql_get_db_async() as db:
            await db.execute("SELECT COUNT(*) AS n FROM invite"
                             " WHERE site_id = %s AND status = 'draft'" + where,
                             (int(site_id),))
            row = await db.fetchone()
    except Exception as e:
        logger_info(f'[dating] пул инвайтов сайта #{site_id} не сосчитался: {e}')

        return 0

    return int((row or {}).get('n') or 0)


def invite_marks_strip(text: str) -> str:
    """Убирает метки, которые подставить не вышло. Страховка, а не основной путь.

    ⚠⚠ **Сырой метки в готовом инвайте быть не может.** Письмо человек читает и
    правит перед отправкой, а инвайт уносит круг — `[[companion_name]]` уедет в
    чат живому человеку ровно так, в скобках.

    ⚠ **Вырезаем вместе с лишним знаком препинания.** Простое удаление оставляет
    «I'm curious, , what's…» — две запятые подряд читаются как опечатка, то есть
    беда остаётся, просто выглядит иначе.

    ⚠ **Заглавная буква возвращается**, если метка стояла первой: «[[girl_name]]
    здесь» без этого станет «здесь» со строчной.
    """
    clean = str(text or '')
    if '[[' not in clean:
        return clean

    mark = r'\[\[[^\]]*\]\]'
    # Метка между двумя знаками — оставляем второй: «curious, [[X]], what» → «curious, what».
    clean = re.sub(rf'[,;:]\s*{mark}\s*([,.;:!?])', r'\1', clean)
    # Метка перед знаком и после него — знак остаётся, метка уходит.
    clean = re.sub(rf'\s*{mark}\s*([,.;:!?])', r'\1', clean)
    clean = re.sub(rf'([,;:])\s*{mark}', r'\1', clean)
    # Всё прочее — метка вместе с окружающими пробелами.
    clean = re.sub(rf'\s*{mark}\s*', ' ', clean)

    clean = re.sub(r'\s{2,}', ' ', clean).strip(' ,;:')

    return clean[:1].upper() + clean[1:] if clean else clean


