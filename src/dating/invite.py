"""Инвайты: первая реплика в чат тому, с кем разговора ещё не было.

Пул устроен как пул писем — карточки «кто, кому, с каким текстом», которые человек
читает, правит и отправляет, — но занятие другое. Письмо продолжает знакомство,
инвайт его **начинает**: одна реплика, которая всплывёт у мужчины в окне чата.

## Кого зовём

Кандидаты берутся из снимка ленты «Все онлайн» — того же, что кормит рассылку, — и
из него вычитаются двое:

| Кто вычитается | Почему |
|----------------|--------|
| с кем у этой анкеты уже есть диалог | приветствие тому, с кем говорили, читается как сбой |
| кому инвайт уже готовили | пул набирает круг, и повтор был бы вторым приглашением |

⚠ **Диалог считается по анкете, а не по сайту.** Один и тот же мужчина незнаком с
Дианой и знаком с Еленой; для первой он кандидат, для второй нет. Это тот же довод,
по которому избранные лежат по анкете (`favorite`).

⚠ **Онлайн, а не «все с сайта».** Реплика в чате застаёт человека или не застаёт:
написать тому, кого сейчас нет, значит положить сообщение в ленту, которую он
откроет через неделю. Приоритетные (`companion.priority`) идут первыми —
порядок ленты для панели случаен, а пул обрывается на потолке.

## ⚠⚠ Каждой девушке — свой текст, и все они разные

Девушек в сети бывает дюжина, и одна реплика на всех выдавала бы агентство: разные
имена, слово в слово одно сообщение, одна минута.

Лечили это сперва тем, что заход шёл от одной анкеты — помогало, но упирало пул в
неё одну: остальные ждали следующего круга.

Теперь панель просит у агента **столько текстов, сколько девушек**, и получает их
в одном вызове: дюжина вызовов вернула бы цену, ради ухода от которой шаблон и
заводили. Разными их делает не жребий, а прямое требование и **судья у соседа**,
который сверяет тексты между собой (`_templates`).

## ⚠⚠ Карточки перемешиваются перед укладкой в пул

`_cards` выдаёт их очередью по девушкам, а пул обрывается на потолке: при дюжине
девушек и двух десятках мест туда попадали бы первые две-три анкеты целиком.
После перемешивания места достаются всем поровну — и журнал сайта перестаёт
читаться как рассылка: ровное чередование имён заметно само по себе.

## ⚠⚠ Шаблон один на весь пул, и вызов LLM тоже один

Прежде реплику сочинял агент **на каждого человека**: пул в полсотни карточек
стоил полусотни вызовов LLM и минут ожидания у нажатой кнопки. Теперь заход
устроен иначе:

1. бросаем жребий, каким быть шаблону: с именем мужчины (доля — настройка сайта
   `invite_name_percent`, по умолчанию 10%) или вовсе без имён. ⚠ Имя девушки
   сейчас не просим никогда: «я Diana, и мне скучно» в первой реплике звучит как
   визитка бота;
2. **один** запрос агенту — он присылает шаблон с метками `[[girl_name]]` и
   `[[companion_name]]` (теми же двойными скобками, что у писем);
3. раскладываем шаблон по парам: девушки по очереди, каждой случайный свободный
   собеседник, метки заменяются именами.

Цена размена названа прямо: **все реплики пула одинаковы** с точностью до имён.
Прежний довод «двадцать инвайтов по одной рамке читаются как двадцать копий»
верен ровно для того, кто их видит подряд, — а видим их только мы. Каждый мужчина
получает одну карточку и сравнить её не с чем.

## ⚠⚠ Собеседники в пуле уникальны — это условие общего шаблона

Один человек — одна карточка на весь пул. Не «за заход», как было раньше, а по
всему пулу: кнопку жмут поверх непустого, и второй заход выдал бы тем же людям
вторую карточку с тем же текстом.

Отправь одинаковую реплику две наши девушки одному мужчине — он получит два
одинаковых сообщения от разных незнакомок, то есть увидит агентство. Прежнее
правило («один инвайт на человека за заход») ловило то же самое: двух Диан, #849 и
#850, написавших одному человеку в первом же прогоне.

⚠ **Отсюда изменение в приоритете.** Отмеченному прежде писали **все** свободные
девушки; с общим шаблоном это пять одинаковых сообщений подряд. Приоритет остался
порядком: он уходит первым — случай бросается среди отмеченных, пока они есть, —
но карточку получает одну.

## ⚠ Имя собеседника больше не обязательно

Требование «обращение по имени» держалось тем, что оно отличало написанное
человеку от рассылки. С общим шаблоном оно ничего не отличает: имя подставляется
механически, и в семи случаях из десяти метки нет вовсе.

Выигрыш неожиданный: люди с нелатинским именем (`許萊納` из ленты Ladadate)
перестали выпадать из работы. Прежде такая пара отбрасывалась всегда — агент это
имя в реплику не вставлял; теперь она отбрасывается, только если шаблону имя
нужно.

## ⚠ Язык реплики задаётся явно, и это про доставку

Первый прогон дал все четыре реплики **по-русски** — мужчинам на англоязычном
сайте. Причина была в промпте: правило «пиши на языке его профиля», профиля у этих
людей нет, и модель ушла в язык, которым написан сам промпт.

Фильтр сайта такое отклоняет («Message not delivered. Unacceptable words: …», см.
`answer.ANSWER_LANGUAGE`), то есть пул был бы пулом недоставляемых
сообщений. Теперь язык берётся из настройки сайта (`presence.answer_language`,
умолчание `en`) и уезжает агенту переменной — той же, что у писем и автоответа.

⚠ **Профиль собеседника решает, о чём спросить, а не на каком языке.** Иначе один
и тот же сайт получал бы реплики на трёх языках — по тому, чем каждый мужчина
заполнил свою анкету.

## Что делает круг, а что человек

Круг **готовит и не отправляет** — как у писем. Отправляет человек кнопкой на
карточке, и только когда у сайта поднят второй выключатель (`invite_send_on`):
реплика уходит живому человеку в чат, и «расписание включено» согласием на это не
является.
"""

