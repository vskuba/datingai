def _cards(girls: list, people: list, invited: set, talked: set,
           blocked: set = None, taken: set = None):
    """Карточки пула: девушки по очереди, собеседник каждому достаётся один раз.

    Args:
        girls: анкеты в сети — очередь идёт по ним, по кругу.
        people: кто сейчас в сети, приоритетные впереди (`_people`).
        invited: пары, которым звать пока рано — черновик в пуле, недавняя
            отправка либо дневной потолок (`_invited`). ⚠ **Пары, а не номера
            людей**: предел у каждой девушки свой.
        talked: пары, у которых переписка уже есть.
        blocked: пары, где человек закрылся от анкеты (`block`).
        taken: **пары** «анкета — собеседник», уже занятые карточками пула.
            **Мутируется**: каждая выданная пара добавляется сюда сразу.

    ## ⚠⚠ Одна карточка на пару, а не на человека

    Здесь стоял набор **номеров людей**: один человек — одна карточка на весь пул,
    от кого бы она ни была. Довод был верный для своего времени: текст в пуле был
    **один на всех девушек**, и два приглашения означали два одинаковых сообщения
    от двух незнакомок. Двух Диан (#849 и #850), написавших одному мужчине в первом
    же прогоне, поймали именно на этом.

    Текст теперь у каждой девушки свой (`_templates`), и правило ушло вместе с
    общим текстом: мужчина, которому написали двое, получает два **разных**
    сообщения — на сайте знакомств это обычное дело.

    ⚠ Цена прежнего ограничения была видна в пуле: людей в ленте под две сотни, и
    потолок в четыреста карточек не набирался никогда — пул упирался не в
    настройку, а в число людей, пока двенадцать девушек простаивали.

    Частоту держат пределы **по паре** (`invited`): пауза `invite_repeat_after` и
    дневной потолок `invite_repeat_max_day`.

    ⚠ **Приоритет теперь только порядок, а не число реплик.** Раньше отмеченному
    писали **все** свободные девушки; с общим шаблоном это означало бы пять
    одинаковых сообщений подряд одному человеку. Он по-прежнему уходит первым —
    случай бросается среди приоритетных, пока они есть.

    ⚠ **Очередь по девушкам, а выбор человека — случайный.** Очередь делит пул
    поровну: бери мы каждый раз первую свободную, весь пул уходил бы от анкеты с
    меньшим `id`. Случайный собеседник ломает ровное чередование, по которому
    журнал сайта читается как рассылка.
    """
    blocked = blocked or set()
    taken = taken if taken is not None else set()

    # Свободные для этой девушки — те, с кем она не говорила, кто её не закрыл и
    # кому она сегодня ещё может писать.
    def free_for(girl):
        return [person for person in people
                if str(person.get('uid') or '')
                and (girl['id'], str(person['uid'])) not in taken
                and (girl['id'], str(person['uid'])) not in talked
                and (girl['id'], str(person['uid'])) not in blocked
                and (girl['id'], str(person['uid'])) not in invited]

    while True:
        gave = False

        for girl in girls:
            free = free_for(girl)
            if not free:
                continue

            # Приоритетные первыми: пока среди свободных есть отмеченные, случай
            # бросается только среди них.
            first = [person for person in free if person.get('priority')]
            person = random.choice(first or free)

            taken.add((girl['id'], str(person['uid'])))
            gave = True

            yield girl, person

        # Круг по всем девушкам не дал ни одной карточки — свободных больше нет.
        if not gave:
            return


async def _templates(site_id: int, language: str, how_many: int) -> list[str]:
    """Шаблоны реплики от агента: свой каждой девушке, **один вызов на всех**.

    Args:
        site_id: сайт-закладка.
        language: код языка реплики.
        how_many: сколько текстов просим — по числу девушек в сети.

    Returns:
        list: тексты шаблонов. Пустой список — агент промолчал или всё забраковал,
        и пул в этот заход не наберётся.

    ## ⚠⚠ Почему один вызов, а не по вызову на девушку

    Прежде шаблон был один на весь заход, и пул уходил от одного имени. Просить
    агента на каждую девушку отдельно — это дюжина вызовов LLM за заход, ровно та
    цена, ради ухода от которой шаблон и заводили.

    Середина: один вызов, а в нём просим столько текстов, сколько девушек, и
    **судья у соседа сверяет их между собой**. Похожие бракуются там же, где
    пишутся, — до того, как лягут в пул.

    ## ⚠ Жребий — на весь заход, а не на текст

    Приём, длина и метки бросаются один раз и уезжают общими для всех текстов.
    Разнообразие между ними даёт не жребий, а прямое требование к модели: «эти
    тексты должны отличаться друг от друга» плюс судья. Бросай мы жребий на
    каждый, просьба «пиши разное» спорила бы с указанием «пиши вот таким приёмом».
    """
    girl_slot = random.random() < INVITE_GIRL_NAME_CHANCE
    man_slot = random.random() < await _man_chance(site_id)

    return await invite_template(
        int(site_id), language,
        # ⚠ Время показываем по жребию, а не всегда: иначе им пестрит половина
        # пула (`INVITE_TIME_SETTING`).
        with_time=random.random() < await _time_chance(site_id),
        girl_slot=girl_slot, man_slot=man_slot,
        angle=random.choice(INVITE_ANGLES),
        length=random.choice(INVITE_LENGTHS),
        avoid=await _avoid(site_id),
        country=await _country(site_id),
        how_many=max(1, int(how_many)))


