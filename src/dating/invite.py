def _cards(girls: list, people: list, invited: set, talked: set,
           blocked: set = None, taken: set = None):
    """Карточки пула: девушки по очереди, собеседник каждому достаётся один раз.

    Args:
        girls: анкеты в сети — очередь идёт по ним, по кругу.
        people: кто сейчас в сети, приоритетные впереди (`_people`).
        invited: пары, которым звать пока рано — черновик в пуле, недавняя
            отправка либо дневной потолок (`_invited`). ⚠ **Пары, а не номера
            людей**: предел у каждой девушки свой.
        talked: пары, у которых переписка уже есть.
        blocked: пары, где человек закрылся от анкеты (`block`).
        taken: **пары** «анкета — собеседник», уже занятые карточками пула.
            **Мутируется**: каждая выданная пара добавляется сюда сразу.

    ## ⚠⚠ Одна карточка на пару, а не на человека

    Здесь стоял набор **номеров людей**: один человек — одна карточка на весь пул,
    от кого бы она ни была. Довод был верный для своего времени: текст в пуле был
    **один на всех девушек**, и два приглашения означали два одинаковых сообщения
    от двух незнакомок. Двух Диан (#849 и #850), написавших одному мужчине в первом
    же прогоне, поймали именно на этом.

    Текст теперь у каждой девушки свой (`_templates`), и правило ушло вместе с
    общим текстом: мужчина, которому написали двое, получает два **разных**
    сообщения — на сайте знакомств это обычное дело.

    ⚠ Цена прежнего ограничения была видна в пуле: людей в ленте под две сотни, и
    потолок в четыреста карточек не набирался никогда — пул упирался не в
    настройку, а в число людей, пока двенадцать девушек простаивали.

    Частоту держат пределы **по паре** (`invited`): пауза `invite_repeat_after` и
    дневной потолок `invite_repeat_max_day`.

    ⚠ **Приоритет теперь только порядок, а не число реплик.** Раньше отмеченному
    писали **все** свободные девушки; с общим шаблоном это означало бы пять
    одинаковых сообщений подряд одному человеку. Он по-прежнему уходит первым —
    случай бросается среди приоритетных, пока они есть.

    ⚠ **Очередь по девушкам, а выбор человека — случайный.** Очередь делит пул
    поровну: бери мы каждый раз первую свободную, весь пул уходил бы от анкеты с
    меньшим `id`. Случайный собеседник ломает ровное чередование, по которому
    журнал сайта читается как рассылка.
    """
    blocked = blocked or set()
    taken = taken if taken is not None else set()

    # Свободные для этой девушки — те, с кем она не говорила, кто её не закрыл и
    # кому она сегодня ещё может писать.
    def free_for(girl):
        return [person for person in people
                if str(person.get('uid') or '')
                and (girl['id'], str(person['uid'])) not in taken
                and (girl['id'], str(person['uid'])) not in talked
                and (girl['id'], str(person['uid'])) not in blocked
                and (girl['id'], str(person['uid'])) not in invited]

    while True:
        gave = False

        for girl in girls:
            free = free_for(girl)
            if not free:
                continue

            # Приоритетные первыми: пока среди свободных есть отмеченные, случай
            # бросается только среди них.
            first = [person for person in free if person.get('priority')]
            person = random.choice(first or free)

            taken.add((girl['id'], str(person['uid'])))
            gave = True

            yield girl, person

        # Круг по всем девушкам не дал ни одной карточки — свободных больше нет.
        if not gave:
            return


def invite_templates_check(texts: list, asked: int) -> tuple[list[str], str]:
    """Предохранитель на ответ агента: столько ли текстов и все ли разные.

    Args:
        texts: что прислал агент, уже разобранное (`mail_agent._invites`).
        asked: сколько просили — по числу девушек в сети.

    Returns:
        tuple: `(годные, претензия)`. Годные — **уникальные** тексты в том
        порядке, в каком пришли. Претензия — строка для журнала и страницы
        «Ошибки»; пустая, когда ответ ровно такой, как просили.

    ## ⚠⚠⚠ Зачем: один шаблон ушёл всем девушкам, и это было незаметно

    Раздача текстов девушкам шла по кругу — `templates[at % len(templates)]`, — и
    на одном тексте круг замыкался на нём же: **все двенадцать анкет получали
    один и тот же шаблон**. Ни ошибки, ни отказа: пул набирался, инвайты
    уходили, панель докладывала «готово 93».

    Сломалось при этом не у нас: у соседа в шаге цикла `repeat.count` потерял
    метку переменной и стал единицей, то есть цикл давал один текст вместо
    одиннадцати. Мы же приняли это как законный ответ, потому что **не
    проверяли ответ вовсе**.

    Отсюда правило: ответ агента — это данные извне, и доверять им нельзя даже
    когда «извне» — свой же сосед.

    ## Что считается нарушением

    * **текстов меньше, чем просили** — часть девушек останется без инвайтов
      в этот заход (решает вызывающий), но повторять текст по кругу нельзя;
    * **есть одинаковые** — сосед уже обещал, что сверит их судьёй; раз
      одинаковые дошли, судья этого не сделал.

    ⚠ **Сравниваем нормализованно**, а не побайтно: регистр и лишние пробелы
    двух одинаковых реплик человек не различит, а сайт отправит обе.

    ⚠ **Больше, чем просили, — тоже претензия, но мягкая**: лишние не вредят,
    их просто не раздадут. Сказать о них стоит — это признак, что промпт
    соседа понял число иначе.
    """
    asked = max(0, int(asked or 0))

    seen, unique = set(), []
    for one in texts or []:
        text = str(one or '').strip()
        if not text:
            continue

        # ⚠ Ключ сравнения — не сам текст: разный регистр и двойные пробелы
        # дают «разные» строки, которых человек не различит.
        key = ' '.join(text.lower().split())
        if key in seen:
            continue

        seen.add(key)
        unique.append(text)

    got, same = len(unique), len(
        [one for one in (texts or []) if str(one or '').strip()]) - len(unique)

    why = []
    if same:
        why.append(f'одинаковых текстов: {same}')
    if asked and got < asked:
        why.append(f'текстов меньше, чем просили: {got} из {asked}')
    elif asked and len(texts or []) > asked:
        why.append(f'текстов больше, чем просили: {len(texts)} из {asked}')

    return unique, '; '.join(why)


async def _templates(site_id: int, language: str, how_many: int) -> list[str]:
    """Шаблоны реплики от агента: свой каждой девушке, **один вызов на всех**.

    Args:
        site_id: сайт-закладка.
        language: код языка реплики.
        how_many: сколько текстов просим — по числу девушек в сети.

    Returns:
        list: тексты шаблонов. Пустой список — агент промолчал или всё забраковал,
        и пул в этот заход не наберётся.

    ## ⚠⚠ Почему один вызов, а не по вызову на девушку

    Прежде шаблон был один на весь заход, и пул уходил от одного имени. Просить
    агента на каждую девушку отдельно — это дюжина вызовов LLM за заход, ровно та
    цена, ради ухода от которой шаблон и заводили.

    Середина: один вызов, а в нём просим столько текстов, сколько девушек, и
    **судья у соседа сверяет их между собой**. Похожие бракуются там же, где
    пишутся, — до того, как лягут в пул.

    ## ⚠⚠ Жребий бросает СОСЕД, а не панель

    Приём, длину, метки имён и «показать ли время» бросает шаг `dice` в workflow
    `dating_invite_one`; отсюда уезжают только **доли** — настройки сайта в
    процентах. Так каждая грань разнообразия живёт в одном месте: прежде новая
    стоила четырёх — настройка в реестре, жребий здесь, объявление переменной у
    соседа и правка промпта.

    ⚠ Жребий по-прежнему **на весь заход**, а не на текст: шаг стоит один раз до
    цикла реплик. Разнообразие между текстами даёт не он, а прямое требование
    модели «эти тексты должны отличаться» плюс судья. Бросай жребий на каждый —
    просьба «пиши разное» спорила бы с указанием «пиши вот таким приёмом».
    """
    asked = max(1, int(how_many))
    got = await invite_template(
        int(site_id), language,
        avoid=await _avoid(site_id),
        how_many=asked,
        # ⚠ Проценты, а не доли: у соседа они уезжают прямо в `spec` жребия, где
        # доли заданы в процентах. Делить на сто больше негде и не нужно.
        name_percent=await _man_percent(site_id),
        # ⚠ Строкой, как и доля имени мужчины: переменные вызова уходят строками,
        # и два типа на один довод читались бы как разные вещи. Настройки сайта под
        # эту долю нет — отсюда константа, а не `percent_value`.
        girl_name_percent=str(INVITE_GIRL_NAME_PERCENT))

    # ⚠⚠ **Ответ соседа проверяем, а не принимаем на слово.** Один текст на
    # двенадцать девушек выглядел законным ответом — и уехал в прод
    # (`invite_templates_check`).
    texts, why = invite_templates_check(got, asked)
    if why:
        logger_info(f'[dating] шаблоны инвайтов сайта #{site_id}: {why}')
        # ⚠ На страницу «Ошибки», а не в журнал анкеты: претензия про соседа и
        # про весь сайт. Удачный заход строку стирает сам.
        await error_write(ERROR_INVITE_TEMPLATES,
                          f'агент инвайтов прислал не то, что просили: {why}. '
                          f'Пока так, инвайты уйдут только от {len(texts)} '
                          f'анкет(ы) из {asked} — один текст на всех не '
                          f'раздаётся', int(site_id))
    else:
        await error_clear(ERROR_INVITE_TEMPLATES, int(site_id))

    return texts


