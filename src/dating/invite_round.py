# Как часто круг просыпается. ⚠ Не частота набора: её задаёт `invite_every`.
INVITE_ROUND_TICK_SEC = 60

# Настройки сайта, по которым круг живёт.
INVITE_EVERY_SETTING = 'invite_every'

# Отметка «этому сайту только что набирали». В Redis — переживает смену держателя.
INVITE_ROUND_KEY = 'dating:invite:round:{site_id}'

# Сколько держать строки инвайтов. Часами; ноль — не удалять.
INVITE_CLEAN_SETTING = 'invite_clean_hours'

# Как часто чистить. ⚠ **Свой срок, а не срок набора**: уборка не зависит ни от
# смен, ни от `invite_every` — таблица растёт круглые сутки, в том числе когда
# набор молчит. Десять минут: удаление стоит одного запроса, а держать таблицу
# точнее незачем.
INVITE_ROUND_CLEAN_EVERY = 600
INVITE_ROUND_CLEAN_KEY = 'dating:invite:clean:{site_id}'


async def invite_round_run(offset: int = 0) -> dict:
    """Один круг: добрать пул тем сайтам, у которых идёт смена и подошёл срок.

    Args:
        offset: сдвиг часового пояса панели, в часах. Смены заданы в местном
            времени, а сервер живёт по `UTC` — без сдвига «09:00–18:00» означало
            бы другие часы. Читается вызывающим на каждый круг: настройку правят
            на ходу.

    Returns:
        dict: `sites` — сайтов обойдено, `made` — реплик готово,
            `skipped` — пар пропущено.

    ⚠ **`schedule_now` принимает минуты суток, а не сдвиг.** Здесь стоял
    именно этот промах: в проверку смен уезжал `offset` (то есть `3`), и она
    сравнивала расписание с 00:03 — в смену `07:45–22:15` это не попадает
    никогда. Круг исправно находил сайт, молча его пропускал и возвращал `sites:
    0`; включённая на странице генерация не давала ни одной реплики, и понять это
    по логу было нечем — он пишет только про сделанное.
    """
    sites = await _sites()
    ran = made = skipped = 0
    for _, c in await pool_round_run(sites, offset_hours=offset, gate=_gate,
                                    every=_every, work=_work,
                                    key=INVITE_ROUND_KEY, what='инвайтам'):
        if c is not None:
            ran += c['sites']
            made += c['made']
            skipped += c['skipped']

    if made or skipped:
        logger_info(f'[dating] круг инвайтов: сайтов {ran}, готово {made}'
                    + (f', пропущено {skipped}' if skipped else ''))

    return {'sites': ran, 'made': made, 'skipped': skipped}


def invite_round_next(site_id: int) -> int:
    """Через сколько секунд круг вернётся к этому сайту. `0` — готов идти сейчас.

    ⚠ **Отвечает `TTL` отметки, а не наш расчёт.** Отметку ставит сам круг и
    гасит её Redis; считай мы «последний заход плюс срок», ответ разошёлся бы с
    действительностью в тот же час, когда настройку поправят на ходу.

    Заведено для страницы: в шапке пула висело «по расписанию» — обещание без
    срока. Пул набирается сам, и человек, включивший генерацию, не знал, ждать ему
    минуту или полчаса; выглядело это как «включил, а оно не работает».

    Returns:
        int: секунды до следующего захода. `0` — отметки нет, круг возьмётся за
        сайт на ближайшем тике (в пределах минуты). `-1` — спросить не вышло, и
        врать сроком нельзя.
    """
    try:
        left = redis_conn_get().ttl(INVITE_ROUND_KEY.format(site_id=int(site_id)))
    except Exception as e:
        logger_info(f'[dating] срок инвайтов не спросился: {e}')

        return -1

    # `-2` — ключа нет, `-1` — есть без срока. Первое значит «пора», второе у нас
    # невозможно (ставим только `setex`), но отвечать на него сроком нельзя.
    return 0 if int(left) == -2 else max(0, int(left))


async def _gate(site: dict, minutes: int) -> bool:
    """Сайт нуждается в доборе: чистка сделана, смена идёт, срок вышел.

    Чистка обязана идти и когда набор молчит: строки копятся круглые сутки,
    а смены говорят только о том, когда набирать. Выключатель и срок круга
    отвечают вместе, а часы общие на все сайты — их считает обвязка.
    """
    site_id = int(site['site_id'])

    # ⚠ **Уборка идёт до проверки смен, и это не оплошность.** Строки копятся
    # круглые сутки — отправкой, кнопками, прошлыми заходами, — а смены
    # говорят только о том, когда набирать. Чисти мы внутри смены, у сайта с
    # ночным расписанием таблица росла бы весь день.
    await _clean(site_id)

    # Смены пусты — расписания нет, и круг молчит: готовят такие сайты руками.
    shifts = json_column_load(site.get('invite_schedule')) or []

    return bool(shifts) and schedule_now(shifts, minutes) and round_slot_due(
        INVITE_ROUND_KEY, site_id, 'инвайтам')


async def _work(site: dict, minutes: int) -> dict | None:
    """Добирает пул до потолка; отказ одной анкетной пары не уносит пул.

    Строки с прежней ошибкой в счёт не идут: отправитель их не берёт, и одна
    застрявшая карточка иначе остановила бы инвайты навсегда.
    """
    site_id = int(site['site_id'])

    # ⚠ Сперва убираем из пула черновики ушедших анкет, и только потом
    # считаем место. Инвайт от анкеты не в сети отправить некому — отправка
    # ждёт её, — а потолок он занимает: полный пул мёртвых реплик означал бы,
    # что круг не добирает ни одной живой (`pool.py`).
    await pool_sweep(site_id)

    # ⚠ И черновики тех, **кому** писали, если их уже нет в сети. Реплика
    # зовёт сидящего в чате сейчас; ушёл — звать некого, а место в пуле она
    # держит. Без этой строки пул зарастал: 50 черновиков, годных 27.
    await pool_sweep_away(site_id)

    # ⚠⚠ И черновики тем, кто за это время **ответил**: инвайт заканчивается
    # ответом, и первой реплики ему больше не бывает. Такую строку не берёт ни
    # очередь отправки, ни сама отправка — то есть без уборки она лежала бы в
    # пуле вечно, занимая потолок (`pool.pool_sweep_answered`).
    await pool_sweep_answered(site_id)

    # ⚠⚠ **Добираем до потолка, а не ждём, пока пул опустеет.**
    #
    # Здесь стояло «набираем только пустой пул»: шаблон один на заход, и
    # доложенные карточки казались вторым текстом вперемешку с первым. Довод
    # был эстетический, а беда вышла настоящая — на проде пул застыл навсегда:
    # 21 черновик, отправка выключена (её включают отдельно), расходоваться
    # нечем, опустеть неоткуда. Круг исправно чистил ушедших и не набирал
    # ничего — со стороны «работает, но пул не растёт».
    #
    # ⚠ **Разные тексты в пуле оказались не бедой, а пользой.** Пул, набранный
    # с нуля, выходит одним текстом на всех; дальше он расходуется отправкой,
    # и каждый следующий заход добирает израсходованное **своим** текстом.
    # Человек читает пул не ради единообразия, а чтобы вычитать реплики.
    #
    # ⚠ Строки с прежней ошибкой в счёт не идут: отправитель их не берёт (их
    # дошлёт человек), и одна такая застрявшая карточка иначе остановила бы
    # инвайты навсегда.
    left = await _pool_max(site_id) - await invite_pool_left(site_id,
                                                                   ready_only=True)
    if left <= 0:
        return None

    try:
        got = await invite_make(site_id, left)
    except DatingInviteError as e:
        logger_info(f'[dating] инвайты сайта #{site_id}: {e}')

        return {'sites': 1, 'made': 0, 'skipped': 0}

    made = int(got.get('made') or 0)

    if got.get('made'):
        feed_write(site_id, 'invite',
                          f"Готовы инвайты в чат: {got['made']}")
    skipped = int(got.get('skipped') or 0)
    return {'sites': 1, 'made': made, 'skipped': skipped}


# ── Приватное ────────────────────────────────────────────────────────────────

async def _sites() -> list[dict]:
    """Сайты с включённым расписанием инвайтов."""
    try:
        async with mysql_get_db_async() as db:
            await db.execute('SELECT site_id, invite_schedule FROM site'
                             ' WHERE is_gone = 0 AND invite_schedule_on = 1'
                             ' ORDER BY site_id')
            rows = await db.fetchall()
    except Exception as e:
        logger_info(f'[dating] сайты для инвайтов не спросились: {e}')

        return []

    return [dict(row) for row in rows or []]


async def _seconds(site_id: int, key: str) -> int:
    from src.uvicorn.routers.dating.site_ import site_seconds

    return int(await site_seconds(site_id, key))


async def _every(site_id: int) -> int:
    """Как часто добирать пул внутри смены, в секундах."""
    return await _seconds(site_id, INVITE_EVERY_SETTING)


async def _pool_max(site_id: int) -> int:
    """До какого числа неотправленных добираем пул."""
    return await _seconds(site_id, INVITE_POOL_SETTING) or INVITE_POOL_DEFAULT


async def _clean(site_id: int) -> int:
    """Убирает старые строки инвайтов. Возвращает, сколько удалено.

    ## ⚠⚠ Это **единственное** удаление в таблице

    Прежде их было два: здесь по сроку, и в наборе пула — по числу строк на пару
    (`invite_keep`). Второе убрано. Инвайт живёт у собеседника около часа, ответить
    на вчерашний он не может физически, и «держать историю на случай ответа» было
    решением без задачи. А два правила на «сколько строк живёт» спорили друг с
    другом, и по журналу нельзя было сказать, какое сработало.

    `invite_keep` осталась, но отвечает теперь на другой вопрос — сколько
    приглашений **показать в диалоге**, когда собеседник ответил
    (`chat.chat_invites_to_history`).

    ## ⚠⚠ Срок короче суток укорачивает паузу повтора и дневной потолок

    Оба считаются по этой же таблице (`invite._invited`): пауза смотрит
    `MAX(sent_at)`, потолок — сколько ушло за скользящие сутки. Стёртая строка
    поднимает их молча — поставив «старше 6 часов» при потолке «10 в сутки»,
    человек получает потолок «10 за шесть часов», то есть вчетверо больший.

    Это названо в самой настройке, и выбор остаётся за ним: таблица на сто с
    лишним тысяч строк — тоже настоящая беда, и она больше ничем не ограничена.
    Наше дело — не решать за него тихо.

    ⚠ **Ответы собеседников не теряются.** Реплика, на которую ответили, уезжает
    в переписку (`message`) тем же кругом, который ответ принимает; здесь
    удаляется учётная строка, а не разговор.

    ⚠ **Черновики удаляются наравне с отправленным.** Черновик старше срока —
    это реплика тому, кто был в сети полсуток назад: отправлять её уже некому,
    а место в пуле она держит.

    ⚠ Сбой чистки не роняет круг: набор пула важнее размера таблицы.
    """
    from src.uvicorn.routers.dating.site_ import site_seconds

    if not round_slot_due(INVITE_ROUND_CLEAN_KEY, site_id, 'чистке инвайтов'):
        return 0

    try:
        hours = int(await site_seconds(int(site_id), INVITE_CLEAN_SETTING) or 0)
    except Exception as e:
        logger_info(f'[dating] срок чистки инвайтов сайта #{site_id} не прочитался: {e}')

        return 0

    # ⚠ Отметку ставим и при выключенной настройке: иначе чтение настройки
    # повторялось бы каждый тик, то есть шестьдесят раз за те же десять минут.
    round_slot_mark(INVITE_ROUND_CLEAN_KEY, site_id, INVITE_ROUND_CLEAN_EVERY,
                  'чистке инвайтов')
    if hours <= 0:
        return 0

    try:
        async with mysql_get_db_async() as db:
            await db.execute(
                'DELETE FROM invite WHERE site_id = %s'
                ' AND created_at < NOW() - INTERVAL %s HOUR',
                (int(site_id), hours))
            gone = int(db.rowcount or 0)
            await db.connection.commit()
    except Exception as e:
        logger_info(f'[dating] чистка инвайтов сайта #{site_id} не прошла: {e}')

        return 0

    if gone:
        logger_info(f'[dating] инвайты сайта #{site_id}: убрано {gone} строк '
                    f'старше {hours} ч')

    return gone


