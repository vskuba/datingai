# Как часто круг просыпается. ⚠ Это **не** частота отправки: ту задаёт
# `invite_send_every`, а круг лишь смотрит, не пора ли.
#
# ⚠⚠ **Тик — потолок частоты, и об этом легко забыть.** Пауза короче тика
# недостижима: круг просто не проснётся вовремя. Было пятнадцать секунд, и любая
# настройка ниже пятнадцати молча означала бы пятнадцать — то есть страница
# обещала бы то, чего круг не сделает.
#
# Секунда — самая частая отправка, которую предлагает страница; тик равен ей, а не
# меньше: просыпаться чаще, чем можно отправить, незачем.
#
# ⚠ Было три секунды. Опустили по просьбе заказчика, попросившего пункт «1
# секунда»: добавить его в список, не тронув тик, значило бы обещать со страницы
# то, чего круг не сделает — он выждал бы свои три.
#
# Цена — один запрос к базе на сайт в секунду вместо одного в три: 3600 в час
# против 1200. Для двух сайтов это по-прежнему пустяк, а вот отправка на такой
# частоте — нет: см. предупреждение у предела ниже.
INVITE_SEND_ROUND_TICK_SEC = 1

# Настройки сайта: пауза между репликами и потолок за сутки.
INVITE_SEND_EVERY_SETTING = 'invite_send_every'
INVITE_SEND_MAX_DAY_SETTING = 'invite_send_max_day'

# Сколько реплик отправлять за один заход круга.
#
# ⚠ **Пачка — это не «быстрее», а «крупнее».** Пауза (`invite_send_every`) осталась
# и держит промежутки **между заходами**; пачка говорит, сколько уйдёт внутри
# одного. Раньше уходила ровно одна, и полсотни реплик растягивались на полсотни
# пауз.
#
# ⚠ Внутри пачки реплики идут **подряд, без паузы**: сайт видит их одним всплеском
# — за этим и нужна настройка, а не константа. Один сайт терпит десяток, другой
# закроет учётку и на трёх.
INVITE_SEND_BATCH_SETTING = 'invite_send_batch'
INVITE_SEND_BATCH_DEFAULT = 1

# Умолчания на случай сайта без настроек. Минута и сотня — с них решили начать.
INVITE_SEND_EVERY_DEFAULT = 60
INVITE_SEND_MAX_DAY_DEFAULT = 100

# ⚠ Нижний предел поверх настройки: он сторожит **опечатку**, а не решение.
#
# Был двадцать секунд с доводом «пять превратило бы смену в очередь из сотен
# реплик в час». Довод верен, но это решение заказчика, а не наше: он и просил
# трёхсекундную паузу, увидев, как сайт отвечает на поток. Предел остаётся, чтобы
# `0` или `-1`, вписанные руками в базу, не превратились в отправку без пауз
# вовсе — то есть в сотни запросов в минуту к чужому сайту.
#
# ⚠ **Равен тику круга** (`INVITE_SEND_ROUND_TICK_SEC`): меньшее значение
# всё равно недостижимо — круг не проснётся чаще, — и предел, не совпадающий с
# тиком, обещал бы частоту, которой нет.
#
# ⚠⚠ **Секунда — это 3600 реплик в час**, и предел её больше не сдерживает. Что
# сдерживает: дневной потолок (`invite_send_max_day`), размер пула и число анкет в
# сети. Ставить секунду постоянно — значит проверять терпение сайта, а не
# работать; он считает частоту обращений и отвечает на такое блокировкой.
INVITE_SEND_EVERY_MIN = INVITE_SEND_ROUND_TICK_SEC

# Когда сайту уходила последняя реплика: `{сайт: время}`. В памяти процесса, как у
# круга отправки писем: перезапуск смены — это лишняя пауза, а не лишняя реплика,
# и ошибаться сюда безопасно.
_sent_at: dict[int, float] = {}


async def invite_send_round_run(offset_hours: int = 0) -> dict:
    """Один заход: каждому сайту, которому пора, — по одной реплике.

    Args:
        offset_hours: часовое смещение панели (настройка `timezone`). Смены
            заданы местным временем, а сервер живёт по UTC.

    Returns:
        dict: `sent` и `failed` — сколько ушло и сколько не ушло за этот заход.
    """
    minutes = _minutes_now(offset_hours)
    sent = failed = 0

    for site in await _sites():
        site_id = int(site['site_id'])

        # ⚠⚠ **Почему не пошли — записью, а не молчанием.** Причину считает тот же
        # код, что отвечает странице (`invite_send_why`): своя копия правил
        # разошлась бы с кругом на первой же правке. Пишется **смена** причины, а
        # не каждый заход — иначе за ночь набежало бы пятьсот одинаковых строк
        # (`idle.py`).
        #
        # Беда, ради которой заведено, случилась живьём: пул застыл на 21
        # черновике и не набирался неделю, а со стороны выглядел работающим.
        # ⚠ Размен осознанный: `_why` внутри снова спрашивает список сайтов, то
        # есть на заход выходит лишний запрос к **своей** базе. Он дешёвый, а
        # единственный источник правил дороже: разойдись круг с ответом странице,
        # человек читал бы «уходит» там, где не уходит.
        why = await invite_send_why(site_id, offset_hours)
        if why:
            await idle_write('invite_send', why, site_id=site_id)
            continue

        if time.time() - _sent_at.get(site_id, 0.0) < await _every(site_id):
            continue

        invite = await _next(site_id)
        if not invite:
            await idle_write('invite_send', 'пул пуст: отправлять нечего',
                                    site_id=site_id)
            continue

        # Пошли — гасим прежнее объявление о простое, если оно было.
        await idle_write('invite_send', '', site_id=site_id)

        # ⚠ Отметку о заходе ставим **до** отправки, а не после. Отправка идёт
        # секунды, а тик — пятнадцать: не отметь мы сразу, второй тик успел бы
        # взять ту же строку, пока первый ждёт ответа сайта.
        _sent_at[site_id] = time.time()

        # ⚠⚠ **Пачка не смеет перескочить дневной потолок.** До правки за заход
        # уходила одна реплика, и проверка нормы перед ней была достаточной;
        # пачка же шлёт несколько — а норма считается до захода. Берём меньшее:
        # сколько просит настройка и сколько осталось до потолка.
        today, cap = await _today(site_id, offset_hours), await _max_day(site_id)
        batch = min(await _batch(site_id), max(0, cap - today))

        for number in range(batch):
            # Первую реплику уже взяли выше — не спрашивая пул дважды.
            if number:
                invite = await _next(site_id)
                if not invite:
                    break

            if (await invite_send_one(invite))['ok']:
                sent += 1
            else:
                # ⚠ **Неудача обрывает пачку.** Причина у неё почти всегда общая
                # для всех реплик захода — сайт отказал, сессия протухла, — и
                # дослать остальные значило бы получить те же отказы, кормя
                # счётчик сайта. Круг вернётся через пятнадцать секунд.
                failed += 1
                break

    if sent or failed:
        logger_info(f'[dating] круг инвайтов: ушло {sent}'
                    + (f', не ушло {failed}' if failed else ''))

    return {'sent': sent, 'failed': failed}


async def _batch(site_id: int) -> int:
    """Сколько реплик отправлять за заход. Настройка сайта.

    ⚠ Ноль и мусор дают единицу, а не «ничего»: «не отправлять» — это отдельный
    выключатель (`invite_send_on`), и отменять отправку настройкой размера пачки
    значило бы два выключателя об одном.
    """
    from src.uvicorn.routers.dating.site_ import site_seconds

    return max(1, int(await site_seconds(site_id, INVITE_SEND_BATCH_SETTING))
               or INVITE_SEND_BATCH_DEFAULT)


async def invite_send_why(site_id: int, offset_hours: int = 0) -> str:
    """Почему из пула сейчас ничего не уходит. Пусто — уходит, повода нет.

    Args:
        site_id: сайт-закладка.
        offset_hours: часовое смещение панели — смены и сутки нормы местные.

    Returns:
        str: одна строка для шапки пула, человеческими словами.

    ⚠⚠ **Ради этого всё и написано: молчащий пул неотличим от сломанного.**
    Наблюдалось живьём — «пул инвайтов 50 из 50», девять анкет в сети, смена идёт,
    и ничего не уходит третий час. Причина была законной (выбрана дневная норма), но
    лежала она в журнале воркера, а человек смотрел на страницу.

    ⚠ **Считается теми же вопросами и в том же порядке, что и сам круг** (выше в
    этом файле), а не второй их копией: разойдись они, шапка объясняла бы простой,
    которого нет, или молчала бы там, где круг стоит.

    ⚠ **Порядок — от решённого к преходящему.** Снятый выключатель важнее часов, а
    часы важнее того, что прямо сейчас никого нет в сети: первое человек менял сам,
    последнее пройдёт само через минуты.
    """
    site_id = int(site_id or 0)
    if not site_id:
        return ''

    try:
        sites = {int(one['site_id']): one for one in await _sites()}
        site = sites.get(site_id)
        if not site:
            # Выключатель снят либо сайт помечен ушедшим. Первое человек сделал
            # сам, и сказать об этом надо прямо: «пул полон, а ничего не уходит»
            # без объяснения читается как поломка.
            return 'отправка инвайтов выключена'

        if not schedule_now(json_column_load(site['invite_schedule']),
                                   _minutes_now(offset_hours)):
            return 'сейчас не смена: инвайты уходят по часам, заданным у сайта'

        today, cap = await _today(site_id, offset_hours), await _max_day(site_id)
        if today >= cap:
            return (f'на сегодня норма выбрана: ушло {today} из {cap}. '
                    'Поднять — настройка сайта «Инвайтов наружу в сутки»')

        # ⚠ Дальше — **ровно то, что смотрит `_next`**, и в том же порядке: анкета в
        # сети, черновик без прежней ошибки, собеседник в ленте. Каждое из трёх
        # объясняется своими словами, иначе «нечего отправлять» звучало бы одинаково
        # для «все девушки спят» и «все адресаты ушли с сайта».
        if await _next(site_id):
            return ''

        return await _nothing_to_send(site_id)
    except Exception as e:
        logger_info(f'[dating] повод простоя инвайтов не спросился: {e}')

        # Молчим: подсказка не обязана работать, когда не работает база. Пустая
        # строка означает «сказать нечего», а не «всё хорошо».
        return ''


# ── Приватное ────────────────────────────────────────────────────────────────


async def _nothing_to_send(site_id: int) -> str:
    """Почему `_next` вернул пусто: три разные причины, и каждая своя работа."""
    try:
        async with mysql_get_db_async() as db:
            await db.execute(
                "SELECT SUM(p.status = 'online' AND p.enabled = 1) AS from_alive,"
                "       SUM(i.error <> '') AS failed, COUNT(*) AS total"
                '  FROM invite i'
                '  JOIN profile p ON p.id = i.profile_id'
                " WHERE i.site_id = %s AND i.status = 'draft'", (int(site_id),))
            row = dict((await db.fetchone()) or {})
    except Exception as e:
        logger_info(f'[dating] разбор простоя инвайтов не удался: {e}')

        return ''

    if not int(row.get('total') or 0):
        return 'пул пуст: отправлять нечего'

    if not int(row.get('from_alive') or 0):
        return 'анкеты, которым принадлежат черновики, сейчас не в сети'

    if int(row.get('failed') or 0) >= int(row.get('total') or 0):
        return ('все черновики с ошибкой — круг такие не берёт, '
                'их досылают кнопкой')

    return 'никого из адресатов пула нет сейчас в сети — ждём, пока зайдут'


async def _sites() -> list[dict]:
    """Сайты, где отправка инвайтов разрешена."""
    try:
        async with mysql_get_db_async() as db:
            await db.execute(
                'SELECT site_id, invite_schedule FROM site'
                ' WHERE is_gone = 0 AND invite_send_on = 1 ORDER BY site_id')
            rows = await db.fetchall()
    except Exception as e:
        logger_info(f'[dating] сайты для отправки инвайтов не спросились: {e}')

        return []

    return [dict(row) for row in rows or []]


async def _next(site_id: int) -> dict:
    """Следующая реплика сайта: самая старая годная. Пусто — отправлять нечего.

    ⚠ **Только строки без прежней ошибки** (`error = ''`): взявшись за них снова,
    круг зациклился бы на отказе сайта. Такая реплика ждёт человека с кнопкой.

    ⚠ **Только от анкеты, которая в сети** — условие в запросе, а не после
    выборки: отбери мы старейшую и отбрось её по статусу, круг стоял бы, пока
    первая в очереди девушка не вернётся, хотя писать было кому.

    ⚠⚠ **И только тому, кто сейчас в сети.** Пул набирается кругом раз в полчаса,
    а люди на сайте живут минутами: через час половина адресатов ушла. Прежде круг
    брал старейшую строку не глядя, получал «собеседника нет в сети» — и **писал
    это в `error`**, то есть глушил черновик состоянием, которое само проходит.

    Поймано в первый же час работы: пул на 50 черновиков, в сети из них 27, и
    круг пошёл заглушать остальные по одной в минуту.

    Отбор идёт по тому же снимку ленты, что и запрет в самой отправке
    (`send`): второй источник «кто в сети» разошёлся бы с первым, и круг
    выбирал бы того, кому отправка всё равно откажет.

    ⚠⚠ **Приоритетные — первыми.** Отметка на карточке (`companion.priority`)
    и заведена ради этого: человек указал, с кем говорить в первую очередь. Стой
    очередь по одному возрасту, его реплика ждала бы полсотни чужих — при паузе в
    минуту это час, а он в чате десять минут.

    Отметка работает и на наборе (`_by_priority` ставит его первым в ленте), но
    одного набора мало: попасть в пул и уйти из пула — разные сроки.

    Порядок внутри половин — по возрасту строки: реплика сочинялась под человека,
    который был в чате тогда, и чем дольше она лежит, тем меньше от неё толку.
    """
    try:
        async with mysql_get_db_async() as db:
            # ⚠ `LEFT JOIN`: карточка собеседника заводится по требованию, и у
            # большинства адресатов её нет вовсе. Обычный `JOIN` оставил бы в
            # очереди только тех, кому её однажды открывали.
            await db.execute(
                'SELECT i.id, i.site_id, i.profile_id, i.uid, i.name, i.body'
                '  FROM invite i'
                '  JOIN profile p ON p.id = i.profile_id'
                '  LEFT JOIN companion c'
                '         ON c.site_id = i.site_id AND c.uid = i.uid'
                " WHERE i.site_id = %s AND i.status = 'draft' AND i.error = %s"
                "   AND p.enabled = 1 AND p.status = 'online'"
                ' ORDER BY COALESCE(c.priority, 0) DESC, i.created_at, i.id',
                (int(site_id), ''))
            rows = await db.fetchall()
    except Exception as e:
        logger_info(f'[dating] очередь инвайтов сайта #{site_id} не спросилась: {e}')

        return {}

    for row in rows or []:
        if online_check(int(site_id), str(row['uid']))['online']:
            return dict(row)

    return {}


async def _today(site_id: int, offset_hours: int = 0) -> int:
    """Сколько реплик сайта ушло за сегодня. Считаем по факту, а не по попыткам.

    ⚠⚠ **Сутки — местные, а не серверные.** Прежде здесь стояло `DATE(sent_at) =
    CURDATE()`, то есть календарный день **базы**, а она живёт по UTC. Смены же
    заданы местным временем, и панель показывает местное: при смещении в три часа
    сутки нормы кончались в три часа ночи — посреди ночной смены.

    Ровно это и наблюдалось: ночная смена (00:00–05:00 местных) прошла границу
    суток UTC, за час выбрала все сто реплик «нового дня» — и до следующей полуночи
    UTC отправка стояла. В пуле при этом лежало полсотни готовых, девять анкет были
    в сети, и по всем признакам панель выглядела сломанной.

    ⚠ Календарные сутки, а не скользящие, — намеренно: настройка называется «в
    сутки», и человек читает её как «с полуночи». Скользящее окно у нас есть, но у
    другого вопроса — «как часто звать **одного и того же**» (`invite.py`),
    где полночь и правда ничего не значит.
    """
    try:
        async with mysql_get_db_async() as db:
            await db.execute(
                'SELECT COUNT(*) AS n FROM invite'
                " WHERE site_id = %s AND status = 'sent'"
                '   AND DATE(sent_at + INTERVAL %s HOUR)'
                '     = DATE(NOW() + INTERVAL %s HOUR)',
                (int(site_id), int(offset_hours or 0), int(offset_hours or 0)))
            row = await db.fetchone()
    except Exception as e:
        logger_info(f'[dating] дневной счёт инвайтов #{site_id} не спросился: {e}')

        # ⚠ Не сосчитали — считаем, что потолок выбран. Верная сторона ошибки:
        # молчание дешевле сотни реплик сверх нормы.
        return INVITE_SEND_MAX_DAY_DEFAULT

    return int((row or {}).get('n') or 0)


async def _every(site_id: int) -> int:
    """Пауза между репликами у этого сайта, не короче жёсткого предела."""
