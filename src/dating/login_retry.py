"""Сколько раз подряд пробовать вход и с какой паузой — две настройки сайта.

## ⚠⚠ Зачем заведено: девять входов за четырнадцать минут

Живой случай на проде, анкета #41 (Ladadate). Сценарий проходил форму, сайт
кабинет не подтверждал, и круг расписания пробовал снова — **каждые 86 секунд,
безостановочно**:

    17:11:17  Прохожу форму входа сценарием «вход под анкетой»
    17:11:42  Сайт вход не признал: нужен повторный логин
    17:12:43  Прохожу форму входа сценарием «вход под анкетой»
    17:13:09  Сайт вход не признал: нужен повторный логин
    …

Ровно то, за что сайт закрывает вход по внешнему адресу, и ровно та беда, из-за
которой мы уже сутки просидели в блокировке Ladadate.

## ⚠ Почему лестница отката это не поймала

Лестница пауз (`revive.py`) была, работала и к этому входу **отношения не
имела**: её спрашивает круг восстановления, а входил круг расписания — прямым
вызовом `login_run`, минуя все правила.

Отсюда первое решение: **правило живёт у самой двери**. Проверка стоит в
`login_run`, то есть перед любым входом — расписание, восстановление,
кнопка, — и обойти её нельзя, не переписав вход.

## ⚠ Почему параметрами, а не константами

Прежние сроки были зашиты в код лестницей `(1, 5, 15, 45, 90)` минут. Спорить с
ними человек не мог, и — что хуже — не мог **узнать**, чего ждать: в панели это
выглядело как «оно почему-то не входит». Теперь в настройках сайта две строки, и
обе отвечают на вопрос словами:

| Ключ | Что задаёт | По умолчанию |
|------|-----------|--------------|
| `login_retry_max` | сколько **отказов сайта** подряд терпим | 3 |
| `login_retry_every` | пауза между попытками | 15 минут |

## ⚠⚠ Потолок считает отказ сайта, а не сорвавшийся прогон

Неудачи входа двух родов, и мешать их нельзя:

| Что случилось | Чем считается | Что делает |
|---------------|---------------|------------|
| сайт не признал кабинет, пароль не тот | отказ сайта, `login_retry_fail` | счётчик +1, на третий раз автомат замолкает |
| вкладка закрылась, клик не дождался кнопки | сорвавшийся прогон, `login_retry_hold` | только пауза, потолок не двигается |

⚠ **Цена размена: у сорвавшегося прогона потолка нет вовсе.** Сломанный наглухо
сценарий будет пробоваться, пока держится смена, — примерно четыре раза в час
(круг расписания зовёт вход каждую минуту, пропускает его пауза). Прежде такой
сценарий замолкал после третьего раза и навсегда. Разменяно сознательно: «навсегда»
запирало и **здоровые** учётки, а четыре попытки в час — это на порядок меньше той
долбёжки, ради которой потолок заводили (тридцать восемь в час). Понадобится предел
и здесь — заводить его отдельной настройкой, а не возвращать общий счётчик.

Цена смешения измерена дважды, и с обеих сторон:

* **Анкета #40 (Ladadate), 28.09.** Три браузерных таймаута за вечер — «Target
  page, context or browser has been closed» и дважды `Locator.click: Timeout
  30000ms` — защёлкнули потолок. Сутки после этого автомат к сайту не ходил ни
  разу: двенадцать «попыток» лестницы восстановления упирались в свою же дверь, а
  панель объявила «сутки не выходит войти». Сайт при этом пускал — тем же логином
  человек вошёл руками без заминки.
* **Обратный конец.** Ветка «Сайт вход не признал» уходила из входа своим
  `return`, до счётчика не доходя, — то есть отказ сайта в потолок не попадал
  вовсе, и беда, ради которой потолок заводили (девять входов за четырнадцать
  минут, ниже), им не ловилась.

Кончились попытки — автомат к сайту не идёт вовсе, пока человек не нажмёт «Войти»
руками. Это и есть предел: неудачи копятся, счётчик не сбрасывается сам по
времени, а гаснет **только удавшимся входом**.

⚠ **Пауза одна на все попытки, а не лестница.** Растущая пауза точнее в теории —
частые беды рассасываются за минуту, редкие требуют часа, — но объяснить её
человеку нечем: он видит «следующая попытка через 45 минут» и не понимает, откуда
число. Одна пауза и один потолок понятны с первого взгляда, а разницу в цене
покрывает потолок: три попытки по четверти часа — это сорок пять минут, после
которых автомат замолкает совсем.

## Кнопка человека сильнее

`force=True` проходит и через исчерпанный счётчик, и через паузу: человек у экрана
видит больше автомата — он мог сменить пароль, разблокировать учётку, дождаться
конца чужой блокировки. Отказывать ему значило бы чинить сайт через базу.
"""

from datetime import timedelta

from datetime_.datetime_ import datetime_utc_now
from mysql_.mysql_ import mysql_get_db_async

# Настройки сайта. Ключи — в `SITE_KNOWN`.
LOGIN_RETRY_MAX_SETTING = 'login_retry_max'
LOGIN_RETRY_EVERY_SETTING = 'login_retry_every'

# Умолчания на случай, если настройки у сайта нет. Три попытки по четверти часа:
# сорок пять минут на беду, которая проходит сама, и полная тишина после.
LOGIN_RETRY_MAX_DEFAULT = 3
LOGIN_RETRY_EVERY_DEFAULT = 900


class DatingLoginHeld(Exception):
    """Вход сейчас запрещён: идёт пауза или кончились попытки.

    ⚠ **Своё исключение, а не `DatingLoginError`.** Тот значит «войти нечем» —
    нет пароля, сценария, сайта, — и человек по нему идёт что-то исправлять.
    Здесь же всё настроено, просто рано: круг обязан промолчать и уйти, а не
    писать в журнал строку, похожую на поломку.
    """


async def login_retry_allowed(profile: dict) -> tuple[bool, str]:
    """Можно ли пробовать вход прямо сейчас.

    Два тормоза, и они про разное: **потолок** считает отказы сайта, **пауза**
    отсчитывается от последней неудачи любого рода. Поэтому пауза проверяется и
    при нулевом счётчике — иначе у сорвавшегося прогона её не было бы вовсе, и
    сломанный браузер соседа получал бы вкладку раз в минуту.

    Returns:
        tuple: `(можно, причина)`. Причина непустая только у запрета и написана
        для человека: она уходит в журнал анкеты.
    """
    site_id = int(profile.get('site_id') or 0)
    tries = int(profile.get('login_fail_tries') or 0)
    last = profile.get('login_fail_at')

    # Чистая анкета уходит без вопросов и без чтения настроек: первая попытка
    # бесплатна, а вход зовут из трёх кругов.
    if not tries and not last:
        return True, ''

    retry_max = await _retry_max(site_id) if tries else 0
    if tries and tries >= retry_max:
        return False, (f'вход не идёт: {tries} отказов сайта подряд из {retry_max} '
                       f'разрешённых. Автомат больше не пробует — нажмите «Войти» '
                       f'на карточке анкеты, когда будет что менять')

    if not last:
        return True, ''

    every = await _retry_every(site_id)
    left = int(every - (datetime_utc_now() - last).total_seconds())
    if left <= 0:
        return True, ''

    if not tries:
        # ⚠ Номера попытки тут нет намеренно: к потолку сорвавшийся прогон не
        # попытка, и «Попытка 1 из 3» обещала бы человеку счёт, которого не идёт.
        return False, (f'вход не идёт: прогон сорвался, ждём {_minutes(every)}, '
                       f'осталось {_minutes(left)}')

    return False, (f'вход не идёт: после неудачи ждём {_minutes(every)}, '
                   f'осталось {_minutes(left)}. Попытка {tries + 1} из {retry_max}')


async def login_retry_fail(profile_id: int) -> None:
    """Записывает **отказ сайта**: счётчик плюс один, отсчёт паузы с этой минуты.

    ⚠ Только отказ сайта, а не любая неудача. Сорвавшийся прогон браузера идёт в
    `login_retry_hold` — там же и объяснено, почему их нельзя считать вместе.

    ⚠ **Счётчик не сбрасывается временем.** Пауза кончилась — значит можно
    пробовать снова, но попытка эта уже вторая, а не первая. Считай мы «давно
    было, начнём заново», потолок не наступил бы никогда: сайт, отвергающий вход
    ровно раз в четверть часа, получал бы их бесконечно.
    """
    async with mysql_get_db_async() as db:
        await db.execute(
            'UPDATE profile'
            '   SET login_fail_tries = login_fail_tries + 1, login_fail_at = NOW()'
            ' WHERE id = %s', (int(profile_id),))
        await db.connection.commit()


async def login_retry_hold(profile_id: int) -> None:
    """Сорвавшийся прогон: пауза встаёт, потолок не двигается.

    ⚠⚠ **Отдельно от `login_retry_fail`, и это главное в потолке.** Отказ сайта и
    сорвавшаяся вкладка Chromium — разные события: первое значит «войти не
    получается, нужен человек», второе — «прогон не отработал, повод попробовать
    позже». Считай их одним счётчиком, и беда соседа запирает здоровую учётку.

    Цена измерена на проде, анкета #40 (Ladadate): три браузерных таймаута
    вечером 28.09 защёлкнули потолок, и сутки после того автомат к сайту не ходил
    ни разу — при живом пароле и работающем сайте. Снять защёлку могла только
    кнопка человека.

    Пауза при этом нужна: без неё круг расписания пошёл бы в браузер снова через
    минуту, а каждая вкладка — память в пуле, общем с соседом.
    """
    async with mysql_get_db_async() as db:
        await db.execute('UPDATE profile SET login_fail_at = NOW() WHERE id = %s',
                         (int(profile_id),))
        await db.connection.commit()


async def login_retry_max(site_id: int) -> int:
    """Сколько неудач подряд терпит этот сайт — для журнала и страниц.

    Публичная обёртка над той же настройкой, что читает сама проверка: номер
    попытки в журнале обязан совпадать с тем пределом, по которому вход
    останавливается, а две копии чтения разошлись бы на первой же правке.
    """
    return await _retry_max(site_id)


# ── Приватное ────────────────────────────────────────────────────────────────

async def _retry_max(site_id: int) -> int:
    from src.uvicorn.routers.dating.site_ import site_seconds

    return int(await site_seconds(site_id, LOGIN_RETRY_MAX_SETTING)
               or LOGIN_RETRY_MAX_DEFAULT)


async def _retry_every(site_id: int) -> int:
    from src.uvicorn.routers.dating.site_ import site_seconds

    return int(await site_seconds(site_id, LOGIN_RETRY_EVERY_SETTING)
               or LOGIN_RETRY_EVERY_DEFAULT)


def _minutes(seconds: int) -> str:
    """Секунды словами: «15 минут», «90 секунд». Человек читает журнал глазами."""
    seconds = max(0, int(seconds))
    if seconds < 120:
        return f'{seconds} сек'

    return f'{round(seconds / 60)} мин'
