"""Шаблоны писем: переменные, подстановка, проверка.

Письмо рассылки собирается из **шаблона** (`mail.body`) и **переменных
анкеты**, от которой оно уходит.

## ⚠ Переменные заводит человек, а не код

Прежде здесь лежал жёсткий список из семи имён (`his_name`, `her_name`, …), и
письмо умело ровно то, что придумал код. Это было неверно: какие сведения об
анкете нужны письму, знает человек, ведущий сайт.

Теперь переменные — **данные**: реестр по сайту (`mail_var`), значения по
анкете (`dating_profile_var`). Заведённая переменная появляется у каждой анкеты
сайта пустой и наполняется — руками или агентом у соседа.

Отсюда главное следствие: **этот модуль ничего не знает про поля анкеты**. Он
берёт готовый словарь «имя → значение» и работает с текстом. Откуда словарь —
дело ручек (`routers/dating/mail.py`).

## Почему `[[name]]`, а не формат Python

`str.format` и f-строки спотыкаются на живом тексте: фигурная скобка в письме
роняет подстановку, а `{0}` из чужого текста лезет в аргументы. Здесь формат
закрытый — заменяются только известные имена, а всё прочее остаётся текстом,
включая одиночные скобки.

## ⚠ Незаполненная переменная — это отказ отправить письмо

Не пустая строка в тексте. Письмо «Меня зовут , мне  лет» уходит живому человеку и
выдаёт рассылку вернее, чем что-либо ещё. Поэтому `mail_missing` считает
нехватку до отправки, а рассылка такое письмо пропускает.
"""

import re

# Что считаем **попыткой** написать переменную. Пробелы внутри скобок разрешены —
# человек их ставит не думая, и `[[ firstName ]]` обязано работать так же, как
# `[[firstName]]`.
#
# ⚠ **Квадратные скобки, а не фигурные, и это не вкус.** Страницы панели собирает
# Jinja, у которой `{{ … }}` — свой синтаксис: литерал в фигурных скобках в коде
# страницы она пыталась вычислить как выражение и роняла разбор файла целиком.
# Обходилось это сборкой скобок из констант — то есть костылём в каждом месте, где
# скобки упоминались. `[[ … ]]` Jinja не трогает, и костыль убран.
#
# ⚠ **Содержимое здесь любое, а не только годное имя, и это важно.** Сперва
# регулярка ловила ровно то, что мы умеем подставлять. Выходило наоборот
# задуманному: `[[нет_такой]]` переменной не считалось вовсе, проверка его не
# видела, шаблон сохранялся — и скобки уезжали живому человеку в письме как есть.
#
# Поймано тестом `test_refused_template_is_not_stored`. Поэтому ловим всё, что
# похоже на переменную, а сверяет с реестром уже `mail_check`: «не знаю
# такого» — отказ, а не молчание.
MAIL_VAR_RE = re.compile(r'\[\[\s*([^\[\]]*?)\s*\]\]')

# Каким может быть имя переменной. ⚠ **Только латиница**, цифры и подчёркивание;
# регистр любой — человек пишет и `firstName`, и `first_name`, и спорить с ним
# здесь не о чем.
#
# Кириллица не годится намеренно: имя переменной уезжает агенту у соседа и
# возвращается ключом в JSON, а на этом пути один неверно угаданный кодек
# превращает `[[её_имя]]` в мусор, который не совпадёт ни с чем — молча.
MAIL_NAME_RE = re.compile(r'^[A-Za-z_][A-Za-z0-9_]*$')

# Предел длины письма. Не техническое ограничение колонки (`TEXT` вместит куда
# больше), а смысловое: письмо на сайте знакомств читают с телефона, и простыня в
# десять тысяч знаков не будет прочитана — зато будет отправлена тысяче человек.
MAIL_BODY_MAX = 4000

# ── Каким выходит шаблон рассылки: жребий вместо просьбы ────────────────────
#
# ⚠⚠ **Разнообразие даём мы, а не надеемся на модель** — вывод куплен дважды, на
# инвайтах и на письмах избранным. Один и тот же промпт она отвечает похоже: у
# неё сильные притяжения, и «будь разной» их не ломает. Живой прогон инвайтов дал
# три шаблона из трёх, начинавшихся с «you're trouble».
#
# Здесь цена ошибки выше, чем где-либо: шаблон рассылки живёт **сутками** и
# уходит сотням людей, а круг пишет по три штуки в день. Три похожих текста в
# сутки — это и есть «рассылка робота», которой мы стараемся не быть.
#
# ⚠⚠ **Бросаем мы не все оси: приём, длина, подпись и тема рассказа уехали к
# соседу.** Их бросает шаг «Жребий» самого `dating_mail_write` — `dice_mail_angle`,
# `dice_mail_length`, `dice_mail_sign`, `dice_mail_story`, — а объявления входящими
# сняты: присылка любой из них роняет **весь** вызов `400`-м. Здесь остался один
# зачин. Переехало место броска, а не решение бросать: правило выше в силе для
# всех осей, и доля рассказа больше не настройка панели — темы и жребий у одного
# шага.
#
# ⚠ Довод про длину остаётся записанным, потому что относится к оси, а не к месту
# броска: прежний промпт говорил «до четырёх абзацев», и это **потолок, а не
# вилка** — модель писала четыре каждый раз, а однообразие длины видно так же,
# как однообразие слов.

# ⚠ **Зачина здесь больше нет: с 2026-10-20 его бросает сосед** — шаг «Жребий»
# самого `dating_mail_write` (`dice_mail_greeting`, семь граней). Объявление
# `mail_greeting` у него снято, и присылка роняет весь вызов `400`-м.
#
# ⚠⚠ Вместе с переездом из набора ушёл приём «начни с признания, что писать
# первой было неловко» — и это не потеря, а починка. Он **дублировал** приёмы
# соседа (`honesty about the site`, `the second letter problem`), но весил
# 15,9% против их 3% — доли складывались. Живой разбор 20 заготовок: таким
# зачином начиналось **9 из 20** при ожидании 3,7. Одно решение — одно место.

# Сколько прошлых шаблонов показываем модели со словами «так уже было».
MAILING_AVOID_MAX = 10

# Доли — настройками сайта. ⚠ **Проценты в форме, доля в коде**: человек думает
# «каждое четвёртое письмо», а `random.random()` сравнивают с 0.25.
MAILING_QUESTION_SETTING = 'mailing_question_percent'
MAILING_QUESTION_CHANCE = 0.25


# ⚠⚠ Доли обращения по имени здесь больше нет (22.10.2026): жребий уехал к
# соседу осью `dice_mail_name`, к приёму, длине, подписи, теме и зачину. Веса
# 25/75 живут там же, в шаге «Жребий», и настройки сайта под это не нужно.
#
# Прежде бросали здесь, и это сломалось о правила промпта: строка «о получателе
# только через `[[companion_name]]`» стояла безусловно, а метку мы вычёркивали —
# модель ставила в обращение имя самой анкеты. Решение и правило должны жить
# рядом, иначе они расходятся молча.

# Предел названия шаблона. Оно живёт в списке панели и в колонку шире не влезет.
MAIL_NAME_MAX = 190

# Пределы переменной — по колонкам `mail_var`.
MAIL_VAR_NAME_MAX = 64
MAIL_VAR_TITLE_MAX = 190
MAIL_VAR_VALUE_MAX = 500


def mail_vars_found(body: str) -> list[str]:
    """Какие переменные встретились в тексте — в порядке появления, без повторов.

    Нужно и проверке (нет ли незнакомых), и странице (показать, что шаблон
    использует), и отправке (чего не хватает у анкеты).
    """
    found = []
    for name in MAIL_VAR_RE.findall(str(body or '')):
        # Пустые скобки (`[[]]`, `[[ ]]`) переменной не считаем: имени в них нет,
        # ругаться не на что, а подставлять тем более нечего.
        if name and name not in found:
            found.append(name)

    return found


def mail_var_check(name: str) -> str:
    """Годится ли имя переменной. Пустая строка — годится, иначе причина словами.

    Отдельно от проверки шаблона: имя заводят на вкладке «Переменные», а шаблон
    пишут на вкладке «Шаблоны», и ошибки у них разные.
    """
    name = str(name or '').strip()
    if not name:
        return 'у переменной должно быть имя'

    if len(name) > MAIL_VAR_NAME_MAX:
        return f'имя длиннее {MAIL_VAR_NAME_MAX} знаков'

    if not MAIL_NAME_RE.match(name):
        return ('имя переменной — только латиница, цифры и подчёркивание, '
                'и начинается не с цифры: firstName, last_name')

    return ''


def mail_check(name: str, body: str, known) -> str:
    """Годен ли шаблон. Пустая строка — годен, иначе причина словами.

    Args:
        name: название шаблона — для списка в панели.
        body: текст письма.
        known: имена переменных, заведённых на сайте этого шаблона.

    Причина уезжает человеку на страницу, поэтому говорит, что поправить, а не
    какое правило нарушено.

    ⚠ **Незнакомая переменная — отказ, а не молчаливая замена пустотой.** Опечатка
    `[[frstName]]` иначе уехала бы в письмо как есть, живому человеку, от имени
    анкеты. Заметить это можно было бы только в журнале отправок — то есть после
    рассылки.
    """
    known = set(known or ())

    if not str(name or '').strip():
        return 'у шаблона должно быть название'

    if len(str(name)) > MAIL_NAME_MAX:
        return f'название длиннее {MAIL_NAME_MAX} знаков'

    if not str(body or '').strip():
        return 'письмо не может быть пустым'

    if len(str(body)) > MAIL_BODY_MAX:
        return f'письмо длиннее {MAIL_BODY_MAX} знаков'

    unknown = [found for found in mail_vars_found(body) if found not in known]
    if unknown:
        # Говорим, что есть, а не только чего нет: у сайта без единой переменной
        # список пуст, и это само по себе ответ — их надо сперва завести.
        have = ', '.join(sorted(known)) if known \
            else 'на этом сайте переменных пока нет — заведите их на вкладке «Переменные»'

        return f'неизвестная переменная [[{unknown[0]}]]; {have}'

    return ''


def mail_missing(body: str, values: dict) -> list[str]:
    """Каких переменных не хватает, чтобы отправить это письмо.

    Args:
        body: текст шаблона.
        values: значения переменных анкеты — «имя → значение».

    Returns:
        list: имена, которых письму нужны, а значения у анкеты пусты. Порядок —
        как в письме: человек читает его сверху вниз и там же ищет пропуск.

    ⚠ **Пустое значение считается нехваткой.** Строка в базе есть, но пустая —
    это «переменную завели, а заполнить забыли», и подставлять пустоту нельзя:
    «Меня зовут , мне  лет» выдаёт рассылку вернее, чем что-либо ещё.
    """
    return [name for name in mail_vars_found(body)
            if not str(values.get(name) or '').strip()]


def mail_mark_drop(body: str, name: str) -> str:
    """Убирает переменную из текста вместе с её абзацем.

    Args:
        body: текст шаблона.
        name: имя переменной — той, которую в этом письме не заполняем.

    Returns:
        str: текст без неё. Пустые строки по краям и двойные разрывы внутри
        подчищены: вырезанный абзац не должен оставлять после себя дыру.

    ## ⚠⚠ Зачем вообще вырезать, а не оставить пустым

    Живой вопрос (`question_to_companion`) стоит **отдельным абзацем** — так
    требует промпт, потому что его значение это целая фраза. Спрашиваем мы его
    не в каждом письме: вопрос стоит вызова LLM на каждого адресата, и доля
    задана настройкой.

    Письмо, где вместо абзаца осталась метка, не уйдёт вовсе (`mail_missing`);
    письмо с пустой строкой на её месте выдаёт заготовку. Остаётся вырезать — и
    письмо честно кончается тем абзацем, который был до неё.

    ⚠ **Абзац вырезается целиком, только если в нём нет ничего, кроме метки.**
    Встроенную в фразу метку (такое ловит `text_marks_inline` у соседа, но
    старые шаблоны его не проходили) убираем саму — иначе вырезали бы полфразы.
    """
    name = str(name or '').strip()
    if not name:
        return str(body or '')

    mark = re.compile(r'\[\[\s*' + re.escape(name) + r'\s*\]\]')
    kept = []
    for block in re.split(r'\n\s*\n', str(body or '')):
        if not mark.search(block):
            kept.append(block)
            continue

        # В абзаце есть что-то кроме метки — вырезаем только её.
        rest = mark.sub('', block).strip()
        if rest:
            kept.append(rest)

    return '\n\n'.join(one.strip() for one in kept if one.strip()).strip()


def mail_render(body: str, values: dict) -> str:
    """Подставляет значения в текст письма.

    ⚠ **Заменяются только имена, для которых значение есть.** Незнакомое
    `[[что-то]]` остаётся в тексте как есть — и это осознанно: сохранить
    непонятное виднее, чем стереть. До отправки такое не доходит:
    `mail_check` не даёт сохранить шаблон с незнакомой переменной, а
    `mail_missing` — отправить письмо с незаполненной.

    Подстановка **не рекурсивная**: значение, в котором окажется `[[firstName]]`
    (агент вернул такое, собеседник вписал в имя на сайте), останется текстом.
    Иначе чужие данные управляли бы нашим шаблоном.
    """
    def _put(match):
        name = match.group(1)
        value = values.get(name)

        return str(value) if value not in (None, '') else match.group(0)

    return MAIL_VAR_RE.sub(_put, str(body or ''))
