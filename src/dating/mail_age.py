"""Возрастной критерий получателя: кому письмо не уйдёт, сколько его ни пиши.

Сайт отвечает на холодное письмо так:

    403 {"Error":"You do not match the criteria of age to send messages to this
         user","Reason":"ERROR_MESSAGE_AGE_CRITERIA"}

Человек выставил, от женщин какого возраста готов получать письма. Это
**не состояние и не каприз часа**: возраст девушки не изменится, и пара закрыта
навсегда — её и заносит `block.py` с каналом `mail`.

## ⚠⚠ Узнать это можно было бесплатно, и три недели мы платили

Отказ слышался **после** сочинения письма: 205 строк `failed` в пуле рассылки и
208 записей запрета за три недели — каждая ценой письма и похода к сайту.

А окно возраста **уже приезжает** в том же списке, по которому набирается пул.
`GET /users/{state}` отдаёт на каждого человека:

    {"AccountId":"706690","Age":68,"AgeFrom":35,"AgeTo":55, …}

Панель читала из этой записи четыре поля из десяти (`people_api.py`), и `AgeFrom`
с `AgeTo` выбрасывались.

## ⚠ Правило с запасом: промах меньше двух лет не считается

Сверка 203 пар из журнала запросов с живыми окнами (03.10.2026):

| | внутри окна | вне окна |
|---|---|---|
| сайт разрешил (140 пар) | 121 | 19 |
| сайт отказал по возрасту (63 пары) | **0** | **63** |

«Вне окна» — условие **необходимое**: отказов внутри окна нет ни одного. Но не
достаточное: у семи разрешённых пар промах был ровно год, и ещё у двенадцати —
больше. Объяснений двум последним случаям два, и оба мы проверить не можем: окна
читаются сегодня, а отказы случились до трёх суток назад (мужчина правит свои
критерии когда хочет), и у шести из девятнадцати мужчина **писал первым** —
похоже, для начатого разговора критерий не спрашивается вовсе.

Отсюда запас: **отсекаем, когда промах два года и больше**. Это снимает все 63
обречённых письма и может стоить до двенадцати разрешённых из ста сорока. Размен
осознанный: лишнее письмо стоит сочинения, запрета в базе и строки «не ушло» в
«Доставке», а пропущенное — одной возможности из сотни, и та вернётся, едва
мужчина поправит своё окно.

⚠ **Пара, которая уже переписывалась, не отсекается** — см. `talked` у
`mail_age_fits`. Шесть из девятнадцати разрешённых промахов именно такие.

## ⚠ «Не знаем» значит «пишем»

Нет окна в записи (сайт не отдал, снимок ленты старый), нет возраста у девушки —
письмо готовим. Ошибка в эту сторону стоит одного отказа сайта, в обратную —
молчания рассылки по причине, которой никто не увидит.
"""

# На сколько лет можно промахнуться мимо окна, прежде чем мы сочтём пару
# обречённой. ⚠ Число выверено сверкой журнала с живыми окнами (см. заголовок), а
# не выбрано из осторожности: при нуле мы потеряли бы семь разрешённых пар из
# ста сорока, при пяти пропустили бы треть обречённых.
MAIL_AGE_SLACK = 2


def mail_age_fits(girl: dict, person: dict, talked: bool = False) -> bool:
    """Возьмёт ли сайт холодное письмо этой пары. `False` — не возьмёт, не пишем.

    Args:
        girl: анкета-отправительница; возраст читается из её карточки
            (`profile.age`).
        person: запись человека из списка сайта: `age_from`, `age_to`.
        talked: он уже писал этой девушке. ⚠ Тогда **пишем всегда**: критерий
            возраста, судя по журналу, спрашивается только на холодном обращении,
            а молчать в начатом разговоре хуже отказа.

    Returns:
        bool: `True` — письмо имеет смысл. Незнание — тоже `True`.
    """
    if talked:
        return True

    age = _age(girl)
    if not age:
        return True

    return _miss(age, person) < MAIL_AGE_SLACK


def mail_age_nobody(girls: list, person: dict, talked: set = None) -> str:
    """Никому из наших анкет сайт писать этому человеку не даст. Пусто — даст.

    Args:
        girls: анкеты, которым есть чем писать — с шаблонами этого набора.
            Анкета без шаблона письмо не напишет, и её возраст покрытием
            быть не может.
        person: запись человека из списка сайта.
        talked: пары «анкета — адресат», где он писал первым: такая пара
            проходит всегда.

    Returns:
        str: причина для списка причин набора — пустая, если хоть одна анкета
        подходит.

    ## ⚠ Зачем отдельный вопрос, если отбор и так отсеет

    Отсев живёт в `mailing._pairs` и работает **парами**: не подошла эта
    девушка — письмо напишет другая, чей возраст в окно попадает. Человек
    выпадает лишь тогда, когда не подошла ни одна, — и вот об этом случае ему
    стоит сказать словами, иначе набор выглядит так, будто адресатов стало
    меньше без причины.

    ⚠ Называем **числа**, а не вывод: «не подходит по возрасту» читается как
    наша выдумка, а «он ищет 40–75, нашим анкетам 28–37» — как правило сайта,
    которым оно и является.
    """
    talked = talked or set()
    if any(mail_age_fits(girl, person,
                         (int(girl.get('id') or 0),
                          str(person.get('uid') or '')) in talked)
           for girl in girls or []):
        return ''

    low = int(person.get('age_from') or 0)
    high = int(person.get('age_to') or 0)
    ages = sorted({_age(girl) for girl in girls or [] if _age(girl)})

    return (f'сайт не даст написать: он ищет {low or "?"}–{high or "?"}, '
            f'а нашим анкетам '
            + (f'{ages[0]}–{ages[-1]}' if len(ages) > 1
               else (str(ages[0]) if ages else 'возраст неизвестен')))


# ── Приватное ────────────────────────────────────────────────────────────────

def _age(girl: dict) -> int:
    """Возраст девушки из её карточки. Ноль — не знаем.

    ⚠ Карточка — это `profile.profile`, снятая со страницы кабинета
    (`profile_page.py`), и у части анкет она пуста. Ноль здесь означает ровно
    «не знаем», и правило выше трактует его как «пишем».
    """
    try:
        return int((girl.get('profile') or {}).get('age') or 0)
    except (TypeError, ValueError):
        return 0


def _miss(age: int, person: dict) -> int:
    """На сколько лет возраст мимо окна. Ноль — внутри окна или окна нет."""
    try:
        low = int(person.get('age_from') or 0)
        high = int(person.get('age_to') or 0)
    except (TypeError, ValueError):
        return 0

    if low and age < low:
        return low - age

    if high and age > high:
        return age - high

    return 0
