async def _agent_id(site_id: int, pattern: str = MAIL_AGENT_NAME,
                    workflow: str = MAIL_AGENT_WORKFLOW) -> int:
    """Номер агента у соседа: находим или заводим.

    Args:
        pattern: шаблон имени — свой у каждого занятия. Агентов два, потому что у
            агента один workflow: заполнять переменные и писать письма одному
            нельзя.

    ⚠ **Заводим при первом обращении, а не заранее.** Сайтов у соседа десятки, и
    заводить агента каждому впрок значило бы плодить их ради тех, где рассылкой
    не занимаются вовсе.
    """
    slug = await agent_site(int(site_id))
    if not slug:
        raise DatingMailAgentError(
            f'у сайта #{site_id} нет метки для агента: имя сайта у соседа не '
            'сводится к латинице')

    name = pattern.format(site=slug)

    try:
        found = await rhapsody_api_agent_find(name)
        if found.get('id'):
            return int(found['id'])

        logger_info(f'[dating] завожу агента «{name}» ({workflow})')
        made = await rhapsody_api_agent_create(
            node=AGENT_NODE, workflow=workflow,
            name=name, title=f'Письма: {name}',
            variables={}, site=slug)
    except RhapsodyError as e:
        raise DatingMailAgentError(f'агент недоступен: {e}') from e

    agent_id = int(made.get('id') or 0)
    if not agent_id:
        raise DatingMailAgentError('сосед завёл агента, но не вернул его номер')

    return agent_id


def _card(profile: dict) -> str:
    """Сведения об анкете — текстом, по строке на поле.

    ⚠ **Текстом, а не JSON.** Промпт читает LLM, и подписи по-русски отвечают на
    вопрос «что это», а ключи `site_uid` и `login` — нет. Отсутствующие поля
    пропускаем: строка «Город: » учит модель, что пустое значение допустимо, и
    она начинает возвращать такие же.
    """
    card = profile.get('profile') if isinstance(profile.get('profile'), dict) else {}

    rows = [
        ('Имя', card.get('name')),
        ('Возраст', card.get('age')),
        ('Город', card.get('city')),
        ('О себе', str(card.get('about') or '')[:MAIL_AGENT_ABOUT_MAX]),
        # Логин — почта, и как имя он не годится; но иногда это единственное, что
        # есть, и по нему видно хотя бы написание.
        ('Логин', profile.get('login')),
    ]

    found = [f'{title}: {value}' for title, value in rows
             if str(value or '').strip() and str(value) != '0']

    return '\n'.join(found) if found else 'об анкете ничего не известно'


