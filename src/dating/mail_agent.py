def _letter(answer: str) -> str:
    """Текст письма из ответа агента.

    ⚠ **Снимаем размышления модели.** Рассуждающие LLM обрамляют их `<think>…`,
    и хвост вроде «exceeded, let\'s stop and write the final answer now.</think>»
    уехал бы живому человеку в начале письма. Поймано на первом же живом прогоне.

    Режем по **последнему** закрывающему тегу, а не по паре: открывающий тег
    модель часто теряет, и обрезка по паре оставила бы весь хвост на месте.

    ⚠ **Снимаем обрамление markdown.** Просить «только текст» надо, а полагаться
    на это нельзя: LLM оборачивает ответ в ``` при первой возможности.
    """
    text = str(answer or '').strip()

    close = text.rfind('</think>')
    if close >= 0:
        text = text[close + len('</think>'):].strip()

    text = re.sub(r'^```[a-z]*|```$', '', text, flags=re.MULTILINE).strip()

    return text[:MAIL_WRITE_MAX]


def _question(answer: str) -> str:
    """Вопрос из ответа агента: одна строка, без кавычек и размышлений.

    ⚠ **Берём первый абзац, а не весь ответ.** Модель охотно поясняет свой выбор
    («Вот вопрос: … Он опирается на его увлечения») — и пояснение уехало бы в
    письмо следом за вопросом. Абзац после первого письму не нужен: вопрос по
    условию один.

    ⚠ **Снимаем кавычки по краям.** Просили «только вопрос», а модель подаёт его
    репликой — в письме такие кавычки выглядят цитатой неизвестно кого.

    ⚠ **Не вопрос — возвращаем пусто, и письма не будет.** Поймано живым кругом:
    из ста писем одно ушло бы в пул с рассуждением модели вместо вопроса —

        «Given the description of the letter, I need to ask Matthias a question
        about his interests. Since we don't know much about his profile…»

    Первым абзацем оно и было, кавычек не имело, длину прошло. Отличает его от
    вопроса ровно одно, и это признак формальный: вопрос кончается знаком
    вопроса. Пустая переменная означает «письма не будет» — а это несравнимо
    лучше, чем письмо, в котором живой человек читает мысли робота о себе.
    """
    text = _letter(answer)
    if not text:
        return ''

    text = text.split('\n\n')[0].strip()

    # Кавычки всех видов, какими модель обрамляет реплику.
    while len(text) > 1 and text[0] in '"«\'“' and text[-1] in '"»\'”':
        text = text[1:-1].strip()

    # ⚠ **Знак проверяем до обрезки, а режем по знаку.** Иначе длинный вопрос
    # терял бы «?» вместе с хвостом и отбрасывался как рассуждение — тем самым
    # правилом, которое от рассуждений и защищает. Поймано тестом обрезки.
    if not text.rstrip().endswith(('?', '؟')):
        return ''

    if len(text) <= MAIL_QUESTION_MAX:
        return text

    # Режем по последнему вопросу, уместившемуся в предел: обрубок без знака в
    # письме читается как оборванная мысль, а не как вопрос.
    cut = text[:MAIL_QUESTION_MAX]
    at = max(cut.rfind('?'), cut.rfind('؟'))

    return cut[:at + 1] if at >= 0 else ''


async def _mail_avoid(site_id: int, girl: dict = None) -> list[str]:
    """Прошлые шаблоны — чтобы не повторяться.

    ⚠ **Свои, не чужие.** С 2026-10-16 шаблон принадлежит владелице, и адресат
    встречает дважды именно её текст. Карточка на входе — чей номер спрашивать;
    без неё (кнопка без открытой анкеты) как раньше: по всему сайту.

    ⚠ **Берём включённые и выключенные вместе.** Выключенный шаблон уже уходил
    людям: то, что мы его сняли, не отменяет прочитанного.

    ⚠ **Свежий десяток, а не весь список.** Круг пишет по три в сутки, и десяток
    перекрывает трое суток работы — ровно тот срок, за который человек может
    получить два письма и сравнить их.

    Сбой базы отвечает пустым списком: шаблон выйдет чуть более похожим на
    прошлые, и это несравнимо лучше, чем ни одного шаблона.
    """
    gid = int(girl['id']) if girl else 0
    try:
        async with mysql_get_db_async() as db:
            await db.execute(
                'SELECT body FROM mail WHERE site_id = %s AND body <> %s'
                ' AND (%s = 0 OR profile_id = %s)'
                ' GROUP BY body ORDER BY MAX(id) DESC LIMIT %s',
                (int(site_id), '', gid, gid, MAILING_AVOID_MAX))
            rows = await db.fetchall()
    except Exception as e:
        logger_info(f'[dating] прошлые шаблоны рассылки не спросились: {e}')

        return []

    return [str(row['body']) for row in rows or []]


def _avoid_text(avoid) -> str:
    """Список прошлых шаблонов строкой для промпта. Пусто — пустая строка.

    ⚠ **Пустую строку промпт прячет сам** (`[<if invite_avoid>]…[<endif>]` у соседа):
    заголовок «так уже было» без единой строки под ним модель читает как
    противоречие и начинает выдумывать, чего избегать.

    Нумеруем, а не маркируем: номер показывает, что это перечень примеров, а не
    один длинный текст с переносами.
    """
    rows = [str(one).strip() for one in (avoid or []) if str(one).strip()]

    return '\n'.join(f'{n}. {one}' for n, one in enumerate(rows, 1))


def _invites(answer: str,
             language: str = '') -> list[str]:
    """Шаблоны реплики из ответа агента: список, даже когда он один.

    ## ⚠⚠ Ответ бывает двух видов, и оба законны

    Просили один текст — приходит конверт с одним `TEXT:`. Просили несколько —
    тексты разделены строкой `---` (`INVITE_SPLIT`): так у соседа устроен шаг
    ответа, и разбирать JSON-массив здесь было бы третьим способом сказать
    «несколько» — после конверта и разделителя.

    ⚠ **Каждый текст проходит проверки поодиночке** (`_invite`): отказ модели,
    чужая метка, чужая письменность. Один брак не тянет за собой остальные —
    иначе одна неудачная реплика оставляла бы без инвайтов весь заход.

    ⚠ **Пустой список — законный исход.** Агент промолчал, судья забраковал всё:
    пул подождёт следующего захода, а половина брака хуже пустоты.
    """
    text, verdict, why = _envelope(_letter(answer))
    if not text:
        return []

    # ⚠ Вердикт судьи проверяем **до** разбора на куски: он про весь ответ
    # целиком, и делить забракованное незачем.
    if verdict and verdict not in INVITE_VERDICT_OK:
        logger_info(f'[dating] шаблоны инвайта забракованы судьёй ({verdict}): '
                    f'{why or "без объяснения"}')

        return []

    if verdict == 'fixed':
        logger_info(f'[dating] шаблоны инвайта исправлены по замечанию: {why}')

    # ⚠ `MULTILINE` обязателен: без него `^` и `$` значат начало и конец всего
    # текста, и разделитель посреди ответа не находится вовсе — на этом уже
    # спотыкались, получив три реплики, склеенные в одну.
    parts = [one.strip()
             for one in re.split(INVITE_SPLIT, text, flags=re.MULTILINE)
             if one.strip()]

    got = []
    for one in parts:
        # ⚠ Конверт уже снят, и вердикт проверен: каждому куску отдаём **голый**
        # текст, иначе `_invite` искал бы в нём второй конверт и не нашёл.
        ready = _invite(f'{INVITE_TEXT_MARK} {one}', language)
        if ready:
            got.append(ready)

    if parts and not got:
        logger_info('[dating] шаблоны инвайта не прошли проверку — пул подождёт')

    return got


def _invite(answer: str, language: str = '') -> str:
    """Шаблон реплики из ответа агента: один абзац, без кавычек, с нашими метками.

    ⚠ **Один абзац — требование, а не пожелание.** Реплика всплывает у человека в
    окне чата; текст в три абзаца там читается как вставленный из документа, а
    длинное сообщение от незнакомого не читают вовсе. Переносы поэтому не режем по
    первому абзацу, как у письма, а **сводим в пробел**: модель охотно разбивает
    две фразы на две строки, и терять вторую из-за этого незачем.

    Остальные правила — общие с письмом избранному, и живут они в
    `_template_check`: почему конверт судьи сильнее наших проверок, почему отказ
    модели ловится по началу строки и почему чужая метка отбрасывает шаблон
    целиком.
    """
    # ⚠⚠ `wanted` пустой, и это не упущение: **панель больше не знает, какие метки
    # просили** — жребий бросает сосед и наружу об этом не сообщает.
    #
    # Проверка та лишь писала в журнал («шаблон без метки — берём как есть») и
    # шаблон не отбрасывала. Спрашивать у соседа, что он выпал, ради строки в
    # журнале — плата вместо выигрыша: пропущенную метку и так видно по тому, что
    # подстановка ничего не заменила.
    #
    # ⚠ **Чужая метка по-прежнему отбрасывает шаблон целиком** — это внутри
    # `_template_check` и от `wanted` не зависит. Выдуманная `[[his_city]]` уехала
    # бы человеку прямо в скобках, и не одному, а всему пулу.
    return _template_check(answer, language, 'инвайта', wanted=(),
                           one_paragraph=True, limit=INVITE_MAX)


def _template_check(answer: str, language: str, what: str, wanted: tuple,
                    one_paragraph: bool, limit: int) -> str:
    """Общая проверка шаблона от агента: конверт, форма, метки, письменность.

    Args:
        answer: ответ агента целиком — с конвертом судьи или без него.
        language: код языка, который просили.
        what: чего это шаблон — словами, для журнала («инвайта», «письма
            избранному»). ⚠ Строка идёт только в журнал: по ней человек понимает,
            какой пул сейчас не набрался.
        wanted: пары `(просили ли метку, имя метки)`.
        one_paragraph: свести ли текст в одну строку. `False` — сохранить абзацы.
        limit: сколько знаков оставить.

    Returns:
        str: годный шаблон либо пустая строка. ⚠ Пустая — **не** исключение: пул
        подождёт следующего захода, а испорченный шаблон ушёл бы полусотне людей.

    ⚠ **Одна проверка на оба занятия.** Правила тут не про инвайт и не про письмо,
    а про то, «можно ли это разослать»: вердикт судьи, отказ модели, выдуманная
    метка, чужая письменность. Разъедься они по двум копиям — первая же добавка в
    одну из них молча не попала бы во вторую.

    ⚠ **Вердикт судьи сильнее всех проверок здесь**: он про смысл, они про форму.

    ⚠ **Чужих меток быть не должно.** `[[his_city]]`, которую модель выдумала,
    подставить нечем — она уехала бы живому человеку прямо в скобках. Шаблон с
    такой меткой отбрасываем целиком: следующий заход попросит новый, и это дешевле
    одного испорченного текста, помноженного на весь пул.

    ⚠ **Просили метку, а её нет — берём как есть.** Текст без имени остаётся годным;
    отказ стоил бы всего пула. Пропажу видно в журнале — станет правилом, чинить
    надо промпт.

    ⚠ **Отказ модели отбрасываем.** Он выглядит текстом («I can't help with…, but
    here's a neutral opener: …») и уехал бы всему пулу разом вместе с извинением.
    Ловим по началу строки: отказ модель ставит первым, а внутри текста «i cannot»
    — законные слова живого человека.

    ⚠ **Написание метки нормализуем.** Модель пишет `{companion_name}`,
    `%companion_name%`, `[[ companion_name ]]` — все три означают одно, и спорить об
    этом с ней в промпте дороже, чем привести к своему виду здесь.
    """
    text, verdict, why = _envelope(_letter(answer))
    if not text:
        return ''

    if verdict and verdict not in INVITE_VERDICT_OK:
        logger_info(f'[dating] шаблон {what} забракован судьёй ({verdict}): '
                    f'{why or "без объяснения"} — {text[:120]}')

        return ''

    if verdict == 'fixed':
        logger_info(f'[dating] шаблон {what} исправлен по замечанию: {why}')

    # Кавычки всех видов, какими модель обрамляет текст.
    text = text.strip()
    while len(text) > 1 and text[0] in '"«\'“' and text[-1] in '"»\'”':
        text = text[1:-1].strip()

    text = _slots_normal(text)
    if one_paragraph:
        # Один абзац: переносы и лишние пробелы — в один пробел.
        text = re.sub(r'\s+', ' ', text).strip()
    else:
        # Абзацы остаются, но пустых строк между ними ровно по одной, а хвосты
        # пробелов на концах строк уходят: сайт показывает письмо как есть.
        text = '\n\n'.join(
            ' '.join(block.split())
            for block in re.split(r'\n\s*\n', text) if block.strip()).strip()

    if not text:
        return ''

    low = text.lower()
    for mark in INVITE_REFUSAL_MARKS:
        if low.startswith(mark):
            logger_info(f'[dating] шаблон {what} отброшен: модель отказалась — '
                        f'{text[:120]}')

            return ''

    unknown = [one for one in MAIL_VAR_RE.findall(text)
               if one.strip() not in (INVITE_SLOT_GIRL, INVITE_SLOT_MAN)]
    if unknown:
        logger_info(f'[dating] шаблон {what} отброшен: чужая метка [[{unknown[0]}]]')

        return ''

    if _wrong_script(text, language):
        logger_info(f'[dating] шаблон {what} отброшен: кириллица при языке '
                    f'«{language}» — сайт такое не пропустит: {text[:120]}')

        return ''

    for want, slot in wanted:
        if want and f'[[{slot}]]' not in text:
            logger_info(f'[dating] шаблон {what} без метки [[{slot}]] — берём как есть')

    return text[:limit]

def _envelope(answer: str) -> tuple[str, str, str]:
    """Разбирает конверт судьи: `(текст, вердикт, замечание)`.

    ⚠ **Конверта может не быть, и это не отказ.** Так отвечает workflow без
    судьи — прежняя версия у соседа, стенд, чужая инсталляция. Тогда весь ответ и
    есть текст, а вердикт пуст: проверять его нечем, но наши проверки формы
    (метки, отказ, абзац) работают всё равно.

    ⚠ **Текст берём до конца ответа**, а не одной строкой: `TEXT:` стоит
    последним намеренно — реплика может оказаться с переносом, и обрежь мы её по
    строке, ушла бы половина. Переносы схлопнет вызывающий.
    """
    text = str(answer or '').strip()
    if INVITE_TEXT_MARK not in text:
        return text, '', ''

    head, _, body = text.partition(INVITE_TEXT_MARK)

    verdict, why = '', ''
    for line in head.splitlines():
        line = line.strip()
        if line.upper().startswith(INVITE_VERDICT_MARK):
            verdict = line[len(INVITE_VERDICT_MARK):].strip().strip('"\'').lower()
        elif line.upper().startswith(INVITE_WHY_MARK):
            why = line[len(INVITE_WHY_MARK):].strip()

    return body.strip(), verdict, why


def _wrong_script(text: str, language: str) -> bool:
    """Не та письменность: кириллица там, где сайт ждёт латиницу.

    ⚠ **Это про доставку, а не про вкус.** Русская реплика на англоязычном сайте
    не доходит вовсе — фильтр отклоняет её молча для нас и заметно для человека,
    которому она предназначалась.

    Язык не из списка латинских (`ru`, `uk`, `bg`) — не проверяем: там кириллица
    и есть ожидаемое.
    """
    if str(language or '').strip().lower()[:2] not in INVITE_LATIN_LANGUAGES:
        return False

    return any('\u0400' <= one <= '\u04ff' for one in str(text or ''))


def _slots_normal(text: str) -> str:
    """Приводит написание меток к своему виду: `[[girl_name]]`.

    Модель ставит скобки как привыкла — фигурные, проценты, пробелы внутри. Все
    они означают одно; спорить об этом в промпте дороже, чем привести здесь.
    """
    for slot in (INVITE_SLOT_GIRL, INVITE_SLOT_MAN):
        text = re.sub(r'(?:\{\{?|%|\[\[)\s*' + slot + r'\s*(?:\}\}?|%|\]\])',
                      f'[[{slot}]]', text, flags=re.IGNORECASE)

    return text


def _blank_json(wanted: list[dict]) -> str:
    """Заготовка ответа: JSON с настоящими ключами и пустыми значениями.

    ⚠ **Структуру ответа не должна придумывать модель.** Ключи — имена из реестра,
    и они известны точно; просить их переписать из списка значит поручать ей
    механическую работу, в которой она ошибается (`girl_city` → `city`).

    Пустые строки, а не примеры значений: пример подталкивает выдумать похожее, а
    задача — взять из анкеты или пропустить.
    """
    return json.dumps({row['name']: '' for row in wanted}, ensure_ascii=False)


def _wanted_text(wanted: list[dict]) -> str:
    """Список полей — по строке на поле: имя и подпись.

    Подпись здесь работает как задание: «girl_name — имя девушки» говорит модели,
    что искать, куда точнее голого имени.
    """
    rows = []
    for row in wanted:
        title = str(row.get('title') or '').strip()
        rows.append(f"{row['name']} — {title}" if title else str(row['name']))

    return '\n'.join(rows)


def _values(answer: str, wanted: set) -> dict[str, str]:
    """Вырезает JSON из ответа и оставляет только ожидаемое.

    ⚠ **Вырезает, а не разбирает целиком.** LLM любит обрамить ответ пояснением
    или ```json — просить «только JSON» надо, а полагаться на это нельзя. Тот же
    приём, что у `_json_str_clean` в движке соседа.

    ⚠ **Чужие имена молча отбрасываются.** Принять их значило бы завести
    переменную, которой нет ни в одном реестре: письмо на неё сослаться не может,
    а у анкеты она висела бы непонятной строкой.
    """
    chunk = _json_chunk(answer)
    if not chunk:
        logger_info(f'[dating] агент переменных ответил не JSON: {str(answer)[:200]}')

        return {}

    try:
        found = json.loads(chunk)
    except ValueError as e:
        logger_info(f'[dating] JSON агента не разобрался: {e}')

        return {}

    if not isinstance(found, dict):
        return {}

    values = {}
    for name, value in found.items():
        name = str(name).strip()
        if name not in wanted:
            continue

        # ⚠ Числа и `null` приводим к строке, а не отбрасываем: возраст приходит
        # числом законно. `null` при этом становится пустой строкой и отсеивается
        # ниже — как и просили промптом, «не знаешь — пропусти».
        text = '' if value is None else str(value).strip()
        if text:
            values[name] = text[:MAIL_AGENT_VALUE_MAX]

    return values


def _json_chunk(answer: str) -> str:
    """Первый объект `{…}` из текста. Нет такого — пустая строка.

    Ищем по первой `{` и последней `}`: вложенные объекты внутри значений тогда
    остаются целыми. Регулярка с ленивым поиском обрезала бы их по первой же
    закрывающей скобке.
    """
    text = str(answer or '')
    # Обрамление markdown снимаем до поиска: ```json ... ``` встречается чаще
    # всего остального.
    text = re.sub(r'^```(?:json)?|```$', '', text.strip(), flags=re.MULTILINE).strip()

    start, end = text.find('{'), text.rfind('}')

    return text[start:end + 1] if 0 <= start < end else ''
