async def invite_template(site_id: int, language: str = INVITE_LANGUAGE,
                          with_time: bool = True,
                                 girl_slot: bool = False, man_slot: bool = False,
                                 angle: str = '', length: str = '',
                                 avoid: list = None, country: str = '') -> str:
    """Сочиняет **шаблон** первой реплики в чат — один на весь пул инвайтов.

    Args:
        site_id: сайт-закладка: по нему заводится агент.
        language: код языка реплики. ⚠ **Передаётся всегда**, см. оговорку ниже.
        girl_slot: нужна ли в тексте метка имени девушки (`[[girl_name]]`).
        man_slot: нужна ли метка имени собеседника (`[[companion_name]]`).
        angle: приём — каким заходом писать (вопрос, вызов, признание…). Жребий
            бросает вызывающий (`invite.INVITE_ANGLES`).
        length: какой длины просить — от трёх слов до абзаца.
        avoid: что уже писали этому сайту; модель получает список со словами «так
            уже было».
        country: откуда девушки сайта — настройка `girl_country`. Пусто —
            агент про место молчит, и это законно.

    Returns:
        str: текст шаблона. Пустая строка — агент промолчал или прислал не то, и
        пул в этот заход не наберётся.

    Raises:
        DatingMailAgentError: агент не завёлся или не ответил.

    ⚠⚠ **Один вызов на пул, а не на человека.** Прежде реплику сочиняли каждой
    паре: пул в полсотни карточек стоил полусотни вызовов LLM и минут ожидания. С
    шаблоном вызов один, а карточки собирает подстановка — цена падает в
    `invite_pool_max` раз.

    Цена размена честная: **все реплики пула одинаковы** (с точностью до имён).
    Держится это тем, что каждый человек получает из пула ровно одну карточку
    (уникальность собеседников — `invite.py`), и одинаковый текст двум
    людям в глаза не бросается: они друг друга не видят.

    ⚠ **Кому и от кого — агент не знает.** Ни карточки девушки, ни карточки
    мужчины сюда не едет: шаблон общий, и «подстроиться под собеседника» ему не
    подо что. Это и делает вызов дешёвым — просить у модели персонализацию, а
    потом раздавать её пятидесяти разным людям, было бы обманом самих себя.

    ⚠ **Метки просим мы, а не модель решает.** Вероятности заданы снаружи (5% на
    имя девушки, 30% на имя мужчины), и «вставляй имя иногда» модель понимает как
    «вставляй всегда». Здесь она получает прямое указание: метка нужна или нет.

    ⚠⚠ **Тем же приёмом добывается и разнообразие.** Один и тот же промпт модель
    отвечает похоже: у неё сильные притяжения, и «будь разной» их не ломает —
    живой прогон дал три шаблона из трёх, начинавшихся с «you're trouble».
    Поэтому снаружи приходят **приём** и **длина** жребием, а `avoid` показывает,
    что уже писали. Модель не выбирает, насколько ей быть разной; ей говорят, чем
    быть на этот раз.

    ⚠ **Язык передаём явно, и это не мелочь.** Первый прогон прежней версии дал
    все реплики **по-русски** — мужчинам на англоязычном сайте, потому что правило
    было «пиши на языке его профиля», профиля у них нет, и модель ушла в язык
    промпта. Фильтр сайта такое отклоняет («Message not delivered. Unacceptable
    words: …», см. `answer.ANSWER_LANGUAGE`), то есть пул был бы
    пулом недоставляемых сообщений.
    """
    agent_id = await _agent_id(int(site_id), INVITE_NAME,
                               INVITE_WORKFLOW)

    answer = await _chat_ask(
        int(site_id),
        agent_id=agent_id,
        question='Напиши шаблон первой реплики в чат.',
        companion_id=MAIL_AGENT_COMPANION_ID,
        variables={'invite_slots': _slots(girl_slot, man_slot),
                   'invite_angle': str(angle or ''),
                   'invite_length': str(length or ''),
                   'invite_avoid': _avoid_text(avoid),
                   'invite_country': str(country or ''),
                   # ⚠⚠ **Часовой пояс панели, и та же переменная, что у чата.**
                   # Ею агент зовёт инструмент `datetime_current_get` и получает
                   # готовую фразу: день недели, дата, время и словесное время
                   # суток («вечер», «раннее утро»).
                   #
                   # Ради этого всё и заведено: в пуле прода лежал шаблон «My
                   # thoughts have turned sideways **tonight**» — модель писала
                   # про вечер, не зная, который час. Перепутанное время суток
                   # выдаёт робота вернее любой другой приметы: живой человек в
                   # этом не ошибается.
                   # ⚠⚠ **Флаг «показывать ли время» — жребий панели.** Дай
                   # модели время всегда — она поминает его почти в каждом
                   # инвайте: на живом пуле 94 из 202 за сутки. Это не её
                   # ошибка, а свойство: увидела сведение — сочла нужным.
                   #
                   # Пустая строка гасит секцию у соседа (`%if invite_time%`), и
                   # помянуть время модель не может — его в промпте нет.
                   'invite_time': '1' if with_time else '',
                   'datetime_current_get_zone': await _timezone(),
                   # Та же переменная, что у автоответа и писем (`user_language`
                   # у соседа): две переменные одного смысла разошлись бы.
                   'user_language': str(language or INVITE_LANGUAGE)})

    return _invite(answer, girl_slot, man_slot, str(language or INVITE_LANGUAGE))


async def favorite_mail_template(site_id: int, language: str = INVITE_LANGUAGE,
                                 man_slot: bool = False, angle: str = '',
                                 length: str = '', story: str = '',
                                 question: bool = False, avoid: list = None,
                                 country: str = '', with_time: bool = False) -> str:
    """Сочиняет **шаблон** письма тому, кто отвечал и замолчал, — один на пул.

    Args:
        site_id: сайт-закладка: по нему заводится агент.
        language: код языка письма. ⚠ Передаётся всегда, см. оговорку ниже.
        man_slot: нужна ли метка имени собеседника (`[[companion_name]]`).
        angle: приём — с чем письмо приходит. Жребий бросает вызывающий
            (`favorite_mail.FAVORITE_MAIL_ANGLES`).
        length: какой длины просить — от абзаца до трёх.
        story: о чём девушке рассказать про себя. Пусто — рассказа в этот раз
            нет, и промпт секцию прячет.
        question: кончается ли письмо вопросом к нему.
        avoid: что уже писали этому сайту; модель получает список со словами
            «так уже было».
        country: откуда девушки сайта — настройка `girl_country`.
        with_time: показывать ли модели текущее время. ⚠ Просим его только под
            рассказ: «как прошёл день» без часа выходит про несуществующий день.

    Returns:
        str: текст шаблона с метками. Пустая строка — агент промолчал или
        прислал не то, и пул в этот заход не наберётся.

    Raises:
        DatingMailAgentError: агент не завёлся или не ответил.

    ⚠⚠ **Один вызов на пул, а не на человека** — тот же размен, что у инвайтов
    (`invite_template`), и заведён он по той же причине: пул в полсотни писем
    стоил полусотни вызовов LLM и минут ожидания у нажатой кнопки.

    ⚠⚠ **Цена размена здесь выше, чем у инвайтов, и названа прямо.** Инвайт
    уходит незнакомому — терять нечего. Письмо уходит тому, кто **уже отвечал**:
    прежняя версия видела переписку пары и отталкивалась от неё, а шаблон общий и
    не видит ничего. Разговор возобновляется теперь не «с того места», а заново.

    Чем это держится: письмо не притворяется продолжением. Промпт прямо запрещает
    ссылаться на прошлые слова — то самое правило, что раньше включалось только на
    пустой истории. Живому человеку такое письмо читается как «вспомнила о тебе»,
    а не как ответ на реплику, которой он не помнит.

    ⚠ **Кому и от кого — агент не знает.** Ни карточки девушки, ни карточки
    мужчины сюда не едет: шаблон общий, и подстраиваться ему не подо что.

    ⚠ **Чем письмо отличается от инвайта.** Втрое больше текста (от абзаца до
    трёх), рассказ девушки о себе по жребию и вопрос **не всегда**. Всё три —
    доли, и бросает их панель: «иногда расскажи о себе» модель понимает как
    «всегда», ровно как понимала «вставляй имя изредка».

    ⚠ **Язык передаём явно.** Та же причина, что у инвайта: фильтр сайта
    отклоняет письмо не на том языке, и пул стал бы пулом недоставленного.
    """
    agent_id = await _agent_id(int(site_id), FAVORITE_MAIL_NAME,
                               FAVORITE_MAIL_WORKFLOW)

    answer = await _chat_ask(
        int(site_id),
        agent_id=agent_id,
        question='Напиши шаблон письма, возобновляющего разговор.',
        companion_id=MAIL_AGENT_COMPANION_ID,
        # ⚠ Имени девушки в письме не просим никогда — как и в инвайте. Он уже
        # знает, от кого письмо: имя стоит в шапке у сайта, и «меня зовут Diana»
        # в третьем письме читается как визитка бота.
        variables={'fav_slots': _slots(False, man_slot),
                   'fav_angle': str(angle or ''),
                   'fav_length': str(length or ''),
                   'fav_story': str(story or ''),
                   # ⚠ Пустая строка гасит секцию у соседа (`%if fav_question%`):
                   # «вопроса не нужно» промптом не говорят, его просто не просят.
                   'fav_question': '1' if question else '',
                   'fav_avoid': _avoid_text(avoid),
                   'fav_country': str(country or ''),
                   'fav_time': '1' if with_time else '',
                   'datetime_current_get_zone': await _timezone(),
                   # Та же переменная, что у ответа и инвайта: фильтр сайта
                   # отклоняет кириллицу, и русское письмо не дойдёт вовсе.
                   'user_language': str(language or INVITE_LANGUAGE)})

    return _favorite(answer, man_slot, str(language or INVITE_LANGUAGE))


async def mail_reply(profile: dict, site_id: int, history: list[dict],
                            companion: dict = None) -> str:
    """Пишет ответ на письмо мужчины.

    Args:
        profile: анкета девушки — от её имени отвечаем.
        site_id: сайт-закладка: по нему заводится агент.
        history: переписка, **старые сверху**: `{'from': 'him'|'her', 'text': …}`.
            Режет её вызывающий по настройке сайта `reply_history`.
        companion: карточка собеседника, если есть.

    Returns:
        str: текст ответа. Пустая строка — агент не ответил.

    Raises:
        DatingMailAgentError: агент не завёлся или не ответил.

    ⚠ **Здесь конкретика нужна, в отличие от шаблона.** `mail_write` нарочно
    не получает ни анкеты, ни собеседника: шаблон пишут для всех, и «Diana из Kyiv»
    делает его годным одной анкете из сорока. Ответ адресован одному человеку —
    имена, город и то, о чём он спросил, здесь не лишнее, а суть.

    ⚠ **История обязана быть непустой.** Отвечать не на что — значит и звать агента
    незачем: он сочинит письмо-знакомство, а его собеседник уже получал.
    """
    if not history:
        raise DatingMailAgentError('нечего отвечать: переписки нет')

    agent_id = await _agent_id(int(site_id), MAIL_REPLY_NAME,
                               MAIL_REPLY_WORKFLOW)
    language = await mail_agent_language(int(site_id))

    answer = await _chat_ask(
        int(site_id),
        agent_id=agent_id,
        question='Напиши ответ на последнее письмо.',
        companion_id=MAIL_AGENT_COMPANION_ID,
        # ⚠ Карточки собираются **теми же** `_card` и `_companion_card`, что у
        # вопроса получателю: подписи полей одни, и вторая пара разошлась бы с
        # первой — агент вопроса и агент ответа видели бы одного человека по-разному.
        variables={'mail_history': _history_text(history),
                   'girl_card': _card(profile),
                   'companion_card': _companion_card(companion or {}),
                   # ⚠ Язык — на каждом вызове: без него сосед возьмёт первый
                   # язык узла, а он свой у каждой установки (см. константу).
                   'user_language': language})

    return _letter(answer)[:MAIL_REPLY_MAX]


def _history_text(history: list[dict]) -> str:
    """Переписка одним куском: кто и что написал, старые сверху.

    ⚠ **Подписи «Он» и «Она», а не имена.** Имена уже стоят в карточках выше, и
    третий раз они только сбивают: модель начинает обращаться к себе по имени.
    Здесь важно одно — кто из двоих говорит.
    """
    rows = []
    for one in history:
        who = 'Он' if str((one or {}).get('from')) == 'him' else 'Она'
        text = str((one or {}).get('text') or '').strip()
        if text:
            rows.append(f'{who}: {text}')

    return '\n\n'.join(rows)


