async def mail_agent_fill(profile: dict, site_id: int,
                                 variables: list[dict]) -> dict[str, str]:
    """Спрашивает агента и отдаёт значения переменных.

    Args:
        profile: строка `profile` — из неё собираются сведения об анкете.
        site_id: сайт-закладка: по нему заводится агент и берётся его метка.
        variables: реестр сайта — записи `{name, title, source}`. Берутся только
            `profile`: значение `companion`-переменной зависит от адресата, и
            анкета о нём ничего не знает.

    Returns:
        dict: «имя → значение», только ожидаемые имена и только непустые значения.

    Raises:
        DatingMailAgentError: агент не завёлся или не ответил.

    ⚠ **Пустой ответ — законный исход**, а не сбой: агент мог не найти в анкете
    ничего из просимого. Пустой словарь об этом и говорит.
    """
    wanted = [row for row in (variables or []) if row.get('source', 'profile') == 'profile']
    if not wanted:
        return {}

    agent_id = await _agent_id(int(site_id))
    language = await mail_agent_language(int(site_id))

    answer = await _chat_ask(
        int(site_id),
        agent_id=agent_id,
        # ⚠ Вопрос короткий намеренно: вся работа задана промптом workflow, а сюда
        # уходит только повод его запустить. Длинный вопрос спорил бы с промптом
        # за внимание LLM.
        question='Заполни переменные писем по сведениям об анкете.',
        companion_id=MAIL_AGENT_COMPANION_ID,
        variables={'girl_card': _card(profile),
                   'mail_vars': _wanted_text(wanted),
                   # ⚠ **Заготовка ответа с настоящими ключами.** Прежде промпт
                   # давал пример с выдуманными именами и надеялся, что модель
                   # переложит на них имена из списка. Это лишняя работа для неё и
                   # лишний повод ошибиться: ключи известны нам точно, и собрать
                   # их — одна строка.
                   'mail_vars_json': _blank_json(wanted),
                   # Голые имена — для проверки заполненности у соседа
                   # (`dict_fields_check`). Отдельно от `mail_vars`: тот список
                   # читает модель, и подписи в нём к месту.
                   'mail_var_names': ','.join(row['name'] for row in wanted),
                   # ⚠ Язык — на каждом вызове: без него сосед возьмёт первый
                   # язык узла, а он свой у каждой установки (см. константу).
                   'user_language': language})

    return _values(answer, {row['name'] for row in wanted})


async def mail_write(site_id: int, variables: list[dict],
                            hint: str = '') -> dict:
    """Просит агента написать черновик шаблона письма.

    Args:
        site_id: сайт-закладка: по нему заводится агент и берётся реестр.
        variables: реестр сайта — все переменные, **включая `companion`** и
            `live`: в шаблоне нужны все, ими и подставится конкретика.
        hint: пожелание человека: о чём письмо, какой тон.

    ⚠ **Ни анкеты, ни собеседника на входе нет, и это не упущение.** Шаблон —
    заготовка для всех: одним текстом напишут разные девушки разным мужчинам.
    Сведения об участниках превратились бы в зашитую конкретику — так и было,
    агент возвращал «Diana here! I'm a choreographer living in Kyiv».

    Returns:
        dict: `body` — текст шаблона, `title` — название, которое придумал агент
        (пустое, если не придумал). Пустой `body` — агент не ответил.

    ⚠ **Название придумывает агент, а не вызывающий.** Имя должно говорить о самом
    тексте — «Short and direct», «Curious about his hobbies», — а знает текст только
    тот, кто его написал. Вызывающий получает готовую строку и может разве что взять
    из неё первые слова, то есть «Hi [[companion_name]], I came across…».

    Прежде имя собирали здесь, по дате и номеру: `Draft 2026-09-09 #1`. Три письма
    одного дня отличались только цифрой, и в списке их было не различить.

    Raises:
        DatingMailAgentError: агент не завёлся или не ответил.

    ⚠ **Это черновик, а не готовый шаблон.** Проверку он проходит на общих
    основаниях: сославшись на переменную, которой нет в реестре, агент получит
    отказ при сохранении — как и человек, написавший её руками.
    """
    agent_id = await _agent_id(int(site_id), MAIL_WRITE_NAME,
                              MAIL_WRITE_WORKFLOW)
    language = await mail_agent_language(int(site_id))

    # ⚠ **Отбор по занятию, и делается он здесь, а не у вызывающих.** Их двое —
    # кнопка «+ шаблон AI» и круг шаблонов, — и оба передают реестр целиком.
    # Фильтруй каждый сам, один однажды забыл бы, и агент вернул бы переменную,
    # которую из шаблонов как раз убирали.
    #
    # Живой случай: `companion_last_name` пуст у любого, чьё имя в одно слово (на
    # проде 44 из 99), а письмо с незаполненной переменной не уходит. Шаблон
    # поправили руками — и агент вернул бы её в следующий же черновик, потому что
    # получает **весь реестр как обязательный** (`mail_var_must` ниже).
    #
    # Ленивый импорт: `mail_var` импортирует этот модуль сверху, и обратная
    # ссылка на уровне модуля была бы циклом.
    from src.uvicorn.routers.dating.mail_var import mail_var_used

    known = [row for row in (variables or [])
             if mail_var_used(row, MAIL_VAR_USE_WRITE)]

    answer = await _chat_ask(
        int(site_id),
        agent_id=agent_id,
        question='Напиши шаблон письма.',
        companion_id=MAIL_AGENT_COMPANION_ID,
        # ⚠ **Карточек участников здесь нет, и это главное.** Прежде агенту
        # отдавали `girl_card` и `companion_card` — и он честно писал письмо
        # Дианы Джону: «Diana here! I'm a choreographer living in Kyiv». Такой
        # шаблон годен одной анкете из сорока, а рассылка берёт его для всех.
        #
        # Требовать «имена только переменной», отдав при этом сами имена, — это
        # борьба с данными, в которой данные побеждают. Нет данных — нечего
        # вписать.
        variables={'mail_vars': _wanted_text(known),
                   # ⚠ Голые имена через запятую — **отдельно** от `mail_vars`.
                   # Тот список читает модель, и подписи в нём к месту; этот
                   # сверяет регулярка у соседа (`text_regex_unknown`), и подпись
                   # она приняла бы за часть имени.
                   'mail_var_names': ','.join(row['name'] for row in known),
                   # ⚠ Обязательные — **все переменные реестра**, и решает это
                   # здесь, а не workflow. Шаблон, где половина имён написана
                   # словами, проходил все прежние проверки: лишнего в нём нет,
                   # язык верен, живой метки нет — а значит она и «не встроена».
                   # Полнота оказалась четвёртым вопросом, и задать его может
                   # только тот, кто знает, ради чего переменные заведены.
                   'mail_var_must': ','.join(row['name'] for row in known),
                   # Переменные, чьё значение — целая фраза. Они обязаны стоять
                   # отдельным абзацем: встроенная в текст, такая даёт
                   # «What are What do you enjoy??». Проверяет это
                   # `text_marks_inline` у соседа.
                   'mail_var_live': ','.join(row['name'] for row in known
                                             if row.get('source') == 'live'),
                   'mail_hint': str(hint or '').strip() or 'обычное первое письмо',
                   # ⚠ Язык — на каждом вызове: без него сосед возьмёт первый
                   # язык узла, а он свой у каждой установки (см. константу).
                   'user_language': language})

    return _letter_named(answer)


