# Сколько писем переписки показываем человеку в окне ответа.
#
# ⚠ Больше, чем отдаём агенту: тот читает, чтобы ответить, — ему хватает последних;
# человек читает, чтобы **проверить ответ**, и ему важно, о чём говорили раньше.
MAIL_REPLY_THREAD_SHOW = 30

# Сколько ответов пишем за один заход. Каждый — вызов LLM в несколько секунд; больше
# десятка означало бы заход на минуты, а круг вернётся и доберёт.
MAIL_REPLY_BATCH = 10


async def mail_reply_make(site_id: int, limit: int = 0) -> dict:
    """Пишет ответы на входящие письма сайта и кладёт их в пул.

    Args:
        site_id: сайт-закладка.
        limit: сколько ответов пробуем за заход. Ноль — предел по умолчанию.

    Returns:
        dict: `made` — сколько ответов готово, `skipped` — сколько писем пропущено,
        `reasons` — почему (первые несколько), `left` — сколько осталось на потом.

    ⚠ **Повторный заход продолжает с того же места**, а не делает то же самое:
    письма, на которые ответ уже лежит, пропускаются. Поэтому круг может будить
    набор хоть каждую минуту, не заваливая пул повторами.
    """
    letters = await _to_answer(site_id)
    if not letters:
        return {'made': 0, 'skipped': 0, 'reasons': [], 'left': 0}

    cap = min(int(limit) or MAIL_REPLY_BATCH, MAIL_REPLY_BATCH)
    language = await _language(site_id)
    agent_id = 0

    made, skipped, reasons, left = 0, 0, [], 0

    for letter in letters:
        if made + skipped >= cap:
            left += 1
            continue

        if not str(letter.get('body') or '').strip():
            # Тела ещё нет — отвечать не на что.
            skipped += 1
            _reason(reasons, 'у письма нет текста — тело ещё не забрали с сайта')
            continue

        profile = await _profile(int(letter['profile_id']))

        # ⚠ Агент спрашивается лениво и один на заход: это поход к соседу, и
        # заход, где не прошло ни одно письмо, не должен идти туда вовсе.
        if not agent_id:
            try:
                agent_id = await _agent(site_id)
            except DatingMailAgentError as e:
                logger_info(f'[dating] ответы сайта #{site_id} прерваны: {e}')
                _reason(reasons, str(e))
                break

        # ⚠⚠ Переписку сюда не передаём: обе истории — чат и письма — берёт сам
        # `answer_mail_reply`. Прежде круг собирал её своим запросом, знавшим про
        # три таблицы из четырёх и не знавшим про чат вовсе.
        #
        # ⚠ Его письмо едет **вопросом**: у соседа `mail_kind` стал внутренней
        # переменной, и ветку «ответ на письмо» он узнаёт по непустому
        # `prompt_user`. Без текста письма заход ушёл бы веткой письма
        # молчащему.
        body, error, message_id = await answer_mail_reply(
            agent_id, profile, str(letter['uid']), language,
            str(letter.get('name') or ''),
            letter=str(letter.get('body') or ''))

        if error:
            # ⚠ Отказ агента обрывает **весь заход**: сосед занят, и следующие
            # письма упрутся в то же самое. Круг вернётся через свой срок.
            logger_info(f'[dating] ответы сайта #{site_id} прерваны: {error}')
            _reason(reasons, str(error))
            break

        body = str(body or '').strip()
        if not body:
            skipped += 1
            _reason(reasons, 'агент ответил пусто')
            continue

        await _put(site_id, letter, body, message_id)
        made += 1

    if made or skipped:
        logger_info(f'[dating] ответы сайта #{site_id}: готово {made}, '
                    f'пропущено {skipped}, осталось {left}')

    return {'made': made, 'skipped': skipped, 'reasons': reasons, 'left': left}


async def mail_reply_thread(profile_id: int, uid: str, keep: int = 0,
                            with_favorite: bool = False) -> list[dict]:
    """Переписка с человеком — для показа человеку, а не агенту.

    Args:
        profile_id: наша анкета.
        uid: собеседник на сайте.
        keep: сколько последних писем. Ноль — предел показа.
        with_favorite: включать ли **ушедшие** письма-приставания. ⚠ По умолчанию
            нет — см. оговорку ниже.

    Returns:
        list: старые сверху,
        `{'id', 'from': 'him'|'her', 'kind', 'text', 'at', 'status'}`.

        ⚠ **Неотправленный ответ стоит последним**, а не по времени, когда его
        написали. Разговор — это то, что стороны сказали друг другу; черновик из
        пула никто не видел, и место ему в конце, где он и ждёт отправки.

        Поймано глазами: ответ, написанный в 15:28, встал между письмами 12:29 и
        20:32 — как будто девушка его отправила, а собеседник продолжил разговор,
        не заметив. У ушедших же реплик время **отправки**, а не сочинения:
        написать могли за час до того, как письмо ушло.

        `kind` — откуда реплика: `in` (его письмо), `reply` (наш ответ), `mailing`
        (письмо рассылки). Человеку это видно пометкой: письмо рассылки он писал
        не сам, и путать его с ответом не должен.

        ⚠⚠ **Письма «Приставания» — по просьбе (`with_favorite`), и только
        ушедшие.** Их сюда добавляли целиком и убрали целиком; оба раза вышло
        плохо, и правильный ответ посередине.

        На «Входящих» им не место: занятие отдельное, со своим пулом и своей
        подвкладкой, а рядом с ответом лежал бы чужой **черновик**, и форма под
        лентой правила бы ответ — два пула в одном месте читались как смешение,
        чем и были.

        Но на «Фаворитах → Диалоги» без них разговор оказывался **пустым**.
        Поймано на проде глазами: список диалогов считает пары по четырём
        источникам, включая приставания, а разговор собирался тремя — и пара, где
        ушло только приставание, попадала в список с пустой правой частью. У Дианы
        с Семёном письма были входящие, и разговор показывался; у Екатерины ушли
        одни приставания, и справа было пусто.

        ⚠ **Только `sent`.** Черновик человек не отправлял, собеседник его не
        видел, и место ему в пуле на подвкладке «Приставание» — ровно то
        соображение, по которому их отсюда и убирали.

        ⚠ Номер нужен, чтобы вызывающий мог исключить **текущий** ответ: он и так
        стоит ниже, в поле правки, и вторым разом тем же текстом только сбивал бы.
        Номера двух таблиц пересекаются, но вместе со стороной (`from`) пара
        однозначна.

    ⚠ **Отдельно от `_history`, хотя источник один.** Тому нужен голый текст: даты и
    состояния в промпте только сбивают модель. Здесь наоборот — человек читает
    переписку и первым делом смотрит, когда что было и ушёл ли наш ответ.

    Слей мы их в одну функцию с флагом, у флага не было бы имени, и следующий
    читатель гадал бы, зачем он.
    """
    # ⚠ Собираем строкой, а не склейкой литералов: кусок про приставания
    # прицепляется по условию, и «соседние строки склеятся сами» тут не работает.
    sql = (
        "SELECT 'him' AS side, 'in' AS kind, body, date_post AS at, id,"
        " '' AS status, 0 AS pending"
        ' FROM mail_in WHERE profile_id = %s AND uid = %s'
        ' UNION ALL'
        # ⚠ Время ответа — **отправки**, а не сочинения: между ними бывает час, и
        # по времени написания ответ вставал бы в разговор раньше, чем собеседник
        # его получил. Неотправленному времени нет вовсе; его выносит вниз
        # `pending`.
        " SELECT 'her' AS side, 'reply' AS kind, body,"
        ' COALESCE(sent_at, created_at) AS at, id, status,'
        " (status = 'draft') AS pending"
        ' FROM mail_reply WHERE profile_id = %s AND uid = %s'
        ' UNION ALL'
        # ⚠ **Письма рассылки — тоже часть разговора**: чаще всего именно ими он и
        # начат, и он отвечал на них, а не написал сам. Только отправленные:
        # лежащее в пуле он не видел.
        " SELECT 'her' AS side, 'mailing' AS kind, body, sent_at AS at, id,"
        ' status, 0 AS pending'
        " FROM mailing WHERE profile_id = %s AND uid = %s AND status = 'sent'")

    args = [int(profile_id), str(uid), int(profile_id), str(uid),
            int(profile_id), str(uid)]

    if with_favorite:
        sql += (' UNION ALL'
                " SELECT 'her' AS side, 'favorite' AS kind, body, sent_at AS at,"
                ' id, status, 0 AS pending'
                ' FROM favorite_mail'
                " WHERE profile_id = %s AND uid = %s AND status = 'sent'")
        args += [int(profile_id), str(uid)]

    # ⚠ `pending` первым и **по убыванию**: выборка идёт от новых к старым и
    # переворачивается ниже, так что ждущие отправки должны стоять в её конце —
    # только тогда после разворота они окажутся внизу разговора.
    #
    # Порядок сортировки тут легко перепутать, и ошибка выглядит безобидно:
    # черновик просто встаёт первой репликой, будто разговор им и начали. Поймано
    # глазами на живой переписке.
    sql += ' ORDER BY pending DESC, at DESC, id DESC LIMIT %s'
    args.append(int(keep) or MAIL_REPLY_THREAD_SHOW)

    async with mysql_get_db_async() as db:
        await db.execute(sql, tuple(args))
        rows = await db.fetchall()

    # Старые сверху — как читает человек. Обрезали же с конца: «последние N».
    # ⚠ **Лица — одни на всю нить, а не по реплике.** У письма своего фото нет:
    # оно у людей, а людей в разговоре двое. Класть его в каждую строку значило бы
    # тащить одну и ту же пару адресов по тридцать раз.
    #
    # Без этого лента рисовалась серыми кружками: разметка фото ждала, а ответ его
    # не отдавал вовсе — видно было только глазом, на живой переписке.
    faces = await _faces(int(profile_id), str(uid))

    return [{'id': int(row['id']), 'from': str(row['side']),
             'kind': str(row['kind']), 'text': str(row['body'] or ''),
             'at': row['at'], 'status': str(row['status'] or ''),
             'photo': faces['him' if str(row['side']) == 'him' else 'her']}
            for row in reversed(rows or [])]


def mail_reply_answer(row: dict, delay_per10: int = 0) -> dict:
    """Строка пула ответов в вид для страницы.

    Args:
        row: строка `mail_reply`, склеенная с анкетой и входящим письмом.
        delay_per10: коэффициент задержки сайта — секунд на десять слов
            (`reply_delay_per_10_words`). Ноль — задержки нет, и поле `ready_in`
            выйдет нулевым. Довод, а не чтение настройки внутри: вид строки
            собирается в цикле по пулу, и вопрос к базе на каждую карточку был
            бы платой за одно и то же число.

    Returns:
        dict: поля страницы — обе стороны, состояние, текст и то, на что отвечаем.

    ⚠⚠ **Один вид на три места**: пул «Ответов», окно правки и **оба** журнала
    доставки. Жил он приватной функцией роутера (`mail_in._reply_answer`), и сосед
    уже импортировал его оттуда через подчёркивание — то есть вид строки давно был
    общим, а лежал как чужая тайна.

    ⚠ Сторона девушки называется здесь `girl`/`girl_photo`, а не
    `profile_name`/`profile_photo`: так её читают «Входящие». Журналу доставки нужны
    вторые имена, и переименовывает он **у себя, на границе** — иначе сломались бы
    «Входящие».
    """
    card = json_column_load(row.get('profile_card'))

    # В сети ли адресат — **из снимка ленты, а не походом на сайт**. Тем же
    # `online_show`, что у пула рассылки и карточек собеседников: правило одно, и
    # вторая копия разошлась бы.
    online = online_show(int(row['site_id']), str(row['uid']))

    return {'id': int(row['id']),
            'site_id': int(row['site_id']),
            'profile_id': int(row['profile_id']),
            'mail_in_id': int(row['mail_in_id']),
            'online': bool(online.get('online')),
            'online_known': bool(online.get('known')),
            'photo': str(row.get('in_photo') or ''),
            'uid': str(row['uid']),
            'name': str(row['name']),
            'body': str(row['body']),
            'status': str(row['status']),
            'error': str(row['error'] or ''),
            'sent_at': row['sent_at'],
            # ⚠ Время **исхода**: у ушедшего ответа есть `sent_at`, у неудачного его
            # нет вовсе — отметку снимает сама неудача, — и остаётся `updated_at`.
            # Без него журнал доставки показывал время **сочинения** черновика, а
            # между ним и сорвавшейся отправкой бывают часы.
            #
            # ⚠ `.get`, а не ключом: этот же вид строки собирает пул «Ответов», а его
            # запрос столбца не спрашивает — там вопрос «что лежит», не «чем кончилось».
            'updated_at': row.get('updated_at'),
            'created_at': row['created_at'],
            # Имя анкеты, а не логин: логин это почта, и в карточке «от кого» она
            # читается как подпись робота. То же правило, что у пула рассылки.
            'girl': str((card or {}).get('name') or row.get('profile_login') or ''),
            # Лицо девушки — из её карточки: в переписке реплики подписаны лицами, а
            # не только именами.
            'girl_photo': str((card or {}).get('photo') or ''),
            # На что отвечаем — рядом: ответ читают, сверяя с письмом.
            'in_body': str(row.get('in_body') or ''),
            'in_at': row.get('in_at'),
            # ⚠⚠ **Сколько ещё ждать этому ответу, секундами.** Задержка по длине
            # текста (`reply_delay.py`) держит готовый ответ, пока не наберётся
            # время, которое человек потратил бы на эти слова, — и без числа на
            # карточке лежащий ответ читается как застрявший.
            #
            # ⚠ Отдаём **остаток**, а не время готовности: часы страницы и часы
            # сервера расходятся, и срок, посчитанный из абсолютной метки, у
            # одного человека шёл бы с минутой в запасе, у другого — с минутой
            # долга. Остаток тикает у страницы от мгновения загрузки.
            #
            # ⚠ Только у черновика без ошибки: ушедшему и неудачному ждать
            # нечего — их отправка больше не берёт.
            'ready_in': _ready_in(row, delay_per10),
            'in_message_id': int(row.get('in_message_id') or 0),
            # ⚠⚠ Номер обмена разговора у соседа (`companion_session`), а не
            # номер письма на сайте (тот — `in_message_id` выше). По нему
            # отправка отмечает у соседа доставку; запрос, который не выбрал
            # это поле, оставил бы отметку без номера молча — `.get`, потому
            # что не все запросы, собирающие этот вид, его спрашивают.
            'message_id': int(row.get('message_id') or 0)}


def mail_reply_delivery_scope(*, favorites: bool, profile_id: int = 0,
                              uid: str = '') -> tuple[str, str, list]:
    """Отбор ответов для журнала доставки: приклейка, условие и аргументы.

    Args:
        favorites: какую **половину** ответов брать. `True` — только пары, которые
            есть в избранных; `False` — только те, которых там нет.
        profile_id: сузить до одной анкеты. Ноль — все анкеты сайта.
        uid: сузить до одного собеседника. Пусто — все.

    Returns:
        tuple: (`JOIN`-часть, кусок `WHERE` после `r.site_id = %s`, аргументы к нему).

    ## ⚠⚠⚠ Довод обязательный, и «не фильтровать» из него убрано

    Два журнала доставки **делят** ответы, а не показывают каждый своё подмножество:
    «Фавориты» берут пары из звёздочек, «Письма» — все прочие. Вместе это все ответы
    ровно по одному разу.

    Прежде `False` означало «без отбора», и одна и та же строка честно попадала в оба
    журнала — это было решение («журнал, а не пул»), и человек его отменил: ответ
    избранному ищут на «Фаворитах», а видеть его вторым списком незачем.

    ⚠ Поэтому довод **без умолчания и только по имени**: половина, взятая молча по
    умолчанию, однажды снова склеила бы журналы. Забудь его вызывающий — падёт на
    вызове, а не в глазах человека.

    ⚠⚠ **Отбор отдаётся кусками, а не готовым запросом**, потому что зовущих два и
    каждому он нужен дважды: для счёта строк и для выборки страницы. Разойдись они —
    число страниц перестало бы отвечать содержимому.

    ⚠ Приклейка идёт **без оглядки на `favorite.state`**, как и список переписок с
    избранными (`favorite_mail_threads` идёт `FROM favorite`). Звезда со
    `state = 'fail'` — это «нажать не вышло», а не «человек не избранный»: убери мы
    такие пары, журнал разошёлся бы со списком разговоров на той же вкладке.

    ⚠⚠ Половины считаются **одним и тем же условием**, отличаясь только знаком:
    `JOIN` против `LEFT JOIN … IS NULL`. Напиши их порознь — и пара, попавшая между
    двумя разными правилами, пропала бы из обоих журналов совсем. А это хуже
    двойного показа: тогда письмо видно дважды, здесь — ни разу.

    ⚠ Пара в `favorite` одна на `(profile_id, uid)` — уникальным ключом, — поэтому
    приклейка строк не удваивает. Была бы не одна, счёт и выборка поехали бы вместе.
    """
    stars = ('  JOIN favorite fv'
             if favorites else '  LEFT JOIN favorite fv')
    join = f'{stars}    ON fv.profile_id = r.profile_id AND fv.uid = r.uid'
    # ⚠ Отбор именами — общей `pool_pick_where`, той же, что у писем и инвайтов:
    # шесть своих копий расходятся с первой правкой, и забытый `strip()` у номера
    # превращает «отобрать по Семёну» в «ничего не нашлось», молча.
    pick, args = pool_pick_where('r', profile_id, uid)
    where = pool_delivery_where('r') + ('' if favorites else ' AND fv.id IS NULL')

    return join, where + pick, args


async def mail_reply_delivery(db, site_id: int, take: int, *, favorites: bool,
                              profile_id: int = 0,
                              uid: str = '') -> list[dict]:
    """Ответы для журнала доставки — свежие сверху, готовыми строками страницы.

    Args:
        db: открытое соединение. ⚠ Своего не берём: журнал сливает две таблицы, и
            открой мы второе — счёт и строки пришли бы из разных мгновений.
        site_id: сайт-закладка.
        take: сколько свежих строк взять (см. приём слияния у зовущих).
        favorites: какую половину ответов брать — см. `mail_reply_delivery_scope`.
            ⚠ Обязателен и только по имени: журналы делят ответы, и половина,
            взятая молча, склеила бы их обратно.
        profile_id: сузить до одной анкеты.
        uid: сузить до одного собеседника — отбор именем в журнале.

    Returns:
        list: строки с `kind = 'reply'` и именами полей общей строки журнала.

    ⚠⚠ **Ответы приводим к общему виду здесь, на границе.** `mail_reply_answer`
    отвечает ещё и «Входящим», где сторону девушки читают как `girl`/`girl_photo`, а
    общая строка журнала доставки — как `profile_name`/`profile_photo`, теми же
    именами, что у пулов (`pool_pair_girl`). Без этой пары строк лицо девушки в
    журнале пропадало бы молча: имя есть, фото пусто.

    ⚠ `profile_uid` у ответов нет вовсе (номер анкеты на сайте лежит в её карточке, а
    запрос ответов её не читает) — пустая строка честнее нуля: `talkSide` без номера
    просто не покажет его.
    """
    join, where, args = mail_reply_delivery_scope(favorites=favorites,
                                                 profile_id=profile_id, uid=uid)

    await db.execute(
        'SELECT r.id, r.site_id, r.profile_id, r.mail_in_id, r.uid, r.name,'
        ' r.body, r.status, r.error, r.sent_at, r.created_at,'
        # ⚠ Время исхода у неудачного ответа: `sent_at` у него нет вовсе.
        ' r.updated_at,'
        ' p.login AS profile_login, p.profile AS profile_card,'
        ' i.body AS in_body, i.date_post AS in_at,'
        ' i.message_id AS in_message_id, i.photo AS in_photo'
        ' FROM mail_reply r'
        ' LEFT JOIN profile p ON p.id = r.profile_id'
        ' LEFT JOIN mail_in i ON i.id = r.mail_in_id'
        + join +
        ' WHERE r.site_id = %s' + where +
        # ⚠ По времени события, а не по номеру: журнал читают как ленту «что
        # происходило», и неудача, случившаяся позже удачи, обязана стоять выше.
        #
        # ⚠⚠ Тот же `COALESCE`, что у писем избранным и у показа (`_sentWhen`). Три
        # места, и порядок в них обязан совпадать: по этому же ключу зовущий **режет
        # страницу** из слитых списков, и разойдись они — срез взял бы строки не в том
        # порядке, в котором их считали.
        ' ORDER BY COALESCE(r.sent_at, r.updated_at, r.created_at) DESC, r.id DESC'
        ' LIMIT %s',
        tuple([int(site_id)] + args + [int(take)]))

    rows = []
    for row in (await db.fetchall()) or []:
        # ⚠ Один вызов на строку: внутри спрашивается снимок «в сети ли адресат», и
        # звать её трижды ради трёх полей значило бы платить за один ответ три раза.
        got = mail_reply_answer(row)
        rows.append({**got, 'kind': 'reply',
                     'profile_name': got['girl'],
                     'profile_photo': got['girl_photo'],
                     'profile_uid': ''})

    return rows


