"""Круг шаблонов: новые заготовки писем пишутся сами, по расписанию сайта.

Шаблон пишет агент (`mail_write`), а зовут его руками, кнопкой. Кнопку
нажимают, когда вспомнят, — и через неделю у сайта те же пять текстов, которыми он
писал в понедельник. Письма при этом уходят сотням людей, и один и тот же текст на
всех читается как рассылка робота, чем он и является.

Круг отвечает на это: несколько новых заготовок в сутки, сами собой, в те часы,
когда за ними присмотрят.

## ⚠ Новый шаблон приходит **включённым** — и почему это не опасно

`enabled = 1`, то есть рассылка возьмёт его сразу. Без этого цепочка не замыкается:
заготовка, ждущая, пока её включат руками, превращает «работает само» в «работает,
если каждый день зайти и щёлкнуть».

Опасным это было бы, если бы за набором пула шла отправка. Её **нет**: круга
отправки не существует вовсе, письма уходят по одному, кнопкой на карточке
(`mail_send.py`). То есть автоматически текст доходит только до пула — до
места, куда человек и приходит читать, что вышло.

Граница проходит там же, где и была: **необратимый шаг остаётся за человеком.**
Автоматически пишется текст, автоматически собираются письма — и всё это ждёт
нажатия. Появись однажды круг отправки, это решение надо будет пересмотреть первым.

⚠ Проверку шаблон при этом проходит на общих основаниях: сославшись на переменную,
которой нет в реестре, письмо по нему не соберётся — набор пула пропустит пару и
скажет, чего не хватило.

## Сколько и как часто

| Что | Чем задано | На какой вопрос отвечает |
|-----|------------|--------------------------|
| смены суток | `site_.template_schedule` | в какие часы вообще пишем |
| сколько в сутки | настройка `template_per_day` | сколько заготовок за день |

⚠ **Предел считается по суткам, а не по заходу.** «Три в сутки» — это про день, и
проверяется он запросом к базе: сколько шаблонов этого сайта заведено сегодня. Считай
мы в памяти, перезапуск смены держателя обнулял бы счёт, и за день выходило бы
столько, сколько раз его перезапускали.

⚠ Сутки — **местные**, по настройке `timezone`: человек, поставивший «три в сутки»,
имеет в виду свой день, а не гринвичский.

## Раз в сутки — сразу все

Пришло время смены — пишем столько заготовок, сколько задано настройкой, и на этом
день закончен. Не по одной в час: «три в сутки» человек читает как «утром будет три»,
а не «одна к обеду, вторая к ужину».

Повторный заход в тот же день ничего не делает — предел проверяется по базе. Но если
из трёх вышло две (сосед был занят), следующий заход **доберёт третью**: предел про
день, а не про заход.

## Старые заготовки уходят сами — **после** написания новых

По три в сутки — это девяносто за месяц, и список перестаёт читаться. Настройка
`template_keep` убирает то, что старше: по умолчанию — старше двух суток.

⚠ **Уборка идёт последней в заходе, и порядок здесь не вкусовой.** Убери мы первыми,
а написать не вышло — сосед занят, агент молчит, — и сайт остался бы с обрезанным
списком, ничего не получив взамен. Написав раньше, мы удаляем старое, **уже имея
новое**: это замена, а не освобождение места под неё.

Отсюда и следствие для счёта: свежие заготовки этого захода попадают в «запас», и
уборка убирает всё, что старше срока. Так и задумано — новые приходят на смену
старым. А если написать не удалось, запасом остаются вчерашние, и список всё равно
не пустеет (см. ниже).

⚠ **Убирает все, включая написанные руками.** Настройка так и называется, и делать
исключение для ручных значило бы завести два срока жизни там, где человек задал один.

⚠⚠ **Но список никогда не пустеет.** Самые свежие — дневную норму — уборка не трогает
даже старыми: смысл настройки в том, что тексты не застаиваются, а не в том, что
рассылке однажды нечем писать.

⚠ **Письма из пула это не трогает.** У `mailing.mail_id` внешний ключ с `ON
DELETE SET NULL`: готовое письмо помнит свой текст само, и удаление шаблона его не
уносит — только имя шаблона в карточке сменится на «шаблон удалён».
"""


from datetime_.datetime_ import datetime_offset_now
from logging_.logging_ import logger_info
from mysql_.mysql_ import mysql_get_db_async

from src.dating.json_column import json_column_load
from src.dating.round import (round_sites_run, round_slot_due,
                            round_slot_mark)
from src.dating.mail import MAIL_NAME_MAX
from src.dating.mail_agent import DatingMailAgentError, mail_write
from src.dating.schedule import schedule_now
from src.dating.site_setting import site_seconds

# Как часто круг просыпается. Минута — как у прочих кругов смены.
MAIL_ROUND_TICK_SEC = 60

# Через сколько круг вернётся к сайту. Час — это **сторож от повтора**, а не частота
# работы: за день он всё равно напишет не больше дневного предела.
#
# ⚠ Нужен потому, что заготовки пишутся минутами: без отметки следующий тик (через
# минуту) завёл бы вторую пачку поверх первой. Час же оставляет запас на «доберём
# позже», если сосед был занят.
MAIL_ROUND_EVERY_SEC = 3600

# Отметка «этому сайту только что писали». Живёт свой срок и гаснет сама.
MAIL_ROUND_KEY = 'dating:mail:round:{id}'

# Сколько заготовок в сутки, если настройки сайта нет.
MAIL_ROUND_PER_DAY = 3

# Настройка «сколько заготовок в сутки». Она же задаёт, сколько самых свежих
# шаблонов уборка не трогает: дневная норма — тот запас, ниже которого список
# опускаться не должен.
MAIL_ROUND_PER_DAY_SETTING = 'template_per_day'

# Настройка «удалять шаблоны старше N дней». Ноль — не удалять.
#
# ⚠ Умолчание — **двое суток** (в реестре сайта): при трёх заготовках в день это
# шесть текстов в списке, и все свежие. Смысл цепочки в том, что тексты не
# застаиваются: один и тот же на сотню людей читается как рассылка робота.
MAIL_ROUND_KEEP_SETTING = 'template_keep'

# Запасное имя заготовки — **на случай, если агент названия не придумал**.
#
# ⚠ Обычное имя приходит от него же (`title` в ответе workflow) и говорит о тексте:
# «Short and direct», «Curious about his hobbies». По дате и номеру имя не говорит
# ничего — три письма одного дня отличались бы только цифрой, и в списке их было не
# различить. Человек это и заметил.
#
# По-английски, как и сам текст: имя стоит в списке рядом с письмом англоязычному
# мужчине, и русское «Черновик» в этом ряду читается как чужая запись.
MAIL_ROUND_NAME = 'Draft {day} #{n}'


async def mail_round_run(offset_hours: int = 0) -> dict:
    """Один круг: написать заготовку тем сайтам, у кого идёт смена и вышел срок.

    Args:
        offset_hours: часовое смещение панели (настройка `timezone`). Расписание
            задано местным временем, а сервер живёт по UTC.

    Returns:
        dict: `checked` — сколько сайтов посмотрели, `made` — сколько заготовок
        написали, `gone` — сколько убрано старых.
    """
    sites = await _sites()
    made = gone = 0
    for _, counters in await round_sites_run(sites, offset_hours=offset_hours,
                                           gate=_gate, every=_every,
                                           work=lambda site, _m: _work(site, offset_hours),
                                           key=MAIL_ROUND_KEY, what='шаблонам'):
        if counters is not None:
            made += counters['made']
            gone += counters['gone']

    if made or gone:
        logger_info(f'[dating] круг шаблонов: написано {made}, убрано старых {gone}')

    return {'checked': len(sites), 'made': made, 'gone': gone}


async def _gate(site: dict, minutes: int) -> bool:
    """Смена идёт и шаблонный срок вышел.

    Смена идёт? Пустое расписание — это «нет», а не «всегда»: правило общее с
    расписанием анкеты и рассылки.
    """
    if not schedule_now(site['schedule'], minutes):
        return False

    return round_slot_due(MAIL_ROUND_KEY, int(site['site_id']), 'шаблонам')


async def _every(site_id: int) -> int:
    return MAIL_ROUND_EVERY_SEC


async def _work(site: dict, offset_hours: int) -> dict:
    """Пишет заготовку и убирает старые; порядок решает, чем кончится неудача.

    ⚠ **Сперва пишем, потом убираем.** Убери мы первыми — а написать не вышло
    (сосед занят, агент молчит), — и сайт остаётся с тем немногим, что
    уцелело от предохранителя, взамен ничего не получив. Один такой заход
    в сутки, и рассылке нечем писать. Написав раньше, мы удаляем старое,
    **уже имея новое**: замена, а не освобождение места под неё.
    """
    site_id = int(site['site_id'])

    return {'made': await _write(site_id, offset_hours),
            'gone': await _sweep(site_id)}
# ── Приватное ────────────────────────────────────────────────────────────────

async def _sites() -> list[dict]:
    """Сайты с включённым расписанием шаблонов и сами смены."""
    try:
        async with mysql_get_db_async() as db:
            await db.execute(
                'SELECT site_id, template_schedule FROM site'
                ' WHERE template_schedule_on = 1 AND is_gone = 0'
                ' ORDER BY site_id')
            rows = await db.fetchall()
    except Exception as e:
        logger_info(f'[dating] сайты для шаблонов не спросились: {e}')

        return []

    return [{'site_id': int(row['site_id']),
             'schedule': json_column_load(row['template_schedule'])}
            for row in rows or []]


async def _write(site_id: int, offset_hours: int) -> int:
    """Пишет дневную норму заготовок разом. Возвращает, сколько написалось.

    ⚠ **Заготовка ложится включённой** — иначе цепочка не замыкается: рассылка
    берёт только включённые шаблоны. Безопасно это потому, что круга отправки нет:
    текст доходит до пула, а из пула письма уходят по одному, кнопкой.

    ⚠ **Норма считается по суткам**, и потому повторный заход в тот же день ничего
    не делает, а неполный — добирает. Отказ соседа на второй заготовке не должен
    лишать день третьей.
    """
    from src.uvicorn.routers.dating.mail_var import mail_var_rows
    per_day = int(await site_seconds(site_id, MAIL_ROUND_PER_DAY_SETTING)
                  or MAIL_ROUND_PER_DAY)
    day = _today(offset_hours)
    already = await _made_today(site_id, day)

    if already >= per_day:
        return 0

    known = await mail_var_rows(site_id)
    made = 0

    for n in range(already, per_day):
        try:
            drafted = await mail_write(site_id, known)
        except DatingMailAgentError as e:
            # ⚠ Отказ агента обрывает **весь заход**, а не одну заготовку: сосед
            # занят, и следующие упрутся в то же самое. Недостающие доберём через
            # час — предел про день, а не про заход.
            logger_info(f'[dating] шаблоны сайта #{site_id} прерваны: {e}')
            break

        body = str((drafted or {}).get('body') or '').strip()
        if not body:
            logger_info(f'[dating] шаблон сайта #{site_id}: агент ответил пусто')
            break

        # ⚠ Имя придумывает агент — оно говорит о самом тексте («Short and direct»).
        # Не придумал — берём по дате: шаблон без имени в списке не найти вовсе.
        name = (str((drafted or {}).get('title') or '').strip()
                or MAIL_ROUND_NAME.format(day=day, n=n + 1))[:MAIL_NAME_MAX]

        async with mysql_get_db_async() as db:
            await db.execute(
                'INSERT INTO mail (site_id, name, body, enabled)'
                ' VALUES (%s, %s, %s, 1)', (int(site_id), name, body))
            await db.connection.commit()

        made += 1
        logger_info(f'[dating] шаблон сайта #{site_id} написан: «{name}» '
                    f'({n + 1} из {per_day} за сутки)')

    return made


async def _sweep(site_id: int) -> int:
    """Убирает шаблоны старше срока из настройки. Ноль в настройке — не трогаем.

    ⚠ **Убирает все, включая написанные руками.** Настройка так и называется
    («удалять шаблоны письма старше»), и делать исключение для ручных значило бы
    завести два срока жизни там, где человек задал один.

    ⚠⚠ **Но никогда не оставляет сайт без текстов.** Самые свежие — дневную норму
    (`template_per_day`) — не трогаем, даже если они старше срока.

    Это вторая линия, и нужна она **на случай неудачного захода**. В обычном заход
    новые уже написаны, и они же составляют запас: старое уходит, потому что есть
    чем его заменить. Но если агент промолчал, запасом оказываются вчерашние тексты
    — и список не пустеет, хотя по сроку должен был.

    Без этого предохранителя первое же включение расписания опустошало бы список: у
    живого сайта пять шаблонов, написанных на прошлой неделе, срок по умолчанию —
    двое суток. Смысл настройки в том, что тексты не застаиваются, а не в том, что
    рассылке однажды нечем писать.

    ⚠ **Готовые письма это не трогает**: у `mailing.mail_id` внешний ключ с
    `ON DELETE SET NULL`, и письмо помнит свой текст само. В карточке сменится
    только имя шаблона — на «шаблон удалён».
    """
    days = int(await site_seconds(site_id, MAIL_ROUND_KEEP_SETTING) or 0)
    if days <= 0:
        return 0

    keep = int(await site_seconds(site_id, MAIL_ROUND_PER_DAY_SETTING)
               or MAIL_ROUND_PER_DAY)

    async with mysql_get_db_async() as db:
        # Номера тех, кого бережём: самые свежие, числом в дневную норму. Отдельным
        # запросом, потому что MySQL не даёт вычитать из `DELETE` подзапрос по той
        # же таблице.
        await db.execute(
            'SELECT id FROM mail WHERE site_id = %s'
            ' ORDER BY created_at DESC, id DESC LIMIT %s', (int(site_id), keep))
        safe = [int(row['id']) for row in await db.fetchall() or []]

        sql = ('DELETE FROM mail WHERE site_id = %s'
               ' AND created_at < NOW() - INTERVAL %s DAY')
        args = [int(site_id), days]
        if safe:
            sql += ' AND id NOT IN (%s)' % ', '.join(['%s'] * len(safe))
            args.extend(safe)

        await db.execute(sql, tuple(args))
        gone = int(db.rowcount or 0)
        await db.connection.commit()

    if gone:
        logger_info(f'[dating] шаблоны сайта #{site_id}: убрано {gone} старше '
                    f'{days} дней (свежие {keep} оставлены)')

    return gone


async def _made_today(site_id: int, day: str) -> int:
    """Сколько заготовок этого сайта завели сегодня — по местным суткам.

    ⚠ **Считаем по базе, а не в памяти.** Смена держателя перезапускается (свой
    срок, деплой, падение), и счётчик в памяти обнулялся бы вместе с ней: за день
    выходило бы столько заготовок, сколько раз её перезапускали.

    ⚠ Считаются **все** шаблоны сайта, заведённые сегодня, а не только написанные
    кругом. Предел про то, сколько новых текстов появляется в сутки, а откуда они —
    вопрос второй: человек, написавший три руками, уже сделал дневную норму.
    """
    async with mysql_get_db_async() as db:
        await db.execute(
            'SELECT COUNT(*) AS n FROM mail'
            ' WHERE site_id = %s AND DATE(created_at) = %s', (int(site_id), day))
        row = await db.fetchone()

    return int((row or {}).get('n') or 0)


def _today(offset_hours: int) -> str:
    """Сегодняшняя дата по часам панели, `YYYY-MM-DD`.

    ⚠ **По часам панели, а не сервера.** Человек, поставивший «три в сутки», имеет
    в виду свой день; на границе полуночи UTC разница в сутки — не мелочь, а лишняя
    дневная норма.
    """
    return datetime_offset_now(int(offset_hours)).strftime('%Y-%m-%d')


