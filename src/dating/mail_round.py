# ⚠ Прежние имена несли владелицу ключом (`elena_template_1`) — и имя не различало
# трёх Елен на сайте, только сбивало: имена анкет повторяются, а номер анкеты
# человек с аватаркой сверяет глазами.
MAIL_ROUND_NAME_HEAD = 'template_'

# Настройка «время жизни шаблона в часах»; ноль — не удалять. Прежняя
# `template_keep` была в сутках и снята 20.10.2026 (см. начало файла) — ключ
# новый намеренно: старое значение `2` в старых настройках значило бы «двое
# суток», а прочитанное часами означало бы «два часа» и снесло бы списки молча.
MAIL_ROUND_KEEP_SETTING = 'template_keep_hours'

# Как часто чистить. ⚠ **Свой срок, а не срок захода**: `template_every` и смены
# отвечают за написание, а стареют строки круглые сутки. Десять минут: удаление
# стоит двух запросов, чаще — уже расточительство базы.
MAIL_ROUND_CLEAN_EVERY = 600
MAIL_ROUND_CLEAN_KEY = 'dating:mail:clean:{id}'


async def mail_round_run(offset_hours: int = 0) -> dict:
    """Один круг: написать заготовку тем сайтам, у кого идёт смена и вышел срок.

    Args:
        offset_hours: часовое смещение панели (настройка `timezone`). Расписание
            задано местным временем, а сервер живёт по UTC.

    Returns:
        dict: `checked` — сколько сайтов посмотрели, `made` — сколько заготовок
        написали.

    ⚠ Убранным здесь не считают: чистка по сроку живёт в `_gate`, вне счёта
    захода, и говорит о себе строкой в журнале.
    """
    sites = await _sites()
    made = 0
    for _, counters in await round_sites_run(sites, offset_hours=offset_hours,
                                           gate=_gate, every=_every,
                                           work=lambda site, _m: _work(site, offset_hours),
                                           key=MAIL_ROUND_KEY, what='шаблонам'):
        if counters is not None:
            made += counters['made']

    if made:
        logger_info(f'[dating] круг шаблонов: написано {made}')

    return {'checked': len(sites), 'made': made}


async def mail_round_state(site_id: int) -> dict:
    """Что круг шаблонов сделает дальше — словами для страницы.

    Args:
        site_id: сайт-закладка.

    Returns:
        dict: `on` — исполняется ли расписание, `shift` — идёт ли смена **сейчас**,
        `next_in` — секунд до следующего захода (`0` — возьмётся на ближайшем тике,
        `-1` — спросить не вышло), `made` и `norm` — сколько заготовок у сайта за
        сегодня и сколько положено, `per_day` и `girls` — множители нормы
        (на анкету и сколько включённых).

    ⚠⚠ **Отвечает сервер теми же выражениями, что решают за круг.** Та же
    `schedule_now` на смену, тот же `round_slot_left` на срок, тот же
    `round_day_count` на сутки. Своя арифметика на странице разошлась бы с кругом
    на первой правке — грабля, которая в этом проекте случалась дважды (причина
    пустого пула и значок потолка инициативы).

    ⚠ **Нужно потому, что ожидание круга невидимо.** После захода сайт ждёт час
    (`template_every`, по умолчанию час), и всё это время список выглядит как при
    поломке: пусто и молча. 20.10.2026 на этом ушёл разбор — заготовки удалили
    сразу после захода, и час до следующего читался как «круг сломался».
    """
    site_id = int(site_id)
    # ⚠ Пояс читаем **сами и тем же выражением**, что `round_offset_loop`: он и
    # есть то, чем круг меряет сутки и смены. Приди он доводом от ручки — у
    # страницы появился бы свой способ его узнать, и разойтись им ничто не мешает.
    offset_hours = datetime_offset_hours(
        await setting_get(ROUND_TIMEZONE_SETTING, '+0'))
    rows = await round_sites(flags=('template_schedule_on',),
                             schedule='template_schedule', what='шаблонам')
    mine = next((row for row in rows if int(row['site_id']) == site_id), None)

    # ⚠ Сайта нет в списке — это «расписание выключено», а не поломка: отбор тот
    # же самый, которым круг и берёт сайты в работу.
    if mine is None:
        return {'on': False, 'shift': False, 'next_in': -1,
                'made': 0, 'norm': 0, 'per_day': 0, 'girls': 0}

    now = datetime_offset_now(int(offset_hours))
    per_day = await _per_day(site_id)
    # ⚠ Спрашиваем **один раз**: ниже число нужно и множителем, и произведением.
    girls = len(await _profiles(site_id))

    return {
        'on': True,
        'shift': schedule_now(json_column_list(mine['schedule']),
                              now.hour * 60 + now.minute),
        'next_in': round_slot_left(MAIL_ROUND_KEY, site_id, 'шаблонам'),
        'made': await round_day_count('mail', {'site_id': site_id},
                                      date_column='created_at',
                                      offset_hours=int(offset_hours),
                                      unknown=-1, what='шаблонам'),
        # ⚠ Норма сайта — дневная норма анкеты, умноженная на число включённых:
        # круг обходит каждую своей рукой.
        #
        # ⚠⚠ Множители отдаются **рядом с произведением**, а не считаются
        # страницей: «57» без «3 × 19» не отвечает на вопрос «почему столько»,
        # а посчитай их страница сама — у неё появился бы свой способ узнать,
        # кого круг берёт в работу, и разойтись с `_profiles` ему ничто не
        # мешает (выключенная анкета в норму не идёт).
        'norm': per_day * girls,
        'per_day': per_day,
        'girls': girls,
    }


async def _gate(site: dict, minutes: int) -> bool:
    """Чистка сделана, смена идёт, шаблонный срок вышел.

    ⚠ **Уборка идёт до проверки смен, и это не оплошность** — тот же порядок,
    что у круга инвайтов: шаблоны стареют круглые сутки, а смены и `template_every`
    говорят только о том, когда писать. Чисти мы внутри захода, у сайта с ночным
    расписанием список зарастал бы старьём весь день.

    Смена идёт? Пустое расписание — это «нет», а не «всегда»: правило общее с
    расписанием анкеты и рассылки.
    """
    await _clean(int(site['site_id']))

    if not schedule_now(json_column_list(site['schedule']), minutes):
        return False

    return round_slot_due(MAIL_ROUND_KEY, int(site['site_id']), 'шаблонам')


async def _every(site_id: int) -> int:
    """Срок возврата к сайту — в секундах, как ждёт слой.

    ⚠ Настройка хранится **в минутах** (её читает человек), а слой меряет слот
    секундами: перевод здесь и только здесь.
    """
    minutes = int(await site_seconds(site_id, MAIL_ROUND_EVERY_SETTING)
                  or MAIL_ROUND_EVERY_MIN)

    return minutes * 60


async def _work(site: dict, offset_hours: int) -> dict:
    """Пишет дневную норму заготовок сайту.

    ⚠ Чистки по сроку здесь нет намеренно: она живёт в `_gate`, до проверки смен
    (`_clean`) — стареют строки и вне смены, а это дело — писать норму.
    """
    site_id = int(site['site_id'])

    return {'made': await _write(site_id, offset_hours)}
# ── Приватное ────────────────────────────────────────────────────────────────

async def _sites() -> list[dict]:
    """Сайты с включённым расписанием шаблонов и сами смены."""
    return await round_sites(flags=('template_schedule_on',),
                             schedule='template_schedule', what='шаблонам')


async def _per_day(site_id: int) -> int:
    """Дневная норма на анкету — настройка, с переходным умолчанием.

    ⚠ Одна дверь на три места: по ней круг пишет норму, по ней же страница
    расписания показывает произведение, и её же числом чистка бережёт запас
    (`_clean`). Своя копия в каждом разошлась бы на первой правке.
    """
    return int(await site_seconds(int(site_id), MAIL_ROUND_PER_DAY_SETTING)
               or MAIL_ROUND_PER_DAY)


async def _clean(site_id: int) -> int:
    """Убирает шаблоны, чьё время жизни истекло. Возвращает, сколько удалено.

    ⚠ **Убирает все, включая написанные руками.** Настройка так и называется —
    время жизни, и делать исключение для ручных значило бы завести два срока
    там, где человек задал один.

    ⚠⚠ **Но ни одна анкета не пустеет:** самые свежие каждой, числом в её
    дневную норму, не удаляются даже старыми. В обычном заход новые уже писал,
    и старое уходит, потому что есть чем заменить; но если агент молчал неделю,
    по сроку ушёл бы список целиком. Это про размер списка, а не про повторы:
    на «не повториться этому человеку» отвечает ключ `(profile_id, uid,
    mail_id)` таблицы `mailing`, он никуда не делся.

    ⚠ **Готовые письма это не трогает**: у `mailing.mail_id` внешний ключ
    `ON DELETE SET NULL`, письмо помнит свой текст само.

    ⚠ Свой слот, а не слот захода: чистка обязана идти и когда написание молчит
    (ночные смены, выключенное написание при включённой чистке — см. `_gate`).

    ⚠ Сбой чистки не роняет круг: писать норму важнее, чем размер списка.
    """
    if not round_slot_due(MAIL_ROUND_CLEAN_KEY, site_id, 'чистке шаблонов'):
        return 0

    try:
        hours = int(await site_seconds(int(site_id), MAIL_ROUND_KEEP_SETTING) or 0)
    except Exception as e:
        logger_info(f'[dating] срок жизни шаблонов сайта #{site_id} '
                    f'не прочитался: {e}')

        return 0

    # ⚠ Отметку ставим и при выключенной настройке: иначе её чтение повторялось
    # бы каждый тик, то есть шестьдесят раз за те же десять минут.
    round_slot_mark(MAIL_ROUND_CLEAN_KEY, site_id, MAIL_ROUND_CLEAN_EVERY,
                    'чистке шаблонов')
    if hours <= 0:
        return 0

    try:
        keep = await _per_day(site_id)

        async with mysql_get_db_async() as db:
            # Номера тех, кого бережём: самые свежие **каждой анкеты**, числом в
            # её дневную норму. Отдельным запросом, потому что MySQL не даёт
            # вычитать из `DELETE` подзапрос по той же таблице.
            #
            # ⚠⚠ Нормы у анкет общие, а запас — свой: один общий `LIMIT` на весь
            # сайт выбрал бы norm строк одной и оставил бы без запаса другую,
            # чьи тексты чуть старее. `PARTITION BY profile_id` считает каждой
            # свою норму.
            await db.execute(
                'SELECT id FROM ('
                ' SELECT id, ROW_NUMBER() OVER'
                '     (PARTITION BY profile_id ORDER BY created_at DESC, id DESC)'
                '     AS rn FROM mail'
                '     WHERE site_id = %s AND profile_id IS NOT NULL) t'
                ' WHERE rn <= %s', (int(site_id), keep))
            safe = [int(row['id']) for row in await db.fetchall() or []]

            # ⚠ У старых строк безхозяйных (`profile_id IS NULL`) своей нормы
            # нет — их окно пустое, и они уходят по сроку без запаса: беречь
            # общий текст прежних дней «как чью-то норму» значило бы вечно возить
            # в списке чужое.
            sql = ('DELETE FROM mail WHERE site_id = %s'
                   ' AND created_at < NOW() - INTERVAL %s HOUR')
            args = [int(site_id), hours]
            if safe:
                sql += ' AND id NOT IN (%s)' % ', '.join(['%s'] * len(safe))
                args.extend(safe)

            await db.execute(sql, tuple(args))
            gone = int(db.rowcount or 0)
            await db.connection.commit()
    except Exception as e:
        logger_info(f'[dating] чистка шаблонов сайта #{site_id} сорвалась: {e}')

        return 0

    if gone:
        logger_info(f'[dating] шаблоны сайта #{site_id}: убрано {gone} старше '
                    f'{hours} ч (свежие {keep} каждой оставлены)')

    return gone


async def _write(site_id: int, offset_hours: int) -> int:
    """Пишет дневную норму заготовок каждой включённой анкете. Сколько написалось.

    ⚠ **Норма — на анкету**, и считается по её строкам за сегодня: у кого норма
    есть, той круг не пишет вовсе. Считается по базе, а не в памяти: смена держателя
    перезапускается, и счётчик в памяти обнулялся бы вместе с ней.

    ⚠ **Имя не придумывают и не выводят из её имени — оно считает место в её
    норме**: `template_1`, `template_2`. Владелицу строки показывает аватарка в
    списке страницы, а не буква в имени: однофамилиц в именах не различить.
    Ответ агента — только текст: по нему не понять, чей текст, — и в имя он не
    просится вовсе.

    ⚠ **Норма считается по суткам**, и потому повторный заход в тот же день ничего
    не делает, а неполный — добирает: её строки за сегодня считаются вместе с
    написанными руками (человек, написавший три руками для анкеты, уже сделал её
    норму). Отказ соседа на второй заготовке не должен лишать день третьей.

    ⚠ **Заготовка ложится включённой** — иначе цепочка не замыкается: рассылка
    берёт только включённые шаблоны своей анкеты. Безопасно это потому, что круга
    отправки нет: текст доходит до пула, а из пула письма уходят по одному, кнопкой.
    """
    from src.uvicorn.routers.dating.mail_var import mail_var_rows
    per_day = await _per_day(site_id)
    girls = await _profiles(site_id)

    known = await mail_var_rows(site_id)
    made = 0

    for girl in girls:
        gid = int(girl['id'])
        already = await _made_today(site_id, gid, offset_hours)

        if already >= per_day:
            continue

        for n in range(already, per_day):
            try:
                drafted = await mail_write(site_id, known, girl=girl)
            except DatingMailAgentError as e:
                # ⚠ Отказ агента обрывает **весь заход**, а не одну заготовку:
                # сосед занят для всех одинаково, и следующие упрутся в то же
                # самое. Недостающие доберём через час — предел про день.
                logger_info(f'[dating] шаблоны сайта #{site_id} прерваны: {e}')

                return made

            body = (drafted or '').strip()
            if not body:
                logger_info(f'[dating] шаблон сайта #{site_id}: агент ответил пусто')
                break

            # Имя только считает место в норме: владелицу строки показывает
            # аватарка в списке, а имя с ключом лишь сбивало (три Елены — три
            # пары одинаковых `elena_` в одном списке).
            name = f'{MAIL_ROUND_NAME_HEAD}{n + 1}'

            # ⚠⚠ **Проверяем тем же `mail_check`, что и правка руками.** Круг
            # писал прямым `INSERT`, то есть мимо проверки, — и это стоило двум
            # анкетам всей рассылки: 20.10.2026 агент выдумал метку
            # `[[recipient_name]]` вместо `companion_name`, круг записал, а пул
            # по такому шаблону не собирается вовсе («не заполнено —
            # recipient_name»). Судья у соседа брак пропустил: у него предел
            # проб, и после него он отдаёт что есть.
            #
            # ⚠ Негодную заготовку **не сохраняем и не переписываем**: вторая
            # попытка стоит вызова LLM и упрётся в ту же склонность модели.
            # Недостающее доберёт следующий заход — предел про сутки.
            why = mail_check(name, body, {row['name'] for row in known})
            if why:
                logger_info(f'[dating] шаблон анкеты #{gid} забракован: {why}')
                break

            async with mysql_get_db_async() as db:
                await db.execute(
                    'INSERT INTO mail (site_id, profile_id, name, body, enabled)'
                    ' VALUES (%s, %s, %s, %s, 1)',
                    (int(site_id), gid, name, body))
                await db.connection.commit()

            made += 1
            logger_info(f'[dating] шаблон анкеты #{gid} написан: «{name}» '
                        f'({n + 1} из {per_day} за сутки)')

    return made


async def _profiles(site_id: int) -> list[dict]:
    """Включённые анкеты сайта: круг пишет заготовки каждой своей рукой.

    ⚠ **Только `enabled = 1`, без `status = 'online'`.** Снятая анкета пишет себе
    нечего, но и в сети она для этого быть обязана не обязана: круг пишет про запас,
    и тексты переживут её часы не в сети. Отбор «в сети» — у рассылки, когда письма
    уходят; здесь только «анкета жива».
    """
    async with mysql_get_db_async() as db:
        await db.execute(
            'SELECT id, profile_id, profile FROM profile'
            ' WHERE site_id = %s AND enabled = 1 ORDER BY id', (int(site_id),))
        rows = await db.fetchall() or []

    for row in rows:
        row['profile'] = json_column_load(row['profile'])

    return rows


async def _made_today(site_id: int, gid: int, offset_hours: int) -> int:
    """Сколько заготовок **этой анкеты** завели сегодня — по местным суткам.

    Правило общее — `round_day_count`: метка лежит в UTC, а сутки местные; без
    сдвига на пояс строки ночи (до полуночи UTC) остались бы вчерашним днём, и
    круг дописывал бы норму заново каждый час.

    ⚠ **Считаем по базе, а не в памяти.** Смена держателя перезапускается (свой
    срок, деплой, падение), и счётчик в памяти обнулялся бы вместе с ней: за день
    выходило бы столько заготовок, сколько раз её перезапускали.

    ⚠ Считаются **все** её шаблоны, заведённые сегодня, а не только написанные
    кругом. Предел про то, сколько новых текстов появляется в сутки у анкеты, а
    откуда они — вопрос второй: человек, написавший ей три руками, уже сделал её
    дневную норму.

    ⚠ Не сосчитали — молчим (потолок): недозаписанный круг допишет в следующий
    слот, а лишние тройки съели бы норму и место в пуле — ровно тот почасовой
    самозаписанный поток, что устроил починенный здесь сдвиг.
    """
    return await round_day_count('mail', {'site_id': int(site_id),
                                          'profile_id': int(gid)},
                                 date_column='created_at',
                                 offset_hours=offset_hours,
                                 unknown=10 ** 6, what='шаблонам')


