def mail_sent_union(where: str, select: str = 'sent_at',
                    tables: tuple = ()) -> str:
    """`UNION ALL` по пулам ушедшей почты — одним куском SQL.

    Args:
        where: условие отбора, общее всем веткам. Подставляется **в каждую**,
            поэтому `%s`-подстановок в итоге столько же раз больше — вызывающий
            повторяет их сам.
        select: что выбираем из каждой таблицы. По умолчанию время отправки —
            он нужен и счёту за сутки, и паузе.
        tables: какие пулы берём. Пусто — **все** (`MAIL_SEND_TABLES`), и это
            умолчание: «сколько писем мы ему отправили» почти всегда значит
            «сколько всего».

            ⚠ Довод заведён ради предела навязчивости: он меряется только
            холодными пулами (`MAIL_SEND_COLD_TABLES`), потому что ответ на его
            письмо навязчивостью не является. Список при этом остаётся **здесь**,
            рядом с отправкой, — своё перечисление у вызывающего и было той
            бедой, ради которой эта функция заведена.

    Returns:
        str: `SELECT … FROM mailing WHERE … UNION ALL SELECT … FROM mail_reply …`
        без внешних скобок: оборачивает вызывающий, ему же и давать псевдоним.

    ## ⚠⚠ Зачем это отдельной функцией

    Перечисление трёх таблиц жило **четырьмя** копиями: дневной предел получателя
    (`favorite_mail_person_soon`), пауза отправительницы (`favorite_mail`), дневной потолок сайта
    (`send_round._today`) и отбор затихших пар (`_quiet`). Списки совпадали, а
    записаны были порознь — то есть четвёртый пул писем добрался бы до трёх мест
    из четырёх, и молча: запрос не падает от того, что в нём на таблицу меньше,
    он просто отвечает неправду в меньшую сторону.

    Цена такой неправды известна: ровно из-за неё один человек получил четыре
    письма за одиннадцать минут при пределе в два.

    ## ⚠⚠ Доводы вызывающий обязан считать **длиной списка**, а не числом

    `where` подставляется **в каждую** ветку, то есть `%s`-мест в итоге во
    столько раз больше, сколько таблиц. Запиши вызывающий это числом — четвёртый
    пул ломает его запрос, и ломает **молча**: доводов меньше, чем мест,
    `execute` бросает, `except` вызывающего отвечает пустотой, и наружу это
    выходит не ошибкой, а «данных нет».

    Так и случилось 30.10.2026 с `mail_explain._last`: там стояло `* 3`, и
    с появлением `intention_mail` окно «почему этой паре не пишут» перестало
    называть последнего говорившего. Правильная запись —
    `* len(MAIL_SEND_TABLES)` либо `len(tables)` своего набора; сторож на это
    стоит в `tests/test_mail_send.py`.
    """
    return ' UNION ALL '.join(
        f'SELECT {select} FROM {table} WHERE {where}'
        for table in (tables or MAIL_SEND_TABLES))


