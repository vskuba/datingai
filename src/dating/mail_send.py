async def mail_send_one(letter: dict, profile: dict, base: str,
                               password: str,
                               table: str = 'mailing') -> dict:
    """Отправляет одно письмо из пула. Пишет исход в его строку.

    Args:
        letter: строка пула: нужны `id`, `uid`, `body`, `status`. У ответа — ещё
            `reply_to`: номер письма на сайте, на которое отвечаем.
        profile: анкета-отправитель (`profile_`): `id`, `login`, `password`,
            `password_source`.
        base: корень API сайта из настройки `api_base`.
        password: общий пароль анкет сайта (настройка `api_password`). Свой пароль
            анкеты сильнее — решает `password_source`.
        table: куда писать исход — `mailing` (рассылка) или
            `mail_reply` (ответы).

            ⚠ **Пулов три, а отправка одна.** Разговор с сайтом у них одинаков до
            последнего поля, и вторая копия разошлась бы с первой ровно там, где это
            дороже всего, — в `CheckId` и его десяти секундах. Различаются они лишь
            тем, куда лечь исходу, и `ReplyForMessageId` в теле.

    Returns:
        dict: `{'sent': True}` — ушло. Иначе `DatingMailSendError`.

    Raises:
        DatingMailSendError: письмо уже ушло, писать нечем, сайт отказал.

    ⚠ **Проверки — до похода на сайт.** Пустое тело и уже отправленное письмо видно
    здесь и сразу; узнавать о них от чужого сервера значило бы платить запросом за
    то, что и так известно.
    """
    letter_id = int(letter.get('id') or 0)
    uid = str(letter.get('uid') or '').strip()
    body = str(letter.get('body') or '').strip()
    # ⚠ Номер письма, на которое отвечаем, — **у ответов**; у писем рассылки его нет,
    # и поле в строке отсутствует вовсе. Одна функция шлёт и то и другое: разговор с
    # сайтом у них одинаков до последнего поля, и вторая копия разошлась бы с первой
    # ровно там, где это дороже всего, — в `CheckId` и его десяти секундах.
    reply_to = letter.get('reply_to')
    # ⚠⚠ Вложение приезжает **готовыми байтами**, а не номером файла на Диске.
    # Добыть их — это поход в сеть на секунды, а между `check-send` и `send`
    # нельзя делать ничего: `CheckId` живёт десять секунд. Готовит их
    # вызывающий, до того как сюда войти.
    attach = letter.get('attach')

    if str(letter.get('status') or '') != 'draft':
        raise DatingMailSendError('письмо уже ушло — второй раз не отправляем')

    if not uid:
        raise DatingMailSendError('у письма нет адресата')

    if not body:
        raise DatingMailSendError('письмо пустое — отправлять нечего')

    # ⚠ Вложение разбирается **до** похода на сайт, вместе с прочими проверками:
    # негодное видно здесь и сразу, и платить за это запросом незачем. Заодно
    # тяжёлая работа (base64 от двух мегабайт) уходит из промежутка между
    # разрешением и отправкой.
    _attach_parts(attach)

    # ── Развилка: панель или ручка сайта ────────────────────────────────────
    #
    # ⚠⚠ **Здесь, а не у вызывающих.** Отправку зовут двое — кнопка человека и круг
    # отправки, — и развилка у каждого разошлась бы: этой бедой уже обожглись на
    # `reply_to`, который кнопка передавала, а круг терял.
    #
    # ⚠ Спрашиваем **до** `check-send`: между разрешением и отправкой не делаем
    # ничего, `CheckId` живёт десять секунд.
    if str(table) == 'mail_reply':
        done = await _by_panel(letter, table, int(profile.get('id') or 0))
        if done is not None:
            return done

    if not str(base or '').strip():
        raise DatingMailSendError('у сайта не задан адрес API '
                                  '(настройка сайта «Адрес API сайта»)')

    # ⚠ Пароль выбираем **по настройке анкеты**, а не «свой, если задан»: у анкеты
    # есть явный `password_source`, и обойти его здесь значило бы отправить письмо
    # под паролем, которого человек для неё не выбирал.
    secret = password_pick(profile, password)

    try:
        # ── Шаг 1: можно ли писать этому человеку ───────────────────────────
        check = await site_api_call(
            profile, base, secret,
            MAIL_SEND_CHECK_PATH.format(uid=uid), method='GET',
            door=REQUEST_SEND)
    except DatingSiteApiError as e:
        # ⚠⚠ **Сперва временная причина, и только потом вечная.** «У него
        # переполнен ящик за этот час» — это 1392 отказа из 1463 на живом проде, и
        # до появления остуды каждый такой отказ хоронил письмо навсегда: причина
        # ложилась в `error`, а строки с причиной круг не берёт.
        left = mail_wait_mark(int(profile.get('site_id') or 0), uid, str(e))
        if left:
            raise DatingMailWaitError(mail_wait_words(str(e), left))

        # ⚠ Отказ приходит **и на этом шаге**: «можно ли писать этому человеку» —
        # ровно тот вопрос, на который сайт отвечает «он вас закрыл».
        await _deny_check(profile, letter, table, uid, str(e))

        raise DatingMailSendError(f'сайт не дал разрешения на отправку: {e}')

    check_id = str(check.get(MAIL_SEND_CHECK_FIELD) or '').strip()
    if not check_id:
        raise DatingMailSendError('сайт не вернул разрешения на отправку '
                                  f'({MAIL_SEND_CHECK_FIELD} пуст)')

    # ── Шаг 2: сама отправка ────────────────────────────────────────────────
    #
    # ⚠ Сразу за проверкой, без единого шага между: `CheckId` живёт десять секунд.
    try:
        answer = await site_api_call(
            profile, base, secret, MAIL_SEND_PATH,
            payload=_payload(check_id, uid, body, reply_to, attach),
            method='POST', door=REQUEST_SEND)
    except DatingSiteApiError as e:
        # ⚠ Та же развилка, что и у разрешения: ящик получателя мог переполниться
        # между двумя шагами — их разделяют доли секунды, но предел считает не
        # только нас. Правило одно на оба отказа.
        left = mail_wait_mark(int(profile.get('site_id') or 0), uid, str(e))
        if left:
            raise DatingMailWaitError(mail_wait_words(str(e), left))

        await _deny_check(profile, letter, table, uid, str(e))

        raise DatingMailSendError(f'сайт не принял письмо: {e}')

    # ⚠ Ответ сайта храним **как есть**, и у удачи тоже: «доставлено» — это наш
    # вывод из его слов, а не его слова. У инвайтов этот же разрыв уже стоил
    # времени: панель числила реплики ушедшими, а в чате у собеседника было пусто.
    said = json.dumps(answer, ensure_ascii=False)[:MAIL_SEND_ERROR_MAX]

    status = str(answer.get(MAIL_SEND_STATUS_FIELD) or '').strip()
    if status.upper() != MAIL_SEND_STATUS_OK:
        # ⚠ Код 200 с чужим `Status` — тоже неудача. Сайт вправе отвечать «принял
        # запрос, но не отправил», и считать это успехом значило бы объявить
        # ушедшим письмо, которого адресат не увидит.
        await mail_send_mark(letter, sent=False, table=table, answer=said,
                                    error='')

        raise DatingMailSendError(
            f'сайт ответил не «{MAIL_SEND_STATUS_OK}»: {status or "пусто"}')

    await mail_send_mark(letter, sent=True, table=table, answer=said)
    logger_info(f'[dating] письмо #{letter_id} ушло: анкета #{profile.get("id")} → {uid}')

    return {'sent': True}


async def mail_send_fail(letter: dict, error, table: str = 'mailing') -> None:
    """Исход неудачной отправки — одной дверью на все пять дорог.

    Args:
        letter: строка письма целиком (как у `mail_send_mark`).
        error: **само исключение**, а не его текст: по роду ошибки и решается,
            портить ли письмо причиной. Строку тоже принимаем — тогда это
            обычная неудача.
        table: чей пул — `mailing`, `mail_reply` или `favorite_mail`.

    ## ⚠⚠ Зачем отдельной функцией

    `except DatingMailSendError: mail_send_mark(sent=False, error=str(e))` стояло
    **четырьмя копиями** — в круге отправки и у трёх кнопок. Пока правило было
    одно («не ушло — пиши причину»), копии не расходились. С остудой правил стало
    два, и четвёртая забытая копия означала бы ровно ту беду, от которой остуда и
    заведена: письмо, похороненное временной причиной.

    ⚠ **Молчание здесь — это решение, а не пропуск.** Временная причина не ложится
    в `error` намеренно: там она запрещает кругу вернуться к письму
    (`send_round._oldest`). Человеку же она видна — её несёт текст исключения в
    ответе кнопки и в журнале анкеты.
    """
    if isinstance(error, DatingMailWaitError):
        # ⚠ Уровень `info`, а не `fail`: ничего не сломалось, письмо ждёт своего
        # часа. И только из этих пяти значений — `log.level` их перечисляет
        # `ENUM`-ом, а чужое он молча не запишет вовсе.
        await log_write(
            int(letter.get('profile_id') or 0), 'info',
            f'{str(letter.get("name") or letter.get("uid") or "")}: {error}')

        return

    await mail_send_mark(letter, sent=False, error=str(error), table=table)


async def mail_send_mark(letter: dict, sent: bool, error: str = '',
                                table: str = 'mailing',
                                final: bool = False, answer: str = '') -> None:
    """Записывает исход отправки: в строку письма и в журнал анкеты.

    Args:
        letter: строка письма целиком — нужны `id`, `profile_id`, `uid`, `name`.
        sent: ушло или нет.
        error: причина, если не ушло.
        table: куда писать — `mailing`, `mail_reply` или
            `favorite_mail`.

    ⚠ **Оба места — здесь, а не по разным.** Исход отправки записывается дважды:
    в само письмо (его читает страница) и в журнал анкеты (его читают, разбираясь,
    что вообще происходило). Разведи мы их — одна половина однажды осталась бы без
    другой, и «Доставка» показывала бы то, чего в журнале нет.

    ⚠ **Письмо принимаем целиком, а не одним номером.** Журналу нужны анкета и
    адресат, и добирать их вторым запросом значило бы платить походом в базу за то,
    что у вызывающего уже в руках.

    ⚠ **Неудача оставляет письмо в пуле** (`draft`), а причину кладёт в `error`.
    `failed` его бы похоронил: уникальный ключ `uq_mailing_once` считает и
    неудавшиеся, и второй раз такое письмо уже не сгенерировать. Причина же обычно
    временная — сайт просит подождать, протух пароль, — и повтор после неё законен.

    ⚠ **`final` — ровно тот случай, когда хоронить правильно.** Сайт ответил «он
    вас закрыл»: второго письма этой паре не будет никогда, и ключ, который его не
    даст сгенерировать, здесь не помеха, а то же самое решение.

    ⚠ **И только так попытку видно в «Доставке».** Запрет выметает черновики пары
    из пулов (`block.py`); останься письмо `draft`, его снесло бы следом — и
    отказ исчез бы бесследно, как будто отправки не было.
    """
    letter_id = int(letter.get('id') or 0)
    addressee = str(letter.get('name') or '').strip() or str(letter.get('uid') or '')

    # ⚠ Имя таблицы подставляем **из белого списка**, а не из строки вызывающего:
    # в SQL оно не параметризуется, и любое другое было бы дырой. Здесь их ровно
    # три, и все наши.
    if str(table) not in MAIL_SEND_TABLES:
        raise DatingMailSendError(f'неизвестный пул писем: {table}')

    # ⚠ Ответ сайта пишем, только когда он есть: пустая строка затёрла бы то, что
    # записала сама отправка, — исход отмечают дважды (здесь и у вызывающего).
    said = str(answer or '')[:MAIL_SEND_ERROR_MAX]
    tail = ', answer = %s' if said else ''

    if sent:
        sql = (f"UPDATE {table} SET status = 'sent', sent_at = NOW(), error = ''"
               f'{tail} WHERE id = %s')
        args = ((said, letter_id) if said else (letter_id,))
    elif final:
        sql = f"UPDATE {table} SET status = 'failed', error = %s{tail} WHERE id = %s"
        args = ((str(error or '')[:MAIL_SEND_ERROR_MAX], said, letter_id)
                if said else (str(error or '')[:MAIL_SEND_ERROR_MAX], letter_id))
    else:
        sql = f'UPDATE {table} SET error = %s{tail} WHERE id = %s'
        args = ((str(error or '')[:MAIL_SEND_ERROR_MAX], said, letter_id)
                if said else (str(error or '')[:MAIL_SEND_ERROR_MAX], letter_id))

    async with mysql_get_db_async() as db:
        await db.execute(sql, args)
        await db.connection.commit()

    # ⚠ Журнал — **после** записи в письмо, а не до: строка «письмо ушло» при
    # неудавшемся `UPDATE` была бы ложью, а обратный порядок такой лжи не даёт.
    # Сам `log_write` не бросает: сбой журнала не должен ронять отправку,
    # которая уже случилась.
    await log_write(
        int(letter.get('profile_id') or 0),
        'ok' if sent else 'fail',
        f'письмо ушло: {addressee}' if sent
        else f'письмо не ушло: {addressee} — {str(error or "причина неизвестна")}')

    # ⚠⚠ **Доставка отмечается здесь, а не в круге отправки.** Через эту точку
    # проходят обе дороги письма — круг и путь через панель
    # (`mail_reply_panel.py`), — и она уже знает таблицу доводом `table`. Две
    # точки вместо одной разошлись бы ровно так же, как разошлись бы записи
    # исхода, которые тут и сведены в одно место.
    #
    # ⚠ Отметка **после** записи исхода: сосед может не ответить, а исход письма
    # обязан лечь в любом случае.
    if sent and table in MAIL_SEND_TALK_TABLES:
        said = int(letter.get('message_id') or 0)
        await rhapsody_api_chat_delivered(said)
        # ⚠⚠ Письмо дошло — обещание из него становится настоящим. У писем
        # между сочинением и отправкой проходят часы, и всё это время
        # намерение законно ждёт (`chat_intention.py`).
        await chat_intention_delivered(said)

    # ⚠⚠ **Отметки исполнения — тоже здесь, и по той же причине.** Ушедшее
    # письмо-исполнение обязано запомнить снимок (`companion_gallery_file`) и
    # закрыть обещание (`chat_intention`); поставь мы это у вызывающего, дороги
    # разошлись бы — кнопка человека отмечала бы, а круг забывал, и один и тот
    # же снимок ушёл бы второй раз по следующему обещанию.
    #
    # ⚠ Импорт отложенный: отправка — общая дверь, и знать про исполнение
    # намерений на самом импорте ей незачем. Круга сегодня нет (`intention_do`
    # отправку не зовёт), но появится он с первой же надобностью взять отсюда
    # предел вложения — а искать тогда будут не здесь.
    # ⚠⚠ **Память о показанном снимке — общая для всех пулов.** Кадр ушёл
    # человеку, и второй раз слать его нельзя, кем бы он ни был выбран: по
    # обещанию агента или жребием (`mail_shot.py`). Своя отметка у каждого
    # пула означала бы, что один и тот же снимок уйдёт дважды — сперва ответом,
    # потом обещанием.
    #
    # ⚠ Ставится **после** отправки, а не при выборе: первая же неудача иначе
    # сожгла бы кадр, и повторная попытка взяла бы другой.
    if sent and int(letter.get('gallery_file_id') or 0):
        from src.dating.companion_gallery import companion_gallery_sent

        try:
            await companion_gallery_sent(int(letter.get('profile_id') or 0),
                                         int(letter.get('site_id') or 0),
                                         str(letter.get('uid') or ''),
                                         int(letter['gallery_file_id']))
        except Exception as e:
            # ⚠ Письмо **уже ушло**: исключение отсюда заставило бы вызывающего
            # считать отправку несостоявшейся. Молча, впрочем, не проходит.
            logger_info(f"[dating] {table} #{letter.get('id')} ушло, а снимок "
                        f'не отметился показанным: {e}')

    if sent and table == 'intention_mail':
        from src.dating.intention_do import intention_mail_done

        await intention_mail_done(letter)


