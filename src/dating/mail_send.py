async def _by_panel(letter: dict, table: str, profile_id: int):
    """Отправка ответа **через панель**, если так решено для этой пары.

    Args:
        letter: строка пула ответов. Нужен `reply_to` — номер письма в панели.
        table: куда лечь исходу; здесь всегда `mail_reply`.
        profile_id: анкета-отправительница.

    Returns:
        `{'sent': True}` — ушло панелью. `None` — панельный путь не наш случай либо
        не вышел, и решать дальше обычной ручке.

    ## ⚠⚠ Почему `None`, а не исключение

    «Панель не наш случай» и «панель не смогла, но можно ручкой» — это не отказ
    отправки, а выбор пути. Брось мы исключение, вызывающий обязан был бы его
    ловить и разбирать причину словами — то есть повторять здешнее решение.

    ⚠ А вот **окончательный** отказ (панель не смогла, и досылать запрещено) —
    именно исключение: письмо не ушло, и сказать об этом надо тем же способом, каким
    об этом говорит обычный путь.
    """
    from src.dating.mail_reply_panel import (DatingPanelReplyError,
                                             mail_reply_panel_due,
                                             mail_reply_panel_fallback,
                                             mail_reply_panel_send)

    site_id = int(letter.get('site_id') or 0)
    uid = str(letter.get('uid') or '').strip()

    if not await mail_reply_panel_due(site_id, profile_id, uid):
        return None

    try:
        done = await mail_reply_panel_send(site_id,
                                          int(letter.get('reply_to') or 0),
                                          str(letter.get('body') or ''))
    except DatingPanelReplyError as e:
        if await mail_reply_panel_fallback(site_id):
            # ⚠ Причину не теряем: она уйдёт в журнал анкеты, даже если письмо
            # следом уйдёт ручкой. Иначе «панель включена, а письма идут ручкой»
            # выглядело бы как неработающая настройка.
            logger_info(f'[dating] ответ #{letter.get("id")} панелью не ушёл '
                        f'({e}) — досылаем ручкой API')

            return None

        await mail_send_mark(letter, sent=False, error=str(e), table=table)

        raise DatingMailSendError(f'панель не приняла ответ: {e}')

    await mail_send_mark(letter, sent=True, table=table,
                         answer=str(done.get('answer') or ''))

    return {'sent': True}


async def _deny_check(profile: dict, letter: dict, table: str, uid: str,
                      said: str) -> None:
    """Не значит ли отказ сайта «он закрылся от этой девушки».

    ⚠ **Внутри отправки, а не у пяти вызывающих.** Письмо шлют кнопка рассылки,
    кнопка ответа, кнопка избранных и два круга — и каждый читает отказ по-своему.
    Расставь проверку по ним, первый забытый продолжал бы писать закрывшемуся.

    ⚠ **Разбор — общий с чатом** (`block_deny`): закрылся человек от
    девушки, а не от способа доставки, и два перечня примет разошлись бы.

    Молчит при любой беде: это подсказка поверх отправки, и уронить ею письмо,
    которое сайт отказался принять по другой причине, было бы хуже отказа.
    """
    from src.dating.block import block_add, block_deny

    site_id = int(profile.get('site_id') or 0)
    profile_id = int(profile.get('id') or 0)
    if not site_id or not profile_id:
        return

    try:
        channel = await block_deny(site_id, said)
        if not channel:
            return

        # ⚠ Сперва хороним это письмо, потом заносим запрет: тот выметает из пулов
        # **черновики**, и `draft` снесло бы вместе с прочими — отказ пропал бы из
        # «Доставки», хотя ради него всё и затевалось.
        await mail_send_mark(letter, sent=False, error=said, table=table,
                                    final=True)
        # ⚠ Канал — из разбора, а не «почта раз пришли из почты»: «он закрылся»,
        # услышанное здесь, гасит и чат тоже, а «не подходите по возрасту» — нет.
        await block_add(site_id, profile_id, uid,
                               str(letter.get('name') or ''), reason=said,
                               source='mail', channel=channel)
    except Exception as e:
        logger_info(f'[dating] отказ письма не разобрался: {e}')


def _payload(check_id: str, uid: str, body: str, reply_to=None,
             attach: dict = None) -> dict:
    """Тело запроса `POST /messages/send` — ровно по документации сайта.

    Args:
        reply_to: номер письма на сайте, на которое отвечаем. `None` — письмо
            первое, предыстории нет.
        attach: вложение `{'name': имя файла, 'data': байты}`. Пусто — письмо
            без вложения, три поля уходят пустыми.

    ## ⚠⚠ Имени у нового вложения быть НЕ ДОЛЖНО

    Документация сайта: «If the attachment **already exists**, provide its name
    and hash. If **not**, provide the hash and base64-encoded file.» То есть
    `AttachmentName` — признак «такой файл у вас уже лежит, возьмите его», а не
    подпись к присылаемому.

    Слали все три поля сразу, и сайт отвечал `Status: OK` — а письмо приходило
    **без снимка**: по имени он искал готовое вложение, не находил и отправлял
    текст. Собеседник получал «вот моё фото» без фото, а обещание закрывалось
    исполненным. Проверено на живой паре: после снятия имени тот же файл принят,
    и `check-attachment-by-hash` отвечает на него именем **сайта**
    (`0e11024c…jpg`), а не нашим.

    ⚠ Имя файла из индекса наружу, стало быть, не уходит вовсе — и это верно:
    оно наше, с Диска, и сайту ничего не говорит.

    ⚠ **Поля вложения шлём пустыми, а не опускаем.** Документация перечисляет их в
    теле, и сайт вправе требовать их наличия; пустое поле означает «вложения нет», а
    отсутствующее — «мы не знаем такого поля». Это разные утверждения, и второе
    неверно.
    """
    # ⚠ Имя разбираем, но наружу не шлём — см. ⚠⚠ в докстринге. Проверку
    # годности вложения оно при этом выполняет: `_attach_parts` падает на
    # негодном, и сделать это надо **до** похода на сайт.
    _name, raw = _attach_parts(attach)

    return {'CheckId': check_id,
            'RecipientAccountId': str(uid),
            'Body': str(body),
            # ⚠ У письма рассылки предыстории нет по определению — там `None`. У
            # ответа же он обязателен: без него сайт покажет ответ отдельным письмом,
            # и собеседник не поймёт, на что ему отвечают.
            'ReplyForMessageId': int(reply_to) if reply_to else None,
            # ⚠⚠ У нового вложения имя **пустое**: непустое значит «оно у
            # вас уже есть», и файл тогда не принимается вовсе.
            'AttachmentName': None,
            # ⚠ Хэш — **от самих байтов**, а не от base64: сайт сверяет им то, что
            # получил после разбора. Считать его от строки значило бы сверять не
            # файл, а его запись.
            'AttachmentHash': hashlib.md5(raw).hexdigest() if raw else '',
            'AttachmentFile': base64.b64encode(raw).decode() if raw else None}


def _attach_parts(attach) -> tuple:
    """Вложение → `(имя, байты)`. Негодное — отказ, а не тихая отправка текстом.

    ## ⚠⚠ Пустота и брак — разные вещи

    Письмо **без** вложения законно: три пула из четырёх шлют текст, и `None`
    здесь — обычный путь. А вот вложение, которое просили приложить, но приложить
    нечем, — это отказ: уйди такое письмо текстом, девушка ответила бы «вот моё
    фото» без фото, и собеседник счёл бы это издёвкой или поломкой. Хуже всего,
    что обещание при этом закрылось бы исполненным.

    ⚠ Предел считается по **байтам до base64**: сама запись длиннее на треть, и
    меряя её, мы меряли бы не файл.
    """
    if not attach:
        return '', b''

    raw = attach.get('data') or b''
    name = str(attach.get('name') or '').strip()

    if not isinstance(raw, (bytes, bytearray)) or not raw:
        raise DatingMailSendError('к письму просили приложить снимок, '
                                  'а байтов нет')

    if len(raw) > MAIL_ATTACH_MAX:
        raise DatingMailSendError(
            f'снимок тяжелее предела: {len(raw) // 1024} КБ при '
            f'{MAIL_ATTACH_MAX // 1024} КБ')

    if not name:
        raise DatingMailSendError('у вложения нет имени файла')

    return name, bytes(raw)
