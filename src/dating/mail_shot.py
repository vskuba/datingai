"""Снимок к письму: прикладывать ли и какой.

Девушка пишет человеку письмо — и изредка прикладывает к нему фотографию, о
которой он не просил. Так делает живой человек; письма, где текст и только
текст, со стороны однообразны.

## ⚠⚠⚠ Жребий бросает **сосед**, а не этот модуль

Решает, прикладывать ли снимок, шаг `dice` у соседа, и ответ приезжает в
`extra` прогона ключом `img_attach` (`rhapsody_api.py`). Здесь остаётся только
выбрать кадр.

Так было не всегда: доля жила настройкой панели, а бросок — здешним
`random.random()`. Это повторяло уже исправленную ошибку — доли стояли в двух
местах разом и складывались: приём «писать первой неловко» выпадал девяти
заготовкам из двадцати при ожидаемых четырёх. Правило теперь одно: **жребия в
коде панели нет**, все доли у соседа.

## ⚠⚠ Это не то же, что снимок по обещанию

Обещанный снимок (`intention_do.py`) уходит потому, что о нём **попросили**, и
выбирается по приметам, которые прислал агент: «outdoor, evening, smiling».
Здесь примет нет вовсе — повода выбирать конкретный кадр не было, — и берётся
просто первый, которого этот человек ещё не видел.

Отсюда же разница в папке. Обещание может быть каким угодно, и отбор идёт по
всей галерее; тут же берётся **только `public`**: прислать интимный снимок
тому, кто ни о чём не просил, — не то, что делают жребием.

## ⚠ Снимок выбирается при сборке письма, а не при отправке

Между сочинением и уходом проходят минуты и часы: держат пауза
отправительницы, остуда ящика получателя, расписание. Выбирай мы в момент
отправки, человек видел бы в пуле одно, а уходило бы другое. По той же причине
номер снимка **хранится в строке пула**, а не считается заново.
"""

import random

from logging_.logging_ import logger_info
from mysql_.mysql_ import mysql_get_db_async

from src.dating.companion_gallery import (companion_gallery_fresh,
                                          companion_gallery_shown)
from src.dating.gallery import gallery_group_of

# Ключ в `extra` прогона, которым сосед говорит «приложи снимок».
#
# ⚠⚠ Слово здесь — **то самое**, что в шаге workflow у соседа
# (`chat_response_extra_set(key='img_attach', …)`). Третьего списка нет: ключ
# приезжает строкой, и опечатка здесь означала бы вечно пустой отбор — без
# единой ошибки, потому что «снимка не просили» законный исход.
MAIL_SHOT_KEY = 'img_attach'

# Из какой папки галереи берём.
#
# ⚠⚠ **Только `public`, и это решение, а не умолчание.** Отбор умеет брать из
# любой папки, включая `intim`; слать интимный снимок человеку, который о нём
# не просил, жребием нельзя. Такие уходят лишь по обещанию агента
# (`intention_do.py`), где о снимке попросили словами.
MAIL_SHOT_GROUP = 'public'


class DatingMailShotError(RuntimeError):
    """Снимок к письму взять нечем. Текст годен для журнала и строки пула."""


def mail_shot_want(extra: dict) -> int:
    """Сколько снимков просил приложить прогон. Ноль — письмо уйдёт текстом.

    Args:
        extra: решения прогона из ответа соседа (`rhapsody_api.py`).

    Returns:
        int: число от нуля. Сегодня это «да/нет» (`1`/`0`), но форма уже
        готова к «сколько снимков»: ключ придёт числом, и менять здесь будет
        нечего.

    ## ⚠⚠ Приводим к числу **здесь**, а не у соседа

    Там значение остаётся строкой намеренно: `extra` свободен по форме, и
    решать за читателя, что это число, инструмент не должен. Приводит тот, кто
    по значению работает, — тот же приём, что у долей (`percent.py`).

    ⚠ Чужое значение не роняет заход: ключ кладёт шаг workflow, и опечатка
    (`'yes'` вместо `'1'`) читается как ноль — письмо уйдёт текстом. Это хуже
    отказа только на первый взгляд: письмо с текстом дойдёт, а упавший заход
    не дойдёт вовсе.
    """
    said = str((extra or {}).get(MAIL_SHOT_KEY) or '').strip()

    try:
        return max(0, int(float(said)))
    except (TypeError, ValueError):
        return 0


async def mail_shot_pick(profile_id: int, site_id: int, uid: str,
                         extra: dict = None) -> int:
    """Какой снимок приложить к письму. Возвращает номер строки `gallery_file`.

    Args:
        profile_id: анкета-отправительница — её галерея.
        site_id: сайт собеседника.
        uid: получатель на сайте: по нему считается, чего он ещё не видел.
        extra: решения прогона. Нет ключа `img_attach` либо он ноль — снимка
            не будет.

    Returns:
        int: номер строки индекса галереи либо **ноль** — письмо уйдёт текстом.
        Ноль — самый частый ответ и законный: жребий у соседа редкий.

    ## ⚠ Ничего не бросает

    Снимка может не быть по трём причинам — прогон его не просил, галереи нет,
    всё уже показано, — и ни одна из них не повод отказать письму. Текст у него
    есть, человеку он уйдёт; молчание здесь дороже разбирательства.

    ⚠ Отметку «показан» ставит **отправка** (`mail_send_mark`), а не этот
    отбор: пока письмо лежит в пуле, снимок никому не показан, и сожги мы его
    здесь, первая же неудачная отправка унесла бы кадр навсегда.
    """
    if not mail_shot_want(extra):
        return 0

    fresh = await companion_gallery_fresh(int(profile_id), int(site_id),
                                          str(uid), limit=1,
                                          group=MAIL_SHOT_GROUP)
    if not fresh:
        # ⚠ Не ошибка и не повод для журнала анкеты: галерея конечна, а
        # переписка нет — рано или поздно человек увидит всё.
        return 0

    row = fresh[0]
    logger_info(f'[dating] к письму анкеты #{profile_id} для {uid} '
                f'приложен снимок #{row["id"]}')

    return int(row['id'])


async def mail_shot_for_template(profile_id: int, mail_id: int = 0,
                                 keep: int = 0) -> int:
    """Кадр шаблону рассылки. Возвращает номер строки `gallery_file` либо ноль.

    Args:
        profile_id: анкета-владелица шаблона — её галерея.
        mail_id: номер шаблона, которому берут кадр; нужен только чтобы не
            счесть занятым **его собственный** кадр. Ноль — строки ещё нет.
        keep: кадр, который шаблон уже держит. Свободен — он и остаётся,
            перевыбор не трогает державший кадр; занят чужим живым шаблоном
            (шаблон выключали, пока другой на тот же кадр сел) — берём новый.

    Returns:
        int: номер строки индекса галереи либо **ноль** — анкете брать нечем
        (галереи нет либо Диск не обошли). Ноль законен, как в `_put`.

    ## ⚠⚠ Кадр принадлежит шаблону, а не письму (правило владельца от 04.11.2026)

    До этого кадр выбирали **получателю** («первый, которого он ещё не видел»),
    и все новые адресаты получали один и тот же первый кадр: на странице разных
    шаблонов стояла одна миниатюра. Теперь кадр берёт шаблон один раз — и
    письма этого шаблона несут его; удаление шаблона кругом-чисткой освобождает
    кадр, и он снова годен.

    ⚠⚠ **Одна дверь на все дороги.** Зовут её круг заготовок
    (`mail_round._write`), ручное заведение шаблона (routers `mail.py`) и
    дозор рассылки (`mailing_shots_fill` через сборку `_put`). Свой отбор в
    каждом — те же повторы, что это правило чинит.

    ## Порядок выбора

    0. **свой кадр свободен — он и есть выбор**: правка текста шаблона не
       переселяет его на другой снимок и не передвигает `last_shot_at`;
    1. **кандидаты** — живые снимки папки `public`, не занятые включёнными
       шаблонами этой анкеты: у каждого живого шаблона свой кадр;
    2. среди кандидатов — никогда не бранные (`last_shot_at IS NULL`), самыми
       свежими файлами вперёд; нет таких — давнейший по `last_shot_at`;
    3. все кадры анкеты уже брались — **сброс круга**: `last_shot_at`
       обнуляется по всей анкете, и первый кадр нового круга берётся
       **случайно** (правило владельца — круг заново идёт вразноброд);
       дальше по кругу действует обычная лестница свежести;
    4. кандидатов нет, а круг не исчерпан — живые шаблоны съели все кадры
       (галерея мельче нормы): случайный из всех, иначе шаблон остался бы
       без кадра там, где кадры есть.

    ⚠ Включённый шаблон держит кадр; **выключенный — не держит** (решение
    владельца 04.11.2026): занятость считают только строки с `enabled = 1`,
    кадр выключенного шаблона сразу годен живым.

    ⚠ ⚠ Дверь ничего не знает о **получателе**: память пары живёт по-прежнему
    в `companion_gallery_file` и метится отправкой. Обязанность зовущего —
    сверить кадр с памятью (`companion_gallery_shown`) и отдать письму
    следующий невиданный, если этот человек кадр уже видел: шаблон ≠ лицензия
    повторять человеку показанное.
    """
    gid = int(profile_id or 0)
    if not gid:
        return 0

    try:
        if int(keep or 0):
            # Свой кадр занят чужим живым шаблоном? Показатель — тот же, что
            # у кандидатов ниже: включённые строки этой анкеты.
            async with mysql_get_db_async() as db:
                await db.execute(
                    'SELECT EXISTS (SELECT 1 FROM mail t'
                    '                   WHERE t.profile_id = %s'
                    '                     AND t.enabled = 1'
                    '                     AND t.id <> %s'
                    '                     AND t.gallery_file_id = %s)',
                    (gid, int(mail_id or 0), int(keep)))
                busy = bool(list(dict(await db.fetchone() or {}).values())[0])

            if not busy:
                return int(keep)

        async with mysql_get_db_async() as db:
            await db.execute(
                'SELECT g.id, g.path, g.last_shot_at'
                '  FROM gallery_file g'
                ' WHERE g.profile_id = %s AND g.is_gone = 0 AND g.kind = %s'
                '   AND NOT EXISTS (SELECT 1 FROM mail t'
                '                     WHERE t.profile_id = g.profile_id'
                '                       AND t.enabled = 1'
                '                       AND t.gallery_file_id = g.id)'
                ' ORDER BY g.id',
                (gid, 'image'))
            live = [dict(row) for row in (await db.fetchall() or [])]

            await db.execute(
                'SELECT g.id, g.path, g.last_shot_at'
                '  FROM gallery_file g'
                ' WHERE g.profile_id = %s AND g.is_gone = 0 AND g.kind = %s'
                ' ORDER BY g.id',
                (gid, 'image'))
            whole = [dict(row) for row in (await db.fetchall() or [])]

        # Группа — общим правилом (`gallery_group_of`), как у
        # `companion_gallery_fresh`: в SQL вышло бы второе правило о папке.
        pool = [row for row in whole
                if gallery_group_of(row['path']) == MAIL_SHOT_GROUP]
        free = [row for row in live
                if gallery_group_of(row['path']) == MAIL_SHOT_GROUP]

        if not pool:
            # Галереи нет (или обошли не весь Диск) — письмо без кадра, то же
            # исключение правила 08.11.2026, что у `_put`. Тихо: не случай.
            return 0

        exhausted = all(row['last_shot_at'] is not None for row in pool)

        if exhausted:
            # Сброс свежести: обнуляем по всей анкете и без группы — колонку
            # `last_shot_at` заполняет только эта дверь, чужих значений у
            # кадров других папок нет, а второе правило о папке в UPDATE
            # было бы копией, расходящейся с отбором выше.
            async with mysql_get_db_async() as db:
                await db.execute('UPDATE gallery_file SET last_shot_at = NULL'
                                 ' WHERE profile_id = %s', (gid,))
                await db.connection.commit()

            logger_info(f'[dating] анкете #{gid} кадры исчерпаны: круг сброшен')

        # Порядок после всех развилок.
        if exhausted:
            # Первый подбор нового круга — случайный (правило владельца:
            # круг заново идёт вразноброд). Свободных нет — из всех.
            chosen = random.choice(free or pool)

        elif not free:
            # Живые шаблоны съели все кадры, а круг не исчерпан (галерея
            # мельче нормы) — случайный из всех, иначе шаблон остался бы
            # без кадра на галерее, которая есть.
            chosen = random.choice(pool)

        else:
            never = [row for row in free if row['last_shot_at'] is None]
            if never:
                # Никогда не бранные — самыми свежими файлами вперёд.
                chosen = max(never, key=lambda row: int(row['id']))

            else:
                # Страховка: свободные все браные, а круг не исчерпан —
                # невиданные кадры сидят под живыми шаблонами. Давнейший.
                chosen = min(free, key=lambda row: (str(row['last_shot_at']),
                                                    -int(row['id'])))

        shot = int(chosen['id'])

        async with mysql_get_db_async() as db:
            await db.execute('UPDATE gallery_file SET last_shot_at = NOW()'
                             ' WHERE id = %s', (shot,))
            await db.connection.commit()

        logger_info(f'[dating] шаблону анкеты #{gid} отдан кадр #{shot}')

        return shot

    except Exception as e:
        logger_info(f'[dating] кадр шаблону анкеты #{gid} не выбрался: {e}')

        return 0


async def mail_shot_ready(letter: dict) -> dict:
    """Строка пула → письмо, готовое к отправке: тот же словарь плюс снимок.

    Args:
        letter: строка любого пула — нужен `gallery_file_id`.

    Returns:
        dict: копия строки с ключом `attach` (`{'name', 'data'}`). Снимка нет
        (`gallery_file_id = 0`) — та же строка без `attach`, и письмо уйдёт
        текстом.

    Raises:
        DatingMailShotError: снимок назначен, а взять его нечем.

    ## ⚠⚠ Одна дверь на все пулы и обе дороги

    Готовить вложение надо и кругу отправки, и кнопке человека, и трём пулам
    сразу — обещанию агента, ответу и приставанию. Своя подготовка у каждого
    разошлась бы ровно там, где это дороже всего: один слал бы снимок, другой
    то же письмо текстом.

    ⚠ Зовётся **до** `mail_send_one`, а не внутри: между `check-send` и `send`
    нельзя ходить в сеть, а Диск отвечает секунды.
    """
    # ⚠ Импорты отложенные: `intention_do` зовёт этот модуль за жребием, и
    # обычные дали бы круг «снимок → намерения → снимок».
    from mysql_.mysql_ import mysql_get_db_async

    from src.dating.intention_do import (DatingIntentionError,
                                         intention_mail_attach)

    file_id = int(letter.get('gallery_file_id') or 0)
    if not file_id:
        return dict(letter)

    async with mysql_get_db_async() as db:
        await db.execute('SELECT file_id, name FROM gallery_file WHERE id = %s',
                         (file_id,))
        file = await db.fetchone()

    if not file:
        raise DatingMailShotError('снимка больше нет в индексе галереи')

    try:
        attach = await intention_mail_attach(str(file['file_id']),
                                             str(file['name'] or ''))
    except DatingIntentionError as e:
        raise DatingMailShotError(str(e)) from e

    return {**letter, 'attach': attach}


def mail_shot_join(table: str = 'm') -> tuple[str, str]:
    """Кусок запроса «какой снимок ушёл этим письмом»: что выбрать и чем склеить.

    Args:
        table: псевдоним таблицы письма в запросе (`m`, `r`).

    Returns:
        tuple: `(select, join)` — обе строки уже с ведущей запятой/пробелом,
        подставляются в запрос как есть.

    ## ⚠⚠ Зачем кусок, а не четыре копии

    Номер снимка лежит в строке письма (`gallery_file_id`), а показать кадр по
    нему нельзя: превью отдаётся **по номеру файла на Диске**, и спутать их
    легко — оба числа, и ошибка видна лишь пустым квадратом в ленте.

    Склейка эта понадобилась четырём читателям: вкладке намерений, ленте
    отправленного, журналу доставки избранным и журналу ответов. Четыре
    одинаковых `LEFT JOIN` с одинаковыми псевдонимами полей — это четыре места,
    которые разойдутся на первой же правке, и разойдутся **молча**: запрос
    останется верным, а поле у страницы станет называться иначе, и превью
    пропадёт без единой ошибки.

    ⚠ Имена полей (`gallery_file`, `gallery_path`, `gallery_tags`) — часть
    договора **со страницей**: превью рисует одна её выкройка на все журналы.
    Поэтому они здесь, рядом с остальным знанием о снимке письма, а не у
    каждого запроса своим написанием.

    ⚠ `gallery_tags` приходит из JSON-колонки **строкой**; кто собирается его
    показывать — разбирает у себя (`json_column_list`), как это делает
    вкладка намерений. Не разобранное поле безвредно: страницы, которым оно
    не нужно, его просто не читают.
    """
    one = str(table or 'm').strip() or 'm'

    # ⚠⚠ Запятая **ведущая, и она часть куска**. Без неё запрос склеивается в
    # `… profile_card g.path AS …` и падает `1064` — то есть громко, но только
    # на живом запросе: сам кусок при этом выглядит верным, а зовущий не обязан
    # помнить, чем он начинается. Отдать запятую зовущему значило бы раздать
    # четыре места, где её можно забыть.
    return (', g.path AS gallery_path, g.file_id AS gallery_file,'
            ' g.tags AS gallery_tags',
            f' LEFT JOIN gallery_file g ON g.id = {one}.gallery_file_id')
