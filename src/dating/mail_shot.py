"""Снимок к письму: прикладывать ли и какой.

Девушка пишет человеку письмо — и изредка прикладывает к нему фотографию, о
которой он не просил. Так делает живой человек; письма, где текст и только
текст, со стороны однообразны.

## ⚠⚠⚠ Жребий бросает **сосед**, а не этот модуль

Решает, прикладывать ли снимок, шаг `dice` у соседа, и ответ приезжает в
`extra` прогона ключом `img_attach` (`rhapsody_api.py`). Здесь остаётся только
выбрать кадр.

Так было не всегда: доля жила настройкой панели, а бросок — здешним
`random.random()`. Это повторяло уже исправленную ошибку — доли стояли в двух
местах разом и складывались: приём «писать первой неловко» выпадал девяти
заготовкам из двадцати при ожидаемых четырёх. Правило теперь одно: **жребия в
коде панели нет**, все доли у соседа.

## ⚠⚠ Это не то же, что снимок по обещанию

Обещанный снимок (`intention_do.py`) уходит потому, что о нём **попросили**, и
выбирается по приметам, которые прислал агент: «outdoor, evening, smiling».
Здесь примет нет вовсе — повода выбирать конкретный кадр не было, — и берётся
просто первый, которого этот человек ещё не видел.

Отсюда же разница в папке. Обещание может быть каким угодно, и отбор идёт по
всей галерее; тут же берётся **только `public`**: прислать интимный снимок
тому, кто ни о чём не просил, — не то, что делают жребием.

## ⚠ Снимок выбирается при сборке письма, а не при отправке

Между сочинением и уходом проходят минуты и часы: держат пауза
отправительницы, остуда ящика получателя, расписание. Выбирай мы в момент
отправки, человек видел бы в пуле одно, а уходило бы другое. По той же причине
номер снимка **хранится в строке пула**, а не считается заново.
"""

from logging_.logging_ import logger_info

from src.dating.companion_gallery import companion_gallery_fresh

# Ключ в `extra` прогона, которым сосед говорит «приложи снимок».
#
# ⚠⚠ Слово здесь — **то самое**, что в шаге workflow у соседа
# (`chat_response_extra_set(key='img_attach', …)`). Третьего списка нет: ключ
# приезжает строкой, и опечатка здесь означала бы вечно пустой отбор — без
# единой ошибки, потому что «снимка не просили» законный исход.
MAIL_SHOT_KEY = 'img_attach'

# Из какой папки галереи берём.
#
# ⚠⚠ **Только `public`, и это решение, а не умолчание.** Отбор умеет брать из
# любой папки, включая `intim`; слать интимный снимок человеку, который о нём
# не просил, жребием нельзя. Такие уходят лишь по обещанию агента
# (`intention_do.py`), где о снимке попросили словами.
MAIL_SHOT_GROUP = 'public'


class DatingMailShotError(RuntimeError):
    """Снимок к письму взять нечем. Текст годен для журнала и строки пула."""


def mail_shot_want(extra: dict) -> int:
    """Сколько снимков просил приложить прогон. Ноль — письмо уйдёт текстом.

    Args:
        extra: решения прогона из ответа соседа (`rhapsody_api.py`).

    Returns:
        int: число от нуля. Сегодня это «да/нет» (`1`/`0`), но форма уже
        готова к «сколько снимков»: ключ придёт числом, и менять здесь будет
        нечего.

    ## ⚠⚠ Приводим к числу **здесь**, а не у соседа

    Там значение остаётся строкой намеренно: `extra` свободен по форме, и
    решать за читателя, что это число, инструмент не должен. Приводит тот, кто
    по значению работает, — тот же приём, что у долей (`percent.py`).

    ⚠ Чужое значение не роняет заход: ключ кладёт шаг workflow, и опечатка
    (`'yes'` вместо `'1'`) читается как ноль — письмо уйдёт текстом. Это хуже
    отказа только на первый взгляд: письмо с текстом дойдёт, а упавший заход
    не дойдёт вовсе.
    """
    said = str((extra or {}).get(MAIL_SHOT_KEY) or '').strip()

    try:
        return max(0, int(float(said)))
    except (TypeError, ValueError):
        return 0


async def mail_shot_pick(profile_id: int, site_id: int, uid: str,
                         extra: dict = None) -> int:
    """Какой снимок приложить к письму. Возвращает номер строки `gallery_file`.

    Args:
        profile_id: анкета-отправительница — её галерея.
        site_id: сайт собеседника.
        uid: получатель на сайте: по нему считается, чего он ещё не видел.
        extra: решения прогона. Нет ключа `img_attach` либо он ноль — снимка
            не будет.

    Returns:
        int: номер строки индекса галереи либо **ноль** — письмо уйдёт текстом.
        Ноль — самый частый ответ и законный: жребий у соседа редкий.

    ## ⚠ Ничего не бросает

    Снимка может не быть по трём причинам — прогон его не просил, галереи нет,
    всё уже показано, — и ни одна из них не повод отказать письму. Текст у него
    есть, человеку он уйдёт; молчание здесь дороже разбирательства.

    ⚠ Отметку «показан» ставит **отправка** (`mail_send_mark`), а не этот
    отбор: пока письмо лежит в пуле, снимок никому не показан, и сожги мы его
    здесь, первая же неудачная отправка унесла бы кадр навсегда.
    """
    if not mail_shot_want(extra):
        return 0

    fresh = await companion_gallery_fresh(int(profile_id), int(site_id),
                                          str(uid), limit=1,
                                          group=MAIL_SHOT_GROUP)
    if not fresh:
        # ⚠ Не ошибка и не повод для журнала анкеты: галерея конечна, а
        # переписка нет — рано или поздно человек увидит всё.
        return 0

    row = fresh[0]
    logger_info(f'[dating] к письму анкеты #{profile_id} для {uid} '
                f'приложен снимок #{row["id"]}')

    return int(row['id'])


async def mail_shot_ready(letter: dict) -> dict:
    """Строка пула → письмо, готовое к отправке: тот же словарь плюс снимок.

    Args:
        letter: строка любого пула — нужен `gallery_file_id`.

    Returns:
        dict: копия строки с ключом `attach` (`{'name', 'data'}`). Снимка нет
        (`gallery_file_id = 0`) — та же строка без `attach`, и письмо уйдёт
        текстом.

    Raises:
        DatingMailShotError: снимок назначен, а взять его нечем.

    ## ⚠⚠ Одна дверь на все пулы и обе дороги

    Готовить вложение надо и кругу отправки, и кнопке человека, и трём пулам
    сразу — обещанию агента, ответу и приставанию. Своя подготовка у каждого
    разошлась бы ровно там, где это дороже всего: один слал бы снимок, другой
    то же письмо текстом.

    ⚠ Зовётся **до** `mail_send_one`, а не внутри: между `check-send` и `send`
    нельзя ходить в сеть, а Диск отвечает секунды.
    """
    # ⚠ Импорты отложенные: `intention_do` зовёт этот модуль за жребием, и
    # обычные дали бы круг «снимок → намерения → снимок».
    from mysql_.mysql_ import mysql_get_db_async

    from src.dating.intention_do import (DatingIntentionError,
                                         intention_mail_attach)

    file_id = int(letter.get('gallery_file_id') or 0)
    if not file_id:
        return dict(letter)

    async with mysql_get_db_async() as db:
        await db.execute('SELECT file_id, name FROM gallery_file WHERE id = %s',
                         (file_id,))
        file = await db.fetchone()

    if not file:
        raise DatingMailShotError('снимка больше нет в индексе галереи')

    try:
        attach = await intention_mail_attach(str(file['file_id']),
                                             str(file['name'] or ''))
    except DatingIntentionError as e:
        raise DatingMailShotError(str(e)) from e

    return {**letter, 'attach': attach}
