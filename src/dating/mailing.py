async def _people(site_id: int) -> list[dict]:
    """Кто сейчас в сети — из того же снимка, что показывает лента «Все онлайн».

    ⚠ **Из кэша, а не походом на сайт.** Лента снимается своим кругом и живёт в
    Redis; сходи мы за ней заново, нажатие кнопки стоило бы сорока секунд браузера
    вдобавок к письмам. Пустой кэш означает, что ленту ещё не открывали, — и это
    честный ответ «в сети никого не знаем», а не повод лезть на сайт.

    ⚠ Ключ кэша и его чтение берём **у ленты** (`people.py`), а не собираем
    свои: разойдись они, рассылка писала бы не тем, кого человек видит на экране.

    ⚠ **Отмеченные приоритетом идут первыми.** Порядок в ленте — тот, в каком людей
    отдал сайт, и для панели он случаен: пул набирается до потолка и обрывается на
    полпути по списку, так что «кому досталось письмо» решал случай. Отметка
    (`companion.priority`) — способ сказать «этим в первую очередь».
    """
    from src.uvicorn.routers.dating.people import _cache_get, _key

    cached = _cache_get(_key('online', site_id=site_id))
    people = [row for row in ((cached or {}).get('people') or []) if row.get('uid')]

    return await _by_priority(site_id, people) if people else people


async def _by_priority(site_id: int, people: list[dict]) -> list[dict]:
    """Отмеченные приоритетом — вперёд, остальные — следом, порядок внутри прежний.

    ⚠ **Это перестановка, а не отбор.** Неотмеченные никуда не деваются: сделай мы
    из отметки фильтр, включённая галочка у одного человека молча выключила бы
    рассылку всем прочим — а человек отмечал одного, а не отменял остальных.

    ⚠ **Порядок внутри каждой половины сохраняется.** `sorted` в Python устойчива, и
    это здесь по существу: лента приходит от сайта в своём порядке, а перетасуй мы её
    сверх нужного — два набора подряд давали бы разных адресатов без всякой причины.

    ⚠ **Сбой базы не роняет набор**: возвращаем ленту как есть. Приоритет — это
    удобство, и падать из-за него значило бы менять письма на порядок писем.
    """
    try:
        marked = await _marked(site_id)
    except Exception as e:
        logger_info(f'[dating] приоритет собеседников не спросился: {e}')

        return people

    if not marked:
        return people

    # ⚠ **Отметку не только сортируем, но и ставим в запись** (`priority`). Порядок
    # отвечает «кого взять раньше», а набору инвайтов нужно второе: «этому пишут
    # все свободные девушки, а не одна». Без признака он спрашивал бы базу заново
    # на каждого человека в ленте — двести запросов на заход.
    #
    # ⚠ Копией, а не правкой на месте: лента лежит в кэше снимка, и дописав в неё
    # поле, мы изменили бы то, что показывает страница.
    return sorted(({**row, 'priority': str(row.get('uid')) in marked}
                   for row in people),
                  key=lambda row: 0 if row['priority'] else 1)


async def _marked(site_id: int) -> set:
    """Номера собеседников сайта, отмеченных приоритетом."""
    async with mysql_get_db_async() as db:
        await db.execute('SELECT uid FROM companion'
                         ' WHERE site_id = %s AND priority = 1', (int(site_id),))
        rows = await db.fetchall()

    return {str(row['uid']) for row in rows or []}


async def _taken(site_id: int) -> set:
    """Тройки «анкета — адресат — шаблон», которые уже готовили или отправляли.

    ⚠ **Шаблон входит в ключ**, и это то же правило, что стоит в базе
    (`uq_dating_mailing_once`): не больше одного письма от анкеты адресату **тем же
    шаблоном**. Разными — можно: у них разный текст, и второе письмо читается как
    продолжение разговора, а не как повтор.

    Прежде здесь была пара без шаблона — правило строже базы. Оно и работало, пока
    пул набирали по нажатию: адресатов сотня, писем полсотни, до вторых заходов
    дело не доходило. С наполнением по расписанию дошло: круг добирает пул до
    предела, и без вторых писем ему быстро становится нечего делать.

    ⚠ Берём **все состояния**, а не только пул: ушедшее письмо тоже значит, что
    этим шаблоном этому человеку уже писали.
    """
    async with mysql_get_db_async() as db:
        await db.execute(
            'SELECT profile_id, uid, mail_id FROM mailing WHERE site_id = %s',
            (int(site_id),))
        rows = await db.fetchall()

    return {(int(row['profile_id']), str(row['uid']), int(row['mail_id'] or 0))
            for row in rows}


async def _talked(site_id: int) -> set:
    """Пары «анкета — адресат», где **он написал первым**: письмом или в чате.

    ⚠ Нужно одному — возрастному отсеву (`mail_age.py`): критерий возраста сайт,
    судя по журналу, спрашивает только на холодном обращении, а в начатом
    разговоре пропускает. Шесть из девятнадцати разрешённых пар с промахом мимо
    окна — именно такие.

    ⚠ **Два источника, и оба обязательны.** Письмо лежит в `mail_in`, реплика
    чата — в `message` с `direction = 'in'`; у сайта без чата работает первый, у
    сайта без писем — второй. Один источник означал бы «он нам не писал» там, где
    писал другим каналом.

    ⚠ Сбой запроса отвечает пустым множеством: «не знаем, писал ли» — это
    «считаем, что не писал», то есть обычный холодный отбор. Ошибка в эту сторону
    стоит пропущенной пары, в обратную — письма, которое сайт не возьмёт.
    """
    try:
        async with mysql_get_db_async() as db:
            await db.execute(
                'SELECT profile_id, uid FROM mail_in WHERE site_id = %s'
                ' UNION'
                # ⚠ Псевдоним обязателен: имена столбцов `UNION` берёт у первой
                # половины, и без него строка чата приехала бы под именем `uid`
                # молча — читается как опечатка, а не как правило.
                ' SELECT m.profile_id, m.sender_uid AS uid FROM message m'
                '  JOIN profile p ON p.id = m.profile_id'
                "  WHERE p.site_id = %s AND m.direction = 'in'",
                (int(site_id), int(site_id)))
            rows = await db.fetchall()
    except Exception as e:
        logger_info(f'[dating] кто писал первым не спросилось: {e}')

        return set()

    return {(int(row['profile_id']), str(row['uid'] or ''))
            for row in rows or []}


async def _mail_answered(site_id: int) -> set:
    """Пары «анкета — адресат», где он **ответил письмом**: рассылки им больше нет.

    ⚠ **Не то же, что `_talked`.** Тот отвечает «он написал первым — письмом или в
    чате» и нужен возрастному отсеву; здесь вопрос уже: «состоялось ли письменное
    знакомство». Реплика в чате его не заменяет — у чата своё занятие и свой пул
    (`chat_initiative`), а письмо рассылки она не отменяет.

    ⚠ **Правило одно с отправкой и уборкой** (`pool_mail_answered_where`), и
    здесь оно спрашивается множеством, а не условием: набор держит пары в памяти —
    он их и так перебирает, — и лишний подзапрос на каждую тройку был бы платой за
    то же знание.

    ⚠ Сбой запроса — **пустое множество**, как у `_talked`: «не знаем, отвечал ли»
    на наборе значит «сочиним», а последнее слово всё равно за отправкой — там то
    же правило стоит условием запроса, и ошибка в эту сторону стоит сочинённого
    впустую письма, а не ушедшего.
    """
    try:
        async with mysql_get_db_async() as db:
            await db.execute(
                'SELECT DISTINCT profile_id, uid FROM mail_in WHERE site_id = %s',
                (int(site_id),))
            rows = await db.fetchall()
    except Exception as e:
        logger_info(f'[dating] кто отвечал письмом не спросилось: {e}')

        return set()

    return {(int(row['profile_id']), str(row['uid'] or ''))
            for row in rows or []}


async def _put(site_id: int, girl: dict, person: dict, template: dict,
               body: str) -> None:
    """Кладёт письмо в пул.

    `INSERT IGNORE`: уникальный ключ ловит гонку, если кнопку нажали дважды разом.
    """
    async with mysql_get_db_async() as db:
        await db.execute(
            'INSERT IGNORE INTO mailing'
            ' (site_id, profile_id, mail_id, uid, name, body, status)'
            " VALUES (%s, %s, %s, %s, %s, %s, 'draft')",
            (int(site_id), int(girl['id']), int(template['id']),
             str(person['uid']), str(person.get('name') or ''), body))
        await db.connection.commit()
