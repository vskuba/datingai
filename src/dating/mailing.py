async def mailing_make(site_id: int, templates: list, limit: int,
                              profile_id: int = 0, first_uid: str = '') -> dict:
    """Набирает пул: письма по заданным шаблонам, не больше `limit` попыток.

    Args:
        site_id: сайт-закладка.
        templates: шаблоны, из которых каждому письму достаётся случайный.
        limit: сколько пар пробуем за заход.
        profile_id: писать только от этой анкеты. Ноль — от всех, у кого включена
            рассылка. ⚠ Сужение, а не отбор заново: анкета всё равно должна быть с
            рассылкой и с этого сайта, иначе писем не будет вовсе.
        first_uid: кого поставить первым — карточка, выбранная в ленте «Все
            онлайн». ⚠ Перестановка, а не отбор: остальные адресаты остаются.

    Returns:
        dict: `made` — сколько писем готово, `skipped` — сколько пар пропущено из-за
        нехватки переменных, `reasons` — чего именно не хватило (первые несколько),
        `left` — сколько пар осталось на следующий заход, `stopped` — почему заход
        оборвался раньше времени (пусто — дошёл до конца).

    ⚠ **Повторный заход продолжает с того же места**, а не делает то же самое: пары,
    для которых письмо уже лежит в пуле или ушло, пропускаются. Поэтому кнопку можно
    жать, пока пул не наберётся, и не бояться дублей — а круг может будить набор
    каждые полчаса, не заваливая пул повторами.
    """
    girls = await _girls(site_id)
    people = mailing_people_first(await _people(site_id), first_uid)

    # ⚠ Сужаем **после** отбора, а не запросом: правила «включена» и «с рассылкой»
    # должны быть одни на оба случая. Спроси мы анкету отдельным запросом, письма
    # от выключенной уходили бы там, где от неё же в общем наборе не уходят.
    if profile_id:
        girls = [girl for girl in girls if girl['id'] == int(profile_id)]

    if not girls or not people or not templates:
        return {'made': 0, 'skipped': 0, 'reasons': [], 'left': 0, 'stopped': ''}

    # ⚠ Реестр и значения берём **у роутера переменных, лениво**. Импорт наверху
    # завёл бы предметный модуль в зависимость от ручек: обход сайтов в воркере
    # тянул бы за собой FastAPI и всю обвязку прав, которой в круге нет.
    from src.uvicorn.routers.dating.mail_var import (
        mail_var_rows, profile_var_values)

    known = await mail_var_rows(site_id)
    taken = await _taken(site_id)
    # ⚠⚠ **Остывшие адресаты выпадают до всякого сочинения.** Сайт уже сказал,
    # что писать им сейчас не даст (`mail_wait.py`), и письмо такому человеку
    # легло бы в пул мёртвым грузом: отправка его не унесёт, а место оно займёт.
    # Один поход в Redis на заход — против двухсот отказов сайта.
    cooling = set(mail_wait_uids(site_id))
    cooled = 0
    if cooling:
        warm = [one for one in people
                if str(one.get('uid') or '') not in cooling]
        cooled, people = len(people) - len(warm), warm

    # ⚠ Пустой список после остуды — **ответ с причиной**, а не молчаливый ноль.
    # «Готово 0, пропущено 0» человек читает как поломку; здесь же всё работает,
    # и сказать надо именно это.
    if not people:
        return {'made': 0, 'skipped': cooled,
                'reasons': ([f'все {cooled} адресатов остывают: сайт не даёт им '
                             f'сейчас писать'] if cooled else []),
                'left': 0, 'stopped': ''}
    # Кто из адресатов уже писал нашим девушкам: таким пара не отсекается по
    # возрасту (`mail_age.py`). Один запрос на заход.
    talked = await _talked(site_id)
    # Пары «адресат — шаблон», потраченные любой анкетой: один текст уходит
    # человеку ровно раз (`_pairs`).
    spent = {(uid, mail_id) for _, uid, mail_id in taken if mail_id}
    # Закрывшиеся от анкеты: письмо им не уйдёт — сайт откажет тем же отказом, что
    # и в чате (`block.py`). Отдельным набором, потому что и вопрос свой.
    blocked = await block_pairs(site_id)
    # ⚠⚠ **Ответившие письмом: рассылка им больше не положена вовсе.** Холодное
    # обращение кончается его письмом — дальше разговор ведёт «приставание»
    # (`favorite_mail`), которое пишет по переписке и от той же девушки. Правило и
    # его цена — в `pool_mail_answered_where`; здесь оно стоит первым из двух мест:
    # сочинять письмо, которое отправка не возьмёт, незачем.
    answered = await _mail_answered(site_id)

    # ⚠ Считаем **попытки**, а не только удачи. Прежде предел проверялся по готовым
    # письмам, и проход, где всё пропускается, шёл по всем парам до конца: 176 пар,
    # 8 минут и ноль писем на выходе. Поймано живым прогоном.
    made, tried, skipped, reasons, left, stopped = 0, 0, 0, [], 0, ''

    # ⚠⚠ **Кому не напишет ни одна наша анкета — говорим словами, а не молча.**
    #
    # Отсев по возрасту живёт в `_pairs` и работает парами: не подошла эта
    # девушка — напишет другая. Но бывает, что не подходит ни одна, и тогда
    # человек просто исчезает из набора. Молчаливое исчезновение адресатов — то
    # самое «круг работает, писем нет», за которое уже платили временем.
    for person in people:
        why = mail_age_nobody(girls, person, talked)
        if not why:
            continue

        skipped += 1
        # ⚠ Причина подписана адресатом, поэтому и не дедуплицируется: у каждого
        # человека своё окно, и «пропущено 24» без имён — число без ответа на
        # «кого». Держим первые пять, как и прочие причины набора.
        if len(reasons) < 5:
            reasons.append(f'{person.get("name") or person.get("uid")}: {why}')

    # ⚠ Значения анкеты читаются **один раз на анкету**, а не на письмо: они не
    # зависят от адресата, а запрос на каждое письмо превратил бы полсотни писем в
    # полсотни лишних походов в базу.
    values_by_girl = {}

    for girl, template, person in _pairs(girls, people, templates, taken, blocked,
                                         spent, talked, answered):
        if tried >= limit:
            left += 1
            continue

        tried += 1

        if girl['id'] not in values_by_girl:
            values_by_girl[girl['id']] = await profile_var_values(girl['id'])

        try:
            body, why = await _body(template, girl, person, known,
                                    values_by_girl[girl['id']], site_id)
        except DatingMailAgentError as e:
            # Агент недоступен — это не «письмо не годится», а «сейчас не выйдет
            # вовсе». Останавливаемся: следующие пары упрутся в то же самое.
            logger_info(f'[dating] рассылка остановлена: {e}')
            stopped = str(e)
            break

        if why:
            skipped += 1
            if len(reasons) < 5 and why not in reasons:
                reasons.append(why)
            continue

        await _put(site_id, girl, person, template, body)
        made += 1
        taken.add((girl['id'], person['uid'], template['id']))

    return {'made': made, 'skipped': skipped, 'reasons': reasons, 'left': left,
            'stopped': stopped}


async def mailing_templates(site_id: int, mail_ids: list = None) -> list[dict]:
    """Шаблоны сайта: заданные номерами или все включённые.

    Args:
        mail_ids: какие брать. ⚠ **Пусто — берём все включённые**, и это не
            вольность: так набирает круг по расписанию, где выбирать некому.
            Человек же выбирает сам, и пустой выбор для него — отказ, а не «все».
    """
    sql = 'SELECT id, name, body FROM mail WHERE site_id = %s AND enabled = 1'
    args = [int(site_id)]

    ids = [int(one) for one in (mail_ids or []) if int(one) > 0]
    if ids:
        sql += ' AND id IN (%s)' % ', '.join(['%s'] * len(ids))
        args.extend(ids)

    sql += ' ORDER BY id'

    async with mysql_get_db_async() as db:
        await db.execute(sql, tuple(args))
        rows = await db.fetchall()

    return [{'id': int(row['id']), 'name': str(row['name']), 'body': str(row['body'])}
            for row in rows]


