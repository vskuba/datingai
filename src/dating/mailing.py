def _pairs(girls: list, people: list, templates: list, taken: set,
           blocked: set = None, spent: set = None, talked: set = None,
           answered: set = None):
    """Тройки «анкета — адресат — шаблон»: кому, от кого и чем писать.

    ⚠ **По адресатам, а не перебором всех сочетаний.** Анкет два десятка, людей в
    сети под две сотни, шаблонов пяток: перебор дал бы тысячи троек за заход. Здесь
    каждый адресат получает одно письмо за проход, и вопрос только в том, от кого и
    каким текстом.

    ⚠ **Анкета и шаблон выбираются наугад, а не по кругу.** Круг давал правильное
    чередование — первая, вторая, третья, снова первая, — и по журналу сайта такая
    рассылка читается как рассылка.

    ⚠ **Выбираем из свободных троек.** Иначе случай раз за разом выпадал бы на
    занятую пару, и человек оставался без письма, хотя другая анкета или другой
    шаблон были доступны.

    ⚠ **Запрет отнимает анкету, а не адресата.** Закрылся человек от одной
    девушки — от остальных письмо ему уйдёт: они ему не писали и отказа не
    получали. Закрылся от всех — свободных троек не останется, и он выпадет сам.

    Args:
        taken: тройки, которым письмо уже готовили или отправляли.
        blocked: пары «анкета — адресат», где человек закрылся от девушки
            (`block`). ⚠ Пара, а не тройка: он закрылся от неё целиком, и
            шаблон тут ничего не меняет.
        spent: пары «адресат — шаблон», уже потраченные **любой** анкетой.
        answered: пары «анкета — адресат», где он **ответил письмом**. ⚠ Тоже
            пара, и тоже целиком: холодного обращения от этой девушки больше не
            бывает, каким бы шаблоном оно ни было.

    ## ⚠⚠ Один шаблон уходит человеку ровно раз, кем бы ни была девушка

    Прежде ключом была тройка «анкета — адресат — шаблон», и одно это правило
    держало всё: «не больше письма от анкеты адресату одним шаблоном». Разным
    девушкам оно не мешало — тройки-то разные, — и один и тот же текст мог прийти
    человеку дважды, от Дианы и от Екатерины.

    Внутри одного захода этого не случалось: каждый адресат получает одно письмо
    за проход. Но заходов много — круг добирает пул по расписанию, — и на втором
    человек снова оказывался свободен, только уже для другой анкеты.

    Со стороны получателя это и есть **выданное агентство**: два одинаковых письма
    от двух незнакомок. Тот же довод, по которому собеседники уникальны в пуле
    инвайтов (`invite.py`).

    ⚠ **Разные шаблоны от разных девушек — по-прежнему можно.** У них разный
    текст, и второе письмо читается как ещё одно знакомство, а не как копия.

    ## ⚠⚠ Ответившему письмом рассылки не бывает — и анкету отнимает его ответ

    Он написал этой девушке письмо, значит холодное обращение состоялось и
    кончилось: дальше разговор ведёт «приставание» (`favorite_mail`), которое
    пишет **по переписке**, а рассылка пишет как незнакомой. Отнимает она при этом
    **анкету, а не адресата** — третье правило того же вида, что запрет и
    возрастное окно: другая наша девушка ему не писала, и для неё обращение
    законно.
    """
    blocked = blocked or set()
    spent = spent or set()
    talked = talked or set()
    answered = answered or set()

    for person in people:
        free = [(girl, template) for girl in girls for template in templates
                if (girl['id'], person['uid'], template['id']) not in taken
                and (person['uid'], template['id']) not in spent
                and (girl['id'], person['uid']) not in blocked
                and (girl['id'], person['uid']) not in answered
                # ⚠⚠ **Возрастное окно отнимает анкету, а не адресата** — ровно
                # как запрет строкой выше. Ему тридцать пять, ищет он
                # сорокалетних: письмо напишет та наша девушка, чей возраст в
                # окно попадает, а не ни одна. Проверь мы возраст после выбора
                # пары — случай раз за разом выпадал бы на негодную анкету, и
                # человек остался бы без письма при годной рядом.
                and mail_age_fits(girl, person,
                                  (girl['id'], person['uid']) in talked)]
        if not free:
            continue

        yield (*random.choice(free), person)


async def _body(template: dict, girl: dict, person: dict, known: list,
                girl_values: dict, site_id: int) -> tuple:
    """Готовый текст письма. Вторым — причина, по которой письма не будет.

    Собирает значения из трёх источников по `source` переменной:

      `profile`   — из значений анкеты;
      `companion` — из карточки адресата;
      `live`      — спрашивается у агента, под эту самую пару.

    ⚠ **Дешёвое считается первым, `live` — последним.** Это не порядок ради
    порядка: `live` стоит вызова LLM, а `profile` и `companion` лежат в памяти.
    Спроси мы агента раньше проверки — платили бы за письмо, которое всё равно не
    уйдёт из-за незаполненного `girl_name`.

    Поймано живым прогоном: 157 пар, восемь с половиной минут и ноль писем.

    ⚠ **`live` спрашивается только если шаблон на него ссылается** — по той же
    причине: вызов ради переменной, которой в тексте нет, это плата за воздух.

    ## ⚠⚠ Живой вопрос спрашивается не в каждом письме, и жребий здесь, а не в шаблоне

    Персональный вопрос стоит **вызова LLM на каждого адресата**: замер на проде —
    ноль секунд на письмо без него и одиннадцать с ним. Доля задана настройкой
    `mailing_question_percent`.

    ⚠ **Бросать жребий при написании шаблона было ошибкой.** Сперва так и было:
    выпало — шаблон получал метку, и дальше **каждое** письмо по нему платило за
    вызов; не выпало — не платило ни одно. Доля означала «в скольких шаблонах»,
    а человек читал её как «в скольких письмах», и читал правильно: настройка
    про деньги, а деньги тратятся на письмо.

    Теперь шаблон несёт метку всегда, а решение принимается здесь, по каждому
    письму: выпало — спрашиваем агента; не выпало — **вырезаем абзац с меткой**
    (`mail_mark_drop`) и не платим ничего.
    """
    used = set(mail_vars_found(template['body']))
    values = dict(girl_values)

    live = []
    for var in known:
        name = var['name']
        if name not in used or var['source'] == 'profile':
            continue

        if var['source'] == 'companion':
            values[name] = _from_person(name, person, var)
        elif var['source'] == 'live':
            live.append(name)

    # Проверяем то, что уже известно: `live` в этот счёт не идёт — его ещё не
    # спрашивали, и «не хватает» про него было бы неправдой.
    missing = [name for name in mail_missing(template['body'], values)
               if name not in live]
    if missing:
        return '', f"{MAILING_SKIP_FREE}: {', '.join(missing)}"

    if not live:
        return mail_render(template['body'], values), ''

    # ⚠⚠ **Карточку адресата заводим ВСЕГДА — до жребия и до всякой платы.**
    #
    # Это два разных дела, и путать их нельзя: карточка — строка из ленты, она уже
    # в памяти и стоит запроса в базу; описание — поход браузером на 50 секунд.
    #
    # Однажды их уже путали: карточку заводил сам сбор описания, и она была у
    # одного адресата из пяти. В карточках писем имя адресата ссылается на его
    # страницу у нас, и ссылка вела в никуда чаще, чем куда-нибудь.
    #
    # Второй раз это вернулось, когда вопрос стал жребием: `_card` ушла под `if
    # ask`, и вместе с походом перестала заводиться карточка. На проде — 55
    # карточек на 100 писем в пуле. Поэтому бесплатная часть стоит здесь, отдельно
    # и безусловно.
    await _from_feed(site_id, person)

    # ⚠⚠ **Анкета собеседника снимается здесь же — и только когда пора.**
    #
    # Раньше за ней ходили браузером, по пять человек за заход: 12 секунд на
    # каждого и половина неудач. Теперь это обычный GET под сессией анкеты — доли
    # секунды, — и лимит стал не нужен: сколько людей в работе, столько и снимем.
    #
    # Когда идти, решает `companion_about_due`: нового снимаем всегда, снятого —
    # когда выйдет срок сайта (`companion_about_every`, две недели по умолчанию).
    # Отдельного круга обновления нет и не нужно: человек попал в работу — заодно и
    # проверили, не устарела ли его анкета.
    await _about_fresh(site_id, person, girl)

    # ⚠ Жребий на каждую живую переменную отдельно: их бывает несколько, и «одна
    # монета на все» означала бы, что доля считается не по вопросам, а по письмам
    # с вопросами — то есть опять не то, что написано в настройке.
    body, ask = template['body'], []
    chance = await _question_chance(site_id)
    for name in live:
        if random.random() < chance:
            ask.append(name)
        else:
            body = mail_mark_drop(body, name)

    if not ask:
        # Платного не осталось: ни похода на сайт за карточкой, ни вызова агента.
        return mail_render(body, values), ''

    # ── Дальше платное: сначала сайт, потом агент ────────────────────────────
    #
    # ⚠ **Агенту нужна карточка, а не запись ленты.** Лента даёт имя, фото и
    # номер — по ним вопроса про интересы не задашь. Описание живёт в
    # `companion`, и раньше оно до агента не доезжало вовсе: сюда
    # передавался `person` из ленты, у которого поля `about` нет и не бывает.
    # Собранные описания при этом лежали в базе и никуда не шли.
    card = await _card(site_id, person)

    for name in ask:
        values[name] = await mail_question(girl, site_id, card)

    missing = mail_missing(body, values)
    if missing:
        return '', f"агент не ответил: {', '.join(missing)}"

    # ⚠ Собираем из `body`, а не из `template['body']`: в нём уже вырезаны абзацы
    # тех живых переменных, которые в этот раз не спрашивали.
    return mail_render(body, values), ''


async def _question_chance(site_id: int) -> float:
    """Доля писем, в которых спрашиваем персональный вопрос у агента.

    ⚠ **Настройка про деньги, и читается она здесь — при сборке письма.** Каждое
    «да» это вызов LLM на адресата: одиннадцать секунд против нуля.

    ⚠ Ноль — законное значение и отличается от «настройки нет»: пустая строка даёт
    умолчание, «0» означает «никогда не спрашивать».
    """
    from src.dating.percent import percent_share

    return await percent_share(int(site_id), MAILING_QUESTION_SETTING,
                               MAILING_QUESTION_CHANCE)


async def _about_fresh(site_id: int, person: dict, girl: dict) -> None:
    """Снимает анкету собеседника, если её ещё нет или она устарела.

    ⚠ **Ничего не бросает.** Анкета — украшение письма, а не его условие: не
    снялась, и письмо уйдёт по тому, что известно. Причина уходит в журнал.

    ⚠ **Тишина, когда снимать нечего**: у большинства адресатов анкета свежая, и
    заход не должен об этом сообщать.
    """
    from src.dating.companion_about import (companion_about_collect,
                                            companion_about_due)
    from src.uvicorn.routers.dating.companion import companion_get

    uid = str((person or {}).get('uid') or '')
    if not uid:
        return

    try:
        if not await companion_about_due(site_id, await companion_get(site_id, uid)):
            return

        await companion_about_collect(girl, uid)
    except Exception as e:
        logger_info(f'[dating] анкета собеседника {uid} не обновилась: {e}')


async def _card(site_id: int, person: dict) -> dict:
    """Что известно об адресате — для агента, который сочиняет ему вопрос.

    Читает карточку из базы и кладёт сверху то, что знает лента.

    ## ⚠⚠ На сайт за описанием отсюда больше не ходят

    Ходили: у кого описания не было, за ним шли браузером — вход под девушкой,
    ~50 секунд на человека, — и это нормировала настройка `mailing_probe`.

    Убрано целиком, и довод заказчика прост: **описание у нас уже есть**, снятое
    однажды и лежащее в карточке. Ходить за ним на каждом наборе пула значит
    платить минутами за то, что и так в базе. Устареет — этим займётся отдельная
    работа, обходящая карточки по своему расписанию; набор писем ей не место.

    Что изменилось на деле — и что нет.

    **Карточка есть у каждого адресата**, и в ней имя и возраст (на проде: 376 из
    376), фото у большинства, город и страна примерно у половины. Всё это приходит
    из ленты и с самого сайта бесплатно — походом браузера добывалось **только**
    `about`, рассказ мужчины о себе.

    Его на проде имеют 139 карточек из 376. Остальным агент сочинит вопрос по
    имени, возрасту и месту. Это слабее вопроса по интересам, и это осознанный
    размен: пул набирается подстановкой, без минут ожидания у нажатой кнопки.

    ⚠ Сам сборщик (`companion_about.py`) на месте и рабочий — он понадобится той
    самой отдельной работе. Вызывающих у него сейчас нет.

    ⚠ **Заведение карточки сюда не входит.** Оно бесплатно (строка из ленты) и
    делается для каждого адресата выше, до жребия. Два дела здесь уже путали
    дважды, и оба раза кончалось одним: карточка была у одного адресата из пяти.
    """
    from src.uvicorn.routers.dating.companion import companion_get

    card = await companion_get(site_id, str(person.get('uid') or ''))

    # ⚠ Лента старше карточки в том, что знает обе: имя и фото она снимает каждые
    # две минуты, а карточка их помнит с первого раза. Поэтому сверху кладём ленту.
    return {**(card or {}), **{k: v for k, v in (person or {}).items() if v}}


async def _from_feed(site_id: int, person: dict) -> None:
    """Заводит карточку адресата и переносит в неё то, что знает лента.

    ⚠ **Пустое не пишем.** `companion_touch` правит только названное, и
    пустая строка из ленты затёрла бы то, что уже сняли со страницы анкеты.

    ⚠ **А вот саму карточку заводим и когда лента не дала ничего.** Строка нужна не
    ради полей: письмо ссылается на страницу адресата у нас, и адресат без строки —
    ссылка в никуда. Пустая карточка честнее её отсутствия: «этот человек есть, о
    нём пока ничего не знаем» — законный ответ, а «такой страницы нет» про того,
    кому мы прямо сейчас пишем письмо, выглядит поломкой.

    Тем же занимается щелчок по ленте на «Профилях» — но он бывает не всегда:
    адресата берут из пула, а не из ленты под рукой.
    """
    from src.uvicorn.routers.dating.companion import companion_touch

    extra = {name: value for name, value in
             (('name', person.get('name')), ('photo', person.get('photo')),
              ('age', person.get('age')))
             if value}

    await companion_touch(int(site_id), str(person.get('uid') or ''), **extra)


def _from_person(name: str, person: dict, var: dict) -> str:
    """Значение `companion`-переменной из карточки адресата.

    ⚠ **По суффиксу имени, а не по точному совпадению.** Переменные зовут
    `companion_name`, `his_city`, `name` — как решил человек. Гадать по всему имени
    бессмысленно, а вот хвост после последнего подчёркивания совпадает с полем
    карточки почти всегда.

    Не нашлось — умолчание реестра; нет и его — пусто, и письмо не уйдёт. Это
    правильный исход: подставить наугад значило бы отправить чужие данные.
    """
    fields = mailing_person_fields(person)
    key = mailing_person_key(name, fields)
    value = fields.get(key)

    # ⚠ **Обращение по имени, а не по имени с фамилией.** Сайт отдаёт `name`
    # целиком — «Semen Gorbunkov», — и письмо, начинающееся «Hi Semen Gorbunkov»,
    # читается как рассылка из базы, чем оно и является. Поэтому у `…_name` в дело
    # идёт разобранное первое слово, если оно есть.
    #
    # ⚠ **Правим подстановку, а не тексты шаблонов**, и это не лень. Замени мы
    # `[[companion_name]]` на `[[companion_firstName]]` в девяти готовых письмах —
    # адресатам с именем одним словом («Kevin») подставлять стало бы нечего:
    # `firstname` у них пуст намеренно (`people_name_parts`), нехватка
    # переменной останавливает отправку, и письмо не ушло бы вовсе. Здесь же пустой
    # разбор просто оставляет прежнее поведение.
    if key == 'name' and str(fields.get('firstname') or '').strip():
        value = fields['firstname']

    if value in (None, '', 0):
        return str(var.get('default_value') or '')

    return str(value)


