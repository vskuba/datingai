# Как часто круг просыпается. Минута — как у расписания анкет: смены заданы с
# точностью до четверти часа, и чаще смотреть нечего.
#
# ⚠ Тик — это не частота набора. Набор ограничен своим сроком (`mailing_every`), и
# большинство тиков внутри смены не делают ничего, кроме чтения отметки в Redis.
MAILING_ROUND_TICK_SEC = 60

# Как часто добираем пул внутри смены, если настройки сайта нет. Полчаса: за это
# время лента онлайна успевает смениться (она снимается раз в две минуты), и новые
# адресаты появляются.
MAILING_EVERY_DEFAULT = 1800

# Настройка сайта, задающая эту частоту.
MAILING_EVERY_SETTING = 'mailing_every'

# Сколько неотправленных писем держим в пуле, если настройки сайта нет.
#
# ⚠ **Это запас, а не скорость.** Круг добирает пул, пока в нём не станет столько
# черновиков, и на этом останавливается: письма ждут человека, который их прочтёт,
# и складывать их тысячами незачем — устареют раньше, чем дойдёт очередь.
MAILING_POOL_MAX_DEFAULT = 50

# Жёсткий потолок поверх настройки: значение правят руками, и «5000» превратило бы
# каждый заход круга в часы работы LLM.
MAILING_POOL_MAX = 500

# Настройка сайта, задающая размер пула.
MAILING_POOL_SETTING = 'mailing_pool_max'

# Отметка «этому сайту только что набирали». Живёт ровно свой срок и гаснет сама.
MAILING_ROUND_KEY = 'dating:mailing:round:{id}'


async def mailing_round_run(offset_hours: int = 0) -> dict:
    """Один круг: добрать пул тем сайтам, у кого идёт смена и вышел срок.

    Args:
        offset_hours: часовое смещение панели (настройка `timezone`). Расписание
            задано местным временем, а сервер живёт по UTC.

    Returns:
        dict: `checked` — сколько сайтов с включённым расписанием посмотрели,
        `ran` — скольким набирали, `made` — сколько писем готово всего.
    """
    sites = await _sites()
    ran = made = 0
    for _, result in await round_sites_run(sites, offset_hours=offset_hours,
                                         gate=_gate, every=_every, work=_work,
                                         key=MAILING_ROUND_KEY, what='рассылке'):
        if result is not None:
            ran += 1
            made += int(result['made'])

    if ran:
        logger_info(f'[dating] круг рассылки: сайтов {ran}, писем {made}')

    return {'checked': len(sites), 'ran': ran, 'made': made}


# ── Приватное ────────────────────────────────────────────────────────────────

async def _gate(site: dict, minutes: int) -> bool:
    """Сайт сейчас нуждается в доборе: идёт смена и вышел срок.

    Смена идёт? Пустое расписание — это «нет», а не «всегда»: правило общее с
    расписанием анкеты, и толковать его иначе значило бы включить
    круглосуточную рассылку всем, кто смены не заводил.

    ⚠ Сбой — не идём, общим правилом `round_slot_due`: лишний заход это вызовы
    LLM и письма живым людям.
    """
    if not schedule_now(json_column_list(site['schedule']), minutes):
        return False

    return round_slot_due(MAILING_ROUND_KEY, int(site['site_id']), 'рассылке')


async def _work(site: dict, minutes: int) -> dict | None:
    """Добирает пул; заход, который ничего не сделал, слот не держит.

    ⚠ **Заход впустую слот не занимает.** Отметка стоит для того, чтобы
    набор не шёл чаще, чем просили, — а набора не было. Держи мы её все
    полчаса, человек, очистивший пул сразу после такого захода, ждал бы
    писем до конца чужого срока и решил бы, что рассылка сломана. Ровно
    это и случилось.

    ⚠ Отпускаем **только когда делать было нечего** (пул полон, шаблонов
    нет). Сорванный набор слот держит: причина обычно не рассосётся за
    минуту, а повтор стоит вызовов LLM.

    ⚠ **Заход, потративший себя на нехватку переменных, слот не держит.**
    Полчаса — это срок для захода, который сделал, что просили. Живой
    случай повторился дважды: причину нашли и починили, а пул ещё полчаса
    стоял на семи письмах — «сгенерировало и зависло». Держать слот после
    такого значит наказывать за исправление. «Не хватает переменных»
    решается до всякого похода — ни LLM, ни сайта; «агент не ответил» уже
    стоило вызова, и такой заход слот держит, как и раньше.
    """
    site_id = int(site['site_id'])
    result, idle = await _make(site_id)
    if result is None:
        if idle:
            round_slot_release(MAILING_ROUND_KEY, site_id, 'рассылке')

        return None

    if _skipped_for_free(result):
        round_slot_release(MAILING_ROUND_KEY, site_id, 'рассылке')

    return result


def _skipped_for_free(result: dict) -> bool:
    """Заход пропустил больше, чем сделал, и не потратил на это ничего.

    Оба условия обязательны, и каждое отвечает за свою беду:

      **больше пропущено, чем сделано** — иначе слот отпускался бы после
      здорового захода, где один адресат из полусотни оказался безымянным.
      Такой заход своё отработал: пул набран, ждать положено;

      **пропуски бесплатные** — «не хватает переменных» решается до похода к
      агенту и на сайт, и повтор через минуту не стоит ничего. «Агент не
      ответил» уже стоило вызова LLM на каждую пару, и такой заход слот держит:
      причина не рассосётся за минуту, а круг сжёг бы вызовы впустую.

    ⚠ **Разбираем причину строкой, а не кодом отказа.** Причина эта живёт ради
    человека — её показывает кнопка и пишет журнал, — и заводить рядом второй,
    машинный, набор значило бы держать два списка в согласии. Метка вынесена в
    `MAILING_SKIP_FREE`, так что «согласие» проверяет импорт.

    Args:
        result: итог `mailing_make` — `made`, `skipped`, `reasons`.

    Returns:
        bool: `True` — слот держать не за что, пусть следующий тик попробует
        снова. ⚠ Пустой список причин при непустом `skipped` читается как
        «не знаем, за что платили» и слот **держит**: причины хранятся первыми
        пятью, и молчание тут значит незнание, а не бесплатность.
    """
    from src.dating.mailing import MAILING_SKIP_FREE

    skipped = int(result.get('skipped') or 0)
    if not skipped or skipped <= int(result.get('made') or 0):
        return False

    reasons = result.get('reasons') or []

    return bool(reasons) and all(str(why).startswith(MAILING_SKIP_FREE)
                                 for why in reasons)


async def _sites() -> list[dict]:
    """Сайты с включённым расписанием рассылки и сами смены."""
    return await round_sites(flags=('mailing_schedule_on',),
                             schedule='mailing_schedule', what='рассылке')


async def _every(site_id: int) -> int:
    """Как часто добирать пул этому сайту, в секундах."""
    return int(await site_seconds(site_id, MAILING_EVERY_SETTING)
               or MAILING_EVERY_DEFAULT)


async def _make(site_id: int) -> tuple[dict | None, bool]:
    """Набор пула по всем включённым шаблонам сайта.

    Returns:
        tuple: `(итог, впустую)`. `итог` — `None`, если писем не готовили;
        `впустую` — **делать было нечего** (пул полон, шаблонов нет), в отличие от
        «пытались и сорвалось». Разница решает, держать ли слот: см. вызывающего.

    ⚠ **Шаблоны берутся все включённые.** Выбирать здесь некому: круг работает,
    пока человека нет у экрана. Отсюда и смысл галочки «участвует в рассылке» у
    шаблона — она и есть выбор, сделанный заранее. Дальше выбор делает `_pairs`:
    каждой анкете из этого списка живёт только её полоса (`mail.profile_id`).

    ⚠ **Добираем до потолка, а не фиксированную порцию.** Пул — это запас готовых
    писем (`mailing_pool_max`, обычно 50): в нём должно лежать столько
    неотправленных, и не больше. Набирай круг по порции каждый заход — пул рос бы
    без предела, пока отправка не поспевает, и человек читал бы письма, написанные
    вчера про тех, кто давно ушёл с сайта.
    """
    templates = await mailing_templates(site_id)
    if not templates:
        return None, True

    # ⚠ Сперва убираем черновики ушедших анкет, и только потом считаем место:
    # письмо от анкеты не в сети отправить некому (отправка ждёт её), а потолок
    # пула — **на сайт**, и такие письма держат его за всех (`pool.py`).
    await pool_sweep(site_id)

    # ⚠⚠ И письма тем, кто за это время **ответил письмом**: отправка их больше не
    # берёт (`send_round._oldest`), а место в пуле они держат — то есть сами по
    # себе они и есть та мертвечина, из-за которой пул однажды встал «полным».
    # Тоже **до** счёта места, и по той же причине.
    await pool_sweep_mail_answered(site_id)

    # Сколько уже готово и сколько ещё нужно.
    have = await _pool_size(site_id)
    cap = await _pool_max(site_id)
    need = cap - have

    if need <= 0:
        return None, True

    # ⚠⚠ **Добираем до потолка за один заход, а не порциями.**
    #
    # Порция (`mailing_batch`) была заведена, когда личный вопрос требовал вызова
    # LLM на **каждое** письмо: полный проход по всем, кто онлайн, длился десятки
    # минут и вылезал за смену. С тех пор вопрос стал жребием на письмо
    # (`mailing._body`), и письмо без него собирается подстановкой — нисколько.
    # Замер на проде: полсотни писем одним заходом за считанные секунды.
    #
    # Порция при этом отвечала на тот же вопрос, что и `mailing_pool_max`, вторым
    # голосом: человеку приходилось держать в голове, какое из двух чисел
    # сработает первым. Осталось одно правило — **пул набирается до потолка**.
    #
    # ⚠ Жёсткий предел в коде остаётся (`MAILING_BATCH_MAX`): он не настройка, а
    # страховка от потолка пула, выставленного руками в «5000».
    limit = min(need, MAILING_BATCH_MAX)

    try:
        result = await mailing_make(site_id, templates, limit)
    except Exception as e:
        logger_info(f'[dating] рассылка сайта #{site_id}: {e}')

        # ⚠ Сорванный набор — **не «впустую»**: слот держим. Причина (сосед лёг,
        # сайт не пускает) обычно не рассосётся за минуту, а повтор стоит вызовов
        # LLM на каждое письмо.
        return None, False

    if result['made'] or result['skipped']:
        # ⚠ **Пропуски идут с причиной.** Голое «пропущено 25» — это число без
        # ответа на «почему», и живой случай показал цену: половина писем не
        # готовилась, потому что у трёх анкет не заполнен `girl_name`, а по
        # журналу это выглядело как «круг работает, писем нет». Причину набор и
        # так возвращает — кнопка её показывает человеку, круг молчал.
        why = '; '.join(result['reasons'])
        logger_info(f"[dating] рассылка сайта #{site_id}: готово {result['made']}, "
                    f"пропущено {result['skipped']}, осталось {result['left']}"
                    + (f' — {why}' if why else ''))

    return result, False


async def _pool_max(site_id: int) -> int:
    """Сколько неотправленных писем держим в пуле у этого сайта."""
    return min(int(await site_seconds(site_id, MAILING_POOL_SETTING)
                   or MAILING_POOL_MAX_DEFAULT), MAILING_POOL_MAX)


async def _pool_size(site_id: int) -> int:
    """Сколько писем ждёт отправки прямо сейчас.

    ⚠ Считаем только `draft`: ушедшие и не ушедшие места в пуле не занимают —
    первые уже сделали своё дело, вторые больше не пойдут.

    ⚠⚠ **И только без причины отказа (`error = ''`), и это правка живой беды.**
    Круг отправки строки с причиной не берёт **никогда** (`send_round._oldest`):
    такое письмо ждёт человека с кнопкой. Для потолка же оно было обычным
    черновиком — и пул, набитый отказами, означал «мест нет», хотя отправлять
    было нечего.

    Замер на проде 03.10.2026: 100 черновиков при потолке 100, из них живых 17,
    остальные 83 — «у получателя переполнен ящик за этот час». Рассылка стояла
    сутки: набор видел полный пул, отправка — семнадцать писем.

    Сам этот отказ больше писем не хоронит (`mail_wait.py`), но правило верно и
    без него: место в пуле — это **готовое к отправке**, а не «лежащее».
    """
    async with mysql_get_db_async() as db:
        await db.execute(
            "SELECT COUNT(*) AS n FROM mailing"
            " WHERE site_id = %s AND status = 'draft' AND error = ''",
            (int(site_id),))
        row = await db.fetchone()

    return int((row or {}).get('n') or 0)
