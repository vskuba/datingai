"""Близнецы в переписке: одна реплика, записанная двумя дорогами.

## ⚠⚠ Откуда они берутся

Наше исходящее сообщение попадает в `message` **дважды**:

1. в момент отправки — своей строкой с ULID в `message_uid` (`send.py`);
2. при следующем заходе импорта из панели агентства — строкой с номером сайта
   (`panel:52447706`, `chat_panel.py`).

Защита от повторов у импорта есть (`INSERT IGNORE` по паре анкета + `message_uid`),
но здесь она бессильна: **ключи разные**. В `chat_panel.py` это записано прямо —
«у сокета `message_uid` это ULID кадра, у панели свой числовой номер… столкнуться
им негде». Для случайного столкновения это верно и хорошо. Но та же разность не
даёт узнать **нашу собственную** реплику, вернувшуюся из журнала сайта.

Живой случай: Elena → Henry, четыре пары строк за полчаса, у каждой одинаковый
текст и одинаковая секунда.

## ⚠⚠ Собеседнику при этом уходит ОДНО сообщение

Проверено на проде: у журнала самого сайта (`source = 'panel'`) нет ни одного
случая, где один наш текст записан дважды. Значит сайт принял реплику один раз, и
двоится только наша таблица. Это важно понимать, прежде чем чинить: соблазн
«убрать лишнюю отправку» ведёт искать несуществующую ошибку в `send.py`.

## Что делает этот отсев

Прячет близнеца при **чтении**: из группы «та же анкета, тот же собеседник, то же
направление, тот же текст, та же секунда» показывается строка с наименьшим `id`.

⚠ **Наименьший — это наша,** записанная в момент отправки: импорт всегда приходит
позже. А там, где нашей строки нет вовсе (история, привезённая из панели за
прошлые недели), наименьшей окажется сама панельная — и она останется видимой.
Отсев не знает про источники и нарочно: правило «показываем первую запись
события» верно независимо от того, сколько дорог его записали.

## ⚠ Почему отсев в SQL, а не в Python

Из-за `LIMIT`. Отсеяв после выборки, мы бы просили десять последних реплик, а
показывали восемь — и предпросмотр диалога терял бы строки тем чаще, чем больше
в нём близнецов.

## ⚠ Почему секунда входит в ключ

Без неё «ok» вчера и «ok» сегодня слились бы в одну реплику: люди повторяются, и
короткие ответы повторяются особенно. С ней для слияния нужно, чтобы тот же текст
тому же человеку ушёл дважды **в одну секунду**, а это уже не разговор, а сбой.
"""

# Условие для `WHERE`: строка показывается, если она первая в своей группе.
#
# ⚠ Подставляется в запрос подстановкой имени таблицы (`{t}`), а не параметром:
# имя таблицы параметром не передать. Значение приходит из кода, не от человека.
#
# ⚠ Индекс `idx_dating_message_time (profile_id, sender_uid, created_at, id)`
# закрывает поиск близнеца целиком: сравнение текста достаётся считанным строкам
# той же секунды.
MESSAGE_TWIN_SKIP = (
    ' AND NOT EXISTS (SELECT 1 FROM message twin'
    '                  WHERE twin.profile_id = {t}.profile_id'
    '                    AND twin.sender_uid = {t}.sender_uid'
    '                    AND twin.created_at = {t}.created_at'
    '                    AND twin.direction = {t}.direction'
    '                    AND twin.text = {t}.text'
    '                    AND twin.id < {t}.id)')


def message_twin_skip(table: str = 'message') -> str:
    """Кусок `WHERE`, прячущий вторую запись той же реплики.

    Args:
        table: как называется таблица в запросе — имя или псевдоним (`m`).

    Returns:
        str: условие, начинающееся с ` AND`. Приклеивается к готовому `WHERE`.

    ⚠ **Зовут все, кто показывает переписку человеку.** Своя копия условия
    разошлась бы с этой на первой же правке, и одна страница показывала бы
    близнецов, а другая нет — разницу списали бы на «подвисло».
    """
    return MESSAGE_TWIN_SKIP.format(t=str(table or 'message'))
