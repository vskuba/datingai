"""Близнецы в переписке: одна реплика, записанная двумя дорогами.

## ⚠⚠ Откуда они берутся

Наше исходящее сообщение попадает в `message` **дважды**:

1. в момент отправки — своей строкой с ULID в `message_uid` (`send.py`);
2. при следующем заходе импорта из панели агентства — строкой с номером сайта
   (`panel:52447706`, `chat_panel.py`).

Защита импорта от повторов (`INSERT IGNORE` по паре анкета + `message_uid`) здесь
бессильна: **ключи разные**. Для случайного столкновения это и хорошо, но узнать
свою собственную реплику, вернувшуюся из журнала сайта, так нельзя.

## ⚠⚠ Собеседнику при этом уходит ОДНО сообщение

Проверено на проде: у журнала самого сайта нет ни одного случая, где один наш
текст записан дважды. Сайт принял реплику один раз, двоится только наша таблица.
Это важно понимать, прежде чем чинить: соблазн «убрать лишнюю отправку» ведёт
искать несуществующую ошибку в `send.py`.

## Что считается близнецом

Строка **из панели**, для которой есть строка **не из панели** с тем же
собеседником, направлением и текстом, записанная примерно в то же время.

⚠ **Источник в правиле, а не «оставляем строку с меньшим номером».** Первая
редакция брала наименьший `id`, и это молча ломалось бы на двух панельных строках
подряд: человек, написавший одно и то же дважды через сайт агентства, увидел бы
одну реплику вместо двух. Теперь прячется только отражение — своя запись остаётся
всегда, а две панельные друг друга не трогают.

## ⚠⚠ Время сравнивается с допуском, и вот почему

Время у строк **разное по природе**: своё мы ставим по нашим часам в момент
отправки, панель отдаёт отметку сайта. Замерено на проде по пáрам, сопоставленным
текстом:

| Расхождение | Пар |
|---|---|
| 0 секунд | 11 |
| 1 секунда | 1 |
| **7 секунд** | 1 |

Первая редакция требовала совпадения **секунда в секунду** и пару с расхождением
не узнавала — дубли Diana → Henry пережили починку именно поэтому.

⚠ Ошибка была не только в правиле, но и в **замере**: он требовал совпадения
текста и потому видел лишь те пары, что уже совпадали. Выборка отобрала сама
себя, и «9 из 9 сошлись посекундно» звучало убедительно, будучи бессмыслицей.

## ⚠⚠ Панель режет текст на 256 знаках — и обрезок тоже близнец

Журнал агентства отдаёт сообщение **обрезанным**: замер на проде 02.11.2026 —
у всех 512 панельных строк `CHAR_LENGTH(text)` не больше 256, тогда как у наших
доходит до 1532. Сравнение текстов **равенством** на такой паре не срабатывает:
278 ≠ 256, импорт считает строку новой, показ её не прячет. На экране — две
строки одной реплики, вторая оборвана на полуслове (Yekaterina → Frank, 02.11
12:18; таких пар накопилось шесть, и все шесть — отражения наших же отправок).

Поэтому сравнивается не весь наш текст, а его **начало длиной среза**:
`RTRIM(LEFT(twin.text, 256)) = RTRIM(panel.text)`.

⚠ **Именно срез, а не любой префикс.** «Начало совпало» как правило съело бы
короткую реплику: панельное «Ok» спрятал бы наш «Ok, let us meet tomorrow» той же
секунды. `LEFT(…, 256)` короче нашего текста не делает ничего — для реплик до
среза условие остаётся прежним равенством.

⚠⚠ **`RTRIM` обязателен, и вот почему.** Обрезок бывает и **255** знаков:
разбор панели зовёт `.strip()` (`chat_panel._text`), и пробел, на который попал
срез, пропадает. Живой случай — строка 684180 при нашей в 355 знаков. Правило
«длина ровно 256» такую пару не узнаёт, а `RTRIM` с обеих сторон — узнаёт, не
полагаясь на то, как сравнивает хвостовые пробелы сличение колонки.

## ⚠ Допуск только у исходящих

У входящих близнецов на проде **нет ни одного** — сайт без сокета, и реплики
собеседника приходят единственной дорогой. Зато входящие в одну секунду бывают
настоящими: человек пишет очередью, до пяти реплик. Поэтому им оставлен прежний
строгий ключ: показать лишнюю строку неприятно, а съесть чужую реплику — беда.

Появится сайт с сокетом — входящие тоже станут приходить двумя дорогами, и это
место придётся пересмотреть **вместе с замером**, а не по аналогии.
"""

# Допуск по времени у исходящих, секунды. Замеренный разброс — до семи; берём
# с запасом, но далеко от того, чтобы слиться могли две разные реплики: для этого
# один и тот же текст должен уйти одному человеку дважды за минуту, а такое
# отсекает `send._said_already` ещё до отправки.
MESSAGE_TWIN_WINDOW_OUT = 60

# У входящих допуска нет: очередь реплик в одну секунду — обычное дело.
MESSAGE_TWIN_WINDOW_IN = 0

# Где журнал панели режет текст, в знаках. Замер на проде 02.11.2026: длиннее
# этого панельных строк нет ни одной (512 строк), а наших — четверть сотни.
# ⚠ В знаках, а не в байтах: строка 487249 — 256 знаков при 258 байтах.
MESSAGE_TWIN_PANEL_CUT = 256


def message_twin_skip(table: str = 'message') -> str:
    """Кусок `WHERE`, прячущий отражение реплики из панели.

    Args:
        table: как называется таблица в запросе — имя или псевдоним (`m`).

    Returns:
        str: условие, начинающееся с ` AND`. Приклеивается к готовому `WHERE`.

    ⚠ **Зовут все, кто показывает переписку человеку.** Своя копия условия
    разошлась бы с этой на первой же правке, и одна страница показывала бы
    близнецов, а другая нет — разницу списали бы на «подвисло».

    ⚠ Отбор по времени написан через `BETWEEN`, а не `TIMESTAMPDIFF`: первое
    ложится на индекс `(profile_id, sender_uid, created_at, id)` диапазоном,
    второе заставило бы читать все реплики диалога.
    """
    t = str(table or 'message')

    return (
        f" AND NOT ({t}.source = 'panel' AND EXISTS ("
        '   SELECT 1 FROM message twin'
        f'    WHERE twin.profile_id = {t}.profile_id'
        f'      AND twin.sender_uid = {t}.sender_uid'
        f'      AND twin.direction = {t}.direction'
        # ⚠ Не равенство: панель режет текст, и обрезок равным не будет.
        f'      AND RTRIM(LEFT(twin.text, {MESSAGE_TWIN_PANEL_CUT}))'
        f' = RTRIM({t}.text)'
        "      AND twin.source <> 'panel'"
        f'      AND twin.created_at BETWEEN {t}.created_at'
        f"           - INTERVAL IF({t}.direction = 'out',"
        f'                         {MESSAGE_TWIN_WINDOW_OUT},'
        f'                         {MESSAGE_TWIN_WINDOW_IN}) SECOND'
        f'        AND {t}.created_at'
        f"           + INTERVAL IF({t}.direction = 'out',"
        f'                         {MESSAGE_TWIN_WINDOW_OUT},'
        f'                         {MESSAGE_TWIN_WINDOW_IN}) SECOND))')


def message_twin_absent(direction: str) -> str:
    """Условие «такой реплики ещё нет» — для вставки из панели агентства.

    Args:
        direction: направление вставляемой строки; от него зависит допуск.

    Returns:
        str: кусок `WHERE`, начинающийся с ` AND`. Ждёт четыре значения: анкета,
        собеседник, текст, время (время — дважды, на обе границы допуска).

    ⚠ **Ставится в `INSERT … SELECT`, а не проверяется отдельным запросом.** Между
    проверкой и вставкой успевает пройти другой заход импорта, и дубль появился бы
    ровно в ту щель, которую мы закрываем.

    ⚠ **То же определение близнеца, что и у показа.** Разойдись они — импорт счёл
    бы строку новой, а страница спрятала бы её как двойника, и реплика пропала бы
    с экрана совсем.
    """
    window = _window(direction)

    return (
        ' AND NOT EXISTS ('
        '   SELECT 1 FROM message twin'
        '    WHERE twin.profile_id = %s'
        '      AND twin.sender_uid = %s'
        f"      AND twin.direction = '{'out' if str(direction) == 'out' else 'in'}'"
        # ⚠ Не равенство: панель режет текст, и обрезок равным не будет.
        f'      AND RTRIM(LEFT(twin.text, {MESSAGE_TWIN_PANEL_CUT})) = RTRIM(%s)'
        "      AND twin.source <> 'panel'"
        "      AND twin.created_at BETWEEN COALESCE(NULLIF(%s, ''), NOW())"
        f'           - INTERVAL {window} SECOND'
        "        AND COALESCE(NULLIF(%s, ''), NOW())"
        f'           + INTERVAL {window} SECOND)')


def _window(direction: str) -> int:
    """Допуск по времени для этого направления, секунды."""
    return (MESSAGE_TWIN_WINDOW_OUT if str(direction) == 'out'
            else MESSAGE_TWIN_WINDOW_IN)
