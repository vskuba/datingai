"""Круг админ-панели: сессия агентства держится живой круглые сутки.

Раз в `PANEL_ROUND_TICK_SEC` обходит сайты с заданным адресом панели
(`admin_url`) и у тех, чей срок вышел, спрашивает панель одним GET по сохранённым
cookie. Не признала — заходит сценарием и спрашивает снова.

## ⚠ Расписания здесь нет, и это не упущение

Прочие круги спят по сменам сайта: письма и инвайты уходят живым людям, и слать их
ночью незачем. Панель — наша собственная страница агентства, и вопрос к ней один:
жива ли сессия. Она должна быть жива **всегда** — в том числе в три часа ночи,
когда придёт круг импорта переписки.

## ⚠ Когда ходили — помним в Redis

Смена держателя перезапускается (свой срок, деплой, перезапуск воркера), и память
процесса сбрасывалась бы вместе с ней: после каждого перезапуска круг спрашивал бы
все панели заново. Тот же приём, что у забора писем и звёздочек.

## ⚠ Сайты обходятся по одному

Проверка дешева, а вот вход — вкладка Chromium у соседа. Две панели, у которых
сессия истекла разом, дали бы два одновременных прогона; у соседа они всё равно
встанут в очередь (`rhapsody_api_scenario_run` держит замок), но уже после того,
как мы обещали себе параллельность.
"""

from logging_.logging_ import logger_info

from src.dating.feed import feed_write
from src.dating.round import (round_slot_due,
                            round_slot_mark)
from src.dating.panel import (panel_every, panel_keep,
                                     panel_sites)

# Как часто круг просыпается. ⚠ Не частота проверки: её задаёт `admin_every`, а
# минута — мельчайший из его вариантов.
PANEL_ROUND_TICK_SEC = 60

# Отметка «эту панель только что спрашивали». В Redis — переживает смену держателя.
PANEL_ROUND_KEY = 'dating:panel:round:{id}'


async def panel_round_run() -> dict:
    """Один круг: спросить панели, чей срок вышел.

    Returns:
        dict: `sites` — сколько панелей спросили, `online` — сколько живы,
        `logged_in` — сколько пришлось заводить входом сценарием.
    """
    ran = online = logged = 0

    for site_id in await panel_sites():
        # ⚠ Сбой — молчим: лишний заход может кончиться вкладкой Chromium.
        if not round_slot_due(PANEL_ROUND_KEY, site_id, 'панели'):
            continue

        # ⚠ Отметку ставим **до** захода: вход сценарием идёт десятками секунд, и
        # следующий тик завёл бы второй, пока идёт первый.
        round_slot_mark(PANEL_ROUND_KEY, site_id, await panel_every(site_id),
                        'панели')

        ran += 1
        answer = await panel_keep(site_id)

        if answer.get('logged_in'):
            logged += 1
            # ⚠ В ленту пишем **вход**, а не каждую проверку: проверка идёт раз в
            # пять минут и отвечает «всё по-прежнему», а вход — это событие, после
            # которого стоит посмотреть, не было ли перед ним отказов.
            feed_write(site_id, 'panel', 'Сессия админ-панели поднята заново')

        if answer.get('status') == 'online':
            online += 1
        else:
            feed_write(site_id, 'warn',
                              f"Админ-панель: {answer.get('error') or answer.get('status')}")
            logger_info(f"[dating] панель сайта #{site_id}: {answer.get('status')} "
                        f"— {answer.get('error')}")

    return {'sites': ran, 'online': online, 'logged_in': logged}


