"""Собеседники анкеты: разбор списков, которые снял сценарий сайта.

Два списка — **избранные** и **кто в сети**. Данные добывает RhapsodyAi: он входит
под анкетой в её кабинет на сайте и снимает карточки со страницы. Здесь только
разбор того, что он вернул.

## Почему это отдельно от собеседниц чата

`dating_contact` — те, с кем есть переписка: они пришли из чата и лежат в нашей
базе. Здесь другое: **кто есть на сайте прямо сейчас** и кого анкета отметила
избранным. Пересечение между списками есть, но смысл разный, и своей таблицы у
этих списков нет — их показывают и забывают.

## Что приходит от сценария

Карточка со страницы, поля названы по-русски (так названы шаги `extract_rows`):

    {"имя": "Vincent pitchen\\n,\\u00a0\\n49",
     "ссылка": "https://ladadate.com/profile/812886-men-from-france",
     "фото": "https://ladadate.com/content/photos/7f23711d….jpg",
     "статус_класс": "people__item-content people__item-online",
     "новый": "new"}

Имя приходит склеенным с возрастом через перевод строки и запятую — так его
отдаёт разметка сайта. Номер анкеты живёт **в ссылке**, отдельного поля под него
нет: `/profile/812886-men-from-france` → `812886`.

⚠ **Фотография бывает заглушкой.** Сайт грузит картинки лениво, и у первых
карточек в `src` успевает попасть `/images/placeholder-loading.svg`. Такое
значение отбрасываем: пустое поле страница покажет буквой имени, а заглушка
сайта — сломанной картинкой.
"""

from text_.text_emoji import text_emoji_same
import re

from src.dating.scenario_field import scenario_field

# Номер анкеты в ссылке. Два вида, потому что списки сняты с разных страниц:
# `/profile/812886-men-from-france` в кабинете и `/chat#181685` в чате.
PEOPLE_UID_RE = re.compile(r'/profile/(\d+)|#(\d+)')

# Номер фотографии как запасной ключ. У списка диалогов ссылка приходит голой
# (`/chat#`, без номера) — сайт открывает разговор скриптом, а не адресом. Тогда
# человека опознаём по имени файла фотографии: оно уникально и не меняется.
# `-s` в хвосте — размер миниатюры, и он не часть номера: в кабинете тот же
# человек приходит с полным `…4a.jpg`, а в чате с `…4a-s.jpg`. Не отсеки мы
# суффикс, один и тот же собеседник получил бы два разных ключа и показался бы
# в колонках дважды.
PEOPLE_PHOTO_UID_RE = re.compile(r'/([0-9a-f]{16,})(?:-[a-z0-9]+)?\.[a-z]+', re.I)

# Признак «в сети» в классе карточки. Ищем по подстроке, а не по точному классу:
# рядом с ним стоит `people__item-content`, и порядок сайт не гарантирует.
PEOPLE_ONLINE_MARK = 'people__item-online'

# Заглушка ленивой загрузки. Не адрес фотографии, а признак того, что картинка
# ещё не подгрузилась к моменту съёмки.
PEOPLE_PHOTO_STUB = 'placeholder'

# Длины, под которые режем: списки показываются в колонке шириной 150 пикселей,
# и мегабайт текста оттуда не нужен никому.
PEOPLE_NAME_MAX = 100
PEOPLE_UID_MAX = 64

# Скрытая строка-образец в разметке списка. Сайт держит её и заполняет скриптом;
# человеком она не является, а в список попадает наравне со всеми.
PEOPLE_TEMPLATE_NAMES = ('name, age', 'name , age', 'name')


def people_name_case(name: str) -> str:
    """Имя человека в нормальном виде: каждое слово с большой буквы, остальные
    строчные.

    Args:
        name: как отдал сайт — «VINCENT VEGA», «vincent», «ViNcEnT».

    Returns:
        str: «Vincent Vega». Пустое на входе — пустое на выходе.

    ## ⚠⚠ Зачем: имя уезжает живому человеку в реплику

    Сайт отдаёт имена как попало: часть людей пишет себя капсом, часть строчными.
    Имя подставляется в инвайт вместо метки (`invite._fill`) и уходит в чат:
    «Привет, VINCENT!» читается как крик, «привет, vincent» — как небрежность.
    Ни то ни другое не похоже на живую девушку.

    ## ⚠ Не `str.title()`

    `title()` ставит большую букву после любого не-буквенного знака, включая
    цифры: «vega3d» превратилось бы в «Vega3D». Здесь же заглавная ставится
    только там, где начинается **часть имени**.

    ## ⚠ Дефис и апостроф — тоже границы слова

    «anna-maria» → «Anna-Maria», «o'neill» → «O'Neill»: это составные имена, а не
    одно слово с чёрточкой, и человек ждёт заглавной в обеих половинах. Ошибиться
    здесь дешевле в другую сторону — «Isn'T» в настоящем имени не встречается, а
    «O'neill» встречается постоянно.

    ⚠ **Непонятное проходит нетронутым.** Имя из иероглифов (`許萊納` в ленте
    Ladadate) регистра не имеет: правило к нему просто не применяется.
    """
    # Каждая часть — от границы слова до следующей; разделители (пробел, дефис,
    # апостроф) остаются на месте.
    # ⚠ Эмодзи к одному виду: имя приходит снаружи, и люди ставят их прямо в
    # имя анкеты. Здесь же, потому что через эту воронку имя идёт со всех семи
    # дверей, которыми оно к нам попадает.
    return re.sub(r"[^\s\-']+",
                  lambda m: m.group(0)[:1].upper() + m.group(0)[1:].lower(),
                  ' '.join(text_emoji_same(str(name or '')).split()))


def people_rows(extract: dict, field: str) -> list[dict]:
    """Карточки со страницы — в наш вид.

    Args:
        extract: `extract` прогона сценария.
        field: имя шага, под которым лежат записи (`favorites`, `men`). Новое,
            латиницей — старое подставит `scenario_field`, пока сценарии не
            переименованы.

    Returns:
        list: записи `{uid, name, age, photo, online, is_new, link}`. Запись без
        номера пропускается: по нему её узнают, и пустой склеил бы разных в одну.
    """
    rows = scenario_field(extract, field)
    if not isinstance(rows, list):
        return []

    found, seen = [], set()
    for row in rows:
        if not isinstance(row, dict):
            continue

        link = str(scenario_field(row, 'link') or '').strip()
        photo = _photo(scenario_field(row, 'photo'))
        name, age = _name_age(scenario_field(row, 'name'))

        # Шаблон разметки, а не человек: сайт держит в списке скрытую строку-образец
        # и заполняет её скриптом. Отсекаем по тексту — своего признака у неё нет.
        if name.lower() in PEOPLE_TEMPLATE_NAMES:
            continue

        uid = _uid(link, photo, name)
        if not uid:
            continue

        uid = uid[:PEOPLE_UID_MAX]
        # Повтор в одном списке — не беда сайта, а следствие ленивой подгрузки:
        # карточка попадает в съёмку дважды. Показать одного человека двумя
        # строками хуже, чем потерять дубль.
        if uid in seen:
            continue
        seen.add(uid)

        found.append({'uid': uid,
                      # ⚠ Тот же разбор регистра, что у API сайта: источника два,
                      # а правило одно — иначе имя выглядело бы по-разному в
                      # зависимости от того, чем сняли список.
                      'name': people_name_case(name)[:PEOPLE_NAME_MAX],
                      'age': age,
                      'photo': photo,
                      # Ключ по фотографии — отдельным полем, помимо `uid`. По нему
                      # страница сводит человека из кабинета с ним же из чата:
                      # номера у них разные (в чате его нет вовсе), а файл один.
                      'photo_uid': people_photo_uid(photo),
                      'online': PEOPLE_ONLINE_MARK in str(
                          scenario_field(row, 'status_class') or ''),
                      'is_new': bool(str(
                          scenario_field(row, 'is_new') or '').strip()),
                      'link': link})

    return found


def people_photo_uid(photo: str) -> str:
    """Ключ по имени файла фотографии — им сводятся списки из кабинета и из чата.

    Наружу, а не приватно: тем же ключом пользуется список, снятый через API сайта
    (`people_api.py`). Разойдись эти два способа считать ключ — значок «есть
    переписка» пропал бы у половины карточек, и никто бы не понял почему.
    """
    match = PEOPLE_PHOTO_UID_RE.search(str(photo or ''))

    return match.group(1) if match else ''


# Чем помечаем имя, которым нельзя обратиться. ⚠ Не пустая строка: пустое имя и
# «имя есть, но им не обратиться» — разные вещи, и на странице карточки они должны
# читаться по-разному. Значение уезжает в поле `why` переменной, а не в письмо.
PEOPLE_NAME_ALIEN = 'имя записано не латиницей — в письме им не обратиться'


def people_name_usable(name: str) -> bool:
    """Годится ли имя для обращения в письме.

    Args:
        name: имя, как его отдал сайт.

    Returns:
        bool: `False` — имя есть, но обратиться им нельзя.

    ⚠ **Живой случай, ради которого правило и появилось.** В ленте Ladadate
    попался `許萊納`. Письма сайт пишет по-английски, агент вставить это имя не
    смог — вернул пустую реплику, — и набор пула потратил на него вызов LLM,
    чтобы затем отбросить результат. И так каждый заход: человек в сети, значит
    попадает в ленту снова. На проде таких в ленте дюжина из полутора сотен.

    ⚠ **Судим по письменности, а не по «странности».** Диакритика — не помеха:
    `Piller László`, `Thor Andrè Wisløff`, `Norman Tobon López` пишутся латиницей
    и в английском письме выглядят обычно. А `許萊納` и `Амір Даш` — другая
    письменность, и в английском тексте это инородное тело.

    ⚠ **Латиница зашита, а не выведена из языка сайта.** Сегодня письма пишутся
    по-английски (`presence.answer_language` = `en`), и второй язык означал бы
    таблицу «язык → письменность», выдуманную по одному примеру. Признак
    пересмотреть: появится сайт, который пишет кириллицей, — правило станет
    параметром языка, а не константой.

    ⚠ **Ни одной буквы — тоже не годится**: «12345» или «***» это не имя, и
    обращение по нему хуже, чем общее.
    """
    import unicodedata

    letters = [one for one in str(name or '') if one.isalpha()]

    return bool(letters) and all(
        unicodedata.name(one, '').startswith('LATIN') for one in letters)


def people_name_parts(name: str) -> dict:
    """Имя собеседника на части: `firstname` и `lastname`.

    Args:
        name: имя, как его отдал сайт, — «Brian Ritter», «Kevin», «JULIO RODRIGO
            ZAPATA OLIVA».

    Returns:
        dict: `{'firstname': …, 'lastname': …}`. `firstname` пуст только когда
        пусто само имя; `lastname` — когда фамилии в строке нет.

    ⚠ **Делим по первому пробелу, а не по последнему.** Первое слово — имя, всё
    остальное фамилия: «JULIO RODRIGO ZAPATA OLIVA» это Хулио и четыре фамилии, а
    не «JULIO RODRIGO ZAPATA» и «OLIVA». Гадать, где кончается имя, мы не умеем, а
    первое слово угадывается всегда.

    ## ⚠⚠ Имя одним словом — это имя, и раньше здесь было иначе

    Прежде «Kevin» давал **обе части пустыми**: так была видна разница между «имя
    известно отдельно» и «у нас просто строка», а чем звать — решал тот, кто пишет
    текст (`%if%` в промпте, `default_value` у переменной).

    Разница эта стоила дороже, чем сообщала, и цену измерили дважды:

    * **инвайты** — 23 черновика из 36 ушли бы к живым людям с сырой меткой
      `[[companion_name]]` в тексте; ради обхода в `invite.py` завелась вторая
      копия разбора (`_first_word`), и теперь она зовёт эту функцию;
    * **письма** — `companion_first_name` пустовал у большинства адресатов (имя
      одним словом на сайте обычное дело), а пустая переменная **останавливает
      отправку** целиком.

    ⚠ **Фамилия при этом остаётся пустой, и это не то же самое.** «Не знаем
    фамилию» — правда, а выдуманная фамилия уехала бы в текст письма.

    ⚠ **Строка `Tall_Good_Man` — одно слово**, хотя выглядит как три. Подчёркивание
    не пробел, и придумывать по нему разбиение значило бы звать человека «Tall».
    """
    flat = ' '.join(str(name or '').split())
    first, _, last = flat.partition(' ')

    return {'firstname': first, 'lastname': last}


# ── Приватное ────────────────────────────────────────────────────────────────

def _uid(link: str, photo: str, name: str) -> str:
    """Номер человека: из ссылки, из фотографии или из имени — что найдётся первым.

    ⚠ **Три источника — не перестраховка, а три разных случая.**

    1. **Ссылка.** В кабинете она ведёт на анкету, и номер в ней есть:
       `/profile/812886-…`. Это настоящий номер, и он лучше прочих.
    2. **Имя файла фотографии.** В чате ссылка голая (`/chat#`) — разговор
       открывает скрипт. Тогда ключом служит hex-имя файла: у каждого своё.
       Суффикс размера (`-s`) отсекается, поэтому один и тот же человек получает
       одинаковый ключ и в чате, и в кабинете — на этом держится сопоставление
       «с кем есть диалог».
    3. **Имя.** Сайт грузит картинки лениво, и у части строк вместо фотографии
       стоит заглушка. Без третьего источника такие диалоги пропадали бы молча —
       поймано на живом кабинете: из тринадцати терялись двое.

    Имя как ключ хуже прочих: тёзки склеятся. Но потерять собеседника хуже, чем
    показать двоих под одним ключом, а тёзки в списке из полутора десятков — редкость.
    """
    match = PEOPLE_UID_RE.search(str(link or ''))
    if match:
        return match.group(1) or match.group(2)

    match = PEOPLE_PHOTO_UID_RE.search(str(photo or ''))
    if match:
        return match.group(1)

    return f'name:{name.lower()}' if name else ''


def _name_age(value) -> tuple[str, int]:
    """Имя и возраст из склейки вида `Vincent\\n,\\u00a0\\n49`.

    Возраст — последнее число после запятой; нет его — ноль, а не догадка. Имя
    режем по первой запятой: у самих имён её не бывает, а вот у «Vincent
    pitchen» бывает пробел, и делить по нему нельзя.
    """
    text = ' '.join(str(value or '').split())
    if not text:
        return '', 0

    head, _, tail = text.rpartition(',')
    if not head:
        return text.strip(), 0

    digits = tail.strip()

    return head.strip(), int(digits) if digits.isdigit() else 0


def _photo(value) -> str:
    """Адрес фотографии или пусто, если сайт отдал заглушку ленивой загрузки."""
    photo = str(value or '').strip()
    if not photo or PEOPLE_PHOTO_STUB in photo:
        return ''

    return photo
