"""Доля из настройки сайта: проценты в форме, доля в коде.

## ⚠⚠ Зачем отдельный модуль

Эта функция жила **тремя копиями** — в инвайтах, в шаблоне рассылки и в письмах
избранным. Копии разошлись, и разошлись молча: две клампили значение сами
(`min(max(…), 100) / 100`), а третья читала через `site_seconds` — то есть
соблюдала границы, записанные в реестре настроек.

Разница видна только на кривом значении. Правило проекта — «границы числа
проверяет и **чтение**, форма не единственный вход» — выполняла одна копия из
трёх, и узнать об этом можно было, лишь сравнив их глазами.

## ⚠ Ноль — законное значение, а не «настройки нет»

Человек выбрал в форме «никогда»; подмени мы его умолчанием — имя или вопрос
появлялись бы там, где их запретили. Отличаем по тому, задан ли ключ у сайта
вообще: пустая строка означает «не трогали», строка `0` — «никогда».

## ⚠ Сбой чтения даёт умолчание, а не ноль

«Этого не будет вовсе» — решение, и принимать его молча из-за недоступной базы
нельзя. Пустой пул хуже пула без рассказа.

## ⚠ Жребий здесь больше не бросают — модуль только читает долю

Была `percent_hit`: она читала долю и **тут же бросала жребий**, чтобы «жребий и
чтение жили в одном месте». Довод был верным, пока жребий бросала панель; 26.09.2026
он переехал к соседу — в шаг `dice`, — и функцию не позвал никто ни разу (проверено
по истории: за всё время только тесты).

Отсюда две выдачи вместо трёх: `percent_share` отдаёт долю от единицы тому, кто
бросает жребий сам, `percent_value` — целые проценты строкой для описания жребия у
соседа.
"""

from logging_.logging_ import logger_info
from src.dating.site_setting import site_seconds, site_setting


async def percent_share(site_id: int, key: str, fallback: float) -> float:
    """Настройка-процент долей от единицы.

    Args:
        site_id: сайт-закладка.
        key: ключ настройки в `SITE_KNOWN` — процент целым числом.
        fallback: доля (0..1), если настройки нет или её не прочитать.

    Returns:
        float: доля от нуля до единицы.

    ⚠ **В настройке проценты, здесь доля.** Человек в форме пишет «10», а жребий
    бросается по доле; перевод живёт в одном месте — иначе где-нибудь сравнят
    процент с `random.random()`, и выпадать будет всегда.

    ⚠ **Читаем через `site_seconds`**, а не разбираем строку сами: он применяет
    границы из реестра (`min`/`max`), и 150% не превратится в «всегда».
    """
    try:
        percent = int(await site_seconds(int(site_id), str(key)))

        # Ноль от `site_seconds` двусмыслен: и «выбрали ноль», и «ключа нет».
        # Различаем по сырому значению.
        if not percent:
            raw = str(await site_setting(int(site_id), str(key)) or '').strip()
            if raw == '':
                return float(fallback)
    except Exception as e:
        logger_info(f'[dating] доля «{key}» сайта #{site_id} не прочиталась: {e}')

        return float(fallback)

    return max(0.0, min(1.0, percent / 100))


async def percent_value(site_id: int, key: str, fallback: float) -> str:
    """Настройка-процент так, как её понимает жребий на стороне workflow.

    Args:
        site_id: сайт-закладка.
        key: ключ настройки в `SITE_KNOWN`.
        fallback: доля (0..1), если настройки нет или её не прочитать.

    Returns:
        str: целые проценты строкой — `'10'`, `'40'`.

    ⚠⚠ **Проценты, а не доля**, и в этом вся разница с соседями по модулю. Те
    отдают долю, потому что по ней тут же бросают жребий; здесь число едет
    **наружу**, в шаг `dice` у соседа, а он считает в процентах.

    ⚠ Строкой: переменные вызова уходят строками, и `10` превратилось бы в `'10'`
    всё равно — но уже где-то по дороге, а не здесь, где это видно.

    ⚠ Границы реестра соблюдаются те же — считаем через `percent_share`, а не
    читаем настройку заново: вторая дорога чтения разошлась бы с первой, как уже
    разошлись три копии этой самой функции.
    """
    return str(int(round(await percent_share(site_id, key, fallback) * 100)))
