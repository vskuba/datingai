"""Пулы анкеты: черновики уходят вместе с ней из сети.

Три пула готовят текст заранее — рассылка (`mailing`), письма избранным
(`favorite_mail`) и инвайты (`invite`). Готовит их круг, а отправляет
человек или круг отправки, и оба спрашивают одно: **в сети ли девушка**.

## ⚠ Зачем стирать, а не оставлять до следующей смены

Потолок пула — **на сайт**, а не на анкету: круг добирает его до `mailing_pool_max`
(инвайты — до `invite_pool_max`) и встаёт. Черновики ушедшей анкеты этот потолок
занимают, но уйти не могут: отправка ждёт, когда она будет онлайн. Пятьдесят писем
от трёх ушедших девушек означают, что сайт молчит целиком, хотя в сети есть кому
писать.

Наблюдалось живьём: пул рассылки полон, пул инвайтов полон, отправка не идёт, а в
сети — три анкеты, которым круг не может добрать ни одного письма.

## ⚠ Что стираем и чего не стираем

| Пул | Уходит | Почему |
|-----|--------|--------|
| `mailing` | да | письмо незнакомому: ждать его неделю незачем |
| `favorite_mail` | да | приставание «ты замолчал» через сутки уже не про то |
| `invite` | да | зовут того, кто **сейчас** в чате: назавтра его там нет |
| `mail_reply` | **нет** | это ответ живому человеку на его письмо |

Ответ остаётся намеренно: его ждёт написавший, и «девушка вышла из сети» не повод
оставить письмо без ответа — круг отправки дождётся её следующей смены. Пулу это
не мешает: ответы набираются по входящим письмам, а не до потолка сайта.

## ⚠ Две стороны, а не одна

Всё выше — про **отправителя**: ушла девушка, и её черновики отправить нечем. Но у
инвайта есть вторая сторона, и она уходит чаще: **адресат**. Реплика в чат зовёт
того, кто сидит там сейчас, а сидят люди минутами — через час полпула зовёт тех,
кого на сайте нет. Их стирает `pool_sweep_away`, и только у инвайтов:
письмо ждёт в почте, уход адресата ему ничего не отменяет.

## ⚠ Стираем, а не помечаем

Помеченный черновик пришлось бы исключать из счёта во всех трёх пулах, из показа
на трёх вкладках и из отправки — четыре места вместо одного, и каждое молча
ломалось бы поодиночке. Текст при этом не теряется: он сочиняется заново, когда
анкета вернётся, — и сочиняется **по свежему состоянию**, а это честнее, чем
отправить вчерашнее.
"""

from logging_.logging_ import logger_info
from mysql_.mysql_ import mysql_get_db_async

# Пулы, из которых уходят черновики. ⚠ Список закрытый и проверяется при записи
# имени в SQL: имена таблиц нельзя подставлять параметром, и открытый список
# означал бы склейку строки из того, что пришло снаружи.
#
# ⚠ `mail_reply` здесь нет намеренно — см. заголовок модуля.
POOL_TABLES = ('mailing', 'favorite_mail', 'invite')


async def pool_drop(profile_id: int, why: str = '') -> dict:
    """Стирает черновики анкеты во всех пулах. Отправленное не трогает.

    Args:
        profile_id: анкета, которая ушла из сети.
        why: чем вызвано — уходит в журнал анкеты одной строкой.

    Returns:
        dict: `{имя таблицы: сколько стёрли}` плюс `total`.

    ⚠ **Только `draft`.** Отправленное — история: она отвечает на вопрос «что мы
    этому человеку уже писали», и пределы частоты (`favorite_mail_per_day`,
    `favorite_mail_gap`) считают именно по ней. Сотри мы её вместе с черновиками,
    вернувшаяся анкета написала бы тому же человеку второй раз подряд.
    """
    profile_id = int(profile_id or 0)
    if not profile_id:
        return {'total': 0}

    dropped = {}
    try:
        async with mysql_get_db_async() as db:
            for table in POOL_TABLES:
                await db.execute(
                    f"DELETE FROM {table} WHERE profile_id = %s AND status = 'draft'",
                    (profile_id,))
                dropped[table] = int(db.rowcount or 0)

            await db.connection.commit()
    except Exception as e:
        logger_info(f'[dating] пулы анкеты #{profile_id} не почистились: {e}')

        return {'total': 0}

    total = sum(dropped.values())
    if total:
        # ⚠ В журнал **анкеты**, а не только в общий лог: письма исчезают из пула, и
        # человек, видевший их минуту назад, должен найти причину там, где смотрит
        # на эту анкету.
        from src.dating.log import log_write

        await log_write(
            profile_id, 'info',
            f"Ушла из сети{f' ({why})' if why else ''} — из пулов убрано "
            f"черновиков: {total}")

    return {**dropped, 'total': total}


async def pool_sweep_away(site_id: int) -> int:
    """Стирает черновики инвайтов тем, **кого нет в сети** на самом сайте.

    Returns:
        int: сколько черновиков убрали.

    ⚠ **Только инвайты, и это не произвол.** Инвайт зовёт того, кто **сейчас** в
    чате: ушёл — и звать некого, а реплика, сочинённая под сидящего в сети,
    назавтра не про него. У писем иначе: письмо лежит в почте и ждёт, когда его
    откроют, — там уход адресата ничего не отменяет.

    ⚠ **Место в пуле важнее сочинённого текста.** Потолок один на сайт, и
    черновики ушедших держат его за тех, кто в сети прямо сейчас: круг видит пул
    полным и уходит ни с чем. Наблюдалось живьём — 50 черновиков, из них годных
    27, и очередь стояла.

    ⚠⚠ **Стираем только тех, про кого точно знаем, что их нет.** Снимок ленты
    бывает пустым (её ещё не снимали) и несвежим, и «не нашёл в списке» тогда
    значит «не знаю», а не «ушёл». Неизвестных не трогаем: потерять готовую
    реплику из-за неснятой ленты хуже, чем подержать её лишний круг.
    """
    from src.dating.online import online_check

    site_id = int(site_id or 0)
    if not site_id:
        return 0

    try:
        async with mysql_get_db_async() as db:
            await db.execute("SELECT id, uid FROM invite"
                             " WHERE site_id = %s AND status = 'draft'", (site_id,))
            rows = [dict(one) for one in (await db.fetchall() or [])]

            gone = [int(one['id']) for one in rows
                    if _away(online_check(site_id, str(one['uid'])))]
            if not gone:
                return 0

            marks = ', '.join(['%s'] * len(gone))
            await db.execute(f'DELETE FROM invite WHERE id IN ({marks})', gone)
            await db.connection.commit()
    except Exception as e:
        logger_info(f'[dating] черновики ушедших собеседников не убрались: {e}')

        return 0

    logger_info(f'[dating] пул инвайтов #{site_id}: убрано {len(gone)} — собеседники ушли')

    return len(gone)


def _away(state: dict) -> bool:
    """Точно ли человека нет в сети. «Не знаем» — не повод стирать."""
    return bool(state.get('known')) and not state.get('online')


async def pool_sweep(site_id: int) -> int:
    """Стирает черновики **всех** анкет сайта, которых сейчас нет в сети.

    Returns:
        int: сколько черновиков убрали.

    ⚠ **Это страховка, а не второй способ сделать то же.** `pool_drop`
    срабатывает на переходе — конец смены, отключение анкеты, — и покрывает те
    выходы, о которых мы знаем. Но анкета уходит в офлайн и иначе: сайт выбросил
    сессию, вход не признали, статус сбился в `error`. Поводов много, и ловить
    каждый значило бы держать список мест, который однажды окажется неполным.

    Здесь же проверяется само условие: черновик от анкеты не в сети отправить
    некому, а потолок пула он занимает. Зовут это круги — перед тем как считать,
    сколько в пуле места.

    ⚠ **По сайту, а не по анкете**: потолок тоже на сайт, и вопрос круга — «сколько
    в пуле годного», а не «что с этой девушкой».
    """
    site_id = int(site_id or 0)
    if not site_id:
        return 0

    total = 0
    try:
        async with mysql_get_db_async() as db:
            for table in POOL_TABLES:
                # ⚠ Отбор по `status` анкеты, а не по `enabled`: выключенную уже
                # убрал `pool_drop`, а здесь ловится именно «была в сети,
                # а теперь нет» — что бы её ни увело.
                await db.execute(
                    f"DELETE p FROM {table} p"
                    '  JOIN profile g ON g.id = p.profile_id'
                    "  WHERE p.site_id = %s AND p.status = 'draft'"
                    "    AND g.status <> 'online'", (site_id,))
                total += int(db.rowcount or 0)

            await db.connection.commit()
    except Exception as e:
        logger_info(f'[dating] пулы сайта #{site_id} не почистились: {e}')

        return 0

    if total:
        logger_info(f'[dating] сайт #{site_id}: убрано черновиков ушедших анкет: {total}')

    return total
