"""Пара «кто пишет — кому» для пулов писем: имя, лицо и номер обеих сторон.

Пулов писем три — рассылка, ответы, письма избранным, — и все они показывают
человеку одно и то же: от какой анкеты письмо и какому собеседнику. Карточка в
списке, строка в журнале доставки, окно правки. Вопрос один, а собирался он в
каждом пуле заново.

## ⚠⚠ Чем это вышло

Пул избранных доставал имя и лицо собеседника из трёх источников; пул рассылки
не доставал вовсе — в его окне стояло «Diana → 803656», голый номер вместо
человека. Там же, где у избранных лицо и ссылка на карточку.

И это не «недоделали»: поля лежали в базе, а запрос про них не знал, потому что
каждый пул писал свой.

## Что здесь лежит

| | |
|---|---|
| `pool_pair_joins()` | приклейка контакта и карточки собеседника |
| `pool_pair_select()` | `name` и `photo` собеседника — из трёх источников |
| `pool_pair_girl()` | имя, лицо и номер анкеты — из её карточки |
| `pool_delivery_where()` | «что происходило с отправкой» — условие журнала |
| `pool_answered_where()` | «он ещё не отвечал» — кому первая реплика впору |
| `pool_mail_answered_where()` | «он не отвечал **письмом**» — кому рассылка впору |
| `pool_pick_where()` | отбор именами: от этой анкеты, этому собеседнику |

⚠ Последняя про пару не знает и лежит здесь по другой причине: это **кусок запроса
по пулу**, а таких мест теперь два — журнал доставки писем и журнал доставки писем
избранным, — и каждый спрашивает по две таблицы. Пять копий одного условия разошлись
бы на первой правке, а расхождение счёта с выборкой даёт пустую последнюю страницу.

⚠ **Порядок источников собеседника не случаен.** Контакт анкеты (`contact`)
свежее общей карточки сайта (`companion`): он обновляется при каждом разговоре.
Имя из самой строки пула — последнее прибежище: оно записано в момент набора и
успело устареть.

⚠ Лицо, наоборот, берём сперва из `companion`: общая карточка хранит снимок с
анкеты сайта, а контакт — мелкий значок из ленты диалогов.
"""


def pool_pair_joins(alias: str = 'm') -> str:
    """Приклейка контакта и карточки собеседника.

    Args:
        alias: как названа таблица пула в запросе. ⚠ Доводом, а не догадкой:
            пулы зовут свою таблицу `m`, а список переписок — `f`, и жёсткое
            `m.` оставило бы третьего пользователя со своей копией.

    ⚠ Алиасы `c` и `comp` — часть договора: их занимает эта приклейка, и
    вызывающий запрос не вправе назвать так что-то своё.
    """
    return (f' LEFT JOIN contact c'
            f'   ON c.profile_id = {alias}.profile_id AND c.uid = {alias}.uid'
            f' LEFT JOIN companion comp'
            f'   ON comp.site_id = {alias}.site_id AND comp.uid = {alias}.uid')


def pool_pair_select(alias: str = 'm', own_name: bool = True,
                     own_photo: bool = True) -> str:
    """Куски `SELECT` с именем и лицом собеседника.

    Args:
        alias: как названа таблица пула — тот же довод, что у `pool_pair_joins`.
        own_name: есть ли у таблицы пула свой столбец `name`.
        own_photo: есть ли у неё свой `photo`. ⚠ У `mailing` его нет вовсе, и
            запрос с `m.photo` упал бы — потому и флаг, а не единый текст.

    Returns:
        str: `COALESCE(...) AS name, COALESCE(...) AS photo,` — с запятой на
        конце, чтобы вставлялось в середину списка полей.

    ⚠ Пустые строки литералами, а не заполнителями `%s`: прежний вариант тянул
    за собой восемь одинаковых аргументов `''`, и при любой правке запроса их
    приходилось пересчитывать руками. Подстановки здесь нет — значения свои.
    """
    name_own = f" NULLIF({alias}.name, ''), " if own_name else ' '
    photo_own = f" NULLIF({alias}.photo, ''), " if own_photo else ' '

    return (f" COALESCE(NULLIF(c.name, ''), NULLIF(comp.name, ''),"
            f"{name_own}'') AS name,"
            f" COALESCE(NULLIF(comp.photo, ''), NULLIF(c.photo, ''),"
            f"{photo_own}'') AS photo,")


def pool_pair_girl(got: dict, card: dict) -> dict:
    """Дописывает в ответ имя, лицо и номер анкеты. Меняет `got` на месте.

    Args:
        got: строка пула, уже превращаемая в ответ страницы.
        card: разобранный JSON-столбец `profile.profile`.

    Returns:
        dict: тот же `got` — чтобы вызов читался одной строкой.

    ⚠ **Имя анкеты, а не логин.** Логин это почта, и в строке «от кого» она
    читается как подпись робота. Логин остаётся запасным: он есть всегда.

    ⚠ `girl` и `profile_name` — одно значение под двумя именами, и это не
    небрежность: по первому зовут карточки пулов, по второму — общий вид стороны
    разговора (`talkSide`). Свести их в одно — отдельная правка страницы, и
    делать её заодно значило бы менять два дела одним движением.
    """
    got['girl'] = str(card.get('name') or got.get('profile_login') or '')
    got['profile_name'] = got['girl']
    got['profile_photo'] = str(card.get('photo') or '')
    got['profile_uid'] = str(card.get('id') or '')

    return got


def pool_delivery_where(alias: str) -> str:
    """Условие «всё про доставку» для таблицы пула под этим алиасом.

    Args:
        alias: алиас таблицы в запросе (`m` у писем, `r` у ответов).

    Returns:
        str: кусок `AND (...)` — дописывается к `WHERE` и счёта, и выборки.

    ⚠ Одной функцией на **шесть** мест: два журнала доставки, в каждом счёт и
    выборка по двум таблицам. Разойдись условия счёта и выборки — число страниц
    перестало бы отвечать содержимому, и последняя выходила бы пустой.

    ⚠⚠ Именно функция, а не строка с `replace` по имени столбца: такая замена
    ломается молча, стоит слову `status` или `error` появиться внутри литерала.

    ⚠ «Доставка» шире перечисления `sent,failed`: неудачная отправка **оставляет
    письмо в пуле** (`draft` с непустой причиной, `mail_send.py`), и по статусу её
    от нетронутого черновика не отличить. Именно этих строк и ищут в журнале.
    """
    return (f" AND ({alias}.status IN ('sent', 'failed')"
            f"      OR ({alias}.status = 'draft' AND {alias}.error <> ''))")


def pool_answered_where(alias: str, answered: bool = False) -> str:
    """Условие «он этой анкете ещё не отвечал» — кому первая реплика впору.

    Args:
        alias: как названа таблица пула в запросе.
        answered: какую половину оставить. `False` — ещё не отвечавшие, то есть
            годные для первой реплики; так спрашивают очередь и отправка. `True`
            — наоборот, уже ответившие: так спрашивает уборка пула
            (`pool.pool_sweep_answered`), которой нужно стереть именно их.

    Returns:
        str: кусок `AND [NOT] EXISTS (…)` — дописывается к `WHERE`.

    ⚠⚠ **Половина доводом, а не отрицанием снаружи.** Уборке нужно обратное
    условие, и собрать его на месте («`AND NOT (1 = 1 …)`») значило бы завести
    второе правило в обёртке вокруг первого: подзапрос один, а читается такое
    задом наперёд, и при правке подзапроса обёртка молча меняет смысл.

    ⚠ Алиас `zm` — часть договора: его занимает эта проверка, и вызывающий запрос
    не вправе назвать так что-то своё.

    ## ⚠⚠ Почему проверка нужна **второй раз**, уже перед отправкой

    На наборе пула это же правило стоит в `invite._talked`, и его одного мало **по
    устройству**: между набором и отправкой проходят минуты, а у сайта без сокета
    входящее приезжает импортом панели — то есть «он ответил» узнаётся позже, чем
    набран пул. Разрыв не закрыть, его можно только перепроверить.

    Поймано на проде 03.10.2026, пара Оксана ↔ Frank. Пул набрался в 06:04:20,
    когда Frank молчал на пять приглашений; в 06:05:12 он ответил, а в 06:07:28
    круг унёс **лежавшую** строку — и готовый зачин встал в диалоге ответом на его
    слова: «Ich denke, dass du Sex mit Frauen hast» → «You look like the type who's
    smart… terrible at chess». Со стороны человека это агент, не читающий ответов.

    ⚠ **Считаем только входящие.** Наш собственный инвайт ложится в переписку
    исходящим (`chat.chat_invites_to_history`), и считай мы любую строку
    разговором — отправка умерла бы целиком, а молчащего больше не позвал бы
    никто. Та же грабля уже была у `_talked`: у пары Соломия ↔ Semen четыре строки,
    все `out`, входящих ноль — монолог, который панель считала диалогом.

    ⚠ **Пара, а не человек.** Он ответил одной нашей анкете и не знает второй — для
    второй это законная первая реплика.

    ⚠ Запрос дешёвый: `EXISTS` ложится равенством на `idx_dating_message_dialog`
    (`profile_id`, `sender_uid`, `id`) и останавливается на первой строке.
    """
    return (f' AND {"" if answered else "NOT "}EXISTS ('
            f'SELECT 1 FROM message zm'
            f' WHERE zm.profile_id = {alias}.profile_id'
            f'   AND zm.sender_uid = {alias}.uid'
            f"   AND zm.direction = 'in')")


def pool_mail_answered_where(alias: str, answered: bool = False) -> str:
    """Условие «он этой анкете письмом ещё не отвечал» — кому рассылка впору.

    Args:
        alias: как названа таблица пула в запросе.
        answered: какую половину оставить. `False` — ещё не отвечавшие письмом,
            то есть годные для рассылки; так спрашивают набор пула, очередь
            отправки и кнопка. `True` — наоборот, уже ответившие: так спрашивает
            уборка пула (`pool.pool_sweep_mail_answered`), которой нужно стереть
            именно их.

    Returns:
        str: кусок `AND [NOT] EXISTS (…)` — дописывается к `WHERE`.

    ## ⚠⚠ Почему рассылка — и почему именно «ответил письмом»

    Рассылка это **холодное обращение к незнакомому**: один шаблон на сайт, метки
    вместо имени, ни слова из переписки. Ответившему письмом она не нужна — у него
    уже есть своё занятие, «приставание» (`favorite_mail`, §3.7.7), которое пишет
    по разговору и от той же девушки.

    Поймано на проде 04.10.2026, пара Yulia ↔ Riano. Разговор шёл с полудня, в
    13:25 он прислал письмо, в 13:30 ушёл ответ на него — а в 14:10 следом уехало
    письмо рассылки: «Hi Riano, I noticed a specific detail in your profile…».
    Человек прочитал его в той же нити, под своим письмом, и со стороны это ровно
    то, чем является: робот, не заметивший разговора.

    ⚠ **Пара, а не человек.** Он написал одной нашей анкете и не знает второй — для
    второй это законное холодное обращение, ровно как у первой реплики в чат
    (`pool_answered_where`) и у запрета `block`. Сужать до сайта значило бы отнимать
    у остальных анкет людей, которым они ещё не писали.

    ⚠ **Считаем только входящие письма.** Наша рассылка и наши ответы лежат в своих
    таблицах, в `mail_in` попадает только присланное нам, — и других источников у
    вопроса нет: чат живёт в `message`, и про него отвечает соседняя функция.

    ## ⚠⚠ Почему проверка нужна **второй раз**, уже перед отправкой

    На наборе пула её одной мало **по устройству**, и живой случай это показал
    числами: письмо сочинено в 13:21:33, его письмо пришло в 13:25:41, а ушло
    наше в 14:10:04 — через три четверти часа после сочинения. Между набором и
    отправкой у рассылки проходят не минуты, как у инвайтов, а часы: пул копится
    по расписанию, уносит его круг по письму за свой срок.

    Разрыв не закрыть, его можно только перепроверить — и подмести: черновик,
    который отправка больше не возьмёт, держал бы потолок пула
    (`mailing_pool_max`) вечно, как держали его инвайты ответившим.

    ⚠ Алиас `zi` — часть договора: его занимает эта проверка, и вызывающий запрос
    не вправе назвать так что-то своё.

    ⚠ Запрос дешёвый: `EXISTS` ложится равенством на `profile_id` (первый столбец
    `uq_dating_mail_in`) и останавливается на первой строке. Входящих писем в базе
    сотни, а не десятки тысяч: их шлют люди, а не круги.
    """
    return (f' AND {"" if answered else "NOT "}EXISTS ('
            f'SELECT 1 FROM mail_in zi'
            f' WHERE zi.profile_id = {alias}.profile_id'
            f'   AND zi.uid = {alias}.uid)')


def pool_pick_where(alias: str, profile_id: int = 0,
                    uid: str = '') -> tuple[str, list]:
    """Отбор именами: от какой анкеты и какому собеседнику.

    Args:
        alias: алиас таблицы пула в запросе.
        profile_id: только письма этой анкеты. Ноль — всех.
        uid: только письма этому собеседнику. Пусто — всем.

    Returns:
        tuple: (кусок `AND …` к `WHERE`, аргументы к нему).

    ⚠ **Отбор сужает уже отобранное, а не спрашивает другое.** Прикладывается
    после условий состояния, к тому же запросу — и к счёту, и к выборке.

    ⚠ Три журнала доставки — инвайты, письма, письма избранным — спрашивают его
    одинаково, и у каждого это два места (счёт и страница). Своя копия в шести
    местах расходится с первой правкой: забытый `strip()` у номера превращает
    «отобрать по Семёну» в «ничего не нашлось», и молча.

    ⚠ Стороны **порознь и обе разом**: «от Дианы и ему» — законный вопрос, а вот
    двух девушек сразу здесь нет, и это решение показа, а не запроса (полоса отбора
    держит по одному имени на сторону).
    """
    sql = ''
    args = []

    if int(profile_id or 0):
        sql += f' AND {alias}.profile_id = %s'
        args.append(int(profile_id))

    if str(uid or '').strip():
        sql += f' AND {alias}.uid = %s'
        args.append(str(uid).strip())

    return sql, args
