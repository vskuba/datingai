"""Пара «кто пишет — кому» для пулов писем: имя, лицо и номер обеих сторон.

Пулов писем три — рассылка, ответы, письма избранным, — и все они показывают
человеку одно и то же: от какой анкеты письмо и какому собеседнику. Карточка в
списке, строка в журнале доставки, окно правки. Вопрос один, а собирался он в
каждом пуле заново.

## ⚠⚠ Чем это вышло

Пул избранных доставал имя и лицо собеседника из трёх источников; пул рассылки
не доставал вовсе — в его окне стояло «Diana → 803656», голый номер вместо
человека. Там же, где у избранных лицо и ссылка на карточку.

И это не «недоделали»: поля лежали в базе, а запрос про них не знал, потому что
каждый пул писал свой.

## Что здесь лежит

| | |
|---|---|
| `pool_pair_joins()` | приклейка контакта и карточки собеседника |
| `pool_pair_select()` | `name` и `photo` собеседника — из трёх источников |
| `pool_pair_girl()` | имя, лицо и номер анкеты — из её карточки |

⚠ **Порядок источников собеседника не случаен.** Контакт анкеты (`contact`)
свежее общей карточки сайта (`companion`): он обновляется при каждом разговоре.
Имя из самой строки пула — последнее прибежище: оно записано в момент набора и
успело устареть.

⚠ Лицо, наоборот, берём сперва из `companion`: общая карточка хранит снимок с
анкеты сайта, а контакт — мелкий значок из ленты диалогов.
"""


def pool_pair_joins(alias: str = 'm') -> str:
    """Приклейка контакта и карточки собеседника.

    Args:
        alias: как названа таблица пула в запросе. ⚠ Доводом, а не догадкой:
            пулы зовут свою таблицу `m`, а список переписок — `f`, и жёсткое
            `m.` оставило бы третьего пользователя со своей копией.

    ⚠ Алиасы `c` и `comp` — часть договора: их занимает эта приклейка, и
    вызывающий запрос не вправе назвать так что-то своё.
    """
    return (f' LEFT JOIN contact c'
            f'   ON c.profile_id = {alias}.profile_id AND c.uid = {alias}.uid'
            f' LEFT JOIN companion comp'
            f'   ON comp.site_id = {alias}.site_id AND comp.uid = {alias}.uid')


def pool_pair_select(alias: str = 'm', own_name: bool = True,
                     own_photo: bool = True) -> str:
    """Куски `SELECT` с именем и лицом собеседника.

    Args:
        alias: как названа таблица пула — тот же довод, что у `pool_pair_joins`.
        own_name: есть ли у таблицы пула свой столбец `name`.
        own_photo: есть ли у неё свой `photo`. ⚠ У `mailing` его нет вовсе, и
            запрос с `m.photo` упал бы — потому и флаг, а не единый текст.

    Returns:
        str: `COALESCE(...) AS name, COALESCE(...) AS photo,` — с запятой на
        конце, чтобы вставлялось в середину списка полей.

    ⚠ Пустые строки литералами, а не заполнителями `%s`: прежний вариант тянул
    за собой восемь одинаковых аргументов `''`, и при любой правке запроса их
    приходилось пересчитывать руками. Подстановки здесь нет — значения свои.
    """
    name_own = f" NULLIF({alias}.name, ''), " if own_name else ' '
    photo_own = f" NULLIF({alias}.photo, ''), " if own_photo else ' '

    return (f" COALESCE(NULLIF(c.name, ''), NULLIF(comp.name, ''),"
            f"{name_own}'') AS name,"
            f" COALESCE(NULLIF(comp.photo, ''), NULLIF(c.photo, ''),"
            f"{photo_own}'') AS photo,")


def pool_pair_girl(got: dict, card: dict) -> dict:
    """Дописывает в ответ имя, лицо и номер анкеты. Меняет `got` на месте.

    Args:
        got: строка пула, уже превращаемая в ответ страницы.
        card: разобранный JSON-столбец `profile.profile`.

    Returns:
        dict: тот же `got` — чтобы вызов читался одной строкой.

    ⚠ **Имя анкеты, а не логин.** Логин это почта, и в строке «от кого» она
    читается как подпись робота. Логин остаётся запасным: он есть всегда.

    ⚠ `girl` и `profile_name` — одно значение под двумя именами, и это не
    небрежность: по первому зовут карточки пулов, по второму — общий вид стороны
    разговора (`talkSide`). Свести их в одно — отдельная правка страницы, и
    делать её заодно значило бы менять два дела одним движением.
    """
    got['girl'] = str(card.get('name') or got.get('profile_login') or '')
    got['profile_name'] = got['girl']
    got['profile_photo'] = str(card.get('photo') or '')
    got['profile_uid'] = str(card.get('site_uid') or '')

    return got
