"""Карточка анкеты: что в ней правит человек и что это защищает от перезаписи.

Карточка (`profile.profile`, JSON) — **кэш того, что отдал сайт**, и писателей у
неё трое: импорт анкет (`import_.py`), чтение страницы кабинета
(`profile_page.py`) и кэш анкеты по кнопке «Проверка»
(`profile_cache._profile_save_card`). Человек стал четвёртым: окно правки на
вкладке «Общая информация» даёт вписать то, чего сайт не отдал или отдал неверно.

⚠⚠ Писателей было найдено двое, а оказалось трое — план и спека закрыли первых
двух и пропустили кэш анкеты: он заменял карточку целиком и правила не знал.
Нашло финальное ревью: та же грабля проекта, что уже случалась, — «пять дорог,
план закрыл две».

## ⚠⚠ Правило одно, а мест применения три

Правленое руками сайт перезаписывать не вправе — таково правило проекта («не
трогаем то, что завёл человек», `import_.py`). Проверять это приходится в **трёх**
писателях, и своя копия правила в каждом разошлась бы на первой правке: часть
системы уважала бы ручную правку, другая затирала. Поэтому правило живёт здесь
одной функцией `profile_card_keep`, а все три писателя её зовут.

## ⚠ Почему отметка выбрасывает поле, а не перекрывает его

`profile_card_keep` возвращает пришедшее с сайта **без** правленых ключей, а не
подменяет их прежними значениями. Так проще и так вернее: у всех трёх вызывающих
прежняя карточка под рукой (`{**before, **fresh}`), и класть её значения второй раз
означало бы два источника правды в одном выражении.

## ⚠ Номер анкеты — поле карточки, хотя живёт ещё и колонкой

Ключ `id` в списке правимых полей есть, и это не описка: номер записан дважды —
колонкой `profile.profile_id` и ключом карточки, — потому что читают их разные
места (ключ фактов агента берёт колонку, сведение переписки из панели и ссылка на
сайт берут карточку). Отметка защищает обе записи сразу: пока она стоит, импорт не
трогает ключ, а колонку он не пишет вовсе.

⚠ Почты (`login`) среди полей нет намеренно. Это колонка учётки, и писатели со
стороны сайта её не трогают вовсе: импорт у существующей анкеты пишет только
`profile` (`_profile_update`), а чтение страницы и кэш анкеты — тем более.
Отметка (`profile_edited`) защищает от перезаписи сайтом; почте сайт не грозит,
защищать её от него незачем.

⚠⚠ От гонки **между людьми** (или кругом и человеком, правящими одну анкету
одновременно) почту защищает не отметка, а сверка снимка в `_card_claim`: `login`
стоит в её `WHERE` наравне с `profile` и `profile_edited`, хотя колонкой
`profile_edited` не огорожен и правкой не метится. Находка финального ревью —
прежде сверка этот столбец пропускала, и правка одной почты могла затереть
правку другой молча.
"""

import json

from logging_.logging_ import logger_info
from mysql_.mysql_ import mysql_get_db_async

from src.dating.json_column import json_column_list, json_column_load
from src.dating.profile_param import (PROFILE_PARAM_KEYS, PROFILE_PARAM_PREFIX,
                                      profile_param_frame)

# Поля карточки верхнего уровня, которые правят руками. ⚠ Имена — ключи самой
# карточки, а не подписи окна: по ним же ложится отметка, и второе написание
# развело бы их.
PROFILE_CARD_OWN = ('id', 'name', 'age', 'city', 'about')

# Всё правимое разом: свои поля плюс параметры составными именами.
#
# ⚠⚠ Составное имя (`parameters.height`), а не своя колонка отметок: механизм
# `profile_edited` уже есть, и вторая колонка рядом отвечала бы на тот же вопрос
# дважды. На этом списке стоят три проверки — отсев чужих имён в
# `profile_card_edited`, сверка в `profile_card_forget` и сверка в ручке.
PROFILE_CARD_FIELDS = PROFILE_CARD_OWN + tuple(
    PROFILE_PARAM_PREFIX + key for key in PROFILE_PARAM_KEYS)

# Чем «пусто» у каждого **своего** поля. ⚠ Нужно потому, что карточку собирают
# разные писатели и ключа может не быть вовсе: без этого «возраст 0 там, где ключа
# нет» читалось бы как правка, и окно, открытое поглядеть и сохранённое без
# изменений, заморозило бы возраст навсегда.
#
# ⚠ Параметров здесь нет: пусто у них у всех одно — пустая строка.
PROFILE_CARD_EMPTY = {'id': '', 'name': '', 'age': 0, 'city': '', 'about': ''}


def profile_card_edited(value) -> list[str]:
    """Отметки из колонки `profile_edited` — списком известных имён.

    Args:
        value: значение колонки: список, строка JSON или `None`.

    Returns:
        list: имена правленых полей в порядке объявления `PROFILE_CARD_FIELDS`.
        Незнакомые имена и испорченный JSON дают пустой список.

    ⚠ Чужие имена отсеиваются, а не переносятся как есть: строка, попавшая в
    колонку мимо нашей двери, иначе отняла бы у сайта поле, которого в карточке
    нет вовсе.

    ⚠ Порядок — наш, а не как лежало: он уезжает в ответ ручки и в окно, и
    «то же самое, но в другом порядке» выглядело бы изменением.
    """
    said = {str(one) for one in json_column_list(value)}

    return [name for name in PROFILE_CARD_FIELDS if name in said]


def profile_card_keep(fresh: dict, edited) -> dict:
    """Пришедшее с сайта без полей, которые правил человек.

    Args:
        fresh: карточка или её часть, как её отдал сайт.
        edited: значение колонки `profile_edited` — список, строка JSON или `None`.

    Returns:
        dict: копия `fresh` без правленых ключей. Отметок нет — копия целиком.

    ⚠ Вложенный `parameters` разбирается **поключево**: отметка `parameters.height`
    роняет только его, соседние остаются. Сам ключ при этом не исчезает никогда.
    """
    skip = set(profile_card_edited(edited))
    got = fresh or {}

    out = {name: value for name, value in got.items()
           if name not in skip and name != 'parameters'}

    # ⚠⚠ Ключ `parameters` остаётся **даже когда из него выброшено всё**: пустой
    # словарь говорит «параметры пришли, но все правлены руками», и на этом стоит
    # глубокое слияние в `profile_card_merge`. Исчезни он — слияние не узнало бы,
    # что параметры вообще приходили, и положило бы прежние поверх.
    if 'parameters' in got:
        inner = dict(got.get('parameters') or {})
        out['parameters'] = {key: value for key, value in inner.items()
                             if PROFILE_PARAM_PREFIX + key not in skip}

    return out


# Имена уникальных ключей таблицы. ⚠ Нужны **оба и порознь**: по ним причина
# отказа узнаётся точно, а «просто дубль» отправил бы человека править не то поле.
PROFILE_CARD_KEY_LOGIN = 'uk_dating_profile_site_login'
PROFILE_CARD_KEY_UID = 'uk_dating_profile_site_uid'

# Сколько раз пробуем записать правку, если строку успели увести из-под нас.
#
# ⚠ Две, а не «до победы». Третья попытка значила бы, что по анкете идёт поток
# записей, которого у правки руками не бывает, — и цикл крутился бы молча, держа
# соединение. Две попытки закрывают единственный правдоподобный случай: человек и
# круг (или двое людей) сошлись на одной анкете в одну секунду.
PROFILE_CARD_TRIES = 2


async def profile_card_save(profile_id: int, values: dict) -> dict:
    """Записать правку руками: карточка, две колонки и отметки одним заходом.

    Args:
        profile_id: наш номер анкеты.
        values: что пришло из окна. `login` — почта; остальные ключи — имена из
            `PROFILE_CARD_FIELDS`. Отсутствующий ключ значит «не трогать».

    Returns:
        dict: `login`, `card` и `edited` — что в итоге легло.

    Raises:
        LookupError: анкеты с таким номером нет.
        ValueError: почта или номер на сайте уже заняты; либо строку правили
            одновременно с нами и попытки исчерпались — причина словами.

    ## ⚠⚠ Номер уезжает в оба написания

    Колонка `profile_id` и ключ `id` карточки держат одну и ту же величину, и
    читают их разные места: ключ фактов агента — колонку (`agent_site_uid`),
    сведение переписки из панели и ссылка на сайт — карточку. Пишем их **одним
    `UPDATE`**: разойдясь, они не уронят ни одной проверки — половина кода просто
    увидит номер, а половина пустоту.

    ## ⚠⚠ Метится изменённое, а не присланное

    Поле попадает в отметки, только если значение разошлось с тем, что лежит.
    Иначе человек, открывший окно поглядеть и нажавший «Сохранить», заморозил бы
    все пять полей разом — и сайт больше не обновил бы ни одного.

    ⚠ Стирание при этом — правка: вписанное пустым значит «неправда, не знаем», и
    без отметки импорт вернул бы убранное.

    ⚠ Совпало с тем, что лежит, — отметка **не ставится и не снимается**. Снять её
    можно только «вернуть сайту» (`profile_card_forget`): это решение человека, и
    угадывать его по совпадению значений нельзя — девушку могли переименовать в то
    же самое.

    ## ⚠⚠ Почему запись идёт попытками, а не одним `UPDATE`

    Чтение строки и запись — два обращения к базе, и между ними карточка собирается
    в памяти. Безусловный `UPDATE` в конце уносил бы **всю** карточку и весь список
    отметок, записанные в эту щель кем-то ещё: двое, правящие разные поля одной
    анкеты в одну секунду, теряли одну правку целиком, молча.

    Закрыто условным `UPDATE` со сверкой снимка (`_card_claim`) — тем же приёмом,
    которым заперта отправка инвайта (`invite_send._claim`), и по той же причине:
    транзакций в проекте нет вовсе, а пул идёт с `autocommit = True`.
    """
    # ⚠⚠ Почта на первом снимке, а не на каждом. Карточку (`profile`) писатели
    # со стороны сайта не затрагивают почту вовсе, и внутри неё «не трогать»
    # значит «ключа нет». Почта мандатна — ключа «не трогать» у неё не бывает,
    # окно всегда присылает значение, и без устойчивого ориентира повтор не
    # отличил бы «человек переписывает почту снова и снова» от «форма просто
    # эхом носит то, что увидела при открытии, пока снимок на руках». Первый
    # случай обязан победить (последняя правка того же поля — выигрывает);
    # второй обязан отступить перед тем, что сейчас лежит в базе.
    first_login = None
    for _ in range(PROFILE_CARD_TRIES):
        row = await _card_read(profile_id)
        if first_login is None:
            first_login = row.get('login')
        login, card, marks = _card_apply(row, values, first_login)

        try:
            if await _card_claim(profile_id, row, login, card, marks):
                return {'login': login, 'card': card, 'edited': marks}
        except Exception as error:
            raise ValueError(
                profile_card_why(error, login, str(card.get('id') or ''))) from error

    raise ValueError('анкету правил кто-то ещё — откройте окно заново и повторите')


async def profile_card_forget(profile_id: int, field: str) -> list[str]:
    """Снять отметку с поля — «вернуть сайту».

    Args:
        profile_id: наш номер анкеты.
        field: имя поля карточки из `PROFILE_CARD_FIELDS`.

    Returns:
        list: отметки, которые остались.

    Raises:
        ValueError: такого поля среди правимых нет.
        LookupError: анкеты нет.

    ⚠ **Значение остаётся на месте.** Стереть его значило бы выбросить то, что
    человек видел в поле; обновит его следующий импорт, когда сайт отдаст своё.

    ⚠ Отметка нужна человеку именно снимаемой: без этого правило «сайт правленое
    не трогает» становится ловушкой — поправивший имя однажды отрезал бы его от
    сайта навсегда и узнал об этом только тем, что имя больше не обновляется.
    """
    if field not in PROFILE_CARD_FIELDS:
        raise ValueError(f'поля «{field}» в карточке анкеты нет')

    async with mysql_get_db_async() as db:
        await db.execute('SELECT profile_edited FROM profile WHERE id = %s',
                         (int(profile_id),))
        row = await db.fetchone()
        if not row:
            raise LookupError(f'анкеты #{int(profile_id)} нет')

        left = [one for one in profile_card_edited(row['profile_edited'])
                if one != field]
        # ⚠ Пустые отметки ложатся `NULL`, а не `'[]'`: «отметок нет» должно иметь
        # одно написание — то же правило, что в миграции колонки.
        await db.execute('UPDATE profile SET profile_edited = %s WHERE id = %s',
                         (json.dumps(left) if left else None, int(profile_id)))
        await db.connection.commit()

    return left


async def profile_card_merge(profile_id: int, fresh: dict, note: str) -> dict:
    """Положить пришедшее с сайта, не затирая правленого руками.

    Args:
        profile_id: наш номер анкеты.
        fresh: карточка или её часть, как её отдал сайт. Ключа нет — поле не
            трогается вовсе.
        note: чем назвать неудачу в журнале — у каждого вызывающего своя фраза.

    Returns:
        dict: карточка, как она **легла**. Пустой словарь значит «записать не
        удалось»; вызывающие на это не падают.

    ## ⚠⚠ Одна дверь вместо двух близнецов

    Этот путь был написан дважды и слово в слово — `profile_page._profile_save` и
    `profile_cache._profile_save_card` отличались только фразой в журнале, и в
    докстринге обоих стояло «правятся парой». Чтение панели стало бы третьей
    копией, то есть ровно той граблёй, что уже стоила проекту пропущенного
    третьего писателя карточки.

    ⚠ Импорт анкет сюда **не входит**, и это не упущение: у него решение
    (`import_.import_plan`) и запись (роутер импорта) разведены намеренно, а
    отметки он уважает своим путём, тем же `profile_card_keep`.

    ## ⚠⚠ Слияние `parameters` — глубокое, и это не придирка

    `profile_card_keep` выбрасывает из пришедшего помеченные подключи. У анкеты,
    где человек правил **все** 21 поле, она вернёт `{'parameters': {}}` — и
    плоское `{**before, **kept}` положило бы пустой словарь поверх полного,
    стерев правленое руками целиком. У той самой анкеты, которую заполняли
    дольше всех.

    ⚠ Это **единственное** место с глубоким слиянием, и держится оно на том, что
    вложенный ключ в карточке один. Появится второй — правило придётся обобщать,
    а не копировать строкой ниже.

    ## ⚠ Сверки снимка здесь нет

    Её не было и у обоих близнецов. Безусловный `UPDATE` уносит то, что записали в
    щель между чтением и записью; у писателей со стороны сайта это маловероятно
    (круги по одной анкете парами не ходят), а у правки руками сверка есть
    (`_card_claim`). Признак завести её и здесь: второй круг, пишущий карточку.
    """
    try:
        async with mysql_get_db_async() as db:
            await db.execute('SELECT profile, profile_edited FROM profile '
                             ' WHERE id = %s', (int(profile_id),))
            row = dict(await db.fetchone() or {})
            if not row:
                raise LookupError(f'анкеты #{int(profile_id)} нет')

            before = json_column_load(row.get('profile'))
            kept = profile_card_keep(fresh, row.get('profile_edited'))
            card = {**before, **kept}

            if 'parameters' in kept:
                card['parameters'] = {**(before.get('parameters') or {}),
                                      **kept['parameters']}

            await db.execute('UPDATE profile SET profile = %s WHERE id = %s',
                             (json.dumps(card, ensure_ascii=False),
                              int(profile_id)))
            await db.connection.commit()

        return card
    except Exception as e:
        logger_info(f'[dating] {note}: {e}')

        return {}


def profile_card_why(error: Exception, login: str, uid: str) -> str:
    """Причина отказа словами вместо текста драйвера.

    Args:
        error: исключение драйвера.
        login: почта, которую пытались записать.
        uid: номер на сайте, который пытались записать.

    Returns:
        str: предложение для человека.

    ⚠ **Ключи различаются порознь, и общий признак дубля стоит последним.** У
    таблицы два уникальных ключа, и «почта занята» вместо «номер занят» отправило
    бы человека править не то поле.
    """
    text = str(error)

    if PROFILE_CARD_KEY_UID in text:
        return f'номер {uid} на этом сайте уже у другой анкеты'

    if PROFILE_CARD_KEY_LOGIN in text or '1062' in text or 'Duplicate entry' in text:
        return f'учётка «{login}» на этом сайте уже заведена'

    return f'не удалось сохранить анкету: {text}'


async def _card_claim(profile_id: int, row: dict, login: str, card: dict,
                      marks: list) -> bool:
    """Записать, если строку не увели из-под нас.

    Args:
        profile_id: наш номер анкеты.
        row: снимок, с которым считали — нужны его `login`, `profile` и
            `profile_edited`.
        login: почта, которая должна лечь.
        card: карточка, которая должна лечь.
        marks: отметки, которые должны лечь.

    Returns:
        bool: `True` — легло либо класть было нечего; `False` — снимок устарел,
        строку правил кто-то ещё.

    ⚠ Пусто в номере ложится `NULL`, а не `''`: уникальный ключ считает пустые
    строки одинаковыми, а `NULL`-ы — разными, и второй анкеты без номера не
    завелось бы. То же правило у пустых отметок.

    ## ⚠⚠ Сверка — трёх столбцов, а не двух

    Почты (`login`) нет среди полей карточки, но она пишется **всегда**: окно
    присылает все шесть полей при любом сохранении. Сверяй `WHERE` только
    `profile` и `profile_edited` — и правка одной почты при неизменной карточке
    проходила бы первым же заходом, а следом снимок соперника, прочитанный
    раньше, совпадал бы по обоим сверяемым столбцам и возвращал прежнюю почту
    поверх, молча затирая чужую правку. `login` сверяется обычным `=`, а не
    `<=>`: колонка `NOT NULL`, и `NULL`-ов в ней не бывает.

    ## ⚠⚠ Ноль изменённых строк значит две разные вещи

    `rowcount` у MySQL — число **изменённых** строк, а не совпавших. Ноль приходит
    и когда условие в `WHERE` не сошлось (строку увели), и когда мы записали ровно
    то, что в строке и лежало (менять было нечего). Второе — это «человек открыл
    окно и сохранил, не правя», то есть обычнейшее действие; прими мы ноль за
    проигранную гонку, оно отвечало бы отказом «вас опередили».

    Различает их повторное чтение, и делается оно **только при нуле** — то есть
    почти никогда.

    ## ⚠⚠ Сверка — `CAST(%s AS JSON)`, а не голый `%s`

    Проверено прямым запросом: `profile <=> %s`, где `%s` — связанный параметр со
    строкой, прочитанной тем же запросом секунду назад из той же колонки, **не
    совпадает никогда** (`rowcount` неизменно 0, даже когда строку никто не
    трогал) — MySQL сравнивает JSON-колонку со связанным параметром не как JSON, а
    драйвер не приводит его к нужному типу сам. `CAST(%s AS JSON)` заставляет
    сравнение идти по значению, а не по байтам параметра, и воспроизводимо даёт
    `rowcount = 1` на совпавшем снимке и `0` на устаревшем — проверено той же
    парой запросов на временной таблице до того, как лечь в код.
    """
    uid = str(card.get('id') or '').strip() or None

    async with mysql_get_db_async() as db:
        await db.execute(
            'UPDATE profile SET login = %s, profile_id = %s, profile = %s, '
            '       profile_edited = %s '
            ' WHERE id = %s AND login = %s AND profile <=> CAST(%s AS JSON) '
            '       AND profile_edited <=> CAST(%s AS JSON)',
            (login, uid, json.dumps(card, ensure_ascii=False),
             json.dumps(marks) if marks else None, int(profile_id),
             row.get('login'), row.get('profile'), row.get('profile_edited')))
        written = int(db.rowcount or 0)
        await db.connection.commit()

        if written:
            return True

        await db.execute('SELECT login, profile, profile_edited FROM profile '
                         ' WHERE id = %s', (int(profile_id),))
        now = dict(await db.fetchone() or {})

    return (now.get('login') == row.get('login')
            and now.get('profile') == row.get('profile')
            and now.get('profile_edited') == row.get('profile_edited'))


def _card_apply(row: dict, values: dict, first_login=None) -> tuple[str, dict, list[str]]:
    """Что должно лечь: почта, карточка и отметки. Чистая — базы не касается.

    Args:
        row: снимок строки, с которым считаем на этой попытке.
        values: что пришло из окна.
        first_login: почта, какой она была на **самой первой** попытке этого
            вызова `profile_card_save` — ориентир, не трогавшийся повтором.
            `None` — считать, что текущая попытка и есть первая.

    Отдельной функцией, потому что решение «что считать правкой» хочется читать и
    проверять без базы, а попытка записи может повториться — считать то же самое
    дважды внутри цикла незачем, но и прятать это в запрос нельзя.

    ## ⚠⚠ Почта решается не как поля карточки

    У полей `PROFILE_CARD_FIELDS` отсутствие в `values` само по себе значит «не
    трогать» — окно может прислать только изменённое. Почта обязательна
    (`NOT NULL`, половина ключа входа), и окно присылает её всегда, правил
    человек её или просто открыл и сохранил. Поэтому «значение не изменилось»
    для почты узнаётся не присутствием ключа, а сравнением с `first_login`:
    совпало с тем, что было на первой попытке, — это эхо формы, и в дело идёт
    **свежая** строка (`row.get('login')`), какой бы она ни была к этой попытке;
    разошлось — человек правит почту осознанно, и его значение побеждает, как
    и для прочих полей при столкновении на одном и том же поле.

    ⚠ **Чего это не закрывает, и так было всегда.** `first_login` снят на первой
    попытке **этого вызова**, а не в тот миг, когда человек открыл окно. Смени
    кто-то почту между открытием окна и нажатием «Сохранить», и присланное
    значение разойдётся с `first_login` — то есть будет принято за осознанную
    правку и ляжет поверх чужой. Окно здесь шире, чем у прочих полей, и сузить
    его можно только одним способом: присылать со страницы ту почту, что была
    при открытии, и сверять уже с ней. Признак, по которому стоит это сделать:
    появление второго места, откуда почту правят.
    """
    before = json_column_load(row.get('profile'))
    card = dict(before)
    edited = set(profile_card_edited(row.get('profile_edited')))

    for field in PROFILE_CARD_OWN:
        if field not in values:
            continue

        if _same(field, before.get(field), values[field]):
            continue

        card[field] = values[field]
        edited.add(field)

    # ⚠ Параметры — своим проходом, потому что лежат вложенным словарём, а правило
    # то же: метится **изменённое**, а не присланное. Ключа `parameters` в
    # присланном нет вовсе — не трогаем ничего, как и у прочих полей.
    if 'parameters' in values:
        was = dict(before.get('parameters') or {})
        now = dict(was)
        for key, value in (values.get('parameters') or {}).items():
            if key not in PROFILE_PARAM_KEYS:
                continue

            if str(was.get(key) or '').strip() == str(value or '').strip():
                continue

            now[key] = value
            edited.add(PROFILE_PARAM_PREFIX + key)

        # ⚠ Каркас восстанавливается на **каждой** записи руками: анкета, у которой
        # параметров не было вовсе, получает их здесь — и окно с био дальше видят
        # одно и то же у всех.
        card['parameters'] = profile_param_frame(now)

    submitted = str(values.get('login') or '').strip()
    baseline = str(first_login if first_login is not None else row.get('login') or '')
    login = submitted if submitted and submitted != baseline else str(row.get('login') or '')

    return login, card, profile_card_edited(sorted(edited))


async def _card_read(profile_id: int) -> dict:
    """Строка анкеты: прежние значения и снимок столбцов для сверки.

    Raises:
        LookupError: анкеты нет. Правка несуществующей — ошибка вызывающего.
    """
    async with mysql_get_db_async() as db:
        await db.execute('SELECT login, profile, profile_edited FROM profile '
                         ' WHERE id = %s', (int(profile_id),))
        row = await db.fetchone()

    if not row:
        raise LookupError(f'анкеты #{int(profile_id)} нет')

    return dict(row)


def _same(field: str, before, after) -> bool:
    """Совпало ли значение с тем, что лежит.

    ⚠ Отсутствующий ключ приравнивается к «пусто» своего вида
    (`PROFILE_CARD_EMPTY`): без этого присланный возраст `0` там, где ключа нет
    вовсе, читался бы как правка.
    """
    empty = PROFILE_CARD_EMPTY[field]
    was = empty if before is None else before
    now = empty if after is None else after

    return str(was) == str(now)



