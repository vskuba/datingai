"""Удаление анкеты: то, что каскад не уносит.

## ⚠⚠⚠ Каскад уносит двенадцать таблиц, но не все

У `profile` есть внешние ключи с `ON DELETE CASCADE`, и переписка, пулы, журнал
уходят за анкетой сами. А у нескольких таблиц ключа **нет вовсе** — только
колонка `profile_id`, — и их строки анкету переживают. Номер в них после этого
ни на что не указывает: ни показать, ни найти, ни связать.

Замер 03.11.2026 показал цену на живых данных сюиты: `intention_mail` накопила
**166** таких строк, `gallery_file` оставляла по две за прогон. На проде их ноль
— но только потому, что анкеты в панели **не удаляют**. Удалят — утечка
проявится там же.

## ⚠⚠ Почему список, а не внешние ключи

Поставить всем недостающим таблицам `FOREIGN KEY … ON DELETE CASCADE` было бы
правильнее по существу: правило жило бы в схеме, и обойти его стало бы нельзя.
Но это миграция поверх живых данных, а строки в этих таблицах есть у каждой
анкеты, и неудачный `ALTER` роняет панель целиком. Проект уже выбрал списки
(`TEST_SWEEP_BY_PROFILE` у сюиты), и второй способ рядом с первым расходился бы
молча.

⚠ Поэтому список **сверяется со схемой** сторожем `test_profile_drop.py`, а не
с другим списком: новая таблица без ключа обязана попасть сюда, и красный там
значит «она копит мусор», а не «тест устарел».

## ⚠⚠ Два журнала переживают анкету намеренно

`scenario_run` и `request` тоже каскадом не уходят, и в список сноса они **не**
попадают — это решение, а не упущение, и потому записано вторым списком
(`PROFILE_DROP_KEEP`), а не молчаливым отсутствием в первом.

Довод у обоих один: это журналы **работы системы**, а не собственность анкеты.
Прогон сценария отвечает на «что вообще происходило», поход наружу — на «куда
мы ходили и что ответили» (`request.py`); снеси их вместе с анкетой, и
расследование вчерашнего отказа лишилось бы ровно тех строк, ради которых его
и ведут. У `scenario_run` это прямо выражено схемой — ключ есть, но гасится в
`NULL`; у `request` ключа нет вовсе, а срок жизни свой, трое суток, и чистит
его круг.
"""

from logging_.logging_ import logger_info
from mysql_.mysql_ import mysql_get_db_async

# Таблицы с `profile_id`, у которых нет внешнего ключа на `profile`. ⚠ Порядок
# роли не играет: связей между ними нет, и каждая сносится своим запросом.
#
# ⚠⚠ Совпадение со схемой сторожит `test_profile_drop.py`. Появится новая
# таблица без ключа — красный там, и это **не** «тест устарел»: её строки
# переживут анкету и останутся в базе навсегда.
PROFILE_DROP_TABLES = ('favorite', 'stat_day', 'gallery_file',
                       'companion_gallery_file', 'companion_guest',
                       'mail', 'intention_mail')

# Кто переживает анкету **намеренно**. ⚠⚠ Список нужен затем, что сторож
# сверяет первый со схемой: без второго он требовал бы снести и журналы, а
# молчаливое отсутствие в первом списке неотличимо от забывчивости.
#
# ⚠ Оба — журналы работы системы: `scenario_run` отвечает на «что вообще
# происходило», `request` — на «куда мы ходили и что ответили». У `request` к
# тому же свой срок, трое суток, и чистит его круг.
PROFILE_DROP_KEEP = ('scenario_run', 'request')


async def profile_drop(profile_id: int) -> dict:
    """Удаляет анкету и всё, что за ней не уходит само.

    Args:
        profile_id: номер анкеты в нашей базе.

    Returns:
        dict: `{имя таблицы: сколько строк убрано}` плюс `profile` — сама
        анкета (0 или 1). Пустых чисел в ответе нет.

    ⚠⚠ **Бесключевые сносятся раньше анкеты**, а не после. После — значит по
    номеру, который уже ни на что не указывает: найти строки ещё можно, но
    любая ошибка посреди уборки оставила бы их ничьими навсегда, и второго
    захода за ними не будет.

    ⚠ Одной транзакцией: оборвись она посередине, анкета осталась бы с
    наполовину убранным хвостом — состояние хуже исходного, потому что человек
    уже видит её удалённой.
    """
    out = {}

    async with mysql_get_db_async() as db:
        for table in PROFILE_DROP_TABLES:
            # ⚠ Имя таблицы уезжает в запрос текстом, поэтому только из
            # константы выше — не из довода и не из схемы на лету.
            await db.execute(f'DELETE FROM `{table}` WHERE profile_id = %s',
                             (int(profile_id),))
            if db.rowcount:
                out[table] = int(db.rowcount)

        await db.execute('DELETE FROM profile WHERE id = %s', (int(profile_id),))
        out['profile'] = int(db.rowcount or 0)

        await db.connection.commit()

    if len(out) > 1:
        logger_info(f'[dating] анкета #{profile_id} удалена, за ней убрано: '
                    + ', '.join(f'{k} {v}' for k, v in out.items()
                                if k != 'profile'))

    return out
