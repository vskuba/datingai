"""Адрес анкеты девушки **на самом сайте**: шаблон сайта плюс её номер.

Панель показывает анкету по-своему — карточка, настройки, расписание, — а живой
человек на сайте видит совсем другую страницу. Сверить одно с другим (то ли фото,
тот ли текст «о себе», не сняли ли анкету) можно только там, и дорога туда нужна
прямо из карточки.

## Почему шаблоном, а не полем у анкеты

Адрес анкеты на сайте строится по правилу, а не заводится руками: у Ladadate это
`https://ladadate.com/profile/{ID}`, где `{ID}` — номер анкеты (`site_uid`,
кладёт его импорт). Заводи мы адрес полем, его пришлось бы вписать тринадцать раз
на тринадцать анкет — и ещё раз на каждую новую, а при переезде сайта на другой
домен переписать все.

⚠ **Хвоста из имени в шаблоне не нужно.** Настоящий адрес анкеты длиннее —
`/profile/643694-single-ukrainian-lady-diana`, — но сайт на короткий отвечает
`301` и сам уводит на полный (проверено на трёх анкетах: 643694, 486221, 999029).
Собирать хвост из имени было бы догадкой: он приходит от сайта, а не считается по
имени, и ошибись мы — ссылка вела бы в никуда.

## Почему настройкой у нас, а не переменной у соседа

Правило проекта — «описывает сам сайт, значит живёт у соседа» — и адрес чата так
и лежит (`chat_companion_url_pattern`). Здесь взято иначе, и вот почему: ссылку
рисует **карточка анкеты**, а карточку открывают десятки раз за смену. Ходить за
шаблоном к соседу означало бы запрос к нему на каждое открытие — и пустую ссылку
всякий раз, когда он перезапускается. Настройки же сайта лежат в нашей базе рядом
со снимком его списка и читаются тем же запросом, что и всё остальное (`api.md`,
§3.5): панель не зависит от соседа там, где может не зависеть.

⚠ Метка та же — `{ID}`, — и это не совпадение: два вида адресов одного сайта,
записанные по-разному, человек рано или поздно перепутает местами.
"""

from urllib.parse import quote
from src.dating.site_setting import site_setting

# Метка номера в шаблоне. Та же, что у адреса чата у соседа (`send.py`).
PROFILE_LINK_MARK = '{ID}'

# Ключ настройки сайта. Реестр — `site_.SITE_KNOWN`.
PROFILE_LINK_SETTING = 'profile_url_pattern'

# С чего обязан начинаться шаблон. ⚠ Не педантизм: значение уезжает в `href` на
# странице, и `javascript:…`, вписанное в настройку, стало бы выполняемым кодом у
# каждого, кто откроет карточку. Настройку правит только админ, но «только админ»
# — это про то, кто вписал, а не про то, кто пострадает.
PROFILE_LINK_SCHEMES = ('https://', 'http://')


async def profile_link(site_id: int, site_uid: str) -> str:
    """Адрес анкеты на сайте или пустая строка, если его не собрать.

    Args:
        site_id: сайт-закладка анкеты — у него и спрашиваем шаблон.
        site_uid: номер анкеты на сайте (`profile_.profile.site_uid`).

    Returns:
        str: готовый адрес либо `''` — шаблона у сайта нет, он без метки `{ID}`,
        ведёт не по HTTP или у анкеты нет номера.

    ⚠ **Пустота — обычный исход, а не отказ.** Номер кладёт импорт с сайта, и у
    заведённых руками его нет вовсе (у Goldenbride сейчас нет ни у одной из
    сорока). Шаблон тоже заполнен не у каждого сайта. Ссылки в таких случаях
    просто не будет — бросать исключение значило бы ронять карточку из-за
    незаполненной настройки.
    """
    uid = str(site_uid or '').strip()
    if not uid:
        return ''

    pattern = str(await site_setting(int(site_id or 0),
                                            PROFILE_LINK_SETTING)).strip()

    return profile_link_build(pattern, uid)


def profile_link_build(pattern: str, site_uid: str) -> str:
    """Подстановка номера в шаблон — без похода в базу. Отдельно ради тестов.

    ⚠ Номер **кодируется** (`quote`), хотя приходит цифрами: он живёт в JSON
    анкеты, куда его положил разбор чужой страницы, и «цифры» — это ожидание, а
    не проверка. Незакодированная кавычка в адресе разорвала бы `href`.
    """
    pattern = str(pattern or '').strip()
    uid = str(site_uid or '').strip()

    if not pattern or not uid or PROFILE_LINK_MARK not in pattern:
        return ''

    if not pattern.lower().startswith(PROFILE_LINK_SCHEMES):
        return ''

    return pattern.replace(PROFILE_LINK_MARK, quote(uid, safe=''))
