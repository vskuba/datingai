"""Круг проверки выходов: просит реестр пройтись по прокси и забирает итог.

## Зачем

Прокси умирают молча. Канал кончился, провайдер сменил пароль, подсеть уехала в
чужие руки — ошибки при этом не происходит: она случится потом, когда анкета не
сможет войти на сайт, и выглядеть будет как беда сайта.

Круг переворачивает это: выходы проверяются по расписанию, мёртвый выпадает из
раздачи сам, а живой остаётся с честным `check_ip`.

⚠ **Проверяет реестр, а не мы.** Своя проверка пошла бы с адреса нашего
контейнера, и увиденный IP оказался бы не тем, который мы же считаем. Круг только
говорит «пора» и забирает итог.

## Включается галочкой у сайта

Настройка живёт у **сайта** (`proxy_ping_every`) — человек ищет её там, где
смотрит на пул. Это переключатель: «проверять каждые 5 минут» либо «только
вручную»; значение хранится секундами (`300` / `0`), потому что читает его отсюда
именно как срок.

Круг при этом один на установку: выходы общие, и проверять их дважды по двум
расписаниям значило бы стучаться к провайдеру вдвое чаще без всякой пользы.

⚠ **Просит хоть один сайт — проверяются все выходы.** Ноль у сайта значит «мне не
надо», а не «никому не надо»: один сайт не вправе оставить без свежих данных
чужие анкеты. Выключить проверку совсем можно, только сняв галочку у всех.

Срок берётся **наименьший** из настроенных — на случай, если у настройки снова
появятся варианты. Сейчас он один на всех, пять минут.

## Смена адреса у канала

⚠ Резидентные и мобильные каналы меняют внешний IP сами. Круг, увидев это,
**подтягивает новый адрес анкетам**, которые на этом выходе сидят: иначе предел
«анкет на IP» считался бы по адресу, которого больше нет, и две съехавшие на один
IP анкеты выглядели бы как сидящие на разных.

## Чего здесь нет

**Гашения мёртвых выходов.** `is_enabled` — выключатель человека, и код, который
его дёргает, отбирает у человека понимание, кто что выключил. Мёртвый выход и без
того не попадает к анкетам: раздача берёт только `check_ok` с увиденным адресом
(`proxy.py`), а на странице он уходит вниз серым.
"""

import time

from logging_.logging_ import logger_info
from mysql_.mysql_ import mysql_get_db_async

from src.dating.proxy import (PROXY_PING_SETTING,
                                     proxy_enabled)
from src.rhapsody.rhapsody_api import RhapsodyError, rhapsody_api_proxy_check_all

# Как часто круг просыпается. ⚠ Это **не** период проверки: он смотрит, не пора
# ли, и обычно уходит спать дальше. Минута — мельче любого разумного срока
# проверки и достаточно грубо, чтобы не будить процесс попусту.
PROXY_ROUND_TICK_SEC = 60

# Когда проверяли последний раз. В памяти смены, а не в базе: переживать
# перезапуск этой метке незачем — после него проверить заново скорее полезно.
_checked_at = 0.0


async def proxy_round_run() -> dict:
    """Один заход: если пора — просит реестр проверить выходы.

    Returns:
        dict: `ran` — ходили ли к реестру, `checked` и `ok` — сколько выходов
        проверено и сколько из них годных, `every` — выбранный срок в секундах.

    ⚠ **Ничего не бросает.** Круг крутится в смене рядом с остальными, и отказ
    соседа не должен ронять ни их, ни смену (`round.py` ловит всё, но
    внятная строка в журнале лучше трейсбека).
    """
    every = await _every()
    if not every:
        return {'ran': False, 'checked': 0, 'ok': 0, 'every': 0}

    global _checked_at
    if time.monotonic() - _checked_at < every:
        return {'ran': False, 'checked': 0, 'ok': 0, 'every': every}

    # ⚠ Метку ставим **до** похода, а не после. Проверка идёт до минуты; поставь
    # мы её потом, соседний тик успел бы начать вторую такую же.
    _checked_at = time.monotonic()

    try:
        rows = await rhapsody_api_proxy_check_all()
    except RhapsodyError as e:
        logger_info(f'[proxy] круг проверки: реестр не ответил — {e}')

        return {'ran': False, 'checked': 0, 'ok': 0, 'every': every}

    ok = sum(1 for row in rows if row.get('ok'))
    dead = [str(row.get('name') or row.get('id')) for row in rows if not row.get('ok')]

    moved = await _ip_sync(rows)

    # ⚠ Пишем в журнал только когда есть мёртвые. Строка «проверено 20, годных 20»
    # раз в десять минут — это сто сорок строк в сутки, за которыми не видно той
    # единственной, ради которой круг заведён.
    if dead:
        logger_info(f'[proxy] круг проверки: выходов {len(rows)}, годных {ok}; '
                    f'не отвечают: {", ".join(dead[:5])}'
                    + (f' и ещё {len(dead) - 5}' if len(dead) > 5 else ''))

    return {'ran': True, 'checked': len(rows), 'ok': ok, 'moved': moved, 'every': every}


# ── Приватное ────────────────────────────────────────────────────────────────

async def _ip_sync(rows: list) -> int:
    """Подтягивает у анкет новый внешний адрес их выхода. Возвращает, скольким.

    ⚠⚠ **Без этого счёт «анкет на IP» врёт молча.** Резидентные и мобильные
    каналы меняют внешний адрес сами, по своему усмотрению: строка подключения та
    же, а наружу смотрит другой IP. Анкета при этом продолжает ходить — ей всё
    равно, — но:

    * сайт видит **смену адреса у живой сессии**, а это подозрительнее паузы;
    * `profile_.proxy_ip` остаётся прежним, и предел мы считаем по адресу,
      которого больше нет. Две анкеты, съехавшие на один новый IP, для нас
      по-прежнему «на разных» — то есть защита, ради которой всё делалось,
      перестаёт работать, и узнаём мы об этом из блокировок.

    Кэш анкеты сам протух бы через `PROXY_FRESH_SEC` (полчаса), но полчаса
    неверного счёта — это полчаса, за которые круги успевают посадить на адрес
    лишних. Проверка уже знает новый адрес; подтянуть его стоит одного `UPDATE`.

    ⚠ Обновляем **только `proxy_ip`**: строка подключения (`proxy_url`) не
    менялась, а `proxy_at` трогать нельзя — по нему считается старшинство при
    перегрузе адреса (`proxy._fits`), и сдвиг сделал бы всех «младшими».
    """
    moved = 0

    async with mysql_get_db_async() as db:
        for row in rows:
            if not row.get('ok') or not row.get('ip'):
                continue

            await db.execute('UPDATE profile SET proxy_ip = %s '
                             ' WHERE proxy_id = %s AND proxy_ip <> %s',
                             (str(row['ip']), int(row['id']), str(row['ip'])))
            if db.rowcount:
                moved += db.rowcount
                logger_info(f'[proxy] выход #{row["id"]} сменил адрес на {row["ip"]}: '
                            f'подтянуто анкет {db.rowcount}')

        await db.connection.commit()

    return moved

async def _every() -> int:
    """Наименьший срок проверки из настроенных сайтами. Ноль — не проверяем.

    Ноль у отдельного сайта означает «мне не надо» и в расчёт не идёт: выходы
    общие, и один сайт не вправе оставить чужие анкеты без свежих данных. Ноль
    здесь выходит только если так сказали **все**.
    """
    from src.uvicorn.routers.dating.site_ import (site_rows,
                                                        site_seconds)

    try:
        rows = await site_rows()
    except Exception as e:
        logger_info(f'[proxy] круг проверки: список сайтов не спросился — {e}')

        return 0

    # ⚠ Ключ строки — `id`, а не `site_id`: `site_rows` уже переименовал
    # его для страницы, и ушедшие закладки (`is_gone`) отсеял сам.
    every = []
    for row in rows:
        # ⚠ Сайт, который выходами не пользуется, срока не задаёт — даже если
        # галочка автопроверки у него когда-то стояла. Иначе выключение прокси у
        # единственного сайта установки не останавливало бы походы к соседу: круг
        # продолжал бы гонять проверку каналов, которыми никто не ходит.
        if not await proxy_enabled(int(row['id'])):
            continue

        seconds = await site_seconds(int(row['id']), PROXY_PING_SETTING)
        if seconds:
            every.append(seconds)

    return min(every) if every else 0
