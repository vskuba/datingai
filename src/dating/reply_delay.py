"""Задержка ответа по длине текста: столько, сколько его писал бы человек.

## ⚠⚠ Зачем

Собеседник видит два времени рядом: когда он написал и когда пришёл ответ. Его
письмо в 15:42, наш ответ в 15:46 — и в ответе четыреста слов. Столько за четыре
минуты не печатает никто, и читается это ровно так, как есть: отвечала не
женщина. Поймано на живой переписке Olena ↔ Benoit 25.10.2026.

Правило простое: **сколько слов, столько времени**. Настройка сайта
`reply_delay_per_10_words` говорит, сколько секунд уходит на десять слов; ответ
из трёхсот слов при тридцати секундах ждёт пятнадцать минут.

## ⚠⚠ Отсчёт идёт от **его письма**, а не от сочинения черновика

Круг ответов сочиняет черновик через `reply_every` после входящего — обычно пять
минут. Эти пять минут человек потратил бы на то самое чтение и печать, и
складывать их с задержкой незачем: собеседник увидел бы двадцать минут там, где
назначено пятнадцать.

Поэтому ждём `время его письма + задержка`, а уже прошедшее засчитывается. Ответ,
пролежавший в пуле дольше срока, уходит сразу — и это тот же ответ на вопрос «не
пора ли», а не особый случай.

⚠ Отметка времени берётся у **сайта** (`mail_in.date_post`), и это верно: именно
её собеседник видит в своём ящике. Нет её — считаем от сочинения черновика, иначе
задержки не было бы вовсе.

## ⚠ Занятие одно — ответы на письма

Рассылка и приставание пишутся **первыми**: входящего письма у них нет, и
промежутка, который собеседник мог бы сравнить, тоже. Их частоту держат свои
правила — пауза анкеты (`favorite_mail_gap`) и расписание.

## ⚠⚠ Правило живёт здесь, а не в SQL

Очередь отправки спрашивает его куском `WHERE` (`reply_delay_hold_sql`), но сам
счёт идёт **в Python**: слова считает одна функция, и вторая её запись на языке
MySQL разошлась бы молча — запрос не падает оттого, что считает иначе. Та же
грабля и то же решение, что у жребия паузы (`favorite_mail_girls_busy_sql`).
"""


import re

from logging_.logging_ import logger_info
from mysql_.mysql_ import mysql_get_db_async

from src.dating.site_setting import site_seconds

# Настройка сайта: сколько секунд уходит на **десять** слов.
#
# ⚠ Десять, а не одно: «три секунды на слово» человек вводит целым числом с
# ошибкой в треть, а «30 секунд на десять слов» задаёт тот же темп точнее. Темп
# счётом как раз человеческий — 120 слов в минуту это быстрая печать вслепую,
# 20 секунд на десять слов.
REPLY_DELAY_SETTING = 'reply_delay_per_10_words'
REPLY_DELAY_DEFAULT = 30

# На сколько слов задан коэффициент. ⚠ Числом здесь, а не в формуле по месту:
# делитель и заголовок настройки обязаны говорить одно.
REPLY_DELAY_PER = 10

# Разметка в теле письма словами не считается. `<br/>` между абзацами — не слово,
# а у входящих из панели тегов бывает и больше.
_TAGS = re.compile(r'<[^>]{1,200}>')


def reply_delay_words(body: str) -> int:
    """Сколько слов в письме. Разметка не в счёт.

    ⚠ Слово — всё, что разделено пробелами, и считать точнее незачем: число
    уходит в срок, который человек задаёт на глаз десятками секунд.
    """
    return len(_TAGS.sub(' ', str(body or '')).split())


def reply_delay_sec(body: str, per10: int) -> int:
    """Сколько времени человек писал бы это письмо, в секундах.

    Args:
        body: текст ответа — то, что уйдёт.
        per10: секунд на десять слов (`reply_delay_per_10_words`). Ноль —
            задержки нет вовсе, и это законное «выключено».

    ⚠ Округление **вверх**: письмо из трёх слов при тридцати секундах на десять
    даёт девять, а не ноль. Ноль здесь означал бы «задержки нет», то есть
    настройку, которая на коротких письмах молча не работает.
    """
    per10 = int(per10 or 0)
    if per10 <= 0:
        return 0

    words = reply_delay_words(body)
    if not words:
        return 0

    return -(-words * per10 // REPLY_DELAY_PER)


def reply_delay_left(body: str, since: int, per10: int) -> int:
    """Сколько ещё ждать этому ответу, в секундах. Ноль — можно отправлять.

    Args:
        body: текст ответа.
        since: сколько секунд прошло с **его** письма.
        per10: секунд на десять слов.

    ⚠ Прошедшее засчитывается: круг сочиняет черновик не мгновенно, и эти минуты
    человек потратил бы на чтение и печать. Иначе промежутки складывались бы, и
    собеседник видел бы срок больше назначенного.
    """
    return max(0, reply_delay_sec(body, per10) - max(0, int(since or 0)))


async def reply_delay_per10(site_id: int) -> int:
    """Коэффициент сайта: секунд на десять слов. Одно чтение на всех.

    ⚠ Умолчание живёт здесь, а не у каждого спрашивающего: круг отправки, пул на
    странице и объяснение простоя обязаны понимать «настройки нет» одинаково.
    """
    try:
        return max(0, int(await site_seconds(int(site_id or 0),
                                             REPLY_DELAY_SETTING)))
    except Exception as e:
        logger_info(f'[dating] коэффициент задержки ответа сайта #{site_id} '
                    f'не прочитался: {e}')

        return REPLY_DELAY_DEFAULT


async def reply_delay_hold(site_id: int) -> dict[int, int]:
    """Ответы сайта, которым ещё рано: номер строки пула → сколько ждать, сек.

    ⚠ Один запрос на сайт, а не на ответ: пул общий, и спрашивать «готов ли» по
    строке значило бы ходить в базу на каждую карточку.

    ⚠ Берём только то, что круг и так может унести, — черновики без прежней
    ошибки: ответ с причиной отправка не трогает вовсе, и держать его незачем.

    ⚠⚠ **Сбой базы — молчим про задержку, а не держим всё.** Непрочитанный счёт
    означает неизвестный срок, а ответ, застрявший навсегда, хуже ответа,
    ушедшего раньше времени: первое чинит только человек, второе — следующее
    письмо.
    """
    site_id = int(site_id or 0)
    per10 = await reply_delay_per10(site_id)
    if not site_id or per10 <= 0:
        return {}

    try:
        async with mysql_get_db_async() as db:
            await db.execute(
                'SELECT r.id, r.body,'
                # ⚠ Разницу считает **база**: метки стоят по её часам, а процесс
                # живёт по своим — та же причина, что у паузы между письмами.
                ' TIMESTAMPDIFF(SECOND, COALESCE(i.date_post, r.created_at),'
                '                NOW()) AS since'
                '  FROM mail_reply r'
                '  LEFT JOIN mail_in i ON i.id = r.mail_in_id'
                " WHERE r.site_id = %s AND r.status = 'draft' AND r.error = ''",
                (site_id,))
            rows = await db.fetchall()
    except Exception as e:
        logger_info(f'[dating] задержки ответов сайта #{site_id} '
                    f'не спросились: {e}')

        return {}

    hold = {}
    for row in rows or []:
        left = reply_delay_left(row.get('body'), row.get('since'), per10)
        if left > 0:
            hold[int(row['id'])] = left

    return hold


async def reply_delay_hold_sql(site_id: int, key: str = 'm.id') -> str:
    """Условие «эти ответы ещё пишутся» — куском `WHERE`. Пусто — все готовы.

    Args:
        site_id: сайт-закладка.
        key: чем в чужом запросе зовётся номер строки пула.

    ⚠ Номера подставляются **числами**, а не `%s`: кусок уезжает в чужой запрос,
    где своя очередь подстановок, и лишний `%s` в середине сдвинул бы все
    остальные. Тот же приём, что у паузы анкеты и остуды получателей.
    """
    hold = await reply_delay_hold(site_id)
    if not hold:
        return ''

    return f' AND {key} NOT IN ({", ".join(str(int(one)) for one in hold)})'


def reply_delay_why(left: int) -> str:
    """Почему очередь стоит — словами. Пусто, если ждать нечего.

    ⚠ Срок называется прямо: «ещё пишется» без числа читается как зависший круг,
    и человек идёт проверять выключатели вместо того, чтобы подождать минуту.
    """
    left = int(left or 0)
    if left <= 0:
        return ''

    return (f'ответ ещё пишется: по длине текста он уйдёт через '
            f'{reply_delay_left_word(left)}')


def reply_delay_left_word(seconds: int) -> str:
    """Сколько ещё ждать: «40 с», «7 мин», «1 ч 10 мин».

    ⚠ Секунды нужны: у короткого ответа задержка меньше минуты, и «1 мин» вместо
    «20 с» обещало бы втрое больше, чем есть.
    """
    seconds = max(0, int(seconds or 0))
    if seconds < 60:
        return f'{seconds} с'

    minutes = round(seconds / 60)
    if minutes < 60:
        return f'{minutes} мин'

    hours, rest = divmod(minutes, 60)

    return f'{hours} ч' + (f' {rest} мин' if rest else '')
