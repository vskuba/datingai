"""Круг уборки журналов: убирает записи старше срока.

⚠ Журналов **два**, и чистятся они вместе: журнал внешних запросов
(`request`, срок настройкой панели) и журнал анкет (`log`, срок
настройкой сайта). Занятие одно — «прибраться в том, что растёт само», —
и второй круг ради него означал бы ещё одну задачу в держателе, которая
просыпается раз в час ради одного запроса.

## Зачем отдельный круг

Журнал внешних запросов растёт быстрее всего в базе: по настройкам прода около
52 тысяч строк в сутки на тринадцать анкет, из них 37 тысяч — удары присутствия.
Это полтора миллиона строк в месяц, больше всей остальной базы вместе взятой.

Чистить его при записи нельзя: писатели идут из десятка кругов разом, и `DELETE`
внутри вставки означал бы, что каждый удар присутствия ждёт чужой уборки.

## ⚠ Раз в час, а не раз в минуту

Тик круга — минута, как у соседей по смене, но сама чистка идёт **раз в час**:
удалять по горстке строк каждую минуту значит держать таблицу в постоянной
блокировке ради работы, которая терпит.

## ⚠ Срок — настройка, а не константа

`request_keep_days` на странице «Настройки → Значения», по умолчанию трое суток.
Разбирают такое задним числом: «вечер пятницы» должен быть на месте в понедельник
утром. Кому мало — поднимет, и цена этого решения видна ему же по размеру базы.
"""

import time

from src.dating.chat_reply import chat_reply_expire
from src.dating.log import log_sweep
from src.dating.request import request_sweep

# Как часто круг просыпается. ⚠ Не частота чистки: её задаёт срок ниже.
REQUEST_ROUND_TICK_SEC = 60

# Как часто чистим на самом деле. Час: таблица терпит, а блокировка — нет.
REQUEST_ROUND_EVERY_SEC = 3600

# Когда чистили последний раз. В памяти смены: переживать перезапуск метке
# незачем — после него прибраться заново только полезно.
_swept_at = 0.0


async def request_round_run() -> dict:
    """Один заход: если пора — убирает записи старше срока.

    Returns:
        dict: `ran` — чистили ли, `gone` — сколько строк убрано всего,
        `requests` и `logs` — по журналам.

    ⚠ **Ничего не бросает.** Уборка не повод ронять смену: оба сметальщика гасят
    свои отказы сами и возвращают то, что успели.
    """
    global _swept_at

    if time.monotonic() - _swept_at < REQUEST_ROUND_EVERY_SEC:
        return {'ran': False, 'gone': 0}

    # ⚠ Метку ставим **до** уборки: миллион строк режется пачками и не мгновенно,
    # а соседний тик завёл бы вторую такую же поверх первой.
    _swept_at = time.monotonic()

    requests = await request_sweep()
    # ⚠ Журнал анкет — вторым, а не вместо: сроки у них разные и заданы в
    # разных местах (панель против сайта), а занятие одно.
    logs = await log_sweep()
    # ⚠ И черновики ответа, которых никто не дождался. Они снимают у отбора
    # сторожевые проверки (`answer._waiting_find`), и без уборки послабление
    # работало бы вечно — однажды ушёл бы ответ недельной давности.
    stale = await chat_reply_expire()

    return {'ran': True, 'gone': requests + logs + stale,
            'requests': requests, 'logs': logs, 'drafts': stale}
