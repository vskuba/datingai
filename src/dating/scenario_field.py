"""Имена шагов `extract` в сценариях соседа: перевод со старых на новые.

Сценарии у RhapsodyAi называют свои шаги, а мы читаем результат по этим именам.
Имена были русскими (`'анкеты'`, `'текст_подсказка'`), то есть ключами на
кириллице, чего правило `code_rules.md` §1.2 не терпит: такой ключ не найти
`grep`-ом с латинской раскладки, а `с`/`c` и `о`/`o` в нём различимы только
байтами.

Переименовать их у себя в одиночку нельзя: имя задаёт **сценарий**, и разъехаться
с ним значило бы молча перестать понимать его ответ. Поэтому переезд идёт в три
захода, и порядок в нём — главное.

## ⚠⚠ Порядок выкладки, и обратный ломает прод

| Заход | Где | Что |
|-------|-----|-----|
| 1 | **DatingAi** | этот модуль: код понимает **оба** имени — новое и старое |
| 2 | **RhapsodyAi** | миграция переименовывает шаги в сценариях |
| 3 | потом, отдельно | старые имена убираются отсюда |

Выложи мы сперва сценарии, и работающий на проде код перестал бы понимать ответ —
разом встали бы импорт анкет, списки собеседников, переписка из панели, отправка
и избранные. Ровно эта грабля уже случалась при снятии входящей переменной у
соседа и стоила 91 отказа.

Между первым и вторым заходом всё работает: код читает новое имя, не находит и
берёт старое.

## ⚠ Одно имя — один перевод, даже когда смысл разный

`'номер'` в импорте — номер анкеты, в переписке из панели — номер сообщения. Имя
при этом одно, и перевод у него один (`number`): карта переводит **имена**, а не
значения, и второй перевод под тот же ключ развёл бы одно имя на два.

## ⚠ Чего здесь нет

**Записи наружу.** Модуль только читает ответ прогона. Имена, которые мы сами
отправляем сценарию (подстановки, `variables`), латинские и были такими всегда.

**Шагов, которые латиницей были всегда.** Сценарии диалогов (`dialog.py`) и
выгрузки (`export.py`) зовут свои шаги `head`, `flow`, `names` — их никто не
переименовывал, в карте их нет, и читать их через эту дверь незачем. Признак, по
которому читателя переводят сюда, механический: **его имя есть в карте**.
"""

# Новое имя шага → старое. ⚠ Одна таблица на все сценарии: имена у них общие по
# смыслу (`имя`, `фото`, `ссылка` встречаются в пяти), и таблица на каждый сценарий
# разошлась бы с остальными на первой правке.
#
# ⚠⚠ Это **единственное место**, где кириллица в значениях ключей уместна: справа
# — имена, которые задал сценарий у соседа, и до второго захода выкладки они
# живые. После него таблица уходит целиком (третий заход).
SCENARIO_FIELD_WAS = {
    # Поля верхнего уровня: под ними лежат списки записей.
    'profiles': 'анкеты',
    'men': 'мужчины',
    'favorites': 'избранные',
    'dialogs': 'диалоги',
    'messages': 'сообщения',
    # Поля внутри записи.
    'name': 'имя',
    'city': 'город',
    'number': 'номер',
    'photo': 'фото',
    'link': 'ссылка',
    'status_class': 'статус_класс',
    'is_new': 'новый',
    'when': 'когда',
    'from': 'от',
    'from_uid': 'от_номер',
    'to': 'кому',
    'to_uid': 'кому_номер',
    'text': 'текст',
    'text_title': 'текст_подсказка',
    # Одиночные шаги `extract`.
    'sent': 'отправлено',
    'profile': 'анкета',
    'head': 'шапка',
    'before': 'до',
    'after': 'после',
}


def scenario_field(data, name: str):
    """Значение шага по новому имени; нет его — по старому. `None` — нет обоих.

    Args:
        data: `extract` прогона либо одна запись из `extract_rows`.
        name: **новое** имя шага, латиницей.

    Returns:
        Значение как его положил сценарий, без приведения типа: вызывающий знает,
        строка это, список или число.

    ⚠ Новое имя спрашивается **первым**: после второго захода выкладки старого в
    ответе не будет вовсе, и лишний промах по отсутствующему ключу не нужен.

    ⚠ `None` и пустая строка — разное: пустую строку сценарий **положил**, и
    вызывающие на это опираются (статус офлайн-собеседника приходит пустым).
    Поэтому запасное имя спрашивается только когда нового ключа нет вовсе.
    """
    got = data if isinstance(data, dict) else {}
    if name in got:
        return got[name]

    return got.get(SCENARIO_FIELD_WAS.get(name, ''))
