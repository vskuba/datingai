"""Разбор страницы собеседника: третья половина драйвера сайта.

Анкету мужчины снимает обычный GET (`companion_about.companion_about_http`), а
вот **что считать анкетой в отданном HTML** — вопрос к сайту: у каждого своя
вёрстка, свои классы блоков и свой способ показать подписи.

## ⚠⚠ Почему драйвером, а не одной функцией с `if`

Сайтов у нас будет больше одного, и разметка у них общего не имеет вовсе. Пиши мы
разбор одной функцией, она через три сайта превратилась бы в лестницу условий, где
правка под Goldenbride молча ломает LadaDate — а заметно это станет на живом пуле,
письмами без описаний.

Здесь тот же приём, что у чата и анкеты девушки (`site_registry.py`): имя драйвера
берётся из `presence.driver`, и новому сайту достаточно нового класса рядом.

## ⚠ Настройкой, если вёрстка укладывается

Большинству сайтов класса не нужно: хватит блоков в `presence.about`, и базовый
драйвер прочитает их сам.

    "about": {
      "path": "/profile/{uid}",
      "blocks": {"анкета": "user__profile-info", "шапка": "top__profle-wr"}
    }

Класс заводят, когда разметка требует **другого разбора**, а не других имён: поля в
таблице вместо подписей, описание за кнопкой, отдельный запрос за «About myself».

## ⚠ Что драйвер отдаёт

Два куска текста под теми же именами, что `extract` у сценария, — «анкета» и
«шапка». Дальше их разбирает общий код (`companion_about`): подписи полей, место,
имя и возраст. Это нарочно: подписи у сайтов похожи куда больше, чем вёрстка, и
разносить по драйверам ещё и их значило бы копировать одно и то же.
"""

import html as html_
import re

# Тег с именем: нужен, чтобы считать вложенность при вырезании блока.
_TAG_RE = re.compile(r'<(/?)([a-zA-Z][a-zA-Z0-9]*)[^>]*>')

# Сколько знаков взять, если закрывающий тег блока не нашёлся: вёрстка испорчена,
# но текст в ней есть, и обрезок полезнее пустоты.
ABOUT_TAIL_MAX = 4000


class DatingSiteAbout:
    """Базовый разбор: блоки по классу, текст — видимый.

    Работает у всякого сайта, который отдаёт анкету готовым HTML и держит поля в
    блоке с постоянным классом. Имена блоков и путь берутся из `presence.about`.
    """

    name = 'base'

    # Путь к странице собеседника. `{uid}` — его номер на сайте.
    path = '/profile/{uid}'

    # Какие блоки снимаем: имя для разбора → класс в вёрстке.
    #
    # ⚠ Имена те же, что у `extract` в сценарии («анкета», «шапка»): дальше их
    # разбирает общий код, и второй набор имён означал бы второй разбор.
    blocks = {'profile': 'user__profile-info', 'head': 'top__profle-wr'}

    # Какой тег считаем рамкой блока. ⚠ Почти всегда `div`; выносится в поле
    # затем, чтобы сайт на `section` закрывался настройкой, а не новым классом.
    frame = 'div'

    # Слова, которые в разметке есть, а в тексте не нужны: подписи кнопок внутри
    # блока.
    #
    # ⚠⚠ **Это не косметика.** «More» раскрывает длинное описание, и в HTML стоит
    # сразу после него: «…and have a good sense of humor. More». Такой хвост уезжает
    # агенту, который сочиняет вопрос, а оттуда — в письмо живому человеку.
    #
    # ⚠ Слово целиком и с краю: «More» внутри фразы («More than anything») —
    # законный текст, и вырезать его нельзя.
    drop = ('More', 'Less', 'Show more', 'Show less')

    # Как на сайте зовут поля анкеты: строка — подпись и есть канон, пара
    # `(подпись сайта, канон)` — на сайте она называется иначе, `None` в каноне —
    # только граница, значение между границами выбрасывается (см.
    # `companion_about_parse`).
    #
    # ⚠ Пусто значит «общий список» (`COMPANION_FIELDS`): у сайтов этой семьи
    # подписи страницы и есть канон, и заводить для каждого свою копию списка
    # значило бы иметь N перечней одного правила. Класс со своей картой нужен
    # там, где **имена разъехались**, — как у Step2Love: «Eye color» вместо
    # «Eyes Color», «Hair length» вместо «Hair Color» и целый блок вопросника.
    about_fields: tuple = ()

    def __init__(self, presence: dict | None = None):
        about = ((presence or {}).get('about') or {})

        self.path = str(about.get('path') or self.path)
        self.blocks = dict(about.get('blocks') or self.blocks)
        self.frame = str(about.get('frame') or self.frame)
        self.drop = tuple(about.get('drop') or self.drop)

    def url(self, base: str, uid: str) -> str:
        """Адрес страницы собеседника."""
        return str(base).rstrip('/') + self.path.format(uid=str(uid))

    def parse(self, html: str) -> dict:
        """Страница → куски текста под именами блоков.

        Returns:
            dict: `{'profile': '…', 'head': '…'}`. Пустая строка у блока значит,
            что его в разметке нет — сайт сменил вёрстку либо отдал не ту
            страницу.
        """
        return {name: self.block(html, mark)
                for name, mark in self.blocks.items()}

    def block(self, html: str, mark: str) -> str:
        """Текст блока по классу — то же, что `extract` у сценария.

        ## ⚠⚠ Разбор идёт по вложенности, а не «до следующего такого же»

        Первая версия резала от класса до конца строки и хватала полторы тысячи
        знаков наугад — на живой странице это давало «Id: 102327 Location limoges,
        France» и обрыв посреди описания.

        Здесь считается баланс рамочных тегов: от открывающего до того, который
        его закрывает. Так берётся ровно блок, сколько бы в нём ни было вложенного.
        """
        html = str(html or '')
        start = html.find(str(mark))
        if start < 0:
            return ''

        # Отступаем к началу самого тега: класс стоит внутри него.
        start = html.rfind('<', 0, start)
        if start < 0:
            return ''

        depth, at = 0, start
        while at < len(html):
            tag = _TAG_RE.search(html, at)
            if not tag:
                break

            if tag.group(2).lower() == self.frame:
                depth += -1 if tag.group(1) else 1
                if depth == 0:
                    return self.text(html[start:tag.end()])

            at = tag.end()

        # Закрывающего не нашлось — отдаём что есть: испорченная вёрстка лучше
        # пустоты.
        return self.text(html[start:start + ABOUT_TAIL_MAX])

    def text(self, html: str) -> str:
        """Видимый текст куска разметки.

        ⚠ **Теги сносим, а на их месте оставляем пробел.** Без него
        `<p>Occupation</p><p>plumber</p>` склеивается в «Occupationplumber», и
        разбор по подписям не находит ничего.

        ⚠ **Сущности раскрываем все**, а не список: в анкетах полно числовых —
        `&#237;` вместо `í` у испанца, `&#241;` вместо `ñ`. Браузер показывал их
        знаками, и разбор ждёт того же.

        ⚠ **Переводы строк сохраняем**: разбор по подписям ищет их как границы
        полей.
        """
        text = re.sub(r'<(script|style)[^>]*>.*?</\1>', ' ', str(html or ''),
                      flags=re.S | re.I)
        text = re.sub(r'<[^>]+>', ' ', text)
        text = html_.unescape(text)
        text = re.sub(r'[ \t\r\f\v]+', ' ', text)
        text = '\n'.join(line.strip() for line in text.split('\n')).strip()

        return self.without_buttons(text)

    def without_buttons(self, text: str) -> str:
        """Убирает подписи кнопок, стоящие в конце строки.

        ⚠ **Только в конце и только словом целиком.** Кнопка «More» стоит сразу за
        текстом, который раскрывает, — там ей и место; «More» же посреди фразы
        («More than anything I want…») это слова человека.
        """
        if not self.drop:
            return text

        tail = '|'.join(re.escape(one) for one in self.drop)

        return re.sub(rf'\s*\b(?:{tail})\s*$', '', text,
                      flags=re.MULTILINE).strip()


class DatingSiteAboutLadadate(DatingSiteAbout):
    """LadaDate: базовая вёрстка, имя драйвера ради явности.

    ⚠ Своего разбора не имеет, и это законно: сайт укладывается в базовый. Класс
    заведён затем, чтобы `presence.driver = 'ladadate'` находил его по имени, а не
    падал в умолчание — молчаливое умолчание однажды скроет, что сайт разъехался.
    """

    name = 'ladadate'
