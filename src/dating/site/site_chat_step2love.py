"""Чат Step2Love: разговор открывается приглашением, и это меняет «доставлено».

## ⚠⚠⚠ Чем этот сайт отличается от прочих

У всех остальных написать человеку можно всегда: отправка либо уходит, либо
отказывает. Здесь между «отправили» и «прочитал» стоит ещё одно состояние —
**разговор не открыт**. Чат у этого сайта отдельный объект: он закрывается
крестиком, и собеседник, вернувшийся на страницу, закрытый диалог не видит.

Написать в такой разговор нечем. Открыть его может только приглашение
(`chat_request.py`), и приглашение **несёт текст** — собеседник читает его
прямо в списке запросов. То есть первая реплика и приглашение у этого сайта
одно событие.

## ⚠⚠⚠ Отсюда и «доставлено» у него своё

Ушедшее приглашением лежит в списке запросов и ждёт галочки. Не нажали —
сайт стирает запрос по своему сроку, и текст не читал никто.

Замер 03.11.2026: инициатива Anastasiya → Semen ушла приглашением в 17:01:28,
к 17:30 запроса не было ни в списке анкеты, ни в панели, чат не открылся — а
обмен #4730 у соседа стоял **«доставлен»**.

Цена лжи здесь та же, что у правки черновика руками: агент считает реплику
сказанной и продолжает разговор от непрочитанного. Расхождение молчаливое,
всплывает странным ответом через неделю.

## ⚠⚠ Почему драйвером, а не развилкой в круге

Развилка `if result['offline']` внутри `initiative_round` работала бы — ровно
до второго места, которому нужен тот же ответ. Их уже видно три: инициатива,
инвайты и ручная кнопка. Три копии одного правила разошлись бы на первой же
правке, причём **по сайтам**: поправили бы под Step2Love, а изменилось бы и у
Ladadate, где приглашений нет вовсе и «доставлено» значит просто «ушло».

## ⚠⚠ Наследник goldenbride, а не базы

До этого файла Step2Love брал драйвер чата **по умолчанию**, то есть
`goldenbride` (имени `step2love` в таблице не было). Заведи мы класс от
`DatingSiteChat`, у сайта молча сменились бы кадры, разбор и признаки —
вместе с появлением одного нового метода. Поэтому за основу взят тот класс, что
работал, а своего здесь — ровно два ответа.
"""

from src.dating.site.site_goldenbride import DatingSiteChatGoldenbride


class DatingSiteChatStep2Love(DatingSiteChatGoldenbride):
    """Step2Love: разговор открывается приглашением, и приглашение — не доставка."""

    name = 'step2love'

    def invites(self) -> bool:
        """Да: без принятого приглашения разговора у этого сайта не бывает."""
        return True

    def delivered(self, result: dict) -> bool:
        """Доставка — только то, что ушло **в живой чат**.

        Args:
            result: ответ `send_message`.

        Returns:
            bool: `True` — собеседник уже открыл разговор, и реплика легла ему
            в ленту. `False` — либо не ушло вовсе, либо ушло приглашением и
            ждёт согласия.

        ⚠⚠ Признак приглашения — `offline` при удаче. Пара странная на вид, и
        она намеренная: `offline` у этого транспорта значит «живого чата нет»,
        а `ok` — «сайт принял кадр». Вместе это ровно «приглашение ушло,
        разговор ещё не открыт» (`send_connection.py`).
        """
        return bool(result.get('ok')) and not result.get('offline')
