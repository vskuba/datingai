"""Ленты сайта под сессией анкеты: без браузера и без сценария.

Восьмая грань драйвера. Чат — про кадры сокета, анкета — про поля JSON, панель —
про чужой кабинет, описание собеседника — про вёрстку его страницы, гости —
про разбор ответа сценария, избранные — про ручку чата, а эта — про **две ленты
сайта, которые читаются обычным GET под cookie анкеты**: «кто сейчас в сети»
и «кто приходила в гости».

## ⚠⚠ Зачем эта дорога появилась

26.11.2026 в 20:56 агентство Step2Love **заблокировало нам панель**: все десять
девушек вышли из сети, вход перестал проходить. Виной была не переписка и не
рассылка, а ленты: сценарий «анкеты мужчин: список» гонялся каждые
`online_check_every` (на проде — две минуты), а «гости: список» — под каждой
анкетой, и **каждый прогон у соседа это вход в панель**, потому что сценарий
живёт там. Один только онлайн — тридцать заходов в час, и в чужом учёте это
тридцать посещений кабинета.

А между тем сессия анкеты уже живая: круг присутствия держит её cookie
живыми каждую минуту (`http_heartbeat.py`), и кабинет под этими cookie
открывается обычным GET (`site_session.py` — оттуда же, откуда `companion_about`
и `site_favorite`). Панель для лент не нужна вовсе: сто́ит копейку, сайтом
входом не считается.

## Граница

Базовый класс держит **механику**: сколько страниц онлайна пройти, где встать,
когда пустая страница — отказ, а когда правда. Класс сайта даёт **адреса и
вёрстку**: где у этого сайта эти ленты и как выглядят его строки. А правила
карточки здесь не чужие: карточки строит `people_rows` — те же, что разбирают
строки сценарного прогона, иначе один и тот же человек получал бы разные номера
в разных списках (та же грабля, что уже стоила потерянных визитов в `guests`).

## ⚠ Пустой список и «не снялось» — разные ответы

⚠⚠ **Онлайн не бывает пустым молча.** Пустая первая страница либо правда,
либо мёртвая сессия, а отличить их надо, потому что «лента не пришла» и
«никого нет» — разные ответы, и путаница стоит рассылки в пустоту. Правила:

* страницы есть → лента живая, идём дальше;
* первую страницу сайт отдал без строк (увёл на вход или показал форму входа)
  → **отказ**, снимок остаётся прежним с причиной;
* страницу без строк в середине пагинации → просто конец ленты;
* ни одной строчки на первой странице, но и признаков входа нет → отказ: на
  живом сайте строчка разбора обязана быть, её отсутствие — смена вёрстки.

Гости — наоборот: **пустая страница гостей законна** (никто не приходил).
Отказ здесь только когда явно не пустили: увели на вход или показали форму.
"""

from urllib.parse import urlparse

from src.dating.guests import GUESTS_FIELD, guests_rows
from src.dating.people import PEOPLE_ROWS_PAGE_MAX, people_rows
from src.dating.site_session import DatingSiteSessionError, site_session_get


class DatingSiteFeedError(RuntimeError):
    """Ленту с сайта снять не вышло. Текст пригоден для журнала и для страницы."""


class DatingSiteFeed:
    """Лента по умолчанию: по HTTP не умею — ленты идут прежней дорогой (сценарий).

    ⚠ Именно так работают все сайты, кроме Step2Love, и ломать это ради
    единообразия незачем: сценарии у них есть и работают.
    """

    name = 'base'

    def __init__(self, presence: dict | None = None):
        self.presence = presence or {}

    # ── Переключатель и адрес сайта ──────────────────────────────────────────

    def by_http(self) -> bool:
        """Снимаются ленты этого сайта под сессией анкеты? Базовый — нет."""
        return False

    def site_base(self) -> str:
        """Адрес сайта из закладки (`presence.base`), без косой черты на конце."""
        return str(self.presence.get('base') or '').rstrip('/')

    # ── Что даёт класс сайта ─────────────────────────────────────────────────

    def online_url(self, page_no: int) -> str:
        """Адрес страницы онлайна. Первая — витрина, дальние — продолжения."""
        raise NotImplementedError

    def guests_url(self) -> str:
        """Адрес страницы гостей под сессией этой анкеты."""
        raise NotImplementedError

    def page_rows(self, html: str) -> list[dict]:
        """HTML страницы → сырые строки, те же поля, что `extract_rows` прогона."""
        return []

    def login_page(self, html: str) -> bool:
        """Похожа ли страница на форму входа: сессия мертва, но нас не перенаправили."""
        return False

    def guests_cards(self, rows: list[dict], html: str) -> list[dict]:
        """Строки гостей → карточки. Разбор общий, дат по умолчанию нет."""
        return guests_rows({GUESTS_FIELD: rows}, GUESTS_FIELD)

    # ── Две ленты ────────────────────────────────────────────────────────────

    async def online_rows(self, profile: dict) -> list[dict]:
        """Список «кто в сети» всего сайта — под сессией одной анкеты.

        ⚠ **Пагинация та же, что у сценарного съёма:** витрина плюс
        `PEOPLE_ROWS_PAGE_MAX - 1` продолжений, встать на первой странице без
        строк. Считать карточки отдано `people_rows` — он же чинит двойные
        строки сайта (каждый человек в сетке лежит дважды), и делает это ровно
        так, как привыкли списки, приехавшие сценарием.
        """
        rows: list[dict] = []

        for page_no in range(1, PEOPLE_ROWS_PAGE_MAX + 1):
            html, moved = await self._fetch(profile, self.online_url(page_no))
            part = self.page_rows(html)

            if not part:
                if moved or self.login_page(html):
                    raise DatingSiteFeedError(
                        'сайт увёл на вход: сессия не признана')
                if page_no == 1:
                    raise DatingSiteFeedError(
                        'сайт отдал страницу без строк онлайна')

                break   # конец ленты: страница без строк, а не без ответа

            rows += part

        return people_rows({'men': rows}, 'men')

    async def guests_rows(self, profile: dict) -> list[dict]:
        """Гости этой анкеты — под её собственной сессией.

        ⚠ Под чужой cookie страница пустая, поэтому дорога и поанкетная, как у
        круга гостей: анкета спит — снимаем не её, а ничего (см. `guests_round`).
        """
        html, moved = await self._fetch(profile, self.guests_url())
        rows = self.page_rows(html)

        if not rows and (moved or self.login_page(html)):
            raise DatingSiteFeedError('сайт увёл на вход: сессия не признана')

        return self.guests_cards(rows, html)

    # ── Приватное ────────────────────────────────────────────────────────────

    async def _fetch(self, profile: dict, url: str) -> tuple[str, bool]:
        """Один GET под сессией анкеты. Ответ: HTML и «нас увели с адреса».

        ⚠ «Увели» считается по **пути** финального адреса, а не по факту
        перенаправления: http→https и догоняющий слэш случаются и у живой
        сессии, а вот вход под мёртвой всегда меняет страницу.
        """
        try:
            answer = await site_session_get(profile, url)
        except DatingSiteSessionError as e:
            raise DatingSiteFeedError(str(e)) from e

        if answer.status_code >= 400:
            raise DatingSiteFeedError(f'сайт ответил кодом {answer.status_code}')

        return answer.text, urlparse(str(url)).path != answer.url.path
