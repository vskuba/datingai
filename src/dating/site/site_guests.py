"""Гости: каким сценарием снимать список и как разбирать его ответ.

Шестая грань драйвера сайта: чат — про кадры сокета, анкета — про имена полей
JSON, панель и переписка — про чужой кабинет, описание собеседника — про вёрстку
его страницы, а эта — про **страницу визитов в кабинете самой анкеты**. У сайтов
она выглядит по-разному даже в одном движке: где-то список карточек с датой на
каждой, где-то строки таблицы, где-то дата лежит голым текстом в ячейке, и
селектором её не взять — только текстом строки.

## Граница

Драйвер отвечает на два вопроса и ни на что больше:

* **как звать сценарий** у соседа — имя прогона;
* **что в ответе прогона человек** — строки `extract` в карточки с датой визита.

Запуск сценария, слоты, остуды и запись визитов остаются у `guests_round.py` и
`guests.py`: они про нашу механику, а не про сайт. Драйвер — чистая функция
разбора, ему не нужны ни база, ни сеть.

## ⚠ Почему драйвером, а не `if` по сайту

Сайтов больше одного, и общего у них только замысел ленты. Пиши разбор одной
функцией с развилкой, правка под Step2Love молча ломала бы LadaDate — заметно
это стало бы на живой ленте, где у половины карточек пропали бы даты. Тот же
приём, что у чата, анкеты и панели (`site_registry.py`): имя драйвера из
`presence.driver`, новому сайту — новый класс рядом.

## Что отдаёт `rows`

Список карточек `people_row_card` (`uid`, `name`, `age`, `photo`) плюс `visit` —
дата (`datetime.date`) или `None`. Правила карточки — **не свои**: `uid`, имя и
фото обязаны приехать через `people_row_card`/`people_rows`, иначе номер, по
которому визит притягивается к человеку, считался бы в двух местах по-разному
(та же грабля, что уже стоила потерянных строк в `message_twin`).
"""

from src.dating.guests import GUESTS_FIELD, GUESTS_SCENARIO, guests_rows


class DatingSiteGuests:
    """Гости по умолчанию: сценарий «гости: список», съём шагом `guests`."""

    name = 'base'

    def __init__(self, presence: dict | None = None):
        self.presence = presence or {}

    def scenario_name(self) -> str:
        """Имя сценария у соседа. Голое: `scenario_find` сама терпит суффикс
        « (Метка)», которым заведено имя, когда голое занято."""
        return GUESTS_SCENARIO

    def rows(self, extract: dict) -> list[dict]:
        """Строки прогона — карточками с датами; разбор общий, `guests_rows`."""
        return guests_rows(extract, GUESTS_FIELD)
