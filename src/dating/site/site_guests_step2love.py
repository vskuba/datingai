"""Step2Love: гости — сетка карточек, а дата визита лежит в ней голым текстом.

Страница `guests/` этого сайта показывает гостей той же сеткой `gal_*` карточек,
что и остальные списки собеседников (`favorite.py`, `people`), — и разбор
карточек тот же общий. Не одна дата: **она не завёрнута в элемент**. В ячейке
карточки лежат `p` с именем, номером и возрастом, кнопка «Send Intro», а после
них — перенос и просто текст `27-10-2026`. Селектором голый текстовый узел не
взять (`querySelector` знает только элементы), поэтому дата приехать может
только **текстом страницы** — вторым шагом съёма, `read_text`.

## Как date встречается с карточкой

Прогон отдаёт два куска: `guests` — структурные строки (`extract_rows`, в них
`uid`/`name`/`photo`) и `guests_text` — текст той же страницы. Сшиваются по
`uid`, а не по позиции: текст режется лимитом чтения, карточек в нём может
оказаться меньше или больше, и сшивка по индексу разъехалась бы молча — даты
уехали бы на чужих людей. Номер у карточки и маркер `(ID: 834523)` в тексте —
одно и то же число, вынутые одним правилом.

## ⚠ Возраст — тоже из текста

На карточке возраст подписан (`Возраст: 65`), но подписью же, а не полем
строки: в `people_row_card` он приехал бы нулём, и карточка человека в
`companion` стояла бы без возраста у всех гостей. Цифру берёт тот же кусок
текста.

## ⚠ Пустая страница — не отказ

У анкеты без гостей сетки нет вовсе: `guests` пуст, `guests_text` — кабинет без
карточек. Это ответ «гостей нет», а не ошибка, и круг ставит слот (см.
`guests_round.py`).
"""

import re

from src.dating.guests import GUESTS_FIELD, guests_rows, guests_visit_day
from src.dating.scenario_field import scenario_field
from src.dating.site.site_guests import DatingSiteGuests

# Имя шага-подсказки: имена карточек вынуты структурно, а вот даты и возраст —
# из него. Латиницей, как требуют правила переезда имён (`scenario_field.py`).
GUESTS_TEXT_FIELD = 'guests_text'

# Маркер карточки в тексте страницы: «(ID: 834523)». Разбивает текст на куски,
# каждый из которых — одна карточка от своего маркера до следующего.
_UID_MARK_RE = re.compile(r'\(ID: (\d+)\)')

# «27-10-2026» — дата после «Send Intro»; в куске она первая, но ищется и без
# привязки: у заблокированного гостя кнопки мог не быть.
_WHEN_RE = re.compile(r'Send Intro\s*(\d{2}-\d{2}-\d{4})')
_WHEN_ANY_RE = re.compile(r'(\d{2}-\d{2}-\d{4})')

# «Возраст: 65» — число может уехать на следующую строку, `\s` терпит и неё.
_AGE_RE = re.compile(r'[Вв]озраст:?\s*(\d{1,3})')


class DatingSiteGuestsStep2Love(DatingSiteGuests):
    """Гости Step2Love: сетка `gal_*` плюс даты и возраст из текста страницы."""

    name = 'step2love'

    def rows(self, extract: dict) -> list[dict]:
        """Карточки общего разбора + даты и возраст из текста той же страницы.

        ⚠ Карточки делает **базовый** `guests_rows`: правила `uid`, имени и фото
        у сайта общие со всеми лентами, своей копии им нет.
        """
        cards = guests_rows(extract, GUESTS_FIELD)
        visits = _guests_page_visits(
            str(scenario_field(extract, GUESTS_TEXT_FIELD) or ''))

        for one in cards:
            got = visits.get(one['uid'])
            if not got:
                continue

            if got.get('visit'):
                one['visit'] = got['visit']

            if int(got.get('age') or 0) > 0:
                one['age'] = int(got['age'])

        return cards


# ── Приватное ────────────────────────────────────────────────────────────────

def _guests_page_visits(text: str) -> dict:
    """Текст страницы — в `{uid: {'visit': date|None, 'age': int}}`.

    Args:
        text: `read_text` той же страницы, что и сетка карточек.

    ⚠ Кусок карточки — от её маркера до следующего. Дата и возраст ищутся **в
    своём куске**: найдёшь по всему тексту — и у второго гостя окажется дата
    первого, лента врёт свежестью молча.

    ⚠ Кусок обрезается с запасом: после «Send Intro» и даты в разметке идёт
    «Статус:…» — свободный текст посетителя, в нём теоретически может найтись
    похожая на дату строка. Окна в несколько сотен символов хватает на живую
    карточку, а чужой текст остаётся за краем.
    """
    parts = _UID_MARK_RE.split(text)
    out: dict[str, dict] = {}

    # `split` по маркеру даёт чередование: преамбула, номер, кусок, номер,
    # кусок… Преамбула — шапка кабинета, её не разбираем.
    for index in range(1, len(parts) - 1, 2):
        uid = parts[index]
        if uid in out:
            continue

        chunk = parts[index + 1][:600]
        match = _WHEN_RE.search(chunk) or _WHEN_ANY_RE.search(chunk)
        age = _AGE_RE.search(chunk)

        out[uid] = {'visit': guests_visit_day(match.group(1)) if match else None,
                    'age': int(age.group(1)) if age else 0}

    return out
