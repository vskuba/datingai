"""Где у сайта лежит переписка и как её читать: пятая грань драйвера сайта.

Долго выбор был один на все сайты: страница `userchatmessages` Goldenbride-образной
панели (см. `chat_panel.py`). Он и ломался по-своему: у Step2Love агентская панель
(`agency.step2love.com`) такой страницы не имеет вовсе, и забор переписки ходил за
ней каждые пять минут, получая `404` там, где панель была совершенно живая. Журнал
«Запросы» показывал 100 строк 404 за день, а человек в это же время открывал
страницы панели руками — и правой руки не хватало: путь страницы был зашит, а не
спрошен.

## Что отвечает эта грань

Три вопроса, и ни одного из них не решают втроем прежние:

* **формат даты панели** — Goldenbride понимает только `дд.мм.гггг`, Step2Love —
  `гггг-мм-дд`; на чужой формат панель молча подставляет свой срок, и это не
  отказ, а тихая подмена (см. `panel_fetch.py`);
* **как звать сценарий** у соседа — имена шагов и сам сценарий у сайтов разные;
* **где журнал и как извлечь из него строки** — у Goldenbride это одна страница с
  пятью столбцами, у Step2Love — страница задач, ссылки которой ведут то на
  фильтрованные списки писем, то на историю чата.

## Граница

Драйвер **ходит в панель и разбирает её страницы** — и на этом останавливается.
Запись в `message`, близнецы, значки ленты и перенос инвайтов остаются у
`chat_panel`: они про нашу механику, а не про сайт. Строки драйвер отдаёт тем же
видом, что отдаёт сценарий (`chat_panel_rows` один на все дороги), — и вторая
копия разбора не заводится.

Страницу драйвер читает `panel_fetch`-ом под сессией круга (`panel_round.py`);
своего входа здесь нет, как и у прочих читателей панели.

## Выбор

По ключу `driver` в описании сайта (`site_registry.py`), как у остальных граней.
Без драйвера — переходное умолчание `goldenbride` (та же transitional-мера, что у
чата и анкеты; убрав её, уберите и её копию здесь).
"""

# Формат даты, которым по умолчанию говорит большинство панелей — `дд.мм.гггг`.
# Проверено на живой странице Goldenbride: тот же формат она принимает строкой
# запроса и им же заполняет поля формы.
DATING_IMPORT_DATE_FMT = '%d.%m.%Y'

# Сценарий-запас у соседа: браузерный забор той же таблицы для сайтов, у которых
# панель не заведена (нет `admin_url`) — как было до чтения ручкой.
DATING_IMPORT_SCENARIO = 'чат: сообщения из панели'


class DatingSiteImport:
    """Как этот сайт отдаёт свою переписку. Настройкой — без своего файла.

    Базовый driver описывает сайт **без панельного журнала**: он не ходит никуда
    и отвечает `has_journal() == False` — такие сайты забирают сценарием, как
    забирали всегда. Goldenbride-образную панель описывает свой файл; сайту, у
    которого журнал устроен иначе (Step2Love), заводится свой.
    """

    name = 'base'

    def __init__(self, presence: dict | None = None):
        self.presence = presence or {}

    def date_fmt(self) -> str:
        """Формат дат, который панель этого сайта понимает. Остальной — молча
        подставит свой срок, и это не отказ, а подмена диапазона."""
        return DATING_IMPORT_DATE_FMT

    def scenario_name(self) -> str:
        """Имя сценария у соседа — чем забирать, когда панельного пути нет."""
        return DATING_IMPORT_SCENARIO

    def has_journal(self) -> bool:
        """Есть ли у панели этого сайта страница с журналом переписки.

        ⚠ **Это не про «заведена ли панель»** — это про то, знает ли драйвер,
        где в ней лежат сообщения. Панель может быть живой и с адресом, но без
        понятной нам страницы: ходить наугад — значит врать человеку отказом
        `404` про живую панель.
        """
        return False

    async def journal_rows(self, site_id: int, profiles: dict, date_from: str,
                           date_to: str) -> tuple[int, list[dict]]:
        """Строки журнала за диапазон.

        Args:
            profiles: `site_uid` анкет сайта → их номер у нас — на случай сайта,
            который подписывает в строке только одну сторону (у Step2Love письма
            адресованы девушке, её номер и стоит в строке).

        Returns:
            tuple: (`total`, `rows`) — сколько всего строк отдала панель и чем
            они выглядят для `chat_panel_rows` (тот же вид, что отдаёт сценарий:
            `number` / `when` / `from` / `to` / `text`).

        ⚠ Отказ — исключением `DatingPanelFetchError` с причиной; пустой список
        — только когда панель правдиво сказала «пусто». Пустоту молча вместо
        непонятой страницы — то же враньё, что и молчаливый нулевой импорт.
        """
        raise NotImplementedError(f'{type(self).__name__} не умеет читать журнал')
