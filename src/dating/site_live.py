"""Живые счётчики сайта: сколько анкет в сети и много ли работы за полсуток.

Их показывают вкладки сайтов в шапке раздела: человек видит, где сейчас идёт
жизнь, не переключаясь на каждый сайт по очереди. До вкладок это был селект —
имя сайта и ничего больше, и «где сегодня разговоры» узнавалось перебором.

## ⚠⚠ Один заход на все сайты, а не по заходу на сайт

Счётчики обновляются вместе со страницей, то есть каждые несколько секунд, и
сайтов четыре. Запрос на каждый означал бы четыре обращения к базе за тик —
при том, что все четыре числа берутся из одних и тех же таблиц группировкой.

⚠ Отсюда же форма ответа: словарь «номер сайта → счётчики», а не список.
Страница рисует вкладки по **своему** списку сайтов (снимок у неё уже есть), и
счётчики к ним только прикладываются — сайт без строки здесь рисуется нулями,
а не пропадает со вкладок.

## ⚠ Почему двенадцать часов, а не сутки

Полсуток — это смена оператора плюс ночь. Сутки сгладили бы разницу между
«сайт работал утром» и «работает прямо сейчас», а ради этой разницы счётчики и
заводились.
"""

from logging_.logging_ import logger_info
from mysql_.mysql_ import mysql_get_db_async

from src.dating.message_twin import message_twin_skip

# За какой срок считаем работу. ⚠ Часы, а не минуты: число на вкладке отвечает
# «идёт ли тут жизнь», и минутное окно дрожало бы от каждой реплики.
SITE_LIVE_HOURS = 12


async def site_live_rows() -> dict:
    """Счётчики всех сайтов разом.

    Returns:
        dict: `{номер сайта: {'online', 'profiles', 'whole', 'chat', 'mail'}}`.
        `profiles` — включённые анкеты (знаменатель вкладки), `whole` — все
        вместе с выключенными (для подсказки). Сайта нет в ответе — значит у
        него нет ни одной анкеты.

    ⚠ Отказ отдаётся **пустым словарём**, а не исключением: счётчики украшают
    вкладку, и уронить из-за них всю шапку значило бы поменять важное на
    второстепенное. В журнале при этом строка остаётся.
    """
    try:
        async with mysql_get_db_async() as db:
            counted = await _profiles(db)
            await _chat(db, counted)
            await _mail(db, counted)

        return counted
    except Exception as e:
        logger_info(f'[dating] счётчики сайтов не прочитались: {e}')

        return {}


async def _profiles(db) -> dict:
    """Анкеты сайта: в сети, в работе и всего.

    ## ⚠⚠ Знаменатель — **все анкеты сайта**, а не включённые

    Прежде здесь стояли включённые, и довод был такой: выключенную увёл
    человек, работать она не должна, а `2/19` читалось бы как «семнадцать
    куда-то делись». Довод оказался неверным, и показала это живая страница: у
    Ladadate девятнадцать анкет, включённых ноль — вкладка писала `0/0` **рядом
    со списком из девятнадцати строк**.

    Два числа про одно и то же, спорящие на одном экране, хуже любого из них по
    отдельности: список рядом — та самая мера, с которой человек сверяет
    вкладку. Поэтому знаменатель теперь совпадает с заголовком списка
    («ПРОФИЛИ 19»), а сколько из них включено, говорит подсказка.

    ⚠ По той же причине и числитель берётся **без оглядки на `enabled`**:
    числитель со знаменателем обязаны считать одно множество, иначе `online`
    может оказаться больше `whole` при первой же выключенной, но живой анкете.
    """
    await db.execute(
        "SELECT site_id, COUNT(*) AS whole,"
        "       SUM(enabled = 1) AS working,"
        "       SUM(status = 'online') AS online"
        '  FROM profile GROUP BY site_id')

    return {int(row['site_id']): {'profiles': int(row['working'] or 0),
                                  'whole': int(row['whole'] or 0),
                                  'online': int(row['online'] or 0),
                                  'chat': 0, 'mail': 0}
            for row in (await db.fetchall() or [])}


async def _chat(db, counted: dict) -> None:
    """Реплики чата за срок — **только от собеседников**.

    ## ⚠⚠ Входящие, а не обе стороны

    Сперва считались обе, и довод был такой: разговор это обмен, одни входящие
    показали бы молчащий сайт живым. Довод оказался неверным, и показал это
    прод: у Ladadate за полсуток 20 исходящих реплик против 6 входящих —
    вкладка писала 26 и отвечала в основном **про нашу собственную работу**.

    Значок отвечает на вопрос «сколько пришло людям ответить», а не «сколько
    строк мы записали»: наши исходящие круг наделает и в пустоту, и число от
    этого вырастет, ничего не сообщив.

    ⚠⚠ **Близнецов прячем общим правилом** `message_twin_skip`. Наше
    исходящее лежит в `message` дважды — своей строкой и отражением из панели,
    — и то же бывает со **входящим**: реплика приходит сокетом и второй раз
    импортом. Правило одно на всех, кто показывает человеку счёт реплик; своя
    копия разошлась бы на первой правке. Эта грабля уже случалась: значок
    диалогов говорил 61 при шестидесяти видимых.

    ⚠ Сайт берётся через анкету: у `message` своего `site_id` нет — реплика
    принадлежит паре, а пара живёт у анкеты.
    """
    await db.execute(
        'SELECT p.site_id, COUNT(*) AS n'
        '  FROM message m JOIN profile p ON p.id = m.profile_id'
        " WHERE m.direction = 'in'"
        '   AND m.created_at > NOW() - INTERVAL %s HOUR'
        + message_twin_skip('m')
        + ' GROUP BY p.site_id', (SITE_LIVE_HOURS,))

    for row in (await db.fetchall() or []):
        counted.setdefault(int(row['site_id']),
                           {'profiles': 0, 'whole': 0, 'online': 0, 'chat': 0, 'mail': 0})
        counted[int(row['site_id'])]['chat'] = int(row['n'] or 0)


async def _mail(db, counted: dict) -> None:
    """Письма за срок — **только пришедшие**.

    ## ⚠⚠ Входящие, а не вся почта

    Сперва считались и ушедшие тоже, союзом по всем пулам отправки. Прод
    показал цену: у Ladadate за полсуток 95 писем, из них входящих **ноль** —
    значок целиком докладывал о нашей собственной рассылке.

    Вкладка отвечает «сколько людям есть что ответить». Исходящие письма
    делает круг, и их число растёт само по себе — хоть в пустоту, хоть в
    тишину.

    ⚠ Отсюда и простота запроса: пулы отправки перечислять больше незачем,
    `mail_in` это одна таблица со своим `site_id`. Вместе с союзом ушла и
    арифметика его подстановок.
    """
    await db.execute(
        'SELECT site_id, COUNT(*) AS n FROM mail_in'
        ' WHERE created_at > NOW() - INTERVAL %s HOUR'
        ' GROUP BY site_id', (SITE_LIVE_HOURS,))

    for row in (await db.fetchall() or []):
        counted.setdefault(int(row['site_id']),
                           {'profiles': 0, 'whole': 0, 'online': 0, 'chat': 0, 'mail': 0})
        counted[int(row['site_id'])]['mail'] = int(row['n'] or 0)
