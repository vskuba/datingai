"""Описание сайта: где его ручки, какими кадрами чат, чем отправлять.

Это тот самый словарь, который прежде жил **только у соседа** — в
`browser_site.presence`, и спрашивался у него ручкой `GET /api/browser/site/{id}`.
Теперь он лежит в нашей настройке сайта (`site_.settings.presence`,
страница «Сайты»), а сосед остался запасным путём.

## ⚠⚠ Зачем переехало: 137 запросов в минуту ради трёхсот байт

Описание читают четыре петли воркера, и каждая — по разу **на сайт**:

| Кто | Как часто | Что ему было нужно |
|-----|-----------|--------------------|
| держатель, `_presence_loop` | раз в 15 с | `send.transport` |
| держатель, главный цикл | раз в 60 с | то же |
| держатель, `_answer_loop` | раз в 60 с | то же |
| круг восстановления | раз в 60 с | **ничего** |

Журнал запросов прода за час показал счёт: `/api/browser/site/343` — 412
обращений, `/api/browser/site/19` — 343. У Ladadate это триста байт, не менявшихся
пять дней, и читалось из них одно слово — `"http"`.

Хуже цены — зависимость. Лежит сосед, и встаёт **чат**: не браузер, не сценарии, а
отправка ручкой сайта по своим cookie, к которой он отношения не имеет.

## ⚠ Кеш здесь не годится, и это был первый неверный ответ

Кеш — признание, что настройка живёт не там, где её читают. Настройки сайтов у нас
и так свои: `site_.settings`, страница «Сайты», правка человеком. Описание
сайта было последним, что осталось на чужой стороне, — и переносится оно целиком,
а не по ключу, ровно потому, что по ключу его уже начали растаскивать
(`heartbeat` уехал отдельно) и второй такой переезд оставил бы третье место.

## Что внутри и кто это читает

| Ключ | Кто читает |
|------|------------|
| `base`, `headers` | присутствие, кабинет, отправка ручкой |
| `send` | `send`: транспорт, кадр сокета, тело ручки, примета удачи |
| `chat`, `chat_url`, `chat_ws_mark`, `driver` | держатель сокетов и драйвер сайта |
| `heartbeat`, `status`, `unread`, `logout` | присутствие (⚠ у него **своя** настройка, `heartbeat`, и она старше) |
| `profile`, `contacts` | кабинет анкеты |
| `answer_language` | язык реплик: инвайты и письма |
| `*_scenario` | имена сценариев у соседа по ролям |

⚠ **Сценарии в описании — это имена, а не сами сценарии.** Гоняет их по-прежнему
сосед, и в этом смысле граница не сдвинулась: мы храним, **как** его попросить, а
не то, что он делает.
"""

from src.dating.json_column import json_column_load

# Ключ нашей настройки. Значение — JSON строкой, как у `heartbeat`.
SITE_PRESENCE_SETTING = 'presence'


async def site_presence(site_id: int) -> dict:
    """Описание сайта. Пустой словарь — не настроено ни у нас, ни у соседа.

    Порядок тот же, что у присутствия и у транспорта отправки: **своё старше
    соседского**. Сосед описывает сайт, но правит описание наша сторона — иначе
    правка настройки требовала бы чужой панели.

    ⚠ **Молчание соседа не отказ, а пустота.** Сайт со своей настройкой его не
    спрашивает вовсе, а у сайта без настройки пустое описание значит «работать
    нечем» — тот же исход, что и раньше. Бросать отсюда нельзя: зовут из петель
    держателя, и упавшая петля унесла бы чат целиком.
    """
    from logging_.logging_ import logger_info
    from src.uvicorn.routers.dating.site_ import site_setting

    raw = await site_setting(site_id, SITE_PRESENCE_SETTING)
    own = json_column_load(raw)
    if own:
        return own

    # ⚠ **Уход к соседу — событие, а не будни.** Описание сайта полагается держать
    # у себя; поход за ним значит либо «сайт ещё не настроен», либо «настройку
    # стёрли», и человеку это надо видеть, не читая счётчики журнала запросов.
    #
    # Длина прочитанного здесь не для красоты: она разделяет два разных случая —
    # настройки нет вовсе (ноль) и настройка есть, но не разобралась (не ноль).
    # Второе — сломанный JSON в поле, которое правят руками.
    logger_info(f'[dating] описание сайта #{int(site_id)} не взято у себя '
                f'(в настройке {len(str(raw or ""))} байт) — спрашиваем соседа')

    return await site_presence_neighbour(site_id)


async def site_presence_neighbour(site_id: int) -> dict:
    """Описание у соседа — запасной путь для сайта, которому его не переносили.

    ⚠ **Оставлен намеренно, и убирать его рано.** Новый сайт заводят у соседа:
    пока настройку не перенесли, это единственное, чем анкета работает. Сними мы
    запасной путь — заведение сайта стало бы двухходовым, и второй ход забывался
    бы ровно до первой поломки.
    """
    from logging_.logging_ import logger_info
    from src.rhapsody.rhapsody_api import rhapsody_api_site_get

    try:
        site = await rhapsody_api_site_get(int(site_id))
    except Exception as e:
        logger_info(f'[dating] описание сайта #{site_id} не пришло: {e}')

        return {}

    return json_column_load((site or {}).get('presence'))
