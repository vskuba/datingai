async def site_setting(site_id: int, key: str, default: str = '') -> str:
    """Одна настройка сайта — для кода, которому она понадобится.

    Отдельной функцией, а не запросом на месте: настройки читают из разных мест, и
    разбор JSON, размазанный по коду, разойдётся в мелочах — например, в том, что
    делать с отсутствующей строкой.

    Умолчание берётся из реестра, если своё не передали: код, который спрашивает
    известную настройку, не должен повторять её умолчание — два места разошлись бы.
    """
    key = str(key)
    if not default:
        default = str(SITE_KNOWN.get(key, {}).get('default') or '')

    return (await site_settings_all()).get(int(site_id), {}).get(key, default)


async def site_settings(site_id: int) -> dict:
    """Все настройки сайта разом — коду, которому нужно несколько сразу.

    Отдельно от `site_setting`: тот читает по ключу и подставляет умолчание
    из реестра. Здесь набор как есть — вызывающий сам решает, чего в нём не хватает.

    ⚠ **Секреты приходят настоящими**, а не маской: это чтение для кода, а не для
    страницы. Отправка входит на сайт этим паролем, и маска сорвала бы вход.
    """
    return dict((await site_settings_all()).get(int(site_id), {}))


async def site_seconds(site_id: int, key: str) -> int:
    """Настройка-число из реестра. Мусор и пустота — умолчание.

    ⚠ **Значение вне набора не принимается.** Набор — условие кода, а не украшение
    формы: впиши кто-нибудь в базу «месяц», и снимок жил бы месяц, хотя ни одна
    страница такого не предлагала. Берём умолчание и говорим об этом в лог.

    ⚠⚠ **У числовой настройки то же правило держат границы, а не набор.**

    Счётчики (`kind: 'number'`) набора не имеют вовсе: осмысленно любое целое, и
    перечислять его нечем. Проверка при этом обязана остаться — форма не
    единственный вход: есть заливка seed, есть чужой токен, есть руки в
    phpMyAdmin. Пропусти мы её, «500 ответов за заход» заняли бы круг до конца
    суток, а «-5» сравнилось бы с чем угодно как «никогда».

    Поймано тестом `test_reply_round_rejects_batch_out_of_range` в тот же час,
    когда счётчики переводили с наборов на числа: набор пропал, и вместе с ним
    молча пропала единственная проверка.
    """
    known = SITE_KNOWN.get(str(key), {})
    fallback = int(known.get('default') or 0)
    raw = str(await site_setting(site_id, key)).strip()

    if known.get('kind') == 'number':
        # ⚠⚠ **Потолка у счётчика нет, и `int(known.get('max', 0))` был бы
        # ловушкой**: без ключа он даёт ноль, и ноль становится потолком —
        # любое число отвергается, настройка тихо работает умолчанием.
        #
        # Поймано тестом чистки инвайтов в тот же час, когда потолки
        # снимали: «старше 2 часов» перестало удалять что-либо вовсе.
        low, high = int(known.get('min', 0)), known.get('max')

        try:
            value = int(raw)
        except ValueError:
            if raw:
                logger_info(f'[dating] «{key}» у сайта #{site_id} не число: {raw!r}')

            return fallback

        if value < low or (high is not None and value > int(high)):
            logger_info(f'[dating] «{key}» у сайта #{site_id} вне границ: {value}')

            return fallback

        return value

    allowed = {value for value, _ in known.get('options') or ()}

    if allowed and raw not in allowed:
        if raw:
            logger_info(f'[dating] «{key}» у сайта #{site_id} вне набора: {raw!r}')

        return fallback

    return int(raw) if raw.isdigit() else fallback


async def site_settings_all() -> dict[int, dict]:
    """Все сохранённые настройки: номер сайта → набор.

    Публичная, потому что её зовут и ручки роутера, и читалка рядом:
    приватное имя через границу модуля — это тот же протёкший внутренний
    порядок, что и отложенный импорт (`code_rules.md`, §4.3).

    Одним запросом, а не по сайту: строк здесь единицы (сайтов у соседа десятки), и
    запрос на каждый сайт при показе списка означал бы десяток запросов ради
    десятка строк.
    """
    async with mysql_get_db_async() as db:
        await db.execute('SELECT site_id, settings FROM site')
        rows = await db.fetchall()

    found = {}
    for row in rows:
        raw = row['settings']
        try:
            # MySQL отдаёт JSON строкой, а не разобранным словарём — разбираем сами.
            # Битую строку пропускаем: настройка одного сайта не должна ронять
            # список всех.
            value = json.loads(raw) if isinstance(raw, (str, bytes)) else raw
        except ValueError as e:
            logger_info(f"[dating] настройки сайта #{row['site_id']} не разобрались: {e}")
            continue

        found[int(row['site_id'])] = _strings(value) if isinstance(value, dict) else {}

    return found


