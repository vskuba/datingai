"""Снимок списка сайтов: что показываем, пока сверка не принесла нового.

Список сайтов ведёт RhapsodyAi, а здесь лежит **снимок его ответа** — чтобы
панель работала, когда сосед недоступен (довод и цена размена —
`.claude/docs/api.md`, §3.5). Сверку с соседом делает
`src/uvicorn/routers/dating/site_sync.py`, показ — ручка `site_list`.

## ⚠ Почему отдельным файлом от настроек

Таблица `site` одна, а вещей в ней две, и `site_.py` это прямо говорил:
«две вещи: снимок его списка и настройки, которые про нашу работу с сайтом».
Снимок — чужие данные, которые мы только отражаем; настройки — свои, которых у
соседа нет. Класть их в один модуль значило бы называть одним словом то, что
расходится по владельцу: переименование сайта приезжает сверкой, а частота
обхода правится человеком на нашей странице.

⚠ Ушедшие у соседа (`is_gone`) отсюда не приходят: закладку убрали, и предлагать
её к выбору значит обещать работу, которой не будет.
"""

from mysql_.mysql_ import mysql_get_db_async


async def site_rows() -> list[dict]:
    """Снимок списка сайтов: то, что показываем, пока сверка не принесла нового.

    Порядок — по имени: селект читают глазами, а порядок вставки в базу для
    человека случаен. Ушедшие у соседа (`is_gone`) не показываем: закладку убрали,
    и предлагать её к выбору значит обещать работу, которой не будет.
    """
    async with mysql_get_db_async() as db:
        await db.execute(
            'SELECT site_id, name, url, tags, synced_at FROM site'
            ' WHERE is_gone = 0 AND name <> %s ORDER BY name, site_id', ('',))
        rows = await db.fetchall()

    return [{'id': int(row['site_id']),
             'name': row['name'],
             'url': row['url'],
             'tags': row['tags'],
             'synced_at': row['synced_at']} for row in rows]
