"""Круг опроса: статус анкеты свежий, даже когда панель никто не открыл.

Раз в `STATUS_ROUND_TICK_SEC` смотрит, каким сайтам пора, и опрашивает у
них все анкеты, у которых есть чем ходить (`status.py`).

## ⚠ Зачем: до него статус обновляла **открытая страница**

Опрос жил в ручке `/api/dating/profile/probe`, а звала её страница «Анкеты» —
раз в пятнадцать секунд, пока открыта. Отсюда две беды, обе наблюдались на проде:

* **Никто не смотрит — статус не двигается.** У анкеты без смен и без присмотра
  (`schedule_on = 0`, `keep_online = 0`) его не трогает ни один круг. На проде
  таких было одиннадцать из тринадцати, и строки не менялись **девять с половиной
  суток**: `last_seen_at` пуст, `status` тот, что записали однажды.
* **«Профили» показывали неправду.** Список там освежается сам, но читает он нашу
  базу, а в базе лежало девятидневное. Перезагрузка страницы не помогала — данные
  те же; помогала соседняя вкладка «Анкеты», и понять это со стороны невозможно.

Теперь спрашивает воркер, а страницы только читают. Это и правильнее по существу:
«кто сейчас в сети» — свойство системы, а не открытого браузера.

## Кого берём

Все анкеты сайта, у которых `enabled = 1` и есть `storage_state`, — тот же отбор,
что делала ручка. Выключенную не опрашиваем: «не ведём» значит не ведём совсем.

⚠ **Опрос ничего не чинит.** Он спрашивает и записывает; вход заводит
`schedule_round`, восстанавливает — `revive_round`. Смешай мы это,
два круга гоняли бы браузер наперегонки.

⚠ **Круг расписания читает то, что мы пишем**, и это осознанная связь: он берёт
анкеты с `schedule_on = 1` и по статусу решает, входить или выходить. Свежий
статус — ровно то, чего ему не хватало; анкеты без смен (а их большинство) он не
трогает вовсе, так что новых входов от этого круга не прибавится.

## Цена

Один дешёвый HTTP-запрос на анкету по сохранённым cookie: вкладка Chromium стоит
~143 МБ, а клиент с cookie единицы килобайт. Тринадцать анкет раз в минуту — это
тринадцать запросов в минуту против пятидесяти двух, которые делала открытая
страница «Анкеты» (те же тринадцать раз в пятнадцать секунд). То есть вчетверо
меньше, чем сегодня, и не зависит от того, открыл ли кто-нибудь панель.
"""

from logging_.logging_ import logger_info
from mysql_.mysql_ import mysql_get_db_async

from src.dating.round import round_mem_due, round_mem_mark
from src.dating.status import status_probe_site

# Как часто круг просыпается. ⚠ Это **не** частота опроса: её задаёт настройка
# сайта, а круг лишь смотрит, кому пора.
STATUS_ROUND_TICK_SEC = 15

# Настройка сайта: как часто опрашивать его анкеты.
STATUS_ROUND_EVERY_SETTING = 'probe_every'

# Умолчание на случай сайта без настройки. Минута: статус читают глазами со
# страницы, и минутная давность там незаметна, а чаще — лишний стук в сайт.
STATUS_ROUND_EVERY_DEFAULT = 60

# Когда сайт опрашивали в последний раз: `{сайт: время}`. В памяти процесса, как у
# круга присутствия: перезапуск смены — это лишний опрос, а не пропущенный, и
# цена ошибки в эту сторону копеечная. Правило общее — `round_mem_*` слоя.
_asked: dict[int, float] = {}


async def status_round_run() -> dict:
    """Один заход: опросить сайты, которым пора.

    Returns:
        dict: `sites` — сколько сайтов обошли, `checked` и `online` — сколько
        анкет спросили и сколько из них в сети.

    ⚠ **Смещение пояса не нужно**: расписания круг не спрашивает. Статус нужен
    свежим круглые сутки — по нему смотрят, жив ли вход, и ночью тоже. Тот же
    довод, что у круга админ-панели.
    """
    sites = checked = online = 0

    for site_id in await _sites():
        if not round_mem_due(_asked, site_id, await _every(site_id)):
            continue

        # ⚠ Отметку ставим **до** опроса: он идёт секундами, а тик пятнадцать.
        round_mem_mark(_asked, site_id)

        got = await status_probe_site(site_id)
        if not got['ready']:
            # У сайта не настроено присутствие — опрашивать нечем. Молчим: это
            # состояние настройки, а не сбой, и строка об этом раз в минуту
            # залила бы журнал.
            continue

        sites += 1
        checked += got['checked']
        online += got['online']

    if checked:
        logger_info(f'[dating] круг опроса: сайтов {sites}, анкет {checked}, '
                    f'в сети {online}')

    return {'sites': sites, 'checked': checked, 'online': online}


# ── Приватное ────────────────────────────────────────────────────────────────

async def _sites() -> list[int]:
    """Сайты, на которых есть кого опрашивать.

    ⚠ Отбор идёт **от анкет**, а не от списка сайтов: сайтов у соседа десятки, а
    работают обычно один-два. Спрашивать настройку у каждого значило бы ходить к
    соседу за описанием сайтов, где нет ни одной нашей анкеты. Тот же приём, что
    у круга присутствия.
    """
    try:
        async with mysql_get_db_async() as db:
            await db.execute(
                'SELECT DISTINCT site_id FROM profile'
                ' WHERE enabled = 1 AND storage_state IS NOT NULL ORDER BY site_id')
            rows = await db.fetchall()
    except Exception as e:
        logger_info(f'[dating] сайты для опроса не спросились: {e}')

        return []

    return [int(row['site_id']) for row in rows or []]


async def _every(site_id: int) -> int:
    """Как часто опрашивать этот сайт."""
    from src.uvicorn.routers.dating.site_ import site_seconds

    return int(await site_seconds(site_id, STATUS_ROUND_EVERY_SETTING)
               or STATUS_ROUND_EVERY_DEFAULT)
