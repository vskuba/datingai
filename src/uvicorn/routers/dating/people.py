async def people_snap_start(site_id: int) -> bool:
    """Заводит фоновый съём ленты этого сайта. `False` — не завёлся.

    Не заводится по трём причинам, и все они законные: съём уже идёт, выдержка
    между попытками не кончилась, у сайта нет анкет — заходить не под кем (на
    сценарном сайте это значит «нет ни одной включённой»: спящая годится,
    `_site_sleeper`).

    ⚠ **Не ждёт результата**, как и страница: съём это ~40 секунд живого браузера.
    Круг заводит его и идёт дальше; снимок появится в кэше сам.

    ⚠ **`log_id=0`** — прогон не пишется в журнал случайно выбранной анкеты: список
    про сайт, а не про неё. След остаётся в журнале прогонов
    (`scenario.py`).
    """
    site_id = int(site_id)
    profile = await _site_profile(site_id)
    if not profile and not await _api_for(site_id, 'online'):
        profile = await _site_sleeper(site_id)
    if not profile:
        return False

    return _refresh_start(profile, 'online', _key('online', site_id=site_id),
                          log_id=0, fresh=False,
                          fresh_sec=await _fresh_sec('online', site_id),
                          floor_sec=await _floor_sec(site_id))


class _PeopleFailure(RuntimeError):
    """Снять список не вышло. Текст пригоден для журнала анкеты и для страницы."""


def _refresh_start(profile: dict, kind: str, key: str, log_id: int,
                   fresh: bool = False,
                   fresh_sec: int = PEOPLE_FRESH_SEC,
                   floor_sec: int = PEOPLE_FLOOR_SEC) -> bool:
    """Заводит фоновое обновление снимка, если его пора и можно заводить.

    Args:
        fresh: пришли по кнопке «обновить». Тогда выдержка между попытками
            сокращается до жёсткого пола — см. ниже.
        fresh_sec: выдержка этого вида списка.
        floor_sec: жёсткий пол сайта.

            ⚠ **Оба приходят параметром, а не читаются здесь**: их задают настройки
            сайта, а чтение настройки асинхронное — функция же обязана остаться
            синхронной, её результат уходит прямо в ответ ручки.

    Returns:
        bool: идёт ли обновление прямо сейчас — своё или начатое раньше.

    ⚠ **Два сторожа, и оба обязательны.**

    Первый — «уже идёт»: страница спрашивает список, пока ждёт результата, и без
    него каждый опрос плодил бы ещё один прогон.

    Второй — **выдержка между попытками**. Он закрывает случай, который первый
    пропускает: прогон не удался, снимок остался старым, и следующий же опрос
    завёл бы новую попытку. Раз в пятнадцать секунд, бесконечно — то есть ровно
    то, от чего бережёт кэш. Поэтому попытка считается попыткой независимо от
    того, чем кончилась, и следующая — не раньше конца выдержки.

    ⚠ **Кнопке «обновить» второй сторож укорачивается до жёсткого пола.** Иначе
    она молча ничего не делала: минуту назад прошёл удачный прогон, человек видит
    список полуторной минуты и нажимает «⟳» — а обновление не заводится, потому
    что выдержка ещё не кончилась. Кнопка обходит выдержку по своему смыслу
    (`fresh` в ручке); пол не обходит никто, потому что пол — про предел сайта.

    ⚠ **Выдержка считается по общему штампу, а не по памяти процесса.** Страницу
    спрашивает uvicorn, а круг ленты заводит съём в воркере: читал бы каждый свою
    копию, сценарный сайт ловил бы по заходу с каждого процесса за одну выдержку.
    Для ленты, где каждый заход — **вход в панель агентства**, это ровно то, чем
    панель считает лишним: лимитом попыток входа она и встала 28.10.2026 на несколько
    часов. Отсюда `_attempt_mark` ниже.
    """
    task = _refreshing.get(key)
    if task and not task.done():
        return True

    # ⚠ Выдержка не мешает **первому** заходу: пока снимка не было, обновление
    # никто не заводил, и ждать пять минут ради первого показа незачем. Порог тут
    # про повторные попытки, а не про начало работы.
    if time.time() - _attempt_at(key) < (floor_sec if fresh else fresh_sec):
        return False

    _attempt_mark(key)
    _refreshing[key] = asyncio.ensure_future(_refresh_run(profile, kind, key, log_id))

    return True


def _attempt_at(key: str) -> float:
    """Когда в последний раз пробовали снять этот список; 0 — не пробовали никогда.

    Решает штамп в Redis (тот же ключ, что у снимка, с суффиксом `:att`), копия
    `_refresh_at` — подпорка на его сбой: тот же размен, что у самого кэша. На
    пустом Redis не полагаемся на память: нулевой ответ честнее чужого штампа
    другого процесса.
    """
    try:
        raw = redis_conn_get().get(key + ':att')
    except Exception:
        raw = None

    if raw is not None:
        try:
            return float(raw)
        except (TypeError, ValueError):
            return 0.0

    return _refresh_at.get(key, 0.0)


def _attempt_mark(key: str) -> None:
    """Ставит штамп попытки. Не бросает — как чтение и запись кэша."""
    now = time.time()
    _refresh_at[key] = now
    try:
        # Срок — вдвое с запасом против самой длинной выдержки: протухший штамп
        # читался бы как «не пробовали», и первый же опрос завёл бы попытку раньше
        # срока. PEOPLE_KEEP_SEC — самое длинное, чем живёт список.
        redis_conn_get().set(key + ':att', repr(now), ex=2 * PEOPLE_KEEP_SEC)
    except Exception as e:
        logger_info(f'[dating] штамп попытки «{key}» не записался: {e}')


async def _refresh_run(profile: dict, kind: str, key: str, log_id: int) -> None:
    """Снимает список в фоне и переписывает кэш. Не бросает: ждать его некому.

    Ошибку пишем в журнал анкеты — там её и ищут. В ответ ручки она не попадёт:
    тот запрос давно ушёл со старым снимком, а следующий увидит либо новый
    снимок, либо прежний, если прогон не удался.
    """
    title = PEOPLE_TITLES.get(kind, kind)

    try:
        people = await _snapshot(profile, kind)
    except _PeopleFailure as e:
        _refresh_error[key] = str(e)
        if log_id:
            await log_write(log_id, 'fail', f'{title} с сайта не снялись: {e}')
        logger_info(f'[dating] фоновый список «{key}» не снялся: {e}')

        return
    except Exception as e:
        # Сюда падает то, чего мы не предусмотрели. Ждать эту задачу некому, и без
        # перехвата исключение утонуло бы в логе `asyncio` без следа на странице.
        _refresh_error[key] = f'обновление сорвалось: {e}'
        logger_info(f'[dating] фоновый список «{key}» упал: {e}')

        return

    _cache_put(key, {'at': time.time(),
                     'when': datetime_utc_now().strftime('%Y-%m-%d %H:%M:%S'),
                     'people': people},
               await _keep_sec(kind, int(profile.get('site_id') or 0)))
    _refresh_error.pop(key, None)
    if log_id:
        await log_write(log_id, 'ok', f'{title} с сайта: {len(people)} собеседников')


async def _hold_why(profile: dict) -> str:
    """Почему за списком этой анкеты на сайт не идём. Пустая строка — идём.

    ⚠⚠ **Написано по живому следу в журнале.** Открытая страница «Профили» зовёт
    эту ручку на каждое открытие карточки (вкладки «Чат» и «Фавориты»), а решение
    «идти или нет» принималось **только по возрасту снимка**: состояние анкеты не
    смотрели вовсе. В журнале это выглядело так:

        21:39:52 Diana | Избранные с сайта не снялись: вход отложен на 2388 с

    Анкета была офлайн вторые сутки, а панель всё равно шла за её избранными — то
    есть за входом под спящей учёткой. Лестница пауз (`site_api`) вход не
    пустила, и строка — это её отчёт; но самой попытки быть не должно.

    ⚠ **Разница с лентой «Все онлайн» существенная.** Та про **сайт**: список
    мужчин один на всех, и снять его можно от лица любой работающей девушки.
    Избранные и диалоги — данные **этой** анкеты, и прочитать их можно, только
    войдя под ней.

    ⚠ **Даром — можно.** Токен API живёт у анкеты 12 часов: пока он цел, запрос не
    стоит ни входа, ни риска, и запрещать его незачем — девушка ушла со смены час
    назад, а человек смотрит, кого она набрала. Нет токена (или сайт работает
    сценарием, где токена не бывает вовсе) — поход означает вход, и мы его не
    делаем.
    """
    if str(profile.get('status') or '') == 'online':
        return ''

    site_id = int(profile.get('site_id') or 0)
    if await _api_ready(site_id) and site_api_has_token(int(profile.get('id') or 0)):
        return ''

    return 'анкета не в сети — список не обновляется'


async def _api_ready(site_id: int) -> bool:
    """Настроен ли у сайта его собственный API.

    Двух условий мало по одному: выбранный источник без адреса — это опечатка в
    настройке, а адрес при выбранном сценарии — заготовка на будущее. Ни то ни
    другое не повод молча ходить не туда, поэтому нужны оба.
    """
    if not site_id:
        return False

    source = str(await site_setting(site_id, PEOPLE_SOURCE_SETTING)).strip()

    return source == PEOPLE_SOURCE_API and bool(
        str(await site_setting(site_id, PEOPLE_API_BASE_SETTING)).strip())


async def _api_for(site_id: int, kind: str) -> bool:
    """Берём этот вид списка у самого сайта, а не сценарием.

    Одно условие на три двери: прогон в `_snapshot`, выбор анкеты у вызывающих
    да подпись на странице. Расползись оно копиями, разошёлся бы и источник —
    настройка сайта уже выбирает его, а не код.
    """
    return kind in people_api_kinds() and await _api_ready(site_id)


async def _api_rows(profile: dict, kind: str, site_id: int) -> list:
    """Список через API сайта. Пароль — по настройке анкеты `password_source`.

    ⚠ **Источник пароля выбирает анкета явно**, а не правило «свой, если задан»
    (`password_pick`). Здесь это правило и стояло, и на живой установке оно
    сломало ровно одну анкету из тринадцати:

        Избранные с сайта не снялись: сайт не принял вход: неверный логин или
        пароль: Login or password invalid (…) (/auth/login → 400)

    У анкеты 849 в поле пароля лежала строка от прежних времён, а `password_source`
    стоял `site` — то есть человек решил ходить общим паролем агентства. Правило
    «свой сильнее» этого решения не видело: у него нет состояния, и оставленная в
    поле строка молча перебивала выбор. У остальных двенадцати поле было пусто, они
    падали в общий пароль и работали — оттого и выглядело, будто дело в самой Диане.

    Остальные двери сайта (письма, звёздочки, карточка мужчины) спрашивали
    `password_pick` с самого начала; расходилась только эта.
    """
    password = password_pick(profile, str(
        await site_setting(site_id, PEOPLE_API_PASSWORD_SETTING)).strip())
    base = str(await site_setting(site_id, PEOPLE_API_BASE_SETTING)).strip()

    try:
        return await people_api_rows(profile, kind, base, password)
    except DatingPeopleApiError as e:
        # В общую неудачу: кэш и страница поступают с ней так же, как с отказом
        # соседа, — показывают прежний снимок и причину.
        raise _PeopleFailure(str(e))


async def _floor_sec(site_id: int) -> int:
    """Жёсткий пол: чаще этого к сайту не ходим ни при каких условиях.

    Настройкой, а не константой, потому что предел у сайтов разный: один терпит
    заход раз в четверть минуты, другой считает подозрением и заход в минуту.
    Умолчание — прежние 15 секунд.

    ⚠ **Пол остаётся полом.** Выдержку кнопка «обновить» обходит по своему смыслу,
    а пол не обходит никто: он про то, чего не выдержит сайт, а блокировка стоит
    анкеты, а не запроса.
    """
    if not site_id:
        return PEOPLE_FLOOR_SEC

    return await site_seconds(site_id, PEOPLE_FLOOR_SETTING) \
        or PEOPLE_FLOOR_SEC


async def _fresh_sec(kind: str, site_id: int) -> int:
    """Через сколько снимок этого вида стоит снять заново.

    У ленты «кто в сети» срок задаёт настройка сайта: в ней решается, кому можно
    писать, и на разных сайтах состав меняется по-разному быстро. Остальные виды
    живут умолчанием — понадобится, заводится строкой в
    `PEOPLE_FRESH_SETTING`.

    ⚠ **Пол этим не обходится.** Он остаётся поверх выдержки (`_floor_sec`): пол
    про предел самого сайта, а не про то, чего хочет страница. Поставь кто-нибудь «каждые две минуты» и жми «обновить» — к сайту всё
    равно уйдёт не чаще раза в четверть минуты.
    """
    setting = PEOPLE_FRESH_SETTING.get(kind)
    if not setting or not site_id:
        return PEOPLE_FRESH_SEC

    return await site_seconds(site_id, setting) or PEOPLE_FRESH_SEC


async def _keep_sec(kind: str, site_id: int) -> int:
    """Сколько держим и показываем снимок этого вида.

    У избранных срок задаёт настройка сайта: состав избранных меняет человек, и на
    разных сайтах по-разному часто. Остальные виды живут умолчанием — понадобится,
    заводится строкой в `PEOPLE_KEEP_SETTING`.
    """
    setting = PEOPLE_KEEP_SETTING.get(kind)
    if not setting or not site_id:
        return PEOPLE_KEEP_SEC

    return await site_seconds(site_id, setting) or PEOPLE_KEEP_SEC


def _key(kind: str, profile_id: int = 0, site_id: int = 0) -> str:
    """Ключ снимка: по анкете или по сайту.

    Он же служит ключом сторожей фонового обновления — одна строка на один список,
    и разъехаться им негде.
    """
    return (PEOPLE_KEY.format(profile_id=profile_id, kind=kind) if profile_id
            else PEOPLE_SITE_KEY.format(site_id=site_id, kind=kind))


async def _site_profile(site_id: int) -> dict:
    """Анкета **в сети**, под которой снимаем список. Нет таких — пустой словарь.

    Какая именно, на результат не влияет: «кто в сети» одинаков под любой учёткой.
    Порядок задан явно (сперва те, у кого снят вход, дальше по номеру), чтобы
    список не снимался то одной анкетой, то другой: в журнале прогонов это
    выглядело бы как случайная чехарда.

    ⚠⚠ **Только `status = 'online'`, и это исправление живой беды.** Прежде бралась
    любая анкета сайта, даже спящая, — и круг ленты ходил на сайт круглые сутки, в
    том числе когда работать было некому. Смысла в снимке тогда нет: лента «Все
    онлайн» нужна тем анкетам, что сейчас в чате, а их ноль.

    Цена такого хождения оказалась высокой. Общий агентский пароль перестал
    подходить 13 сентября, вход стал давать `400`, токена не появлялось — и круг
    честно пробовал войти **каждые две минуты**. За сутки 484 неудачных входа, и
    сайт закрыл наш IP целиком: `ERROR_SING_IN_BY_IP_DAILY_FAILED_LIMIT`. Анкета в
    сети такого не устроит: пока она в сети, вход у неё уже есть.

    ⚠⚠ **Среди онлайн берём ту, у которой уже есть токен.** Токен API живёт у
    каждой анкеты свой и держится 12 часов. Возьми мы просто «первую по номеру»,
    смена онлайн-состава (утро, вечер, чужое расписание) означала бы новый вход
    при каждой перемене — а входы сайт считает и за них закрывает адрес. Спросив
    сперва Redis, круг чаще всего не логинится вовсе: ходит тем, что уже есть.

    Токена нет ни у кого — берём первую по прежнему правилу, и это один вход на
    двенадцать часов, а не один на каждые две минуты.

    ⚠ **`password_source` и `password` в выборке не нужны.** Пароль берётся общий
    агентский (`password_pick` без этих полей отвечает «общий»), и это
    верно: список снимается от лица сайта, а не конкретной девушки.

    Спит весь сайт — на сценарных сайтах за лентой идём всё равно, дверью служит
    первая включённая анкета: `_site_sleeper`.
    """
    async with mysql_get_db_async() as db:
        await db.execute(
            'SELECT id, site_id, login FROM profile '
            ' WHERE site_id = %s AND login <> %s'
            "   AND enabled = 1 AND status = 'online'"
            ' ORDER BY storage_state IS NULL, id LIMIT %s',
            (int(site_id), '', PEOPLE_ONLINE_PICK_MAX))
        rows = await db.fetchall() or []

    if not rows:
        return {}

    for row in rows:
        if site_api_has_token(int(row['id'])):
            return dict(row)

    return dict(rows[0])


async def _site_sleeper(site_id: int) -> dict:
    """Первая включённая анкета сайта, спит она или нет. Пусто — пустой словарь.

    ⚠ **Дополняет `_site_profile`, а не отменяет её: только для сайтов, которые
    снимают список сценарием.** Правило «только в сети» стережёт вход паролем
    анкеты (осенняя история в `_site_profile`); сценарий же того пароля не
    спрашивает вовсе: он входит в агентскую панель её же логином (переменные
    `panel_login`/`panel_password`) и оттуда попадает в кабинет девушки по
    автологину. Спящая анкета здесь — дверь, а не ключи: лента не умирает,
    когда смена кончилась и «в сети» не держит никто.

    Частота входа не отдана на волю и здесь: тот же срок `online_check_every`,
    круг ходит не чаще него.

    ⚠ **Для сайтов с своим API не зовётся.** Там вход — это вход паролем
    анкеты, и оживлять им спящих значит вернуть сентябрь.
    """
    async with mysql_get_db_async() as db:
        await db.execute(
            'SELECT id, site_id, login FROM profile '
            ' WHERE site_id = %s AND login <> %s'
            '   AND enabled = 1'
            ' ORDER BY storage_state IS NULL, id LIMIT 1',
            (int(site_id), ''))
        row = await db.fetchone()

    return dict(row) if row else {}


def _cache_get(key: str) -> dict | None:
    """Снимок из Redis или None.

    ⚠ **Сбой Redis не должен ронять ручку.** Кэш — ускорение, а не источник
    правды: не прочитался — сходим к соседу, как в первый раз. Ронять из-за этого
    страницу значило бы менять «медленно» на «никак».

    Не прочитался — смотрим в подпорку (`_CACHE_FALLBACK`): результат фонового
    прогона едет к странице только через кэш, и без неё «никак» получилось бы всё
    равно, просто тихо.
    """
    try:
        raw = redis_conn_get().get(key)
    except Exception as e:
        logger_info(f'[dating] кэш собеседников не прочитался: {e}')

        raw = _CACHE_FALLBACK.get(key)

    if not raw:
        return None

    try:
        snapshot = json.loads(raw)
    except ValueError:
        return None

    return snapshot if isinstance(snapshot, dict) and 'people' in snapshot else None


def _cache_drop(key: str) -> None:
    """Убирает снимок, переживший свой срок. Не бросает — как чтение и запись."""
    _CACHE_FALLBACK.pop(key, None)
    try:
        redis_conn_get().delete(key)
    except Exception as e:
        logger_info(f'[dating] кэш собеседников не убрался: {e}')


def _cache_put(key: str, snapshot: dict, keep: int = PEOPLE_KEEP_SEC) -> None:
    """Кладёт снимок в Redis на заданный срок. Не бросает — как и чтение.

    Срок ставится и здесь, и проверяется при показе, и это не дубль: Redis чистит
    место, а проверка при показе выполняет настройку, которую могли укоротить уже
    после записи.

    Не записался — кладём в подпорку: срок там сторожит проверка при показе, а
    иначе снятый список пропал бы вместе с сорока секундами работы браузера.
    """
    raw = json.dumps(snapshot, ensure_ascii=False)
    try:
        redis_conn_get().set(key, raw, ex=max(60, int(keep)))
        _CACHE_FALLBACK.pop(key, None)
    except Exception as e:
        logger_info(f'[dating] кэш собеседников не записался: {e}')

        _CACHE_FALLBACK[key] = raw


async def _snapshot(profile: dict, kind: str) -> list:
    """Снимает список: **через API сайта, если он настроен, иначе сценарием**.

    Любая неудача — `_PeopleFailure`. Разные поводы не получить список сведены в
    одно исключение намеренно: страница поступает с ними одинаково — показывает
    прежний снимок и причину, — а разбирать, чем «сосед занят» отличается от
    «сайт просит подождать», по тексту причины проще, чем по веткам кода.

    ⚠ **Источник — настройка сайта, а не выбор кода.** `people_source: api` у сайта
    с настроенным адресом означает, что список берётся прямо у сайта: 70–170 мс
    вместо 35–40 секунд браузера, и полный список вместо первой страницы (замер:
    201 человек в сети против 20 у сценария). Сайт без API работает как работал.

    Вида, которого API не отдаёт (`dialog`), это не касается: он уходит к сценарию,
    как и раньше.
    """
    site_id = int(profile.get('site_id') or 0)
    if await _api_for(site_id, kind):
        return await _api_rows(profile, kind, site_id)

    spec = PEOPLE_KINDS[kind]

    # Сайт спрашиваем здесь, а не в ручке: он живёт у соседа, и его недоступность
    # — такая же неудача прогона, как занятый браузер, а не повод погасить колонку
    # с готовым снимком. `profile_site` отвечает `HTTPException` (502 или
    # 422) — переводим её в общую неудачу, чтобы кэш отработал по своим правилам.
    try:
        site = await profile_site(int(profile['site_id']))
    except HTTPException as e:
        raise _PeopleFailure(str(e.detail))

    site_id = int(site['id'])

    try:
        scenario = await rhapsody_api_scenario_find(site_id, spec['scenario'])
    except RhapsodyError as e:
        raise _PeopleFailure(str(e))

    if not scenario:
        raise _PeopleFailure(f"у сайта нет сценария «{spec['scenario']}» — "
                             f'заведите его в RhapsodyAi на вкладке «Сценарии»')

    # Логин анкеты передаём мы, пароль — переменная сайта у соседа (`girl_password`):
    # у агентства он общий на все анкеты, а импортированные анкеты своего пароля и
    # не имеют — панель его не показывает.
    #
    # `keep_session=False`: вкладка нужна на один прогон, и держать её незачем —
    # она стоит ~143 МБ в пуле, общем с соседом.
    # Общей дверью (`scenario_run`): она пишет прогон в журнал прогонов и в
    # журнал самой анкеты — список снимается под ней, и след должен быть у неё.
    try:
        run = await scenario_run(
            scenario, site_id, int(profile['id']), '',
            {**spec['variables'], 'profile_login': str(profile['login'])}, {},
            keep_session=False)
    except RhapsodyError as e:
        # «Нет такого сценария» у соседа — повод забыть его номер: сценарий
        # переименовали или удалили, а мы держим номер до конца выдержки и стучимся
        # по нему каждый раз. Прочие отказы номера не порочат.
        if ' → 404' in str(e):
            rhapsody_api_scenario_forget(site_id, spec['scenario'])
        raise _PeopleFailure(str(e))

    if str(run.get('status')) == 'error':
        raise _PeopleFailure(f"сценарий встал на шаге {run.get('step_no')}: {run.get('error')}")

    return people_rows(run.get('extract') or {}, spec['field'])


def _answer(snapshot: dict | None, cached: bool, error: str, refreshing: bool = False,
            site_id: int = 0, kind: str = '', next_in: int = -1) -> dict:
    """Ответ ручки из снимка. Нет снимка — пустой список и возраст `-1`.

    `-1` вместо нуля: ноль значит «снят только что», и показать его там, где
    снимка нет вовсе, значило бы соврать свежестью.

    `refreshing` — «прямо сейчас снимаем новый»: страница по нему знает, что стоит
    вернуться за результатом, и показывает, что список обновляется.

    `next_in` — через сколько секунд лента сама пойдёт на сайт по своему сроку;
    `-1` — расписания у этого списка нет (страница по такому таймер не показывает).
    Считает тот же срок, по которому круг ленты решает «пора» (`people_snap_due`),
    — вторая цифра на тот же вопрос разъехалась бы с кругом на первой правке.
    """
    if not snapshot:
        return {'result': {'people': [], 'cached': False, 'age_sec': -1,
                           'taken_at': '', 'refreshing': refreshing, 'error': error,
                           'next_in_sec': next_in}}

    # Возраст меряется календарными часами, а не монотонными: снимок переживает
    # перезапуск процесса, а монотонные часы после него начинаются заново — и
    # недельный снимок объявили бы свежим.
    return {'result': {'people': _online_now(snapshot['people'], site_id, kind),
                       'cached': cached,
                       'age_sec': max(0, int(time.time() - snapshot['at'])),
                       'taken_at': snapshot['when'],
                       'refreshing': refreshing,
                       'error': error,
                       'next_in_sec': next_in}}


async def _with_favorites(answer: dict, site_id: int, kind: str) -> dict:
    """Отмечает в ленте тех, кого сайт держит в избранных.

    Args:
        answer: готовый ответ ручки — правится на месте.
        site_id: сайт-закладка.
        kind: вид списка. Отмечаем только ленту онлайна.

    Returns:
        dict: тот же ответ, у карточек появилось поле `favorite`.

    ## ⚠⚠ Отметка, а не отдельный список

    Лента «Избранные онлайн» на «Приставании» — это та же лента «Все онлайн»,
    из которой выброшены чужие. Своей ручки, своего кэша и своего снимка у неё
    нет нарочно: два списка «кто сейчас в сети» разъезжаются во времени, и
    человек видел бы в одном виджете зелёного, а в другом того же серым. Так уже
    было с избранными и онлайном, и чинили это как раз сведе́нием к одному
    источнику (`_online_now`).

    ⚠ **Только для `online`.** У списков по анкете вопрос другой — «кто у **этой**
    девушки», — и отвечает на него `favorite_settled`.

    ⚠ **Один запрос на ответ, а не на карточку.** Лента бывает в полторы сотни
    человек; спроси мы базу по каждому, отрисовка стоила бы полутора сотен
    запросов вместо одного.
    """
    if str(kind) != 'online':
        return answer

    people = (answer.get('result') or {}).get('people') or []
    if not people:
        return answer

    from src.dating.favorite import favorite_site_uids

    uids = await favorite_site_uids(int(site_id or 0))

    for one in people:
        one['favorite'] = str(one.get('uid') or '') in uids

    return answer


def _online_now(people: list, site_id: int, kind: str) -> list:
    """Проставляет «в сети» по ленте сайта, а не по тому, что сказал список.

    ⚠⚠ **Список избранных врал про онлайн, и врал долго.** Его снимают раз в
    несколько часов (`favorites_keep`) и держат в кэше; признак `online` в нём —
    это «был ли он в сети **в момент съёмки**». Человек смотрел на виджет «Мои
    фавориты», видел серую точку у собеседника, который в это же время горел
    зелёным в ленте «Все онлайн», — и оба списка были по-своему правы.

    Ответ на «кто в сети прямо сейчас» в панели один — снимок ленты
    (`online.py`): по нему решает отправка, по нему же светятся точки в
    диалогах. Здесь он и берётся.

    ⚠ **Ленту не трогаем**: принадлежность ей и означает «в сети», и спрашивать
    её саму о себе незачем.

    ⚠ **«Не знаем» — не повод гасить точку.** Ленты может не быть вовсе (её ещё не
    снимали) или она протухла; тогда оставляем то, что сказал список — соврать
    «офлайн» там, где мы просто не смотрели, хуже устаревшей правды.
    """
    site_id = int(site_id or 0)
    if not site_id or kind == 'online' or not people:
        return people

    from src.dating.online import online_check

    out = []
    for one in people:
        row = dict(one)
        state = online_check(site_id, str(row.get('uid') or ''))
        if state.get('known'):
            row['online'] = bool(state.get('online'))
        out.append(row)

    return out


async def _list(kind: str, fresh: bool, profile: dict, key: str, log_id: int,
                cached: dict | None = None, hold: str = '',
                scheduled: bool = False) -> dict:
    """Общее тело обоих списков: кэш, фоновое обновление, запись в журнал.

    Args:
        kind: вид списка.
        fresh: обходить выдержку (но не жёсткий пол).
        profile: под какой анкетой заходить на сайт.
        key: ключ снимка в Redis — по анкете или по сайту.
        log_id: чей журнал ведём. Ноль — списка по сайту: он не про одну анкету, и
            писать его в журнал случайно выбранной было бы враньём. След прогона
            при этом остаётся в журнале прогонов (`scenario.py`).
        cached: уже прочитанный снимок, если вызывающий его читал.
        hold: почему на сайт сейчас не идём (`_hold_why`). Непусто — отдаём
            прежний снимок с этой причиной и обновления **не заводим**.
        scheduled: есть ли у этого снимка круг, который обновит его сам. Таймер
            «через сколько зайдём сами» честно только у таких; у прочего его нет
            и в ответе (`-1`), иначе страница обещала бы срок, которого никто не
            держит.
    """
    site_id = int(profile.get('site_id') or 0)
    keep = await _keep_sec(kind, site_id)
    floor = await _floor_sec(site_id)
    # Выдержку читаем один раз на вызов и передаём дальше: она уходит и в проверку
    # снимка, и в сторож фоновых попыток, а два чтения настройки на один запрос —
    # два обращения в базу за одним и тем же числом.
    fresh_sec = await _fresh_sec(kind, site_id)

    cached = cached if cached is not None else _cache_get(key)

    # ⚠ **Срок проверяем при показе, а не только сроком Redis.** Снимок мог лечь с
    # прежним, длинным сроком, а настройку после этого укоротили: Redis о правке не
    # знает и додержит его до своего конца. Показать в таком случае старое значило
    # бы не выполнить то, о чём попросили настройкой.
    #
    # Ключ заодно убираем: место в Redis держать незачем, а следующий заход и так
    # начнёт со чистого листа.
    if cached and time.time() - cached['at'] >= keep:
        _cache_drop(key)
        cached = None

    # Свежий снимок отдаём не спрашивая сайт — ради этого кэш и существует. Кнопка
    # «обновить» (`fresh`) выдержку обходит, но пол — нет: он про предел самого
    # сайта, а не про то, чего хочет страница.
    if cached and time.time() - cached['at'] < (floor if fresh else fresh_sec):
        # Таймер ставим и здесь, хотя у scheduled-видов ручка обычно отдаёт
        # свежий снимок сама, не доходя до этой строки: сюда она доходит, только
        # если фоновый прогон успел переписать кэш между двумя чтениями.
        return _answer(cached, cached=True, error='', site_id=site_id, kind=kind,
                       next_in=(max(0, fresh_sec - int(time.time() - cached['at']))
                                if scheduled else -1))

    # ⚠⚠ **Анкете не в сети список не снимаем.** Снимок берётся **под ней**: для
    # сайта это вход, а вход под спящей учёткой — лишний поход наружу, который в
    # плохой день кормит счётчик неудачных входов и стоит блокировки адреса всей
    # установке. Отдаём прежний снимок с причиной: он честнее пустоты, и человек
    # видит, почему список не обновился.
    #
    # ⚠ Кнопка «обновить» этого **не обходит** — в отличие от выдержки. Выдержка
    # про нашу бережливость, а здесь про цену для сайта, и щелчок её не отменяет.
    if hold:
        return _answer(cached, cached=bool(cached), error=hold,
                       site_id=site_id, kind=kind)

    # ⚠ **Ручка не ждёт прогона. Никогда.**
    #
    # Прогон — это вход на сайт под анкетой, сорок секунд живого браузера, а с
    # очередью и минуты. Ждать его в запросе значит держать страницу пустой всё это
    # время: белое окно вместо списка, который либо уже есть, либо появится сам.
    #
    # Поэтому: есть снимок — отдаём его, нет — отдаём пустой, и в обоих случаях
    # заводим обновление в фоне. Страница по `refreshing` знает, что стоит вернуться
    # за результатом, и показывает «снимаю…» вместо «пусто».
    #
    # `error` — чем кончилась прошлая попытка: молча показывать старое хуже всего,
    # человек смотрит на список и не знает, что новый не снимается.
    refreshing = _refresh_start(profile, kind, key, log_id, fresh, fresh_sec, floor)

    # ⚠ **Таймер нужен и здесь, а не только на свежей дороге.** Именно на этой
    # дороге человек сидит дольше всего: круг заводит, сайт список не даёт, и без
    # счётчика остаётся «кеш · не обновилось» — ни срока, ни признака, что это
    # кончится. Считаем от попытки — тем же штампом, каким `_refresh_start` меряет
    # свою выдержку: две цифры на вопрос «когда следующая попытка» сошлись бы
    # только в удачный день, а разъезжаются молча. По штампу попытки, а не по
    # возрасту снимка: при неудачах снимок стареет бесконечно и счётчик весь этот
    # срок врал бы «скоро», хотя сторож держит заход до конца выдержки.
    next_in = (max(0, fresh_sec - int(time.time() - _attempt_at(key)))
               if scheduled and cached else -1)

    return _answer(cached, cached=bool(cached), error=_refresh_error.get(key, ''),
                   refreshing=refreshing, site_id=site_id, kind=kind,
                   next_in=next_in)


def _guests_refresh_start(site_id: int) -> None:
    """Заводит фоновый съём гостей — тот, что просит кнопка «обновить».

    ⚠ Один сайт не снимается дважды: задача жива — второй клик ничего нового
    не заводит. Два параллельных прогона одних и тех же анкет — это два входа
    на сайт под одной учёткой подряд, а лимит входов сайт считает по IP, не
    разбирая, кто стучится.
    """
    key = int(site_id)
    task = _guests_refreshing.get(key)

    if task and not task.done():
        return

    async def _run() -> None:
        try:
            got = await guests_site_sweep(key, due_only=False, cap=0)
            why = str(got.get('error') or '')
            if why:
                _guests_refresh_error[key] = why
            else:
                _guests_refresh_error.pop(key, None)
        except Exception as e:
            _guests_refresh_error[key] = str(e) or type(e).__name__
            logger_info(f'[dating] гости сайта #{key} не обновились: {e}')

    _guests_refreshing[key] = asyncio.create_task(_run())


def _guests_age(taken_at: str) -> int:
    """Возраст ленты в секундах — с момента, когда мы записали последний визит.

    ⚠ Меряем по **нашему** времени записи, а не по дате визита: дата отвечает
    «когда он заходил» (и то словами со страницы, а то и пустотой), возраст —
    «когда мы это узнали». Сместить одно другим значило бы доложить «лента
    обновлялась вчера» там, где сегодня сняли анкету с вчерашним гостем.

    `-1` — ленты нет вовсе; ноль был бы враньём свежестью (см. `_answer`).
    """
    if not taken_at:
        return -1

    try:
        when = datetime.strptime(taken_at, '%Y-%m-%d %H:%M:%S')
    except ValueError:
        return -1

    return max(0, int((datetime_utc_now() - when).total_seconds()))

