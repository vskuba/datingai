"""Сайты: снимок списка соседа и наши настройки к нему.

Сам сайт живёт в RhapsodyAi — там его адрес, метки, `presence` и сценарии. Здесь
две вещи: **снимок его списка**, чтобы панель работала, когда сосед недоступен, и
настройки, которые про **нашу** работу с сайтом и у соседа хранить негде.

## ⚠ Снимок — не свой список сайтов

Правило проекта («своей копии чужих данных здесь не заводится») ослаблено ровно на
одну вещь, и вот почему. Селект сайта стоит в шапке **каждой** страницы раздела, и
список для него брали у соседа при каждом открытии. Лежит сосед — селект пуст, и
панель целиком выглядит сломанной: без выбранного сайта ни анкет, ни профилей, ни
журналов. Причём наши-то данные на месте.

Размен принят осознанно:

* было: копии нет, разойтись не с чем, но лежащий сосед гасит всю панель;
* стало: копия есть и может разойтись с оригиналом — ценой пустого селекта.

Расхождение лечится само: каждый показ списка заводит фоновую сверку, и
переименованный сайт получает новое имя в ту же секунду, когда сосед отвечает.
Живёт оно ровно столько, сколько сосед недоступен.

⚠ **Список по-прежнему ведёт сосед.** Строки здесь — снимок его ответа: сайт,
которого у него нет, помечается `is_gone` при первой удачной сверке и из селекта
исчезает. Ручки «завести сайт» здесь нет и не будет — заводят их у него.

Отсюда форма ответа: ручка складывает **снимок списка** и **наши настройки**. Сайт
без сохранённых настроек в списке всё равно есть — с пустым набором.

## Почему JSON, а не колонка на настройку

Настройки сайта только заводятся, и какие понадобятся, сейчас не знает никто.
Колонка под каждую означала бы миграцию на каждую. Когда список устоится, частые
переедут в свои колонки — тогда будет что переносить.

## Права

Граница проходит не по «сайт против анкеты», а по **устройству против работы**.

| Что | Кому | Почему |
|-----|------|--------|
| настройки сайта (`PUT /{id}`), показ секрета, вход в панель | админу | адреса, пароли, частоты — устройство установки |
| выключатели занятий и расписания смен | **всем вошедшим** | это и есть работа оператора анкет |

⚠ **Прежде правка была целиком админской**, и довод звучал так: настройка сайта
меняет работу всех анкет, а не той, что открыл нажавший. Довод верен про адреса и
частоты — и неверен про выключатели: «включить рассылку», «поставить смены»,
«снять генерацию ответов» — это ровно то, ради чего оператора и заводят. Он
открывал «Профили», видел запертые галочки и звал админа щёлкнуть за него.

Чтение открыто всем и было: оператору полезно видеть, с чем он работает.

## Из чего состоит эта дверь

Разложено по тому, **к кому ходит** код, и где он при этом нужен:

| Файл | О чём |
|------|-------|
| `site_.py` (здесь) | ручки: показ списка, чтение, показ секрета, сохранение |
| `site_switch.py` | выключатели занятий и расписания смен — свои колонки |
| `site_sync.py` | фоновая сверка снимка с соседом — только к нему |
| `src/dating/site_setting.py` | **реестр настроек и чтение значений для кода** |
| `src/dating/site_snapshot.py` | **снимок списка сайтов** |

⚠⚠ **Две нижние строки — домен, а не дверь, и это важнее порядка файлов.**
Реестр и читалку звал весь проект: круги, отправка, присутствие, прокси — 109
ссылок, из них **73 отложенными импортами внутри тел функций**, потому что
обычный импорт давал круг «домен → роутер → домен». То есть круг рассылки
импортировал HTTP-роутер, чтобы узнать свой срок. Теперь читалка в домене,
роутер её импортирует как все, и обходных импортов не нужно вовсе.

⚠ **Проверка формы (`_number_check`) осталась здесь.** Она отвечает
`HTTPException 422`, то есть её контракт — код ответа HTTP; границы, по которым
она проверяет, лежат в реестре и импортируются. Так знание о границах в одном
месте, а знание о кодах ответа не протекает в домен.

Импорт идёт в одну сторону: дверь знает про домен и про сверку, домен про дверь
не знает вовсе.
"""

import json

from fastapi import APIRouter, Depends, HTTPException, status
from pydantic import BaseModel, Field

from mysql_.mysql_ import mysql_get_db_async

from src.auth.auth import AuthUser, auth_admin_required, auth_required
# ⚠ Чтение — **модулем, а не именем**, и это не стиль. Подменить настройки в
# тесте можно только в одном месте: сюита патчит `site_settings_all` у
# `src.dating.site_setting`, и этот вызов обязан видеть подмену. Возьми мы имя
# (`from … import site_settings_all`), роутер держал бы свою ссылку, и подмена
# доезжала бы до домена, но не до ручек — половина сюиты проверяла бы не то.
from src.dating import site_setting as setting_
from src.dating.site_setting import (SITE_GROUPS, SITE_KEY_MAX, SITE_KNOWN,
                                     SITE_SUBGROUPS)
from src.dating.site_snapshot import site_rows
from src.uvicorn.routers.dating.site_sync import (site_sync_answer,
                                                  site_sync_start)

router = APIRouter(prefix='/api/dating/site', tags=['dating'])

# Чем секрет выглядит наружу. ⚠ **В списке и в чтении одного сайта — только маска,
# никогда настоящее значение.** Эти ответы уходят на каждую смену сайта и оседают в
# журналах запросов; пароль в них попадать не должен.
#
# Посмотреть пароль всё же можно — отдельной ручкой `/{site_id}/reveal/{key}` по
# нажатию «показать», и только администратору. Так обращение к паролю видно как
# отдельное событие с именем ключа, а не растворяется в обычном показе страницы.
# Тот же приём и то же разделение, что у переменных сайта у соседа.
#
# Точки, а не пустая строка: пустое значение на странице читалось бы как «пароль не
# задан», и человек вписал бы его второй раз, гадая, почему не работало.
SITE_SECRET_MASK = '••••••••'


class DatingSiteSave(BaseModel):
    """Настройки сайта целиком: страница шлёт весь набор, а не по одной."""

    settings: dict[str, str] = Field(default_factory=dict)


@router.get('', include_in_schema=False)


async def site_list(user: AuthUser = Depends(auth_required)):
    """Сайты вместе с нашими настройками — из снимка, а не от соседа.

    Returns:
        dict: `sites` — записи `id`, `name`, `url`, `settings`; `known` — реестр
        известных настроек, по которому страница рисует их набором значений, а не
        полем ввода; `groups` и `subs` — вкладки и подразделы внутри них, с
        подписями и порядком; `sync` — когда снимок сверяли и идёт ли сверка
        сейчас.

    ⚠ **502 отсюда не приходит.** Отвечаем снимком и заводим сверку в фоне: лежащий
    сосед не повод показывать пустую страницу настроек. Отказ сверки виден на
    «Ошибках» (`error.py`), а не вместо списка.
    """
    saved = await setting_.site_settings_all()
    rows = await site_rows()

    return {'result': {'sites': [{'id': row['id'],
                                  'name': row['name'],
                                  'url': row['url'],
                                  'settings': _masked(saved.get(row['id'], {}))}
                                 for row in rows],
                       'known': _known(),
                       # Подписи групп и их порядок — с сервера: страница не должна
                       # знать, какие группы бывают, иначе новая группа в реестре
                       # требовала бы правки и здесь, и в разметке.
                       'groups': [{'key': key, 'title': title}
                                  for key, title in SITE_GROUPS],
                       # Подразделы вкладок — тем же порядком и по той же
                       # причине: подписи знает сервер, а не разметка.
                       'subs': [{'key': key, 'group': group, 'title': title}
                                for key, group, title in SITE_SUBGROUPS],
                       'sync': site_sync_answer(site_sync_start())}}


@router.get('/{site_id}', include_in_schema=False)


async def site_get(site_id: int, user: AuthUser = Depends(auth_required)):
    """Настройки одного сайта. Нет строки — пустой набор, а не 404.

    Сайт, который ещё не настраивали, — законное состояние, а не ошибка: строка
    появляется при первом сохранении.
    """
    return {'result': {'site_id': site_id,
                       'settings': _masked((await setting_.site_settings_all()).get(site_id, {}))}}


@router.get('/{site_id}/reveal/{key}', include_in_schema=False)


async def site_reveal(site_id: int, key: str,
                             user: AuthUser = Depends(auth_admin_required)):
    """Настоящее значение секретной настройки — по нажатию «показать».

    Returns:
        dict: `key` и `value`. Не секретный ключ отдаётся как есть: прятать то, что
        и так видно в списке, значило бы делать вид, что оно секрет.

    Raises:
        HTTPException: 404 — у сайта нет такой настройки.

    ⚠ **Отдельной ручкой, а не полем списка, и это не формальность.** Список
    перерисовывается на каждой смене сайта, и отдавай он пароли — они оседали бы в
    журналах запросов десятками раз в день. Здесь же обращение к паролю видно как
    отдельное событие с именем ключа: кто-то нажал «показать».

    ⚠ **Только администратору.** Правка настроек и так его право (настройка меняет
    работу всех анкет на сайте), а пароль тем более. У соседа под это заведено своё
    право (`BROWSER_SECRET_VIEW`), отличное от «смотреть»; здесь ролей две, и
    третьей ради одной ручки не заводим — расхождение записано в `auth.md`, §7.
    """
    value = (await setting_.site_settings_all()).get(int(site_id), {}).get(str(key))
    if value is None:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND,
                            detail=f'у сайта нет настройки «{key}»')

    return {'result': {'key': str(key), 'value': str(value)}}


@router.put('/{site_id}', include_in_schema=False)


async def site_save(site_id: int, payload: DatingSiteSave,
                           user: AuthUser = Depends(auth_admin_required)):
    """Переписывает настройки сайта целиком.

    ⚠ **Целиком, а не по ключу.** Страница держит весь набор перед глазами и шлёт
    то, что на ней; правка по одному ключу означала бы, что удаление — отдельная
    ручка, а порядок двух правок подряд начинает значить.

    Raises:
        HTTPException: 422 — пустой или слишком длинный ключ.
    """
    before = (await setting_.site_settings_all()).get(int(site_id), {})

    clean = {}
    for key, value in (payload.settings or {}).items():
        key = str(key).strip()
        if not key:
            raise HTTPException(status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
                                detail='ключ не может быть пустым')
        if len(key) > SITE_KEY_MAX:
            raise HTTPException(
                status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
                detail=f'ключ длиннее {SITE_KEY_MAX} знаков: «{key[:60]}…»')

        # ⚠ **Маска вместо секрета означает «не трогать».** Страница настоящего
        # значения не знает и прислать его не может; прими мы точки как значение —
        # первое же сохранение любой соседней настройки затёрло бы пароль строкой
        # «••••••••», и вход перестал бы работать без единого сообщения.
        if str(value) == SITE_SECRET_MASK:
            was = before.get(key, '')
            if was:
                clean[key] = was
            continue

        # Пустое значение выбрасывается, а не хранится: «настройки нет» и
        # «настройка пустая» — разные вещи, и путать их значит получать
        # необъяснимое поведение там, где умолчание кода было осмысленным. То же
        # правило, что у настроек панели (`api.md`, §6.2).
        if str(value) != '':
            clean[key] = _number_check(key, str(value))

    async with mysql_get_db_async() as db:
        await db.execute(
            'INSERT INTO site (site_id, settings) VALUES (%s, %s)'
            ' ON DUPLICATE KEY UPDATE settings = VALUES(settings)',
            (int(site_id), json.dumps(clean, ensure_ascii=False)))
        await db.connection.commit()

    await _proxy_off(int(site_id), before, clean)

    return {'result': {'site_id': site_id, 'settings': _masked(clean)}}

# ── Приватное ────────────────────────────────────────────────────────────────


def _number_check(key: str, value: str) -> str:
    """Числовая настройка — целое в своих границах. Иначе `422`.

    Args:
        key: ключ настройки.
        value: что прислали.

    Returns:
        str: то же значение, приведённое к целому без хвостов («07» → «7»).

    Raises:
        HTTPException: 422 — не число или вне границ, с указанием, каких.

    ⚠⚠ **Проверять обязательно здесь, а не только в форме.** У поля стоят `min` и
    `max`, но браузер — не единственный источник запроса: ручка открыта тому, у
    кого есть токен, и «-500» прошло бы молча. Для доли это не мелочь:
    отрицательная сравнится с `random.random()` как «никогда», и человек получил
    бы тихо выключенную настройку вместо отказа.

    ⚠ **Не числовые настройки не трогаем.** Здесь только те, у кого в реестре
    стоит `kind: 'number'`: остальные бывают строками, JSON и расписанием.
    """
    spec = SITE_KNOWN.get(str(key), {})
    if str(spec.get('kind') or '') != 'number':
        return str(value)

    try:
        number = int(str(value).strip())
    except ValueError:
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
            detail=f'«{spec.get("title") or key}»: нужно целое число, '
                   f'а пришло «{str(value)[:40]}»')

    # ⚠⚠ **Потолка у счётчиков нет, и это решение заказчика.**
    #
    # Он стоял и мешал: «тысяча» казалась щедрой для пула инвайтов, а на проде
    # десяток анкет и почти две сотни людей дают под две тысячи пар — запрет
    # пришёлся ровно по живой работе. Всякое число «по здравому смыслу» однажды
    # окажется меньше настоящей: сколько людей на сайте, знает тот, кто его ведёт.
    #
    # ⚠ **Нижняя граница остаётся.** Отрицательное количество — не выбор, а
    # поломка: `-5` сравнится с чем угодно как «никогда» и тихо выключит занятие
    # вместо того, чтобы отказать вслух.
    low, high = spec.get('min'), spec.get('max')

    if (low is not None and number < int(low)) \
            or (high is not None and number > int(high)):
        bounds = f'от {low} до {high}' if high is not None else f'не меньше {low}'

        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
            detail=f'«{spec.get("title") or key}»: значение {number} вне границ '
                   f'({bounds})')

    return str(number)


def _known() -> list[dict]:
    """Реестр в виде, пригодном для страницы: список, а не словарь.

    Списком, потому что порядок значит: настройки показываются в нём, а у словаря
    порядок — случайность его сборки.
    """
    return [{'key': key,
             # Группа уезжает строкой, а не номером: страница подписывает заголовки
             # по `SITE_GROUPS`, и номер пришлось бы держать в двух местах.
             'group': str(spec.get('group') or SITE_GROUPS[0][0]),
             # Подраздел внутри вкладки. Пусто — настройка стоит в общей таблице
             # группы, над подразделами (`SITE_SUBGROUPS`).
             'sub': str(spec.get('sub') or ''),
             'title': spec['title'],
             'note': spec.get('note', ''),
             'default': spec['default'],
             'secret': bool(spec.get('secret')),
             # ⚠ Настройка известна странице, но строки у неё здесь нет: её
             # правят на другой странице (`template_per_day` — у расписания
             # шаблонов). Отдать её **надо**: иначе страница сочтёт ключ чужим
             # и покажет в «Своих настройках» — то есть он просто переедет на
             # соседнюю вкладку вместо того, чтобы исчезнуть.
             'hidden': bool(spec.get('hidden')),
             # Вид поля, если он не «набор значений» и не «строка». Пока такой
             # один — отбор выходов: его список приходит не из реестра, а от
             # соседа, и рисуется он мультивыбором.
             'kind': str(spec.get('kind') or ''),
             # Границы числового поля. ⚠ Уезжают странице **и** проверяются на
             # сервере (`_number_check`): форма подсказывает, а решает сервер —
             # запрос приходит и мимо формы.
             'min': spec.get('min'),
             'max': spec.get('max'),
             'options': [{'value': value, 'title': title}
                         for value, title in spec.get('options') or ()]}
            for key, spec in SITE_KNOWN.items()]


def _masked(settings: dict) -> dict:
    """Набор настроек, годный к отправке наружу: секреты заменены точками.

    ⚠ **В этих ответах секрета нет ни для кого, включая администратора.** Список и
    чтение одного сайта уходят на каждую смену сайта и оседают в журналах запросов;
    пароль в них попадать не должен.

    Правке это не мешает: страница шлёт маску обратно, и сохранение понимает её как
    «оставить прежний» (`site_save`). А посмотреть пароль можно отдельной
    ручкой (`site_reveal`) — по нажатию и только админу, чтобы обращение к
    нему было видно отдельным событием.
    """
    secret = {key for key, spec in SITE_KNOWN.items() if spec.get('secret')}

    return {key: (SITE_SECRET_MASK if key in secret and value else value)
            for key, value in settings.items()}


async def _proxy_off(site_id: int, before: dict, after: dict) -> None:
    """Галочку «использовать выходы» сняли — снимаем выходы с анкет сайта.

    ⚠ **Иначе выключатель выключает половину.** Раздача спрашивает настройку и
    после снятия отдаёт пусто, но кэш в `profile_.proxy_url` остаётся, а
    его читают напрямую: удары присутствия берут адрес из колонки, прогоны
    сценариев — номер выхода. Анкета продолжала бы ходить каналом, которого для
    сайта уже нет, — и объяснить это, глядя на снятую галочку, было бы нечем.

    ⚠ **Только на переходе `1 → не 1`.** Сохранение настроек идёт при каждой
    правке любого поля; чисти мы по факту «сейчас выключено», каждое сохранение у
    сайта без прокси лезло бы в таблицу анкет ни за чем.
    """
    from src.dating.proxy import (PROXY_ENABLED_SETTING,
                                         proxy_forget_site)

    key = PROXY_ENABLED_SETTING
    was = str(before.get(key, '')).strip() in ('1', 'true', 'on')
    now = str(after.get(key, '')).strip() in ('1', 'true', 'on')

    if was and not now:
        await proxy_forget_site(int(site_id))
