"""Сайты-закладки — витрина того, что лежит у соседа.

Закладки, сценарии и пул Chromium — хозяйство RhapsodyAi. Но странице нужен
список, чтобы человек выбрал, к какому сайту относится анкета, и ходить за ним из
браузера напрямую нельзя: служебный токен живёт на сервере и в разметку попадать
не должен.

## ⚠ Отвечаем снимком, а сверяем в фоне

Раньше эта ручка спрашивала соседа при каждом открытии страницы. Лежит сосед —
селект пуст, и панель целиком выглядит сломанной: без выбранного сайта ни анкет,
ни профилей, ни журналов. Причём наши данные на месте, показать их ничто не мешает.

Поэтому порядок тот же, что у списков собеседников (`api.md`, §3.3): **сначала
показать то, что знаем, потом обновлять**. Ручка отдаёт снимок из своей базы и
заводит сверку с соседом в фоне; следующий запрос увидит обновлённый список.

Ждать сверку никто не ждёт, и 502 отсюда не приходит. Отказ сверки виден на
странице «Ошибки» — там ему и место: он про связь между проектами, а не про
конкретный список.
"""

from fastapi import APIRouter, Depends

from src.auth.auth import auth_required
from src.dating.site_live import SITE_LIVE_HOURS, site_live_rows
from src.dating.site_snapshot import site_rows
from src.uvicorn.routers.dating.site_sync import site_sync_start

router = APIRouter(prefix='/api/site', tags=['site'])


@router.get('')
async def site_list(user=Depends(auth_required)):
    """Сайты-закладки для селекта в шапке страниц раздела.

    Returns:
        dict: `result` — список записей `id`, `name`, `url`, `tags`; `sync` — идёт
        ли сверка с соседом прямо сейчас и чем кончилась прошлая.

    `result` остаётся **списком**, а не словарём с полями: его читает общий селект
    (`site_.js`) на каждой странице раздела, и менять форму ради служебного
    поля значило бы править их все.
    """
    rows = await site_rows()
    refreshing = site_sync_start()

    return {'result': [{'id': row['id'], 'name': row['name'],
                        'url': row['url'], 'tags': row['tags']} for row in rows],
            'sync': {'refreshing': refreshing,
                     'synced_at': max((row['synced_at'] for row in rows
                                       if row['synced_at']), default=None)}}


@router.get('/live')
async def site_live(user=Depends(auth_required)):
    """Живые счётчики вкладок: кто в сети и много ли работы за полсуток.

    Returns:
        dict: `result` — `{номер сайта: {online, profiles, whole, chat, mail}}`,
        `hours` — за сколько часов считана работа.

    ## ⚠⚠ Своя ручка, а не поле в списке сайтов

    Список меняется раз в недели, счётчики — каждые несколько секунд. Сведи мы
    их в одну ручку, страница возила бы имена и адреса сайтов на каждый тик
    обновления. Плюс оговорка у соседней ручки: форму `result` там менять
    нельзя, её читает общий селект всех страниц раздела.

    ⚠ Путь `/live` объявлен **до** `/{site_id}` в других роутерах не случайно
    — здесь он единственный после корня, но правило то же: слово, похожее на
    номер, однажды прочиталось бы номером.

    ⚠ Отказ не приходит вовсе: счётчики украшают вкладку, и ронять из-за них
    шапку значило бы поменять важное на второстепенное. Не прочиталось —
    пустой словарь, вкладки рисуются без чисел (`site_live.py`).
    """
    return {'result': await site_live_rows(), 'hours': SITE_LIVE_HOURS}
