"""Базовый путь: под каким URI проект виден снаружи.

Локально панель живёт в корне (`http://localhost:8021/`), а на проде — под общим
доменом рядом с RhapsodyAi, отдельным путём (`/dating`). Домен один, и делить его
приходится по URI.

Прокси префикс **срезает**, поэтому само приложение всегда видит пути от корня:
`/api/dating/girl`, `/static/js/api.js`. Проблема только в разметке — браузер
запрашивает то, что написано в HTML, и `/static/...` из страницы под `/dating`
ушёл бы к соседу, а не к нам.

Отсюда правило: **в шаблонах пути пишутся с `{{ base }}`**, а в коде — как есть.
Пустой `BASE_PATH` (локально) даёт прежние абсолютные пути, и разница исчезает.
"""

from config.config import config_get

# Под каким URI проект виден снаружи. Пусто — в корне домена.
# Слэш на конце убираем: в шаблонах пишется `{{ base }}/static/...`, и вторая
# косая дала бы `//static`, который браузер считает адресом другого хоста.
UVICORN_BASE_PATH = '/' + str(config_get('BASE_PATH', '')).strip().strip('/') \
    if str(config_get('BASE_PATH', '')).strip().strip('/') else ''


def uvicorn_base_path() -> str:
    """Базовый путь для шаблонов. Пусто либо `/dating` — без слэша на конце."""
    return UVICORN_BASE_PATH
