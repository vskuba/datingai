"""
Воркер чата знакомств: держит вебсокеты всех учёток, чтобы сообщения приходили живыми.

В сообщении очереди нет ничего — задание одно на всю установку. Это не «работа над
объектом», как у конвейера задач, а смена: один job поднимает сокеты всех готовых
учёток, держит их `CHAT_WORKER_HOLD_SEC` и завершается. Список учёток job перечитывает
на ходу (`chat_hold`), поэтому заведённая в середине смены анкета берётся в
работу через минуту, а не в следующую смену.

Кто ставит: восстановление при старте uvicorn (`chat_worker_recover`) и сама смена
в конце своей работы. Оба зовут `chat_worker_enqueue()` вслепую — от дублей защищает
single-flight, и лишний вызов просто ничего не делает.

Очередь одна (`dating`) и других в проекте нет: работа здесь одна — держать сокеты.

## ⚠⚠ Устройство смены — в общем слое `py_modules/worker_/`

Замок с коротким сроком, продление изнутри job'а, постоянный сторож, самопостановка
следующей смены, закрытие пула MySQL — всё это `worker_.worker_shift`, страница
`.claude/docs-common/worker_shift.md`. Здесь остаётся только наше: чем занята смена
(`chat_hold_run`), её имена и сроки.

Своей копии этой механики тут больше нет. Она была, и оказалась дублем соседнего
проекта: PersonaAI написала то же самое независимо, и совпало до числа — срок
смены, потолок задания, срок замка, темп продления, шаг сторожа.

⚠ **Точка входа (`chat_worker_job_run`) обязана остаться здесь**, и в слой её
перенести нельзя: `rq` восстанавливает job по полному имени модуля — в Redis
уезжает ссылка, а не код. Перенеси её, и воркер поднял бы функцию слоя, которая
не знает, какую работу крутить.

Зачем смена конечна, если работа бесконечна. Перезапуск раз в несколько часов — это
обновление кода без ручного рестарта, сброс накопленных соединений и естественная
точка, где умерший воркер заменяется живым. Бесконечный job не даёт ни одного из трёх.

Общие правила — `.claude/docs/worker.md`, предметная часть — `.claude/docs/dating.md`.
"""
import asyncio

from worker_.worker_shift import (worker_shift_busy, worker_shift_enqueue,
                                  worker_shift_keep, worker_shift_keep_stop,
                                  worker_shift_run, worker_shift_unlock)

from src.dating.chat_hold import chat_hold_run
from src.dating.error import error_catch_install

CHAT_WORKER_QUEUE_NAME = 'dating'

# Чья смена — словом. Уезжает в каждую строку журнала слоя, по нему их и отбирают.
CHAT_WORKER_WHAT = 'chat_worker'

# Длина смены. Меньше часа — и перехваты адресов сокетов начинают стоить дороже
# самой работы; больше суток — и правка кода не доезжает до живых соединений.
CHAT_WORKER_HOLD_SEC = 6 * 3600

# Как часто uvicorn проверяет, жива ли смена.
#
# ⚠ **Проверка постоянная, а не разовая при старте**, и это исправление настоящего
# отказа. Смена живёт в контейнере воркера; перезапуск этого контейнера её
# обрывает, и поставить следующую становится некому: сама она мертва, а uvicorn
# своё дело сделал на старте и больше не вернётся. Установка остаётся без
# держателя сокетов, без круга расписания, без рассылки и без ленты — при
# работающей на вид панели. Час такого простоя уже был, и обнаружился случайно.
#
# Довод остаётся здесь, а не уезжает в слой с умолчанием: сторож сторожит **нашу**
# смену, и число, которое его задаёт, человек ищет рядом с ней.
CHAT_WORKER_KEEP_STEP = 30

# Ключ замка. Имя своё у каждой установки: один ключ на двоих означал бы, что
# смена одного проекта запирает смену другого.
#
# ⚠ **Значение остаётся `…:flight`, хотя замок в слое переименован в `lock`.**
# Ключ лежит в живом Redis: идущая прямо сейчас смена держит именно его, и новый
# код, искавший бы другое имя, не увидел бы её и поставил **вторую** — то есть
# ровно то, от чего замок и заведён. Для чата это два держателя одной учётки, а
# сайт вышибает оба. Переименовать значение можно только вместе с остановкой
# воркера.
_LOCK_KEY = 'chat_worker:flight'

# Сторож. Держим ссылку, иначе задачу может убрать сборщик мусора.
_keep_task = None


def chat_worker_enqueue() -> str | None:
    """
    Поставить смену держателя чата в очередь. None — смена уже идёт.

    Безопасно звать откуда угодно и как угодно часто: ключ single-flight делает
    повторный вызов бездействием, а не вторым держателем на те же сокеты. Два
    держателя одной учётки — это два соединения, и сайт вышибает оба.
    """
    return worker_shift_enqueue(chat_worker_job_run,
                                queue=CHAT_WORKER_QUEUE_NAME, key=_LOCK_KEY,
                                what=CHAT_WORKER_WHAT,
                                hold=CHAT_WORKER_HOLD_SEC)


def chat_worker_lock_release() -> bool:
    """Снять замок прежней смены. `True` — он был занят.

    ## ⚠⚠ Звать это можно **только сразу после пересоздания воркера**

    Пересоздание контейнеров обрывает идущее задание, но его замок живёт ещё
    минуты: смена умерла, а место занято. Восстановление на старте
    (`chat_worker_recover`) видит занятый ключ и честно ничего не делает —
    живой чат молчит до следующего перезапуска. Ровно это и ловит выкладка.

    В любом другом месте снятие замка **запрещено**: у работающей смены он
    поднял бы вторую, и обе держали бы вторые соединения на те же анкеты — а
    сайт вышибает оба.

    ## ⚠ Зачем дверь, если в слое есть `worker_shift_unlock`

    Чтобы ключ не уезжал в выкладку. Он приватный (`_LOCK_KEY`) и переживал уже
    одно переименование в слое; знай его `deploy.sh` и `deploy.yml` — переезд
    ломал бы их молча. Так и вышло: оба звали `chat_worker_flight_release`,
    которой не стало при переезде смены в общий слой, и шаг падал `ImportError`
    — смена не вставала, а выкладка докладывала «успех» всем предыдущим шагом.

    Returns:
        bool: был ли замок занят. Ложь — снимать было нечего, и это не ошибка.
    """
    was = worker_shift_busy(_LOCK_KEY)
    worker_shift_unlock(_LOCK_KEY)

    return bool(was)


def chat_worker_job_run() -> str:
    """
    Точка входа rq: одна смена держателя чата.

    Синхронная намеренно — rq зовёт job как обычную функцию, свой event loop
    поднимаем внутри. Функция обязана быть импортируемой по полному имени модуля:
    воркер живёт в отдельном контейнере и восстанавливает её по ссылке из Redis.

    ⚠ Именно поэтому она не уехала в слой — см. заголовок файла.
    """
    return asyncio.run(worker_shift_run(_hold, key=_LOCK_KEY,
                                        what=CHAT_WORKER_WHAT,
                                        again=chat_worker_enqueue,
                                        hold=CHAT_WORKER_HOLD_SEC))


async def chat_worker_recover() -> None:
    """
    Ставит смену при старте uvicorn и сторожит её, пока сервер жив.

    Звать один раз из lifespan. Идущую смену не трогает: она в своём контейнере,
    а `chat_worker_enqueue` заперт тем же ключом — попытка при живом держателе это
    бездействие, а не второй держатель на те же сокеты.

    ⚠⚠ **Сторож постоянный, и это исправление настоящего отказа.** Довод целиком —
    в `CHAT_WORKER_KEEP_STEP` выше и в заголовке `worker_.worker_shift`: разового сторожа
    мало, он чинит лишь случай «перезапустили оба контейнера».

    Живая смена отличается от мёртвой сама: первая продлевает ключ, вторая — нет.
    Опрашивать `rq` и гадать, чей это ключ, не нужно.

    Тик Cronicle остаётся страховкой на случай, когда лёг и сам uvicorn.
    """
    # ⚠ Ссылку держим: задача без неё может уехать в сборщик мусора, и сторож
    # исчезнет молча — то есть ровно тот отказ, который он и призван чинить,
    # только теперь ещё и незаметный.
    global _keep_task

    _keep_task = worker_shift_keep(chat_worker_enqueue, CHAT_WORKER_WHAT,
                                   step=CHAT_WORKER_KEEP_STEP)


async def chat_worker_keep_stop() -> None:
    """Снимает сторожа. Звать на остановке сервера — он бесконечный."""
    worker_shift_keep_stop(_keep_task)


async def _hold(hold_sec: float) -> str:
    """Сама смена: держим сокеты весь срок и говорим, чем кончилось.

    ⚠ Движок агентов здесь не нужен — держатель не ходит к LLM, он читает сокеты
    и пишет в базу. Мини-инфраструктуру (журнал, закрытие пула MySQL) заводит
    слой: отдельный процесс rq не получает lifespan uvicorn.
    """
    # ⚠⚠ **Застава ставится здесь, а не в точке входа**, и это не прихоть:
    # `logging_init()` у смены зовёт слой (`worker_shift_run`), и до него
    # ставить заставу некуда — она подвешивается к логгеру, которого ещё нет.
    # `_hold` же слой зовёт **после** него.
    error_catch_install('worker')

    result = await chat_hold_run(hold_sec)

    return f"смена окончена: учёток {result['profiles']}, сообщений {result['saved']}"
