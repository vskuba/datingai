"""Поля окна письма: один помощник на пять окон, и состояние — одной функцией.

Окон писем пять — инвайт из пула, письмо избранному из пула, ответ, письмо рассылки,
запись журнала избранных, — и каждое показывает одно и то же: от кого, кому,
состояние, почему не ушло, иногда ответ сайта. Строки эти собирались **руками в
каждом окне**, и разметка расходилась мелочами:

    где `bad` у значения, где нет
    где `esc` у текста, где нет
    где пустое значение даёт пустую строку, а где строки просто нет

## ⚠⚠ Расхождения были не косметические — два окна отвечали неправдой

**Состояние.** Две копии из пяти считали его так:

    status !== 'draft' ? 'отправлено' : 'в пуле, не отправлено'

То есть `failed` — отказ сайта — назывался **отправкой**, а у ушедшего терялось
время. В пул `failed` сейчас не приходит (списки берут `draft`), и потому это не
видно; но это свойство запроса, а не окна: поменяется отбор — и окно соврёт.

**Причина.** Окно письма спрашивало `status === 'failed' && error`, и у журнала
доставки это **скрывало причину у застрявшего письма**: журнал показывает и
черновики с причиной отказа (`delivery` у ручки), у них `status = 'draft'`, и окно
молчало о том, почему письмо не ушло — ровно у той строки, ради которой его
открывают.

## ⚠ Поэтому сторож смотрит на единственность, а не на вид

Свериться с видом можно снимком. А то, что вопрос «показать поле записи» решается
**в одном месте**, видно только счётом: сколько окон собирают строку руками.

## ⚠⚠ Карточки пулов — отдельная семья, и она всё ещё размазана

Этот файл про **окна**. Рядом живут карточки пулов (`mail-card-fail`), и у них тот же
хвост «не ушло: причина» скопирован **пять раз** — инвайты, письма избранным, ответы,
рассылка, приставание. Там условие по состоянию на месте (в пуле всё черновики), но
сам хвост стоило бы собрать одним помощником. Не тронуто намеренно: карточки в этой
работе не менялись, а расширять правку на соседнюю семью значит менять то, что никто
не просил проверять.
"""

import pathlib
import re

import pytest

pytestmark = pytest.mark.page

PAGE = (pathlib.Path(__file__).resolve().parents[1]
        / 'data/uvicorn/template/admin/dating/profile.html')

# Окна, которые показывают поля письма. ⚠ Список закрытый: заведётся шестое — тест
# о нём не узнает, и потому рядом стоит проверка на сборку руками по всей странице.
WINDOWS = ('inviteOpen', 'favMailOpen', 'replyOpen', 'letterOpen', 'favSentOpen')


def _func(name: str) -> str:
    page = PAGE.read_text(encoding='utf-8')
    found = re.search(r'\n    (?:async )?function ' + name
                      + r'\([^)]*\) \{.*?\n    \}', page, re.S)

    assert found, f'функция {name} не нашлась'

    return found.group(0)


def _code() -> str:
    """Страница без комментариев.

    ⚠ Иначе сторож считает **объяснения**: у `letterState` в оговорке приведена та
    самая копия, которую она заменила, — и счёт «слово живёт в одном месте» падал на
    верном коде. Это уже второй такой случай в сюите; правило простое — сторож
    смотрит на рисуемое, а не на текст файла.
    """
    return re.sub(r'//[^\n]*', '', PAGE.read_text(encoding='utf-8'))


class TestOneHelperForAllWindows:
    """⚠⚠ Строку «ключ — значение» собирает `letterFact`, и только он."""

    def test_the_helper_exists(self):
        body = _func('letterFact')

        assert 'class="letter-row"' in body, 'помощник не собирает строку'
        assert 'letter-key' in body and 'letter-val' in body, \
            'у строки нет ключа или значения'

    def test_no_window_builds_the_row_by_hand(self):
        """⚠ Исключения названы поимённо, и признак у них один: **значение не
        текст, а разметка**.

        `letterFact` экранирует значение — в том и смысл одного помощника: часть
        окон иначе экранировала бы дважды. Там, где в значении обязана быть
        разметка, помощник не годится вовсе, и строка собирается руками:

        * `letterSides` — две стороны письма: лицо, имя, ссылка, а не текст;
        * `letterShot` — снимок, ушедший письмом: картинка и путь под ней.

        ⚠⚠ Исключение — не «ещё одна строка руками», а **единственный путь**:
        дай мы `letterFact` режим «без экранирования», и правило «значение
        экранирует помощник» перестало бы держаться вовсе — проверять пришлось
        бы каждый вызов.
        """
        page = PAGE.read_text(encoding='utf-8')
        hand = re.findall(r'<div class="letter-row"><span class="letter-key">'
                          r'(?:\$\{key\}|([^<]+))</span>', page)
        named = [one for one in hand if one]

        assert set(named) <= {'От кого', 'Кому', 'Снимок'}, \
            f'строки снова собираются руками: {", ".join(sorted(set(named)))}'

    def test_every_window_uses_it(self):
        for name in WINDOWS:
            assert 'letterFact(' in _func(name), \
                f'окно {name} собирает поля само'

    def test_the_helper_escapes(self):
        """⚠⚠ Экранирует **помощник**, а значение приходит текстом. Иначе часть окон
        экранировала бы дважды: `&amp;` вместо `&` в причине отказа."""
        assert 'esc(String(value))' in _func('letterFact'), \
            'помощник не экранирует значение — в окно уедет чужая разметка'

    def test_empty_value_draws_nothing(self):
        """⚠ Пустая строка под каждой записью читается как «что-то не показали».
        Правило было в трёх окнах из пяти — теперь оно одно."""
        body = _func('letterFact')

        assert re.search(r'return value\s*\n?\s*\?', body), \
            'помощник рисует строку и при пустом значении'


class TestOneAnswerForTheState:
    """⚠⚠⚠ Состояние письма словами — одна функция на все окна."""

    def test_the_words_live_in_one_place(self):
        code = _code()

        for word in ('в пуле, не отправлено', 'отправить не вышло'):
            assert code.count(f"'{word}'") == 1, \
                f'слово «{word}» снова живёт в двух местах'

    def test_the_old_copy_is_gone(self):
        """⚠ Именно эта копия называла отказ отправкой."""
        assert "sent ? 'отправлено'" not in _code(), \
            'копия состояния вернулась — `failed` снова станет «отправлено»'

    def test_it_keeps_the_time_of_sending(self):
        body = _func('letterState')

        assert 'row.sent_at' in body and 'timeShift' in body, \
            'у ушедшего письма потерялось время отправки'

    def test_it_returns_text_not_markup(self):
        """⚠ `esc` внутри не нужен и вреден: экранирует `letterFact`, и двойное
        экранирование дало бы `&amp;` в окне."""
        body = _func('letterState')

        assert 'esc(' not in body, \
            'состояние экранирует само — выйдет двойное экранирование'

    def test_every_window_asks_it(self):
        for name in WINDOWS:
            assert 'letterState(' in _func(name), \
                f'окно {name} называет состояние своими словами'


class TestTheReasonGoesByItsPresence:
    """⚠⚠ Причину показываем **по её наличию**, а не по состоянию записи.

    Условие по состоянию скрывало причину у застрявшего письма — см. заголовок файла.
    """

    def test_no_window_gates_the_reason_by_status(self):
        """⚠⚠ Сторож смотрит **окна**, а не всю страницу.

        Первая его версия искала по всему файлу и находила пять карточек пулов
        (`mail-card-fail`). Там условие по состоянию **на месте**: карточка живёт в
        пуле, где всё — черновики, и «не ушло» на ней значит «попытка была». Это
        отдельная семья, её собственное размазывание названо в оговорке файла.
        """
        for name in WINDOWS:
            gates = re.findall(r"status === '(?:draft|failed)' && \w+\.error",
                               _func(name))

            assert not gates, \
                f'в окне {name} причина снова за состоянием — у части строк скроется'

    def test_the_reason_is_marked_bad(self):
        """⚠ Красным, а не обычным: в окне это ответ на «почему не ушло»."""
        for name in ('letterOpen', 'favSentOpen', 'replyOpen'):
            assert re.search(r"letterFact\('Почему', \w+\.error, true\)", _func(name)), \
                f'причина в {name} не помечена как отказ'
