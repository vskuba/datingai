"""⚠ Список «Шаблоны» режут по страницам, а нумерацию и «запас» считают по всему списку.

С 2026-10-16 заготовки живут у каждой включённой анкеты своей рукой, и список
вырос до размеров всего сайта: пятьдесят семь строк уже не помещались под
экран, а хвост без подвала не был виден вовсе. Листать стали, как у соседей,
но срез на странице держится на двух правилах, за ними и сторож:

* ручка отдаёт список **целиком**, а срез вырезает открытую страницу. Поверни
  сервер резать сам — `mailNewName` считал бы следующий номер по срезанному
  окну, и на второй странице нумерация анкетки начиналась бы сначала, а
  «запас» уборки показывал бы на разных людей на разных страницах;

* подвал рисует общий `pagerRender` (тот же, что у «Профилей» и прочих
  списков панели), а не пятая по счёту выкройка кнопок; на «Переменных» он
  прячется — под чужим списком шаблонный подвал висел бы мёртвым числом.
"""

import pathlib

import pytest

pytestmark = pytest.mark.mail


def _page() -> str:
    return (pathlib.Path(__file__).resolve().parents[1]
            / 'data/uvicorn/template/admin/dating/profile.html').read_text(encoding='utf-8')


class TestTemplatesArePaged:
    def test_the_list_is_cut_into_pages(self):
        """Строки рисуются страницей: без среза хвост списка не виден вовсе."""
        assert 'slice(tmplPage * TMPL_PAGE' in _page(), \
            'список шаблонов снова рисуется целиком'

    def test_the_pager_is_the_shared_one(self):
        """Подвал рисует общий `pagerRender`, а не своя выкройка кнопок."""
        page = _page()

        assert page.count("pagerRender(slot('tmplPager')") == 3, \
            'все три состояния подвала (список, пусто, «Переменные») должны звать общий пейджер'
        assert 'class="page-btn"' not in page, \
            'под список завели свою разметку кнопок вместо общего подвала'

    def test_numbering_and_reserve_count_every_row(self):
        """⚠ Номер и «запас» считаются по **всем** строкам анкетки, не по окну:
        режь сервер — и следующий номер родился бы из одной страницы."""
        page = _page()

        assert 'for (const row of mails)' in page, \
            'mailNewName больше не обходит весь список'
        assert '[...mails]' in page, \
            '«запас» уборки больше не считается по всему списку'

    def test_the_page_is_fixed_when_pages_grew_fewer(self):
        """Страниц могло стать меньше — и та, на которой человек стоял, показала
        бы пустоту вместо списка."""
        assert 'if (tmplPage > pages - 1)' in _page(), \
            'номер страницы не правится, когда страниц стало меньше'


class TestTheNameIsAlwaysCounted:
    """⚠⚠ Имя считает номер **всегда** — пустым `mailNewName` не бывает.

    Пустую строку он отдавал, пока имя было чем подпереть: ответ агента нёс
    название (`TITLE:`), и первая заготовка анкеты называлась им. С 2026-10-17
    ответ — только текст, и пустота стала тупиком на два хода: поле «Название»
    уходило в `POST` пустым (`min_length=1` — отказ), а «+ шаблон AI» звал
    заготовку словом `Draft`, которое узор `template_(\\d+)$` не читает, — второе
    нажатие заводило второй `Draft` рядом с первым.
    """

    def test_the_first_template_is_template_1(self):
        """Считать нечего — это `template_1`, а не пустая строка: так же назвал бы
        её круг, и следующее нажатие продолжит нумерацию, а не начнёт её заново."""
        page = _page()

        assert 'return `template_${last + 1}`;' in page, \
            'mailNewName снова отдаёт пустую строку, когда считать нечего'
        assert "return last ? `template_${last + 1}` : '';" not in page, \
            'вернулась пустая строка у первой заготовки'

    def test_the_page_never_reads_a_title_from_the_agent(self):
        """⚠ Ответ агента имени не несёт (2026-10-17) — `draft.title` всегда
        `undefined`, и чтение его было бы мёртвой ветвью, молча не делающей
        ничего."""
        assert 'draft.title' not in _page(), \
            'страница снова ждёт названия от агента, а ручка его не отдаёт'
