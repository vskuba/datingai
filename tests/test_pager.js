// Пейджер: какие страницы показать, когда их много.
//
// ⚠ **Проверяется настоящий модуль** (`view.js`), а не его копия: копия
// разошлась бы с оригиналом в первую же правку, продолжая при этом проходить.
// Импортируется он подменой `time.js` — единственной зависимости, из
// которой `pagerPages` не нужно ничего.
//
// Запускает это `test_pager.py`: сюита на Python, а модуль на JS, и мост между
// ними — `node`.
//
// Что здесь ловится и почему стоит проверки:
//
//   ряд рос вместе с числом страниц. У сорока страниц он не помещался в колонку и
//   переносился на вторую строку, отодвигая список. Нужны из них три — где мы,
//   начало и конец;
//
//   разрыв в одну страницу. «…» вместо «3» ничего не сокращает (ширина та же), а
//   прячет то, до чего один щелчок.

import assert from 'node:assert/strict';

import {PAGER_GAP, pagerPages} from './view.js';

let провалов = 0;

function проверка(имя, тело) {
    try {
        тело();
        console.log('ok   ' + имя);
    } catch (e) {
        провалов++;
        console.log('ПЛОХО ' + имя + ': ' + e.message);
    }
}

// ── Сколько страниц показываем ───────────────────────────────────────────────

проверка('мало страниц — показываем все, без разрывов', () => {
    // ⚠ До семи включительно (`PAGER_MAX_ROW`): столько мест в самом длинном ряду,
    // и разрыв здесь ничего не сокращает — только прячет. Так и вышло на пяти:
    // «1 2 … 5» той же ширины, что «1 2 3 4 5», а двух страниц в нём нет.
    for (const n of [2, 3, 4, 5, 6, 7]) {
        const got = pagerPages(n, 0);

        assert.deepEqual(got, [...Array(n).keys()], `сбилось на ${n} страницах`);
        assert.ok(!got.includes(PAGER_GAP), `разрыв на ${n} страницах — прятать нечего`);
    }
});

проверка('восемь страниц — разрывы уже нужны', () => {
    // Первая граница, за которой ряд не помещается целиком.
    const got = pagerPages(8, 3);

    assert.ok(got.includes(PAGER_GAP), 'на восьми страницах разрыва нет');
    assert.ok(got.length < 8, 'ряд не сократился');
});

проверка('ряд не растёт вместе с числом страниц', () => {
    // ⚠ Главное здесь. Прежде длина равнялась числу страниц: сорок страниц — сорок
    // кнопок, и подвал переносился на вторую строку.
    for (const n of [10, 40, 200, 5000]) {
        assert.ok(pagerPages(n, Math.floor(n / 2)).length <= 7,
                  `ряд разросся на ${n} страницах`);
    }
});

проверка('в середине — края, соседи и два разрыва', () => {
    assert.deepEqual(pagerPages(20, 9),
                     [0, PAGER_GAP, 8, 9, 10, PAGER_GAP, 19]);
});

проверка('в начале разрыв только справа', () => {
    assert.deepEqual(pagerPages(20, 0), [0, 1, PAGER_GAP, 19]);
    assert.deepEqual(pagerPages(20, 1), [0, 1, 2, PAGER_GAP, 19]);
});

проверка('в конце разрыв только слева', () => {
    assert.deepEqual(pagerPages(20, 19), [0, PAGER_GAP, 18, 19]);
    assert.deepEqual(pagerPages(20, 18), [0, PAGER_GAP, 17, 18, 19]);
});

// ── Разрывы ──────────────────────────────────────────────────────────────────

проверка('разрыв в одну страницу закрывается самой страницей', () => {
    // Между «1» и окном вокруг третьей лежит ровно одна — вторая. «…» на её месте
    // был бы той же ширины и прятал бы то, до чего один щелчок.
    const got = pagerPages(9, 3);

    assert.deepEqual(got, [0, 1, 2, 3, 4, PAGER_GAP, 8]);
    assert.ok(!got.slice(0, 4).includes(PAGER_GAP), 'одну страницу спрятали за «…»');
});

проверка('текущая страница всегда в ряду', () => {
    for (let now = 0; now < 40; now++) {
        assert.ok(pagerPages(40, now).includes(now), `потеряли страницу ${now}`);
    }
});

проверка('края всегда в ряду', () => {
    for (const now of [0, 1, 7, 20, 38, 39]) {
        const got = pagerPages(40, now);

        assert.ok(got.includes(0), `нет первой при текущей ${now}`);
        assert.ok(got.includes(39), `нет последней при текущей ${now}`);
    }
});

проверка('ряд идёт по возрастанию и без повторов', () => {
    for (const now of [0, 1, 5, 19, 38, 39]) {
        const pages = pagerPages(40, now).filter(one => one !== PAGER_GAP);

        assert.deepEqual(pages, [...new Set(pages)], `повтор при текущей ${now}`);
        assert.deepEqual(pages, [...pages].sort((a, b) => a - b),
                         `порядок сбился при текущей ${now}`);
    }
});

проверка('два разрыва подряд не бывают', () => {
    for (const now of [0, 3, 20, 36, 39]) {
        const got = pagerPages(40, now);
        for (let i = 1; i < got.length; i++) {
            assert.ok(!(got[i] === PAGER_GAP && got[i - 1] === PAGER_GAP),
                      `два «…» подряд при текущей ${now}`);
        }
    }
});

// ── Мусор на входе ───────────────────────────────────────────────────────────

проверка('одна страница — она одна и есть', () => {
    assert.deepEqual(pagerPages(1, 0), [0]);
});

проверка('страниц нет — ряда нет', () => {
    for (const n of [0, -3, null, undefined, NaN]) {
        assert.deepEqual(pagerPages(n, 0), [], `сбилось на ${n}`);
    }
});

проверка('текущая за пределами прижимается к краю', () => {
    // ⚠ Приходит не из воздуха: список мог укоротиться между отрисовками (убрали
    // карточку, сработал поиск), а номер страницы пережил это в переменной.
    assert.deepEqual(pagerPages(5, 99), pagerPages(5, 4));
    assert.deepEqual(pagerPages(5, -7), pagerPages(5, 0));
});

process.exit(провалов ? 1 : 0);
