// Лента расписания: границы ручек и перевод времени.
//
// ⚠ **Проверяется настоящий модуль** (`dating_schedule.js`), а не его копия:
// копия разошлась бы с оригиналом в первую же правку, продолжая при этом
// проходить. Импортируется он подменой `dating_view.js` — единственной внешней
// зависимости, из которой нужен только `esc`.
//
// Запускает это `test_dating_schedule_band.py`: сюита на Python, а модуль на JS,
// и мост между ними — `node`.
//
// Что здесь ловится и почему стоит проверки:
//
//   `edgeRange` — упор ручек. Прежде значения пары сортировались, и ручки
//   проходили друг сквозь друга, меняясь ролями под пальцем; соседние смены при
//   этом налезали одна на другую;
//
//   `timeText` — конец суток. Свёрнутый по модулю (`24 % 24`), он давал `00:00`:
//   смена «19:00 → 00:00» получалась отрицательной длины и пропадала с ленты;
//
//   `scheduleNowIndex` — какая смена идёт прямо сейчас. Границы обязаны совпадать
//   с серверными (`dating_schedule_now`), иначе зелёным горело бы то, чего нет.

import assert from 'node:assert/strict';

import {DAY_MINUTES, SCHEDULE_GAP_MINUTES, edgeRange, scheduleBandHtml,
        scheduleNowIndex, scheduleRoom, timeText,
        timeMinutes} from './dating_schedule.js';

const ТРИ = [{from: '07:00', to: '11:00'},
             {from: '14:00', to: '16:45'},
             {from: '19:00', to: '23:00'}];

let провалов = 0;

function проверка(имя, тело) {
    try {
        тело();
        console.log('ok   ' + имя);
    } catch (e) {
        провалов++;
        console.log('ПЛОХО ' + имя + ': ' + e.message);
    }
}

// ── Границы ручек ────────────────────────────────────────────────────────────

проверка('начало не доходит до своего конца — между ними зазор', () => {
    const r = edgeRange(ТРИ, 0, 'from');

    assert.equal(r.max, timeMinutes('11:00') - SCHEDULE_GAP_MINUTES);
});

проверка('конец не доходит до своего начала — между ними зазор', () => {
    const r = edgeRange(ТРИ, 0, 'to');

    assert.equal(r.min, timeMinutes('07:00') + SCHEDULE_GAP_MINUTES);
});

проверка('начало останавливается в зазоре от предыдущей смены', () => {
    assert.equal(edgeRange(ТРИ, 1, 'from').min,
                 timeMinutes('11:00') + SCHEDULE_GAP_MINUTES);
});

проверка('конец останавливается в зазоре от следующей смены', () => {
    assert.equal(edgeRange(ТРИ, 1, 'to').max,
                 timeMinutes('19:00') - SCHEDULE_GAP_MINUTES);
});

проверка('первая смена начинается хоть с полуночи', () => {
    assert.equal(edgeRange(ТРИ, 0, 'from').min, 0);
});

проверка('последняя смена кончается концом суток', () => {
    assert.equal(edgeRange(ТРИ, 2, 'to').max, DAY_MINUTES);
});

проверка('ручки не сходятся в одну точку', () => {
    // ⚠ **Главное, ради чего зазор и заведён.** Смены вплотную («до 11:00» и «с
    // 11:00») по смыслу законны — и сервер их принимает, — но две ручки в одной
    // точке выглядят как одна, и взять нужную нельзя ни мышью, ни глазом.
    for (let i = 0; i + 1 < ТРИ.length; i++) {
        const конецПервой = edgeRange(ТРИ, i, 'to').max;
        const началоВторой = edgeRange(ТРИ, i + 1, 'from').min;

        assert.ok(timeMinutes(ТРИ[i + 1].from) - конецПервой >= SCHEDULE_GAP_MINUTES,
                  'конец смены может подойти к соседке вплотную');
        assert.ok(началоВторой - timeMinutes(ТРИ[i].to) >= SCHEDULE_GAP_MINUTES,
                  'начало смены может подойти к соседке вплотную');
    }
});

проверка('зазор — ширина ручки, а не «сколько длится смена»', () => {
    // 13 пикселей ручки на ленте в 520 — это 36 минут суток; ближайший кратный
    // шагу отрезок — 45. Число живёт в модуле, и проверка держит его от сползания.
    assert.equal(SCHEDULE_GAP_MINUTES, 45);
});

проверка('одинокая смена ходит по всем суткам', () => {
    const одна = [{from: '10:00', to: '12:00'}];

    assert.equal(edgeRange(одна, 0, 'from').min, 0);
    assert.equal(edgeRange(одна, 0, 'to').max, DAY_MINUTES);
});

проверка('ручки не могут пройти друг сквозь друга', () => {
    // Предел каждой ручки не пускает её за соседнюю — и оставляет зазор.
    for (let i = 0; i < ТРИ.length; i++) {
        const начало = edgeRange(ТРИ, i, 'from');
        const конец = edgeRange(ТРИ, i, 'to');

        assert.ok(timeMinutes(ТРИ[i].to) - начало.max >= SCHEDULE_GAP_MINUTES,
                  'начало подходит к своему концу вплотную');
        assert.ok(конец.min - timeMinutes(ТРИ[i].from) >= SCHEDULE_GAP_MINUTES,
                  'конец подходит к своему началу вплотную');

        if (i + 1 < ТРИ.length) {
            assert.ok(конец.max <= timeMinutes(ТРИ[i + 1].from),
                      'конец залез в следующую смену');
            assert.ok(edgeRange(ТРИ, i + 1, 'from').min >= timeMinutes(ТРИ[i].to),
                      'начало залезло в предыдущую');
        }
    }
});

проверка('новая смена садится с зазором от соседей', () => {
    // ⚠ Иначе только что заведённую смену нечем было бы взять: её ручка сразу
    // легла бы на соседскую.
    const место = scheduleRoom([{from: '07:00', to: '11:00'}]);

    assert.ok(место, 'место не нашлось на пустых сутках');
    assert.ok(место.to - место.from >= SCHEDULE_GAP_MINUTES, 'смена уже зазора');

    const до = timeMinutes('07:00') - место.to;
    const после = место.from - timeMinutes('11:00');

    assert.ok(до >= SCHEDULE_GAP_MINUTES || после >= SCHEDULE_GAP_MINUTES,
              'новая смена села вплотную к соседке');
});

проверка('на пустых сутках место есть', () => {
    const место = scheduleRoom([]);

    assert.equal(место.from, 0);
    assert.equal(место.to, SCHEDULE_GAP_MINUTES);
});

// ── Время ────────────────────────────────────────────────────────────────────

проверка('конец суток — 24:00, а не 00:00', () => {
    assert.equal(timeText(DAY_MINUTES), '24:00');
    assert.equal(timeText(0), '00:00');
});

проверка('перевод туда и обратно не теряет крайние значения', () => {
    for (const m of [0, 15, 705, 1425, DAY_MINUTES]) {
        assert.equal(timeMinutes(timeText(m)), m, `сбилось на ${m}`);
    }
});

проверка('за пределы суток значение не выходит', () => {
    assert.equal(timeText(9999), '24:00');
    assert.equal(timeText(-5), '00:00');
});

// ── «Сейчас»: какая смена идёт ───────────────────────────────────────────────
//
// ⚠ Правило сверяется **с сервером** (`dating_schedule.py`, `dating_schedule_now`):
// `from <= minutes < to`. Оно же красит смену зелёным, и разойдись они на минуту —
// лента показывала бы «идёт сейчас» там, где воркер уже вышел.

проверка('минута внутри смены — её номер', () => {
    assert.equal(scheduleNowIndex(ТРИ, timeMinutes('09:30')), 0);
    assert.equal(scheduleNowIndex(ТРИ, timeMinutes('15:00')), 1);
    assert.equal(scheduleNowIndex(ТРИ, timeMinutes('22:59')), 2);
});

проверка('минута в перерыве между сменами — ничья', () => {
    assert.equal(scheduleNowIndex(ТРИ, timeMinutes('12:30')), -1);
    assert.equal(scheduleNowIndex(ТРИ, timeMinutes('02:00')), -1);
});

проверка('вход считается своим, выход — уже нет', () => {
    // Ровно как на сервере: `from <= minutes < to`. Иначе в 11:00 горели бы разом
    // кончившаяся смена и — на следующей ленте — ещё не начавшаяся.
    assert.equal(scheduleNowIndex(ТРИ, timeMinutes('07:00')), 0, 'вход не свой');
    assert.equal(scheduleNowIndex(ТРИ, timeMinutes('11:00')), -1, 'выход ещё свой');
});

проверка('пустое расписание — ничья минута', () => {
    assert.equal(scheduleNowIndex([], 600), -1);
    assert.equal(scheduleNowIndex(null, 600), -1);
});

проверка('мусор вместо времени не делает смену идущей', () => {
    // Часов у страницы может не быть вовсе (модуль зовут и вне браузера), и
    // «NaN попал в смену» было бы худшим ответом из возможных: зелёным горела бы
    // первая попавшаяся.
    assert.equal(scheduleNowIndex(ТРИ, NaN), -1);
    assert.equal(scheduleNowIndex(ТРИ, undefined), -1);
});

// ── «Сейчас» в разметке ──────────────────────────────────────────────────────

проверка('лента несёт время смен в разметке — по нему её и перекрашивают', () => {
    // ⚠ `data-from`/`data-to` не украшение: раз в полминуты лента перекрашивается
    // **по разметке**, а не по списку, который был при отрисовке. Пропади они —
    // перекраска молча перестала бы находить смены, и зелёное застыло бы на месте.
    const html = scheduleBandHtml(ТРИ);

    assert.ok(html.includes('data-from="07:00"'), 'нет времени входа в разметке');
    assert.ok(html.includes('data-to="23:00"'), 'нет времени выхода в разметке');
});

проверка('черта «сейчас» рисуется всегда — и когда ни одна смена не идёт', () => {
    // Ради неё же: без черты пустая лента не отличается от сломанной подсветки.
    assert.ok(scheduleBandHtml([]).includes('sched-now'), 'нет черты у пустой ленты');
    assert.ok(scheduleBandHtml(ТРИ).includes('sched-now'));
});

проверка('выключенное расписание помечено в самой ленте', () => {
    // Оттенок зелёного решает перекраска, а она видит только разметку — значит
    // «действует ли расписание» обязано лежать в ней.
    assert.ok(scheduleBandHtml(ТРИ, false).includes('data-on="0"'));
    assert.ok(scheduleBandHtml(ТРИ, true).includes('data-on="1"'));
});

process.exit(провалов ? 1 : 0);
