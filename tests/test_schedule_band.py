"""Лента расписания: правила, которые живут в JS.

⚠ **Проверяется настоящий модуль** `data/uvicorn/public/js/schedule.js`, а
не его пересказ на Python. Пересказ разошёлся бы с оригиналом в первую же правку и
продолжал бы при этом проходить — то есть врал бы ровно тогда, когда нужен.

Сам тест написан на JS (`test_schedule_band.js`) и запускается `node`; здесь —
мост: собрать временную папку, подложить заглушку единственной зависимости и
показать вывод человеку, если что-то не сошлось.

## Почему не браузером

Браузером проверено, что упор работает под мышью (`dashboard_frontend.md`,
§3.5.1.1) — и это правильная проверка для перетаскивания. Но границы ручек это
арифметика над четырьмя числами, и поднимать ради неё Chromium в сюите значило бы
менять секунды на минуты, ничего не добавляя.

## Что здесь ловится

`edgeRange` — упор ручек. Прежде значения пары сортировались, и ручки проходили
друг сквозь друга, меняясь ролями под пальцем; соседние смены налезали одна на
другую, и расписание переставало сохраняться.

`timeText` — конец суток. Свёрнутый по модулю (`24 % 24`), он давал `00:00`:
смена «19:00 → 00:00» получалась отрицательной длины и пропадала с ленты. Человек
это и увидел: «ползунок доходит до конца, исчезает и появляется в начале».

`scheduleNowIndex` — какая смена идёт прямо сейчас. ⚠ Границы обязаны совпадать с
серверными (`schedule_now`: вход включительно, выход нет). Разойдись они на
минуту — лента красила бы зелёным смену, которая для воркера уже кончилась, и
человек видел бы «идёт сейчас» там, где не происходит ничего.
"""

import pathlib
import shutil
import subprocess
import tempfile

import pytest

pytestmark = pytest.mark.page
JS_DIR = pathlib.Path(__file__).resolve().parents[1] / 'data/uvicorn/public/js'
MODULE = JS_DIR / 'dating_schedule.js'
TEST_JS = pathlib.Path(__file__).with_suffix('.js')

# Единственная зависимость модуля — `esc` из `dating_view.js`. Подкладываем
# заглушку вместо настоящего файла: тот тянет за собой разметку и `document`,
# которых в `node` нет, а от `esc` здесь нужно только не падать.
VIEW_STUB = 'export const esc = (value) => String(value ?? "");\n'

# ⚠ А вот `dating_time.js` кладём **настоящий**, а не заглушкой: из него берётся
# `timeNowMinutes` — минуты суток по часовому поясу панели, и на них держится вся
# подсветка «идёт сейчас». Подделай мы его — проверялась бы наша выдумка о том, как
# считается время, а не то, как оно считается на самом деле.
#
# Работать в `node` он умеет: `window` там нет, и пояс честно выходит нулевым.
TIME_MODULE = JS_DIR / 'dating_time.js'


def test_schedule_band_rules():
    """Границы ручек и перевод времени — прогоном настоящего модуля."""
    node = shutil.which('node')
    if not node:
        pytest.skip('node не найден в PATH')

    with tempfile.TemporaryDirectory() as tmp:
        room = pathlib.Path(tmp)
        shutil.copy(MODULE, room / MODULE.name)
        shutil.copy(TIME_MODULE, room / TIME_MODULE.name)
        shutil.copy(TEST_JS, room / TEST_JS.name)
        (room / 'dating_view.js').write_text(VIEW_STUB, encoding='utf-8')

        result = subprocess.run([node, str(room / TEST_JS.name)],
                                capture_output=True, text=True, timeout=60)

    # ⚠ Вывод показываем **целиком и всегда при отказе**: тест на JS сам называет,
    # какая проверка не сошлась, и прятать это за «returncode != 0» значило бы
    # заставлять человека повторять прогон руками.
    assert result.returncode == 0, (
        f'проверки ленты расписания не прошли:\n{result.stdout}\n{result.stderr}')
