"""У каждого выключателя сайта есть **живой** читатель — иначе галочка не выключает.

## ⚠⚠ Зачем: галочка, которая ничего не выключает

`site.chat_answer_on` («отправка ответов» на вкладке «Диалоги») сохранялась ручкой,
стояла в интерфейсе, а круг автоответа её **не читал**. Единственный читатель —
`auto._answer_on` — остался в файле, но звать его перестали, когда убирали вторую
проверку (флаг анкеты `auto_answer`). Со стороны всё выглядело исправным: галочку
снимаешь, панель её сохраняет, а анкеты продолжают писать живым людям.

⚠⚠ **Сторона ошибки здесь обратная обычной.** Привычная беда — «агент молчит, когда
должен говорить»: так и было, сутки молчания на проде. Здесь агент **говорил, когда
человек это запретил**, а отменить ушедшее нельзя.

## ⚠⚠ Почему «имя где-то встречается» — негодная проверка

Первая мысль — сверить `SITE_FLAGS` с текстом `src/`. Она бы **не сработала**: имя
флага в проекте встречалось, потому что чтение лежало внутри мёртвой функции.
Проверка была бы зелёной весь тот срок, что галочка не работала.

Поэтому вопрос ставится иначе: **есть ли у флага читатель, которого кто-то зовёт**.
Мёртвого читателя не считаем — он и есть поломка.

## Чем считается

| Что нужно | Чем берём |
|-----------|-----------|
| список выключателей | `SITE_FLAGS` из `site_switch.py` — тот же, что разрешает запись |
| в какой функции упомянут флаг | `tool_impact_functions` (разбором дерева) |
| какие имена мёртвые | `tool_dead`: вердикты «мёртвое» **и «только тесты»** |

⚠⚠ «Только тесты» считается мёртвым наравне с «мёртвым», и это не придирка — на
этом застава попалась при первой же проверке. Вернув вчерашний дефект (зов убран,
функция осталась), она **не упала**: собственные тесты автоответа упоминают
`_answer_on` подменой (`monkeypatch.setattr`), и вердикт вышел «только тесты».
Читатель, которого зовут одни тесты, в проде не гасит ничего — то есть галочка
по-прежнему не работает, а проверка зелёная.

⚠ Своего обхода дерева здесь нет намеренно: третья копия `ast.walk` в проекте
разошлась бы с первыми двумя. Вопрос «где упомянуто имя» принадлежит `tool_impact`,
и там он и решается.

⚠ Тест **структурный**: ни базы, ни HTTP. Он отвечает не «работает ли выключатель»,
а «есть ли кому его прочесть». Работу проверяют тесты занятий — для автоответа это
`test_auto_agent_id.py`, `TestTheSiteSwitch`.
"""

from pathlib import Path

import pytest

from tool_.tool_dead import TOOL_DEAD_GONE, TOOL_DEAD_TESTS_ONLY, tool_dead
from tool_.tool_impact import tool_impact_functions

from src.uvicorn.routers.dating.site_switch import SITE_FLAGS

pytestmark = pytest.mark.core

# Корень кода. ⚠ От файла теста, а не от рабочего каталога: сюиту запускают и из
# корня, и из `tests/`, и во втором случае относительный путь не нашёл бы ничего.
SRC = Path(__file__).resolve().parents[1] / 'src'

# Где флаг лежит **списком разрешённых к записи**, а не читается по существу.
# ⚠ Без этого отсева каждый флаг считался бы прочитанным: ручка `site_flag_put`
# упоминает их все, и застава зеленела бы всегда.
SKIP = ('uvicorn/routers/dating/site_switch.py',)


@pytest.fixture(scope='module')
def dead() -> set:
    """Имена, которых не зовёт рабочий код. ⚠ Один обход: он стоит полсекунды.

    ⚠⚠ Оба вердикта, а не только «мёртвое» — см. ⚠⚠ в докстринге модуля.
    """
    return {one['name'] for one in tool_dead(str(SRC))
            if one['verdict'] in (TOOL_DEAD_GONE, TOOL_DEAD_TESTS_ONLY)}


class TestEveryFlagHasALiveReader:
    """⚠⚠ Главное: у каждого выключателя есть читатель, которого зовут."""

    @pytest.mark.parametrize('flag', SITE_FLAGS)
    def test_the_flag_is_read_by_someone_alive(self, flag, dead):
        readers = _readers(flag)

        assert readers, (
            f'выключатель `{flag}` не читает никто: панель его сохраняет, а '
            'занятие идёт независимо от него')

        live = [one for one in readers if one.rsplit(':', 1)[-1] not in dead]

        assert live, (
            f'у выключателя `{flag}` все читатели мёртвые ({", ".join(readers)}): '
            'галочка сохраняется, но никто её не спрашивает — ровно так перестала '
            'работать `chat_answer_on`')


class TestTheGuardCanFail:
    """⚠ Застава обязана уметь падать: зелёная всегда — это не проверка.

    Оба признака проверяются подделкой: «сломай флаг и посмотри» в сюите не сделать,
    а без этих двух тестов ошибка в самой заставе прошла бы незамеченной — и она
    снова пропустила бы неработающую галочку.
    """

    def test_an_unknown_flag_has_no_readers(self):
        """Выдуманное имя не читает никто — значит счёт читателей вправду считает."""
        assert _readers('no_such_flag_anywhere_in_the_project') == []

    def test_a_dead_reader_does_not_count(self):
        """⚠⚠ Тот самый случай: читатель есть, но мёртвый — значит живых нет.

        Именно эта строка отделяет заставу от негодной проверки «имя где-то
        встречается»: если отбор по мёртвым сломается, тест покраснеет здесь.
        """
        readers = _readers('chat_answer_on')

        assert readers, 'у chat_answer_on пропали читатели — сломано занятие'

        # Делаем вид, что мёртвые — все его читатели.
        as_if_dead = {one.rsplit(':', 1)[-1] for one in readers}
        live = [one for one in readers if one.rsplit(':', 1)[-1] not in as_if_dead]

        assert live == [], 'мёртвый читатель посчитался живым'


class TestTheListIsTheOneThatGuardsWrites:
    """⚠ Список проверяемых — тот же, что разрешает запись, а не его копия.

    Заведи выключатель мимо `SITE_FLAGS` — запись его не пропустит, а застава о нём
    не узнает. Поэтому список берётся из кода.
    """

    def test_there_are_flags_at_all(self):
        assert len(SITE_FLAGS) >= 10, 'список выключателей внезапно сократился'

    def test_no_duplicates(self):
        assert len(set(SITE_FLAGS)) == len(SITE_FLAGS), 'выключатель объявлен дважды'


def _readers(flag: str) -> list[str]:
    """Кто читает флаг: `файл.py:функция`, без списка разрешённых к записи."""
    return [f"{one['file']}:{one['func']}"
            for one in tool_impact_functions(flag, str(SRC))
            if one['file'] not in SKIP]
